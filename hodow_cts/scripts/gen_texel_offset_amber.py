#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.texture.texel_offset from the vendored Amber script.

The two fragment shaders (`frag_setup`, which writes the texture, and `frag_shader`, which samples it with `textureOffset`) are read from the script; the vertex
shader is Amber's PASSTHROUGH. Written: shaders/manifest/texture_texel_offset.toml and shaders/src/texture_texel_offset/.

Run from hodow_cts/:  python3 scripts/gen_texel_offset_amber.py   (then `just cts-shaders`)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/texture/texel_offset/texel_offset.amber"
SRC = ROOT / "shaders" / "src" / "texture_texel_offset"
MANIFEST = ROOT / "shaders" / "manifest" / "texture_texel_offset.toml"

PASSTHROUGH_VERTEX = "#version 430\nlayout(location = 0) in vec4 position;\nvoid main() {\n  gl_Position = position;\n}\n"


def shader(text, name):
    lines = text.splitlines()
    for ndx, line in enumerate(lines):
        if line.startswith("SHADER fragment " + name + " "):
            body = []
            for rest in lines[ndx + 1 :]:
                if rest.strip() == "END":
                    return "\n".join(body) + "\n"
                body.append(rest)
    raise RuntimeError(name)


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    text = AMBER.read_text()
    programs = [("vert", "vert", PASSTHROUGH_VERTEX), ("frag_setup", "frag", shader(text, "frag_setup")), ("frag", "frag", shader(text, "frag_shader"))]
    out = [
        "# Shader manifest for dEQP-VK.texture.texel_offset.",
        "#",
        "# @generated by hodow_cts/scripts/gen_texel_offset_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/texture/texel_offset/texel_offset.amber"',
        'rust_module = "texture/texel_offset_tests"',
        "",
        "[[case]]",
        'name = "texel_offset"',
        'rust_const = "TEXEL_OFFSET"',
        'rust_type = "SharedProgram"',
        "programs = [",
    ]
    for name, stage, source in programs:
        (SRC / f"texel_offset_{name}.{stage}").write_text(source)
        out.append(f'    {{ name = "{name}", template = "texture_texel_offset/texel_offset_{name}.{stage}", stage = "{stage}" }},')
    out += ["]", ""]
    MANIFEST.write_text("\n".join(out))


if __name__ == "__main__":
    main()
