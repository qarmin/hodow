#!/usr/bin/env python3
"""Writes the shaders, the manifest and the case table of dEQP-VK.reconvergence.maximal.fragment from the vendored Amber scripts.

The nine scripts have one shape: Amber's PASSTHROUGH vertex shader, a fragment shader (`[[maximally_reconverges]]`, demoting or terminating part of a quad), a full-screen
triangle, the storage buffers `fragments` (one uvec4 of fragment ids, or one uint) and `result` (99), a 16x16 R32G32B32A32_SFLOAT target and `EXPECT result IDX 0 EQ 1`.
Written: shaders/manifest/reconvergence_fragment.toml, shaders/src/reconvergence_fragment/ and src/vkt/tests/reconvergence/maximal_fragment_cases.rs.

Run from hodow_cts/:  python3 scripts/gen_reconvergence_fragment_amber.py   (then `just cts-shaders`)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/reconvergence/maximal/fragment"
SRC = ROOT / "shaders" / "src" / "reconvergence_fragment"
MANIFEST = ROOT / "shaders" / "manifest" / "reconvergence_fragment.toml"
TABLE = ROOT / "src" / "vkt" / "tests" / "reconvergence" / "maximal_fragment_cases.rs"

PASSTHROUGH_VERTEX = "#version 450\nlayout(location = 0) in vec4 position;\nvoid main() {\n  gl_Position = position;\n}\n"


def numbers(text, name):
    match = re.search(rf"BUFFER {name} DATA_TYPE \w+ DATA\s+(.*?)\s*END", text, re.S)
    return [int(token) for token in match.group(1).split()]


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.reconvergence.maximal.fragment.",
        "#",
        "# @generated by hodow_cts/scripts/gen_reconvergence_fragment_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/reconvergence/maximal/fragment/demote_entire_quad.amber"',
        'rust_module = "reconvergence/maximal_fragment_tests"',
        "",
    ]
    table = [
        "// @generated by hodow_cts/scripts/gen_reconvergence_fragment_amber.py - do not hand-edit.",
        "//",
        "// One row per Amber script of dEQP-VK.reconvergence.maximal.fragment.",
        "",
        "use super::maximal_fragment_tests::MaximalFragmentCase;",
        "",
        "pub static MAXIMAL_FRAGMENT_CASES: &[MaximalFragmentCase] = &[",
    ]
    for path in sorted(AMBER.glob("*.amber")):
        name = path.stem
        text = path.read_text()
        match = re.search(r"SHADER fragment frag_shader GLSL TARGET_ENV spv(\d)\.(\d)\n(.*?)\nEND\n", text, re.S)
        spirv = f"spirv{match.group(1)}.{match.group(2)}"
        fragment = match.group(3) + "\n"
        key = f"reconvergence_fragment_{name}"
        vertices = re.search(r"BUFFER vertices DATA_TYPE R32G32_SFLOAT DATA\s+(.*?)\s*END", text, re.S).group(1).split()
        fragments = numbers(text, "fragments")
        size = tuple(int(v) for v in re.search(r"FRAMEBUFFER_SIZE (\d+) (\d+)", text).groups())
        out += ["[[case]]", f'name = "{key}"', f'rust_const = "{key.upper()}"', 'rust_type = "SharedProgram"', "programs = ["]
        for program_name, stage, source in (("vert", "vert", PASSTHROUGH_VERTEX), ("frag", "frag", fragment)):
            (SRC / f"{key}_{program_name}.{stage}").write_text(source)
            spirv_field = f', spirv_version = "{spirv}"' if stage == "frag" else ""
            out.append(f'    {{ name = "{program_name}", template = "reconvergence_fragment/{key}_{program_name}.{stage}", stage = "{stage}"{spirv_field} }},')
        out += ["]", ""]
        table.append(
            f'    MaximalFragmentCase {{ name: "{name}", key: "{key}", vertices: [{", ".join(v + "_f32" if "." in v else v + ".0_f32" for v in vertices)}], '
            f"fragments: &[{', '.join(str(f) for f in fragments)}], size: ({size[0]}, {size[1]}), demote: {str('GL_EXT_demote_to_helper_invocation' in fragment).lower()}, "
            f"terminate: {str('GL_EXT_terminate_invocation' in fragment).lower()} }},"
        )
    table.append("];")
    MANIFEST.write_text("\n".join(out))
    TABLE.write_text("\n".join(table) + "\n")
    print(len(list(AMBER.glob("*.amber"))), "cases")


if __name__ == "__main__":
    main()
