#!/usr/bin/env python3
"""Writes src/vkt/tests/api/unsupported_feature_vendor_structs.rs: the `create_device_unsupported_features` structs that feature_struct_list.rs (generated from
vkDeviceFeatures2.inl) does not carry: vendor structs the upstream test lists in the generated vkDeviceFeatureTest.inl. The members are read from that file,
the structure type value, the owning extension and the size from vk.xml.

Usage: python3 hodow_cts/scripts/gen_unsupported_feature_vendor_structs.py [--glcts tmp/glcts-src]
"""
import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
REPO = CRATE.parent
OUT = CRATE / "src" / "vkt" / "tests" / "api" / "unsupported_feature_vendor_structs.rs"
STRUCTS = CRATE / "src" / "vkt" / "tests" / "api" / "feature_struct_list.rs"
PREFIX = "dEQP-VK.api.device_init.create_device_unsupported_features."


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glcts", type=Path, default=REPO / "tmp" / "glcts-src")
    ap.add_argument("--cts-dir", type=Path, default=REPO / "tmp" / "VK-GL-CTS")
    args = ap.parse_args()

    known = set(re.findall(r'name: "([^"]+)"', STRUCTS.read_text()))
    mustpass = (args.cts_dir / "external/vulkancts/mustpass/main/vk-default/api.txt").read_text().splitlines()
    wanted = [l.strip().removeprefix(PREFIX) for l in mustpass if l.strip().startswith(PREFIX)]
    wanted = [n for n in wanted if n != "core" and n not in known]

    inl = (args.glcts / "external/vulkancts/framework/vulkan/generated/vulkan/vkDeviceFeatureTest.inl").read_text()
    function_of = dict(re.findall(r'addFunctionCase\(testGroup, "([a-z0-9_]+)", createDeviceWithUnsupportedFeaturesTest(\w+)\)', inl))
    root = ET.parse(args.glcts / "external/vulkan-docs/src/xml/vk.xml").getroot()

    ext_of_type, ext_number = {}, {}
    for ext in root.iter("extension"):
        number = int(ext.get("number"))
        ext_number[ext.get("name")] = number
        for require in ext.iter("require"):
            for t in require.iter("type"):
                ext_of_type.setdefault(t.get("name"), ext.get("name"))
    stype_value = {}
    for ext in root.iter("extension"):
        number = int(ext.get("number"))
        for require in ext.iter("require"):
            for e in require.iter("enum"):
                if e.get("extends") == "VkStructureType" and e.get("offset") is not None:
                    stype_value[e.get("name")] = 1000000000 + (int(e.get("extnumber", number)) - 1) * 1000 + int(e.get("offset"))
    structs = {t.get("name"): t for t in root.iter("type") if t.get("category") == "struct"}

    entries = []
    for name in wanted:
        suffix = function_of[name]
        struct = f"VkPhysicalDevice{suffix}"
        members = re.findall(rf"FEATURE_ITEM \({struct}, (\w+)\)", inl)
        node = structs[struct]
        stype_name = node.find("member").get("values")
        value = stype_value[stype_name]
        extension = ext_of_type.get(struct)
        size = (16 + 4 * len(members) + 7) // 8 * 8
        entries.append((name, struct, value, size, extension, members))

    lines = [
        "// @generated by hodow_cts/scripts/gen_unsupported_feature_vendor_structs.py - do not hand-edit.",
        "//",
        "// `create_device_unsupported_features` structs that feature_struct_list.rs does not carry (vendor structs), described the same way.",
        "",
        "use super::feature_struct_list::FeatureStruct;",
        "",
        "pub static VENDOR_FEATURE_STRUCTS: &[FeatureStruct] = &[",
    ]
    for name, struct, value, size, extension, members in entries:
        extensions = f'&["{extension}"]' if extension else "&[]"
        lines += [
            "    FeatureStruct {",
            f'        name: "{name}",',
            f'        struct_name: "{struct}",',
            f"        s_type: {value},",
            f"        size: {size},",
            f"        extensions: {extensions},",
            "        api_version: None,",
            "        fields: &[" + ", ".join(f'"{m}"' for m in members) + "],",
            "    },",
        ]
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(entries)} structs -> {OUT}")


if __name__ == "__main__":
    main()
