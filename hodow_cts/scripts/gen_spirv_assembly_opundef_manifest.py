#!/usr/bin/env python3
"""Writes shaders/manifest/spirv_assembly_opundef_buffer.toml: the 16 `buffer_*` cases of dEQP-VK.spirv_assembly.instruction.compute.opundef.

`OpUndefBufferComputeTestCase::initPrograms` of vktSpvAsmOpUndefTests.cpp fills one assembly template with the storage class of the buffer, whether the
OpUndef of the buffer (or of an array of one) is consumed in live code and whether it is an array. The case names carry all three, which is what
src/vkt/tests/spirv_assembly/opundef_buffer_tests.rs reads back.

    python3 hodow_cts/scripts/gen_spirv_assembly_opundef_manifest.py

A pure text generator: no spirv-as and no cargo.
"""

import json
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "spirv_assembly_opundef_buffer.toml"
TEMPLATE = "spirv_assembly/source.asm"

SPIRV_TEMPLATE = """
    ; SPIR-V
    ; Version: 1.3
    OpCapability Shader
    OpMemoryModel Logical GLSL450
    OpEntryPoint GLCompute %main "main"
    OpExecutionMode %main LocalSize 1 1 1

    %void      = OpTypeVoid
    %float     = OpTypeFloat 32
    %v4float   = OpTypeVector %float 4
    %uint      = OpTypeInt 32 0

    %Buffer  = OpTypeStruct %v4float

    ${UNDEF_TYPE_DEF}

    %ptr_Buffer = OpTypePointer ${STORAGE_CLASS} %Buffer

    %void_fn   = OpTypeFunction %void
    %helper_fn = OpTypeFunction %void ${TARGET_TYPE}

    %undef_res = OpUndef ${TARGET_TYPE}

    %bool      = OpTypeBool
    %condition = ${CONDITION_VAL} %bool

    ; Auxiliary function
    %process_undef = OpFunction %void None %helper_fn
    %param_undef   = OpFunctionParameter ${TARGET_TYPE}
    %helper_entry  = OpLabel
                     ${EXTRACT_OP}
                     OpReturn
                     OpFunctionEnd

    ; Main function
    %main      = OpFunction %void None %void_fn
    %entry     = OpLabel
                 OpSelectionMerge %merge None
                 OpBranchConditional %condition %then %merge

    %then      = OpLabel
    %unused    = OpFunctionCall %void %process_undef %undef_res
                 OpBranch %merge

    %merge     = OpLabel
                 OpReturn
                 OpFunctionEnd
    """

CASES = [("storage", "StorageBuffer"), ("uniform", "Uniform"), ("storage_dynamic", "StorageBuffer"), ("uniform_dynamic", "Uniform")]


def assembly(storage_class, is_array, in_live_code):
    mapping = {
        "STORAGE_CLASS": storage_class,
        "CONDITION_VAL": "OpConstantTrue" if in_live_code else "OpConstantFalse",
        "CONDITION_BRANCH": "%then" if in_live_code else "%merge",
    }
    if is_array:
        mapping["UNDEF_TYPE_DEF"] = "%len       = OpConstant %uint 4\n%ArrBuffer = OpTypeArray %Buffer %len"
        mapping["TARGET_TYPE"] = "%ArrBuffer"
        mapping["EXTRACT_OP"] = "%_         = OpCompositeExtract %v4float %param_undef 0 0"
    else:
        mapping["UNDEF_TYPE_DEF"] = ""
        mapping["TARGET_TYPE"] = "%Buffer"
        mapping["EXTRACT_OP"] = "%_         = OpCompositeExtract %v4float %param_undef 0"
    text = SPIRV_TEMPLATE
    for key, value in mapping.items():
        text = text.replace("${" + key + "}", value)
    return text


def main():
    out = [
        "# Shader manifest for dEQP-VK.spirv_assembly.instruction.compute.opundef.buffer_*\n"
        "#\n"
        "# @generated by hodow_cts/scripts/gen_spirv_assembly_opundef_manifest.py - do not hand-edit.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/spirv_assembly/vktSpvAsmOpUndefTests.cpp"\n'
        'rust_module = "spirv_assembly/opundef_buffer_tests"\n'
    ]
    count = 0
    for name, storage_class in CASES:
        for is_array in (False, True):
            for in_live_code in (False, True):
                case_name = "buffer_" + name + ("_array" if is_array else "") + ("livecode" if in_live_code else "")
                const = "OPUNDEF_" + case_name.upper()
                out.append(
                    f'\n[[case]]\nname = "{case_name}"\nrust_const = "{const}"\nrust_type = "OpUndefBufferCase"\n'
                    f'programs = [ {{ name = "opundef", template = "{TEMPLATE}", stage = "asm", spirv_version = "spirv1.3" }} ]\n'
                    f"derived = {{ source = {json.dumps(repr(assembly(storage_class, is_array, in_live_code)))} }}\n"
                )
                count += 1
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {count} cases")


if __name__ == "__main__":
    main()
