"""Emits the desktop tables of the Khronos GL CTS packed-pixels test as Rust statics.

Upstream (`external/openglcts/modules/common/glcPackedPixelsTests.cpp`) keeps them as C++ initialiser lists: `coreInternalformats`, `coreFormats`, `coreTypes` and `coreValidFormats`. The ES tables are not
carried over: only the desktop roots register this group. The types the statics are built from live in `src/khr_gl/packed_pixels/mod.rs`.

Usage:
    python3 hodow_cts/scripts/gen_khr_packed_pixels_tables.py [--cts-dir ../tmp/glcts-src] [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
OUT_PATH = CRATE_DIR / "src" / "generated" / "khr_packed_pixels_tables.rs"
SOURCE = "external/openglcts/modules/common/glcPackedPixelsTests.cpp"

SAMPLERS = {"SAMPLER_UNORM": "Unorm", "SAMPLER_NORM": "Norm", "SAMPLER_UINT": "Uint", "SAMPLER_INT": "Int", "SAMPLER_FLOAT": "Float"}
COMPONENT_FORMATS = {"FORMAT_STENCIL": "Stencil", "FORMAT_DEPTH": "Depth", "FORMAT_DEPTH_STENCIL": "DepthStencil", "FORMAT_COLOR": "Color", "FORMAT_COLOR_INTEGER": "ColorInteger"}
STORAGES = {"STORAGE_UNSIGNED": "Unsigned", "STORAGE_SIGNED": "Signed", "STORAGE_FLOAT": "Float"}
SIZES = {"sizeof(GLubyte)": "1", "sizeof(GLbyte)": "1", "sizeof(GLushort)": "2", "sizeof(GLshort)": "2", "sizeof(GLuint)": "4", "sizeof(GLint)": "4", "sizeof(GLhalf)": "2", "sizeof(GLfloat)": "4",
         "sizeof(GLfloat) + sizeof(GLuint)": "8"}


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def array_body(text: str, name: str) -> str:
    start = text.index(name)
    start = text.index("= {", start) + 3
    depth = 1
    i = start
    while depth:
        c = text[i]
        depth += (c == "{") - (c == "}")
        i += 1
    return text[start : i - 1]


def parse_entries(body: str) -> list:
    """The top-level `{...}` entries of an initialiser list, each as a (nested) list of stripped tokens."""
    entries = []
    i = 0
    while i < len(body):
        if body[i] == "{":
            node, i = parse_node(body, i)
            entries.append(node)
        else:
            i += 1
    return entries


def parse_node(body: str, i: int):
    assert body[i] == "{"
    i += 1
    items = []
    token = ""
    while True:
        c = body[i]
        if c == "{":
            node, i = parse_node(body, i)
            items.append(node)
            continue
        if c in ",}":
            token = " ".join(token.split())
            if token:
                items.append(token)
            token = ""
            if c == "}":
                return items, i + 1
        else:
            token += c
        i += 1


def bits(node) -> str:
    """`{{...9 ints...}}` of an `InternalFormatBits` union."""
    values = node[0]
    assert len(values) == 9, values
    return "[" + ", ".join(values) + "]"


def flags(token: str) -> str:
    if token == "0":
        return "0"
    return " | ".join(part.strip() for part in token.split("|"))


def render(text: str) -> str:
    text = strip_comments(text)
    out = ["// @generated by hodow_cts/scripts/gen_khr_packed_pixels_tables.py - do not edit.", "//", f"// The desktop tables of {SOURCE}.", "",
           "use crate::glw;", "use crate::khr_gl::packed_pixels::{ComponentFormat, EnumFormats, InternalFormat, PixelFormat, PixelType, Sampler, TypeStorage};",
           "use crate::khr_gl::packed_pixels::{FLAG_COMPRESSED, FLAG_PACKED, FLAG_REQ_RBO, FLAG_REQ_RBO_ES30, FLAG_REQ_RBO_GL42};", ""]

    internal = parse_entries(array_body(text, "coreInternalformats"))
    out.append(f"pub static CORE_INTERNALFORMATS: [InternalFormat; {len(internal)}] = [")
    for sized, base, fmt, typ, sampler, b, fl in internal:
        name = sized[3:].lower()
        out.append(f'    InternalFormat {{ name: "{name}", sized_format: glw::{sized}, base_format: glw::{base}, format: glw::{fmt}, type_: glw::{typ}, sampler: Sampler::{SAMPLERS[sampler]}, bits: {bits(b)}, flags: {flags(fl)} }},')
    out += ["];", ""]

    formats = parse_entries(array_body(text, "coreFormats"))
    out.append(f"pub static CORE_FORMATS: [PixelFormat; {len(formats)}] = [")
    for fmt, comps, comp_fmt, attachment, order in formats:
        name = fmt[3:].lower()
        out.append(f'    PixelFormat {{ name: "{name}", format: glw::{fmt}, components: {comps}, component_format: ComponentFormat::{COMPONENT_FORMATS[comp_fmt]}, attachment: glw::{attachment}, component_order: {bits(order)} }},')
    out += ["];", ""]

    types = parse_entries(array_body(text, "coreTypes"))
    out.append(f"pub static CORE_TYPES: [PixelType; {len(types)}] = [")
    for typ, size, storage, special, reversed, b, clamp in types:
        out.append(f"    PixelType {{ type_: glw::{typ}, size: {SIZES[size]}, storage: TypeStorage::{STORAGES[storage]}, special: {special}, reversed: {reversed}, bits: {bits(b)}, clamp: {clamp} }},")
    out += ["];", ""]

    valid = parse_entries(array_body(text, "coreValidFormats"))
    out.append(f"pub static CORE_VALID_FORMATS: [EnumFormats; {len(valid)}] = [")
    for internalformat, fmt, typ, size, renderable in valid:
        out.append(f"    EnumFormats {{ internalformat: glw::{internalformat}, format: glw::{fmt}, type_: glw::{typ}, size: {size}, renderable: {renderable} }},")
    out += ["];", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cts-dir", default=str(CRATE_DIR.parent / "tmp" / "glcts-src"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = (Path(args.cts_dir) / SOURCE).read_text()
    rendered = render(text)
    if args.check:
        if not OUT_PATH.exists() or OUT_PATH.read_text() != rendered:
            print(f"{OUT_PATH} is stale", file=sys.stderr)
            return 1
        return 0
    OUT_PATH.write_text(rendered)
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
