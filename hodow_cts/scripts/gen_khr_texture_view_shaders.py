#!/usr/bin/env python3
"""Generates hodow_cts/src/khr_gl/texture_view/shaders.rs: the GLSL string literals of TextureViewTestViewSampling in gl4cTextureViewTests.cpp.

The C++ builds six shader stages by concatenating adjacent string literals (with comments between them) and by token replacement; this extracts the concatenated literals verbatim so the Rust side only does the token replacement.

Usage:
    python3 hodow_cts/scripts/gen_khr_texture_view_shaders.py [--cpp PATH] [--out PATH] [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = CRATE_DIR.parent
DEFAULT_CPP = REPO_DIR / "tmp" / "glcts-src" / "external" / "openglcts" / "modules" / "gl" / "gl4cTextureViewTests.cpp"
DEFAULT_OUT = CRATE_DIR / "src" / "khr_gl" / "texture_view" / "shaders.rs"

ESCAPES = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'"}


def skip_space_and_comments(text: str, pos: int) -> int:
    while pos < len(text):
        if text[pos].isspace():
            pos += 1
        elif text.startswith("//", pos):
            pos = text.index("\n", pos)
        elif text.startswith("/*", pos):
            pos = text.index("*/", pos) + 2
        else:
            break
    return pos


def parse_literals(text: str, pos: int) -> tuple[str, int]:
    """Parses adjacent string literals starting at pos; returns (decoded value, position after the last literal)."""
    value = []
    while True:
        pos = skip_space_and_comments(text, pos)
        if pos >= len(text) or text[pos] != '"':
            return "".join(value), pos
        pos += 1
        while text[pos] != '"':
            if text[pos] == "\\":
                value.append(ESCAPES[text[pos + 1]])
                pos += 2
            else:
                value.append(text[pos])
                pos += 1
        pos += 1


def assigned_literal(text: str, name: str, start: int = 0) -> tuple[str, int]:
    match = re.compile(r"\b" + re.escape(name) + r"\s*=\s*").search(text, start)
    if match is None:
        raise SystemExit(f"no assignment to {name} after offset {start}")
    value, end = parse_literals(text, match.end())
    return value, end


def function_region(src: str, name: str) -> str:
    start = src.index("TextureViewTestViewSampling::" + name + "(")
    end = src.index("\n}\n", start)
    return src[start:end]


def rust_str(value: str) -> str:
    return json.dumps(value)


def generate(src: str) -> str:
    out = [
        "// SPDX-License-Identifier: Apache-2.0\n//\n// GENERATED by hodow_cts/scripts/gen_khr_texture_view_shaders.py - do not edit by hand.\n//\n"
        "// Derived from VK-GL-CTS:\n//   external/openglcts/modules/gl/gl4cTextureViewTests.cpp  (TextureViewTestViewSampling shader sources)\n"
        "// Upstream revision: see hodow_cts/upstream/COMMIT\n//\n// Copyright (c) 2015-2016 The Khronos Group Inc.\n"
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).\n\n"
        "use crate::glw::{self, GLenum};\nuse crate::tcu::TestError;\n\n"
        "/// The three target-specific strings substituted into the stage templates.\n"
        "pub(super) struct SamplerStrings {\n    pub(super) declarations: &'static str,\n    pub(super) sample_fetch: &'static str,\n    pub(super) sample_fetch_fs: &'static str,\n}\n\n"
    ]

    iteration = function_region(src, "initIterationSpecificProgramObject")
    switch_start = iteration.index("switch (m_iteration_view_texture_target)")
    switch_end = iteration.index("} /* switch (m_iteration_view_texture_target) */", switch_start)
    switch = iteration[switch_start:switch_end]

    out.append("/// The `switch (m_iteration_view_texture_target)` of `initIterationSpecificProgramObject`.\n")
    out.append("pub(super) fn sampler_strings(texture_target: GLenum) -> Result<SamplerStrings, TestError> {\n    Ok(match texture_target {\n")
    chunks = re.split(r"\n\s*case (GL_\w+):", switch)
    for i in range(1, len(chunks), 2):
        target, body = chunks[i], chunks[i + 1]
        declarations, _ = assigned_literal(body, "sampler_declarations_string")
        sample_fetch, _ = assigned_literal(body, "sample_fetch_string")
        sample_fetch_fs, _ = assigned_literal(body, "sample_fetch_fs_string")
        out.append(
            f"        glw::{target} => SamplerStrings {{\n            declarations: {rust_str(declarations)},\n            sample_fetch: {rust_str(sample_fetch)},\n            sample_fetch_fs: {rust_str(sample_fetch_fs)},\n        }},\n"
        )
    out.append('        _ => return Err(TestError::Fail("Unrecognized texture target".to_string())),\n    })\n}\n\n')

    for name, const in (("vs_body", "VS_BODY"), ("tc_body", "TC_BODY"), ("te_body", "TE_BODY"), ("gs_body", "GS_BODY"), ("fs_body", "FS_BODY")):
        value, _ = assigned_literal(iteration, name)
        out.append(f"pub(super) const {const}: &str = {rust_str(value)};\n\n")

    match = re.search(r"varying_names\[\]\s*=\s*\{", iteration)
    pos = match.end()
    names = []
    while True:
        pos = skip_space_and_comments(iteration, pos)
        if iteration[pos] == "}":
            break
        value, pos = parse_literals(iteration, pos)
        names.append(value)
        pos = skip_space_and_comments(iteration, pos)
        if iteration[pos] == ",":
            pos += 1
    out.append(f"pub(super) const VARYING_NAMES: [&str; {len(names)}] = [\n" + "".join(f"    {rust_str(n)},\n" for n in names) + "];\n\n")

    filler = function_region(src, "initPerSampleFillerProgramObject")
    for name, const in (("fs_body", "FILLER_FS_BODY"), ("gs_body", "FILLER_GS_BODY"), ("vs_body", "FILLER_VS_BODY")):
        value, _ = assigned_literal(filler, name)
        out.append(f"pub(super) const {const}: &str = {rust_str(value)};\n\n")

    return "".join(out).rstrip("\n") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cpp", type=Path, default=DEFAULT_CPP)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="fail if the output file is stale instead of writing it")
    args = ap.parse_args()

    if not args.cpp.is_file():
        print(f"error: {args.cpp} not found; run `just glcts-build` first or pass --cpp", file=sys.stderr)
        return 2

    text = generate(args.cpp.read_text())
    if args.check:
        if not args.out.is_file() or args.out.read_text() != text:
            print(f"{args.out} is stale", file=sys.stderr)
            return 1
        return 0

    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
