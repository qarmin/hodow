#!/usr/bin/env python3
"""Writes the shaders, the manifest and the case table of dEQP-VK.texture.multisample.{atomic,invalid_sample_index} from the vendored Amber scripts.

Each script is read for its compute shader, the multisampled `IMAGE texture` (format, size, samples), the dispatch (`RUN pipeline x y z`) and the `EXPECT result`.
The r64 scripts need `shaderImageInt64Atomics`, which the default device does not enable: the instance runs them on a `RobustnessDevice` with it on (SPIR-V 1.3). Written:

  * shaders/manifest/texture_multisample.toml and shaders/src/texture_multisample/,
  * src/vkt/tests/texture/multisample_cases.rs (the table of src/vkt/tests/texture/multisample_tests.rs).

Run from hodow_cts/:  python3 scripts/gen_texture_multisample_amber.py   (then `just cts-shaders`)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/texture/multisample"
SRC = ROOT / "shaders" / "src" / "texture_multisample"
MANIFEST = ROOT / "shaders" / "manifest" / "texture_multisample.toml"
TABLE = ROOT / "src" / "vkt" / "tests" / "texture" / "multisample_cases.rs"

GROUP_NAMES = {"atomic": "atomic", "invalidsampleindex": "invalid_sample_index"}


def compute_shader(text):
    lines = text.splitlines()
    for ndx, line in enumerate(lines):
        if line.startswith("SHADER compute"):
            body = []
            for rest in lines[ndx + 1 :]:
                if rest.strip() == "END":
                    return "\n".join(body) + "\n"
                body.append(rest)
    raise RuntimeError("no compute shader")


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.texture.multisample.",
        "#",
        "# @generated by hodow_cts/scripts/gen_texture_multisample_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/texture/multisample/atomic/storage_image_r32i.amber"',
        'rust_module = "texture/multisample_tests"',
        "",
    ]
    table = [
        "// @generated by hodow_cts/scripts/gen_texture_multisample_amber.py - do not hand-edit.",
        "//",
        "// One row per Amber script of dEQP-VK.texture.multisample: the multisampled image, the dispatch and whether the case is a stub.",
        "",
        "use super::multisample_tests::MultisampleCase;",
        "use vulkanalia::prelude::v1_0::*;",
        "",
        "pub static MULTISAMPLE_CASES: &[MultisampleCase] = &[",
    ]
    for path in sorted(AMBER.glob("*/*.amber")):
        group = GROUP_NAMES[path.parent.name]
        name = path.stem
        text = path.read_text()
        key = f"multisample_{group}_{name}"
        fmt, width, height, samples = re.search(r"IMAGE texture FORMAT (\w+) DIM_2D WIDTH (\d+) HEIGHT (\d+) SAMPLES (\d+)", text).groups()
        dispatch = re.search(r"RUN pipeline (\d+) (\d+) (\d+)", text).groups()
        stub = None
        spirv = ', spirv_version = "spirv1.3"' if fmt.startswith("R64") else ""
        if stub is None:
            (SRC / f"{key}_comp.comp").write_text(compute_shader(text))
            out += ["[[case]]", f'name = "{key}"', f'rust_const = "{key.upper()}"', 'rust_type = "SharedProgram"', "programs = [",
                    f'    {{ name = "comp", template = "texture_multisample/{key}_comp.comp", stage = "comp"{spirv} }},', "]", ""]
        stub_literal = "None" if stub is None else f'Some("{stub}")'
        table.append(
            f'    MultisampleCase {{ group: "{group}", name: "{name}", key: "{key}", format: vk::Format::{fmt}, size: ({width}, {height}), samples: {samples}, '
            f"dispatch: ({dispatch[0]}, {dispatch[1]}, {dispatch[2]}), atomic: {str(group == 'atomic').lower()}, stub: {stub_literal} }},"
        )
    table.append("];")
    MANIFEST.write_text("\n".join(out))
    TABLE.write_text("\n".join(table) + "\n")
    print(len(list(AMBER.glob("*/*.amber"))), "cases")


if __name__ == "__main__":
    main()
