#!/usr/bin/env python3
"""Writes shaders/manifest/pipeline_multisample_conservative.toml and its fragment shaders.

`SampleMaskWithConservativeTest::initPrograms`: the colour fragment shader depends on post depth coverage, min sample shading (with the
sample count), and whether it reads gl_FragFullyCoveredNV. The vertex shader is the multisample `color.vert`, the copy shaders are the
multisample `quad.vert` and `copy_sample.frag`.
"""
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
SRC = CRATE / "shaders" / "src" / "pipeline" / "multisample_conservative"
MANIFEST = CRATE / "shaders" / "manifest" / "pipeline_multisample_conservative.toml"


def frag(post_depth: bool, min_shading: bool, fully_covered: bool, samples: int) -> str:
    text = "#version 440\n"
    if post_depth:
        text += "#extension GL_ARB_post_depth_coverage : require\n"
    if fully_covered:
        text += "#extension GL_NV_conservative_raster_underestimation : enable\n"
    text += "layout(early_fragment_tests) in;\n"
    if post_depth:
        text += "layout(post_depth_coverage) in;\n"
    text += "layout(location = 0) in vec4 vtxColor;\nlayout(location = 0) out vec4 fragColor;\nvoid main (void)\n{\n"
    if min_shading:
        text += (
            "    const int coveredSamples = bitCount(gl_SampleMaskIn[0]);\n"
            f"    vec4 color = vtxColor * (1.0 / {samples} * coveredSamples);\n"
        )
    else:
        text += "    vec4 color = vtxColor;\n"
    if fully_covered:
        text += "    if (!gl_FragFullyCoveredNV) color = vec4(0.0f);\n"
    text += "    fragColor = color;\n}\n"
    return text


def main() -> None:
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.pipeline.*.multisample*.conservative_with_full_coverage.*",
        "#",
        "# @generated by hodow_cts/scripts/gen_conservative_manifest.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/pipeline/vktPipelineMultisampleTests.cpp"',
        'rust_module = "pipeline/multisample_tests"',
        "",
    ]
    for post_depth in (False, True):
        for min_shading in (False, True):
            for fully_covered in (False, True):
                for samples in (2, 4, 8, 16):
                    if not min_shading and samples != 2:
                        continue
                    key = f"pdc{int(post_depth)}_min{int(min_shading)}_fc{int(fully_covered)}_s{samples if min_shading else 0}"
                    (SRC / f"{key}.frag").write_text(frag(post_depth, min_shading, fully_covered, samples))
                    out += [
                        "[[case]]",
                        f'name = "{key}"',
                        f'rust_const = "CONSERVATIVE_{key.upper()}"',
                        'rust_type = "SharedProgram"',
                        "programs = [",
                        '    { name = "color_vert", template = "pipeline/multisample/color.vert", stage = "vert" },',
                        f'    {{ name = "color_frag", template = "pipeline/multisample_conservative/{key}.frag", stage = "frag" }},',
                        '    { name = "quad_vert", template = "pipeline/multisample/quad.vert", stage = "vert" },',
                        '    { name = "copy_sample_frag", template = "pipeline/multisample/copy_sample.frag", stage = "frag" },',
                        "]",
                        "",
                    ]
    MANIFEST.write_text("\n".join(out))


if __name__ == "__main__":
    main()
