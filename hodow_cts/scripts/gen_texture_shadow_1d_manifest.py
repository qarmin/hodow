#!/usr/bin/env python3
"""Writes shaders/manifest/texture_shadow_1d.toml: the PROGRAM_1D_SHADOW and PROGRAM_1D_ARRAY_SHADOW programs of vktTextureTestUtil.cpp's initializePrograms, used by dEQP-VK.texture.shadow.{1d,1d_array}.

    python3 hodow_cts/scripts/gen_texture_shadow_1d_manifest.py

Reuses the three templates of gen_texture_swizzle_manifest.py; the 1D program stores into an image1D at `int(coord.x + pc.u_offset.x)` like upstream's `isOutput1D` branch.

A pure text generator: no glslang and no cargo.
"""

import json
import sys
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_texture_swizzle_manifest as swz  # noqa: E402

OUT = CRATE / "shaders" / "manifest" / "texture_shadow_1d.toml"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "texture_shadow_1d"
SOURCE = "external/vulkancts/modules/vulkan/texture/vktTextureTestUtil.cpp"

PROGRAMS = [
    ("1D_SHADOW", "float", "sampler1DShadow", "vec4(texture(u_sampler, vec3(texCoord, 0.0, u_ref)), 0.0, 0.0, 1.0)", "vec4(textureGrad(u_sampler, vec3(texCoord, 0.0, u_ref), dPdx, dPdy), 0.0, 0.0, 1.0)", True),
    ("1D_ARRAY_SHADOW", "vec2", "sampler1DArrayShadow", "vec4(texture(u_sampler, vec3(texCoord, u_ref)), 0.0, 0.0, 1.0)", "vec4(textureGrad(u_sampler, vec3(texCoord, u_ref), dPdx.x, dPdy.x), 0.0, 0.0, 1.0)", False),
]


def main():
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    out = (
        "# Shader manifest for dEQP-VK.texture.shadow.{1d,1d_array}\n#\n"
        "# @generated by hodow_cts/scripts/gen_texture_shadow_1d_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "texture/shadow_tests"\n'
    )
    for program, tc, sampler, frag_lookup, comp_lookup, output_1d in PROGRAMS:
        key = program.lower()
        for stage in ("vert", "frag", "comp"):
            (TEMPLATE_DIR / f"{key}_{stage}.glsl").write_text("${src_" + stage + "}")
        comp = swz.COMP.replace("{imgfmt}", "rgba8").replace("{tctype}", tc).replace("{sampler}", sampler).replace("{swz}", "").replace("{lookup}", comp_lookup)
        if output_1d:
            comp = comp.replace("image2D u_outputImage", "image1D u_outputImage").replace("imageStore(u_outputImage, coord + pc.u_offset, result)", "imageStore(u_outputImage, int(coord.x + pc.u_offset.x), result)")
            assert "image1D" in comp and "int(coord.x" in comp
        sources = {
            "src_vert": swz.VERT.replace("{tctype}", tc),
            "src_frag": swz.FRAG.replace("{fragprec}", "mediump").replace("{tctype}", tc).replace("{sampler}", sampler).replace("{swz}", "").replace("{lookup}", frag_lookup),
            "src_comp": comp,
        }
        programs = ", ".join(
            f'{{ name = "{stage}_{program}", template = "texture_shadow_1d/{key}_{short}.glsl", stage = "{short}" }}'
            for stage, short in (("vertex", "vert"), ("fragment", "frag"), ("compute", "comp"))
        )
        derived = ", ".join(f"{k} = {json.dumps(repr(v))}" for k, v in sources.items())
        out += f'\n[[case]]\nname = "{key}"\nrust_const = "PROGRAM_{program}"\nrust_type = "SharedProgram"\nprograms = [{programs}]\nderived = {{ {derived} }}\n'
    OUT.write_text(out, encoding="utf-8")
    print("wrote 2 cases")


if __name__ == "__main__":
    main()
