#!/usr/bin/env python3
"""Generate src/vkt/tests/api/vulkan_property_consistency_tests.rs, `property_extensions_consistency` of dEQP-VK.api.info.vulkan1p{2,3}.

The twin of gen_vulkan_feature_consistency_tests.py for `devicePropertyExtensionsConsistencyVulkan12/13`: structure lists, compared
member pairs (plain, `deMemCmp` of an array, `strncmp` of a string) and failure messages come from the C++, every name is checked
against vulkanalia. The 1.4 variant also compares arrays whose length is only known after a first query and is not generated.

Usage:
    python3 hodow_cts/scripts/gen_vulkan_property_consistency_tests.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_vulkan_feature_consistency_tests import (  # noqa: E402
    CRATE_DIR,
    UPSTREAM,
    balanced,
    function_text,
    literal,
    normalise,
    rust_struct,
    snake,
    vulkanalia_structs,
)

OUT = CRATE_DIR / "src/vkt/tests/api/vulkan_property_consistency_tests.rs"
FUNCTIONS = [("12", (1, 2)), ("13", (1, 3))]

MEMBER = r"(\w+)\.(\w+)((?:\.\w+)?)"
PLAIN = re.compile(rf"{MEMBER}\s*!=\s*{MEMBER}$")
ARRAY = re.compile(rf"deMemCmp\({MEMBER},\s*{MEMBER},\s*\w+\)\s*!=\s*0$")
STRING = re.compile(rf"strncmp\({MEMBER},\s*{MEMBER},\s*\w+\)\s*!=\s*0$")


def term(variables: dict, text: str) -> str:
    text = re.sub(r"^[()\s]+|[()\s]+$", "", text) if not text.strip().startswith(("deMemCmp", "strncmp")) else text.strip().strip("()")
    text = text.strip()
    if text.startswith(("deMemCmp", "strncmp")):
        text = text if text.endswith("0") else text + "0"
    for pattern, kind in ((ARRAY, "array"), (STRING, "string"), (PLAIN, "plain")):
        match = pattern.match(text)
        if match:
            break
    else:
        sys.exit(f"unrecognised term: {text}")
    a_var, a_member, a_sub, b_var, b_member, b_sub = match.groups()
    a_field = variables[a_var][1].get(normalise(a_member))
    b_field = variables[b_var][1].get(normalise(b_member))
    if a_field is None or b_field is None:
        sys.exit(f"{a_var}.{a_member} or {b_var}.{b_member} is not in vulkanalia")
    a = f"{snake(a_var)}.{a_field}{a_sub}"
    b = f"{snake(b_var)}.{b_field}{b_sub}"
    return f"!string_eq(&{a}, &{b})" if kind == "string" else f"{a} != {b}"


def main() -> int:
    cpp = UPSTREAM.read_text()
    structs = vulkanalia_structs()
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp (`devicePropertyExtensionsConsistencyVulkan12`, `...Vulkan13`)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2015 The Khronos Group Inc.",
        "// Copyright (c) 2015 Intel Corporation",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_vulkan_property_consistency_tests.py from upstream's function bodies; do not hand-edit.",
        "//",
        "// `property_extensions_consistency`: the property structures of the extensions promoted into Vulkan 1.2 and 1.3 report the same",
        "// members as the core `VkPhysicalDeviceVulkan1xProperties` structures. The 1.4 case is not ported.",
        "",
        "use vulkanalia::prelude::v1_0::*;",
        "use vulkanalia::vk::InstanceV1_1;",
        "",
        "use crate::tcu::{TestError, TestOutcome, TestStatus};",
        "use crate::vkt::Context;",
        "",
        "fn require_api_version(context: &Context<'_>, version: (u32, u32)) -> Result<(), TestError> {",
        "    let (major, minor, _) = context.api_version();",
        "    if (major, minor) < version {",
        "        return Err(TestError::NotSupported(format!(\"At least Vulkan {}.{} required to run test\", version.0, version.1)));",
        "    }",
        "    Ok(())",
        "}",
        "",
        "/// `strncmp(a, b, N) != 0` negated: the strings are equal up to their first NUL.",
        "fn string_eq<const N: usize>(a: &vk::StringArray<N>, b: &vk::StringArray<N>) -> bool {",
        "    a.to_string_lossy() == b.to_string_lossy()",
        "}",
        "",
    ]
    for suffix, version in FUNCTIONS:
        text = function_text(cpp, f"devicePropertyExtensionsConsistencyVulkan{suffix}")
        decls = re.findall(r"(Vk\w+)\s+(\w+)\s*=\s*\n?\s*initVulkanStructure\(", text)
        variables: dict[str, tuple[str, dict[str, str]]] = {}
        core, ext = [], []
        for c_type, var in decls:
            if c_type == "VkPhysicalDeviceProperties2":
                continue
            variables[var] = rust_struct(structs, c_type)
            (core if re.fullmatch(r"VkPhysicalDeviceVulkan1\dProperties", c_type) else ext).append(var)

        def query(vars_: list[str]) -> list[str]:
            lines = [f"    let mut {snake(v)} = vk::{variables[v][0]}::default();" for v in vars_]
            pushes = "".join(f".push_next(&mut {snake(v)})" for v in vars_)
            lines += [
                "    {",
                f"        let mut properties2 = vk::PhysicalDeviceProperties2::builder(){pushes};",
                "        unsafe { context.get_instance().get_physical_device_properties2(context.get_physical_device(), &mut properties2) };",
                "    }",
                "",
            ]
            return lines

        out += [f"pub fn device_property_extensions_consistency_vulkan{suffix}(context: &Context<'_>) -> TestOutcome {{", f"    require_api_version(context, {version})?;", ""]
        out += query(core) + query(ext)

        body = text[text.index("Validate all fields initialized") :]
        for match in re.finditer(r"\bif \(", body):
            condition, end = balanced(body, match.end() - 1)
            rest = body[end + 1 :].lstrip()
            if rest.startswith("{"):
                rest = rest[1:].lstrip()
            if not rest.startswith("TCU_FAIL("):
                continue
            message = literal(balanced(rest, len("TCU_FAIL"))[0])
            condition = re.sub(r"\s*\.\s*", ".", re.sub(r"\s+", " ", condition))
            parts = [term(variables, part) for part in condition.split("||")]
            expression = " || ".join(parts)
            if any(name in condition for name in ("deviceLUID,", "deviceNodeMask")) and "deviceLUIDValid" not in condition:
                expression = f"id_properties.device_luid_valid != vk::FALSE && ({expression})"
            out += [f"    if {expression} {{", f'        return Ok(TestStatus::fail("{message}".to_string()));', "    }"]

        out += [f'    Ok(TestStatus::pass("Vulkan {version[0]}.{version[1]} device properties are consistent with extension properties"))', "}", ""]

    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(CRATE_DIR.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
