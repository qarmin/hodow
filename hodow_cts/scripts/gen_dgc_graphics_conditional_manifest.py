#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.graphics.conditional_rendering (`fullScreenTrianglePrograms` of
vktDGCGraphicsConditionalTestsExt.cpp), one shared program set. A pure text generator: no glslang, no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_graphics_conditional.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

VERT = (
    "#version 460\n"
    "vec2 positions[3] = vec2[](\n"
    "    vec2(-1.0, -1.0),\n"
    "    vec2( 3.0, -1.0),\n"
    "    vec2(-1.0,  3.0)\n"
    ");\n"
    "void main (void) {\n"
    "    gl_Position = vec4(positions[gl_VertexIndex % 3], 0.0, 1.0);\n"
    "}\n"
)

FRAG = (
    "#version 460\n"
    "layout (location=0) out vec4 outColor;\n"
    "layout (push_constant, std430) uniform PCBlock { vec4 color; } pc;\n"
    "void main (void) {\n"
    "    outColor = pc.color;\n"
    "}\n"
)

MANIFEST_TEXT = """# Shader manifest for dEQP-VK.dgc.ext.graphics.conditional_rendering
#
# @generated by hodow_cts/scripts/gen_dgc_graphics_conditional_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCGraphicsConditionalTestsExt.cpp"
rust_module = "dgc/graphics_conditional_tests"

[[case]]
name = "conditional_fullscreen"
rust_const = "CONDITIONAL_FULLSCREEN"
rust_type = "SharedProgram"
programs = [ { name = "vert", template = "dgc/conditional_fullscreen_vert.vert", stage = "vert" }, { name = "frag", template = "dgc/conditional_fullscreen_frag.frag", stage = "frag" } ]
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    (SRC_DIR / "conditional_fullscreen_vert.vert").write_text(VERT)
    (SRC_DIR / "conditional_fullscreen_frag.frag").write_text(FRAG)
    MANIFEST.write_text(MANIFEST_TEXT)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
