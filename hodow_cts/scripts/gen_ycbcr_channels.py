#!/usr/bin/env python3
"""Generate src/vkt/tests/ycbcr/format_channels.rs: the channel descriptions of `getYCbCrPlanarFormatDescription` (vkImageUtil.cpp).

`gen_ycbcr_formats.py` keeps the planes of every YCbCr format; the formats tests also need where each channel (R, G, B, A) lives:
the plane, the bit offset and size of the value in an element, and the distance in bytes between two values of the channel.

Usage:
    python3 hodow_cts/scripts/gen_ycbcr_channels.py
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
OUT = CRATE_DIR / "src" / "vkt" / "tests" / "ycbcr" / "format_channels.rs"
SOURCE = CRATE_DIR / "upstream" / "external" / "vulkancts" / "framework" / "vulkan" / "vkImageUtil.cpp"

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_format_lists import rust_name as _enum_rust_name  # noqa: E402


def rust_name(vk_name: str) -> str:
    return _enum_rust_name(vk_name.removeprefix("VK_FORMAT_"))


def main() -> int:
    text = SOURCE.read_text()
    body = text[text.index("const PlanarFormatDescription &getYCbCrPlanarFormatDescription") :]
    end = body.find("\nbool isYCbCrExtensionFormat")
    body = body[: end if end >= 0 else len(body)]

    entries: dict[str, list] = {}
    chunks = re.split(r"\n\s*//\s*(VK_FORMAT_[A-Za-z0-9_]+)\s*\n", body)
    for i in range(1, len(chunks) - 1, 2):
        name, entry = chunks[i], chunks[i + 1]
        rows = re.findall(r"\{\s*(\d+)\s*,\s*(unorm|0)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", entry)
        if len(rows) < 4:
            continue
        channels = []
        for plane, kind, offset, size, stride in rows[:4]:
            channels.append(None if kind == "0" and size == "0" else (int(plane), int(offset), int(size), int(stride)))
        entries.setdefault(name, channels)

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/vulkancts/framework/vulkan/vkImageUtil.cpp (`getYCbCrPlanarFormatDescription`, the channel descriptions)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2025 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_ycbcr_channels.py; do not hand-edit.",
        "",
        "use vulkanalia::vk;",
        "",
        "/// One channel of a `PlanarFormatDescription`, always unsigned fixed point.",
        "#[derive(Clone, Copy)]",
        "pub struct ChannelDesc {",
        "    pub plane: u32,",
        "    pub offset_bits: u32,",
        "    pub size_bits: u32,",
        "    pub stride_bytes: u32,",
        "}",
        "",
        "/// The R, G, B and A channels of every YCbCr format.",
        "pub static CHANNELS: &[(vk::Format, [Option<ChannelDesc>; 4])] = &[",
    ]
    for name, channels in sorted(entries.items()):
        cells = ", ".join(
            "None" if c is None else f"Some(ChannelDesc {{ plane: {c[0]}, offset_bits: {c[1]}, size_bits: {c[2]}, stride_bytes: {c[3]} }})"
            for c in channels
        )
        lines.append(f"    (vk::Format::{rust_name(name)}, [{cells}]),")
    lines += ["];", ""]

    OUT.write_text("\n".join(lines))
    subprocess.run(["rustfmt", "--edition", "2024", "--config", "max_width=180", str(OUT)], cwd=CRATE_DIR, check=False)
    print(len(entries), "formats")
    return 0


if __name__ == "__main__":
    sys.exit(main())
