#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.compute.get_info (`initBasicProgram`): one program with and one without a push
constant. A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_compute_get_info.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"


def comp(use_push_constants):
    pc = "layout (push_constant, std430) uniform PCBlock { uint value; } pc;\n" if use_push_constants else ""
    offset = "pc.value" if use_push_constants else "0"
    return f"""#version 460
layout (set=0, binding=0) buffer OutputBufferBlock {{ uint results[]; }} output_buffer;
layout (local_size_x=64, local_size_y=1, local_size_z=1) in;
{pc}void main (void)
{{
    const uint totalWorkGroupSize     = gl_WorkGroupSize.x * gl_WorkGroupSize.y * gl_WorkGroupSize.z;
    const uint workGroupIndex         = gl_NumWorkGroups.x * gl_NumWorkGroups.y * gl_WorkGroupID.z + gl_NumWorkGroups.x * gl_WorkGroupID.y + gl_WorkGroupID.x;
    const uint globalInvocationIndex  = workGroupIndex * totalWorkGroupSize + gl_LocalInvocationIndex;

    const uint offset = {offset};
    output_buffer.results[globalInvocationIndex] = uint(sqrt(float(globalInvocationIndex))) + offset;
}}
"""


HEADER = """# Shader manifest for dEQP-VK.dgc.ext.compute.get_info
#
# @generated by hodow_cts/scripts/gen_dgc_compute_get_info_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCComputeGetInfoTestsExt.cpp"
rust_module = "dgc/compute_get_info_tests"
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    out = [HEADER]
    for key, use_pc in (("get_info_basic", False), ("get_info_pc", True)):
        (SRC_DIR / f"{key}.comp").write_text(comp(use_pc))
        out.append(
            f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [ {{ name = "comp", template = "dgc/{key}.comp", stage = "comp" }} ]
"""
        )
    MANIFEST.write_text("".join(out))
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
