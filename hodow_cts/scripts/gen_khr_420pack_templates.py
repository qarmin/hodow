DECL = re.compile(r"static const GLchar \*(\w+)\s*=\s*")


def parse_literals(text, pos):
    parts = []
    while True:
        while text[pos].isspace():
            pos += 1
        if text.startswith("/*", pos):
            pos = text.index("*/", pos) + 2
        elif text.startswith("//", pos):
            pos = text.index("\n", pos)
        elif text[pos] == '"':
            end = pos + 1
            while text[end] != '"':
                end += 2 if text[end] == "\\" else 1
            parts.append(text[pos + 1:end])
            pos = end + 1
        elif text[pos] == ";":
            return parts
        else:
            raise SystemExit(f"unexpected {text[pos:pos + 20]!r}")


def rust_literal(raw):
    out = []
    i = 0
    while i < len(raw):
        c = raw[i]
        if c == "\\":
            nxt = raw[i + 1]
            assert nxt in 'n"\\t', raw
            out.append(c + nxt)
            i += 2
        else:
            assert c.isascii(), raw
            out.append(c)
            i += 1
    return '"' + "".join(out) + '"'


def generate(src):
    lines = src.read_text().split("\n")
    out = [
        "// GENERATED by hodow_cts/scripts/gen_khr_420pack_templates.py from gl4cShadingLanguage420PackTests.cpp - do not edit.",
        "// SPDX-License-Identifier: Apache-2.0",
        "// Copyright (c) 2015-2016 The Khronos Group Inc.",
        "",
        "#![allow(dead_code)]",
        "",
    ]
    for prefix, first, last in SPECS:
        body = "\n".join(lines[first - 1:last])
        for match in DECL.finditer(body):
            parts = parse_literals(body, match.end())
            name = f"{prefix}_{match.group(1).upper()}"
            out.append(f"pub(super) const {name}: &str = concat!(")
            out.extend(f"    {rust_literal(part)}," for part in parts)
            out.append(");")
            out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--src", type=Path, default=DEFAULT_SRC)
    args = parser.parse_args()
    text = generate(args.src)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is stale")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
