#!/usr/bin/env python3
"""Emit the shader templates of gl4cShadingLanguage420PackTests.cpp as Rust constants.

Every `static const GLchar *name = "..." "...";` between the line ranges of SPECS becomes
`pub(super) const <PREFIX>_<NAME>: &str = concat!(...)` keeping upstream's literal split, so the Rust file can be read
side by side with the C++. Usage: gen_khr_420pack_templates.py [--check] [--src PATH]
"""
