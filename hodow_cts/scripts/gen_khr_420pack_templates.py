DEFAULT_SRC = ROOT / "tmp/glcts-src/external/openglcts/modules/gl/gl4cShadingLanguage420PackTests.cpp"
OUT = ROOT / "hodow_cts/src/khr_gl/shading_language_420pack/templates.rs"

# (prefix, first line, last line) of the prepareShaderSource bodies whose templates are ported.
