#!/usr/bin/env python3
"""Writes shaders/manifest/spirv_assembly_opselect_different_strides.toml: dEQP-VK.spirv_assembly.instruction.compute.variable_pointers.compute.opselect_different_strides
(vktSpvAsmOpSelectDifferentStridesTests.cpp). The assembly is the raw string `spvasm` of the C++, with `${SPV_*_physical_storage_buffer}` set to the EXT and the KHR extension name for the two programs.

    python3 hodow_cts/scripts/gen_spirv_assembly_opselect_different_strides_manifest.py

A pure text generator: no spirv-as and no cargo.
"""

import json
import re
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "spirv_assembly_opselect_different_strides.toml"
SOURCE = "external/vulkancts/modules/vulkan/spirv_assembly/vktSpvAsmOpSelectDifferentStridesTests.cpp"
VAR = "${SPV_*_physical_storage_buffer}"


def main():
    text = (CRATE / "upstream" / SOURCE).read_text(encoding="utf-8")
    spvasm = re.search(r'R"spirv\((.*?)\)spirv"', text, flags=re.S).group(1)
    assert VAR in spvasm
    ext = spvasm.replace(VAR, "SPV_EXT_physical_storage_buffer")
    khr = spvasm.replace(VAR, "SPV_KHR_physical_storage_buffer")
    out = (
        "# Shader manifest for dEQP-VK.spirv_assembly.instruction.compute.variable_pointers.compute.opselect_different_strides\n#\n"
        "# @generated by hodow_cts/scripts/gen_spirv_assembly_opselect_different_strides_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "spirv_assembly/opselect_different_strides_tests"\n\n'
        '[[case]]\nname = "opselect_different_strides"\nrust_const = "OPSELECT_DIFFERENT_STRIDES"\nrust_type = "OpSelectDifferentStridesCase"\n'
        "programs = [\n"
        '    { name = "compute_ext", template = "spirv_assembly_opselect/compute_ext.asm", stage = "asm", spirv_version = "spirv1.4" },\n'
        '    { name = "compute_khr", template = "spirv_assembly_opselect/compute_khr.asm", stage = "asm", spirv_version = "spirv1.4" },\n'
        "]\n"
        f"derived = {{ source_ext = {json.dumps(repr(ext))}, source_khr = {json.dumps(repr(khr))} }}\n"
    )
    OUT.write_text(out, encoding="utf-8")
    print("wrote 1 case")


if __name__ == "__main__":
    main()
