#!/usr/bin/env python3
"""Emit src/generated/khr_blend_colors.rs: BlendTestCaseGroup::s_common and s_rgb10a2 from glcBlendEquationAdvancedTests.cpp (expressions like `A1 * 0.5f` kept as written)."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
cpp = (root / "tmp/glcts-src/external/openglcts/modules/common/glcBlendEquationAdvancedTests.cpp").read_text()

def array(name):
    m = re.search(r"const glw::GLfloat BlendTestCaseGroup::%s\[\] = \{(.*?)\n\};" % name, cpp, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    items = [t.strip() for t in body.split(",") if t.strip()]
    out = []
    for t in items:
        t = re.sub(r"(\d)f\b", r"\1", t)
        t = re.sub(r"\b(\d+)(?=\s*(\*|$))", r"\1", t)
        if re.fullmatch(r"-?\d+", t):
            t += ".0"
        out.append(t)
    return out

lines = ["// Generated by hodow_cts/scripts/gen_khr_blend_colors.py - do not edit.", "", "const A1: f32 = 0.750;", "const A2: f32 = 0.375;", "const A3: f32 = 0.125;", ""]
for cname, name in (("COMMON", "s_common"), ("RGB10A2", "s_rgb10a2")):
    vals = array(name)
    assert len(vals) % 8 == 0, (name, len(vals))
    lines.append(f"pub const {cname}: [f32; {len(vals)}] = [")
    for i in range(0, len(vals), 8):
        lines.append("    " + ", ".join(vals[i:i + 8]) + ",")
    lines.append("];")
    lines.append("")
    print(name, len(vals) // 8, file=sys.stderr)
(root / "hodow_cts/src/generated/khr_blend_colors.rs").write_text("\n".join(lines))
