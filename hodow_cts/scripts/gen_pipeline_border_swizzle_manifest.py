#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.pipeline.*.sampler.border_swizzle.* (`BorderSwizzleCase::initPrograms`).

The shaders depend on the sampler type (float, signed or unsigned, from the texture format and the stencil aspect) and the gather component,
and the compute ones on the matching output image; `bs_key` in sampler_border_swizzle_tests.rs finds an entry. A pure text generator: no
glslang and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "pipeline_border_swizzle.toml"

HEADER = """# Shader manifest for dEQP-VK.pipeline.*.sampler.border_swizzle.*
#
# @generated by hodow_cts/scripts/gen_pipeline_border_swizzle_manifest.py - do not hand-edit.
#
# `BorderSwizzleCase::initPrograms`, one entry per sampler type and gather component, for graphics and for compute.

upstream_source = "external/vulkancts/modules/vulkan/pipeline/vktPipelineSamplerBorderSwizzleTests.cpp"
rust_module = "pipeline/sampler_border_swizzle_tests"
"""

# type letter -> (sampler/vec prefix, image type, image format qualifier)
TYPES = {"f": ("", "image2D", "rgba32f"), "i": ("i", "iimage2D", "rgba32i"), "u": ("u", "uimage2D", "rgba32ui")}


def frag(prefix, gather):
    return (
        "#version 450\n\n"
        "layout (constant_id=0) const float u = 0.0f;\n"
        "layout (constant_id=1) const float v = 0.0f;\n"
        "layout (constant_id=2) const int gatherFlag = 0;\n\n"
        f"layout (set=0, binding=0) uniform {prefix}sampler2D texSampler;\n\n"
        f"layout (location=0) out {prefix}vec4 colorOut;\n\n"
        "void main()\n{\n"
        "    const vec2 coords = vec2(u, v);\n\n"
        "    if (gatherFlag != 0)\n    {\n"
        f"        colorOut = textureGather(texSampler, coords, {gather});\n"
        "    }\n    else\n    {\n"
        "        colorOut = texture(texSampler, coords);\n"
        "    }\n}\n"
    )


def comp(prefix, image_type, qualifier, gather):
    return (
        "#version 450\n\n"
        "layout(local_size_x = 16, local_size_y = 16, local_size_z = 1) in;\n\n"
        "layout (constant_id=0) const float u = 0.0f;\n"
        "layout (constant_id=1) const float v = 0.0f;\n"
        "layout (constant_id=2) const int gatherFlag = 0;\n\n"
        f"layout (set=0, binding=0) uniform {prefix}sampler2D texSampler;\n"
        f"layout (set=0, binding=1, {qualifier}) writeonly uniform {image_type} outImage;\n\n"
        "void main()\n{\n"
        "    const vec2 coords = vec2(u, v);\n"
        f"    {prefix}vec4 colorOut;\n\n"
        "    if (gatherFlag != 0)\n    {\n"
        f"        colorOut = textureGather(texSampler, coords, {gather});\n"
        "    }\n    else\n    {\n"
        "        colorOut = texture(texSampler, coords);\n"
        "    }\n"
        "    imageStore(outImage, ivec2(gl_GlobalInvocationID.xy), colorOut);\n}\n"
    )


def literal(text):
    return '"' + repr(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    out = [HEADER]
    for letter, (prefix, image_type, qualifier) in TYPES.items():
        for gather in range(4):
            key = f"bs_gfx_{letter}_{gather}"
            out.append(f'\n[[case]]\nname = "{key}"\nrust_const = "{key.upper()}"\nrust_type = "SharedProgram"\n')
            out.append(
                "programs = [\n"
                '    { name = "vert", template = "pipeline/border_swizzle/border_swizzle.vert", stage = "vert" },\n'
                '    { name = "frag", template = "pipeline/border_swizzle/border_swizzle.frag", stage = "frag" },\n'
                "]\n"
            )
            out.append(f"derived = {{ frag_source = {literal(frag(prefix, gather))} }}\n")
            key = f"bs_comp_{letter}_{gather}"
            out.append(f'\n[[case]]\nname = "{key}"\nrust_const = "{key.upper()}"\nrust_type = "SharedProgram"\n')
            out.append('programs = [{ name = "comp", template = "pipeline/border_swizzle/border_swizzle.comp", stage = "comp" }]\n')
            out.append(f"derived = {{ comp_source = {literal(comp(prefix, image_type, qualifier, gather))} }}\n")
    MANIFEST.write_text("".join(out))
    print("24 entries")


if __name__ == "__main__":
    main()
