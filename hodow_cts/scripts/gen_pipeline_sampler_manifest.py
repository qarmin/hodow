#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.pipeline.*.sampler.view_type and the other cases built on ImageSamplingInstance.

`SamplerTest::initPrograms` bakes the lookup scale and bias of the format and swizzle into the GLSL as vec4 literals. Here they are
a push constant (`scale`, `bias`, `lod`, written by `ImageSamplingInstance` from the same arithmetic), which leaves one program set
per sampler type, texture coordinate width and lookup kind: `gfx_<type>_<view>_<lookup>` for the vertex + fragment pair and
`cmp_<type>_<view>_<lookup>` for the compute variant, found by `sampler_program_key` in image_sampling_instance.rs.

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "pipeline_sampler.toml"

HEADER = """# Shader manifest for the ImageSamplingInstance based groups of dEQP-VK.pipeline.*
#
# @generated by hodow_cts/scripts/gen_pipeline_sampler_manifest.py - do not hand-edit.
#
# `SamplerTest::initPrograms`, with the lookup scale and bias as a push constant instead of literals in the source.

upstream_source = "external/vulkancts/modules/vulkan/pipeline/vktPipelineSamplerTests.cpp"
rust_module = "pipeline/image_sampling_instance"
"""

# (key, GLSL sampler suffix, texture coordinate swizzle)
VIEWS = [
    ("1d", "sampler1D", "x"),
    ("1d_array", "sampler1DArray", "xy"),
    ("2d", "sampler2D", "xy"),
    ("2d_array", "sampler2DArray", "xyz"),
    ("3d", "sampler3D", "xyz"),
    ("cube", "samplerCube", "xyz"),
    ("cube_array", "samplerCubeArray", "xyzw"),
]
PREFIXES = [("f", ""), ("i", "i"), ("u", "u")]
LOOKUPS = [("tex", "texture(texSampler, vtxTexCoords.{swz})"), ("lod", "textureLod(texSampler, vtxTexCoords.{swz}, pc.lod)")]


def py(value: str) -> str:
    return '"' + repr(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    out = [HEADER]
    count = 0
    for prefix_key, prefix in PREFIXES:
        for view_key, sampler, swizzle in VIEWS:
            for lookup_key, lookup in LOOKUPS:
                derived = f'sampler_type = {py(prefix + sampler)}, lookup = {py(lookup.format(swz=swizzle))}'
                for kind, programs in (
                    ("gfx", '{ name = "tex_vert", template = "pipeline/sampler/tex.vert", stage = "vert" }, { name = "tex_frag", template = "pipeline/sampler/tex.frag", stage = "frag" }'),
                    ("cmp", '{ name = "tex_comp", template = "pipeline/sampler/tex.comp", stage = "comp" }'),
                ):
                    key = f"{kind}_{prefix_key}_{view_key}_{lookup_key}"
                    out.append(
                        f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{programs}]
derived = {{ {derived} }}
"""
                    )
                    count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {MANIFEST}")


EXACT_MANIFEST = MANIFEST.with_name("pipeline_sampler_exact.toml")

EXACT_HEADER = """# Shader manifest for dEQP-VK.pipeline.*.sampler.exact_sampling and max_sampler_lod_bias
#
# @generated by hodow_cts/scripts/gen_pipeline_sampler_manifest.py - do not hand-edit.
#
# `ExactSamplingCase::initPrograms` and `MaxSamplerLodBiasCase::initPrograms`. The compute shader of the exact sampling cases
# declares the format qualifier of the storage image, so it has one entry per qualifier.

upstream_source = "external/vulkancts/modules/vulkan/pipeline/vktPipelineSamplerTests.cpp"
rust_module = "pipeline/sampler_exact_tests"
"""

# The qualifiers `getShaderImageFormatQualifier` gives the storage compatible, non swizzled formats of the exact sampling list.
EXACT_QUALIFIERS = [
    "r8", "rg8", "rgba8", "r8_snorm", "rg8_snorm", "rgba8_snorm", "r8ui", "rg8ui", "rgba8ui", "r8i", "rg8i",
    "r16f", "rg32f", "rgba16f", "rg16ui", "rg16i", "r16_snorm", "r32f", "r32i", "r32ui", "rgba32i",
]


def qualifier_prefix(qualifier: str) -> str:
    if qualifier.endswith("ui"):
        return "u"
    if qualifier.endswith("i"):
        return "i"
    return ""


def exact_main() -> None:
    out = [EXACT_HEADER]
    count = 0

    def case(key: str, programs: str, derived: str) -> str:
        return f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{programs}]
derived = {{ {derived} }}
"""

    for prefix_key, prefix in PREFIXES:
        for unnorm in (0, 1):
            tex_x = "inTexCoord.x" + (" * pushc.texWidth" if unnorm else "")
            tex_y = "inTexCoord.y" + (" * pushc.texHeight" if unnorm else "")
            lookup = "textureLod(texSampler, fragTexCoord, 0.0f)" if unnorm else "texture(texSampler, fragTexCoord)"
            derived = f"sampler_type = {py(prefix + 'sampler2D')}, color_type = {py(prefix + 'vec4')}, lookup = {py(lookup)}, tex_x = {py(tex_x)}, tex_y = {py(tex_y)}"
            out.append(case(f"exact_gfx_{prefix_key}_{unnorm}", '{ name = "vert", template = "pipeline/sampler/exact.vert", stage = "vert" }, { name = "frag", template = "pipeline/sampler/exact.frag", stage = "frag" }', derived))
            count += 1

    for qualifier in EXACT_QUALIFIERS:
        prefix = qualifier_prefix(qualifier)
        prefix_key = prefix or "f"
        for unnorm in (0, 1):
            derived = (
                f"sampler_type = {py(prefix + 'sampler2D')}, color_type = {py(prefix + 'vec4')}, image_type = {py(prefix + 'image2D')}, "
                f"format_qualifier = {py(', ' + qualifier)}, unnormalized = {py('true' if unnorm else 'false')}"
            )
            out.append(case(f"exact_cmp_{qualifier}_{unnorm}", '{ name = "comp", template = "pipeline/sampler/exact.comp", stage = "comp" }', derived))
            count += 1

    gfx_coords = "vec2(gl_FragCoord.x / pc.fbWidth, gl_FragCoord.y / pc.fbHeight)"
    cmp_coords = "vec2((vec2(gl_GlobalInvocationID.xy) + 0.5) / vec2(pc.fbWidth, pc.fbHeight))"
    for key, statement in (
        ("gfx_lod", f"textureLod(texSampler, {gfx_coords}, pc.lodLevel)"),
        ("gfx_bias", f"texture(texSampler, {gfx_coords}, pc.lodLevel)"),
        ("gfx_zero", f"textureLod(texSampler, {gfx_coords}, 0.0)"),
    ):
        out.append(
            case(
                f"lodbias_{key}",
                '{ name = "vert", template = "pipeline/sampler/lodbias.vert", stage = "vert" }, { name = "frag", template = "pipeline/sampler/lodbias.frag", stage = "frag" }',
                f"sample_statement = {py(statement)}",
            )
        )
        count += 1
    for key, statement in (
        ("cmp_lod", f"textureLod(texSampler, {cmp_coords}, pc.lodLevel)"),
        ("cmp_zero", f"textureLod(texSampler, {cmp_coords}, 0.0)"),
    ):
        out.append(case(f"lodbias_{key}", '{ name = "comp", template = "pipeline/sampler/lodbias.comp", stage = "comp" }', f"sample_statement = {py(statement)}"))
        count += 1

    EXACT_MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {EXACT_MANIFEST}")


if __name__ == "__main__":
    main()
    exact_main()


IMAGE_MANIFEST = MANIFEST.with_name("pipeline_image.toml")

IMAGE_HEADER = """# Shader manifest for dEQP-VK.pipeline.*.image
#
# @generated by hodow_cts/scripts/gen_pipeline_sampler_manifest.py - do not hand-edit.
#
# `ImageTest::initPrograms`, with the lookup scale and bias as a push constant instead of literals in the source. One entry per
# sampler type, view type, sampling type and image count; `ImageSamplingInstance` finds them through `image_program_key`.

upstream_source = "external/vulkancts/modules/vulkan/pipeline/vktPipelineImageTests.cpp"
rust_module = "pipeline/image_tests"
"""

IMAGE_COUNTS = [1, 4, 8]
TEXTURE_SUFFIX = {"sampler1D": "texture1D", "sampler1DArray": "texture1DArray", "sampler2D": "texture2D", "sampler2DArray": "texture2DArray", "sampler3D": "texture3D", "samplerCube": "textureCube", "samplerCubeArray": "textureCubeArray"}


def image_main() -> None:
    out = [IMAGE_HEADER]
    count = 0
    for prefix_key, prefix in PREFIXES:
        for view_key, sampler, swizzle in VIEWS:
            for sampling in ("combined", "separate"):
                for image_count in IMAGE_COUNTS:
                    sampler_name = f"texSamplers[{image_count}]" if image_count > 1 else "texSampler"
                    texture_name = f"texImages[{image_count}]" if image_count > 1 else "texImage"
                    sampler_i = "texSamplers[i]" if image_count > 1 else "texSampler"
                    texture_i = "texImages[i]" if image_count > 1 else "texImage"
                    if sampling == "separate":
                        decl = f"layout(set = 0, binding = 0) uniform highp sampler texSampler;\nlayout(set = 0, binding = 1) uniform highp {prefix}{TEXTURE_SUFFIX[sampler]} {texture_name};"
                        lookup = f"{prefix}{sampler}({texture_i}, texSampler)"
                        storage_binding, buffer_binding = 2, 3
                    else:
                        decl = f"layout(set = 0, binding = 0) uniform highp {prefix}{sampler} {sampler_name};"
                        lookup = sampler_i
                        storage_binding, buffer_binding = 1, 2
                    sample = f"(texture({lookup}, vtxTexCoords.{swizzle}) * pc.scale) + pc.bias"
                    if image_count > 1:
                        frag_body = f"    for (uint i = 0; i < {image_count}; ++i)\n        fragColors[i] = {sample};\n"
                        comp_body = f"    for (uint i = 0; i < {image_count}; ++i) {{\n        vec4 color = {sample};\n        imageStore(outImages[i], ivec2(gl_GlobalInvocationID.xy), color);\n    }}\n"
                        frag_color_decl = f"fragColors[{image_count}]"
                    else:
                        frag_body = f"    fragColor = {sample};\n"
                        comp_body = f"    vec4 color = {sample};\n    imageStore(outImages[0], ivec2(gl_GlobalInvocationID.xy), color);\n"
                        frag_color_decl = "fragColor"
                    key = f"{prefix_key}_{view_key}_{sampling}_{image_count}"
                    frag_derived = f"sampler_decl = {py(decl)}, frag_color_decl = {py(frag_color_decl)}, body = {py(frag_body)}"
                    comp_derived = f"sampler_decl = {py(decl)}, storage_binding = {py(str(storage_binding))}, buffer_binding = {py(str(buffer_binding))}, image_count = {py(str(image_count))}, body = {py(comp_body)}"
                    out.append(
                        f"""
[[case]]
name = "gfx_{key}"
rust_const = "GFX_{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "tex_vert", template = "pipeline/image/tex.vert", stage = "vert" }}, {{ name = "tex_frag", template = "pipeline/image/tex.frag", stage = "frag" }}]
derived = {{ {frag_derived} }}

[[case]]
name = "cmp_{key}"
rust_const = "CMP_{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "tex_comp", template = "pipeline/image/tex.comp", stage = "comp" }}]
derived = {{ {comp_derived} }}
"""
                    )
                    count += 2
    IMAGE_MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {IMAGE_MANIFEST}")


if __name__ == "__main__":
    image_main()
