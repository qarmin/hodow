#!/usr/bin/env python3
"""Writes the shader manifests and the case table of dEQP-VK.ssbo.{layout,readonly.layout,phys.layout,unsized_array_length}

ssbo_cases.py reproduces what SSBOLayoutCase::delayedInit builds (reference layout, reference data and the compute shader that embeds it) for every case upstream's
createTests registers. Cases whose programs are identical share one manifest entry; `src/vkt/tests/ssbo/ssbo_cases.rs` lists every case with its blocks and variable
entries, which is all `ssbo/mod.rs` needs to draw the same data again, upload it, run the shader and compare.

A pure text generator: no glslang and no cargo.
"""

import hashlib
import json
from pathlib import Path

import ssbo_cases as sc

CRATE = Path(__file__).resolve().parent.parent
MANIFEST = CRATE / "shaders" / "manifest" / "ssbo.toml"
LENGTH_MANIFEST = CRATE / "shaders" / "manifest" / "ssbo_unsized_array_length.toml"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "ssbo"
CASE_TABLE = CRATE / "src" / "vkt" / "tests" / "ssbo" / "ssbo_cases.rs"

HEADER = """# Shader manifest for dEQP-VK.ssbo.{what}
#
# @generated by hodow_cts/scripts/gen_ssbo_manifest.py - do not hand-edit.
#
# {how}

upstream_source = "external/vulkancts/modules/vulkan/ssbo/{source}"
rust_module = "{module}"
"""

REQUIREMENTS = [(sc.L_16BIT, "REQ_16BIT_STORAGE", 1 << 0), (sc.L_8BIT, "REQ_8BIT_STORAGE", 1 << 1), (sc.L_SCALAR, "REQ_SCALAR", 1 << 2), (sc.L_RELAXED, "REQ_RELAXED", 1 << 3),
                (sc.L_DESCRIPTOR_INDEXING, "REQ_DESCRIPTOR_INDEXING", 1 << 4)]
REQ_PHYS = 1 << 5

UNSIZED_ARRAY_LENGTH_CASES = [
    # elementSize, bufferSize, useMinBufferOffset, bufferBindLength (None is VK_WHOLE_SIZE), variablePointers, length64, name
    (4, 256, False, 256, False, False, "float_no_offset_explicit_size"),
    (4, 256, False, None, False, False, "float_no_offset_whole_size"),
    (4, 512, True, 32, False, False, "float_offset_explicit_size"),
    (4, 512, True, None, False, False, "float_offset_whole_size"),
    (4, 512, True, None, True, False, "float_offset_whole_size_varptr"),
    (4, 3 << 31, True, 3 << 31, False, False, "float_offset_explicit_size_64b"),
    (4, 3 << 31, True, 3 << 31, True, False, "float_offset_explicit_size_64b_varptr"),
    (4, 3 << 31, True, 3 << 31, False, True, "float_offset_explicit_size_64b_length64"),
    (4, 3 << 31, True, 3 << 31, True, True, "float_offset_explicit_size_64b_length64_varptr"),
    (4, 9 << 31, True, None, False, True, "float_offset_explicit_size_64b_length64_2"),
    (4, 9 << 31, True, None, True, True, "float_offset_explicit_size_64b_length64_2_varptr"),
]


def py(value) -> str:
    return json.dumps(repr(value))


def unsized_length_shader(variable_pointers: bool, length64: bool) -> str:
    size_type = "int64_t" if length64 else "int"
    method = "length64" if length64 else "length"
    return (
        "#version 450 core\n"
        "#extension GL_EXT_shader_explicit_arithmetic_types_int64 : enable\n"
        "#extension GL_EXT_shader_64bit_indexing : enable\n"
        + ("#pragma use_variable_pointers\n" if variable_pointers else "")
        + "layout(set=0, binding=0, std430) readonly buffer x {\n   int xs[];\n};\n"
        "layout(set=0, binding=1, std430) writeonly buffer y {\n   " + size_type + " observed_size;\n};\n"
        "layout(local_size_x=1) in;\nvoid main (void) {\n   observed_size = xs." + method + "();\n}\n"
    )


def var_row(entry: sc.VarEntry) -> str:
    dt = sc.TYPES[entry.type]
    num_vecs = (dt.rows if entry.row_major else dt.cols) if dt.is_matrix else 1
    return (f"v({sc.SCALAR_KIND[dt.scalar]}, {dt.size}, {num_vecs}, {entry.offset}, {entry.array_size}, {entry.array_stride}, {entry.top_size}, {entry.top_stride}, "
            f"{entry.matrix_stride}, {str(entry.row_major).lower()}, {str(entry.written).lower()})")


def main() -> None:
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    (TEMPLATE_DIR / "src_comp.glsl").write_text("${src_comp}")
    (TEMPLATE_DIR / "src_length.glsl").write_text("${src_length}")

    cases = sc.all_cases()
    by_signature: dict[str, str] = {}
    entries = []
    var_lists: dict[str, str] = {}
    var_statics: list[str] = []
    block_lists: dict[str, str] = {}
    block_statics: list[str] = []
    rows = []

    for case in cases:
        program = "None"
        if case.program is not None:
            if case.program not in by_signature:
                digest = hashlib.sha1(case.program.encode()).hexdigest()[:12]
                const = f"SB_{digest.upper()}"
                by_signature[case.program] = const
                entries.append(
                    f'\n[[case]]\nname = "sb_{digest}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\n'
                    f'programs = [{{ name = "compute", template = "ssbo/src_comp.glsl", stage = "comp" }}]\nderived = {{ src_comp = {py(case.program)} }}\n'
                )
            program = f"Some(&{by_signature[case.program]})"

        block_rows = []
        if case.layout is not None:
            for block_ndx, block in enumerate(case.layout.blocks):
                var_rows = ", ".join(var_row(case.layout.vars[i]) for i in block.active)
                if var_rows not in var_lists:
                    name = f"VARS_{len(var_lists)}"
                    var_lists[var_rows] = name
                    var_statics.append(f"const {name}: &[VarDef] = &[{var_rows}];")
                block_rows.append(f"BlockDef {{ binding: {block.decl_ndx + 1}, instance: {block.instance_ndx}, size: {case.sizes[block_ndx]}, last_unsized: {case.unsized_sizes[block_ndx]}, vars: {var_lists[var_rows]} }}")
        block_signature = ", ".join(block_rows)
        if block_signature not in block_lists:
            name = f"BLOCKS_{len(block_lists)}"
            block_lists[block_signature] = name
            block_statics.append(f"const {name}: &[BlockDef] = &[{block_signature}];")

        requirements = 0
        for flag, _, bit in REQUIREMENTS:
            if case.layout is not None and case.uses(flag):
                requirements |= bit
        if case.phys:
            requirements |= REQ_PHYS
        num_blocks = sum(b.array_size if b.is_array else 1 for b in case.interface.blocks)
        rows.append(
            f'    SsboCaseDef {{ name: "{".".join(case.path)}", per_block_buffer: {str(case.buffer_mode == sc.BUFFERMODE_PER_BLOCK).lower()}, big: {str(case.big).lower()}, '
            f'requirements: {requirements}, num_blocks: {num_blocks}, blocks: {block_lists[block_signature]}, programs: {program} }},'
        )

    MANIFEST.write_text(
        HEADER.format(what="{layout,readonly.layout,phys.layout}", how="`SSBOLayoutCase::delayedInit`, one entry per distinct compute shader.", source="vktSSBOLayoutCase.cpp", module="ssbo")
        + "".join(entries)
    )

    length_entries = []
    shaders: dict[tuple, str] = {}
    for _, _, _, _, varptr, length64, _ in UNSIZED_ARRAY_LENGTH_CASES:
        key = (varptr, length64)
        if key in shaders:
            continue
        const = "SBL_" + ("VARPTR_" if varptr else "") + ("LEN64" if length64 else "LEN32")
        shaders[key] = const
        version = "spirv1.3" if varptr else "spirv1.0"
        length_entries.append(
            f'\n[[case]]\nname = "{const.lower()}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\n'
            f'programs = [{{ name = "comp", template = "ssbo/src_length.glsl", stage = "comp", spirv_version = "{version}" }}]\nderived = {{ src_length = {py(unsized_length_shader(varptr, length64))} }}\n'
        )
    LENGTH_MANIFEST.write_text(
        HEADER.format(what="unsized_array_length", how="`createUnsizedArrayLengthProgs`, one entry per (variablePointers, length64).", source="vktSSBOLayoutTests.cpp", module="ssbo")
        + "".join(length_entries)
    )

    length_rows = []
    for element_size, buffer_size, use_min_offset, bind_length, varptr, length64, name in UNSIZED_ARRAY_LENGTH_CASES:
        bind = "u64::MAX" if bind_length is None else str(bind_length)
        length_rows.append(
            f'    UnsizedArrayLengthDef {{ name: "{name}", element_size: {element_size}, buffer_size: {buffer_size}, use_min_buffer_offset: {str(use_min_offset).lower()}, '
            f'buffer_bind_length: {bind}, variable_pointers: {str(varptr).lower()}, length64: {str(length64).lower()}, programs: &{shaders[(varptr, length64)]} }},'
        )

    lines = [
        "// @generated by hodow_cts/scripts/gen_ssbo_manifest.py - do not hand-edit.",
        "//",
        "// Every case of dEQP-VK.ssbo.{layout,readonly.layout,phys.layout} in upstream's order: its blocks and variable entries as the reference layout computes them, and the program of the manifest it uses.",
        "",
        "use crate::generated::shaders::ssbo::*;",
        "use crate::generated::shaders::ssbo_unsized_array_length::*;",
        "use crate::vkt::tests::ssbo::{BlockDef, SsboCaseDef, UnsizedArrayLengthDef, VarDef, v};",
        "",
    ]
    for _, name, bit in REQUIREMENTS:
        lines.append(f"pub const {name}: u32 = {bit};")
    lines.append(f"pub const REQ_PHYS: u32 = {REQ_PHYS};")
    lines.append("")
    lines += var_statics + [""] + block_statics + ["", "pub static SSBO_CASES: &[SsboCaseDef] = &["] + rows + ["];", "", "pub static UNSIZED_ARRAY_LENGTH_CASES: &[UnsizedArrayLengthDef] = &["] + length_rows + ["];"]
    CASE_TABLE.parent.mkdir(parents=True, exist_ok=True)
    CASE_TABLE.write_text("\n".join(lines) + "\n")
    print(f"{len(cases)} cases, {len(entries)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
