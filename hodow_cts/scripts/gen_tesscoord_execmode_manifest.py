#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.tessellation.tesscoord.*_execution_mode_in_tesc.

Upstream's `TessCoordTest::initPrograms` builds these from SPIR-V assembly: the tessellation control shader carries the primitive type, the
vertex spacing, the point mode and the vertex order as execution modes and the evaluation shader declares none. Only the control shader
depends on the case, through `execution_modes`, so there is one manifest entry per primitive type and spacing mode.

A pure text generator: no spirv-as and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "tessellation_tesscoord_execmode.toml"

HEADER = """# Shader manifest for dEQP-VK.tessellation.tesscoord.*_execution_mode_in_tesc
#
# @generated by hodow_cts/scripts/gen_tesscoord_execmode_manifest.py - do not hand-edit.
#
# `TessCoordTest::initPrograms` with the execution modes in the control shader, which upstream writes as SPIR-V assembly. The evaluation shader is
# registered twice (`tese` and `tese_point_size`) from the same source, as upstream does.

upstream_source = "external/vulkancts/modules/vulkan/tessellation/vktTessellationCoordinatesTests.cpp"
rust_module = "tessellation/coordinates_tests"
"""

PRIMITIVES = [("triangles", "Triangles"), ("quads", "Quads"), ("isolines", "Isolines")]
SPACINGS = [("equal_spacing", "SpacingEqual"), ("fractional_odd_spacing", "SpacingFractionalOdd"), ("fractional_even_spacing", "SpacingFractionalEven")]


def entry(prim, prim_mode, spacing, spacing_mode):
    name = f"{prim}_{spacing}_execution_mode_in_tesc"
    modes = f"OpExecutionMode %main_fun {prim_mode}\nOpExecutionMode %main_fun {spacing_mode}\nOpExecutionMode %main_fun PointMode\nOpExecutionMode %main_fun VertexOrderCcw\n"
    modes_toml = repr(modes).replace("\\", "\\\\")
    t = "tessellation/tesscoord_execmode"
    return f"""
[[case]]
name = "{name}"
rust_const = "TESSCOORD_{name.upper()}"
rust_type = "SharedProgram"
programs = [
    {{ name = "vert", template = "{t}.vert.spvasm", stage = "asm" }},
    {{ name = "tesc", template = "{t}.tesc.spvasm", stage = "asm" }},
    {{ name = "tese", template = "{t}.tese.spvasm", stage = "asm" }},
    {{ name = "tese_point_size", template = "{t}.tese.spvasm", stage = "asm" }},
]
derived = {{ execution_modes = "{modes_toml}" }}
"""


def main():
    out = [HEADER]
    for prim, prim_mode in PRIMITIVES:
        for spacing, spacing_mode in SPACINGS:
            out.append(entry(prim, prim_mode, spacing, spacing_mode))
    MANIFEST.write_text("".join(out))
    print(f"wrote {MANIFEST} with {len(PRIMITIVES) * len(SPACINGS)} entries")


if __name__ == "__main__":
    main()
