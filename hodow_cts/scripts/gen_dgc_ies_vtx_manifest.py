#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.graphics.misc.ies_increase_vtx_bindings_* (IESInputBindingsCase::initPrograms of
vktDGCGraphicsMiscTestsExt.cpp). A pure text generator."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_ies_vtx.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

OUT_COLOR_ASSIGNMENTS = [
    "    outColor = vec4(0.0, 0.0, 0.0, 1.0);\n",
    "    outColor = vec4(inRed, 0.0, 0.0, 1.0);\n",
    "    outColor = vec4(inRed, inGreen, 0.0, 1.0);\n",
    "    outColor = vec4(inRed, inGreen, inBlue, 1.0);\n",
]

FRAG = (
    "#version 460\n"
    "layout (location=0) in vec4 inColor;\n"
    "layout (location=0) out vec4 outColor;\n"
    "\n"
    "void main (void)\n"
    "{\n"
    "    outColor = inColor;\n"
    "}\n"
)


def vert(color_locations, i):
    return (
        "#version 460\n"
        "layout (location=0) in vec4 inPos;\n"
        f"layout (location={color_locations[0]}) in float inRed;\n"
        f"layout (location={color_locations[1]}) in float inGreen;\n"
        f"layout (location={color_locations[2]}) in float inBlue;\n"
        "\n"
        "layout (location=0) out vec4 outColor;\n"
        "\n"
        "layout (push_constant, std430) uniform PCBlock { vec4 offset; } pc;\n"
        "\n"
        "void main (void)\n"
        "{\n"
        "    gl_Position = inPos + pc.offset;\n"
        + OUT_COLOR_ASSIGNMENTS[i]
        + "}\n"
    )


FILES = {"ies_vtx_frag.frag": FRAG}
CASES = []
for suffix, locations in (("normal", [1, 2, 3]), ("reversed", [3, 2, 1])):
    programs = []
    for i in range(4):
        name = f"ies_vtx_{suffix}_vert{i}.vert"
        FILES[name] = vert(locations, i)
        programs.append(f'{{ name = "vert{i}", template = "dgc/{name}", stage = "vert" }}')
    programs.append('{ name = "frag", template = "dgc/ies_vtx_frag.frag", stage = "frag" }')
    CASES.append(
        f'\n[[case]]\nname = "ies_vtx_{suffix}"\nrust_const = "IES_VTX_{suffix.upper()}"\nrust_type = "SharedProgram"\n'
        f'programs = [ {", ".join(programs)} ]\n'
    )

HEADER = """# Shader manifest for dEQP-VK.dgc.ext.graphics.misc.ies_increase_vtx_bindings_*
#
# @generated by hodow_cts/scripts/gen_dgc_ies_vtx_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCGraphicsMiscTestsExt.cpp"
rust_module = "dgc/graphics_misc_ies_vtx_tests"
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in FILES.items():
        (SRC_DIR / name).write_text(text)
    MANIFEST.write_text(HEADER + "".join(CASES))
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
