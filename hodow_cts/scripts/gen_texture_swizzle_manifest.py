#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.texture.swizzle

vktTextureTestUtil.cpp's `initializePrograms` builds a vertex, a fragment and a compute shader per `Program` from three templates; the swizzle, filtering and shadow tests only ever use the 2D programs below, each with and without a texture coordinate swizzle. Every combination is one manifest entry named `TSW_<program>_<swizzle or NONE>`.

A pure text generator: no glslang and no cargo.
"""

import json
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
MANIFEST = CRATE / "shaders" / "manifest" / "texture_swizzle.toml"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "texture_swizzle"

HEADER = """# Shader manifest for dEQP-VK.texture.swizzle
#
# @generated by hodow_cts/scripts/gen_texture_swizzle_manifest.py - do not hand-edit.
#
# `texture::util::initializePrograms`, one entry per (program, texture coordinate swizzle), plus the `unnormal` variants (`textureLod(.., 0)` lookups).

upstream_source = "external/vulkancts/modules/vulkan/texture/vktTextureTestUtil.cpp"
rust_module = "texture/swizzle_tests"
"""

VERT = (
    "#version 450\n"
    "layout(location = 0) in highp vec4 a_position;\n"
    "layout(location = 1) in highp {tctype} a_texCoord;\n"
    "layout(location = 0) out highp {tctype} v_texCoord;\n"
    "out gl_PerVertex { vec4 gl_Position; };\n"
    "\n"
    "void main (void)\n"
    "{\n"
    "    gl_Position = a_position;\n"
    "    v_texCoord = a_texCoord;\n"
    "}\n"
)

FRAG = (
    "#version 450\n"
    "layout(location = 0) in highp {tctype} v_texCoord;\n"
    "layout(location = 0) out {fragprec} vec4 dEQP_FragColor;\n"
    "layout (set=0, binding=0, std140) uniform Block \n"
    "{\n"
    "  highp float u_bias;\n"
    "  highp float u_ref;\n"
    "  highp vec4 u_colorScale;\n"
    "  highp vec4 u_colorBias;\n"
    "};\n\n"
    "layout (set=1, binding=0) uniform highp {sampler} u_sampler;\n"
    "void main (void)\n"
    "{\n"
    "  highp {tctype} texCoord = v_texCoord{swz};\n"
    "  dEQP_FragColor = {lookup} * u_colorScale + u_colorBias;\n"
    "}\n"
)

COMP = (
    "#version 450\n"
    "layout (local_size_x = 16, local_size_y = 16, local_size_z = 1) in;\n"
    "layout (set=0, binding=0, std140) uniform Block \n"
    "{\n"
    "  highp float u_bias;\n"
    "  highp float u_ref;\n"
    "  highp vec2  u_viewSize;\n"
    "  highp vec4  u_colorScale;\n"
    "  highp vec4  u_colorBias;\n"
    "  int u_lod;\n"
    "};\n\n"
    "layout(push_constant) uniform PushConstants {\n"
    "  ivec2 u_offset;\n"
    "} pc;\n\n"
    "layout (set=0, binding=1) uniform highp {sampler} u_sampler;\n"
    "layout (set=0, binding=2, {imgfmt}) uniform writeonly image2D u_outputImage;\n"
    "layout (set=0, binding=3, std430) readonly buffer Geometry \n"
    "{\n"
    "  vec4 u_texCoords[4];\n"
    "  vec4 u_positions[4];\n"
    "};\n"
    "\n"
    "highp {tctype} interpolate(vec2 p, ivec2 size)\n"
    "{\n"
    "  vec2 uv = (p + 0.5) / vec2(size);\n"
    "\n"
    "  float w0 = u_positions[0].w; float w1 = u_positions[1].w;\n"
    "  float w2 = u_positions[2].w; float w3 = u_positions[3].w;\n"
    "\n"
    "  float b0, b1, b2, b3;\n"
    "  if (uv.x + uv.y <= 1.0)\n"
    "  {\n"
    "    b0 = 1.0 - uv.x - uv.y;\n"
    "    b1 = uv.y;\n"
    "    b2 = uv.x;\n"
    "    b3 = 0.0;\n"
    "  }\n"
    "  else\n"
    "  {\n"
    "    b0 = 0.0;\n"
    "    b1 = 1.0 - uv.x;\n"
    "    b2 = 1.0 - uv.y;\n"
    "    b3 = uv.x + uv.y - 1.0;\n"
    "  }\n"
    "\n"
    "  {tctype} tc = \n"
    "      {tctype}(u_texCoords[0]) * (b0 / w0) +\n"
    "      {tctype}(u_texCoords[1]) * (b1 / w1) +\n"
    "      {tctype}(u_texCoords[2]) * (b2 / w2) +\n"
    "      {tctype}(u_texCoords[3]) * (b3 / w3);\n"
    "\n"
    "  float invW = \n"
    "      (b0 / w0) + (b1 / w1) + (b2 / w2) + (b3 / w3);\n"
    "\n"
    "  return {tctype}(tc / invW);\n"
    "}\n"
    "\n"
    "void main (void)\n"
    "{\n"
    "  ivec2 coord = ivec2(gl_GlobalInvocationID.xy);\n"
    "  ivec2 size  = ivec2(u_viewSize);\n"
    "  if (coord.x >= size.x || coord.y >= size.y)\n"
    "    return;\n"
    "\n"
    "  highp {tctype} texCoord = interpolate(vec2(coord), size){swz};\n"
    "  highp {tctype} texCoordX = interpolate(vec2(coord) + vec2(1.0, 0.0), size){swz};\n"
    "  highp {tctype} texCoordY = interpolate(vec2(coord) + vec2(0.0, 1.0), size){swz};\n"
    "  highp {tctype} dPdx      = texCoordX - texCoord;\n"
    "  highp {tctype} dPdy      = texCoordY - texCoord;\n"
    "\n"
    "  vec4 result = {lookup} * u_colorScale + u_colorBias;\n"
    "  imageStore(u_outputImage, coord + pc.u_offset, result);\n"
    "}\n"
)

def tctype(program: str) -> str:
    return "vec3" if program.startswith(("3D", "2D_ARRAY", "CUBE")) else "vec2"


DERIV = "max(length(dPdx * vec2(textureSize(u_sampler, 0))), length(dPdy * vec2(textureSize(u_sampler, 0))))"

PROGRAMS = {
    "2D_FLOAT": ("sampler2D", "texture(u_sampler, texCoord)", "textureGrad(u_sampler, texCoord, dPdx, dPdy)"),
    "2D_FLOAT_BIAS": ("sampler2D", "texture(u_sampler, texCoord, u_bias)", f"textureLod(u_sampler, texCoord, log2({DERIV}) + u_bias)"),
    "2D_INT": ("isampler2D", "vec4(texture(u_sampler, texCoord))", "vec4(texture(u_sampler, texCoord))"),
    "2D_UINT": ("usampler2D", "vec4(texture(u_sampler, texCoord))", "vec4(texture(u_sampler, texCoord))"),
    "2D_SHADOW": ("sampler2DShadow", "vec4(texture(u_sampler, vec3(texCoord, u_ref)), 0.0, 0.0, 1.0)", "vec4(textureGrad(u_sampler, vec3(texCoord, u_ref), dPdx, dPdy), 0.0, 0.0, 1.0)"),
    "3D_FLOAT": ("sampler3D", "texture(u_sampler, texCoord)", "textureGrad(u_sampler, texCoord, dPdx, dPdy)"),
    "3D_FLOAT_BIAS": ("sampler3D", "texture(u_sampler, texCoord, u_bias)", "textureLod(u_sampler, texCoord, log2(max(length(dPdx * vec3(textureSize(u_sampler, 0))), length(dPdy * vec3(textureSize(u_sampler, 0))))) + u_bias)"),
    "3D_UINT": ("usampler3D", "vec4(texture(u_sampler, texCoord))", "vec4(texture(u_sampler, texCoord))"),
    "2D_ARRAY_FLOAT": ("sampler2DArray", "texture(u_sampler, texCoord)", "textureGrad(u_sampler, texCoord, dPdx.xy, dPdy.xy)"),
    "2D_ARRAY_UINT": ("usampler2DArray", "vec4(texture(u_sampler, texCoord))", "vec4(texture(u_sampler, texCoord))"),
    "CUBE_FLOAT": ("samplerCube", "texture(u_sampler, texCoord)", "textureGrad(u_sampler, texCoord, dPdx, dPdy)"),
    "CUBE_FLOAT_BIAS": ("samplerCube", "texture(u_sampler, texCoord, u_bias)", "textureLod(u_sampler, texCoord, log2(max(length(dPdx), length(dPdy)) * float(textureSize(u_sampler, 0).x)) + u_bias)"),
    "CUBE_UINT": ("usamplerCube", "vec4(texture(u_sampler, texCoord))", "vec4(texture(u_sampler, texCoord))"),
    "2D_ARRAY_SHADOW": ("sampler2DArrayShadow", "vec4(texture(u_sampler, vec4(texCoord, u_ref)), 0.0, 0.0, 1.0)", "vec4(textureGrad(u_sampler, vec4(texCoord, u_ref), dPdx.xy, dPdy.xy), 0.0, 0.0, 1.0)"),
    "CUBE_SHADOW": ("samplerCubeShadow", "vec4(texture(u_sampler, vec4(texCoord, u_ref)), 0.0, 0.0, 1.0)", "vec4(textureGrad(u_sampler, vec4(texCoord, u_ref), dPdx, dPdy), 0.0, 0.0, 1.0)"),
    "2D_INT_BIAS": ("isampler2D", "vec4(texture(u_sampler, texCoord, u_bias))", "vec4(textureGrad(u_sampler, texCoord, dPdx * exp2(u_bias), dPdy * exp2(u_bias)))"),
}
SWIZZLES = [None, "yx", "xx", "yy"]
UNNORMAL_PROGRAMS = {
    "2D_FLOAT": ("sampler2D", "textureLod(u_sampler, texCoord, 0)"),
    "2D_UINT": ("usampler2D", "vec4(textureLod(u_sampler, texCoord, 0))"),
}


def py(value) -> str:
    return json.dumps(repr(value))


def main() -> None:
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    for name in ("vert", "frag", "comp"):
        (TEMPLATE_DIR / f"src_{name}.glsl").write_text("${src_" + name + "}")
    entries = []
    for program, (sampler, lookup_frag, lookup_comp) in PROGRAMS.items():
        for swizzle in SWIZZLES:
            if swizzle is not None and tctype(program) != "vec2":
                continue
            swz = "" if swizzle is None else "." + swizzle
            const = f"TSW_{program}_{(swizzle or 'none').upper()}"
            sources = {
                "src_vert": VERT.replace("{tctype}", tctype(program)),
                "src_frag": FRAG.replace("{fragprec}", "mediump").replace("{tctype}", tctype(program)).replace("{sampler}", sampler).replace("{swz}", swz).replace("{lookup}", lookup_frag),
                "src_comp": COMP.replace("{imgfmt}", "rgba8").replace("{tctype}", tctype(program)).replace("{sampler}", sampler).replace("{swz}", swz).replace("{lookup}", lookup_comp),
            }
            programs = ", ".join(
                f'{{ name = "{stage}_{program}", template = "texture_swizzle/{key}.glsl", stage = "{short}" }}'
                for stage, key, short in (("vertex", "src_vert", "vert"), ("fragment", "src_frag", "frag"), ("compute", "src_comp", "comp"))
            )
            derived = ", ".join(f"{key} = {py(src)}" for key, src in sources.items())
            entries.append(f'\n[[case]]\nname = "{const.lower()}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\nprograms = [{programs}]\nderived = {{ {derived} }}\n')
    for program, (sampler, lookup) in UNNORMAL_PROGRAMS.items():
        const = f"TSW_{program}_UNNORMAL"
        sources = {
            "src_vert": VERT.replace("{tctype}", tctype(program)),
            "src_frag": FRAG.replace("{fragprec}", "mediump").replace("{tctype}", tctype(program)).replace("{sampler}", sampler).replace("{swz}", "").replace("{lookup}", lookup),
            "src_comp": COMP.replace("{imgfmt}", "rgba8").replace("{tctype}", tctype(program)).replace("{sampler}", sampler).replace("{swz}", "").replace("{lookup}", lookup),
        }
        programs = ", ".join(
            f'{{ name = "{stage}_{program}", template = "texture_swizzle/{key}.glsl", stage = "{short}" }}'
            for stage, key, short in (("vertex", "src_vert", "vert"), ("fragment", "src_frag", "frag"), ("compute", "src_comp", "comp"))
        )
        derived = ", ".join(f"{key} = {py(src)}" for key, src in sources.items())
        entries.append(f'\n[[case]]\nname = "{const.lower()}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\nprograms = [{programs}]\nderived = {{ {derived} }}\n')
    # Float render target (highp output, rgba32f storage image): the 2D float program
    entries.append(
        '\n[[case]]\nname = "tsw_2d_float_rgba32f"\nrust_const = "TSW_2D_FLOAT_RGBA32F"\nrust_type = "SharedProgram"\n'
        'programs = [{ name = "vertex_2D_FLOAT", template = "texture_swizzle/src_vert.glsl", stage = "vert" }, { name = "fragment_2D_FLOAT", template = "texture_swizzle/src_frag.glsl", stage = "frag" }, '
        '{ name = "compute_2D_FLOAT", template = "texture_swizzle/src_comp.glsl", stage = "comp" }]\n'
        f'derived = {{ src_vert = {py(VERT.replace("{tctype}", "vec2"))}, '
        f'src_frag = {py(FRAG.replace("{fragprec}", "highp").replace("{tctype}", "vec2").replace("{sampler}", "sampler2D").replace("{swz}", "").replace("{lookup}", "texture(u_sampler, texCoord)"))}, '
        f'src_comp = {py(COMP.replace("{imgfmt}", "rgba32f").replace("{tctype}", "vec2").replace("{sampler}", "sampler2D").replace("{swz}", "").replace("{lookup}", "textureGrad(u_sampler, texCoord, dPdx, dPdy)"))} }}\n'
    )
    snorm_vert = "#version 430\nlayout(location = 0) in vec4 position;\nvoid main()\n{\n    gl_Position = position;\n}\n"
    for count in (1, 2, 3, 4):
        const = f"TSW_SNORM_CLAMP_{count}"
        frag = (
            "#version 430\nlayout(location = 0) out vec4 frag_out;\nuniform layout(set=0, binding=0) sampler1D tex_sampler;\nvoid main()\n{\n"
            "    vec4 color = texture(tex_sampler, 0.0);\n"
            f"    for (int i = 0; i < {count}; i++)\n    {{\n        if (color[i] != -1.0)\n        {{\n            frag_out = vec4(1, 0, 0, 1);\n            return;\n        }}\n    }}\n\n"
            "    frag_out = vec4(0, 1, 0, 1);\n}\n"
        )
        programs = '{ name = "vert", template = "texture_swizzle/src_vert.glsl", stage = "vert" }, { name = "frag", template = "texture_swizzle/src_frag.glsl", stage = "frag" }'
        entries.append(f'\n[[case]]\nname = "{const.lower()}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\nprograms = [{programs}]\nderived = {{ src_vert = {py(snorm_vert)}, src_frag = {py(frag)} }}\n')
    MANIFEST.write_text(HEADER + "".join(entries))
    print(f"{len(entries)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
