#!/usr/bin/env python3
"""Extracts the shader bodies of GPUShaderFP64Test4 (gpu_shader_fp64.fp64.state_query) and the vertex shader of GPUShaderFP64Test1 (gpu_shader_fp64.fp64.errors) from gl4cGPUShaderFP64Tests.cpp into src/khr_gl/gpu_shader_fp64/state_query_shaders.rs and errors_shaders.rs. Usage: gen_khr_fp64_state_query_shaders.py <gl4cGPUShaderFP64Tests.cpp>"""
import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1]).read_text()
crate_dir = pathlib.Path(__file__).resolve().parent.parent


def extract(body, name):
    match = re.search(r"const char \*" + name + r"\s*=((?:\s*\"(?:[^\"\\]|\\.)*\"\s*)+);", body)
    literals = re.findall(r"\"((?:[^\"\\]|\\.)*)\"", match.group(1))
    return "".join(literals)


def header(function):
    return [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        f"//   external/openglcts/modules/gl/gl4cGPUShaderFP64Tests.cpp ({function})",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2015-2016 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Modifications: generated by scripts/gen_khr_fp64_state_query_shaders.py; the shader bodies are extracted from the upstream source, not retyped.",
        "",
    ]


state_start = source.index("void GPUShaderFP64Test4::initProgramObjects()")
state_end = source.index("void GPUShaderFP64Test4::initTest()")
state_body = source[state_start:state_end]
out = header("GPUShaderFP64Test4::initProgramObjects")
for name in ["cs", "vs", "tc", "te", "gs", "fs"]:
    out.append(f'pub(super) const {name.upper()}_BODY: &str = "{extract(state_body, name + "_body")}";')
    out.append("")
(crate_dir / "src/khr_gl/gpu_shader_fp64/state_query_shaders.rs").write_text("\n".join(out))

errors_start = source.index("void GPUShaderFP64Test1::initTest()")
errors_end = source.index("bool GPUShaderFP64Test1::isMatrixUniform(")
out = header("GPUShaderFP64Test1::initTest")
out.append(f'pub(super) const VS_BODY: &str = "{extract(source[errors_start:errors_end], "vs_body")}";')
out.append("")
(crate_dir / "src/khr_gl/gpu_shader_fp64/errors_shaders.rs").write_text("\n".join(out))
