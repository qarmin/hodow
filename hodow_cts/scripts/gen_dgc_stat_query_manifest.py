#!/usr/bin/env python3
"""Writes the compute shaders and the manifest of dEQP-VK.dgc.ext.stat_query.comp_inv_*. A pure text generator."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_stat_query.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

COMP = """#version 460
layout (local_size_x=64) in;
layout (push_constant, std430) uniform PCBlock { uint wgOffset; } pc;
layout (set=0, binding=0, std430) buffer BufferBlock {
    uint values[];
} ssbo;
void main(void) {
    uint global_id = (gl_WorkGroupID.x + pc.wgOffset) * gl_WorkGroupSize.x + gl_LocalInvocationIndex;
    ssbo.values[global_id] = %du;
}
"""


VERT = """#version 460
layout (location=0) in vec4 inPos;
layout (location=0) out vec4 outColor;
out gl_PerVertex {
    vec4 gl_Position;
    float gl_PointSize;
};
void main(void) {
    gl_Position = inPos;
    gl_PointSize = 1.0;
    outColor = vec4(%d.0, 0.0, 1.0, 1.0);
}
"""

FRAG = """#version 460
layout (location=0) in vec4 inColor;
layout (location=0) out vec4 outColor;
void main(void) {
    outColor = inColor%s;
}
"""


TESC = """#version 460
#extension GL_EXT_tessellation_shader : require
layout (vertices=3) out;
layout (location=0) in vec4 inColor[];
layout (location=0) out vec4 outColor[];
in gl_PerVertex
{
    vec4 gl_Position;
    float gl_PointSize;
} gl_in[gl_MaxPatchVertices];
out gl_PerVertex
{
    vec4 gl_Position;
    float gl_PointSize;
} gl_out[];
void main(void) {
    gl_out[gl_InvocationID].gl_Position = gl_in[gl_InvocationID].gl_Position;
    gl_out[gl_InvocationID].gl_PointSize = gl_in[gl_InvocationID].gl_PointSize;
    gl_TessLevelOuter[0] = 1.0;
    gl_TessLevelOuter[1] = 1.0;
    gl_TessLevelOuter[2] = 1.0;
    gl_TessLevelOuter[3] = 1.0;
    gl_TessLevelInner[0] = 1.0;
    gl_TessLevelInner[1] = 1.0;
%s
}
"""

TESE = """#version 460
#extension GL_EXT_tessellation_shader : require
layout (triangles) in;
in gl_PerVertex {
    vec4 gl_Position;
    float gl_PointSize;
} gl_in[gl_MaxPatchVertices];
out gl_PerVertex {
    vec4 gl_Position;
    float gl_PointSize;
};
layout (location=0) in vec4 inColor[];
layout (location=0) out vec4 outColor;
void main(void) {
    gl_Position = (gl_in[0].gl_Position * gl_TessCoord.x +
                   gl_in[1].gl_Position * gl_TessCoord.y +
                   gl_in[2].gl_Position * gl_TessCoord.z);
    gl_PointSize = gl_in[0].gl_PointSize;
%s
}
"""

GEOM = """#version 460
layout (triangles) in;
layout (triangle_strip, max_vertices=3) out;
in gl_PerVertex {
    vec4 gl_Position;
    float gl_PointSize;
} gl_in[3];
out gl_PerVertex {
    vec4 gl_Position;
    float gl_PointSize;
};
layout (location=0) in vec4 inColor[];
layout (location=0) out vec4 outColor;
void main() {
    for (uint i = 0; i < 3; ++i) {
        gl_Position = gl_in[i].gl_Position;
        gl_PointSize = gl_in[i].gl_PointSize;
%s
        EmitVertex();
    }
}
"""


def main():
    gfx_programs = []
    for i in range(2):
        tesc_body = (
            "    outColor[gl_InvocationID] = vec4(inColor[gl_InvocationID].r, 1.0, inColor[gl_InvocationID].ba);"
            if i > 0
            else "    outColor[gl_InvocationID] = inColor[gl_InvocationID];"
        )
        tese_body = (
            "    outColor = vec4(1.0 - inColor[0].r, 1.0 - inColor[0].g, 1.0 - inColor[0].b, inColor[0].a);"
            if i > 0
            else "    outColor = inColor[0];"
        )
        geom_body = "        outColor = inColor[i].gbra;" if i > 0 else "        outColor = inColor[i];"
        (SRC_DIR / f"stat_query_tesc{i}.tesc").write_text(TESC % tesc_body)
        (SRC_DIR / f"stat_query_tese{i}.tese").write_text(TESE % tese_body)
        (SRC_DIR / f"stat_query_geom{i}.geom").write_text(GEOM % geom_body)
        for stage in ("tesc", "tese", "geom"):
            gfx_programs.append(f'{{ name = "{stage}{i}", template = "dgc/stat_query_{stage}{i}.{stage}", stage = "{stage}" }}')
    for i in range(2):
        (SRC_DIR / f"stat_query_vert{i}.vert").write_text(VERT % i)
        (SRC_DIR / f"stat_query_frag{i}.frag").write_text(FRAG % (".gbra" if i > 0 else ""))
        gfx_programs.append(f'{{ name = "vert{i}", template = "dgc/stat_query_vert{i}.vert", stage = "vert" }}')
        gfx_programs.append(f'{{ name = "frag{i}", template = "dgc/stat_query_frag{i}.frag", stage = "frag" }}')
    programs = []
    for i in range(2):
        (SRC_DIR / f"stat_query_comp{i}.comp").write_text(COMP % (i + 1))
        programs.append(f'{{ name = "comp{i}", template = "dgc/stat_query_comp{i}.comp", stage = "comp" }}')
    MANIFEST.write_text(
        f"""# Shader manifest for dEQP-VK.dgc.ext.stat_query (compute cases)
#
# @generated by hodow_cts/scripts/gen_dgc_stat_query_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCStatQueryTestsExt.cpp"
rust_module = "dgc/stat_query_tests"

[[case]]
name = "stat_query_comp"
rust_const = "STAT_QUERY_COMP"
rust_type = "SharedProgram"
programs = [ {", ".join(programs)} ]

[[case]]
name = "stat_query_vert_frag"
rust_const = "STAT_QUERY_VERT_FRAG"
rust_type = "SharedProgram"
programs = [ {", ".join(gfx_programs)} ]
"""
    )
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
