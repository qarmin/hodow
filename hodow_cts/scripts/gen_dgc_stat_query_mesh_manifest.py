#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.stat_query.task_mesh_inv_* (the task, mesh and fragment parts of `initPrograms` of
vktDGCStatQueryTestsExt.cpp): one shared program set without and one with an execution set (two task and two mesh variants). A pure text
generator: no glslang, no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_stat_query_mesh.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"
SPV = ', spirv_version = "spirv1.4"'

FRAG = (
    "#version 460\n"
    "layout (location=0) in vec4 inColor;\n"
    "layout (location=0) out vec4 outColor;\n"
    "void main(void) {\n"
    "    outColor = inColor;\n"
    "}\n"
)


def task(i):
    return (
        "#version 460\n"
        "#extension GL_EXT_mesh_shader : enable\n"
        "layout (local_size_x=32) in;\n"
        "layout (push_constant, std430) uniform PCBlock { uint rowOffset; } pc;\n"
        "struct TaskPayload {\n"
        "    vec4 color;\n"
        "    uint row;\n"
        "};\n"
        "taskPayloadSharedEXT TaskPayload payload;\n"
        "void main(void) {\n"
        f"    payload.color = vec4({i}.0, 0.0, 1.0, 1.0);\n"
        "    payload.row = gl_WorkGroupID.x + pc.rowOffset;\n"
        "    EmitMeshTasksEXT(8u, 1u, 1u);\n"
        "}\n"
    )


def mesh(i):
    force_green = i > 0
    color = (
        "        outColor[gl_LocalInvocationIndex] = vec4(payload.color.r, 1.0, payload.color.ba);\n"
        if force_green
        else "        outColor[gl_LocalInvocationIndex] = payload.color;\n"
    )
    return (
        "#version 460\n"
        "#extension GL_EXT_mesh_shader : enable\n"
        "layout (local_size_x=64) in;\n"
        "struct TaskPayload {\n"
        "    vec4 color;\n"
        "    uint row;\n"
        "};\n"
        "taskPayloadSharedEXT TaskPayload payload;\n"
        "layout (triangles) out;\n"
        "layout (max_vertices=3, max_primitives=1) out;\n"
        "layout (set=0, binding=0, std430) readonly buffer PositionsBlock {\n"
        "    vec4 positions[];\n"
        "} ssbo;\n"
        "layout (location=0) out vec4 outColor[];\n"
        "void main(void) {\n"
        "    uint pixel_id = payload.row * 8 + gl_WorkGroupID.x;\n"
        "    uint vertex_id = pixel_id * 3 + gl_LocalInvocationIndex;\n"
        "    SetMeshOutputsEXT(3u, 1u);\n"
        "    if (gl_LocalInvocationIndex < 3)\n"
        "    {\n"
        "        gl_MeshVerticesEXT[gl_LocalInvocationIndex].gl_Position = ssbo.positions[vertex_id];\n"
        + color
        + "    }\n"
        "    if (gl_LocalInvocationIndex == 0)\n"
        "        gl_PrimitiveTriangleIndicesEXT[0] = uvec3(0, 1, 2);\n"
        "}\n"
    )


def entry(name, file, stage):
    spv = SPV if stage in ("task", "mesh") else ""
    return f'{{ name = "{name}", template = "dgc/{file}", stage = "{stage}"{spv} }}'


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    manifest = (
        "# Shader manifest for dEQP-VK.dgc.ext.stat_query.task_mesh_inv_*\n"
        "#\n"
        "# @generated by hodow_cts/scripts/gen_dgc_stat_query_mesh_manifest.py - do not hand-edit.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCStatQueryTestsExt.cpp"\n'
        'rust_module = "dgc/stat_query_mesh_tests"\n'
    )
    (SRC_DIR / "sq_mesh_frag0.frag").write_text(FRAG)
    for ies in (False, True):
        count = 2 if ies else 1
        programs = [entry("frag0", "sq_mesh_frag0.frag", "frag")]
        for i in range(count):
            file = f"sq_mesh_task{i}.task"
            (SRC_DIR / file).write_text(task(i))
            programs.append(entry(f"task{i}", file, "task"))
        for i in range(count):
            file = f"sq_mesh_mesh{i}.mesh"
            (SRC_DIR / file).write_text(mesh(i))
            programs.append(entry(f"mesh{i}", file, "mesh"))
        name = "sq_mesh_ies" if ies else "sq_mesh"
        manifest += (
            f'\n[[case]]\nname = "{name}"\nrust_const = "{name.upper()}"\nrust_type = "SharedProgram"\n'
            f"programs = [ {', '.join(programs)} ]\n"
        )
    MANIFEST.write_text(manifest)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
