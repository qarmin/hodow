#!/usr/bin/env python3
"""Writes the GLSL of mesh_shader.ext.smoke.*.shared_frag_library (vktMeshShaderSmokeTestsEXT.cpp `SharedFragLibraryCase::initPrograms`) and its manifest.

Four shader sets, one per (primitive ID, extra input): `vert`, `vert_1_2` (the same source built for SPIR-V 1.5), `mesh` and `frag`.
  * shaders/manifest/mesh_shader_smoke_shared_frag.toml and shaders/src/mesh_shader/smoke_shared_frag/

Run from hodow_cts/:  python3 scripts/gen_mesh_smoke_shared_frag.py   (then `just cts-shaders`)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "shaders" / "src" / "mesh_shader" / "smoke_shared_frag"
MANIFEST = ROOT / "shaders" / "manifest" / "mesh_shader_smoke_shared_frag.toml"

VTX_POSITIONS = (
    "vec2 positions[4] = vec2[](\n    vec2(-1.0, -1.0),\n    vec2(-1.0,  1.0),\n    vec2( 1.0, -1.0),\n    vec2( 1.0,  1.0)\n);\n"
)
LAYER_COLORS = ["vec4(0, 0, 0, 1)", "vec4(1, 0, 1, 1)", "vec4(1, 1, 0, 1)"]


def shaders(primitive_id, extra_input):
    use_layer = not primitive_id
    vert = (
        "#version 450\n#extension GL_ARB_shader_viewport_layer_array : enable\n"
        + ("layout (location=0) out float multiplier;\n" if extra_input else "")
        + "\n"
        + VTX_POSITIONS
        + "void main ()\n{\n    gl_Position = vec4(positions[gl_VertexIndex % 4], 0.0, 1.0);\n"
        + ("    gl_Layer = 1;\n" if use_layer else "")
        + ("    multiplier = (gl_VertexIndex < 1024 ? 1.0 : 0.0);\n" if extra_input else "")
        + "}\n"
    )
    mesh = (
        "#version 450\n#extension GL_EXT_mesh_shader : enable\n\nlayout (local_size_x=1, local_size_y=1, local_size_z=1) in;\n"
        "layout (triangles) out;\nlayout (max_vertices=4, max_primitives=2) out;\n\nperprimitiveEXT out gl_MeshPerPrimitiveEXT {\n"
        + ("   int gl_Layer;\n" if use_layer else "   int gl_PrimitiveID;\n")
        + "} gl_MeshPrimitivesEXT[];\n\n"
        + VTX_POSITIONS
        + "\n"
        + ("    layout (location=0) out float multiplier[];\n" if extra_input else "")
        + "void main ()\n{\n    SetMeshOutputsEXT(4u, 2u);\n    for (uint i = 0; i < 4; ++i) {\n"
        "        gl_MeshVerticesEXT[i].gl_Position = vec4(positions[i], 0.0, 1.0);\n"
        + ("        multiplier[i] = (gl_NumWorkGroups[0] < 1024 ? 1.0 : 0.0);\n" if extra_input else "")
        + "    }\n    gl_PrimitiveTriangleIndicesEXT[0] = uvec3(0, 1, 2);\n    gl_PrimitiveTriangleIndicesEXT[1] = uvec3(2, 1, 3);\n"
        + ("    gl_MeshPrimitivesEXT[0].gl_Layer = 2;\n" if use_layer else "    gl_MeshPrimitivesEXT[0].gl_PrimitiveID = 0;\n")
        + ("    gl_MeshPrimitivesEXT[1].gl_Layer = 2;\n" if use_layer else "    gl_MeshPrimitivesEXT[1].gl_PrimitiveID = 1;\n")
        + "}\n"
    )
    frag = (
        "#version 450\n\n"
        + ("layout (location=0) in float multiplier;\n" if extra_input else "")
        + "layout (location=0) out vec4 outColor;\n\nvec4 outColors[3] = vec4[](\n    "
        + ",\n    ".join(LAYER_COLORS)
        + "\n);\n\nvoid main ()\n{\n"
        + (
            "    const vec4 baseColor = outColors[gl_Layer];\n"
            if use_layer
            else "    const vec4 baseColor = vec4(outColors[2].xy, gl_PrimitiveID, 1.0);\n"
        )
        + "    outColor = baseColor"
        + (" * multiplier" if extra_input else "")
        + ";\n}\n"
    )
    return vert, mesh, frag


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.mesh_shader.ext.smoke.{optimized_lib,fast_lib}.shared_frag_library*.",
        "#",
        "# @generated by hodow_cts/scripts/gen_mesh_smoke_shared_frag.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/mesh_shader/vktMeshShaderSmokeTestsEXT.cpp"',
        'rust_module = "mesh_shader/smoke_tests"',
        "",
    ]
    for primitive_id in (False, True):
        for extra_input in (False, True):
            key = f"shared_frag_{'primid' if primitive_id else 'layer'}{'_extra' if extra_input else ''}"
            vert, mesh, frag = shaders(primitive_id, extra_input)
            (SRC / f"{key}.vert").write_text(vert)
            (SRC / f"{key}.mesh").write_text(mesh)
            (SRC / f"{key}.frag").write_text(frag)
            out += [
                "[[case]]",
                f'name = "{key}"',
                f'rust_const = "{key.upper()}"',
                'rust_type = "SharedProgram"',
                "programs = [",
                f'    {{ name = "vert", template = "mesh_shader/smoke_shared_frag/{key}.vert", stage = "vert" }},',
                f'    {{ name = "vert_1_2", template = "mesh_shader/smoke_shared_frag/{key}.vert", stage = "vert", spirv_version = "spirv1.5" }},',
                f'    {{ name = "mesh", template = "mesh_shader/smoke_shared_frag/{key}.mesh", stage = "mesh", spirv_version = "spirv1.4" }},',
                f'    {{ name = "frag", template = "mesh_shader/smoke_shared_frag/{key}.frag", stage = "frag" }},',
                "]",
                "",
            ]
    MANIFEST.write_text("\n".join(out))
    print("4 cases")


if __name__ == "__main__":
    main()
