#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.image.load_store.*.

`LoadStoreTest::makePrograms` (the compute shader of the plain case): it loads a texel from one storage image and stores it mirrored
horizontally into another. It depends on the texture type, the format and the three flags that reach it (the format is declared on the
reads, on the writes, one layer is bound at a time), so there is one entry per distinct combination (plus the `restrict` case of the qualifiers group for each texture type), found by `load_store_key` in
load_store_tests.rs. The tables of the formats are those of gen_image_store_manifest.py.

A pure text generator: no glslang and no cargo.
"""

import json
from pathlib import Path

import gen_image_store_manifest as store

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "image_load_store.toml"

HEADER = """# Shader manifest for dEQP-VK.image.load_store.*
#
# @generated by hodow_cts/scripts/gen_image_load_store_manifest.py - do not hand-edit.
#
# `LoadStoreTest::makePrograms`, one entry per texture type, format and flag combination.

upstream_source = "external/vulkancts/modules/vulkan/image/vktImageLoadStoreTests.cpp"
rust_module = "image/load_store_tests"
"""


def py(value) -> str:
    return json.dumps(repr(value))


def entry(texture: tuple, info: dict, declare_reads: bool, declare_writes: bool, single_layer: bool, restrict: bool = False) -> tuple:
    type_name, dimension, layer_dimension, x_max, _, _, shader_type, single_type = texture
    used_dimension = layer_dimension if single_layer else dimension
    image_prefix = {"uint": "u", "int": "i"}.get(info["cls"], "")
    image_type_name = single_type if single_layer else shader_type
    body = {
        1: "    int pos = int(gl_GlobalInvocationID.x);\n" f"    imageStore(u_image1, pos, imageLoad(u_image0, {x_max}-pos));\n",
        2: "    ivec2 pos = ivec2(gl_GlobalInvocationID.xy);\n" f"    imageStore(u_image1, pos, imageLoad(u_image0, ivec2({x_max}-pos.x, pos.y)));\n",
        3: "    ivec3 pos = ivec3(gl_GlobalInvocationID);\n" f"    imageStore(u_image1, pos, imageLoad(u_image0, ivec3({x_max}-pos.x, pos.y, pos.z)));\n",
    }[used_dimension]
    qualifier = info["qualifier"]
    derived = {
        "extensions": "#extension GL_EXT_shader_image_load_formatted : require\n" if (not declare_reads or not declare_writes) else "",
        "read_qualifier": f", {qualifier}" if declare_reads else "",
        "write_qualifier": f", {qualifier}" if declare_writes else "",
        "image_type": f"{image_prefix}image{image_type_name}",
        "body": body,
        "restrict": "restrict " if restrict else "",
    }
    key = f"ls_{type_name}_{info['name'].lower()}_{int(declare_reads)}{int(declare_writes)}{int(single_layer)}{'r' if restrict else ''}"
    return key, derived


def emit(key: str, derived: dict) -> str:
    derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
    return f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "comp", template = "image/load_store.comp", stage = "comp" }}]
derived = {{ {derived_text} }}
"""


def main() -> None:
    out = [HEADER]
    seen = set()
    for texture in store.TEXTURES:
        layered = texture[5]
        for name in store.S_FORMATS:
            info = store.format_info(name)
            combos = [(False, False, False)]
            if info["qualifier"]:
                combos += [(True, True, False), (False, True, False)]
                if layered:
                    combos.append((True, True, True))
            for reads, writes, single_layer in combos:
                key, derived = entry(texture, info, reads, writes, single_layer)
                if key not in seen:
                    seen.add(key)
                    out.append(emit(key, derived))
        # the restrict case of `createImageQualifierRestrictCase`
        key, derived = entry(texture, store.format_info("R32G32B32A32_UINT"), True, True, False, True)
        seen.add(key)
        out.append(emit(key, derived))
    MANIFEST.write_text("".join(out))
    print(f"{len(seen)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
