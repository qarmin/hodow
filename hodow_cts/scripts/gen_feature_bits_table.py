#!/usr/bin/env python3
"""Writes src/vkt/tests/api/feature_bits_table.rs from featureBitInfluenceOnDeviceCreate in vktApiFeatureInfo.cpp.

Every table item names a core structure, an extension structure, the VkBool32 member they share and the extension that enables the latter; the structures are
resolved by name against feature_struct_list.rs at run time, so the table holds names only.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "upstream/external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp"
OUT = ROOT / "src/vkt/tests/api/feature_bits_table.rs"
STRUCT_LIST = ROOT / "src/vkt/tests/api/feature_struct_list.rs"

text = SRC.read_text()
start = text.index("tcu::TestStatus featureBitInfluenceOnDeviceCreate")
end = text.index("template <typename T>\nclass CheckIncompleteResult")
body = text[start:end]

types = {}
for m in re.finditer(r"\n\s*(VkPhysicalDevice\w+)\s+(\w+)\s*=\s*initVulkanStructure\(\);", body):
    types[m.group(2)] = m.group(1)
for m in re.finditer(r"\n\s*(VkPhysicalDevice\w+)\s+(\w+)\s*=\s*\n\s*initVulkanStructure\(\);", body):
    types[m.group(2)] = m.group(1)
types["unusedExtensionFeatures"] = None

known = set(re.findall(r'struct_name: "(\w+)"', STRUCT_LIST.read_text()))

blocks = {}
for version in ("1_2", "1_3", "1_4"):
    marker = f"VK_API_VERSION == VK_API_VERSION_{version}"
    blocks[version] = body.index(marker)
order = sorted(blocks.items(), key=lambda kv: kv[1])
segments = {}
for i, (version, pos) in enumerate(order):
    stop = order[i + 1][1] if i + 1 < len(order) else body.index("else\n        DE_ASSERT(false)")
    segments[version] = body[pos:stop]

item_re = re.compile(r'FEATURE_TABLE_ITEM\(\s*(\w+),\s*(\w+),\s*(\w+),\s*(nullptr|"[^"]*")\s*\)')
dep_re = re.compile(r"DEPENDENCY_DUAL_ITEM\(\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+)\s*\)")

def struct_of(var):
    if var == "unusedExtensionFeatures":
        return "unused"
    name = types[var]
    if name not in known:
        sys.exit(f"{var}: {name} is not in feature_struct_list.rs")
    return name

lines = [
    "// SPDX-License-Identifier: Apache-2.0",
    "//",
    "// Derived from VK-GL-CTS:",
    "//   external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp (`featureBitInfluenceOnDeviceCreate`)",
    "// Upstream revision: see hodow_cts/upstream/COMMIT",
    "//",
    "// Copyright (c) 2015 The Khronos Group Inc.",
    "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
    "//",
    "// Generated by scripts/gen_feature_bits_table.py; do not hand-edit.",
    "",
    "/// One `FEATURE_TABLE_ITEM`: the core structure and the extension structure both carry the member `field`.",
    "pub struct FeatureBitItem {",
    "    pub core_struct: &'static str,",
    "    pub ext_struct: &'static str,",
    "    pub field: &'static str,",
    "    pub ext_string: Option<&'static str>,",
    "}",
    "",
    "/// One `DEPENDENCY_DUAL_ITEM` half: enabling `field` of `structure` also needs `depends_on` of the same structure.",
    "pub struct FeatureBitDependency {",
    "    pub structure: &'static str,",
    "    pub field: &'static str,",
    "    pub depends_on: &'static str,",
    "}",
    "",
]
for version, seg in segments.items():
    items = item_re.findall(seg)
    lines.append(f"pub static FEATURE_BIT_ITEMS_{version}: &[FeatureBitItem] = &[")
    for core, ext, field, ext_string in items:
        es = "None" if ext_string == "nullptr" else f"Some({ext_string})"
        lines.append(f'    FeatureBitItem {{ core_struct: "{struct_of(core)}", ext_struct: "{struct_of(ext)}", field: "{field}", ext_string: {es} }},')
    lines.append("];")
    lines.append("")
    deps = dep_re.findall(seg)
    lines.append(f"pub static FEATURE_BIT_DEPENDENCIES_{version}: &[FeatureBitDependency] = &[")
    for core, ext, field, parent in deps:
        for var in (core, ext):
            lines.append(f'    FeatureBitDependency {{ structure: "{struct_of(var)}", field: "{field}", depends_on: "{parent}" }},')
    lines.append("];")
    lines.append("")

OUT.write_text("\n".join(lines))
print(f"wrote {OUT}")
