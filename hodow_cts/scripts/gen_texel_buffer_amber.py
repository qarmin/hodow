#!/usr/bin/env python3
"""Writes the shaders, the manifest and the case table of dEQP-VK.texture.texel_buffer.uniform.{packed,snorm,srgb} from the vendored Amber scripts.

Each script is read for its fragment shader (and vertex shader, where it is not PASSTHROUGH), the texel data (`BUFFER .. DATA_TYPE <format> DATA` or the
two `IMAGE .. DATA`), the framebuffer size, the clear colour, the `DRAW_RECT` and the `EXPECT framebuffer` lines. Written:

  * shaders/manifest/texture_texel_buffer.toml and shaders/src/texture_texel_buffer/,
  * src/vkt/tests/texture/texel_buffer_cases.rs (the table of src/vkt/tests/texture/texel_buffer_tests.rs).

Run from hodow_cts/:  python3 scripts/gen_texel_buffer_amber.py   (then `just cts-shaders`)
"""
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/texture/texel_buffer/uniform"
SRC = ROOT / "shaders" / "src" / "texture_texel_buffer"
MANIFEST = ROOT / "shaders" / "manifest" / "texture_texel_buffer.toml"
TABLE = ROOT / "src" / "vkt" / "tests" / "texture" / "texel_buffer_cases.rs"

PASSTHROUGH_VERTEX = "#version 430\nlayout(location = 0) in vec4 position;\nvoid main() {\n  gl_Position = position;\n}\n"


def component_bytes(format_name):
    """The size in bytes of one DATA value of `format_name`."""
    if format_name.endswith("PACK32"):
        return 4
    if re.match(r"^[A-Z]+16", format_name) or "16" in format_name.split("_")[0]:
        return 2
    return 1


def parse_values(lines, size):
    data = bytearray()
    for line in lines:
        line = line.split("#")[0]
        for token in line.split():
            value = int(token, 16) if token.lower().startswith("0x") else int(token)
            if value < 0:
                data += struct.pack({1: "<b", 2: "<h", 4: "<i"}[size], value)
            else:
                # r8g8_srgb.amber has a 272 in its image data; Amber stores the value in the width of the format
                data += struct.pack({1: "<B", 2: "<H", 4: "<I"}[size], value & ((1 << (8 * size)) - 1))
    return bytes(data)


def block(text, start_re):
    """The lines after the first line that matches `start_re`, up to END."""
    lines = text.splitlines()
    for ndx, line in enumerate(lines):
        if re.match(start_re, line):
            out = []
            for body in lines[ndx + 1 :]:
                if body.strip() == "END":
                    return line, out
                out.append(body)
    raise RuntimeError(start_re)


def rust_bytes(data):
    return "&[" + ", ".join(str(b) for b in data) + "]"


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.texture.texel_buffer.",
        "#",
        "# @generated by hodow_cts/scripts/gen_texel_buffer_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/texture/texel_buffer/uniform/srgb/r8g8b8a8_srgb.amber"',
        'rust_module = "texture/texel_buffer_tests"',
        "",
    ]
    table = [
        "// @generated by hodow_cts/scripts/gen_texel_buffer_amber.py - do not hand-edit.",
        "//",
        "// One row per Amber script of dEQP-VK.texture.texel_buffer.uniform: the texel data, the framebuffer, the draw and the expectations.",
        "",
        "use super::texel_buffer_tests::{Expectation, TexelBufferCase};",
        "use vulkanalia::prelude::v1_0::*;",
        "",
        "pub static TEXEL_BUFFER_CASES: &[TexelBufferCase] = &[",
    ]
    for path in sorted(AMBER.glob("*/*.amber")):
        group = path.parent.name
        name = path.stem
        text = path.read_text()
        key = f"texel_buffer_{group}_{name.replace('-', '_')}"

        _, frag_lines = block(text, r"^SHADER fragment \w+ GLSL")
        fragment = "\n".join(frag_lines) + "\n"
        if "SHADER vertex vert_shader PASSTHROUGH" in text:
            vertex = PASSTHROUGH_VERTEX
        else:
            _, vert_lines = block(text, r"^SHADER vertex \w+ GLSL")
            vertex = "\n".join(vert_lines) + "\n"

        if group == "srgb":
            header, tex_lines = block(text, r"^IMAGE texture FORMAT")
            fmt = re.search(r"FORMAT (\w+)", header).group(1)
            width, height = (int(v) for v in re.search(r"WIDTH (\d+) HEIGHT (\d+)", header).groups())
            data = parse_values(tex_lines, 1)
            size = (width, height)
            clear = (0, 0, 0, 0)
            rect = (0, 0, width, height)
            reference = "true"
        else:
            header, lines = block(text, r"^BUFFER texel_buffer DATA_TYPE")
            fmt = re.search(r"DATA_TYPE (\w+)", header).group(1)
            data = parse_values(lines, component_bytes(fmt))
            size = tuple(int(v) for v in re.search(r"FRAMEBUFFER_SIZE (\d+) (\d+)", text).groups())
            clear = tuple(int(v) for v in re.search(r"CLEAR_COLOR pipeline (\d+) (\d+) (\d+) (\d+)", text).groups())
            rect = tuple(int(v) for v in re.search(r"DRAW_RECT POS (\d+) (\d+) SIZE (\d+) (\d+)", text).groups())
            reference = "false"
        expects = []
        for m in re.finditer(r"EXPECT framebuffer IDX (\d+) (\d+) SIZE (\d+) (\d+) EQ_RGBA +(\d+) +(\d+) +(\d+) +(\d+)(?: TOLERANCE (\d+))?", text):
            x, y, w, h, r, g, b, a = (int(v) for v in m.groups()[:8])
            tolerance = int(m.group(9) or 0)
            expects.append(f"Expectation {{ x: {x}, y: {y}, width: {w}, height: {h}, rgba: [{r}, {g}, {b}, {a}], tolerance: {tolerance} }}")

        out += ["[[case]]", f'name = "{key}"', f'rust_const = "{key.upper()}"', 'rust_type = "SharedProgram"', "programs = ["]
        for program_name, stage, source in (("vert", "vert", vertex), ("frag", "frag", fragment)):
            (SRC / f"{key}_{program_name}.{stage}").write_text(source)
            out.append(f'    {{ name = "{program_name}", template = "texture_texel_buffer/{key}_{program_name}.{stage}", stage = "{stage}" }},')
        out += ["]", ""]
        table.append(
            f'    TexelBufferCase {{ group: "{group}", name: "{name}", key: "{key}", format: vk::Format::{fmt}, data: {rust_bytes(data)}, size: ({size[0]}, {size[1]}), '
            f"clear: [{clear[0]}, {clear[1]}, {clear[2]}, {clear[3]}], rect: ({rect[0]}, {rect[1]}, {rect[2]}, {rect[3]}), reference_texture: {reference}, "
            f"expectations: &[{', '.join(expects)}] }},"
        )
    table.append("];")
    MANIFEST.write_text("\n".join(out))
    TABLE.write_text("\n".join(table) + "\n")
    print(len(list(AMBER.glob("*/*.amber"))), "cases")


if __name__ == "__main__":
    main()
