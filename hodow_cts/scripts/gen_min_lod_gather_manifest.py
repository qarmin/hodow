#!/usr/bin/env python3
"""Writes shaders/manifest/texture_min_lod_gather.toml and its GLSL sources.

`TextureGatherMinLodTest::initPrograms` (vktTextureMipmapTests.cpp): a full screen triangle and a fragment shader that gathers one component at
(0.5, 0.5); one program set per component.
"""
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
SRC = CRATE / "shaders" / "src" / "texture" / "min_lod_gather"
MANIFEST = CRATE / "shaders" / "manifest" / "texture_min_lod_gather.toml"

VERT = """#version 450

vec2 positions[3] = vec2[](
    vec2(-1.0, -1.0),
    vec2(3.0, -1.0),
    vec2(-1.0, 3.0)
);

void main (void)
{
    gl_Position = vec4(positions[gl_VertexIndex], 0.0, 1.0);
}
"""

FRAG = """#version 450

layout (location=0) out vec4 outColor;
layout (set=0, binding=0) uniform sampler2D u_sampler;

void main (void)
{{
    const vec2 gatherCoords = vec2(0.5, 0.5);
    const vec4 gatherRes = textureGather(u_sampler, gatherCoords, {component});
    outColor = vec4(gatherRes.xyz, 1.0);
}}
"""


def main() -> None:
    SRC.mkdir(parents=True, exist_ok=True)
    (SRC / "vert.vert").write_text(VERT)
    out = [
        "# Shader manifest for dEQP-VK.texture.mipmap.min_lod_gather.*",
        "#",
        "# @generated by hodow_cts/scripts/gen_min_lod_gather_manifest.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/texture/vktTextureMipmapTests.cpp"',
        'rust_module = "texture/min_lod_gather_tests"',
        "",
    ]
    for component in range(4):
        (SRC / f"frag_component_{component}.frag").write_text(FRAG.format(component=component))
        out += [
            "[[case]]",
            f'name = "component_{component}"',
            f'rust_const = "MIN_LOD_GATHER_COMPONENT_{component}"',
            'rust_type = "SharedProgram"',
            "programs = [",
            '    { name = "vert", template = "texture/min_lod_gather/vert.vert", stage = "vert" },',
            f'    {{ name = "frag", template = "texture/min_lod_gather/frag_component_{component}.frag", stage = "frag" }},',
            "]",
            "",
        ]
    MANIFEST.write_text("\n".join(out))


if __name__ == "__main__":
    main()
