#!/usr/bin/env python3
"""Writes everything `binding_model.descriptor_heap_random.*` needs that upstream computes at run time.

`vktBindingDescriptorHeapRandomTests.cpp` draws a random descriptor layout from `de::Random(seed)` in `initPrograms` (and generates the GLSL while
it draws the check decisions), then the instance reuses that layout. This script replays the same draws (`generateRandomLayout`, `CheckDecider`,
the GLSL builder), in the order of `populateDescriptorHeapRandomTests`, and writes:

  shaders/manifest/binding_model_heap_random*.toml   one program set per case (GLSL as a derived value), split into files of about 12 MB
  src/vkt/tests/binding_model/heap_random_cases/cases.txt   one line per case: name, seed, the case definition and the layout the instance needs
  src/vkt/tests/binding_model/heap_random_programs.rs        the program of every seed

`--check` fails when the files on disk differ. A pure text generator: no glslang and no cargo.
"""

import json
import sys
from pathlib import Path

from de_random import DeRandom

CRATE = Path(__file__).resolve().parent.parent
MANIFEST_DIR = CRATE / "shaders" / "manifest"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "binding_model" / "heap_random"
CASES = CRATE / "src" / "vkt" / "tests" / "binding_model" / "heap_random_cases" / "cases.txt"
PROGRAM_TABLE = CRATE / "src" / "vkt" / "tests" / "binding_model" / "heap_random_programs.rs"
MANIFEST_SIZE_TARGET = 12_000_000

DIM = 8

INDEX_NONE, INDEX_CONSTANT, INDEX_PUSHCONSTANT, INDEX_DEPENDENT, INDEX_RUNTIME_SIZE = range(5)
STAGE_COMPUTE, STAGE_VERTEX, STAGE_FRAGMENT = range(3)

UBO, SSBO, STORAGE_TEXEL, STORAGE_IMAGE, UNIFORM_TEXEL, COMBINED, INPUT_ATTACHMENT = "U", "S", "X", "I", "T", "C", "A"

HEADER = """# Shader manifest for dEQP-VK.binding_model.descriptor_heap_random.*
#
# @generated by hodow_cts/scripts/gen_heap_random_manifest.py - do not hand-edit.
#
# One entry per case: `DescriptorHeapRandomCase::initPrograms` builds the GLSL from the random layout of the case's seed.
# src/vkt/tests/binding_model/heap_random_programs.rs maps a seed to its entry.

upstream_source = "external/vulkancts/modules/vulkan/binding_model/vktBindingDescriptorHeapRandomTests.cpp"
rust_module = "binding_model/heap_random_tests"
"""

VERT_SOURCE = (
    "#version 450 core\n"
    "void main()\n"
    "{\n"
    "  vec2 uv = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2);\n"
    "  gl_Position = vec4(uv * 2.0 - 1.0, 0.0, 1.0);\n"
    "}\n"
)


def rand_range(rnd, minimum, maximum):
    if maximum < 0:
        return 0
    return (rnd.get_uint32() % (maximum - minimum + 1)) + minimum


class Layout:
    def __init__(self, sets):
        self.bindings = [[] for _ in range(sets)]  # per set: dict(type, count)
        self.array_sizes = [[] for _ in range(sets)]
        self.shader_bindings = [[] for _ in range(sets)]
        self.writes = {}  # (set, binding, number) -> generated flag


def choose_writes_randomly(layout, rnd, s, b, count):
    for i in range(count):
        if rand_range(rnd, 1, 2) == 1:
            layout.writes[(s, b, i)] = False


def generate_random_layout(layout, case, rnd):
    num_ubo = num_ssbo = num_image = num_storage_tex = num_sampled = num_input = 0
    sets = case["sets"]
    max_bindings = 128 // sets
    max_array = 0 if case["index"] == INDEX_NONE else 32

    for s in range(sets):
        num_bindings = rand_range(rnd, 0, max_bindings)
        if s == 0 and num_bindings == 0:
            num_bindings = 1
        layout.bindings[s] = [{"type": None, "count": 0} for _ in range(num_bindings)]
        layout.array_sizes[s] = [0] * num_bindings

    for b in range(max_bindings + 1):
        for s in range(sets):
            bindings = layout.bindings[s]
            array_sizes = layout.array_sizes[s]
            if b >= len(bindings):
                continue
            binding = bindings[b]

            if s == 0 and b == 0:
                binding["type"] = STORAGE_IMAGE
                binding["count"] = 1
                num_image += 1
                array_sizes[b] = 0
                continue

            binding["count"] = 0
            types = [UBO, SSBO, STORAGE_TEXEL, STORAGE_IMAGE, UNIFORM_TEXEL, COMBINED]
            if case["stage"] == STAGE_FRAGMENT:
                types.append(INPUT_ATTACHMENT)
            binding["type"] = types[rand_range(rnd, 0, len(types) - 1)]
            kind = binding["type"]

            def draw(limit, used):
                return rand_range(rnd, 0, min(max_array, limit - used))

            if kind == UBO:
                if num_ubo < case["ubo"]:
                    array_sizes[b] = draw(case["ubo"], num_ubo)
                    binding["count"] = array_sizes[b] or 1
                    num_ubo += binding["count"]
            elif kind == SSBO:
                if num_ssbo < case["sbo"]:
                    array_sizes[b] = draw(case["sbo"], num_ssbo)
                    binding["count"] = array_sizes[b] or 1
                    num_ssbo += binding["count"]
                    choose_writes_randomly(layout, rnd, s, b, binding["count"])
            elif kind == STORAGE_TEXEL:
                if num_storage_tex < case["stex"]:
                    array_sizes[b] = draw(case["stex"], num_storage_tex)
                    binding["count"] = array_sizes[b] or 1
                    num_storage_tex += binding["count"]
                    choose_writes_randomly(layout, rnd, s, b, binding["count"])
            elif kind == STORAGE_IMAGE:
                if num_image < case["simg"]:
                    array_sizes[b] = draw(case["simg"], num_image)
                    binding["count"] = array_sizes[b] or 1
                    num_image += binding["count"]
                    choose_writes_randomly(layout, rnd, s, b, binding["count"])
            elif kind in (UNIFORM_TEXEL, COMBINED):
                if num_sampled < case["sampled"]:
                    array_sizes[b] = draw(case["sampled"], num_sampled)
                    binding["count"] = array_sizes[b] or 1
                    num_sampled += binding["count"]
            elif kind == INPUT_ATTACHMENT:
                if num_input < case["ia"]:
                    array_sizes[b] = 0
                    binding["count"] = 1
                    num_input += 1

    for s in range(sets):
        bindings = layout.bindings[s]
        array_sizes = layout.array_sizes[s]
        layout.shader_bindings[s] = [0] * len(bindings)
        next_binding = 0
        for b in range(len(bindings)):
            if bindings[b]["count"] == 0:
                continue
            layout.shader_bindings[s][b] = next_binding
            next_binding += max(1, array_sizes[b])


class CheckDecider:
    RANDOM_CHECKS_PER_BINDING = 4

    def __init__(self, rnd, count):
        self.rnd = rnd
        self.count = count
        self.remainder = 0
        self.have_remainder = False

    def should_check(self, array_index):
        if array_index <= 2 or array_index == self.count - 1:
            return True
        if not self.have_remainder:
            assert self.count >= self.RANDOM_CHECKS_PER_BINDING
            self.remainder = rand_range(self.rnd, 0, self.count // self.RANDOM_CHECKS_PER_BINDING - 1)
            self.have_remainder = True
        return array_index % self.count == self.remainder


def build_programs(case, layout, rnd):
    decls = []
    checks = []
    descriptor = 0
    input_attachment_index = 0

    for s in range(case["sets"]):
        bindings = layout.bindings[s]
        array_sizes = layout.array_sizes[s]

        for b in range(len(bindings)):
            binding = bindings[b]
            if binding["count"] == 0:
                continue
            shader_binding = layout.shader_bindings[s][b]

            array = ""
            if case["index"] == INDEX_RUNTIME_SIZE:
                if array_sizes[b]:
                    array = "[]"
            elif array_sizes[b]:
                array = f"[{array_sizes[b]}]"

            kind = binding["type"]
            if kind == UBO:
                decls.append(
                    f"layout(set = {s}, binding = {shader_binding}) uniform ubodef{s}_{b} {{ int val; }} ubo{s}_{b}{array};\n"
                )
            elif kind == SSBO:
                decls.append(
                    f"layout(set = {s}, binding = {shader_binding}) buffer sbodef{s}_{b} {{ int val; }} ssbo{s}_{b}{array};\n"
                )
            elif kind == UNIFORM_TEXEL:
                decls.append(f"layout(set = {s}, binding = {shader_binding}) uniform itextureBuffer texbo{s}_{b}{array};\n")
            elif kind == COMBINED:
                decls.append(f"layout(set = {s}, binding = {shader_binding}) uniform isampler2D combined{s}_{b}{array};\n")
            elif kind == STORAGE_TEXEL:
                decls.append(f"layout(r32i, set = {s}, binding = {shader_binding}) uniform iimageBuffer image{s}_{b}{array};\n")
            elif kind == STORAGE_IMAGE:
                decls.append(f"layout(r32i, set = {s}, binding = {shader_binding}) uniform iimage2D simage{s}_{b}{array};\n")
            elif kind == INPUT_ATTACHMENT:
                decls.append(
                    f"layout(input_attachment_index = {input_attachment_index}, set = {s}, binding = {shader_binding}) "
                    f"uniform isubpassInput attachment{s}_{b};\n"
                )
                input_attachment_index += binding["count"]
            else:
                raise AssertionError(kind)

            array_size = max(1, array_sizes[b])
            decider = CheckDecider(rnd, array_size)

            for ai in range(array_size):
                this_descriptor = descriptor
                descriptor += 1

                if s == 0 and b == 0:
                    continue
                if not decider.should_check(ai):
                    continue

                if case["index"] in (INDEX_NONE, INDEX_CONSTANT):
                    ind = f"[{ai}]" if array_sizes[b] else ""
                elif case["index"] == INDEX_PUSHCONSTANT:
                    ind = f"[pc.identity[{ai}]]" if array_sizes[b] else ""
                else:
                    ind = f"[accum + {ai}]" if array_sizes[b] else ""

                key = (s, b, ai)
                if key not in layout.writes:
                    if kind == UBO:
                        checks.append(f"  temp = ubo{s}_{b}{ind}.val;\n")
                    elif kind == SSBO:
                        checks.append(f"  temp = ssbo{s}_{b}{ind}.val;\n")
                    elif kind == UNIFORM_TEXEL:
                        checks.append(f"  temp = texelFetch(texbo{s}_{b}{ind}, 0).x;\n")
                    elif kind == COMBINED:
                        checks.append(f"  temp = texture(combined{s}_{b}{ind}, vec2(0.5, 0.5)).x;\n")
                    elif kind == INPUT_ATTACHMENT:
                        checks.append(f"  temp = subpassLoad(attachment{s}_{b}).r;\n")
                    elif kind == STORAGE_TEXEL:
                        checks.append(f"  temp = imageLoad(image{s}_{b}{ind}, 0).x;\n")
                    elif kind == STORAGE_IMAGE:
                        checks.append(f"  temp = imageLoad(simage{s}_{b}{ind}, ivec2(0, 0)).x;\n")
                    checks.append(f"  accum |= temp - {this_descriptor};\n")
                else:
                    layout.writes[key] = True
                    write_cond = f"if ({this_descriptor % (DIM * DIM)} == invocationID)"
                    if kind == SSBO:
                        checks.append(f"  {write_cond} ssbo{s}_{b}{ind}.val = {this_descriptor};\n")
                    elif kind == STORAGE_TEXEL:
                        checks.append(f"  {write_cond} imageStore(image{s}_{b}{ind}, 0, ivec4({this_descriptor}, 0, 0, 0));\n")
                    elif kind == STORAGE_IMAGE:
                        checks.append(
                            f"  {write_cond} imageStore(simage{s}_{b}{ind}, ivec2(0, 0), ivec4({this_descriptor}, 0, 0, 0));\n"
                        )

    header = "#version 450 core\n#extension GL_EXT_nonuniform_qualifier : enable\n"
    if case["index"] == INDEX_PUSHCONSTANT:
        header += "layout(push_constant, std430) uniform PushBlock { int identity[32]; } pc;\n"
    header += "".join(decls)
    body = "".join(checks)

    if case["stage"] == STAGE_COMPUTE:
        source = (
            header
            + "layout(local_size_x = 1, local_size_y = 1) in;\n"
            "void main()\n"
            "{\n"
            f"  const int invocationID = int(gl_GlobalInvocationID.y) * {DIM} + int(gl_GlobalInvocationID.x);\n"
            "  int accum = 0, temp;\n"
            + body
            + "  ivec4 color = (accum != 0) ? ivec4(0,0,0,0) : ivec4(1,0,0,1);\n"
            "  imageStore(simage0_0, ivec2(gl_GlobalInvocationID.xy), color);\n"
            "}\n"
        )
        return [("test", "comp", source)]
    if case["stage"] == STAGE_VERTEX:
        source = (
            header
            + "out gl_PerVertex { vec4 gl_Position; float gl_PointSize; };\n"
            "void main()\n"
            "{\n"
            "  const int invocationID = gl_VertexIndex;\n"
            "  int accum = 0, temp;\n"
            + body
            + "  ivec4 color = (accum != 0) ? ivec4(0,0,0,0) : ivec4(1,0,0,1);\n"
            f"  imageStore(simage0_0, ivec2(invocationID % {DIM}, invocationID / {DIM}), color);\n"
            "  gl_Position = vec4(0.0, 0.0, 0.0, 1.0);\n"
            "  gl_PointSize = 1.0;\n"
            "}\n"
        )
        return [("test", "vert", source)]
    source = (
        header
        + "void main()\n"
        "{\n"
        f"  const int invocationID = int(gl_FragCoord.y) * {DIM} + int(gl_FragCoord.x);\n"
        "  int accum = 0, temp;\n"
        + body
        + "  ivec4 color = (accum != 0) ? ivec4(0,0,0,0) : ivec4(1,0,0,1);\n"
        "  imageStore(simage0_0, ivec2(gl_FragCoord.xy), color);\n"
        "}\n"
    )
    return [("vert", "vert", VERT_SOURCE), ("test", "frag", source)]


def enumerate_cases():
    sets_cases = [(4, "sets4"), (8, "sets8")]
    index_cases = [
        (INDEX_NONE, "noarray"),
        (INDEX_CONSTANT, "constant"),
        (INDEX_PUSHCONSTANT, "unifindexed"),
        (INDEX_DEPENDENT, "dynindexed"),
        (INDEX_RUNTIME_SIZE, "runtimesize"),
    ]
    ubo_cases = [(0, "noubo"), (12, "ubolimitlow"), (4096, "ubolimithigh")]
    sbo_cases = [(0, "nosbo"), (4, "sbolimitlow"), (4096, "sbolimithigh")]
    sampled_cases = [(0, "nosampledimg"), (16, "sampledimglow"), (4096, "sampledimghigh")]
    simg_tex_cases = [(1, 0, "outimgonly"), (1, 3, "outimgtexlow"), (4, 0, "lowimgnotex"), (3, 1, "lowimgsingletex")]
    stage_cases = [(STAGE_COMPUTE, "comp"), (STAGE_VERTEX, "vert"), (STAGE_FRAGMENT, "frag")]
    ia_cases = [(0, "noia"), (4, "ialimitlow")]

    seed = 0
    for sets, sets_name in sets_cases:
        for index_ndx, (index, index_name) in enumerate(index_cases):
            for ubo_ndx, (ubo, ubo_name) in enumerate(ubo_cases):
                for sbo_ndx, (sbo, sbo_name) in enumerate(sbo_cases):
                    for sampled_ndx, (sampled, sampled_name) in enumerate(sampled_cases):
                        for simg_ndx, (simg, stex, simg_name) in enumerate(simg_tex_cases):
                            high = (ubo_ndx == 2) + (sbo_ndx == 2) + (sampled_ndx == 2)
                            if 1 < high < 3:
                                continue
                            zero = (ubo_ndx == 0) + (sbo_ndx == 0) + (sampled_ndx == 0)
                            if 1 < zero < 3:
                                continue
                            if simg_ndx >= 2 and index_ndx < 2:
                                continue
                            if (ubo_ndx == 0 or sbo_ndx == 0 or sampled_ndx == 0) and index_ndx < 2:
                                continue

                            num_seeds = (
                                3
                                if (
                                    sets == 4
                                    and ubo_ndx < 2
                                    and sbo_ndx < 2
                                    and sampled_ndx < 2
                                    and (ubo_ndx != 0 or sbo_ndx != 0 or sampled_ndx != 0 or simg_ndx != 0)
                                )
                                else 1
                            )

                            for stage, stage_name in stage_cases:
                                for ia, ia_name in ia_cases:
                                    if ia > 0 and stage != STAGE_FRAGMENT:
                                        continue
                                    for rnd_ndx in range(num_seeds):
                                        name = ".".join(
                                            [
                                                sets_name,
                                                index_name,
                                                ubo_name,
                                                sbo_name,
                                                sampled_name,
                                                simg_name,
                                                stage_name,
                                                ia_name,
                                                str(rnd_ndx),
                                            ]
                                        )
                                        yield {
                                            "name": name,
                                            "seed": seed,
                                            "index": index,
                                            "sets": sets,
                                            "ubo": ubo,
                                            "sbo": sbo,
                                            "sampled": sampled,
                                            "simg": simg,
                                            "stex": stex,
                                            "ia": ia,
                                            "stage": stage,
                                        }
                                        seed += 1


def py(value):
    return json.dumps(repr(value))


def layout_fields(case, layout):
    bindings = []
    for s in range(case["sets"]):
        for b, binding in enumerate(layout.bindings[s]):
            if binding["count"] == 0:
                continue
            bindings.append(f"{s}.{b}.{binding['type']}.{layout.array_sizes[s][b]}.{layout.shader_bindings[s][b]}")
    writes = [f"{s}.{b}.{i}.{int(generated)}" for (s, b, i), generated in sorted(layout.writes.items())]
    return ",".join(bindings), ",".join(writes)


def render():
    entries = []
    case_lines = []
    table = []
    for case in enumerate_cases():
        rnd = DeRandom(case["seed"])
        layout = Layout(case["sets"])
        generate_random_layout(layout, case, rnd)
        programs = build_programs(case, layout, rnd)

        seed = case["seed"]
        program_text = ", ".join(
            f'{{ name = "{name}", template = "binding_model/heap_random/src_{name}.glsl", stage = "{stage}", spirv_version = "spirv1.4" }}'
            for name, stage, _ in programs
        )
        derived = ", ".join(f"src_{name} = {py(source)}" for name, _, source in programs)
        entries.append(
            f'\n[[case]]\nname = "hr_{seed}"\nrust_const = "HR_{seed}"\nrust_type = "SharedProgram"\n'
            f"programs = [{program_text}]\nderived = {{ {derived} }}\n"
        )
        table.append(seed)

        bindings, writes = layout_fields(case, layout)
        case_lines.append(
            "|".join(
                [
                    case["name"],
                    str(seed),
                    str(case["index"]),
                    str(case["sets"]),
                    str(case["ubo"]),
                    str(case["sbo"]),
                    str(case["sampled"]),
                    str(case["simg"]),
                    str(case["stex"]),
                    str(case["ia"]),
                    str(case["stage"]),
                    bindings,
                    writes,
                ]
            )
        )

    chunks = [[]]
    size = 0
    for entry in entries:
        if size >= MANIFEST_SIZE_TARGET:
            chunks.append([])
            size = 0
        chunks[-1].append(entry)
        size += len(entry)

    files = {}
    modules = []
    for number, chunk in enumerate(chunks, start=1):
        module = "binding_model_heap_random" if number == 1 else f"binding_model_heap_random_{number}"
        modules.append(module)
        files[MANIFEST_DIR / f"{module}.toml"] = HEADER + "".join(chunk)
    files[TEMPLATE_DIR / "src_test.glsl"] = "${src_test}"
    files[TEMPLATE_DIR / "src_vert.glsl"] = "${src_vert}"
    files[CASES] = "\n".join(case_lines) + "\n"

    lines = [
        "// @generated by hodow_cts/scripts/gen_heap_random_manifest.py - do not hand-edit.",
        "//",
        "// The program set of every seed of `binding_model.descriptor_heap_random`, indexed by seed.",
        "",
        *[f"use crate::generated::shaders::{module}::*;" for module in modules],
        "use crate::vk::programs::SharedProgram;",
        "",
        "pub static PROGRAM_TABLE: &[&SharedProgram] = &[",
        *[f"    &HR_{seed}," for seed in table],
        "];",
    ]
    files[PROGRAM_TABLE] = "\n".join(lines) + "\n"
    return files, len(table), modules


def main():
    files, count, modules = render()
    if "--check" in sys.argv:
        stale = [str(path) for path, text in files.items() if not path.exists() or path.read_text() != text]
        existing = {MANIFEST_DIR / f"{module}.toml" for module in modules}
        stale += [str(p) for p in MANIFEST_DIR.glob("binding_model_heap_random*.toml") if p not in existing]
        if stale:
            print("stale:", *stale, sep="\n  ")
            sys.exit(1)
        print(f"{count} cases up to date")
        return
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    existing = {MANIFEST_DIR / f"{module}.toml" for module in modules}
    for stale in MANIFEST_DIR.glob("binding_model_heap_random*.toml"):
        if stale not in existing:
            stale.unlink()
    print(f"{count} cases -> {len(modules)} manifests {', '.join(modules)}")


if __name__ == "__main__":
    main()
