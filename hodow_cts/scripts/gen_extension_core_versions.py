#!/usr/bin/env python3
"""Generate src/vkt/tests/api/extension_core_versions_tests.rs, dEQP-VK.api.info.extension_core_versions.

The table is upstream's generated `extensionRequiredCoreVersion` (vkApiExtensionDependencyInfo.inl): for every extension, the core
version a device has to report once it exposes that extension.

Usage:
    python3 hodow_cts/scripts/gen_extension_core_versions.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
INL = CRATE_DIR / "upstream/external/vulkancts/framework/vulkan/generated/vulkan/vkApiExtensionDependencyInfo.inl"
OUT = CRATE_DIR / "src/vkt/tests/api/extension_core_versions_tests.rs"


def main() -> int:
    text = INL.read_text()
    start = text.index("extensionRequiredCoreVersion[]")
    end = text.index("};", start)
    entries = re.findall(r'std::make_tuple\((\d+),\s*(\d+),\s*"(\w+)"\)', text[start:end])
    if not entries:
        sys.exit("no entries found")

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp (`extensionCoreVersions`)",
        "//   external/vulkancts/framework/vulkan/generated/vulkan/vkApiExtensionDependencyInfo.inl (`extensionRequiredCoreVersion`)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2015 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_extension_core_versions.py; do not hand-edit.",
        "//",
        "// `info.extension_core_versions`: an extension the instance or the device exposes must not be exposed by an implementation older",
        "// than the core version that extension requires.",
        "",
        "use vulkanalia::prelude::v1_0::*;",
        "",
        "use super::case_util::add_function_case_no_support;",
        "use crate::tcu::result_collector::ResultCollector;",
        "use crate::tcu::{TestError, TestOutcome};",
        "use crate::vkt::{Context, TestCaseGroup};",
        "",
        "/// `extensionRequiredCoreVersion`: (major, minor, extension).",
        "const EXTENSION_REQUIRED_CORE_VERSION: &[(u32, u32, &str)] = &[",
        *[f'    ({major}, {minor}, "{name}"),' for major, minor, name in entries],
        "];",
        "",
        "/// `extensionCoreVersions`",
        "fn extension_core_versions(context: &Context<'_>) -> TestOutcome {",
        "    let mut results = ResultCollector::new(\"\");",
        "",
        "    let instance_extensions = unsafe { context.get_platform().entry.enumerate_instance_extension_properties(None) }",
        "        .map_err(|e| TestError::InternalError(format!(\"vkEnumerateInstanceExtensionProperties returned {e:?}\")))?;",
        "    let device_extensions = context.get_device_extensions();",
        "    let (major, minor, _) = context.api_version();",
        "",
        "    for &(required_major, required_minor, name) in EXTENSION_REQUIRED_CORE_VERSION {",
        "        let exposed = instance_extensions.iter().any(|p| p.extension_name.to_string_lossy() == name) || device_extensions.iter().any(|e| e == name);",
        "        if exposed && (major, minor) < (required_major, required_minor) {",
        "            results.fail(format!(\"Required core version for {name} not met ({required_major}.{required_minor})\"));",
        "        }",
        "    }",
        "",
        "    Ok(results.to_status())",
        "}",
        "",
        "/// The `extension_core_versions` group of `api.info`.",
        "pub fn create_extension_core_versions_group() -> TestCaseGroup {",
        "    let mut group = TestCaseGroup::new(\"extension_core_versions\");",
        "    add_function_case_no_support(&mut group, \"extension_core_versions\", extension_core_versions);",
        "    group",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{len(entries)} extensions -> {OUT.relative_to(CRATE_DIR.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
