#!/usr/bin/env python3
"""Writes the shader manifest and the case table of dEQP-VK.binding_model.descriptor_copy.*

The sources come from descriptor_copy_cases.py (a transliteration of `DescriptorCopyTestCase::initPrograms` and of the functions that build the cases),
carried in the manifest as derived values; cases with identical sources share one entry. `descriptor_copy_table.rs` describes every case for
`src/vkt/tests/binding_model/descriptor_copy_tests.rs`: its descriptors, copies, dynamic areas and the program set to run.

A pure text generator: no glslang and no cargo.
"""

import hashlib
import json
from pathlib import Path

import descriptor_copy_cases as dc

CRATE = Path(__file__).resolve().parent.parent
MANIFEST = CRATE / "shaders" / "manifest" / "binding_descriptor_copy.toml"
TEMPLATES = CRATE / "shaders" / "src" / "binding_model" / "descriptor_copy"
TABLE = CRATE / "src" / "vkt" / "tests" / "binding_model" / "descriptor_copy_table.rs"

HEADER = """# Shader manifest for dEQP-VK.binding_model.descriptor_copy.*
#
# @generated by hodow_cts/scripts/gen_descriptor_copy_manifest.py - do not hand-edit.
#
# `DescriptorCopyTestCase::initPrograms`, one entry per distinct set of sources. The GLSL is a derived value because upstream builds it from the
# descriptors of the case in C++; src/vkt/tests/binding_model/descriptor_copy_table.rs says which entry a case runs.

upstream_source = "external/vulkancts/modules/vulkan/binding_model/vktBindingDescriptorCopyTests.cpp"
rust_module = "binding_model/descriptor_copy_tests"
"""

KIND_VARIANTS = ["Ubo", "DynUbo", "Ssbo", "DynSsbo", "Utb", "Stb", "Iub", "Input", "Combined", "Sampled", "Sampler", "StorageImage"]

VERTEX = ("#version 450\nout gl_PerVertex\n{\n    vec4 gl_Position;\n};\nvoid main()\n{\n"
          "    gl_Position = vec4(((gl_VertexIndex + 2) / 3) % 2 == 0 ? -1.0 : 1.0,\n"
          "                       ((gl_VertexIndex + 1) / 3) % 2 == 0 ? -1.0 : 1.0, 0.0, 1.0);\n}\n")


def immutable_sampler_programs(sampler_count: int, buffer_first: bool) -> tuple[str, str]:
    """`CopyImmutableSamplerCase::initPrograms`"""
    vert = ("#version 460\nlayout (location=0) in vec4 inPos;\nlayout (location=0) out flat int quadrant;\nvoid main(void) {\n"
            "    gl_Position = inPos;\n    gl_PointSize = 1.0;\n")
    if sampler_count == 1:
        vert += "    quadrant = 0;\n"
    else:
        vert += ("    if (inPos.x < 0.0) {\n        if (inPos.y < 0.0) {\n            quadrant = 0;\n        } else {\n            quadrant = 1;\n"
                 "        }\n    } else {\n        if (inPos.y < 0.0) {\n            quadrant = 2;\n        } else {\n            quadrant = 3;\n"
                 "        }\n    }\n")
    vert += "}\n"

    buffer_binding = 0 if buffer_first else sampler_count
    img_offset = 1 if buffer_first else 0
    frag = "#version 460\nlayout (location=0) in flat int quadrant;\nlayout (location=0) out vec4 outColor;\n"
    for i in range(sampler_count):
        frag += "layout (set=0, binding=%d) uniform sampler2D inSampler%d;\n" % (i + img_offset, i)
    frag += "layout (set=0, binding=%d) readonly buffer BufferBlock { float red; } inBuffer;\nvoid main(void) {\n    vec4 sampledColor = vec4(0.0);\n" % buffer_binding
    if sampler_count == 1:
        frag += "    sampledColor = texture(inSampler0, vec2(0.0));\n"
    else:
        frag += ("    if (quadrant == 0) {\n        sampledColor = texture(inSampler0, vec2(0.0));\n    } else if (quadrant == 1) {\n"
                 "        sampledColor = texture(inSampler1, vec2(0.0));\n    } else if (quadrant == 2) {\n        sampledColor = texture(inSampler2, vec2(0.0));\n"
                 "    } else if (quadrant == 3) {\n        sampledColor = texture(inSampler3, vec2(0.0));\n    }\n")
    frag += "    sampledColor.r = inBuffer.red;\n    outColor = sampledColor;\n}\n"
    return vert, frag


def py(value) -> str:
    return json.dumps(repr(value))


def main() -> None:
    TEMPLATES.mkdir(parents=True, exist_ok=True)
    (TEMPLATES / "compute.comp").write_text("${src_compute}")
    (TEMPLATES / "fragment.frag").write_text("${src_fragment}")
    (TEMPLATES / "vertex.vert").write_text(VERTEX)

    by_sig: dict[tuple, str] = {}
    entries = []
    rows = []
    for group, name, commands in dc.all_cases():
        programs = commands.programs()
        sig = tuple(sorted((n, st, src) for n, (st, src) in programs.items()))
        if sig not in by_sig:
            digest = hashlib.sha1(repr(sig).encode()).hexdigest()[:12]
            const = f"DC_{digest.upper()}"
            by_sig[sig] = const
            if commands.pipeline == dc.COMPUTE:
                progs = '{ name = "compute", template = "binding_model/descriptor_copy/compute.comp", stage = "comp" }'
                derived = f"src_compute = {py(programs['compute'][1])}"
            else:
                progs = ('{ name = "vertex", template = "binding_model/descriptor_copy/vertex.vert", stage = "vert" }, '
                         '{ name = "fragment", template = "binding_model/descriptor_copy/fragment.frag", stage = "frag" }')
                derived = f"src_fragment = {py(programs['fragment'][1])}"
            entries.append(f'\n[[case]]\nname = "dc_{digest}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\nprograms = [{progs}]\nderived = {{ {derived} }}\n')

        descriptors = []
        for d in commands.descriptors:
            attachments = ", ".join(str(i) for i in d.attachment_indices)
            descriptors.append(
                f"DescriptorDef {{ kind: Kind::{KIND_VARIANTS[d.kind]}, id: {d.id}, array_size: {d.array_size}, write_start: {d.write_start}, "
                f"elements_to_write: {d.elements_to_write}, areas: {d.areas}, set: {d.set}, original_attachment: {d.original_attachment}, "
                f"attachment_indices: &[{attachments}] }}"
            )
        copies = ", ".join("CopyDef { src_set: %d, src_binding: %d, src_element: %d, dst_set: %d, dst_binding: %d, dst_element: %d, count: %d }" % c for c in commands.copies)
        areas = ", ".join(str(a) for a in commands.dynamic_areas)
        rows.append(
            f'    CaseDef {{ group: "{group}", name: "{name}", pipeline: Pipeline::{"Compute" if commands.pipeline == dc.COMPUTE else "Graphics"}, '
            f"update_after_bind: {'true' if commands.uab else 'false'}, set_count: {len(commands.sets)}, "
            f"descriptors: &[{', '.join(descriptors)}], copies: &[{copies}], dynamic_areas: &[{areas}], programs: &{by_sig[sig]} }},"
        )

    (TEMPLATES / "immutable.vert").write_text("${src_vert}")
    (TEMPLATES / "immutable.frag").write_text("${src_frag}")
    immutable_rows = []
    for sampler_count in (1, 4):
        for buffer_first in (False, True):
            vert, frag = immutable_sampler_programs(sampler_count, buffer_first)
            const = f"DCI_{sampler_count}_{'BF' if buffer_first else 'AF'}"
            entries.append(
                f'\n[[case]]\nname = "{const.lower()}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\n'
                'programs = [{ name = "vert", template = "binding_model/descriptor_copy/immutable.vert", stage = "vert" }, '
                '{ name = "frag", template = "binding_model/descriptor_copy/immutable.frag", stage = "frag" }]\n'
                f"derived = {{ src_vert = {py(vert)}, src_frag = {py(frag)} }}\n"
            )
            name = f"copy_immutable_sampler_{sampler_count}_images" + ("_buffer_first" if buffer_first else "")
            immutable_rows.append(
                f'    ImmutableSamplerDef {{ name: "{name}", sampler_count: {sampler_count}, buffer_first: {"true" if buffer_first else "false"}, programs: &{const} }},'
            )

    MANIFEST.write_text(HEADER + "".join(entries))

    lines = [
        "// @generated by hodow_cts/scripts/gen_descriptor_copy_manifest.py - do not hand-edit.",
        "//",
        "// Every case of dEQP-VK.binding_model.descriptor_copy.{compute,graphics,graphics_uab} as `addDescriptorCopyTests` & co build it.",
        "",
        "use crate::generated::shaders::binding_descriptor_copy::*;",
        "use crate::vk::programs::SharedProgram;",
        "",
        "#[derive(Clone, Copy, PartialEq, Eq)]",
        "pub enum Kind {",
        *[f"    {k}," for k in KIND_VARIANTS],
        "}",
        "",
        "#[derive(Clone, Copy, PartialEq, Eq)]",
        "pub enum Pipeline {",
        "    Compute,",
        "    Graphics,",
        "}",
        "",
        "pub struct DescriptorDef {",
        "    pub kind: Kind,",
        "    pub id: u32,",
        "    pub array_size: u32,",
        "    pub write_start: u32,",
        "    pub elements_to_write: u32,",
        "    /// Dynamic areas of a dynamic buffer, 1 for every other kind.",
        "    pub areas: u32,",
        "    pub set: u32,",
        "    pub original_attachment: u32,",
        "    /// Input attachments: the attachment index of every element once the copies are applied.",
        "    pub attachment_indices: &'static [u32],",
        "}",
        "",
        "/// A `VkCopyDescriptorSet`; for inline uniform blocks the elements and the count are bytes.",
        "pub struct CopyDef {",
        "    pub src_set: u32,",
        "    pub src_binding: u32,",
        "    pub src_element: u32,",
        "    pub dst_set: u32,",
        "    pub dst_binding: u32,",
        "    pub dst_element: u32,",
        "    pub count: u32,",
        "}",
        "",
        "pub struct CaseDef {",
        "    pub group: &'static str,",
        "    pub name: &'static str,",
        "    pub pipeline: Pipeline,",
        "    pub update_after_bind: bool,",
        "    pub set_count: usize,",
        "    pub descriptors: &'static [DescriptorDef],",
        "    pub copies: &'static [CopyDef],",
        "    pub dynamic_areas: &'static [u32],",
        "    pub programs: &'static SharedProgram,",
        "}",
        "",
        "pub static CASES: &[CaseDef] = &[",
        *rows,
        "];",
        "",
        "/// `CopyImmutableSamplerParams`",
        "pub struct ImmutableSamplerDef {",
        "    pub name: &'static str,",
        "    pub sampler_count: u32,",
        "    pub buffer_first: bool,",
        "    pub programs: &'static SharedProgram,",
        "}",
        "",
        "pub static IMMUTABLE_SAMPLER_CASES: &[ImmutableSamplerDef] = &[",
        *immutable_rows,
        "];",
    ]
    TABLE.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} cases, {len(entries)} program sets")


if __name__ == "__main__":
    main()
