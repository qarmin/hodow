#!/usr/bin/env python3
"""Writes shaders/manifest/sparse_resources_null_address.toml, its GLSL sources and the program lookup of the Rust port.

`NullAddressCase::initPrograms` (vktSparseResourcesBufferTests.cpp) builds one compute shader from (descriptor type, access type, use of the local
invocation index, write). The descriptor heap access type is not ported, so only the device address and descriptor set ones are generated.
"""
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
SRC = CRATE / "shaders" / "src" / "sparse_resources" / "null_address"
MANIFEST = CRATE / "shaders" / "manifest" / "sparse_resources_null_address.toml"
LOOKUP = CRATE / "src" / "vkt" / "tests" / "sparse_resources" / "null_address_programs.rs"

VALUE_COUNT = 64

SB, UB, STB, UTB = "storage_buffer", "uniform_buffer", "storage_texel_buffer", "uniform_texel_buffer"


def shader(desc_type: str, device_address: bool, local_index: bool, write: bool) -> str:
    wg_size = VALUE_COUNT if local_index else 1
    src_desc = SB if write else desc_type
    dst_desc = desc_type if write else SB
    array_index = "gl_LocalInvocationIndex" if local_index else "gl_WorkGroupID.x"
    src_value_count = str(VALUE_COUNT) if desc_type == UB else ""

    decls = ""
    if not device_address:
        if src_desc in (UB, SB):
            glsl_type = "uniform" if src_desc == UB else "readonly buffer"
            decls += (
                f"layout (set=0, binding=0, std430) {glsl_type} SrcBufferBlock {{\n"
                f"    uint values[{src_value_count}];\n"
                "} srcBuffer;\n\n"
            )
            src_expr = "srcBuffer.values[idx]"
        elif src_desc == UTB:
            decls += "layout (set=0, binding=0) uniform utextureBuffer srcBuffer;\n"
            src_expr = "texelFetch(srcBuffer, int(idx)).x"
        else:
            decls += "layout (set=0, binding=0, r32ui) uniform uimageBuffer srcBuffer;\n"
            src_expr = "imageLoad(srcBuffer, int(idx)).x"

        if dst_desc == SB:
            decls += (
                "layout (set=0, binding=1, std430) writeonly buffer DstBufferBlock {\n"
                "    uint values[];\n"
                "} dstBuffer;\n\n"
            )
            dst_store = "dstBuffer.values[idx] = " + src_expr
        else:
            decls += "layout (set=0, binding=1, r32ui) uniform uimageBuffer dstBuffer;\n"
            dst_store = f"imageStore(dstBuffer, int(idx), ivec4({src_expr}, 0u, 0u, 0u))"
    else:
        decls += (
            "layout (buffer_reference) buffer srcBuffer;\n"
            "layout (buffer_reference, buffer_reference_align=4, std430) readonly buffer srcBuffer\n"
            "{\n"
            f"    uint values[{src_value_count}];\n"
            "};\n\n"
            "layout (buffer_reference) buffer dstBuffer;\n"
            "layout (buffer_reference, buffer_reference_align=4, std430) writeonly buffer dstBuffer\n"
            "{\n"
            "    uint values[];\n"
            "};\n\n"
            "layout(push_constant, std430) uniform push_cb\n"
            "{\n"
            "    uvec2 srcBufferAddress;\n"
            "    uvec2 dstBufferAddress;\n"
            "} pc;\n\n"
        )
        src_expr = "srcBuffer(pc.srcBufferAddress).values[idx]"
        dst_store = "dstBuffer(pc.dstBufferAddress).values[idx] = " + src_expr

    return (
        "#version 450\n"
        "#extension GL_EXT_buffer_reference2 : require\n"
        "#extension GL_EXT_buffer_reference_uvec2 : require\n"
        "#extension GL_EXT_scalar_block_layout : require\n"
        f"layout (local_size_x={wg_size}, local_size_y=1, local_size_z=1) in;\n"
        "\n"
        + decls
        + "void main()\n"
        "{\n"
        f"    const uint idx = {array_index};\n"
        f"    {dst_store};\n"
        "}\n"
    )


def keys():
    for desc_type in (SB, UB, STB, UTB):
        for local_index in (False, True):
            for device_address in (True, False):
                if device_address and desc_type != SB:
                    continue
                for write in (False, True):
                    if write and desc_type in (UB, UTB):
                        continue
                    yield desc_type, device_address, local_index, write


def key_name(desc_type: str, device_address: bool, local_index: bool, write: bool) -> str:
    return f"{desc_type}_{'address' if device_address else 'set'}_{'local' if local_index else 'group'}_{'write' if write else 'read'}"


def main() -> None:
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.sparse_resources.buffer.misc.null_address_*",
        "#",
        "# @generated by hodow_cts/scripts/gen_sparse_null_address_manifest.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/sparse_resources/vktSparseResourcesBufferTests.cpp"',
        'rust_module = "sparse_resources/buffer_null_address_tests"',
        "",
    ]
    table = []
    for key in keys():
        name = key_name(*key)
        (SRC / f"{name}.comp").write_text(shader(*key))
        const = "NULL_ADDRESS_" + name.upper()
        out += [
            "[[case]]",
            f'name = "{name}"',
            f'rust_const = "{const}"',
            'rust_type = "SharedProgram"',
            "programs = [",
            f'    {{ name = "comp", template = "sparse_resources/null_address/{name}.comp", stage = "comp", spirv_version = "spirv1.0" }},',
            "]",
            "",
        ]
        table.append((name, const))
    MANIFEST.write_text("\n".join(out))

    lines = [
        "// @generated by hodow_cts/scripts/gen_sparse_null_address_manifest.py - do not hand-edit.",
        "",
        "use crate::generated::shaders::sparse_resources_null_address::*;",
        "use crate::vk::programs::BinaryCollection;",
        "",
        "/// The programs of the manifest case `name` (see `key_name` in the generator)",
        "pub fn programs_for(name: &str) -> Option<BinaryCollection> {",
        "    match name {",
    ]
    for name, const in table:
        lines.append(f'        "{name}" => Some({const}.programs),')
    lines += ["        _ => None,", "    }", "}", ""]
    LOOKUP.write_text("\n".join(lines))
    print(len(table))


if __name__ == "__main__":
    main()
