#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.api.copy_and_blit.{core,copy_memory_indirect}.use_after_copy.

`AfterUsageCase::initPrograms` builds six shaders from four facts about a case: whether it has several layers (the vertex shaders then write
gl_Layer), whether the image is a colour one (the fragment shader samples it, else it writes a constant), whether the texture is 3D and
whether the image is multisampled (the sampler type and the way a texel is fetched). There is one manifest entry per combination that the
registration loops of use_after_copy_tests.rs reach, named by `shader_key` there ("s<slices>c<color>t<tex3d>m<ms>").

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "api_use_after_copy.toml"

HEADER = """# Shader manifest for dEQP-VK.api.copy_and_blit.*.use_after_copy
#
# @generated by hodow_cts/scripts/gen_use_after_copy_manifest.py - do not hand-edit.
#
# One entry per (several layers, colour, 3D texture, multisample) combination; see the generator for the key scheme.

upstream_source = "external/vulkancts/modules/vulkan/api/vktApiUseAfterCopyTests.cpp"
rust_module = "api/use_after_copy_tests"
"""

DS_FORMATS = {"D16_UNORM", "D16_UNORM_S8_UINT", "D24_UNORM_S8_UINT", "X8_D24_UNORM_PACK32", "D32_SFLOAT", "D32_SFLOAT_S8_UINT"}


def combos():
    """The (multi_slice, color, tex3d, ms) combinations the registration loops produce."""
    seen = set()
    for is_ds in (False, True):
        for layers in (1, 2):
            for use_3d_image in (False, True):
                if use_3d_image and is_ds:
                    continue
                for view_is_3d in (False, True):
                    if view_is_3d and (not use_3d_image or is_ds):
                        continue
                    if not is_ds and use_3d_image and layers > 1 and not view_is_3d:
                        continue
                    for ms in (False, True):
                        if ms and use_3d_image:
                            continue
                        seen.add((layers > 1, not is_ds, view_is_3d, ms))
    return sorted(seen)


def key(multi_slice, color, tex3d, ms):
    return f"s{int(multi_slice)}c{int(color)}t{int(tex3d)}m{int(ms)}"


def py_str(text):
    return repr(text)


def entry(multi_slice, color, tex3d, ms):
    ext = "#extension GL_ARB_shader_viewport_layer_array : enable\n" if multi_slice else ""
    layer = "    gl_Layer = gl_InstanceIndex;\n" if multi_slice else ""

    sampler = "sampler" + ("3D" if tex3d else "2D") + ("MS" if ms else "") + ("Array" if multi_slice and not tex3d else "")
    tex_decl = f"layout (set=0, binding=0) uniform {sampler} tex;\n" if color else ""
    coords = "ivec3(gl_FragCoord.xy, layerIndex)" if (multi_slice or tex3d) else "ivec2(gl_FragCoord.xy)"
    lod = "gl_SampleID" if ms else "0"
    body = f"    outColor = texelFetch(tex, {coords}, {lod});\n" if color else "    outColor = vec4(0.0, 0.0, 1.0, 1.0);\n"

    samples = 4 if ms else 1
    out_decl = "layout (location=0) out vec4 outColor;\n" if color else ""
    assign = "    outColor = pixels.values[sampleIndex];\n" if color else "    gl_FragDepth = pixels.values[sampleIndex].x;\n"

    name = key(multi_slice, color, tex3d, ms)
    derived = {
        "ext": py_str(ext),
        "layer": py_str(layer),
        "tex_decl": py_str(tex_decl),
        "body": py_str(body),
        "samples": py_str(str(samples)),
        "out_decl": py_str(out_decl),
        "assign": py_str(assign),
    }
    derived_toml = ", ".join(f"{k} = {py_str_toml(v)}" for k, v in derived.items())
    programs = [
        ("vert-spv10", "api/use_after_copy/vert.vert", "vert", None),
        ("vert-spv15", "api/use_after_copy/vert.vert", "vert", "spirv1.5"),
        ("vert-fill-spv10", "api/use_after_copy/vert_fill.vert", "vert", None),
        ("vert-fill-spv15", "api/use_after_copy/vert_fill.vert", "vert", "spirv1.5"),
        ("frag", "api/use_after_copy/frag.frag", "frag", None),
        ("frag-fill", "api/use_after_copy/frag_fill.frag", "frag", None),
    ]
    lines = ["", "[[case]]", f'name = "{name}"', f'rust_const = "UAC_{name.upper()}"', 'rust_type = "SharedProgram"', "programs = ["]
    for pname, template, stage, spv in programs:
        extra = f', spirv_version = "{spv}"' if spv else ""
        lines.append(f'    {{ name = "{pname}", template = "{template}", stage = "{stage}"{extra} }},')
    lines.append("]")
    lines.append(f"derived = {{ {derived_toml} }}")
    return "\n".join(lines)


def py_str_toml(python_literal):
    """A TOML basic string holding `python_literal` (a Python string expression evaluated by compile_shaders.py)."""
    escaped = python_literal.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def main():
    out = [HEADER]
    for c in combos():
        out.append(entry(*c))
    MANIFEST.write_text("\n".join(out) + "\n")
    print(f"wrote {MANIFEST} with {len(combos())} entries")


if __name__ == "__main__":
    main()
