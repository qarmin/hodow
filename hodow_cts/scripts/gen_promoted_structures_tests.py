#!/usr/bin/env python3
"""Generate src/vkt/tests/api/promoted_structures_tests.rs, `info.get_physical_device_properties2.features.create_device_with_promoted1{1,2,3,4}_structures`.

Upstream's `createDeviceWithPromoted1xStructures` (generated into vkDeviceFeatures2.inl) query the feature structures of every
extension promoted into core version 1.x and create a device with the result chained into VkDeviceCreateInfo. The structure lists are
read from that file and each structure name is checked against vulkanalia.

Usage:
    python3 hodow_cts/scripts/gen_promoted_structures_tests.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_vulkan_feature_consistency_tests import CRATE_DIR, rust_struct, snake, vulkanalia_structs  # noqa: E402

INL = CRATE_DIR / "upstream/external/vulkancts/framework/vulkan/generated/vulkan/vkDeviceFeatures2.inl"
OUT = CRATE_DIR / "src/vkt/tests/api/promoted_structures_tests.rs"


def main() -> int:
    text = INL.read_text()
    structs = vulkanalia_structs()
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/vulkancts/framework/vulkan/generated/vulkan/vkDeviceFeatures2.inl (`createDeviceWithPromoted1{1,2,3,4}Structures`)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2015 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_promoted_structures_tests.py; do not hand-edit.",
        "//",
        "// The feature structures promoted into each core version are queried and the result is passed to vkCreateDevice. Upstream does it on",
        "// an instance of its own; this one uses the context's.",
        "",
        "use vulkanalia::prelude::v1_0::*;",
        "use vulkanalia::vk::InstanceV1_1;",
        "",
        "use super::case_util::add_function_case_no_support;",
        "use crate::tcu::{TestError, TestOutcome, TestStatus};",
        "use crate::vk::VkResultExt;",
        "use crate::vkt::{Context, TestCaseGroup};",
        "",
        "/// The tail of every case: a device created with the queried structures chained into its create info, one queue made idle.",
        "macro_rules! create_device_with {",
        "    ($context:expr, $features2:expr) => {{",
        "        let instance = $context.get_instance();",
        "        let physical_device = $context.get_physical_device();",
        "        let queue_priorities = [1.0f32];",
        "        let queue_infos = [vk::DeviceQueueCreateInfo::builder().queue_family_index(0).queue_priorities(&queue_priorities).build()];",
        "        let info = vk::DeviceCreateInfo::builder().queue_create_infos(&queue_infos).push_next(&mut $features2);",
        "        let device = unsafe { instance.create_device(physical_device, &info, None) }.vk_check(\"vkCreateDevice\")?;",
        "        let result = unsafe {",
        "            let queue = device.get_device_queue(0, 0);",
        "            device.queue_wait_idle(queue)",
        "        };",
        "        unsafe { device.destroy_device(None) };",
        "        result.vk_check(\"vkQueueWaitIdle\")?;",
        "        Ok(TestStatus::pass(\"Pass\"))",
        "    }};",
        "}",
        "",
    ]
    names = []
    for version in ("11", "12", "13", "14"):
        start = text.index(f"tcu::TestStatus createDeviceWithPromoted{version}Structures (Context& context)")
        end = text.index("\ntcu::TestStatus ", start + 10) if "\ntcu::TestStatus " in text[start + 10 :] else len(text)
        body = text[start:end]
        decls = re.findall(r"(Vk\w+)\s+(\w+)\s*=\s*initVulkanStructure\(", body)
        variables = {}
        chain = []
        for c_type, var in decls:
            if c_type == "VkPhysicalDeviceFeatures2":
                continue
            variables[var] = rust_struct(structs, c_type)[0]
            chain.append(var)
        major, minor = version[0], version[1]
        out += [f"fn create_device_with_promoted{version}_structures(context: &Context<'_>) -> TestOutcome {{", f"    let (major, minor, _) = context.api_version();", f"    if (major, minor) < ({major}, {minor}) {{", f'        return Err(TestError::NotSupported("Vulkan {major}.{minor} is not supported".to_string()));', "    }", ""]
        out += [f"    let mut {snake(v)} = vk::{variables[v]}::default();" for v in chain]
        pushes = "".join(f".push_next(&mut {snake(v)})" for v in chain)
        out += [
            f"    let mut features2 = vk::PhysicalDeviceFeatures2::builder(){pushes};",
            "    unsafe { context.get_instance().get_physical_device_features2(context.get_physical_device(), &mut features2) };",
            "",
            "    create_device_with!(context, features2)",
            "}",
            "",
        ]
        names.append(version)

    out += ["/// The four cases, added to the `features` group of `get_physical_device_properties2`.", "pub fn add_promoted_structures_cases(group: &mut TestCaseGroup) {"]
    out += [f'    add_function_case_no_support(group, "create_device_with_promoted{v}_structures", create_device_with_promoted{v}_structures);' for v in names]
    out += ["}", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(CRATE_DIR.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
