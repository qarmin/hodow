#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.sparse_resources.shader_intrinsics.

`SparseShaderIntrinsicsCaseStorage::initPrograms` (OpImageSparseFetch and OpImageSparseRead, a compute shader) and
`SparseShaderIntrinsicsCaseSampledBase::initPrograms` (OpImageSparseSampleExplicitLod, OpImageSparseSampleImplicitLod and OpImageSparseGather,
a vertex, a geometry and a fragment shader) for the formats with a single plane. Each assembly shader is a function of the function, the
image type, the format and whether the Nontemporal operand is used, so there is one entry per such combination, found by `shader_key` in
shader_intrinsics_tests.rs; the vertex shader is one entry (`si_vs`) and the geometry shader depends on the layer count only (`si_gs_<n>`).
The type, constant and name layout of the assembly is the C++'s, line by line, for one plane.

A pure text generator: no glslang, no spirv-as and no cargo.
"""

import json
import re
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "sparse_resources_shader_intrinsics.toml"

HEADER = """# Shader manifest for dEQP-VK.sparse_resources.shader_intrinsics.*
#
# @generated by hodow_cts/scripts/gen_sparse_intrinsics_manifest.py - do not hand-edit.
#
# One entry per (function, image type, format, operand); see the generator for the key scheme.

upstream_source = "external/vulkancts/modules/vulkan/sparse_resources/vktSparseResourcesShaderIntrinsicsStorage.cpp"
rust_module = "sparse_resources/shader_intrinsics_tests"
"""

FORMATS = [
    "R64_SINT", "R32_SINT", "R16_SINT", "R8_SINT", "R64_UINT", "R32_UINT", "R16_UINT", "R8_UINT", "R16_UNORM", "R8_UNORM", "R16_SNORM",
    "R8_SNORM", "R32G32_SINT", "R16G16_SINT", "R8G8_SINT", "R32G32_UINT", "R16G16_UINT", "R8G8_UINT", "R16G16_UNORM", "R8G8_UNORM",
    "R16G16_SNORM", "R8G8_SNORM", "R32G32B32A32_SINT", "R16G16B16A16_SINT", "R8G8B8A8_SINT", "R32G32B32A32_UINT", "R16G16B16A16_UINT",
    "R8G8B8A8_UINT", "R16G16B16A16_UNORM", "R8G8B8A8_UNORM", "R16G16B16A16_SNORM", "R8G8B8A8_SNORM",
]

DIMENSIONS = {
    "2d": "2D 0 0 0",
    "2d_array": "2D 0 1 0",
    "3d": "3D 0 0 0",
    "cube": "Cube 0 0 0",
    "cube_array": "Cube 0 1 0",
}

COORD = {
    "2d": ("%local_int_GlobalInvocationID_x", "%local_ivec2_GlobalInvocationID_xy"),
}

# function -> image types it has cases for
FUNCTION_TYPES = {
    "fetch": ["2d", "2d_array", "3d"],
    "read": ["2d", "2d_array", "cube", "cube_array", "3d"],
    "explicit": ["2d", "2d_array"],
    "implicit": ["2d", "2d_array"],
    "gather": ["2d", "2d_array"],
}

GEOMETRY_LAYERS = [3, 6, 8]


def py(value) -> str:
    return json.dumps(repr(value))


def parse(name: str) -> dict:
    match = re.fullmatch(r"((?:[RGBA]\d+)+)_(SINT|UINT|UNORM|SNORM)", name)
    channels = re.findall(r"([RGBA])(\d+)", match.group(1))
    letters = "".join(c for c, _ in channels)
    bits = int(channels[0][1])
    kind = match.group(2)
    r64 = bits == 64
    order = {"R": "R", "RG": "Rg", "RGBA": "Rgba"}[letters]
    suffix = {"SINT": "i", "UINT": "ui", "SNORM": "Snorm", "UNORM": ""}[kind]
    comp = {"UINT": "%type_uint64" if r64 else "%type_uint", "SINT": "%type_int64" if r64 else "%type_int"}.get(kind, "%type_float")
    vec4 = {"UINT": "%type_u64vec4" if r64 else "%type_uvec4", "SINT": "%type_i64vec4" if r64 else "%type_ivec4"}.get(kind, "%type_vec4")
    return {
        "id": f"{letters.lower()}{bits}{'' if kind == 'UNORM' else {'SINT': 'i', 'UINT': 'ui', 'SNORM': '_snorm'}[kind]}",
        "image_format": f"{order}{bits}{suffix}",
        "r64": r64,
        "comp": comp,
        "vec4": vec4,
    }


R64_CAPABILITIES = 'OpCapability Int64\nOpCapability Int64ImageEXT\nOpExtension "SPV_EXT_shader_image_int64"\n'
R64_TYPES = (
    "%type_int64 = OpTypeInt 64 1\n%type_uint64 = OpTypeInt 64 0\n%type_i64vec2 = OpTypeVector %type_int64  2\n"
    "%type_i64vec3 = OpTypeVector %type_int64  3\n%type_i64vec4 = OpTypeVector %type_int64  4\n"
    "%type_u64vec3 = OpTypeVector %type_uint64 3\n%type_u64vec4 = OpTypeVector %type_uint64 4\n"
)


def op_type_image(fmt: dict, image_type: str, sampled: int) -> str:
    return f"OpTypeImage {fmt['comp']} {DIMENSIONS[image_type]} {sampled} {fmt['image_format']}"


def residency_type(image_type: str) -> str:
    return f"OpTypeImage %type_uint {DIMENSIONS[image_type]} 2 R32ui"


def coord_for(image_type: str, local: tuple) -> str:
    return "%local_ivec2_GlobalInvocationID_xy" if image_type == "2d" else "%local_ivec3_GlobalInvocationID_xyz"


def sampled_coord(image_type: str) -> str:
    return "%local_texCoord_xy" if image_type == "2d" else "%local_texCoord_xyz"


def storage_entry(function: str, image_type: str, fmt: dict, nontemporal: bool) -> tuple:
    operand = "Nontemporal" if nontemporal else ""
    coord = coord_for(image_type, ())
    sparse_op_type = op_type_image(fmt, image_type, 2)
    shares_residency = sparse_op_type == residency_type(image_type)
    if function == "fetch":
        additional = f"|{operand} " if operand else " "
        sparse_op = f"%local_sparse_op_result_plane0 = OpImageSparseFetch %type_struct_int_img_comp_vec4_plane0 %local_image_sparse_plane0 {coord} Lod{additional}%constant_int_0"
        load_type = "%type_image_sparse_with_sampler_fmt"
        pointer_type = "%type_uniformconst_image_sparse_with_sampler_plane0"
    else:
        sparse_op = f"%local_sparse_op_result_plane0 = OpImageSparseRead %type_struct_int_img_comp_vec4_plane0 %local_image_sparse_plane0 {coord} {operand}"
        load_type = "%type_image_sparse_fmt"
        pointer_type = "%type_uniformconst_image_sparse_plane0"
    interface = "%uniform_image_sparse_plane0 %uniform_image_texels_plane0 %uniform_image_residency_plane0 " if nontemporal else ""
    derived = {
        "r64_capabilities": R64_CAPABILITIES if fmt["r64"] else "",
        "interface": interface,
        "r64_types": R64_TYPES if fmt["r64"] else "",
        "img_comp_vec4": fmt["vec4"],
        "op_type_image_sparse": sparse_op_type,
        "op_type_image_sparse_with_sampler": op_type_image(fmt, image_type, 1),
        "residency_type_declaration": "" if shares_residency else f"%type_image_residency = {residency_type(image_type)}\n",
        "residency_type": "%type_image_sparse_fmt" if shares_residency else "%type_image_residency",
        "sparse_pointer_type": pointer_type,
        "sparse_load_type": load_type,
        "sparse_op": sparse_op,
        "coord": coord,
    }
    return derived, "spirv1.6" if nontemporal else "spirv1.0"


def gather_ops(image_type: str, fmt: dict, coord: str, operand: str) -> str:
    result_type = "%type_struct_int_img_comp_vec4"
    image = "%local_image_sparse"
    lines = [
        "%local_image_width = OpCompositeExtract %type_float %local_uniformblock_member_size 0",
        "%local_image_height = OpCompositeExtract %type_float %local_uniformblock_member_size 1",
        "%local_coord_x_bias = OpFDiv %type_float %constant_float_half %local_image_width",
        "%local_coord_y_bias = OpFDiv %type_float %constant_float_half %local_image_height",
    ]
    if image_type == "2d":
        lines.append("%local_coord_bias = OpCompositeConstruct %type_vec2 %local_coord_x_bias %local_coord_y_bias")
        lines.append(f"%local_coord_biased = OpFAdd %type_vec2 {coord} %local_coord_bias")
    else:
        lines.append("%local_coord_bias = OpCompositeConstruct %type_vec3 %local_coord_x_bias %local_coord_y_bias %constant_float_0")
        lines.append(f"%local_coord_biased = OpFAdd %type_vec3 {coord} %local_coord_bias")
    for component, suffix in enumerate("xyzw"):
        lines.append(f"%local_sparse_gather_result_{suffix} = OpImageSparseGather {result_type} {image} %local_coord_biased %constant_int_{component} {operand}")
    lines.append("%local_gather_residency_code = OpCompositeExtract %type_int %local_sparse_gather_result_x 0")
    for suffix in "xyzw":
        lines.append(f"%local_gather_texels_{suffix} = OpCompositeExtract {fmt['vec4']} %local_sparse_gather_result_{suffix} 1")
    for suffix in "xyzw":
        lines.append(f"%local_gather_primary_texel_{suffix} = OpCompositeExtract {fmt['comp']} %local_gather_texels_{suffix} 3")
    lines.append(f"%local_gather_primary_texel = OpCompositeConstruct {fmt['vec4']} %local_gather_primary_texel_x %local_gather_primary_texel_y %local_gather_primary_texel_z %local_gather_primary_texel_w")
    lines.append(f"%local_sparse_op_result = OpCompositeConstruct {result_type} %local_gather_residency_code %local_gather_primary_texel")
    return "\n".join(lines)


def sampled_entry(function: str, image_type: str, fmt: dict, nontemporal: bool) -> tuple:
    operand = "Nontemporal" if nontemporal else ""
    coord = sampled_coord(image_type)
    result_type = "%type_struct_int_img_comp_vec4"
    if function == "explicit":
        additional = f"|{operand} " if operand else " "
        sparse_op = f"%local_sparse_op_result = OpImageSparseSampleExplicitLod {result_type} %local_image_sparse {coord} Lod{additional}%local_uniformblock_member_float_lod"
    elif function == "implicit":
        sparse_op = f"%local_sparse_op_result = OpImageSparseSampleImplicitLod {result_type} %local_image_sparse {coord} {operand}"
    else:
        sparse_op = gather_ops(image_type, fmt, coord, operand)
    if fmt["r64"]:
        texel_store = "%local_img_comp32b = OpSConvert %type_ivec4 %local_img_comp_vec4\nOpStore %output_texel %local_img_comp32b\n"
    else:
        texel_store = "OpStore %output_texel %local_img_comp_vec4\n"
    derived = {
        "r64_capabilities": R64_CAPABILITIES if fmt["r64"] else "",
        "interface": " %uniformconst_image_sparse %uniformblock_instance" if nontemporal else "",
        "r64_types": R64_TYPES if fmt["r64"] else "",
        "img_comp_vec4": fmt["vec4"],
        "output_texel_type": "%type_ivec4" if fmt["r64"] else fmt["vec4"],
        "op_type_image_sparse": op_type_image(fmt, image_type, 1),
        "sparse_op": sparse_op,
        "texel_store": texel_store,
    }
    return derived, "spirv1.6" if nontemporal else "spirv1.0"


def emit(name: str, programs: list, derived: dict) -> str:
    program_text = ", ".join(programs)
    derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
    derived_line = f"derived = {{ {derived_text} }}\n" if derived else ""
    return f"""
[[case]]
name = "{name}"
rust_const = "{name.upper()}"
rust_type = "SharedProgram"
programs = [{program_text}]
{derived_line}"""


def main() -> None:
    out = [HEADER]
    count = 0
    out.append(emit("si_vs", ['{ name = "vertex_shader", template = "sparse_resources/intrinsics/vertex.vert", stage = "vert" }'], {}))
    count += 1
    for layers in GEOMETRY_LAYERS:
        out.append(emit(f"si_gs_{layers}", ['{ name = "geometry_shader", template = "sparse_resources/intrinsics/geometry.geom", stage = "geom" }'], {"max_vertices": 3 * layers, "layers": layers}))
        count += 1
    for function, image_types in FUNCTION_TYPES.items():
        storage = function in ("fetch", "read")
        for image_type in image_types:
            for name in FORMATS:
                fmt = parse(name)
                for nontemporal in (False, True):
                    derived, version = (storage_entry if storage else sampled_entry)(function, image_type, fmt, nontemporal)
                    key = f"si_{function}_{image_type}_{fmt['id']}_{'t' if nontemporal else 'n'}"
                    template = "sparse_resources/intrinsics/storage.spvasm" if storage else "sparse_resources/intrinsics/sampled.spvasm"
                    program_name = "compute" if storage else "fragment_shader"
                    out.append(emit(key, [f'{{ name = "{program_name}", template = "{template}", stage = "asm", spirv_version = "{version}" }}'], derived))
                    count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
