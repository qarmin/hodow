#!/usr/bin/env python3
"""Writes the shader manifests of the fragment_shading_barycentric group.

fragment_shading_barycentric_weights.toml is `FragmentShadingBarycentricTestCase::initWeightPrograms`. fragment_shading_barycentric_data.toml is
`initDataPrograms`, `initMiscDataPrograms` and the tessellation and geometry helpers, expanded for every case of the `data` group:
the GLSL of upstream's `StringTemplate`s is under shaders/src/fragment_shading_barycentric/data/ with the same placeholders, and what upstream
computes into its `attributes` map is the `derived` table of each case. A case name is its test path with the groups joined by `__`,
which is how the Rust side looks a case up.

A pure text generator: no glslang and no cargo. `compile_shaders.py` turns the manifests into SPIR-V (the two qualifier subtypes of the
weights group ship their test fragment shader as SPIR-V assembly, `stage = "asm"`, assembled with spirv-as).
"""

import json
import re
from pathlib import Path

MANIFEST_DIR = Path(__file__).resolve().parent.parent / "shaders" / "manifest"

PERSPECTIVES = [("perspective", "BaryCoord", "smooth"), ("noperspective", "BaryCoordNoPersp", "noperspective")]

SUBTYPES = [
    ("default", lambda bary: f"gl_{bary}EXT", ""),
    ("centroid", lambda bary: f"interpolateAtCentroid(gl_{bary}EXT)", " centroid"),
    ("sample", lambda bary: f"interpolateAtSample(gl_{bary}EXT, gl_SampleID)", " sample"),
    ("offset", lambda bary: f"interpolateAtOffset(gl_{bary}EXT, vec2(gl_SamplePosition - vec2(0.5)))", " sample"),
]

MESH_TOPOLOGIES = ["point_list", "line_list", "triangle_list"]

HEADER = """# Shader manifest for dEQP-VK.fragment_shading_barycentric.weights.*
#
# @generated by hodow_cts/scripts/gen_barycentric_manifest.py - do not hand-edit.
#
# `initWeightPrograms`: a vertex or mesh shader, the reference fragment shader (the colour interpolated by the fixed function with the
# qualifier of the subtype) and the test fragment shader (the colour mixed by hand from the barycentric coordinates). The two
# subtypes that decorate gl_BaryCoord with Centroid or Sample (`msaa_centroid_qualifier`, `msaa_sample_qualifier`) have their test
# fragment shader in SPIR-V assembly, as upstream does, because GLSL cannot qualify the builtin.

upstream_source = "external/vulkancts/modules/vulkan/fragment_shading_barycentric/vktFragmentShadingBarycentricTests.cpp"
rust_module = "fragment_shading_barycentric/weight_tests"
"""


def qualifier_case(name: str, first: dict, declspec: str, variable: str, decoration: str, capabilities: str) -> str:
    const = "WEIGHTS_" + name.upper()
    t = "fragment_shading_barycentric/weights"
    return f"""
[[case]]
name = "{name}"
rust_const = "{const}"
rust_type = "SharedProgram"
programs = [
    {{ name = "{first["name"]}", template = "{t}/{first["template"]}", stage = "{first["stage"]}" }},
    {{ name = "frag_reference", template = "{t}/reference.frag", stage = "frag" }},
    {{ name = "frag_test", template = "{t}/test_qualifier.spvasm", stage = "asm" }},
]
derived = {{ declspec = "'{declspec}'", spirvBaryCoordVariable = "'{variable}'", spirvBaryCoordDecoration = "'{decoration}'", spirvAdditionalCapabilities = {json.dumps(repr(capabilities))} }}
"""


def case(name: str, first: dict, declspec: str, formula: str) -> str:
    const = "WEIGHTS_" + name.upper()
    t = "fragment_shading_barycentric/weights"
    first_line = f'    {{ name = "{first["name"]}", template = "{t}/{first["template"]}", stage = "{first["stage"]}"{first.get("extra", "")} }},'
    return f"""
[[case]]
name = "{name}"
rust_const = "{const}"
rust_type = "SharedProgram"
programs = [
{first_line}
    {{ name = "frag_reference", template = "{t}/reference.frag", stage = "frag" }},
    {{ name = "frag_test", template = "{t}/test.frag", stage = "frag" }},
]
derived = {{ declspec = "'{declspec}'", formula = "'{formula}'" }}
"""


TYPES = ["float", "vec2", "vec3", "vec4", "double", "dvec2", "dvec3", "dvec4", "int", "ivec2", "ivec3", "ivec4", "uint", "uvec2", "uvec3", "uvec4"]

DATA_TOPOLOGIES = [
    "point_list",
    "line_list",
    "line_strip",
    "triangle_list",
    "triangle_strip",
    "triangle_fan",
    "line_list_with_adjacency",
    "line_strip_with_adjacency",
    "triangle_list_with_adjacency",
    "triangle_strip_with_adjacency",
]

PRIMITIVE_FORMULAS = {
    "point_list": "w * y + x",
    "line_list": "y",
    "line_strip": "2*y",
    "triangle_list": "(x < y) ? 0 : 1",
    "triangle_strip": "(x < y) ? 0 : 1",
    "triangle_fan": "(x < y) ? 0 : 1",
    "line_list_with_adjacency": "y",
    "line_strip_with_adjacency": "2*y",
    "triangle_list_with_adjacency": "(x < y) ? 0 : 1",
    "triangle_strip_with_adjacency": "(x < y) ? 0 : 1",
    "patch_list": "(x < y) ? 0 : 1",
}

VERTEX_FORMULAS = {
    "point_list": ("p", "p", "p"),
    "line_list": ("2*p", "2*p+1", "2*p+1"),
    "line_strip": ("p", "p+1", "p+1"),
    "triangle_list": ("3*p", "3*p+1", "3*p+2"),
    "triangle_strip": ("p", "even?p+1:p+2", "even?p+2:p+1"),
    "triangle_fan": ("p+1", "p+2", "0"),
    "line_list_with_adjacency": ("4*p+1", "4*p+2", "4*p+2"),
    "line_strip_with_adjacency": ("p+1", "p+2", "p+2"),
    "triangle_list_with_adjacency": ("6*p", "6*p+2", "6*p+4"),
    "triangle_strip_with_adjacency": ("2*p", "even?2*p+2:2*p+4", "even?2*p+4:2*p+2"),
    "patch_list": ("3*p", "3*p+1", "3*p+2"),
}

VERTEX_FORMULAS_LAST = {
    "triangle_strip": ("even?p:p+1", "even?p+1:p", "p+2"),
    "triangle_fan": ("0", "p+1", "p+2"),
    "triangle_strip_with_adjacency": ("even?2*p:2*p+2", "even?2*p+2:2*p", "2*p+4"),
}

PROVOKING_FORMULAS = {
    "point_list": ("p", "p"),
    "line_list": ("2*p", "2*p+1"),
    "line_strip": ("p", "p+1"),
    "triangle_list": ("3*p", "3*p+2"),
    "triangle_strip": ("p", "p+2"),
    "triangle_fan": ("p+1", "p+2"),
    "line_list_with_adjacency": ("4*p+1", "4*p+2"),
    "line_strip_with_adjacency": ("p+1", "p+2"),
    "triangle_list_with_adjacency": ("6*p", "6*p+4"),
    "triangle_strip_with_adjacency": ("2*p", "2*p+4"),
    "patch_list": ("", ""),
}

INTERPOLATIONS = [("per_vertex", False, False), ("per_vertex_interp", True, False), ("per_vertex_flat", False, True)]


def aggregate_name(aggregate: int) -> str:
    return ["type", "struct", "array2"][aggregate]


def primitive_formula(topology: str, clip: bool) -> str:
    return "((x - 2) * 2 < y) ? 0 : 1" if clip else PRIMITIVE_FORMULAS[topology]


def vertex_formulas(topology: str, provoking_last: bool) -> tuple:
    if provoking_last and topology in VERTEX_FORMULAS_LAST:
        return VERTEX_FORMULAS_LAST[topology]
    return VERTEX_FORMULAS[topology]


def scalar_type(dtype: str) -> tuple:
    """The scalar size and the scalar type name of a GLSL type."""
    size = int(dtype[-1]) if dtype[-1].isdigit() else 1
    for prefix, scalar in (("dvec", "double"), ("ivec", "int"), ("uvec", "uint"), ("vec", "float")):
        if dtype.startswith(prefix):
            return size, scalar
    return 1, dtype


def data_attributes(topology: str, provoking_last: bool, dynamic: bool, clip: bool, aggregate: int, dtype: str, interp: bool, flat: bool) -> dict:
    """What `initDataPrograms` puts in its `attributes` map, with the conditional lines of the templates as ready made blocks."""
    scalar_size, scalar = scalar_type(dtype)
    type_prefix = "DataStruct" if aggregate == 1 else dtype
    type_suffix = f"[{aggregate}]" if aggregate >= 2 else ""
    data_struct = f"struct DataStruct {{{dtype} q;}};" if aggregate == 1 else ""
    multipliers = ["n", "2*n", "4*n", "8*n"][:scalar_size]
    if scalar_size == 1:
        vectored = f"{dtype}(n)"
    else:
        vectored = f"{dtype}(" + ", ".join(f"{scalar}({m})" for m in multipliers) + ")"
    if aggregate == 0:
        value = vectored
    elif aggregate == 1:
        value = f"DataStruct({vectored})"
    else:
        value = f"{dtype}[2]({vectored}, {scalar}(3)*{vectored})"
    component_count = scalar_size * max(aggregate, 1) * 3

    components = ["e${R}"] if scalar_size == 1 else [f"e${{R}}.{c}" for c in "xyzw"[:scalar_size]]
    scalarized = "".join(c + "," for c in components)
    if aggregate == 0:
        deaggregated = scalarized.replace("${R}", "${S}")
    elif aggregate == 1:
        deaggregated = scalarized.replace("${R}", "${S}.q")
    else:
        deaggregated = scalarized.replace("${R}", "${S}[0]") + scalarized.replace("${R}", "${S}[1]")
    unwrap = deaggregated.replace("${S}", "A") + deaggregated.replace("${S}", "B") + deaggregated.replace("${S}", "C")
    expected = unwrap[:-1]
    arrived = expected.replace("e", "v")
    expected_flat = deaggregated.replace("${S}", "FlatV")[:-1]
    arrived_flat = expected_flat.replace("e", "v")
    expected_intrp = deaggregated.replace("${S}", "IntrpV")[:-1]
    arrived_intrp = expected_intrp.replace("e", "v")

    indices = ["pc.n[0]", "pc.n[1]", "pc.n[2]"] if dynamic else ["0", "1", "2"]
    first_formulas = vertex_formulas(topology, provoking_last)
    intrp_formula = ""
    for i in range(max(1, aggregate)):
        acc = f"[{i}]" if aggregate > 1 else ""
        if aggregate == 1:
            acc += ".q"
        intrp_formula += f"eA{acc} * gl_BaryCoordEXT.x + eB{acc} * gl_BaryCoordEXT.y + eC{acc} * gl_BaryCoordEXT.z"
        if i + 1 < aggregate:
            intrp_formula += ", "

    locations_per_input = aggregate if aggregate > 0 else 1
    if scalar == "double":
        locations_per_input *= 2
    used = 0
    loc_interp = loc_flat = 0
    if interp:
        used += locations_per_input
        loc_interp = used
    if flat:
        used += locations_per_input
        loc_flat = used

    flat_formula = PROVOKING_FORMULAS[topology][1 if provoking_last else 0]
    array_ctor = f"{type_prefix}{type_suffix}"

    def fetch(expr_for_index, index):
        if aggregate == 2:
            return f"{array_ctor}({expr_for_index}[{index}][0],{expr_for_index}[{index}][1])"
        return f"{expr_for_index}[{index}]"

    attributes = {
        "dataStruct": data_struct,
        "typePrefix": type_prefix,
        "typeSuffix": type_suffix,
        "value": value,
        "componentCount": str(component_count),
        "expected": expected,
        "arrived": arrived,
        "scalarName": scalar,
        "dynamicIndexing": "layout(push_constant) uniform PushConstant { uint n[3]; } pc;\n" if dynamic else "",
        "primitiveId": primitive_formula(topology, clip),
        "i0": indices[0],
        "i1": indices[1],
        "i2": indices[2],
        "vertexFormula0": "(" + first_formulas[0] + ")",
        "vertexFormula1": "(" + first_formulas[1] + ")",
        "vertexFormula2": "(" + first_formulas[2] + ")",
        "dataAt0": fetch("data", indices[0]),
        "dataAt1": fetch("data", indices[1]),
        "dataAt2": fetch("data", indices[2]),
        "tessDataExpr": f"{array_ctor}(inParam[k].data[0],inParam[k].data[1])" if aggregate == 2 else "inParam[k].data",
        "teseData0": fetch("inData", indices[0]),
        "teseData1": fetch("inData", indices[1]),
        "teseData2": fetch("inData", indices[2]),
        "vertInterpOut": f"layout(location = {loc_interp}) out {type_prefix} dataInterp{type_suffix};\n" if interp else "",
        "vertFlatOut": f"layout(location = {loc_flat}) out {type_prefix} dataFlat{type_suffix};\n" if flat else "",
        "vertInterpAssign": f"    dataInterp    = {value};\n" if interp else "",
        "vertFlatAssign": f"    dataFlat      = {value};\n" if flat else "",
        "meshInterpOut": f"layout(location = {loc_interp}) out {type_prefix} dataInterp[]{type_suffix};\n" if interp else "",
        "meshFlatOut": f"layout(location = {loc_flat}) out {type_prefix} dataFlat[]{type_suffix};\n" if flat else "",
        "meshInterpAssign": f"    dataInterp[vertex]    = {value};\n" if interp else "",
        "meshFlatAssign": f"    dataFlat[vertex]      = {value};\n" if flat else "",
        "fragInterpIn": f"layout(location = {loc_interp}) in {type_prefix} dataIntrp{type_suffix};\n" if interp else "",
        "fragFlatIn": f"layout(location = {loc_flat}) flat in {type_prefix} dataFlat{type_suffix};\n" if flat else "",
        "fragExpectedInterp": (
            f"    {type_prefix} eIntrpV{type_suffix}; {{eIntrpV = {array_ctor}({intrp_formula}); }}\n"
            f"    {scalar} eIntrp[{component_count} / 3] = {{ {expected_intrp} }};\n"
        )
        if interp
        else "",
        "fragExpectedFlat": (
            f"    {type_prefix} eFlatV{type_suffix}; {{ const int n = 1 + ({flat_formula}); eFlatV = {value}; }}\n"
            f"    {scalar} eFlat[{component_count} / 3] = {{ {expected_flat} }};\n"
        )
        if flat
        else "",
        "fragArrivedInterp": (
            f"    {type_prefix} vIntrpV{type_suffix}; {{ vIntrpV = {array_ctor + '(dataIntrp[0],dataIntrp[1])' if aggregate == 2 else 'dataIntrp'}; }}\n"
            f"    {scalar} vIntrp[{component_count} / 3] = {{ {arrived_intrp} }};\n"
        )
        if interp
        else "",
        "fragArrivedFlat": (
            f"    {type_prefix} vFlatV{type_suffix}; {{ vFlatV = {array_ctor + '(dataFlat[0],dataFlat[1])' if aggregate == 2 else 'dataFlat'}; }}\n"
            f"    {scalar} vFlat[{component_count} / 3] = {{ {arrived_flat}}};\n"
        )
        if flat
        else "",
        "fragCheckInterp": f"    for (int i = 0; i<{component_count} / 3; i++)\n        if (abs(eIntrp[i] - vIntrp[i]) < 0.001)\n            mask.y = mask.y | (1<<i);\n" if interp else "",
        "fragCheckFlat": f"    for (int i = 0; i<{component_count} / 3; i++)\n        if (eFlat[i] == vFlat[i])\n            mask.z = mask.z | (1<<i);\n" if flat else "",
    }
    return attributes


def toml_derived(attributes: dict) -> str:
    return "{ " + ", ".join(f"{key} = {json.dumps(repr(value))}" for key, value in attributes.items()) + " }"


DATA_T = "fragment_shading_barycentric/data"


_PLACEHOLDERS: dict = {}


def placeholders(template: str) -> set:
    if template not in _PLACEHOLDERS:
        text = (Path(__file__).resolve().parent.parent / "shaders" / "src" / DATA_T / template).read_text()
        _PLACEHOLDERS[template] = set(re.findall(r"\$\{(\w+)\}", text))
    return _PLACEHOLDERS[template]


def data_case(name: str, programs: list, attributes: dict) -> str:
    needed = set().union(*(placeholders(template) for _, template, _, _ in programs))
    missing = needed - attributes.keys()
    assert not missing, (name, missing)
    attributes = {key: value for key, value in attributes.items() if key in needed}
    entries = ", ".join(
        f'{{ name = "{pname}", template = "{DATA_T}/{template}", stage = "{stage}"{extra} }}' for pname, template, stage, extra in programs
    )
    const = "DATA_" + name.upper()
    return f"""
[[case]]
name = "{name}"
rust_const = "{const}"
rust_type = "BaryDataPrograms"
programs = [ {entries} ]
derived = {toml_derived(attributes)}
"""


MESH_TEMPLATES = {"point_list": "mesh_point_list.mesh", "line_list": "mesh_line_list.mesh", "triangle_list": "mesh_triangle_list.mesh"}

DATA_HEADER = """# Shader manifest for dEQP-VK.fragment_shading_barycentric.data.*
#
# @generated by hodow_cts/scripts/gen_barycentric_manifest.py - do not hand-edit; see the script for what each case is.

upstream_source = "external/vulkancts/modules/vulkan/fragment_shading_barycentric/vktFragmentShadingBarycentricTests.cpp"
rust_module = "fragment_shading_barycentric/data_tests"
"""


def data_manifest() -> str:
    out = [DATA_HEADER]
    plain = lambda template, stage, pname, extra="": (pname, template, stage, extra)  # noqa: E731

    for provoking_last in (False, True):
        for dynamic in (False, True):
            for topology in DATA_TOPOLOGIES:
                for clip in (False, True):
                    if clip and topology != "triangle_list":
                        continue
                    for aggregate in range(3):
                        for dtype in TYPES:
                            for kind, interp, flat in INTERPOLATIONS:
                                if interp and not dtype.startswith(("float", "vec")):
                                    continue
                                for mesh in (True, False):
                                    if mesh and topology not in MESH_TEMPLATES:
                                        continue
                                    path = [
                                        "provoking_last" if provoking_last else "provoking_first",
                                        "dynamic" if dynamic else "static",
                                        topology,
                                        "clip" if clip else "no_clip",
                                        aggregate_name(aggregate),
                                        dtype,
                                        kind,
                                        "mesh_shader" if mesh else "vertex_shader",
                                    ]
                                    name = "__".join(path)
                                    attributes = data_attributes(topology, provoking_last, dynamic, clip, aggregate, dtype, interp, flat)
                                    first = plain(MESH_TEMPLATES[topology], "mesh", "mesh", ', spirv_version = "spirv1.4"') if mesh else plain("data.vert", "vert", "vert")
                                    programs = [first, plain("data.frag", "frag", "frag")]
                                    if provoking_last and topology == "triangle_strip":
                                        forced = data_attributes(topology, False, dynamic, clip, aggregate, dtype, interp, flat)
                                        programs.append(plain("data.vert", "vert", "vert-forced"))
                                        programs.append(plain("data_forced.frag", "frag", "frag-forced"))
                                        attributes.update({f"forced{key[0].upper()}{key[1:]}": value for key, value in forced.items() if key.startswith("vertexFormula")})
                                    out.append(data_case(name, programs, attributes))

    out.append(misc_cases())
    return "".join(out)


def misc_cases() -> str:
    text = []
    programs = [("vert", "misc.vert", "vert", ""), ("frag", "misc.frag", "frag", "")]
    text.append(data_case("misc__pervertex_correctness", programs, {}))
    for subtype, label, topology in (("tess", "with_tess_shader", "patch_list"), ("geom", "with_geom_shader", "triangle_list"), ("tessgeom", "with_tess_geom_shader", "patch_list")):
        for aggregate in range(3):
            for dtype in TYPES:
                attributes = data_attributes(topology, False, False, False, aggregate, dtype, False, False)
                has_tess = subtype in ("tess", "tessgeom")
                has_geom = subtype in ("geom", "tessgeom")
                programs = [("vert", "data.vert", "vert", ""), ("frag", "data_tess.frag" if has_tess else "data.frag", "frag", "")]
                if has_tess:
                    programs += [("tess_ctrl", "tess.tesc", "tesc", ""), ("tess_eval", "tess.tese", "tese", "")]
                if has_geom:
                    programs.append(("geom", "data_tess.geom" if has_tess else "data.geom", "geom", ""))
                name = "__".join(["shader_combos", label, aggregate_name(aggregate), dtype])
                text.append(data_case(name, programs, attributes))
    return "".join(text)


def main() -> None:
    (MANIFEST_DIR / "fragment_shading_barycentric_data.toml").write_text(data_manifest())
    out = [HEADER]
    vert = {"name": "vert", "template": "weights.vert", "stage": "vert"}
    for persp, bary, decl in PERSPECTIVES:
        for sub, formula, qualifier in SUBTYPES:
            out.append(case(f"vertex_{persp}_{sub}", vert, decl + qualifier, formula(bary)))
    for persp, bary, decl in PERSPECTIVES:
        out.append(qualifier_case(f"vertex_{persp}_centroid_qualifier", vert, decl + " centroid", bary + "KHR", "Centroid", ""))
        out.append(qualifier_case(f"vertex_{persp}_sample_qualifier", vert, decl + " sample", bary + "KHR", "Sample", "OpCapability SampleRateShading\n"))
    for topo in MESH_TOPOLOGIES:
        mesh = {"name": "mesh", "template": f"mesh_{topo}.mesh", "stage": "mesh", "extra": ', spirv_version = "spirv1.4"'}
        for persp, bary, decl in PERSPECTIVES:
            out.append(case(f"mesh_{topo}_{persp}", mesh, decl, f"gl_{bary}EXT"))
    (MANIFEST_DIR / "fragment_shading_barycentric_weights.toml").write_text("".join(out))


if __name__ == "__main__":
    main()
