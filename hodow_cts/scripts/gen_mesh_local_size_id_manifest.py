#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.mesh_shader.ext.misc.local_size_id_{mesh,task}.

`LocalSizeIdCase::initPrograms` writes the task and mesh shaders as SPIR-V assembly that gives the work group size with `LocalSizeId` over
specialization constants. The mesh shader differs between the two cases in whether it takes its pixel id from a task payload. The templates are
`shaders/src/mesh_shader/local_size_id/{task,mesh}.spvasm`; the task payload parts of the mesh one are substituted from the tables below, which are the
bodies of the two `if (useTask)` blocks of the C++.

The fragment shader is the generic one `MeshShaderMiscCase::initPrograms` adds, the template of the misc manifest's `frag`.

A pure text generator: no spirv-as and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "mesh_shader_misc_local_size_id.toml"

# `useTask` blocks of `LocalSizeIdCase::initPrograms`
TASK_ENTRY = " %task_data"
TASK_PAYLOAD_DECLS = (
    "\n"
    "%uint_array_32_struct                  = OpTypeStruct %uint_array_32\n"
    "%task_payload_uint_array_32_struct_ptr = OpTypePointer TaskPayloadWorkgroupEXT %uint_array_32_struct\n"
    "%task_data                             = OpVariable %task_payload_uint_array_32_struct_ptr TaskPayloadWorkgroupEXT\n"
    "%task_payload_uint_ptr                 = OpTypePointer TaskPayloadWorkgroupEXT %uint\n"
    "\n"
)
PIXEL_ID_STORE_TASK = (
    "           %td_pixel_id_ptr = OpAccessChain %task_payload_uint_ptr %task_data %int_0 %local_invocation_index_val\n"
    "           %td_pixel_id_val = OpLoad %uint %td_pixel_id_ptr\n"
    "                              OpStore %pixel_id %td_pixel_id_val\n"
)
PIXEL_ID_STORE_MESH = "                              OpStore %pixel_id %local_invocation_index_val\n"

HEADER = """# Shader manifest for dEQP-VK.mesh_shader.ext.misc.local_size_id_*
#
# @generated by hodow_cts/scripts/gen_mesh_local_size_id_manifest.py - do not hand-edit.
#
# SPIR-V assembly with `LocalSizeId`, built for SPIR-V 1.5 with maintenance4 as `LocalSizeIdCase::initPrograms` asks. The task and mesh shaders
# are the SPIR-V ones; the fragment shader is the generic one of the misc cases.

upstream_source = "external/vulkancts/modules/vulkan/mesh_shader/vktMeshShaderMiscTestsEXT.cpp"
rust_module = "mesh_shader/misc_tests"
"""


def toml_str(python_literal):
    return '"' + python_literal.replace("\\", "\\\\").replace('"', '\\"') + '"'


def entry(name, use_task):
    derived = {
        "task_entry": TASK_ENTRY if use_task else "",
        "task_payload_decls": TASK_PAYLOAD_DECLS if use_task else "",
        "pixel_id_store": PIXEL_ID_STORE_TASK if use_task else PIXEL_ID_STORE_MESH,
    }
    items = ", ".join(f"{k} = {toml_str(repr(v))}" for k, v in derived.items())
    t = "mesh_shader/local_size_id"
    programs = [
        f'    {{ name = "mesh", template = "{t}/mesh.spvasm", stage = "asm", spirv_version = "spirv1.5" }},',
        '    { name = "frag", template = "mesh_shader/misc/generic.frag", stage = "frag", spirv_version = "spirv1.5" },',
    ]
    if use_task:
        programs.append(f'    {{ name = "task", template = "{t}/task.spvasm", stage = "asm", spirv_version = "spirv1.5" }},')
    program_text = "\n".join(programs)
    return f"""
[[case]]
name = "{name}"
rust_const = "LOCAL_SIZE_ID_{name.upper()}"
rust_type = "SharedProgram"
programs = [
{program_text}
]
derived = {{ {items} }}
"""


def main():
    MANIFEST.write_text(HEADER + entry("mesh", False) + entry("task", True))
    print(f"wrote {MANIFEST} with 2 entries")


if __name__ == "__main__":
    main()
