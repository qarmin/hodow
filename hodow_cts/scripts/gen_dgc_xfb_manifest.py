#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.graphics.xfb (`XfbTestCase::initPrograms` of vktDGCGraphicsXfbTestsExt.cpp):
one shared program set per (tessellation, geometry) combination, the last pre-rasterization stage carrying the xfb layout. A pure text
generator: no glslang, no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_xfb.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

XFB_PREFIX = "layout(xfb_buffer = 0, xfb_offset = 0) "


def vert(xfb):
    return (
        "#version 460\n"
        + (XFB_PREFIX if xfb else "")
        + "out gl_PerVertex {\n"
        "    vec4 gl_Position;\n"
        "};\n"
        "layout (location=0) in vec4 inPos;\n"
        "void main(void) {\n"
        "    gl_Position = inPos;\n"
        "}\n"
    )


FRAG = (
    "#version 460\n"
    "layout (location=0) out vec4 outColor;\n"
    "void main(void) {\n"
    "    outColor = vec4(0.0, 0.0, 1.0, 1.0);\n"
    "}\n"
)

TESC = (
    "#version 460\n"
    "#extension GL_EXT_tessellation_shader : require\n"
    "layout(vertices=3) out;\n"
    "in gl_PerVertex\n"
    "{\n"
    "    vec4 gl_Position;\n"
    "} gl_in[gl_MaxPatchVertices];\n"
    "out gl_PerVertex\n"
    "{\n"
    "    vec4 gl_Position;\n"
    "} gl_out[];\n"
    "void main() {\n"
    "    gl_out[gl_InvocationID].gl_Position = gl_in[gl_InvocationID].gl_Position;\n"
    "    gl_TessLevelOuter[0] = 1.0;\n"
    "    gl_TessLevelOuter[1] = 1.0;\n"
    "    gl_TessLevelOuter[2] = 1.0;\n"
    "    gl_TessLevelOuter[3] = 1.0;\n"
    "    gl_TessLevelInner[0] = 1.0;\n"
    "    gl_TessLevelInner[1] = 1.0;\n"
    "}\n"
)


def tese(xfb):
    return (
        "#version 460\n"
        "#extension GL_EXT_tessellation_shader : require\n"
        "layout(triangles) in;\n"
        "in gl_PerVertex {\n"
        "    vec4 gl_Position;\n"
        "} gl_in[gl_MaxPatchVertices];\n"
        + (XFB_PREFIX if xfb else "")
        + "out gl_PerVertex {\n"
        "    vec4 gl_Position;\n"
        "};\n"
        "void main() {\n"
        "    gl_Position = (gl_in[0].gl_Position * gl_TessCoord.x + \n"
        "                   gl_in[1].gl_Position * gl_TessCoord.y + \n"
        "                   gl_in[2].gl_Position * gl_TessCoord.z);\n"
        "}\n"
    )


def geom(xfb):
    return (
        "#version 460\n"
        "layout (triangles) in;\n"
        "layout (triangle_strip, max_vertices=3) out;\n"
        "in gl_PerVertex {\n"
        "    vec4 gl_Position;\n"
        "} gl_in[3];\n"
        + (XFB_PREFIX if xfb else "")
        + "out gl_PerVertex {\n"
        "    vec4 gl_Position;\n"
        "};\n"
        "void main() {\n"
        "    for (uint i = 0; i < 3; ++i) {\n"
        "        gl_Position = gl_in[i].gl_Position;\n"
        "        EmitVertex();\n"
        "    }\n"
        "}\n"
    )


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    manifest = (
        "# Shader manifest for dEQP-VK.dgc.ext.graphics.xfb\n"
        "#\n"
        "# @generated by hodow_cts/scripts/gen_dgc_xfb_manifest.py - do not hand-edit.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCGraphicsXfbTestsExt.cpp"\n'
        'rust_module = "dgc/graphics_xfb_tests"\n'
    )
    for use_tess in (False, True):
        for use_geom in (False, True):
            suffix = ("_tess" if use_tess else "") + ("_geom" if use_geom else "")
            xfb_geom = use_geom
            xfb_tess = use_tess and not use_geom
            xfb_vert = not use_geom and not use_tess
            files = [("vert", "vert", vert(xfb_vert)), ("frag", "frag", FRAG)]
            if use_tess:
                files.append(("tesc", "tesc", TESC))
                files.append(("tese", "tese", tese(xfb_tess)))
            if use_geom:
                files.append(("geom", "geom", geom(xfb_geom)))
            programs = []
            for name, stage, text in files:
                template = f"dgc/xfb{suffix}_{name}.{stage}"
                (SRC_DIR / f"xfb{suffix}_{name}.{stage}").write_text(text)
                programs.append(f'{{ name = "{name}", template = "{template}", stage = "{stage}" }}')
            case_name = f"xfb{suffix}"
            manifest += (
                f'\n[[case]]\nname = "{case_name}"\nrust_const = "{case_name.upper()}"\nrust_type = "SharedProgram"\n'
                f"programs = [ {', '.join(programs)} ]\n"
            )
    MANIFEST.write_text(manifest)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
