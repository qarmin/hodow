#!/usr/bin/env python3
"""Writes the shaders of dEQP-VK.api.copy_and_blit.reinterpret.* and shaders/manifest/api_copy_reinterpret.toml.

A transliteration of `ReinterpretTestCase::initPrograms` for the three format pairs and two image types of `createReinterpretationTests`.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / "shaders/src/api/copy_reinterpret"
MANIFEST = ROOT / "shaders/manifest/api_copy_reinterpret.toml"

# name, compressed, block size in bytes, view format components, uint, sint, layout qualifier of the view format, (width, height) in blocks or texels
PAIRS = [
    ("b10g11r11", False, 4, 2, False, False, "rg16f"),
    ("bc1", True, 8, 2, True, False, "rg32ui"),
    ("bc3", True, 16, 4, True, False, "rgba32ui"),
]
# Texels of an uncompressed image; a compressed one is rendered, filled and verified over its extent in blocks (`getSizeInBlocks`, 4x4 texel blocks).
DIMS = [("1d", True, (64, 1)), ("2d", False, (64, 64))]


def color_format_str(components, is_uint, is_sint):
    if components == 1:
        return "uint" if is_uint else "int" if is_sint else "float"
    return ("u" if is_uint else "i" if is_sint else "") + f"vec{components}"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


manifest = [
    "# Shader manifest for dEQP-VK.api.copy_and_blit.reinterpret.*",
    "#",
    "# @generated by hodow_cts/scripts/gen_reinterpret_manifest.py - do not hand-edit.",
    "#",
    "# `ReinterpretTestCase::initPrograms`: a full screen quad, a fragment shader fetching the reinterpreted source texel, and for the compressed formats the compute shaders",
    "# that fill the source and destination images and verify the destination.",
    "",
    'upstream_source = "external/vulkancts/modules/vulkan/api/vktApiCopiesAndBlittingReinterpretTests.cpp"',
    'rust_module = "api/copy_blit_reinterpret_tests"',
    "",
]

for dim_name, is_1d, base_size in DIMS:
    for name, compressed, block_bytes, components, is_uint, is_sint, layout in PAIRS:
        width, height = base_size
        case = f"{dim_name}_{name}"
        tex_coord_type = "float" if is_1d else "vec2"
        vert = [
            "#version 450",
            f"layout(location=0) out {tex_coord_type} texCoord;",
            "vec2 positions[6] = vec2[](",
            "    vec2(-1.0f, 1.0f),",
            "    vec2(1.0f, 1.0f),",
            "    vec2(-1.0f, -1.0f),",
            "    vec2(-1.0f, -1.0f),",
            "    vec2(1.0f, 1.0f),",
            "    vec2(1.0f, -1.0f)",
            ");",
            "",
            "void main() {",
            "    gl_Position = vec4(positions[gl_VertexIndex], 0.0, 1.0);",
            "    texCoord.x = (positions[gl_VertexIndex].x < 0.0) ? 0.0 : positions[gl_VertexIndex].x;",
        ]
        if not is_1d:
            vert.append("    texCoord.y = (positions[gl_VertexIndex].y < 0.0) ? 0.0 : positions[gl_VertexIndex].y;")
        vert.append("}")
        write(SHADERS / case / "reinterpret.vert", "\n".join(vert) + "\n")

        if compressed:
            width, height = width // 4, max(height // 4, 1)
        data_type = color_format_str(components, is_uint, is_sint)
        comps = {1: "r", 2: "rg", 3: "rgb", 4: "rgba"}[components]
        sign = ("u" if is_uint else "i") if (is_uint or is_sint) else ""
        sampler = "sampler1D" if is_1d else "sampler2D"
        fetch = ("int" if is_1d else "ivec2") + f"(texCoord.x * {width}" + ("" if is_1d else f", texCoord.y * {height}") + ")"
        frag = [
            "#version 450",
            f"layout(set=0, binding=0) uniform {sign}{sampler} tex;",
            f"layout(location=0) in {tex_coord_type} texCoord;",
            f"layout(location=0) out {data_type} outColor;",
            "",
            "void main() {",
            f"    {sign}vec4 texColor = texelFetch(tex, {fetch}, 0);",
            f"    outColor = {data_type}(texColor.{comps});",
            "}",
        ]
        write(SHADERS / case / "reinterpret.frag", "\n".join(frag) + "\n")

        programs = [
            f'    {{ name = "vert", template = "api/copy_reinterpret/{case}/reinterpret.vert", stage = "vert" }},',
            f'    {{ name = "frag", template = "api/copy_reinterpret/{case}/reinterpret.frag", stage = "frag" }},',
        ]
        if compressed:
            is_64b = block_bytes == 8
            image_type = "image1D" if is_1d else "image2D"
            fetch_coord = "int(gl_GlobalInvocationID.x)" if is_1d else "ivec2(gl_GlobalInvocationID.xy)"
            bc1_red4 = "4160813056u, 0u, 4160813056u, 0u"
            bc1_blue2 = "2031647, 0u"
            bc1_blue4 = bc1_blue2 + ", " + bc1_blue2
            bc3_red4 = "4294967295u, 4294967295u, 4160813056u, 0u"
            bc3_blue4 = "4294967295u, 4294967295u, 2031647, 0u"
            red = bc1_red4 if is_64b else bc3_red4
            blue = bc1_blue4 if is_64b else bc3_blue4
            comp_fill = [
                "#version 450",
                f"layout(set = 0, binding = 0, {layout}) uniform highp {sign}{image_type} srcImg;",
                f"layout(set = 0, binding = 1, {layout}) uniform highp {sign}{image_type} dstImg;",
                "layout (local_size_x = 1, local_size_y = 1, local_size_z = 1) in;",
                "void main() {",
                f"    {sign}vec4 srcColor = {sign}vec4({blue}); // blue",
                f"    {sign}vec4 dstColor = {sign}vec4({red}); // red",
                f"    imageStore(srcImg, {fetch_coord}, srcColor);",
                f"    imageStore(dstImg, {fetch_coord}, dstColor);",
                "}",
            ]
            write(SHADERS / case / "reinterpret_fill.comp", "\n".join(comp_fill) + "\n")
            blue_verify = bc1_blue2 if is_64b else bc3_blue4
            comp_verify = [
                "#version 450",
                f"layout(set = 0, binding = 0, {layout}) uniform highp {sign}{image_type} dstImg;",
                f"layout(set = 0, binding = 1, rgba8) uniform highp {image_type} outputImg;",
                "layout (local_size_x = 1, local_size_y = 1, local_size_z = 1) in;",
                "void main() {",
                f"    {data_type} color = {data_type}({blue_verify}); // blue",
                "    vec4 green = vec4(0.0f, 1.0f, 0.0f, 1.0f);",
                "    vec4 red = vec4(1.0f, 0.0f, 0.0f, 1.0f);",
                f"    {data_type} dstColor = imageLoad(dstImg, {fetch_coord}).{comps};",
                f"    imageStore(outputImg, {fetch_coord}, color == dstColor ? green : red );",
                "}",
            ]
            write(SHADERS / case / "reinterpret_verify.comp", "\n".join(comp_verify) + "\n")
            programs.append(f'    {{ name = "compFill", template = "api/copy_reinterpret/{case}/reinterpret_fill.comp", stage = "comp" }},')
            programs.append(f'    {{ name = "compVerify", template = "api/copy_reinterpret/{case}/reinterpret_verify.comp", stage = "comp" }},')

        manifest += ["[[case]]", f'name = "{case}"', f'rust_const = "REINTERPRET_{case.upper()}"', 'rust_type = "SharedProgram"', "programs = ["] + programs + ["]", ""]

MANIFEST.write_text("\n".join(manifest))
print("wrote", MANIFEST)
