#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.graphics.misc.{interface_matching,ies_replace,ies_add}[_shader_objects]
(MultiIfaceCase::initPrograms and genIfaceShaders of vktDGCGraphicsMiscTestsExt.cpp). A pure text generator."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_iface.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

# Per quadrant: {location: (name, value)}, then the fragment shader red, green, blue and alpha.
INTERFACES = [
    ({2: ("red", "inPos.x")}, ("red", "0.0", "0.0", "1.0")),
    (
        {5: ("red", "1.0"), 6: ("green", "inPos.x"), 10: ("blue", "0.5"), 11: ("alpha", "inPos.y")},
        ("red", "green", "blue", "alpha"),
    ),
    ({1: ("red", "0.5"), 4: ("blue", "inPos.x")}, ("red", "1.0", "blue", "1.0")),
    ({0: ("red", "inPos.y"), 1: ("green", "inPos.x"), 8: ("blue", "1.0")}, ("red", "green", "blue", "1.0")),
]


def vert(locations):
    text = (
        "#version 460\n"
        "layout (location=0) in vec4 inPos;\n"
        "layout (push_constant, std430) uniform PCBlock { vec4 scale; vec4 offset; } pc;\n"
    )
    for location in sorted(locations):
        text += f"layout (location={location}) out float {locations[location][0]};\n"
    text += "void main (void) {\n"
    for location in sorted(locations):
        name, value = locations[location]
        text += f"    {name} = {value};\n"
    text += "    gl_Position = inPos * pc.scale + pc.offset;\n}\n"
    return text


def frag(locations, colors):
    text = "#version 460\nlayout (location=0) out vec4 outColor;\n"
    for location in sorted(locations):
        text += f"layout (location={location}) in float {locations[location][0]};\n"
    text += "void main (void) {\n"
    text += f"    outColor = vec4({colors[0]}, {colors[1]}, {colors[2]}, {colors[3]});\n}}\n"
    return text


FILES = {}
PROGRAMS = []
for index, (locations, colors) in enumerate(INTERFACES):
    FILES[f"iface_vert{index}.vert"] = vert(locations)
    FILES[f"iface_frag{index}.frag"] = frag(locations, colors)
    PROGRAMS.append(f'{{ name = "vert{index}", template = "dgc/iface_vert{index}.vert", stage = "vert" }}')
    PROGRAMS.append(f'{{ name = "frag{index}", template = "dgc/iface_frag{index}.frag", stage = "frag" }}')

MANIFEST_TEXT = f"""# Shader manifest for dEQP-VK.dgc.ext.graphics.misc.{{interface_matching,ies_replace,ies_add}}[_shader_objects]
#
# @generated by hodow_cts/scripts/gen_dgc_iface_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCGraphicsMiscTestsExt.cpp"
rust_module = "dgc/graphics_misc_iface_tests"

[[case]]
name = "iface"
rust_const = "IFACE"
rust_type = "SharedProgram"
programs = [ {", ".join(PROGRAMS)} ]
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in FILES.items():
        (SRC_DIR / name).write_text(text)
    MANIFEST.write_text(MANIFEST_TEXT)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
