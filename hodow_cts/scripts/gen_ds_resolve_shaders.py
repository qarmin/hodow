#!/usr/bin/env python3
"""Generate the renderpasses depth_stencil_resolve shaders and their manifest.

Only three parameters reach the GLSL: whether the framebuffer is layered (which adds a
geometry shader that fans the quad out over three layers), whether the case reads back
depth or stencil, and - for stencil - whether the sample mask picks the sample instead
of a push constant. Five shaders cover all 18003 cases.

Usage:
    python3 hodow_cts/scripts/gen_ds_resolve_shaders.py
"""

from __future__ import annotations

import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = CRATE_DIR.parent
SRC_DIR = CRATE_DIR / "shaders" / "src" / "renderpass" / "generated"
MANIFEST = CRATE_DIR / "shaders" / "manifest" / "renderpass_ds_resolve.toml"

# `const uint32_t layerCount = 3` - the layered case resolves three layers.
LAYER_COUNT = 3

VERT = (
    "#version 450\n"
    "out gl_PerVertex {\n"
    "\tvec4 gl_Position;\n"
    "};\n"
    "highp float;\n"
    "void main (void) {\n"
    "\tgl_Position = vec4(((gl_VertexIndex + 2) / 3) % 2 == 0 ? -1.0 : 1.0,\n"
    "\t                   ((gl_VertexIndex + 1) / 3) % 2 == 0 ? -1.0 : 1.0, 0.0, 1.0);\n"
    "}\n"
)

GEOM = (
    "#version 450\n"
    "highp float;\n"
    "\n"
    "layout(triangles) in;\n"
    f"layout(triangle_strip, max_vertices = {3 * 2 * LAYER_COUNT}) out;\n"
    "\n"
    "in gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "} gl_in[];\n"
    "\n"
    "out gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "};\n"
    "\n"
    "void main (void) {\n"
    f"    for (int layerNdx = 0; layerNdx < {LAYER_COUNT}; ++layerNdx) {{\n"
    "        for(int vertexNdx = 0; vertexNdx < gl_in.length(); vertexNdx++) {\n"
    "            gl_Position = gl_in[vertexNdx].gl_Position;\n"
    "            gl_Layer    = layerNdx;\n"
    "            EmitVertex();\n"
    "        };\n"
    "        EndPrimitive();\n"
    "    };\n"
    "}\n"
)

# Each sample gets one of four depth values, chosen so min, max, average and sample-zero
# all land on different numbers - which is what makes the resolve mode observable.
FRAG_DEPTH = (
    "#version 450\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "void main (void)\n"
    "{\n"
    "  float sampleIndex = float(gl_SampleID);\n"
    "  float valueIndex = round(mod(sampleIndex, 4.0));\n"
    "  float value = valueIndex + 2.0;\n"
    "  value = round(exp2(value));\n"
    "  bool condition = (int(value) == 8);\n"
    "  value = round(value - float(condition) * 6.0);\n"
    "  gl_FragDepth = value / 100.0;\n"
    "}\n"
)

FRAG_STENCIL_SAMPLE_MASK = (
    "#version 450\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "void main (void)\n"
    "{\n"
    "  gl_FragDepth = 0.5;\n"
    "}\n"
)

FRAG_STENCIL = (
    "#version 450\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "layout(push_constant) uniform PushConstant {\n"
    "  highp int sampleID;\n"
    "} pushConstants;\n"
    "void main (void)\n"
    "{\n"
    "  if(gl_SampleID != pushConstants.sampleID)\n"
    "    discard;\n"
    "  gl_FragDepth = 0.5;\n"
    "}\n"
)


# `MiscTestCase::initPrograms` - a full-screen triangle strip at depth 0.6, with a
# fragment shader that writes nothing (only depth/stencil matter here).
MISC_VERT = (
    "#version 450\n"
    "void main (void)\n"
    "{\n"
    "  const float x = (-1.0+2.0*((gl_VertexIndex & 2)>>1));\n"
    "  const float y = ( 1.0-2.0* (gl_VertexIndex % 2));\n"
    "  gl_Position = vec4(x, y, 0.6, 1.0);\n"
    "}\n"
)

MISC_FRAG = "#version 450\nvoid main (void)\n{\n}\n"


def main() -> int:
    SRC_DIR.mkdir(parents=True, exist_ok=True)

    cases = [
        (
            "ds_resolve",
            "DS_RESOLVE_PROGRAMS",
            [
                ("quad_vert", "vert", VERT),
                ("quad_geom", "geom", GEOM),
                ("quad_frag_depth", "frag", FRAG_DEPTH),
                ("quad_frag_stencil", "frag", FRAG_STENCIL),
                ("quad_frag_stencil_sample_mask", "frag", FRAG_STENCIL_SAMPLE_MASK),
            ],
        ),
        (
            "ds_resolve_misc",
            "DS_RESOLVE_MISC_PROGRAMS",
            [
                ("vert", "vert", MISC_VERT),
                ("frag", "frag", MISC_FRAG),
            ],
        ),
    ]

    lines = [
        "# Shader manifest for dEQP-VK.renderpasses.renderpass2.depth_stencil_resolve.*",
        "#",
        "# Generated by scripts/gen_ds_resolve_shaders.py together with the GLSL it names;",
        "# do not hand-edit either. One case holding all five: which of them a test uses is",
        "# decided by three independent parameters, so enumerating the sets would be more",
        "# entries than there are shaders. The `misc` group is a separate upstream test",
        "# class with its own two shaders, so it gets its own case.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/renderpass/vktRenderPassDepthStencilResolveTests.cpp"',
        'rust_module = "renderpass/depth_stencil_resolve_tests"',
    ]
    total = 0
    for case_name, rust_const, programs in cases:
        lines += [
            "",
            "[[case]]",
            f'name = "{case_name}"',
            f'rust_const = "{rust_const}"',
            'rust_type = "DsResolvePrograms"',
            "programs = [",
        ]
        for name, stage, source in programs:
            (SRC_DIR / f"{case_name}_{name}.{stage}").write_text(source)
            lines.append(f'    {{ name = "{name}", template = "renderpass/generated/{case_name}_{name}.{stage}", stage = "{stage}" }},')
        lines += ["]"]
        total += len(programs)
    lines += [""]

    MANIFEST.write_text("\n".join(lines))
    print(f"wrote {MANIFEST.relative_to(REPO_DIR)} and {total} shaders in {SRC_DIR.relative_to(REPO_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
