#!/usr/bin/env python3
"""Writes shaders/manifest/spirv_assembly_physical_storage_buffer.toml: dEQP-VK.spirv_assembly.instruction.compute.physical_storage_buffer.{push_constants,push_constants_function,addrs_in_ssbo,ptr_access_chain_from_ubo}
(vktSpvAsmPhysicalStorageBufferPointerTests.cpp). The three assembly programs are the raw string literals of the C++ in order (push constants shared by two cases, addresses in an SSBO, ptr access chain from a UBO).

    python3 hodow_cts/scripts/gen_spirv_assembly_physical_storage_buffer_manifest.py

A pure text generator: no spirv-as and no cargo.
"""

import json
import re
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "spirv_assembly_physical_storage_buffer.toml"
SOURCE = "external/vulkancts/modules/vulkan/spirv_assembly/vktSpvAsmPhysicalStorageBufferPointerTests.cpp"
TEMPLATE = "spirv_assembly/source.asm"

CASES = [
    ("push_constants", 0),
    ("push_constants_function", 0),
    ("addrs_in_ssbo", 1),
    ("ptr_access_chain_from_ubo", 2),
]


def main():
    text = (CRATE / "upstream" / SOURCE).read_text(encoding="utf-8")
    programs = re.findall(r'R"\((.*?)\)"\)', text, flags=re.S)
    assert len(programs) == 3, len(programs)
    out = [
        "# Shader manifest for dEQP-VK.spirv_assembly.instruction.compute.physical_storage_buffer.*\n#\n"
        "# @generated by hodow_cts/scripts/gen_spirv_assembly_physical_storage_buffer_manifest.py - do not hand-edit; `spec` is the PassMethod of a case.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "spirv_assembly/physical_storage_buffer_tests"\n'
    ]
    for name, index in CASES:
        const = "PSB_" + name.upper()
        out.append(
            f'\n[[case]]\nname = "{name}"\nrust_const = "{const}"\nrust_type = "PhysicalStorageBufferCase"\n'
            f'programs = [ {{ name = "comp", template = "{TEMPLATE}", stage = "asm", spirv_version = "spirv1.4" }} ]\n'
            f'params = {{ spec = {{ type = "str", value = "method={name}" }} }}\n'
            f"derived = {{ source = {json.dumps(repr(programs[index]))} }}\n"
        )
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {len(CASES)} cases")


if __name__ == "__main__":
    main()
