#!/usr/bin/env python3
"""Writes src/vkt/tests/api/unsupported_feature_names.rs: the `create_device_unsupported_features` case names the mustpass lists that
feature_struct_list.rs has no struct description for (vendor structs the vendored vkDeviceFeatures2.inl does not carry). They are registered as
stubs; every other name is a real case built from FEATURE_STRUCTS.

Usage: python3 hodow_cts/scripts/gen_unsupported_feature_names.py [--cts-dir tmp/VK-GL-CTS]
"""

import argparse
import re
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
REPO = CRATE.parent
OUT = CRATE / "src" / "vkt" / "tests" / "api" / "unsupported_feature_names.rs"
STRUCTS = CRATE / "src" / "vkt" / "tests" / "api" / "feature_struct_list.rs"
VENDOR_STRUCTS = CRATE / "src" / "vkt" / "tests" / "api" / "unsupported_feature_vendor_structs.rs"
PREFIX = "dEQP-VK.api.device_init.create_device_unsupported_features."


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cts-dir", type=Path, default=REPO / "tmp" / "VK-GL-CTS")
    args = ap.parse_args()

    mustpass = args.cts_dir / "external/vulkancts/mustpass/main/vk-default/api.txt"
    known = set(re.findall(r'name: "([^"]+)"', STRUCTS.read_text()))
    if VENDOR_STRUCTS.exists():
        known |= set(re.findall(r'name: "([^"]+)"', VENDOR_STRUCTS.read_text()))
    names = []
    for line in mustpass.read_text().splitlines():
        line = line.strip()
        if line.startswith(PREFIX):
            name = line.removeprefix(PREFIX)
            if name != "core" and name not in known:
                names.append(name)

    lines = [
        "// @generated by hodow_cts/scripts/gen_unsupported_feature_names.py - do not hand-edit.",
        "//",
        "// `create_device_unsupported_features` cases without a struct description in feature_struct_list.rs.",
        "",
        "pub static STUBBED_FEATURE_NAMES: &[&str] = &[",
    ]
    lines += [f'    "{n}",' for n in names]
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(names)} names -> {OUT}")


if __name__ == "__main__":
    main()
