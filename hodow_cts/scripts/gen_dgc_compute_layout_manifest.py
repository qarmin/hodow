#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.compute.layout (`LayoutTestCase::initPrograms`), one program per test type.
A pure text generator: no glslang and no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_compute_layout.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

LOCAL_INVOCATIONS = 64

TEST_TYPES = [
    "push_dispatch",
    "complementary_push_dispatch",
    "complementary_push_index_dispatch",
    "multi_push_dispatch",
    "offset_execution_set_dispatch",
    "execution_set_dispatch",
    "execution_set_push_dispatch",
    "execution_set_index_push_dispatch",
    "execution_set_complementary_push_dispatch",
]


def comp(test_type):
    sequence_index = test_type in ("complementary_push_index_dispatch", "execution_set_index_push_dispatch")
    complementary_push = test_type in ("complementary_push_dispatch", "complementary_push_index_dispatch")
    complementary_push_with_es = test_type == "execution_set_complementary_push_dispatch"

    constants = ""
    if test_type in ("push_dispatch", "multi_push_dispatch") or complementary_push:
        constants += (
            "layout (push_constant, std430) uniform PushConstantBlock {\n"
            "    uint dispatchOffset;\n"
            "    uint skipIndex;\n"
            "    uint valueOffset;\n"
            + ("    uint valueOffset2;\n" if complementary_push else "")
            + ("    uint sequenceIndex;\n" if sequence_index else "")
            + "} pc;\n"
        )
        dispatch_offset_prefix = skip_index_prefix = value_offset_prefix = value_offset2_prefix = "pc."
    elif test_type in ("execution_set_dispatch", "offset_execution_set_dispatch"):
        constants += (
            "layout (constant_id=0) const uint pc_dispatchOffset = 0u;\n"
            "layout (constant_id=1) const uint pc_skipIndex = 0u;\n"
            "layout (constant_id=2) const uint pc_valueOffset = 0u;\n"
        )
        dispatch_offset_prefix = skip_index_prefix = value_offset_prefix = "pc_"
        value_offset2_prefix = ""
    else:
        constants += (
            "layout (push_constant, std430) uniform PushConstantBlock {\n"
            + ("    uint valueOffset2;\n" if complementary_push_with_es else "")
            + "    uint dispatchOffset;\n"
            "    uint skipIndex;\n"
            + ("    uint sequenceIndex;\n" if sequence_index else "")
            + "} pc;\n"
            "layout (constant_id=2) const uint pc_valueOffset = 0u;\n"
        )
        dispatch_offset_prefix = skip_index_prefix = value_offset2_prefix = "pc."
        value_offset_prefix = "pc_"

    text = (
        "#version 460\n"
        f"layout (local_size_x={LOCAL_INVOCATIONS}, local_size_y=1, local_size_z=1) in;\n"
        "layout (set=0, binding=0, std430) buffer StorageBlock { uint values[]; } storageBuffer;\n"
        + constants
        + "void main (void) {\n"
        "    const uint workGroupIndex = gl_NumWorkGroups.x * gl_NumWorkGroups.y * gl_WorkGroupID.z + gl_NumWorkGroups.x * gl_WorkGroupID.y + gl_WorkGroupID.x;\n"
        f"    const uint valueIndex = {dispatch_offset_prefix}dispatchOffset + workGroupIndex * gl_WorkGroupSize.x + gl_LocalInvocationIndex;\n"
        f"    const uint storageValue = {value_offset_prefix}valueOffset + (workGroupIndex << 10) + gl_LocalInvocationIndex\n"
    )
    if complementary_push or complementary_push_with_es:
        text += f"        + {value_offset2_prefix}valueOffset2\n"
    if sequence_index:
        text += "        + pc.sequenceIndex\n"
    text += (
        "        ;\n"
        f"    if ({skip_index_prefix}skipIndex != gl_LocalInvocationIndex) {{\n"
        "        storageBuffer.values[valueIndex] = storageValue;\n"
        "    }\n"
        "}\n"
    )
    return text


HEADER = """# Shader manifest for dEQP-VK.dgc.ext.compute.layout
#
# @generated by hodow_cts/scripts/gen_dgc_compute_layout_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCComputeLayoutTestsExt.cpp"
rust_module = "dgc/compute_layout_tests"
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    out = [HEADER]
    for test_type in TEST_TYPES:
        key = f"layout_{test_type}"
        (SRC_DIR / f"{key}.comp").write_text(comp(test_type))
        out.append(
            f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [ {{ name = "comp", template = "dgc/{key}.comp", stage = "comp" }} ]
"""
        )
    MANIFEST.write_text("".join(out))
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
