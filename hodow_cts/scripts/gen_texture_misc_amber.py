#!/usr/bin/env python3
"""Writes the shaders and the manifest of the two single Amber scripts of dEQP-VK.texture: conversion.ufloat_negative_values.b10g11r11 and shadow.texel_replacement.d32_sfloat.

The compute shaders (`compute_shader`, `compute_shader_verify`) of the first and the fragment shader of the second are read from the vendored scripts; the vertex shader of the
second is Amber's PASSTHROUGH. Written: shaders/manifest/texture_misc_amber.toml and shaders/src/texture_misc_amber/.

Run from hodow_cts/:  python3 scripts/gen_texture_misc_amber.py   (then `just cts-shaders`)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/texture"
SRC = ROOT / "shaders" / "src" / "texture_misc_amber"
MANIFEST = ROOT / "shaders" / "manifest" / "texture_misc_amber.toml"

PASSTHROUGH_VERTEX = "#version 430\nlayout(location = 0) in vec4 position;\nvoid main() {\n  gl_Position = position;\n}\n"


def shader(text, kind, name):
    lines = text.splitlines()
    for ndx, line in enumerate(lines):
        if line.startswith(f"SHADER {kind} {name} "):
            body = []
            for rest in lines[ndx + 1 :]:
                if rest.strip() == "END":
                    return "\n".join(body) + "\n"
                body.append(rest)
    raise RuntimeError(name)


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    ufloat = (AMBER / "conversion/ufloat_negative_values/b10g11r11-ufloat-pack32.amber").read_text()
    shadow = (AMBER / "shadow/texel_replacement/d32_sfloat.amber").read_text()
    cases = [
        ("ufloat_negative_values", [("comp", "comp", shader(ufloat, "compute", "compute_shader")), ("verify", "comp", shader(ufloat, "compute", "compute_shader_verify"))]),
        ("texel_replacement", [("vert", "vert", PASSTHROUGH_VERTEX), ("frag", "frag", shader(shadow, "fragment", "frag_shader"))]),
    ]
    out = [
        "# Shader manifest for dEQP-VK.texture.conversion.ufloat_negative_values and texture.shadow.texel_replacement.",
        "#",
        "# @generated by hodow_cts/scripts/gen_texture_misc_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/texture/conversion/ufloat_negative_values/b10g11r11-ufloat-pack32.amber"',
        'rust_module = "texture/misc_amber_tests"',
        "",
    ]
    for key, programs in cases:
        out += ["[[case]]", f'name = "{key}"', f'rust_const = "{key.upper()}"', 'rust_type = "SharedProgram"', "programs = ["]
        for name, stage, source in programs:
            (SRC / f"{key}_{name}.{stage}").write_text(source)
            out.append(f'    {{ name = "{name}", template = "texture_misc_amber/{key}_{name}.{stage}", stage = "{stage}" }},')
        out += ["]", ""]
    MANIFEST.write_text("\n".join(out))


if __name__ == "__main__":
    main()
