#!/usr/bin/env python3
"""Writes shaders/manifest/pipeline_m10_resolve.toml and its GLSL sources.

`Maint10ResolveCase::initPrograms` builds a vertex and a fragment shader from four booleans/enums: multiLayer, the fragment output type
(none for depth/stencil, uvec4, ivec4, vec4), resolveDepth and resolveStencil. Each distinct combination is one manifest case.
"""
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
SRC = CRATE / "shaders" / "src" / "pipeline" / "m10_resolve"
MANIFEST = CRATE / "shaders" / "manifest" / "pipeline_m10_resolve.toml"
SAMPLES = 4


def vert(multi_layer: bool) -> str:
    return (
        "#version 460\n"
        + ("#extension GL_ARB_shader_viewport_layer_array : require\n" if multi_layer else "")
        + "const vec4 vertices[] = vec4[](\n"
        "    vec4(-1.0, -1.0, 0.0, 1.0),\n"
        "    vec4(-1.0,  3.0, 0.0, 1.0),\n"
        "    vec4( 3.0, -1.0, 0.0, 1.0)\n"
        ");\n"
        "void main (void) {\n"
        "    gl_Position = vertices[gl_VertexIndex % 3];\n"
        + ("    gl_Layer = gl_InstanceIndex;\n" if multi_layer else "")
        + "}\n"
    )


def frag(multi_layer: bool, out_type: str, depth: bool, stencil: bool) -> str:
    return (
        "#version 460\n"
        + ("#extension GL_ARB_shader_stencil_export : require\n" if stencil else "")
        + ("" if not out_type else f"layout (location=0) out {out_type} outColor;\n")
        + "struct PixelData {\n"
        f"    {out_type or 'vec4'} colorValue;\n"
        "    vec4 dsValue; // .x = depth, .y = stencil (as float)\n"
        "};\n"
        "layout (set=0, binding=0) readonly buffer PixelValuesBlock {\n"
        "    PixelData values[];\n"
        "} pixels;\n"
        "layout (push_constant, std430) uniform PushConstantBlock {\n"
        "    float width;\n"
        "    float height;\n"
        "} pc;\n"
        "void main (void) {\n"
        + f"    const uint prevPixels = {'uint(pc.width * pc.height) * uint(gl_Layer)' if multi_layer else '0u'};\n"
        "    const uint pixelIndex = uint(floor(gl_FragCoord.y) * pc.width + floor(gl_FragCoord.x)) + prevPixels;\n"
        f"    const uint sampleIndex = pixelIndex * {SAMPLES} + uint(gl_SampleID);\n"
        + ("" if not out_type else "    outColor = pixels.values[sampleIndex].colorValue;\n")
        + ("    gl_FragDepth = pixels.values[sampleIndex].dsValue.x;\n" if depth else "")
        + ("    gl_FragStencilRefARB = int(pixels.values[sampleIndex].dsValue.y);\n" if stencil else "")
        + "}\n"
    )


def main() -> None:
    SRC.mkdir(parents=True, exist_ok=True)
    (SRC / "vert_ml0.vert").write_text(vert(False))
    (SRC / "vert_ml1.vert").write_text(vert(True))
    out = [
        "# Shader manifest for dEQP-VK.pipeline.*.multisample.m10_resolve.*",
        "#",
        "# @generated by hodow_cts/scripts/gen_m10_resolve_manifest.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/pipeline/vktPipelineMultisampleResolveMaint10Tests.cpp"',
        'rust_module = "pipeline/multisample_resolve_maint10_tests"',
        "",
    ]
    variants = []
    for multi_layer in (False, True):
        for out_type, depth, stencil in [
            ("uvec4", False, False),
            ("ivec4", False, False),
            ("vec4", False, False),
            ("", True, False),
            ("", False, True),
            ("", True, True),
        ]:
            variants.append((multi_layer, out_type, depth, stencil))
    for multi_layer, out_type, depth, stencil in variants:
        key = f"ml{int(multi_layer)}_{out_type or 'none'}_d{int(depth)}_s{int(stencil)}"
        (SRC / f"frag_{key}.frag").write_text(frag(multi_layer, out_type, depth, stencil))
        vert_extra = ', spirv_version = "spirv1.4"' if multi_layer else ""
        out += [
            "[[case]]",
            f'name = "{key}"',
            f'rust_const = "M10_{key.upper()}"',
            'rust_type = "SharedProgram"',
            "programs = [",
            f'    {{ name = "vert", template = "pipeline/m10_resolve/vert_ml{int(multi_layer)}.vert", stage = "vert"{vert_extra} }},',
            f'    {{ name = "frag", template = "pipeline/m10_resolve/frag_{key}.frag", stage = "frag" }},',
            "]",
            "",
        ]
    MANIFEST.write_text("\n".join(out))


if __name__ == "__main__":
    main()
