#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.graphics.misc.tg_push_constants_* (`tessGeomPushConstantsInitPrograms` of
vktDGCGraphicsMiscTestsExt.cpp), two shared program sets (tess, geom). A pure text generator: no glslang, no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_graphics_misc_tg_pc.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

PC_DECL = "layout (push_constant, std430) uniform PCBlock { float red; float green; float blue; } pc;\n"

VERT = (
    "#version 460\n"
    "out gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "};\n"
    "layout (location=0) in vec4 inPos;\n"
    "void main(void) {\n"
    "    gl_Position = inPos;\n"
    "}\n"
)

FRAG = (
    "#version 460\n"
    "layout (location=0) in vec4 inColor;\n"
    "layout (location=0) out vec4 outColor;\n"
    "void main(void) {\n"
    "    outColor = inColor;\n"
    "}\n"
)

TESC = (
    "#version 460\n"
    "#extension GL_EXT_tessellation_shader : require\n"
    "layout(vertices=3) out;\n"
    "in gl_PerVertex\n"
    "{\n"
    "    vec4 gl_Position;\n"
    "} gl_in[gl_MaxPatchVertices];\n"
    "out gl_PerVertex\n"
    "{\n"
    "    vec4 gl_Position;\n"
    "} gl_out[];\n"
    "void main() {\n"
    "    gl_out[gl_InvocationID].gl_Position = gl_in[gl_InvocationID].gl_Position;\n"
    "    gl_TessLevelOuter[0] = 1.0;\n"
    "    gl_TessLevelOuter[1] = 1.0;\n"
    "    gl_TessLevelOuter[2] = 1.0;\n"
    "    gl_TessLevelOuter[3] = 1.0;\n"
    "    gl_TessLevelInner[0] = 1.0;\n"
    "    gl_TessLevelInner[1] = 1.0;\n"
    "}\n"
)

TESE = (
    "#version 460\n"
    "#extension GL_EXT_tessellation_shader : require\n"
    + PC_DECL
    + "layout(triangles) in;\n"
    "in gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "} gl_in[gl_MaxPatchVertices];\n"
    "out gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "};\n"
    "layout (location=0) out vec4 outColor;\n"
    "void main() {\n"
    "    outColor = vec4(pc.red, pc.green, pc.blue, 1.0);\n"
    "    gl_Position = (gl_in[0].gl_Position * gl_TessCoord.x + \n"
    "                   gl_in[1].gl_Position * gl_TessCoord.y + \n"
    "                   gl_in[2].gl_Position * gl_TessCoord.z);\n"
    "}\n"
)

GEOM = (
    "#version 460\n"
    + PC_DECL
    + "layout (triangles) in;\n"
    "layout (triangle_strip, max_vertices=3) out;\n"
    "in gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "} gl_in[3];\n"
    "out gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "};\n"
    "layout (location=0) out vec4 outColor;\n"
    "void main() {\n"
    "    for (uint i = 0; i < 3; ++i) {\n"
    "        outColor = vec4(pc.red, pc.green, pc.blue, 1.0);\n"
    "        gl_Position = gl_in[i].gl_Position;\n"
    "        EmitVertex();\n"
    "    }\n"
    "}\n"
)

FILES = {
    "tg_pc_vert.vert": VERT,
    "tg_pc_frag.frag": FRAG,
    "tg_pc_tesc.tesc": TESC,
    "tg_pc_tese.tese": TESE,
    "tg_pc_geom.geom": GEOM,
}

MANIFEST_TEXT = """# Shader manifest for dEQP-VK.dgc.ext.graphics.misc.tg_push_constants_*
#
# @generated by hodow_cts/scripts/gen_dgc_graphics_misc_tg_pc_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCGraphicsMiscTestsExt.cpp"
rust_module = "dgc/graphics_misc_tg_pc_tests"

[[case]]
name = "tg_pc_tess"
rust_const = "TG_PC_TESS"
rust_type = "SharedProgram"
programs = [ { name = "vert", template = "dgc/tg_pc_vert.vert", stage = "vert" }, { name = "frag", template = "dgc/tg_pc_frag.frag", stage = "frag" }, { name = "tesc", template = "dgc/tg_pc_tesc.tesc", stage = "tesc" }, { name = "tese", template = "dgc/tg_pc_tese.tese", stage = "tese" } ]

[[case]]
name = "tg_pc_geom"
rust_const = "TG_PC_GEOM"
rust_type = "SharedProgram"
programs = [ { name = "vert", template = "dgc/tg_pc_vert.vert", stage = "vert" }, { name = "frag", template = "dgc/tg_pc_frag.frag", stage = "frag" }, { name = "geom", template = "dgc/tg_pc_geom.geom", stage = "geom" } ]
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in FILES.items():
        (SRC_DIR / name).write_text(text)
    MANIFEST.write_text(MANIFEST_TEXT)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
