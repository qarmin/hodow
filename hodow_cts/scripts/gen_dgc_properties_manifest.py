#!/usr/bin/env python3
"""Writes the shaders and the manifest of the compute cases of dEQP-VK.dgc.ext.misc.properties (vktDGCPropertyTestsExt.cpp): the push constant
array shader for 16 and 32 tokens, and the byte and index shaders. A pure text generator."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_properties.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"


def pc_array(pc_len):
    return f"""#version 460
layout (local_size_x=1, local_size_y=1, local_size_z=1) in;
layout (set=0, binding=0, std430) buffer OutputBlock {{ uint values[{pc_len}]; }} outputBuffer;
layout (push_constant, std430) uniform PushConstantBlock {{ uint values[{pc_len}]; }} pc;
void main (void) {{
    for (uint i = 0u; i < {pc_len}u; ++i) {{
        outputBuffer.values[i] = pc.values[i];
    }}
}}
"""


PC_BYTES = """#version 460
layout (local_size_x=1, local_size_y=1, local_size_z=1) in;
layout (set=0, binding=0, std430) buffer OutputBlock { uint value; } outputBuffer;
layout (push_constant, std430) uniform PushConstantBlock { uint value; } pc;
void main (void) {
    atomicOr(outputBuffer.value, (pc.value << (8 * gl_WorkGroupID.z)));
}
"""

PC_INDEX = """#version 460
layout (local_size_x=1, local_size_y=1, local_size_z=1) in;
layout (set=0, binding=0, std430) buffer OutputBlock { uint values[]; } outputBuffer;
layout (push_constant, std430) uniform PushConstantBlock { uint index; uint value; } pc;
void main (void) { outputBuffer.values[pc.index] = pc.value; }
"""

HEADER = """# Shader manifest for the compute cases of dEQP-VK.dgc.ext.misc.properties
#
# @generated by hodow_cts/scripts/gen_dgc_properties_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCPropertyTestsExt.cpp"
rust_module = "dgc/property_tests"
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    out = [HEADER]
    shaders = {
        "prop_pc_array_15": pc_array(15),
        "prop_pc_array_31": pc_array(31),
        "prop_pc_bytes": PC_BYTES,
        "prop_pc_index": PC_INDEX,
    }
    for key, text in shaders.items():
        (SRC_DIR / f"{key}.comp").write_text(text)
        out.append(
            f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [ {{ name = "comp", template = "dgc/{key}.comp", stage = "comp" }} ]
"""
        )
    MANIFEST.write_text("".join(out))
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
