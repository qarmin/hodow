#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.compute.*.basic.replicated_composites_* and secondary_compute_only_queue.

`ReplicatedCompositesTest::initPrograms` builds a compute shader around a composite built from one repeated value, as a value, a constant or a
specialization constant, and `SecondaryCommandBufferComputeOnlyTest::initPrograms` writes a 1 to a buffer. `compute/replicated_composites_tests.rs`
runs them. The sources are derived values because upstream builds them from the case in C++.

A pure text generator: no glslang and no cargo.
"""

import json
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
MANIFEST = CRATE / "shaders" / "manifest" / "compute_replicated_composites.toml"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "compute" / "replicated_composites"

HEADER = """# Shader manifest for dEQP-VK.compute.*.basic.replicated_composites_* and secondary_compute_only_queue
#
# @generated by hodow_cts/scripts/gen_compute_replicated_composites_manifest.py - do not hand-edit.
#
# `ReplicatedCompositesTest::initPrograms` and `SecondaryCommandBufferComputeOnlyTest::initPrograms`.

upstream_source = "external/vulkancts/modules/vulkan/compute/vktComputeBasicComputeShaderTests.cpp"
rust_module = "compute/replicated_composites_tests"
"""

TYPES = ["vector", "matrix", "array", "array_array", "struct", "struct_struct", "coopmat"]
INSTS = ["value", "constant", "specconstant"]

OUTPUT_MEMBER = {
    "vector": "float vec[4];\n",
    "matrix": "float mat[4*4];\n",
    "array": "uint arr[3];\n",
    "array_array": "uint arrarr[6];\n",
    "struct": "uint str[3];\n",
    "struct_struct": "uint str[6];\n",
    "coopmat": "float mat[2];\n",
}

COOPMAT_TYPE = "coopmat<float16_t, gl_ScopeSubgroup, rows, cols, gl_MatrixUseA>"

# the declarations of the composite, at global scope (`indent` empty, with `const`) or in main (four spaces, without)
def declarations(ty: str, indent: str, const: str) -> str:
    c = const
    if ty == "vector":
        return f"{indent}{c}float one = 1.0;\n{indent}{c}vec4 vec = vec4(one);\n"
    if ty == "matrix":
        return f"{indent}{c}float one = 1.0;\n{indent}{c}vec4 vec = vec4(one);\n{indent}{c}mat4 mat = mat4(vec, vec, vec, vec);\n"
    if ty == "array":
        return f"{indent}{c}uint three = 3;\n{indent}{c}uint arr[3] = {{three, three, three}};\n"
    if ty == "array_array":
        return f"{indent}{c}uint three = 3;\n{indent}{c}uint arr[3] = {{three, three, three}};\n{indent}{c}uint arrarr[2][3] = {{arr, arr}};\n"
    if ty == "struct":
        return f"{indent}{c}uint six = 6;\n{indent}struct S {{ uint a; uint b; uint c; }};\n{indent}{c}S str = S(six, six, six);\n\n"
    if ty == "struct_struct":
        return (f"{indent}{c}uint six = 6;\n{indent}struct S {{ uint a; uint b; uint c; }};\n{indent}struct SS {{ S a; S b; }};\n"
                f"{indent}{c}S str = S(six, six, six);\n{indent}{c}SS str2 = SS(str, str);\n\n")
    if ty == "coopmat":
        return f"{indent}{c}float one = 1.0;\n{indent}{c}{COOPMAT_TYPE} mat = {COOPMAT_TYPE}(one);\n"
    raise AssertionError(ty)


STORES = {
    "vector": "".join(f"    sb_out.vec[{i}] = vec[{i}];\n" for i in range(4)),
    "matrix": "".join(f"    sb_out.mat[{c * 4 + r}] = mat[{c}][{r}];\n" for c in range(4) for r in range(4)),
    "array": "".join(f"    sb_out.arr[{i}] = arr[{i}];\n" for i in range(3)),
    "array_array": "".join(f"    sb_out.arrarr[{a * 3 + b}] = arrarr[{a}][{b}];\n" for a in range(2) for b in range(3)),
    "struct": "    sb_out.str[0] = str.a;\n    sb_out.str[1] = str.b;\n    sb_out.str[2] = str.c;\n",
    "struct_struct": "".join(f"    sb_out.str[{i * 3 + j}] = str2.{'ab'[i]}.{'abc'[j]};\n" for i in range(2) for j in range(3)),
    "coopmat": ("    if (gl_LocalInvocationIndex == 0) {\n        sb_out.mat[0] = float(mat[0]);\n"
                "        sb_out.mat[1] = (mat.length() > 1) ? float(mat[1]) : float(mat[0]);\n    }\n"),
}


def source(ty: str, inst: str) -> str:
    s = ("#version 460 core\n#extension GL_EXT_scalar_block_layout : enable\n#extension GL_KHR_cooperative_matrix : enable\n"
         "#extension GL_EXT_shader_explicit_arithmetic_types_float16 : enable\n#extension GL_KHR_memory_scope_semantics : enable\n"
         "#extension GL_EXT_spec_constant_composites : enable\n#pragma use_replicated_composites\n")
    s += f"layout (local_size_x = {'64' if ty == 'coopmat' else '1'}) in;\n"
    s += "layout(binding = 0, scalar) buffer Output {\n" + OUTPUT_MEMBER[ty] + "} sb_out;\n\n"
    if ty == "coopmat":
        s += "layout(constant_id = 1) const uint rows = 1;\nlayout(constant_id = 2) const uint cols = 1;\n"
    if inst != "value":
        if inst == "specconstant":
            # `layout(constant_id = 0)` precedes only the first `const` of the group
            decl = declarations(ty, "", "const ")
            s += "layout(constant_id = 0) " + decl
        else:
            s += declarations(ty, "", "const ")
    s += "void main (void) {\n"
    if inst == "value":
        s += declarations(ty, "    ", "")
    s += STORES[ty]
    s += "}\n"
    return s


SECONDARY = ("#version 450\nlayout(local_size_x = 1, local_size_y = 1, local_size_z = 1) in;\nlayout(set = 0, binding = 0, std430) buffer Out\n{\n"
             "    uint data[];\n};\nvoid main (void)\n{\ndata[0] = 1;}\n")


def py(value) -> str:
    return json.dumps(repr(value))


def main() -> None:
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    (TEMPLATE_DIR / "source.comp").write_text("${source}")
    out = [HEADER]
    for ty in TYPES:
        for inst in INSTS:
            name = f"rc_{ty}_{inst}"
            out.append(
                f'\n[[case]]\nname = "{name}"\nrust_const = "{name.upper()}"\nrust_type = "SharedProgram"\n'
                f'programs = [{{ name = "comp", template = "compute/replicated_composites/source.comp", stage = "comp", spirv_version = "spirv1.3" }}]\n'
                f"derived = {{ source = {py(source(ty, inst))} }}\n"
            )
    out.append(
        f'\n[[case]]\nname = "secondary_compute_only_queue"\nrust_const = "SECONDARY_COMPUTE_ONLY_QUEUE"\nrust_type = "SharedProgram"\n'
        f'programs = [{{ name = "comp", template = "compute/replicated_composites/source.comp", stage = "comp" }}]\n'
        f"derived = {{ source = {py(SECONDARY)} }}\n"
    )
    MANIFEST.write_text("".join(out))
    print(f"{len(TYPES) * len(INSTS) + 1} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
