#!/usr/bin/env python3
"""Generate the renderpasses dynamic_rendering depth_stencil_resolve shaders.

`vktDynamicRenderingDepthStencilResolveTests.cpp`'s `Programs::init` emits at most six
shaders and only two parameters reach the GLSL: whether the case reads back depth or
stencil, and whether it is the push-constant corner case (which additionally renders a
layered quad through a geometry shader and then a full-screen colour quad). Six shaders
cover all 4608 cases.

Usage:
    python3 hodow_cts/scripts/gen_dr_ds_resolve_shaders.py
"""

from __future__ import annotations

import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = CRATE_DIR.parent
SRC_DIR = CRATE_DIR / "shaders" / "src" / "renderpass" / "generated"
MANIFEST = CRATE_DIR / "shaders" / "manifest" / "renderpass_dr_ds_resolve.toml"

# `const uint32_t layerCount = config.viewLayers` - the only layered config here is the
# push-constant corner case, which uses two layers.
LAYER_COUNT = 2

VERT = (
    "#version 450\n"
    "out gl_PerVertex {\n"
    "\tvec4 gl_Position;\n"
    "};\n"
    "highp float;\n"
    "void main (void) {\n"
    "\tgl_Position = vec4(((gl_VertexIndex + 2) / 3) % 2 == 0 ? -1.0 : 1.0,\n"
    "\t                   ((gl_VertexIndex + 1) / 3) % 2 == 0 ? -1.0 : 1.0, 0.0, 1.0);\n"
    "}\n"
)

GEOM = (
    "#version 450\n"
    "highp float;\n"
    "\n"
    "layout(triangles) in;\n"
    f"layout(triangle_strip, max_vertices = {3 * 2 * LAYER_COUNT}) out;\n"
    "\n"
    "in gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "} gl_in[];\n"
    "\n"
    "out gl_PerVertex {\n"
    "    vec4 gl_Position;\n"
    "};\n"
    "\n"
    "void main (void) {\n"
    f"    for (int layerNdx = 0; layerNdx < {LAYER_COUNT}; ++layerNdx) {{\n"
    "        for(int vertexNdx = 0; vertexNdx < gl_in.length(); vertexNdx++) {\n"
    "            gl_Position = gl_in[vertexNdx].gl_Position;\n"
    "            gl_Layer    = layerNdx;\n"
    "            EmitVertex();\n"
    "        };\n"
    "        EndPrimitive();\n"
    "    };\n"
    "}\n"
)

# Each sample gets one of four depth values, chosen so min, max, average and sample-zero
# all land on different numbers - which is what makes the resolve mode observable.
FRAG_DEPTH = (
    "#version 450\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "void main (void)\n"
    "{\n"
    "  float sampleIndex = float(gl_SampleID);\n"
    "  float valueIndex = round(mod(sampleIndex, 4.0));\n"
    "  float value = valueIndex + 2.0;\n"
    "  value = round(exp2(value));\n"
    "  bool condition = (int(value) == 8);\n"
    "  value = round(value - float(condition) * 6.0);\n"
    "  gl_FragDepth = value / 100.0;\n"
    "}\n"
)

FRAG_STENCIL = (
    "#version 450\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "layout(push_constant) uniform PushConstant {\n"
    "  highp int sampleID;\n"
    "} pushConstants;\n"
    "void main (void)\n"
    "{\n"
    "  if(gl_SampleID != pushConstants.sampleID)\n"
    "    discard;\n"
    "  gl_FragDepth = 0.5;\n"
    "}\n"
)

VERT_PC = (
    "#version 450\n"
    "vec2 positions[6] = vec2[](\n"
    "    vec2(-1.0f, 1.0f),\n"
    "    vec2(1.0f, 1.0f),\n"
    "    vec2(-1.0f, -1.0f),\n"
    "    vec2(-1.0f, -1.0f),\n"
    "    vec2(1.0f, 1.0f),\n"
    "    vec2(1.0f, -1.0f)\n"
    ");\n"
    "\n"
    "void main() {\n"
    "    gl_Position = vec4(positions[gl_VertexIndex], 0.0, 1.0);\n"
    "}\n"
)

FRAG_PC = (
    "#version 450\n"
    "layout (push_constant, std430) uniform PushConstants {\n"
    "    vec4 color;\n"
    "} pc;\n"
    "layout (location=0) out vec4 outColor;\n"
    "void main (void) {\n"
    "    outColor = pc.color;\n"
    "}\n"
)


def main() -> int:
    SRC_DIR.mkdir(parents=True, exist_ok=True)

    case_name = "dr_ds_resolve"
    programs = [
        ("quad_vert", "vert", VERT),
        ("quad_geom", "geom", GEOM),
        ("quad_frag_depth", "frag", FRAG_DEPTH),
        ("quad_frag_stencil", "frag", FRAG_STENCIL),
        ("vert_pc", "vert", VERT_PC),
        ("frag_pc", "frag", FRAG_PC),
    ]

    lines = [
        "# Shader manifest for dEQP-VK.renderpasses.dynamic_rendering.*.depth_stencil_resolve.*",
        "#",
        "# Generated by scripts/gen_dr_ds_resolve_shaders.py together with the GLSL it names;",
        "# do not hand-edit either. One case holding all six: which of them a test uses is",
        "# decided by two independent parameters, so enumerating the sets would be more",
        "# entries than there are shaders.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/renderpass/vktDynamicRenderingDepthStencilResolveTests.cpp"',
        'rust_module = "renderpass/dynamic_rendering_depth_stencil_resolve_tests"',
        "",
        "[[case]]",
        f'name = "{case_name}"',
        'rust_const = "DR_DS_RESOLVE_PROGRAMS"',
        'rust_type = "DrDsResolvePrograms"',
        "programs = [",
    ]
    for name, stage, source in programs:
        (SRC_DIR / f"{case_name}_{name}.{stage}").write_text(source)
        lines.append(f'    {{ name = "{name}", template = "renderpass/generated/{case_name}_{name}.{stage}", stage = "{stage}" }},')
    lines += ["]", ""]

    MANIFEST.write_text("\n".join(lines))
    print(f"wrote {MANIFEST.relative_to(REPO_DIR)} and {len(programs)} shaders in {SRC_DIR.relative_to(REPO_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
