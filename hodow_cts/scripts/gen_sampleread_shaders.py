#!/usr/bin/env python3
"""Generate the renderpasses sampleread shaders and their manifest.

`Programs::init` in vktRenderPassSampleReadTests.cpp builds three shaders. Two are
fixed; the third, the second-subpass shader, is parameterised by the test mode - the
`add` variant loops over `sampleCount` samples, the `select` variant reads one chosen
sample - so it needs one shader per sample count and one per selected sample.

Usage:
    python3 hodow_cts/scripts/gen_sampleread_shaders.py
"""

from __future__ import annotations

import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = CRATE_DIR.parent
SRC_DIR = CRATE_DIR / "shaders" / "src" / "renderpass" / "generated"
MANIFEST = CRATE_DIR / "shaders" / "manifest" / "renderpass_sampleread.toml"

SAMPLE_COUNTS = (2, 4, 8, 16, 32)

VERT = (
    "#version 450\n"
    "out gl_PerVertex {\n"
    "\tvec4 gl_Position;\n"
    "};\n"
    "highp float;\n"
    "void main (void)\n"
    "{\n"
    "    gl_Position = vec4(((gl_VertexIndex + 2) / 3) % 2 == 0 ? -1.0 : 1.0,\n"
    "                       ((gl_VertexIndex + 1) / 3) % 2 == 0 ? -1.0 : 1.0, 0.0, 1.0);\n"
    "}\n"
)

FRAG = (
    "#version 450\n"
    "layout(location = 0) out highp uvec4 o_color;\n"
    "void main (void)\n"
    "{\n"
    "    o_color = uvec4(1u << gl_SampleID, 0, 0, 0);\n"
    "}\n"
)

SUBPASS_PROLOGUE = (
    "#version 450\n"
    "precision mediump int;\n"
    "precision highp float;\n"
    "layout(input_attachment_index = 0, set = 0, binding = 0) uniform highp usubpassInputMS i_color;\n"
    "layout(location = 0) out highp vec4 o_color;\n"
    "void main (void)\n"
    "{\n"
    "    o_color = vec4(0.0);\n"
)


def subpass_add(sample_count: int) -> str:
    return (
        SUBPASS_PROLOGUE
        + "    uint load = 0;\n"
        + "    uint expect = 0;\n"
        + f"    for (int i = 0; i < {sample_count}; i++)\n"
        + "    {\n"
        + "        expect += (1 << i);\n"
        + "        if ((gl_SampleMaskIn[0] & (1 << i)) != 0)\n"
        + "            load += subpassLoad(i_color, i).r;\n"
        + "        else\n"
        + "            load += (1 << i);\n"
        + "    }\n"
        + "    o_color.r = (load == expect) ? 1.0 : 0.0;\n"
        + "}\n"
    )


def subpass_select(selected_sample: int) -> str:
    return (
        SUBPASS_PROLOGUE
        + "    float result = 1.0;\n"
        + f"    if ((gl_SampleMaskIn[0] & (1 << {selected_sample})) != 0)\n"
        + "    {\n"
        + f"        uint load = subpassLoad(i_color, {selected_sample}).r;\n"
        + f"        result = (load == (1 << {selected_sample})) ? 1.0 : 0.0;\n"
        + "    }\n"
        + "    o_color.r = result;\n"
        + "}\n"
    )


def main() -> int:
    SRC_DIR.mkdir(parents=True, exist_ok=True)

    programs: list[tuple[str, str, str]] = [("quad_vert", "vert", VERT), ("quad_frag", "frag", FRAG)]
    for sample_count in SAMPLE_COUNTS:
        programs.append((f"quad_subpass_frag_add_{sample_count}", "frag", subpass_add(sample_count)))
    for selected_sample in range(max(SAMPLE_COUNTS)):
        programs.append((f"quad_subpass_frag_select_{selected_sample}", "frag", subpass_select(selected_sample)))

    lines = [
        "# Shader manifest for dEQP-VK.renderpasses.renderpass{1,2}.suballocation.sampleread.*",
        "#",
        "# Generated by scripts/gen_sampleread_shaders.py together with the GLSL it names;",
        "# do not hand-edit either. One case holding all of them: which shader a test uses",
        "# follows from its test mode and sample count.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/renderpass/vktRenderPassSampleReadTests.cpp"',
        'rust_module = "renderpass/sample_read_tests"',
        "",
        "[[case]]",
        'name = "sampleread"',
        'rust_const = "SAMPLE_READ_PROGRAMS"',
        'rust_type = "SampleReadPrograms"',
        "programs = [",
    ]
    for name, stage, source in programs:
        (SRC_DIR / f"sampleread_{name}.{stage}").write_text(source)
        lines.append(f'    {{ name = "{name}", template = "renderpass/generated/sampleread_{name}.{stage}", stage = "{stage}" }},')
    lines += ["]", ""]

    MANIFEST.write_text("\n".join(lines))
    print(f"wrote {MANIFEST.relative_to(REPO_DIR)} and {len(programs)} shaders in {SRC_DIR.relative_to(REPO_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
