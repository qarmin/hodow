#!/usr/bin/env python3
"""Generate the renderpasses.unused_clear_attachments shaders and their manifest.

The shaders exist only so the graphics pipeline can be created; nothing is ever drawn
with them. The fragment shader declares one output per *used* colour attachment, so it
depends on nothing but the used/unused bit pattern - four attachments, sixteen
patterns, and the one- and zero-attachment cases are already among them.

Usage:
    python3 hodow_cts/scripts/gen_unused_clear_shaders.py
"""

from __future__ import annotations

import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = CRATE_DIR.parent
SRC_DIR = CRATE_DIR / "shaders" / "src" / "renderpass" / "generated"
MANIFEST = CRATE_DIR / "shaders" / "manifest" / "renderpass_unused_clear.toml"

# `COLOR_ATTACHMENTS_NUMBER` - maxColorAttachments is guaranteed to be at least 4.
COLOR_ATTACHMENTS_NUMBER = 4

VERTEX_SHADER = (
    "#version 450\n"
    "precision highp float;\n"
    "layout(location = 0) in vec4 position;\n"
    "layout(location = 0) out vec4 vtxColor;\n"
    "void main (void)\n"
    "{\n"
    "\tgl_Position = position;\n"
    "\tvtxColor = vec4(0.5, 0.5, 0.5, 1.0);\n"
    "}\n"
)


def fragment_shader(color_used: list[bool]) -> str:
    """`UnusedClearAttachmentTest::initPrograms`"""
    out = ["#version 450\n", "precision highp float;\n", "layout(location = 0) in vec4 vtxColor;\n"]
    for i, used in enumerate(color_used):
        if used:
            out.append(f"layout(location = {i}) out vec4 fragColor{i};\n")
    out.append("void main (void)\n")
    out.append("{\n")
    for i, used in enumerate(color_used):
        if used:
            out.append(f"\tfragColor{i} = vtxColor;\n")
    out.append("}\n")
    return "".join(out)


def main() -> int:
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    for existing in SRC_DIR.glob("unused_clear_*"):
        existing.unlink()

    lines = [
        "# Shader manifest for dEQP-VK.renderpasses.*.unused_clear_attachments.*",
        "#",
        "# Generated by scripts/gen_unused_clear_shaders.py together with the GLSL it names;",
        "# do not hand-edit either. The fragment shader depends only on which colour",
        "# attachments the subpass uses, so four attachments give sixteen shaders and the",
        "# one- and zero-attachment cases reuse the patterns already among them.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/renderpass/vktRenderPassUnusedClearAttachmentTests.cpp"',
        'rust_module = "renderpass/unused_clear_attachment_tests"',
        "",
    ]

    (SRC_DIR / "unused_clear.vert").write_text(VERTEX_SHADER)

    count = 0
    for mask in range(1 << COLOR_ATTACHMENTS_NUMBER):
        color_used = [(mask >> i) & 1 == 1 for i in range(COLOR_ATTACHMENTS_NUMBER)]
        name = f"unused_clear_{mask:02d}"
        (SRC_DIR / f"{name}.frag").write_text(fragment_shader(color_used))
        lines += [
            "[[case]]",
            f'name = "{name}"',
            f'rust_const = "{name.upper()}"',
            'rust_type = "UnusedClearProgram"',
            'programs = [',
            '    { name = "vert_shader", template = "renderpass/generated/unused_clear.vert", stage = "vert" },',
            f'    {{ name = "frag_shader", template = "renderpass/generated/{name}.frag", stage = "frag" }},',
            "]",
            "[case.params]",
            f'color_mask = {{ type = "u32", value = {mask} }}',
            "",
        ]
        count += 1

    MANIFEST.write_text("\n".join(lines))
    print(f"wrote {MANIFEST.relative_to(REPO_DIR)} and {count} fragment shaders in {SRC_DIR.relative_to(REPO_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
