#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.tessellation.tess_io.level_io.

`LevelIOTest::initPrograms` builds an evaluation shader that reads the tessellation levels (or ignores them) and a control shader that writes
levels of 1 or 0, from `TessReadLevel`. The enumerators are ordered and the comparisons of the C++ against that order decide what is written:
every case before `TESS_WRITES0_OUTER_1` - the inner level ones included - makes the control shader write only ones, and the evaluation shader
outputs the colour data computed from the levels only for the three `TESS_READS_*` cases. This keeps that behaviour as it is.

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "tessellation_level_io.toml"

HEADER = """# Shader manifest for dEQP-VK.tessellation.tess_io.level_io
#
# @generated by hodow_cts/scripts/gen_tess_level_io_manifest.py - do not hand-edit.
#
# One entry per case of `LevelIOTest`: the vertex and fragment shaders are the common ones and the control and evaluation shaders depend on the
# `TessReadLevel` of the case.

upstream_source = "external/vulkancts/modules/vulkan/tessellation/vktTessellationMaxIOTests.cpp"
rust_module = "tessellation/max_io_tests"
"""

# (index in TessReadLevel, case name)
CASES = [
    (1, "tes_reads_inner"),
    (0, "tes_reads_outer"),
    (2, "tes_reads_both"),
    (5, "tcs_writes0_outer_1"),
    (6, "tcs_writes0_outer_all"),
    (3, "tcs_writes0_inner_1"),
    (4, "tcs_writes0_inner_all"),
    (7, "tcs_writes0_outer_inner"),
]
READS_OUTER, READS_INNER, READS_OUTER_INNER, WRITES0_INNER_1, WRITES0_INNER_ALL, WRITES0_OUTER_1, WRITES0_OUTER_ALL, WRITES0_OUTER_INNER = range(8)

READ_OUTER = (
    "    float varOuter0 = gl_TessLevelOuter[0];\n"
    "    float varOuter1 = gl_TessLevelOuter[1];\n"
    "    float varOuter2 = gl_TessLevelOuter[2];\n"
    "    float varOuter3 = gl_TessLevelOuter[3];\n"
)
READ_INNER = "    float varInner0 = gl_TessLevelInner[0];\n    float varInner1 = gl_TessLevelInner[1];\n"
COLOR_OUTER = "    vec4 colorData = vec4(perPatchColor.x * varOuter0, perPatchColor.y * varOuter1, perPatchColor.z * varOuter2, perPatchColor.w * varOuter3);\n"
COLOR_INNER = "    vec4 colorData = vec4(perPatchColor.x * varInner0, perPatchColor.y * varInner1, perPatchColor.z * varInner0, perPatchColor.w * varInner1);\n"
COLOR_INNER_REASSIGN = COLOR_INNER.replace("vec4 colorData =", "colorData =")


def level_reads(level):
    if level == READS_OUTER:
        return READ_OUTER + COLOR_OUTER
    if level == READS_INNER:
        return READ_INNER + COLOR_INNER
    if level == READS_OUTER_INNER:
        return READ_OUTER + READ_INNER + COLOR_OUTER + COLOR_INNER_REASSIGN
    return ""


def levels(level):
    outer0 = outer_other = inner0 = inner_other = 1.0
    if level >= WRITES0_OUTER_1:
        if level == WRITES0_OUTER_1:
            outer0, outer_other = 0.0, 1.0
        elif level == WRITES0_OUTER_ALL:
            outer0, outer_other = 0.0, 0.0
        else:
            outer0 = inner0 = outer_other = inner_other = 0.0
    f = lambda v: f"{v:.6f}"
    return (
        f"   gl_TessLevelOuter = float[4]({f(outer0)}, {f(outer_other)}, {f(outer_other)}, {f(outer_other)});\n"
        f"   gl_TessLevelInner = float[2]({f(inner0)}, {f(inner_other)});\n"
    )


def toml_str(python_literal):
    return '"' + python_literal.replace("\\", "\\\\").replace('"', '\\"') + '"'


def entry(level, name):
    out_color = "colorData" if level < WRITES0_INNER_1 else "perPatchColor"
    derived = {"level_reads": level_reads(level), "out_color": out_color, "levels": levels(level)}
    items = ", ".join(f"{k} = {toml_str(repr(v))}" for k, v in derived.items())
    t = "tessellation/level_io"
    return f"""
[[case]]
name = "{name}"
rust_const = "LEVEL_IO_{name.upper()}"
rust_type = "SharedProgram"
programs = [
    {{ name = "vert", template = "{t}/vert.vert", stage = "vert" }},
    {{ name = "tesc", template = "{t}/tesc.tesc", stage = "tesc" }},
    {{ name = "tese", template = "{t}/tese.tese", stage = "tese" }},
    {{ name = "frag", template = "{t}/frag.frag", stage = "frag" }},
]
derived = {{ {items} }}
"""


def main():
    out = [HEADER]
    for level, name in CASES:
        out.append(entry(level, name))
    MANIFEST.write_text("".join(out))
    print(f"wrote {MANIFEST} with {len(CASES)} entries")


if __name__ == "__main__":
    main()
