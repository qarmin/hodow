#!/usr/bin/env python3
"""Writes shaders/manifest/spirv_assembly_convert_graphics.toml: the graphics cases of dEQP-VK.spirv_assembly.instruction.graphics.{sconvert,uconvert,
fconvert,convertstof,convertftos,convertutof,convertftou}.

`createConvertGraphicsTests` of vktSpvAsmInstructionTests.cpp turns every `ConvertCase` into the fragments of `getConvertCaseFragments` (or the NoStorage
twin) and `createTestsForAllStages` runs them in each of the five stages. The `ConvertCase` tables and assembly types come from
gen_spirv_assembly_convert_manifest.py (read out of upstream), the stage templates and pipelines from gen_spirv_assembly_type_manifest.py.

A pure text generator: no spirv-as and no cargo."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_spirv_assembly_convert_manifest as conv  # noqa: E402
import gen_spirv_assembly_type_manifest as stages  # noqa: E402

CRATE = HERE.parent
OUT = CRATE / "shaders" / "manifest" / "spirv_assembly_convert_graphics.toml"
CPP = CRATE / "upstream" / "external" / "vulkancts" / "modules" / "vulkan" / "spirv_assembly" / "vktSpvAsmInstructionTests.cpp"
CASES = CRATE / "tmp_unused"

DECORATION = (
    "      OpDecorate %SSBOi DescriptorSet 0\n      OpDecorate %SSBOo DescriptorSet 0\n      OpDecorate %SSBOi Binding 0\n      OpDecorate %SSBOo Binding 1\n"
    "      OpDecorate %s_SSBOi Block\n      OpDecorate %s_SSBOo Block\nOpMemberDecorate %s_SSBOi 0 Offset 0\nOpMemberDecorate %s_SSBOo 0 Offset 0\n"
)
PRE_MAIN = (
    "${datatype_additional_decl}"
    "    %ptr_in = OpTypePointer StorageBuffer %${inStorageType}\n   %ptr_out = OpTypePointer StorageBuffer %${outStorageType}\n"
    "   %s_SSBOi = OpTypeStruct %${inStorageType}\n   %s_SSBOo = OpTypeStruct %${outStorageType}\n"
    " %ptr_SSBOi = OpTypePointer StorageBuffer %s_SSBOi\n %ptr_SSBOo = OpTypePointer StorageBuffer %s_SSBOo\n"
    "     %SSBOi = OpVariable %ptr_SSBOi StorageBuffer\n     %SSBOo = OpVariable %ptr_SSBOo StorageBuffer\n"
)
TESTFUN_STORAGE = (
    "%test_code  = OpFunction %v4f32 None %v4f32_v4f32_function\n%param      = OpFunctionParameter %v4f32\n%label      = OpLabel\n"
    "%iLoc       = OpAccessChain %ptr_in %SSBOi %c_u32_0\n%oLoc       = OpAccessChain %ptr_out %SSBOo %c_u32_0\n"
    "%valIn      = OpLoad %${inStorageType} %iLoc\n%valInCast  = ${inCast} %${inputType} %valIn\n"
    "%conv       = ${instruction} %${outputType} %valInCast\n%valOutCast = ${outCast} %${outStorageType} %conv\n"
    "              OpStore %oLoc %valOutCast\n              OpReturnValue %param\n              OpFunctionEnd\n"
)
TESTFUN_NO_STORAGE = (
    "%test_code = OpFunction %v4f32 None %v4f32_v4f32_function\n%param     = OpFunctionParameter %v4f32\n%label     = OpLabel\n"
    "%iLoc      = OpAccessChain %ptr_in %SSBOi %c_u32_0\n%oLoc      = OpAccessChain %ptr_out %SSBOo %c_u32_0\n"
    "%inval      = OpLoad %${inStorageType} %iLoc\n%in_cast    = ${inCast} %${inputType} %inval\n"
    "%conv       = ${instruction} %${outputType} %in_cast\n%out_cast   = ${outCast} %${outStorageType} %conv\n"
    "              OpStore %oLoc %out_cast\n              OpReturnValue %param\n              OpFunctionEnd\n"
)


def fragments(instruction, case):
    params = dict(case.asm_types)
    params["instruction"] = instruction
    params["datatype_extensions"] = params["datatype_extensions"] + 'OpExtension "SPV_KHR_storage_buffer_storage_class"\n'

    def specialize(text):
        return re.sub(r"\$\{(\w+)\}", lambda m: params[m.group(1)], text)

    return {
        "capability": params["datatype_capabilities"],
        "extension": params["datatype_extensions"],
        "decoration": DECORATION,
        "pre_main": specialize(PRE_MAIN),
        "testfun": specialize(TESTFUN_STORAGE if case.use_storage_ext else TESTFUN_NO_STORAGE),
    }


def main():
    source = CPP.read_text(encoding="utf-8")
    header = (
        "# Shader manifest for the graphics convert groups of dEQP-VK.spirv_assembly.instruction.graphics.*\n#\n"
        "# @generated by hodow_cts/scripts/gen_spirv_assembly_convert_graphics_manifest.py - do not hand-edit; the case tables are read out of upstream.\n\n"
        f'upstream_source = "{conv.SOURCE}"\nrust_module = "spirv_assembly/convert_graphics_tests"\n'
    )
    entries = []
    for instruction, group in conv.GROUPS:
        for case in conv.parse_cases(source, instruction):
            frags = fragments(instruction, case)
            filler = (b"\xff" * len(case.output)).hex()
            spec = f"in={case.input.hex()};out={case.output.hex()};feat={','.join(case.features())}"
            for stage, _ in stages.GRAPHICS_STAGES:
                if stage not in stages.PIPELINES:
                    continue
                name = f"{group}/{case.name}_{stage}"
                const = "CONVERT_GRAPHICS_" + "".join(c if c.isalnum() else "_" for c in name).upper()
                programs = ", ".join(
                    f'{{ name = "{p}", template = "spirv_assembly/type_{p}{"" if p == stage else "_passthru"}.asm", stage = "asm", spirv_version = "spirv1.0" }}'
                    for p in stages.PIPELINES[stage]
                )
                derived = ", ".join(f"{key} = {stages.py(frags[key])}" for key in stages.FRAGMENT_KEYS)
                entries.append(
                    f'\n[[case]]\nname = "{name}"\nrust_const = "{const}"\nrust_type = "ConvertGraphicsCase"\nprograms = [ {programs} ]\n'
                    f'params = {{ spec = {{ type = "str", value = "{spec}" }} }}\nderived = {{ {derived} }}\n'
                )
            del filler
    OUT.write_text(header + "".join(entries))
    print(f"{len(entries)} cases -> {OUT}", file=sys.stderr)

    want = {
        line.split("instruction.graphics.", 1)[1].strip().replace(".", "/")
        for line in (HERE.parent.parent / "tmp" / "missing" / "spirv_assembly.txt").read_text().splitlines()
        if "instruction.graphics." in line and any(f".graphics.{g}." in line for _, g in conv.GROUPS)
    }
    got = {line.split('name = "', 1)[1].rstrip('"\n') for line in "".join(entries).splitlines() if line.startswith("name = ")}
    print(f"mustpass {len(want)}, generated {len(got)}, missing {len(want - got)}, extra {len(got - want)}", file=sys.stderr)
    for name in sorted(want - got)[:5]:
        print("  missing", name, file=sys.stderr)
    for name in sorted(got - want)[:5]:
        print("  extra", name, file=sys.stderr)


if __name__ == "__main__":
    main()
