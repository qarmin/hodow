#!/usr/bin/env python3
"""Generates the modules of KHR-GL4x.gl_spirv.spirv_validation_capabilities_test.

Upstream (SpirvValidationCapabilitiesTest::init) builds the pipelines at run time with glslang and only the program build
is a pass/fail criterion; the per-capability cut-off round trip through spirv-as/spirv-val only logs. The shader list, the
pipelines and the extensions guarding them are read out of the upstream C++, every stage is compiled with glslangValidator,
and
  shaders/gl_spirv/capabilities/<NN>.<ext>, <NN>_<ext>.spv   (NN = pipeline index * 10 + stage index)
  src/khr_gl/gl_spirv_capabilities_table.rs
are written.
Usage: python3 hodow_cts/scripts/gen_gl_spirv_capabilities.py [--upstream <gl4cGlSpirvTests.cpp>] [--check]
"""
import argparse
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "shaders" / "gl_spirv" / "capabilities"
TABLE = ROOT / "src" / "khr_gl" / "gl_spirv_capabilities_table.rs"

spec = importlib.util.spec_from_file_location("builtin_gen", Path(__file__).with_name("gen_gl_spirv_builtin_functions.py"))
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)

TOKEN = re.compile(
    r'isExtensionSupported\("(\w+)"\)\)\s*\{'
    r'|(?P<open>\{)|(?P<close>\})'
    r'|ShaderStage\s+(?P<decl>\w+)(?:\(\s*"(?P<declname>\w+)"\s*\))?\s*;'
    r'|(?P<srcvar>\w+)\.source\s*=\s*(?P<kind>\w+)Source\((?P<lits>(?:\s*"(?:[^"\\]|\\.)*")+)\)\s*;'
    r'|Pipeline\s+(?P<pdecl>\w+)\s*;'
    r'|m_pipelines\.push_back\((?P<final>\w+)\)\s*;'
    r'|(?P<pvar>\w+)\.push_back\((?P<stagevar>\w+)\)\s*;'
)


def parse(cpp):
    body = base.function_body(cpp, "void SpirvValidationCapabilitiesTest::init()")
    body = re.sub(r"(?m)^\s*//[^\n]*", "", body)
    sources, pipelines, stack, current = {}, {}, [], []
    for m in TOKEN.finditer(body):
        if m.group(1):
            stack.append(m.group(1))
        elif m.group("open"):
            stack.append(None)
        elif m.group("close"):
            stack.pop()
        elif m.group("decl"):
            sources[m.group("decl")] = None
        elif m.group("srcvar"):
            sources[m.group("srcvar")] = (m.group("kind"), base.literals_value(m.group("lits")))
        elif m.group("pdecl"):
            pipelines[m.group("pdecl")] = []
        elif m.group("pvar") and m.group("pvar") in pipelines:
            pipelines[m.group("pvar")].append(sources[m.group("stagevar")])
        elif m.group("final"):
            current.append(([e for e in stack if e], list(pipelines[m.group("final")])))
    return current


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--upstream", type=Path, default=base.DEFAULT_CPP)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    pipelines = parse(args.upstream.read_text())
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    stale = False
    lines = []
    import tempfile

    for p, (extensions, stages) in enumerate(pipelines):
        entries = []
        for s, (kind, source) in enumerate(stages):
            ext, stage = base.KINDS[kind]
            stem = f"{p:02}{s}"
            glsl_path, spv_path = OUT_DIR / f"{stem}.{ext}", OUT_DIR / f"{stem}_{ext}.spv"
            with tempfile.TemporaryDirectory() as tmp:
                fresh = Path(tmp) / "m.spv"
                base.compile_shader(source, ext, fresh)
                if args.check:
                    if not glsl_path.exists() or glsl_path.read_text() != source or not spv_path.exists() or spv_path.read_bytes() != fresh.read_bytes():
                        print(f"stale: {stem}", file=sys.stderr)
                        stale = True
                else:
                    glsl_path.write_text(source)
                    spv_path.write_bytes(fresh.read_bytes())
            entries.append(
                f'            CapabilityStage {{ stage: ShaderType::{stage}, glsl: include_str!("../../shaders/gl_spirv/capabilities/{stem}.{ext}"), '
                f'spirv: include_bytes!("../../shaders/gl_spirv/capabilities/{stem}_{ext}.spv") }},'
            )
        exts = ", ".join(f'"{e}"' for e in extensions)
        lines.append(f"    CapabilityPipeline {{\n        extensions: &[{exts}],\n        stages: &[\n" + "\n".join(entries) + "\n        ],\n    },")

    text = (
        "// Generated by hodow_cts/scripts/gen_gl_spirv_capabilities.py - do not edit.\n\n"
        "use crate::glu::ShaderType;\n\n"
        "pub(super) struct CapabilityStage {\n    pub stage: ShaderType,\n    pub glsl: &'static str,\n    pub spirv: &'static [u8],\n}\n\n"
        "/// The pipeline is built only when every extension of `extensions` is supported.\n"
        "pub(super) struct CapabilityPipeline {\n    pub extensions: &'static [&'static str],\n    pub stages: &'static [CapabilityStage],\n}\n\n"
        "pub(super) const CAPABILITY_PIPELINES: &[CapabilityPipeline] = &[\n" + "\n".join(lines) + "\n];\n"
    )
    if args.check:
        if not TABLE.exists() or TABLE.read_text() != text:
            print(f"stale: {TABLE}", file=sys.stderr)
            stale = True
        sys.exit(1 if stale else 0)
    TABLE.write_text(text)
    print(f"wrote {len(pipelines)} pipelines and {TABLE.name}")


if __name__ == "__main__":
    main()
