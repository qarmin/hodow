#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.robustness.buffer_access.through_pointers.*

`MakeShader` of vktRobustBufferAccessWithVariablePointersTests.cpp composes SPIR-V assembly that copies data from one storage buffer to another through pointers
chosen by OpSelect (variable pointers), for one shader stage, shader type, buffer format and direction. This is that composition, `ShaderStream` included, and the
manifest gets one assembly program per distinct case; `robustness/variable_pointers_programs.rs` maps the case's key to its program set.

A pure text generator: no spirv-as and no cargo.
"""

import json
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
MANIFEST = CRATE / "shaders" / "manifest" / "robustness_variable_pointers.toml"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "robustness" / "variable_pointers"
PROGRAM_TABLE = CRATE / "src" / "vkt" / "tests" / "robustness" / "variable_pointers_programs.rs"

HEADER = """# Shader manifest for dEQP-VK.robustness.buffer_access.through_pointers.*
#
# @generated by hodow_cts/scripts/gen_robustness_variable_pointers_manifest.py - do not hand-edit.
#
# `MakeShader` (SPIR-V assembly), one entry per stage, shader type, format and direction.

upstream_source = "external/vulkancts/modules/vulkan/robustness/vktRobustBufferAccessWithVariablePointersTests.cpp"
rust_module = "robustness/variable_pointers_tests"
"""


class Operation(str):
    pass


class Variable:
    pass


class Ops:
    pass


op = Ops()
for _name in ("Capability Extension ExtInstImport EntryPoint MemoryModel ExecutionMode Decorate MemberDecorate Name MemberName TypeVoid TypeBool TypeInt TypeFloat TypeVector "
              "TypeMatrix TypeArray TypeStruct TypeFunction TypePointer TypeImage TypeSampledImage Constant ConstantComposite Variable Function FunctionEnd Label Return "
              "LogicalEqual IEqual Select AccessChain Load Store").split():
    setattr(op, _name, Operation("Op" + _name))


class ShaderStream:
    """Composes SPIR-V assembly in the sections `ShaderStream` keeps; variables are named `%0001`... in the order they are first printed."""

    def __init__(self):
        self.vars: dict[int, str] = {}
        self.alive: list = []  # `id()` is the key, so a variable must not be freed and its id reused
        self.counter = 0
        self.capabilities = ""
        self.preamble = ""
        self.names = ""
        self.decorations = ""
        self.basictypes = ""
        self.constants = ""
        self.compositetypes = ""
        self.compositeconstants = ""
        self.shaderstream = ""

    def _map(self, a) -> str:
        if isinstance(a, Variable):
            key = id(a)
            if key not in self.vars:
                self.alive.append(a)
                self.counter += 1
                self.vars[key] = f"%{self.counter:04x}"
            return self.vars[key]
        return str(a)

    def _select(self, a, c) -> str:
        if isinstance(a, Operation):
            if a in (op.Decorate, op.MemberDecorate):
                return "decorations"
            if a in (op.Name, op.MemberName):
                return "names"
            if a in (op.Capability, op.Extension):
                return "capabilities"
            if a in (op.MemoryModel, op.ExecutionMode, op.EntryPoint):
                return "preamble"
            return "shaderstream"
        if isinstance(c, Operation):
            if c == op.ExtInstImport:
                return "preamble"
            if c in (op.TypeVoid, op.TypeBool, op.TypeInt, op.TypeFloat, op.TypeVector, op.TypeMatrix):
                return "basictypes"
            if c in (op.TypeArray, op.TypeStruct, op.TypeFunction, op.TypePointer, op.TypeImage, op.TypeSampledImage):
                return "compositetypes"
            if c == op.Constant:
                return "constants"
            if c == op.ConstantComposite:
                return "compositeconstants"
        return "shaderstream"

    def __call__(self, *args):
        c = args[2] if len(args) > 2 else 0
        line = "\t".join(self._map(a) for a in args) + "\n"
        name = self._select(args[0], c)
        setattr(self, name, getattr(self, name) + line)
        return self

    def make_same(self, a: Variable, b: Variable) -> None:
        if id(b) in self.vars:
            self.vars[id(a)] = self.vars[id(b)]

    def str(self) -> str:
        return (self.capabilities + "; ----------------- PREAMBLE -----------------\n" + self.preamble + "; ----------------- DEBUG --------------------\n" + self.names
                + "; ----------------- DECORATIONS --------------\n" + self.decorations + "; ----------------- TYPES --------------------\n" + self.basictypes
                + "; ----------------- CONSTANTS ----------------\n" + self.constants + "; ----------------- ADVANCED TYPES -----------\n" + self.compositetypes
                + ("; ----------------- CONSTANTS ----------------\n" if self.compositeconstants else "") + self.compositeconstants
                + "; ----------------- VARIABLES & FUNCTIONS ----\n" + self.shaderstream)


class Variables:
    NAMES = ("version mainFunc mainFuncLabel voidFuncVoid copy_type copy_type_vec buffer_type_vec copy_type_ptr buffer_type voidId v4f32 v4s32 v4u32 v4s64 v4u64 s32 f32 u32 s64 u64 "
             "boolean array_content_type s32_type_ptr dataSelectorStructPtrType dataSelectorStructPtr dataArrayType dataInput dataInputPtrType dataInputType dataInputSampledType "
             "dataOutput dataOutputPtrType dataOutputType dataSelectorStructType input inputPtr output outputPtr").split()

    def __init__(self):
        for name in self.NAMES:
            setattr(self, name, Variable())
        self.constants = [Variable() for _ in range(32)]


VECTOR_COPY, SCALAR_COPY, MATRIX_COPY = "vec4", "scalar", "mat4"


def make_shader(stage: str, shader_type: str, fmt: str, reads: bool, unused: bool) -> str:
    is_r64 = fmt in ("R64_UINT", "R64_SINT")
    type_for_code = SCALAR_COPY if (is_r64 and shader_type == VECTOR_COPY) else shader_type
    var = Variables()
    src = ShaderStream()
    IS = "="

    src(op.Capability, "Shader")(op.Capability, "VariablePointersStorageBuffer")
    if is_r64:
        src(op.Capability, "Int64")
    src(op.Extension, '"SPV_KHR_storage_buffer_storage_class"')(op.Extension, '"SPV_KHR_variable_pointers"')(var.version, IS, op.ExtInstImport, '"GLSL.std.450"')(op.MemoryModel, "Logical", "GLSL450")

    if stage == "compute":
        src(op.EntryPoint, "GLCompute", var.mainFunc, '"main"')(op.ExecutionMode, var.mainFunc, "LocalSize", 1, 1, 1)
    elif stage == "vertex":
        src(op.EntryPoint, "Vertex", var.mainFunc, '"main"', var.input, var.output)(op.Decorate, var.output, "BuiltIn", "Position")(op.Decorate, var.input, "Location", 0)
    elif stage == "fragment":
        src(op.EntryPoint, "Fragment", var.mainFunc, '"main"', var.output)(op.ExecutionMode, var.mainFunc, "OriginUpperLeft")(op.Decorate, var.output, "Location", 0)

    if unused:
        if stage == "fragment":
            src(var.voidId, IS, op.TypeVoid)(var.voidFuncVoid, IS, op.TypeFunction, var.voidId)(var.f32, IS, op.TypeFloat, 32)(var.v4f32, IS, op.TypeVector, var.f32, 4)(
                var.outputPtr, IS, op.TypePointer, "Output", var.v4f32)(var.output, IS, op.Variable, var.outputPtr, "Output")(var.constants[6], IS, op.Constant, var.f32, 1)(
                var.constants[7], IS, op.ConstantComposite, var.v4f32, var.constants[6], var.constants[6], var.constants[6], var.constants[6])(
                var.mainFunc, IS, op.Function, var.voidId, "None", var.voidFuncVoid)(var.mainFuncLabel, IS, op.Label)
        elif stage == "vertex":
            src(var.voidId, IS, op.TypeVoid)(var.voidFuncVoid, IS, op.TypeFunction, var.voidId)(var.f32, IS, op.TypeFloat, 32)(var.v4f32, IS, op.TypeVector, var.f32, 4)(
                var.outputPtr, IS, op.TypePointer, "Output", var.v4f32)(var.output, IS, op.Variable, var.outputPtr, "Output")(var.inputPtr, IS, op.TypePointer, "Input", var.v4f32)(
                var.input, IS, op.Variable, var.inputPtr, "Input")(var.mainFunc, IS, op.Function, var.voidId, "None", var.voidFuncVoid)(var.mainFuncLabel, IS, op.Label)
    else:
        src(op.Decorate, var.dataInput, "DescriptorSet", 0)(op.Decorate, var.dataInput, "Binding", 0)(op.Decorate, var.dataOutput, "DescriptorSet", 0)(
            op.Decorate, var.dataOutput, "Binding", 1)

        if type_for_code in (SCALAR_COPY, VECTOR_COPY):
            src(op.Decorate, var.array_content_type, "ArrayStride", 32 if is_r64 else 16)

        src(op.Decorate, var.dataArrayType, "ArrayStride", 128 if is_r64 else 64)

        src(op.MemberDecorate, var.dataOutputType, 0, "Offset", 0)(op.Decorate, var.dataOutputType, "Block")(op.MemberDecorate, var.dataInputType, 0, "NonWritable")(
            op.MemberDecorate, var.dataInputType, 0, "Offset", 0)(op.Decorate, var.dataInputType, "Block")(op.MemberDecorate, var.dataSelectorStructType, 0, "Offset", 0)(
            op.MemberDecorate, var.dataSelectorStructType, 1, "Offset", 4)(op.MemberDecorate, var.dataSelectorStructType, 2, "Offset", 8)(
            op.Decorate, var.dataSelectorStructType, "Block")(op.Decorate, var.dataSelectorStructPtr, "DescriptorSet", 0)(op.Decorate, var.dataSelectorStructPtr, "Binding", 2)(
            var.voidId, IS, op.TypeVoid)(var.voidFuncVoid, IS, op.TypeFunction, var.voidId)(var.boolean, IS, op.TypeBool)(var.f32, IS, op.TypeFloat, 32)(
            var.s32, IS, op.TypeInt, 32, 1)(var.u32, IS, op.TypeInt, 32, 0)

        if is_r64:
            src(var.s64, IS, op.TypeInt, 64, 1)(var.u64, IS, op.TypeInt, 64, 0)

        src(var.v4f32, IS, op.TypeVector, var.f32, 4)(var.v4s32, IS, op.TypeVector, var.s32, 4)(var.v4u32, IS, op.TypeVector, var.u32, 4)

        if is_r64:
            src(var.v4s64, IS, op.TypeVector, var.s64, 4)(var.v4u64, IS, op.TypeVector, var.u64, 4)

        aliases = {"R32_SINT": (var.s32, var.v4s32), "R32_UINT": (var.u32, var.v4u32), "R32_SFLOAT": (var.f32, var.v4f32), "R64_SINT": (var.s64, var.v4s64),
                   "R64_UINT": (var.u64, var.v4u64)}
        scalar, vector = aliases[fmt]
        src.make_same(var.buffer_type, scalar)
        src.make_same(var.buffer_type_vec, vector)

        if type_for_code == SCALAR_COPY:
            src.make_same(var.copy_type, var.buffer_type)
        elif type_for_code == VECTOR_COPY:
            src.make_same(var.copy_type, var.buffer_type_vec)
        else:
            assert fmt == "R32_SFLOAT", "Matrices can be used only with floating point types."
            src(var.copy_type, IS, op.TypeMatrix, var.buffer_type_vec, 4)

        c = var.constants
        src(c[0], IS, op.Constant, var.s32, 0)(c[1], IS, op.Constant, var.s32, 1)(c[2], IS, op.Constant, var.s32, 2)(c[3], IS, op.Constant, var.s32, 3)(
            c[4], IS, op.Constant, var.u32, 4)(c[5], IS, op.Constant, var.u32, 1024)

        if stage == "fragment":
            src(c[6], IS, op.Constant, var.f32, 1)(c[7], IS, op.ConstantComposite, var.v4f32, c[6], c[6], c[6], c[6])

        if type_for_code in (SCALAR_COPY, VECTOR_COPY):
            src(var.array_content_type, IS, op.TypeArray, var.buffer_type_vec, c[4])
        else:
            src.make_same(var.array_content_type, var.copy_type)

        src(var.dataArrayType, IS, op.TypeArray, var.array_content_type, c[5])(var.dataInputType, IS, op.TypeStruct, var.dataArrayType)(
            var.dataOutputType, IS, op.TypeStruct, var.dataArrayType)(var.dataInputPtrType, IS, op.TypePointer, "StorageBuffer", var.dataInputType)(
            var.dataOutputPtrType, IS, op.TypePointer, "StorageBuffer", var.dataOutputType)(var.dataInput, IS, op.Variable, var.dataInputPtrType, "StorageBuffer")(
            var.dataOutput, IS, op.Variable, var.dataOutputPtrType, "StorageBuffer")(var.dataSelectorStructType, IS, op.TypeStruct, var.s32, var.s32, var.s32)(
            var.dataSelectorStructPtrType, IS, op.TypePointer, "Uniform", var.dataSelectorStructType)(var.dataSelectorStructPtr, IS, op.Variable, var.dataSelectorStructPtrType,
                                                                                                         "Uniform")

        if stage == "vertex":
            src(var.inputPtr, IS, op.TypePointer, "Input", var.v4f32)(var.input, IS, op.Variable, var.inputPtr, "Input")(var.outputPtr, IS, op.TypePointer, "Output", var.v4f32)(
                var.output, IS, op.Variable, var.outputPtr, "Output")
        elif stage == "fragment":
            src(var.outputPtr, IS, op.TypePointer, "Output", var.v4f32)(var.output, IS, op.Variable, var.outputPtr, "Output")

        src(var.copy_type_ptr, IS, op.TypePointer, "StorageBuffer", var.copy_type)(var.s32_type_ptr, IS, op.TypePointer, "Uniform", var.s32)

        src(var.mainFunc, IS, op.Function, var.voidId, "None", var.voidFuncVoid)(var.mainFuncLabel, IS, op.Label)

        copy_from_ptr, copy_to_ptr, zero_ptr = Variable(), Variable(), Variable()
        copy_from, copy_to, zero = Variable(), Variable(), Variable()

        src(copy_to_ptr, IS, op.AccessChain, var.s32_type_ptr, var.dataSelectorStructPtr, c[1])(copy_to, IS, op.Load, var.s32, copy_to_ptr)(
            copy_from_ptr, IS, op.AccessChain, var.s32_type_ptr, var.dataSelectorStructPtr, c[0])(copy_from, IS, op.Load, var.s32, copy_from_ptr)(
            zero_ptr, IS, op.AccessChain, var.s32_type_ptr, var.dataSelectorStructPtr, c[2])(zero, IS, op.Load, var.s32, zero_ptr)

        def copy(indices_from: list, indices_to: list) -> None:
            actual_load, actual_store, load_result = Variable(), Variable(), Variable()
            selection = Variable()
            lc_a, lc_b, sc_a, sc_b = Variable(), Variable(), Variable(), Variable()
            src(selection, IS, op.IEqual, var.boolean, zero, c[0])
            if reads:
                src(lc_a, IS, op.AccessChain, var.copy_type_ptr, var.dataInput, c[0], copy_from, *indices_from)(
                    lc_b, IS, op.AccessChain, var.copy_type_ptr, var.dataInput, c[0], copy_from, *indices_from)(
                    actual_load, IS, op.Select, var.copy_type_ptr, selection, lc_a, lc_b)(
                    actual_store, IS, op.AccessChain, var.copy_type_ptr, var.dataOutput, c[0], copy_to, *indices_to)
            else:
                src(actual_load, IS, op.AccessChain, var.copy_type_ptr, var.dataInput, c[0], copy_from, *indices_from)(
                    sc_a, IS, op.AccessChain, var.copy_type_ptr, var.dataOutput, c[0], copy_to, *indices_to)(
                    sc_b, IS, op.AccessChain, var.copy_type_ptr, var.dataOutput, c[0], copy_to, *indices_to)(
                    actual_store, IS, op.Select, var.copy_type_ptr, selection, sc_a, sc_b)
            src(load_result, IS, op.Load, var.copy_type, actual_load)(op.Store, actual_store, load_result)

        if type_for_code == SCALAR_COPY:
            for i in range(4):
                for j in range(4):
                    copy([c[i], c[j]], [c[i], c[j]])
        elif type_for_code == VECTOR_COPY:
            for i in range(4):
                copy([c[i]], [c[i]])
        else:
            copy([], [])

    if stage == "vertex":
        input_value, output_location = Variable(), Variable()
        src(input_value, IS, op.Load, var.v4f32, var.input)(output_location, IS, op.AccessChain, var.outputPtr, var.output)(op.Store, output_location, input_value)
    elif stage == "fragment":
        src(op.Store, var.output, var.constants[7])

    src(op.Return)(op.FunctionEnd)
    return src.str()


FORMATS = [("R32_SINT", "s32"), ("R32_UINT", "u32"), ("R32_SFLOAT", "f32"), ("R64_SINT", "s64"), ("R64_UINT", "u64")]
TYPES = [(VECTOR_COPY, "vec4"), (SCALAR_COPY, "scalar")]


def py(value) -> str:
    return json.dumps(repr(value))


def main() -> None:
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    for name in ("src_compute", "src_vertex", "src_fragment"):
        (TEMPLATE_DIR / f"{name}.spvasm").write_text("${" + name + "}")

    entries = []
    table = []
    for stage in ("vertex", "fragment", "compute"):
        for shader_type, type_name in TYPES:
            for fmt, fmt_name in FORMATS:
                for reads in (True, False):
                    key = f"{stage}.{type_name}.{fmt_name}.{'r' if reads else 'w'}"
                    const = "VP_" + key.upper().replace(".", "_")
                    if stage == "compute":
                        programs = {"compute": make_shader("compute", shader_type, fmt, reads, False)}
                    else:
                        programs = {"vertex": make_shader("vertex", shader_type, fmt, reads, stage != "vertex"), "fragment": make_shader("fragment", shader_type, fmt, reads, stage != "fragment")}
                    program_text = ", ".join(f'{{ name = "{name}", template = "robustness/variable_pointers/src_{name}.spvasm", stage = "asm" }}' for name in programs)
                    derived = ", ".join(f"src_{name} = {py(text)}" for name, text in programs.items())
                    entries.append(f'\n[[case]]\nname = "{key.replace(".", "_")}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\nprograms = [{program_text}]\nderived = {{ {derived} }}\n')
                    table.append((key, const))
    MANIFEST.write_text(HEADER + "".join(entries))

    table.sort()
    lines = [
        "// @generated by hodow_cts/scripts/gen_robustness_variable_pointers_manifest.py - do not hand-edit.",
        "//",
        "// The programs of every case `variable_pointers_tests.rs` registers, by `<stage>.<type>.<format>.<r|w>`, sorted by key.",
        "",
        "use crate::generated::shaders::robustness_variable_pointers::*;",
        "use crate::vk::programs::SharedProgram;",
        "",
        "pub static PROGRAM_TABLE: &[(&str, &SharedProgram)] = &[",
    ]
    lines += [f'    ("{key}", &{const}),' for key, const in table]
    lines.append("];")
    PROGRAM_TABLE.write_text("\n".join(lines) + "\n")
    print(f"{len(entries)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
