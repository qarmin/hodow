#!/usr/bin/env python3
"""Generate the desktop OpenGL core-profile loaders for `glw::Functions`.

`glw::Functions` (src/generated/glw.rs, from `gen_api_wrappers.py`) already declares every
desktop core entry point and every enumerant, because upstream's `glwFunctionTypes.inl` and
`glwEnums.inl` come from the full registry. What upstream's ES-only checkout lacks are the
desktop `glwInitGL*.inl` loaders, so no desktop function is ever filled in. This reads gl.xml
(the Khronos registry) and emits those loaders:

    src/generated/glw_core.rs   Functions::load_gl_1_0 ... load_gl_4_6, load_gl_core, missing_gl_core

Each `load_gl_X_Y` loads what that version adds to the core profile and keeps through 4.6
(`<remove profile="core">` entries are honoured), so `load_gl_core(4, 5, ..)` is exactly the
core profile of 4.5 minus whatever 4.6 removed - which is nothing so far.

gl.xml is not vendored (2 MB, and only needed to regenerate). Default location is the copy in
the `khronos_api` crate of the cargo registry; `--registry` or $HODOW_GL_XML overrides.

Usage:
    python3 hodow_cts/scripts/gen_gl_core_loaders.py [--registry gl.xml] [--check]
"""

from __future__ import annotations

import argparse
import glob
import os
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_api_wrappers import CRATE_DIR, GENERATED_DIR, rust_ident, rustfmt  # noqa: E402

NO_REGISTRY = 3
OUTPUT = GENERATED_DIR / "glw_core.rs"


def find_registry(explicit: Path | None) -> Path:
    candidates = [explicit] if explicit else []
    if os.environ.get("HODOW_GL_XML"):
        candidates.append(Path(os.environ["HODOW_GL_XML"]))
    candidates += [Path(p) for p in sorted(glob.glob(str(Path.home() / ".cargo/registry/src/*/khronos_api-*/api/xml/gl.xml")))]
    for path in candidates:
        if path and path.is_file():
            return path
    print("error: no gl.xml found; pass --registry or set HODOW_GL_XML (the khronos_api crate ships one)", file=sys.stderr)
    raise SystemExit(NO_REGISTRY)


def core_additions(registry: Path) -> list[tuple[str, list[str]]]:
    """(version, commands) per `<feature api="gl">`, in order, for the core profile."""
    root = ET.parse(registry).getroot()
    present: set[str] = set()
    added_in: dict[str, str] = {}
    versions: list[str] = []
    for feature in root.findall("feature"):
        if feature.get("api") != "gl":
            continue
        version = feature.get("number")
        versions.append(version)
        for child in feature:
            profile = child.get("profile")
            names = [c.get("name") for c in child.findall("command")]
            if child.tag == "require" and profile in (None, "core"):
                for name in names:
                    if name not in present:
                        present.add(name)
                        added_in[name] = version
            elif child.tag == "remove" and profile == "core":
                for name in names:
                    present.discard(name)
    return [(v, sorted(n for n in present if added_in[n] == v)) for v in versions]


def emit(additions: list[tuple[str, list[str]]], registry: Path) -> str:
    out: list[str] = []
    w = out.append
    w("// Generated by hodow_cts/scripts/gen_gl_core_loaders.py from the Khronos gl.xml registry.")
    w("// Do not edit by hand: regeneration must stay diff-clean.")
    w("")
    w("#![allow(clippy::missing_safety_doc)]")
    w("")
    w("use std::ffi::c_void;")
    w("")
    w("use super::glw::Functions;")
    w("")
    w("/// # Safety")
    w("/// `p` must be null or a pointer to a function with `F`'s signature.")
    w("#[inline]")
    w("unsafe fn cast<F>(p: *const c_void) -> Option<F> {")
    w("    if p.is_null() { None } else { Some(unsafe { std::mem::transmute_copy(&p) }) }")
    w("}")
    w("")
    w("impl Functions {")
    for version, commands in additions:
        suffix = version.replace(".", "_")
        w(f"    /// What desktop OpenGL {version} adds to the core profile ({len(commands)} entry points).")
        w(f"    pub fn load_gl_{suffix}(&mut self, get: &mut dyn FnMut(&str) -> *const c_void) {{")
        if not commands:
            w("        let _ = get;")
        for name in commands:
            field = rust_ident(name[2:])
            w(f'        self.{field} = unsafe {{ cast(get("{name}")) }};')
        w("    }")
        w("")
    w("    /// The whole core profile up to and including `major.minor`.")
    w("    pub fn load_gl_core(&mut self, major: i32, minor: i32, get: &mut dyn FnMut(&str) -> *const c_void) {")
    for version, _ in additions:
        suffix = version.replace(".", "_")
        maj, mnr = version.split(".")
        w(f"        if (major, minor) >= ({maj}, {mnr}) {{")
        w(f"            self.load_gl_{suffix}(get);")
        w("        }")
    w("    }")
    w("")
    w("    /// Names of core entry points up to `major.minor` the driver did not export, in version")
    w("    /// order. Only meaningful after `load_gl_core`.")
    w("    pub fn missing_gl_core(&self, major: i32, minor: i32) -> Vec<&'static str> {")
    w("        let mut missing = Vec::new();")
    for version, commands in additions:
        maj, mnr = version.split(".")
        if not commands:
            continue
        w(f"        if (major, minor) >= ({maj}, {mnr}) {{")
        for name in commands:
            w(f'            if self.{rust_ident(name[2:])}.is_none() {{ missing.push("{name}"); }}')
        w("        }")
    w("        missing")
    w("    }")
    w("}")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--registry", type=Path, help="path to gl.xml")
    ap.add_argument("--check", action="store_true", help="fail if the generated output would change")
    args = ap.parse_args()

    registry = find_registry(args.registry)
    text = rustfmt(emit(core_additions(registry), registry))

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"error: {OUTPUT.relative_to(CRATE_DIR)} is stale; re-run gen_gl_core_loaders.py", file=sys.stderr)
            return 1
        print("generated desktop GL loaders are up to date")
        return 0

    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(CRATE_DIR)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
