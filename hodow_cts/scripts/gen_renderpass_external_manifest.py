#!/usr/bin/env python3
"""Writes shaders/manifest/renderpass_subpass_dependencies_external.toml and its templates: `ExternalPrograms::init` of
vktRenderPassSubpassDependencyTests.cpp (external_subpass and implicit_dependencies).

One entry per (render size, render pass count): `quad-vert-<n>` and `quad-frag-<n>` for every pass, the first pass drawing four coloured
quarters and the following ones blurring the previous result horizontally (even index) or vertically (odd index) with a kernel of 12 + 1 taps.

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
TEMPLATES = CRATE / "shaders" / "src" / "renderpass" / "subpass_dependencies"
MANIFEST = CRATE / "shaders" / "manifest" / "renderpass_subpass_dependencies_external.toml"
SIZES = [64, 128, 512]
COUNTS = [2, 3, 5]
BLUR_KERNEL = 12

QUAD_VERT = """#version 450
layout(location = 0) out highp vec2 vtxTexCoords;
highp float;
void main (void)
{
    vec4 position;    position = vec4(((gl_VertexIndex + 2) / 3) % 2 == 0 ? -1.0 : 1.0,
                    ((gl_VertexIndex + 1) / 3) % 2 == 0 ? -1.0 : 1.0, 0.0, 1.0);
    gl_Position = position;
    vtxTexCoords = position.xy / 2.0 + vec2(0.5);}
"""

FIRST_FRAG = """#version 450
layout(location = 0) in highp vec2 vtxTexCoords;
layout(location = 0) out highp vec4 o_color;
void main (void)
{
    if (gl_FragCoord.x <= ${half_w} && gl_FragCoord.y <= ${half_h})
        o_color = vec4(1.0, 0.0, 0.0, 1.0);
    else if (gl_FragCoord.x > ${half_w} && gl_FragCoord.y <= ${half_h})
        o_color = vec4(0.0, 1.0, 0.0, 1.0);
    else if (gl_FragCoord.x <= ${half_w} && gl_FragCoord.y > ${half_h})
        o_color = vec4(0.0, 0.0, 1.0, 1.0);
    else
        o_color = vec4(0.0, 0.0, 0.0, 1.0);
}
"""

BLUR_FRAG = """#version 450
layout(binding = 0) uniform ${sampler_qualifier}sampler2D previousPass;
layout(location = 0) in highp vec2 vtxTexCoords;
layout(location = 0) out highp vec4 o_color;
void main (void)
{
    vec2 step = vec2(1.0 / ${w}, 1.0 / ${h});
    vec2 minCoord = vec2(0.0, 0.0);
    vec2 maxCoord = vec2(1.0, 1.0);
    vec4 blurColor = vec4(0.0);
    for(int sampleNdx = 0; sampleNdx < ${taps}; sampleNdx++)
    {
        vec2 sampleCoord = ${sample_coord};
        blurColor += 0.12 * texture(previousPass, clamp(sampleCoord, minCoord, maxCoord));
    }
    o_color = blurColor;
}
"""

SAMPLE_H = "vec2((vtxTexCoords.x - ${half_k} * step.x) + step.x * sampleNdx, vtxTexCoords.y)"
SAMPLE_V = "vec2(vtxTexCoords.x, (vtxTexCoords.y - ${half_k} * step.y) + step.y * sampleNdx)"


def main() -> None:
    TEMPLATES.mkdir(parents=True, exist_ok=True)
    (TEMPLATES / "external_quad.vert").write_text(QUAD_VERT)
    (TEMPLATES / "external_first.frag").write_text(FIRST_FRAG)
    (TEMPLATES / "external_blur_h.frag").write_text(
        BLUR_FRAG.replace("${sampler_qualifier}", "").replace("${sample_coord}", SAMPLE_H)
    )
    (TEMPLATES / "external_blur_v.frag").write_text(
        BLUR_FRAG.replace("${sampler_qualifier}", "highp ").replace("${sample_coord}", SAMPLE_V)
    )

    out = [
        "# Shader manifest for dEQP-VK.renderpasses.*.subpass_dependencies.{external_subpass,implicit_dependencies}.*",
        "#",
        "# @generated by hodow_cts/scripts/gen_renderpass_external_manifest.py - do not hand-edit.",
        "#",
        "# `ExternalPrograms::init`: a quad vertex shader and a fragment shader per render pass, per render size.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/renderpass/vktRenderPassSubpassDependencyTests.cpp"',
        'rust_module = "renderpass/subpass_dependency_external_tests"',
    ]
    for size in SIZES:
        for count in COUNTS:
            programs = []
            for i in range(count):
                programs.append(f'    {{ name = "quad-vert-{i}", template = "renderpass/subpass_dependencies/external_quad.vert", stage = "vert" }},')
                if i == 0:
                    frag = "external_first.frag"
                elif i % 2 == 0:
                    frag = "external_blur_h.frag"
                else:
                    frag = "external_blur_v.frag"
                programs.append(f'    {{ name = "quad-frag-{i}", template = "renderpass/subpass_dependencies/{frag}", stage = "frag" }},')
            out += [
                "",
                "[[case]]",
                f'name = "external_{size}_{count}"',
                f'rust_const = "EXTERNAL_{size}_{count}"',
                'rust_type = "SharedProgram"',
                "programs = [",
                *programs,
                "]",
                f'derived = {{ w = "{size}", h = "{size}", half_w = "{size // 2}", half_h = "{size // 2}", taps = "{BLUR_KERNEL + 1}", half_k = "{BLUR_KERNEL // 2}" }}',
            ]
    MANIFEST.write_text("\n".join(out) + "\n")
    print(f"{len(SIZES) * len(COUNTS)} entries -> {MANIFEST}")


if __name__ == "__main__":
    main()
