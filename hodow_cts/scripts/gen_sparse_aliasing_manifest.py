#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.sparse_resources.image_sparse_memory_aliasing.<type>.<format>.<size>.

`ImageSparseMemoryAliasingCase::initPrograms` for the formats with a single plane: one compute shader per mip level of the image, storing
`index % 127` (or its float form) where `index` is the linear position of the texel in the level. The manifest cannot give a program its
own parameters, so every (case, mip level) is a manifest entry of its own, named `alias_<type>_<format>_<x>_<y>_<z>_m<mip>`, holding the
one program `comp0`; image_memory_aliasing_tests.rs looks the entry up by `alias_key`, as the test case builds no collection of its own.
The level count is the one `initPrograms` computes (a device limit of 20 levels).

A pure text generator: no glslang and no cargo.
"""

import json
import math
import re
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "sparse_resources_image_aliasing.toml"

HEADER = """# Shader manifest for dEQP-VK.sparse_resources.image_sparse_memory_aliasing.<type>.<format>.<size>
#
# @generated by hodow_cts/scripts/gen_sparse_aliasing_manifest.py - do not hand-edit.
#
# `ImageSparseMemoryAliasingCase::initPrograms`, one entry per image type, format, size and mip level.

upstream_source = "external/vulkancts/modules/vulkan/sparse_resources/vktSparseResourcesImageMemoryAliasing.cpp"
rust_module = "sparse_resources/image_memory_aliasing_tests"
"""

FORMATS = [
    "R64_SINT", "R32_SINT", "R16_SINT", "R8_SINT", "R64_UINT", "R32_UINT", "R16_UINT", "R8_UINT", "R16_UNORM", "R8_UNORM", "R16_SNORM",
    "R8_SNORM", "R32G32_SINT", "R16G16_SINT", "R8G8_SINT", "R32G32_UINT", "R16G16_UINT", "R8G8_UINT", "R16G16_UNORM", "R8G8_UNORM",
    "R16G16_SNORM", "R8G8_SNORM", "R32G32B32A32_SINT", "R16G16B16A16_SINT", "R8G8B8A8_SINT", "R32G32B32A32_UINT", "R16G16B16A16_UINT",
    "R8G8B8A8_UINT", "R16G16B16A16_UNORM", "R8G8B8A8_UNORM", "R16G16B16A16_SNORM", "R8G8B8A8_SNORM",
]

TYPES = [
    ("2d", "2D", [(512, 256, 1), (128, 128, 1), (503, 137, 1), (11, 37, 1)]),
    ("2d_array", "2DArray", [(512, 256, 6), (128, 128, 8), (503, 137, 3), (11, 37, 3)]),
    ("cube", "Cube", [(256, 256, 1), (128, 128, 1), (137, 137, 1), (11, 11, 1)]),
    ("cube_array", "CubeArray", [(256, 256, 6), (128, 128, 8), (137, 137, 3), (11, 11, 3)]),
    ("3d", "3D", [(256, 256, 16), (128, 128, 8), (503, 137, 3), (11, 37, 3)]),
]


def layer_size(type_name: str, size: tuple) -> tuple:
    return (size[0], size[1], size[2]) if type_name == "3d" else (size[0], size[1], 1)


def grid_size(type_name: str, size: tuple, mip: int) -> tuple:
    x = max(size[0] >> mip, 1)
    y = max(size[1] >> mip, 1)
    z = max(size[2] >> mip, 1)
    return {
        "2d": (x, y, 1),
        "2d_array": (x, y, size[2]),
        "cube": (x, y, 6),
        "cube_array": (x, y, 6 * size[2]),
        "3d": (x, y, z),
    }[type_name]


def work_group_size(extent: tuple) -> tuple:
    invocations = 128
    wx = min(min(extent[0], 128), invocations)
    wy = min(min(extent[1], 128), invocations // wx)
    wz = min(min(extent[2], 64), invocations // (wx * wy))
    return wx, wy, wz


def parse(name: str) -> dict:
    match = re.fullmatch(r"((?:[RGBA]\d+)+)_(SINT|UINT|UNORM|SNORM)", name)
    channels = re.findall(r"([RGBA])(\d+)", match.group(1))
    letters = "".join(c.lower() for c, _ in channels)
    bits = int(channels[0][1])
    kind = match.group(2)
    suffix = {"SINT": "i", "UINT": "ui", "UNORM": "", "SNORM": "_snorm"}[kind]
    r64 = bits == 64
    return {
        "id": f"{letters}{bits}{suffix}",
        "integer": kind in ("SINT", "UINT"),
        "r64": r64,
        "image_prefix": {"SINT": "i", "UINT": "u"}.get(kind, "") + ("64" if r64 else ""),
        "data_type": {"SINT": "i64vec4", "UINT": "u64vec4"}[kind] if r64 else {"SINT": "ivec4", "UINT": "uvec4"}.get(kind, "vec4"),
    }


def values(fmt: dict) -> str:
    if fmt["integer"]:
        return "(index % 127, index % 127, index % 127, 1)"
    return "(float(index % 127) / 127.0, float(index % 127) / 127.0, float(index % 127) / 127.0, 1.0)"


def py(value) -> str:
    return json.dumps(repr(value))


def main() -> None:
    out = [HEADER]
    count = 0
    for type_name, glsl, sizes in TYPES:
        coord = "ivec2(gl_GlobalInvocationID.x,gl_GlobalInvocationID.y)" if type_name == "2d" else "ivec3(gl_GlobalInvocationID.x,gl_GlobalInvocationID.y,gl_GlobalInvocationID.z)"
        for name in FORMATS:
            fmt = parse(name)
            extensions = ""
            if fmt["r64"]:
                extensions = "#extension GL_EXT_shader_explicit_arithmetic_types_int64 : require\n#extension GL_EXT_shader_image_int64 : require"
            for size in sizes:
                layer = layer_size(type_name, size)
                mip_levels = min(int(math.log2(max(layer))) + 1, 20)
                for mip in range(mip_levels):
                    grid = grid_size(type_name, size, mip)
                    wx, wy, wz = work_group_size(grid)
                    key = f"alias_{type_name}_{fmt['id']}_{size[0]}_{size[1]}_{size[2]}_m{mip}"
                    derived = {
                        "extensions": extensions,
                        "wx": wx, "wy": wy, "wz": wz,
                        "qualifier": fmt["id"],
                        "image_type": f"{fmt['image_prefix']}image{glsl}",
                        "w": grid[0], "h": grid[1], "d": grid[2],
                        "gx": grid[0], "gy": grid[1],
                        "coord": coord,
                        "data_type": fmt["data_type"],
                        "values": values(fmt),
                    }
                    derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
                    out.append(
                        f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "comp0", template = "sparse_resources/residency/alias.comp", stage = "comp" }}]
derived = {{ {derived_text} }}
"""
                    )
                    count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
