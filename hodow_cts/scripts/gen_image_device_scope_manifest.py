#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.image.device_scope_access.*.

`LoadStoreTest::makePrograms` with a device scope type: a compute shader that loads a texel and stores it mirrored horizontally and then
makes the store available at device scope (`comp_store`), a second one that makes the image visible and copies it back unchanged (`comp_load`),
and for the draw configuration a vertex and a fragment shader that make the image visible and read it into the colour attachment. They depend on
the texture type and the format (the format is always declared), so there is one entry per (type, format), found by `device_scope_key` in
device_scope_tests.rs; the 3d entries have no draw shaders. The format tables are those of gen_image_store_manifest.py.

A pure text generator: no glslang and no cargo.
"""

import json
from pathlib import Path

import gen_image_store_manifest as store

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "image_device_scope.toml"

HEADER = """# Shader manifest for dEQP-VK.image.device_scope_access.*
#
# @generated by hodow_cts/scripts/gen_image_device_scope_manifest.py - do not hand-edit.
#
# `LoadStoreTest::makePrograms` for the device scope store and load, one entry per texture type and format.

upstream_source = "external/vulkancts/modules/vulkan/image/vktImageLoadStoreTests.cpp"
rust_module = "image/device_scope_tests"
"""

TEXTURES = [t for t in store.TEXTURES if t[0] in ("1d", "2d", "3d")]


def py(value) -> str:
    return json.dumps(repr(value))


def body(dimension: int, x_sub: str) -> str:
    return {
        1: f"    int pos = int(gl_GlobalInvocationID.x);\n    imageStore(u_image1, pos, imageLoad(u_image0, {x_sub}pos));\n",
        2: f"    ivec2 pos = ivec2(gl_GlobalInvocationID.xy);\n    imageStore(u_image1, pos, imageLoad(u_image0, ivec2({x_sub}pos.x, pos.y)));\n",
        3: f"    ivec3 pos = ivec3(gl_GlobalInvocationID);\n    imageStore(u_image1, pos, imageLoad(u_image0, ivec3({x_sub}pos.x, pos.y, pos.z)));\n",
    }[dimension]


def frag_body(dimension: int) -> str:
    return {
        1: "    int pos = int(gl_FragCoord.x);\n    outcolor = imageLoad(u_image0, pos);\n",
        2: "    ivec2 pos = ivec2(gl_FragCoord.xy);\n    outcolor = imageLoad(u_image0, ivec2(pos.x, pos.y));\n",
    }[dimension]


def main() -> None:
    out = [HEADER]
    count = 0
    for texture in TEXTURES:
        type_name, dimension, _, x_max, _, _, shader_type, _ = texture
        for name in store.S_FORMATS:
            info = store.format_info(name)
            if not info["qualifier"]:
                continue
            image_prefix = {"uint": "u", "int": "i"}.get(info["cls"], "")
            color_type = image_prefix + "vec4"
            derived = {
                "qualifier": info["qualifier"],
                "image_type": f"{image_prefix}image{shader_type}",
                "store_body": body(dimension, f"{x_max}-"),
                "load_body": body(dimension, ""),
                "color_type": color_type,
            }
            programs = [
                '{ name = "comp_store", template = "image/device_scope_store.comp", stage = "comp", spirv_version = "spirv1.3" }',
                '{ name = "comp_load", template = "image/device_scope_load.comp", stage = "comp", spirv_version = "spirv1.3" }',
            ]
            if type_name != "3d":
                derived["frag_body"] = frag_body(dimension)
                programs.append('{ name = "vert", template = "image/device_scope.vert", stage = "vert" }')
                programs.append('{ name = "frag", template = "image/device_scope.frag", stage = "frag", spirv_version = "spirv1.3" }')
            key = f"ds_{type_name}_{name.lower()}"
            program_text = ",\n    ".join(programs)
            derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
            out.append(
                f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [
    {program_text},
]
derived = {{ {derived_text} }}
"""
            )
            count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
