def py(value) -> str:
    return json.dumps(repr(value))


def format_info(name: str) -> dict:
    if name in PACKED:
        cls, nch, depths, range_key = PACKED[name]
    else:
        match = re.fullmatch(r"((?:[RGBA]\d+)+)_(UINT|SINT|UNORM|SNORM|SFLOAT|SRGB)", name)
        channels = re.findall(r"[RGBA](\d+)", match.group(1))
        cls = CLASS[match.group(2)]
        bits = int(channels[0])
        nch = len(channels)
        depths = ([bits] * nch + [0] * 4)[:4]
        range_key = {"uint": f"uint{bits}", "int": f"sint{bits}", "unorm": "unorm", "snorm": "snorm", "float": f"float{bits}"}[cls]
    return {"name": name, "cls": cls, "nch": nch, "depths": depths, "range_key": range_key, "qualifier": QUALIFIERS.get(name)}


def middle_value(info: dict) -> list:
    """`getMiddleValue`"""
    key = info["range_key"]
    if key == "uint1010102":
        maxima = [1023.0, 1023.0, 1023.0, 3.0]
        minima = [0.0] * 4
    elif key == "sint1010102":
        maxima = [511.0, 511.0, 511.0, 1.0]
        minima = [-512.0, -512.0, -512.0, -2.0]
    else:
        low, high = RANGES[key]
        maxima = [high if i < info["nch"] else 0.0 for i in range(4)]
        minima = [low if i < info["nch"] else 0.0 for i in range(4)]
    values = [(maxima[i] - minima[i]) * 0.5 for i in range(4)]
    if info["cls"] in ("uint", "int"):
        values = [math.floor(v) for v in values]
    return values


def number(value) -> str:
    """`de::toString` of a float or of a truncated integer"""
    if float(value) == int(value):
        return str(int(value))
    return f"{value:g}"


def representable(value: int, info: dict) -> bool:
    for channel in range(info["nch"]):
        if info["cls"] == "uint":
            if value > 0 and math.floor(math.log2(value) + 1) > info["depths"][channel]:
                return False
        else:
            if value != 0 and math.floor(math.log2(abs(value)) + 1) + 1 > info["depths"][channel]:
                return False
    return True


def color_expression(info: dict, x_max: int, y_max: int, constant: bool) -> str:
    cls = info["cls"]
    prefix = "u" if cls == "uint" else "i" if cls == "int" else ""
    color_type = prefix + "vec4"
    if constant:
        values = middle_value(info)
        if cls in ("uint", "int"):
            return color_type, f"{color_type}(" + ", ".join(str(int(v)) for v in values) + ")"
        return color_type, f"{color_type}(" + ", ".join(number(v) for v in values) + ")"

    base = f"{color_type}(gx^gy^gz, ({x_max}-gx)^gy^gz, gx^({y_max}-gy)^gz, ({x_max}-gx)^({y_max}-gy)^gz)"
    scale = 1.0
    bias = 0.0
    if cls == "unorm":
        scale = 1.0 / 63.0
    elif cls == "snorm":
        scale = 2.0 / 63.0
        bias = -1.0
    is_signed = cls in ("int", "snorm", "float") and not (cls == "float" and info["name"] in ("B10G11R11_UFLOAT_PACK32", "E5B9G9R9_UFLOAT_PACK32"))
    store_negative = is_signed and bias == 0.0
    half = math.floor(max(x_max, y_max) / 2.0 + 0.5)
    use_clamp = False
    if cls in ("uint", "int"):
        min_value = -half if store_negative else 0
        max_value = half if store_negative else max(x_max, y_max)
        use_clamp = not representable(min_value, info) or not representable(max_value, info)
    if use_clamp:
        depths = info["depths"]
        if cls == "uint":
            low = [0, 0, 0, 0]
            high = [(1 << d) - 1 for d in depths]
        else:
            low = [-(1 << (d - 1)) for d in depths]
            high = [(1 << (d - 1)) - 1 for d in depths]
        base = f"clamp({base}, {color_type}({', '.join(map(str, low))}), {color_type}({', '.join(map(str, high))}))"
    expression = base
    if scale != 1.0:
        expression += "*" + f"{scale:g}"
    if bias != 0.0:
        expression += f" + float({number(bias)})"
    if store_negative:
        expression += f"-{half}"
    return color_type, expression


def entry(texture: tuple, info: dict, with_format: bool, single_layer: bool, constant: bool) -> tuple:
    type_name, dimension, layer_dimension, x_max, y_max, _, shader_type, single_type = texture
    color_type, expression = color_expression(info, x_max, y_max, constant)
    used_dimension = layer_dimension if single_layer else dimension
    coordinate = {1: "gx", 2: "ivec2(gx, gy)", 3: "ivec3(gx, gy, gz)"}[used_dimension]
    image_type_name = single_type if single_layer else shader_type
    image_prefix = {"uint": "u", "int": "i"}.get(info["cls"], "")
    derived = {
        "format_qualifier": f", {info['qualifier']}" if with_format else "",
        "image_type": f"{image_prefix}image{image_type_name}",
        "layer_block": "layout (binding = 1) readonly uniform Constants {\n    int u_layerNdx;\n};\n" if single_layer else "",
        "gz": "u_layerNdx" if single_layer else "int(gl_GlobalInvocationID.z)",
        "color_type": color_type,
        "color_expression": expression,
        "texel_coordinate": coordinate,
    }
    key = f"st_{type_name}_{info['name'].lower()}_{int(with_format)}{int(single_layer)}{int(constant)}"
    return key, derived


def emit(key: str, derived: dict) -> str:
    derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
    return f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "comp", template = "image/store.comp", stage = "comp" }}]
derived = {{ {derived_text} }}
"""


def main() -> None:
    out = [HEADER]
    seen = set()
    for texture in TEXTURES:
        layered = texture[5]
        for name in S_FORMATS:
            info = format_info(name)
            combos = [(False, False, False)]
            if info["qualifier"]:
                combos += [(True, False, False), (True, False, True)]
                if layered:
                    combos.append((True, True, False))
            for with_format, single_layer, constant in combos:
                key, derived = entry(texture, info, with_format, single_layer, constant)
                if key not in seen:
                    seen.add(key)
                    out.append(emit(key, derived))
    MANIFEST.write_text("".join(out))
    print(f"{len(seen)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
