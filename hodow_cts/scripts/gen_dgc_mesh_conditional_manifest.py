#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.graphics.mesh.conditional_rendering (`onePointPerPixelPrograms` of
vktDGCGraphicsMeshConditionalTestsExt.cpp), one shared program set without and one with a task shader. A pure text generator: no glslang,
no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_mesh_conditional.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

WIDTH = 2

FRAG = (
    "#version 460\n"
    "layout (location=0) out vec4 outColor;\n"
    "layout (push_constant, std430) uniform PCBlock { vec4 color; } pc;\n"
    "void main (void) {\n"
    "    outColor = pc.color;\n"
    "}\n"
)

WG_INDEX_FUNC = (
    "uint getWorkGroupIndex (void) {\n"
    "    const uint workGroupIndex = gl_NumWorkGroups.x * gl_NumWorkGroups.y * gl_WorkGroupID.z +\n"
    "                                gl_NumWorkGroups.x * gl_WorkGroupID.y +\n"
    "                                gl_WorkGroupID.x;\n"
    "    return workGroupIndex;\n"
    "}\n"
)

TASK_DATA_DECL = "struct TaskData {\n    uint baseVertex;\n};\ntaskPayloadSharedEXT TaskData td;\n"

BINDING_DECL = (
    "layout(set=0, binding=0, std430) readonly buffer VertexDataBlock {\n"
    "    vec4 positions[];\n"
    "} vertices;\n"
)


def task():
    return (
        "#version 460\n"
        "#extension GL_EXT_mesh_shader : enable\n"
        "layout(local_size_x=1) in;\n"
        + WG_INDEX_FUNC
        + TASK_DATA_DECL
        + "void main (void) {\n"
        f"    td.baseVertex = getWorkGroupIndex() * {WIDTH};\n"
        f"    EmitMeshTasksEXT(1, 1, {WIDTH});\n"
        "}\n"
    )


def mesh(task_shader):
    local_size = 1 if task_shader else WIDTH
    vert_index = "td.baseVertex + getWorkGroupIndex()" if task_shader else f"getWorkGroupIndex() * {WIDTH} + gl_LocalInvocationIndex"
    return (
        "#version 460\n"
        "#extension GL_EXT_mesh_shader : enable\n"
        f"layout(local_size_x={local_size}) in;\n"
        "layout(points) out;\n"
        f"layout(max_vertices={local_size}, max_primitives={local_size}) out;\n"
        + BINDING_DECL
        + WG_INDEX_FUNC
        + (TASK_DATA_DECL if task_shader else "")
        + "void main() {\n"
        f"    SetMeshOutputsEXT({local_size}, {local_size});\n"
        f"    const uint vertIndex = {vert_index};\n"
        "    gl_MeshVerticesEXT[gl_LocalInvocationIndex].gl_Position = vertices.positions[vertIndex];\n"
        "    gl_MeshVerticesEXT[gl_LocalInvocationIndex].gl_PointSize = 1.0;\n"
        "    gl_PrimitivePointIndicesEXT[gl_LocalInvocationIndex] = gl_LocalInvocationIndex;\n"
        "}\n"
    )


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    manifest = (
        "# Shader manifest for dEQP-VK.dgc.ext.graphics.mesh.conditional_rendering\n"
        "#\n"
        "# @generated by hodow_cts/scripts/gen_dgc_mesh_conditional_manifest.py - do not hand-edit.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCGraphicsMeshConditionalTestsExt.cpp"\n'
        'rust_module = "dgc/graphics_mesh_conditional_tests"\n'
    )
    (SRC_DIR / "mesh_cond_frag.frag").write_text(FRAG)
    for task_shader in (False, True):
        suffix = "_task" if task_shader else ""
        (SRC_DIR / f"mesh_cond{suffix}_mesh.mesh").write_text(mesh(task_shader))
        programs = []
        if task_shader:
            (SRC_DIR / "mesh_cond_task_task.task").write_text(task())
            programs.append('{ name = "task", template = "dgc/mesh_cond_task_task.task", stage = "task", spirv_version = "spirv1.4" }')
        programs.append(f'{{ name = "mesh", template = "dgc/mesh_cond{suffix}_mesh.mesh", stage = "mesh", spirv_version = "spirv1.4" }}')
        programs.append('{ name = "frag", template = "dgc/mesh_cond_frag.frag", stage = "frag" }')
        name = f"mesh_cond{suffix}"
        manifest += (
            f'\n[[case]]\nname = "{name}"\nrust_const = "{name.upper()}"\nrust_type = "SharedProgram"\n'
            f"programs = [ {', '.join(programs)} ]\n"
        )
    MANIFEST.write_text(manifest)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
