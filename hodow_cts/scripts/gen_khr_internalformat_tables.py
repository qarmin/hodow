"""Emits the desktop format tables of the Khronos GL CTS internalformat test as Rust consts.

Upstream (`external/openglcts/modules/common/glcInternalformatTests.cpp`, `InternalformatTests::getGLTestData`) builds three arrays of `TF(...)`, `CF(...)` and `RF(...)` entries. The case names upstream derives from them (`formatToString`: the GL enum name without `GL_`, lower case) are computed here so the Rust side needs no enum-to-string table. The types live in `src/khr_gl/internalformat_tests.rs`.

Usage:
    python3 hodow_cts/scripts/gen_khr_internalformat_tables.py [--cts-dir ../tmp/glcts-src] [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
OUT_PATH = CRATE_DIR / "src" / "generated" / "khr_internalformat_tables.rs"
SOURCE = "external/openglcts/modules/common/glcInternalformatTests.cpp"
EXTENSIONS = {
    "EXT_texture_shared_exponent": "GL_EXT_texture_shared_exponent",
    "EXT_texture_integer": "GL_EXT_texture_integer",
    "ARB_texture_rgb10_a2ui": "GL_ARB_texture_rgb10_a2ui",
    "ARB_depth_texture": "GL_ARB_depth_texture",
    "ARB_texture_float": "GL_ARB_texture_float",
}


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def array_body(text: str, name: str) -> str:
    start = text.index(name)
    start = text.index("{", start)
    end = text.index("};", start)
    return text[start + 1 : end]


def entries(body: str, tag: str) -> list[list[str]]:
    result = []
    for match in re.finditer(r"\b" + tag + r"\(([^()]*)\)", body):
        result.append([arg.strip() for arg in match.group(1).split(",")])
    return result


def lower_name(enum: str) -> str:
    assert enum.startswith("GL_"), enum
    return enum[3:].lower()


def extension(arg: str | None) -> str:
    if arg is None:
        return "None"
    return f'Some("{EXTENSIONS[arg]}")'


def generate(cts_dir: Path) -> str:
    text = strip_comments((cts_dir / SOURCE).read_text())
    text = text[text.index("void InternalformatTests::getGLTestData") : text.index("std::string formatToString")]

    out = [
        "// @generated by hodow_cts/scripts/gen_khr_internalformat_tables.py - do not edit.",
        "//",
        "// The desktop format tables of external/openglcts/modules/common/glcInternalformatTests.cpp (`InternalformatTests::getGLTestData`), with the case names upstream derives from them.",
        "",
        "use crate::glw;",
        "use crate::khr_gl::internalformat_tests::{CopyTexImageFormat, RenderbufferFormat, RenderbufferType, TextureFormat};",
        "",
    ]

    textures = entries(array_body(text, "commonTexture2DFormats"), "TF")
    out.append(f"pub const TEXTURE_2D_FORMATS: [TextureFormat; {len(textures)}] = [")
    for args in textures:
        fmt, typ, internal = args[:3]
        ext = args[3] if len(args) > 3 else None
        name = f"{lower_name(fmt)}_{lower_name(typ)}_{lower_name(internal)}"
        out.append(
            f'    TextureFormat {{ name: "{name}", format: glw::{fmt}, type_: glw::{typ}, internal_format: glw::{internal}, required_extension: {extension(ext)} }},'
        )
    out.append("];")
    out.append("")

    copies = entries(array_body(text, "commonCopyTexImageFormats"), "CF")
    out.append(f"pub const COPY_TEX_IMAGE_FORMATS: [CopyTexImageFormat; {len(copies)}] = [")
    for args in copies:
        ext = args[1] if len(args) > 1 else None
        out.append(f'    CopyTexImageFormat {{ name: "{lower_name(args[0])}", internal_format: glw::{args[0]}, required_extension: {extension(ext)} }},')
    out.append("];")
    out.append("")

    renderbuffers = entries(array_body(text, "commonRenderbufferFormats"), "RF")
    out.append(f"pub const RENDERBUFFER_FORMATS: [RenderbufferFormat; {len(renderbuffers)}] = [")
    for args in renderbuffers:
        kind = "".join(part.capitalize() for part in args[1].removeprefix("RENDERBUFFER_").lower().split("_"))
        ext = args[2] if len(args) > 2 else None
        out.append(f'    RenderbufferFormat {{ name: "{lower_name(args[0])}", format: glw::{args[0]}, type_: RenderbufferType::{kind}, required_extension: {extension(ext)} }},')
    out.append("];")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cts-dir", type=Path, default=CRATE_DIR.parent / "tmp" / "glcts-src")
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()

    generated = generate(args.cts_dir)
    if args.check:
        if not OUT_PATH.exists() or OUT_PATH.read_text() != generated:
            print(f"{OUT_PATH} is stale", file=sys.stderr)
            return 1
        return 0
    OUT_PATH.write_text(generated)
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
