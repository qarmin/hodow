#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.sparse_resources.image_sparse_residency.<type>.<format>.<size>.

`ImageSparseResidencyCase::initPrograms` for the formats with a single plane: a compute shader that stores a value derived from the
invocation id into every texel of a storage image. The program depends on the image type, the format and the shader grid (the image size),
so there is one entry per case of `createImageSparseResidencyTestsCommon`'s first loop, found by `residency_key` in
image_sparse_residency_tests.rs. The multi-planar and YCbCr formats and A8_UNORM are not part of it.

A pure text generator: no glslang and no cargo.
"""

import json
import re
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "sparse_resources_image_residency.toml"

HEADER = """# Shader manifest for dEQP-VK.sparse_resources.image_sparse_residency.<type>.<format>.<size>
#
# @generated by hodow_cts/scripts/gen_sparse_residency_manifest.py - do not hand-edit.
#
# `ImageSparseResidencyCase::initPrograms`, one entry per image type, format and size.

upstream_source = "external/vulkancts/modules/vulkan/sparse_resources/vktSparseResourcesImageSparseResidency.cpp"
rust_module = "sparse_resources/image_sparse_residency_tests"
"""

FORMATS = [
    "R64_SINT", "R32_SINT", "R16_SINT", "R8_SINT", "R64_UINT", "R32_UINT", "R16_UINT", "R8_UINT", "R16_UNORM", "R8_UNORM", "R16_SNORM",
    "R8_SNORM", "R32G32_SINT", "R16G16_SINT", "R8G8_SINT", "R32G32_UINT", "R16G16_UINT", "R8G8_UINT", "R16G16_UNORM", "R8G8_UNORM",
    "R16G16_SNORM", "R8G8_SNORM", "R32G32B32A32_SINT", "R16G16B16A16_SINT", "R8G8B8A8_SINT", "R32G32B32A32_UINT", "R16G16B16A16_UINT",
    "R8G8B8A8_UINT", "R16G16B16A16_UNORM", "R8G8B8A8_UNORM", "R16G16B16A16_SNORM", "R8G8B8A8_SNORM",
]

# (type name, GLSL suffix, sizes, grid z of a layer count)
TYPES = [
    ("2d", "2D", [(512, 256, 1), (1024, 128, 1), (11, 137, 1)]),
    ("2d_array", "2DArray", [(512, 256, 6), (1024, 128, 8), (11, 137, 3)]),
    ("cube", "Cube", [(256, 256, 1), (128, 128, 1), (137, 137, 1)]),
    ("cube_array", "CubeArray", [(256, 256, 6), (128, 128, 8), (137, 137, 3)]),
    ("3d", "3D", [(512, 256, 16), (1024, 128, 8), (11, 137, 3)]),
]


def grid_size(type_name: str, size: tuple) -> tuple:
    x, y, z = size
    return {
        "2d": (x, y, 1),
        "2d_array": (x, y, z),
        "cube": (x, y, 6),
        "cube_array": (x, y, 6 * z),
        "3d": (x, y, z),
    }[type_name]


def work_group_size(extent: tuple) -> tuple:
    invocations = 128
    wx = min(min(extent[0], 128), invocations)
    wy = min(min(extent[1], 128), invocations // wx)
    wz = min(min(extent[2], 64), invocations // (wx * wy))
    return wx, wy, wz


def parse(name: str) -> dict:
    match = re.fullmatch(r"((?:[RGBA]\d+)+)_(SINT|UINT|UNORM|SNORM)", name)
    channels = re.findall(r"([RGBA])(\d+)", match.group(1))
    letters = "".join(c.lower() for c, _ in channels)
    bits = int(channels[0][1])
    kind = match.group(2)
    suffix = {"SINT": "i", "UINT": "ui", "UNORM": "", "SNORM": "_snorm"}[kind]
    r64 = bits == 64
    prefix = {"SINT": "i", "UINT": "u"}.get(kind, "")
    return {
        "id": f"{letters}{bits}{suffix}",
        "channels": len(channels),
        "integer": kind in ("SINT", "UINT"),
        "r64": r64,
        "image_prefix": prefix + ("64" if r64 else ""),
        "data_type": {"SINT": "ivec4", "UINT": "uvec4"}.get(kind, "vec4") if not r64 else {"SINT": "i64vec4", "UINT": "u64vec4"}[kind],
    }


def values(fmt: dict) -> str:
    if fmt["integer"]:
        full = ["int(gl_GlobalInvocationID.x) % 127", "int(gl_GlobalInvocationID.y) % 127", "int(gl_GlobalInvocationID.z) % 127", "1"]
    else:
        full = [
            "float(int(gl_GlobalInvocationID.x) % 127) / 127.0",
            "float(int(gl_GlobalInvocationID.y) % 127) / 127.0",
            "float(int(gl_GlobalInvocationID.z) % 127) / 127.0",
            "1.0",
        ]
    used = [full[i] if i < fmt["channels"] else "0" for i in range(4)]
    return ", ".join(used)


def py(value) -> str:
    return json.dumps(repr(value))


def main() -> None:
    out = [HEADER]
    count = 0
    for type_name, glsl, sizes in TYPES:
        coord = "ivec2(gl_GlobalInvocationID.x,gl_GlobalInvocationID.y)" if type_name == "2d" else "ivec3(gl_GlobalInvocationID.x,gl_GlobalInvocationID.y,gl_GlobalInvocationID.z)"
        for name in FORMATS:
            fmt = parse(name)
            for size in sizes:
                extent = grid_size(type_name, size)
                wx, wy, wz = work_group_size(extent)
                extensions = ""
                if fmt["r64"]:
                    extensions = "#extension GL_EXT_shader_explicit_arithmetic_types_int64 : require\n#extension GL_EXT_shader_image_int64 : require"
                key = f"res_{type_name}_{fmt['id']}_{size[0]}_{size[1]}_{size[2]}"
                derived = {
                    "extensions": extensions,
                    "wx": wx, "wy": wy, "wz": wz,
                    "qualifier": fmt["id"],
                    "image_type": f"{fmt['image_prefix']}image{glsl}",
                    "w": extent[0], "h": extent[1], "d": extent[2],
                    "coord": coord,
                    "data_type": fmt["data_type"],
                    "values": values(fmt),
                }
                derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
                out.append(
                    f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "comp0", template = "sparse_resources/residency/store.comp", stage = "comp" }}]
derived = {{ {derived_text} }}
"""
                )
                count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
