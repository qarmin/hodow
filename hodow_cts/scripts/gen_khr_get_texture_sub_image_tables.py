#!/usr/bin/env python3
"""Emit the source texture tables of gl4cGetTextureSubImageTests.cpp as Rust consts.

Usage: gen_khr_get_texture_sub_image_tables.py <glcts-src> <out.rs>
"""
import re
import sys

src_root, out_path = sys.argv[1], sys.argv[2]
text = open(f"{src_root}/external/openglcts/modules/gl/gl4cGetTextureSubImageTests.cpp").read()


def table(class_name, member):
    m = re.search(rf"GetTextureSubImage::{class_name}::{member}\[\] = \{{(.*?)\}};", text, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", body)]


def emit(name, values):
    rows = [", ".join(str(v) for v in values[i : i + 16]) for i in range(0, len(values), 16)]
    return f"pub const {name}: [u8; {len(values)}] = [\n" + "".join(f"    {r},\n" for r in rows) + "];\n\n"


out = "// Generated by hodow_cts/scripts/gen_khr_get_texture_sub_image_tables.py - do not edit.\n\n"
out += emit("ERRORS_TEXTURE_DATA", table("Errors", "s_texture_data"))
out += emit("ERRORS_TEXTURE_DATA_COMPRESSED", table("Errors", "s_texture_data_compressed"))
out += emit("FUNCTIONAL_TEXTURE_DATA", table("Functional", "s_texture_data"))
out += emit("FUNCTIONAL_TEXTURE_DATA_COMPRESSED", table("Functional", "s_texture_data_compressed"))
open(out_path, "w").write(out)
