#!/usr/bin/env python3
"""Writes the shaders, the manifest and the case table of dEQP-VK.texture.subgroup_lod from the vendored Amber scripts.

Each script is read for its vertex shader (`vert_shader_lod`) and fragment shader, the number of mip levels of the texture, the colour every mip level is cleared to
(`CLEAR_COLOR mipclear_pipelineN`), the sampler's `MAX_LOD` and the `EXPECT framebuffer` lines. Written:

  * shaders/manifest/texture_subgroup_lod.toml and shaders/src/texture_subgroup_lod/,
  * src/vkt/tests/texture/subgroup_lod_cases.rs (the table of src/vkt/tests/texture/subgroup_lod_tests.rs).

Run from hodow_cts/:  python3 scripts/gen_subgroup_lod_amber.py   (then `just cts-shaders`)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/texture/subgroup_lod"
SRC = ROOT / "shaders" / "src" / "texture_subgroup_lod"
MANIFEST = ROOT / "shaders" / "manifest" / "texture_subgroup_lod.toml"
TABLE = ROOT / "src" / "vkt" / "tests" / "texture" / "subgroup_lod_cases.rs"

CASE_NAMES = {"texel_fetch": "texelfetch", "texture_grad": "texturegrad", "texture_lod": "texturelod"}


def shader(text, kind, name):
    lines = text.splitlines()
    for ndx, line in enumerate(lines):
        if line.startswith(f"SHADER {kind} {name} "):
            body = []
            for rest in lines[ndx + 1 :]:
                if rest.strip() == "END":
                    return "\n".join(body) + "\n"
                body.append(rest)
    raise RuntimeError(name)


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.texture.subgroup_lod.",
        "#",
        "# @generated by hodow_cts/scripts/gen_subgroup_lod_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/texture/subgroup_lod/texel_fetch.amber"',
        'rust_module = "texture/subgroup_lod_tests"',
        "",
    ]
    table = [
        "// @generated by hodow_cts/scripts/gen_subgroup_lod_amber.py - do not hand-edit.",
        "//",
        "// One row per Amber script of dEQP-VK.texture.subgroup_lod.",
        "",
        "use super::subgroup_lod_tests::SubgroupLodCase;",
        "use super::texel_buffer_tests::Expectation;",
        "",
        "pub static SUBGROUP_LOD_CASES: &[SubgroupLodCase] = &[",
    ]
    for path in sorted(AMBER.glob("*.amber")):
        name = CASE_NAMES[path.stem]
        text = path.read_text()
        key = f"subgroup_lod_{name}"
        mip_levels = int(re.search(r"BUFFER texture FORMAT B8G8R8A8_UNORM MIP_LEVELS (\d+)", text).group(1))
        max_lod = float(re.search(r"SAMPLER sampler MAX_LOD ([\d.]+)", text).group(1))
        clears = [tuple(int(v) for v in m.groups()) for m in re.finditer(r"CLEAR_COLOR mipclear_pipeline\d (\d+) (\d+) (\d+) (\d+)", text)]
        assert len(clears) == mip_levels
        expects = []
        for m in re.finditer(r"EXPECT framebuffer IDX (\d+) +(\d+) +SIZE 1 1 EQ_RGBA +(\d+) +(\d+) +(\d+) +(\d+)", text):
            x, y, r, g, b, a = (int(v) for v in m.groups())
            expects.append(f"Expectation {{ x: {x}, y: {y}, width: 1, height: 1, rgba: [{r}, {g}, {b}, {a}], tolerance: 0 }}")
        out += ["[[case]]", f'name = "{key}"', f'rust_const = "{key.upper()}"', 'rust_type = "SharedProgram"', "programs = ["]
        for program_name, stage, source in (("vert", "vert", shader(text, "vertex", "vert_shader_lod")), ("frag", "frag", shader(text, "fragment", "frag_shader"))):
            (SRC / f"{key}_{program_name}.{stage}").write_text(source)
            out.append(f'    {{ name = "{program_name}", template = "texture_subgroup_lod/{key}_{program_name}.{stage}", stage = "{stage}" }},')
        out += ["]", ""]
        clear_literal = ", ".join(f"[{c[0]}, {c[1]}, {c[2]}, {c[3]}]" for c in clears)
        table.append(f'    SubgroupLodCase {{ name: "{name}", key: "{key}", clears: &[{clear_literal}], max_lod: {max_lod!r}_f32, expectations: &[{", ".join(expects)}] }},')
    table.append("];")
    MANIFEST.write_text("\n".join(out))
    TABLE.write_text("\n".join(table) + "\n")
    print(len(list(AMBER.glob("*.amber"))), "cases")


if __name__ == "__main__":
    main()
