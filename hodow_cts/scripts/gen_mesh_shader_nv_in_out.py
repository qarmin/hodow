#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.mesh_shader.nv.in_out.* (vktMeshShaderMiscTests.cpp, InterfaceVariablesCase).

The NV and EXT versions of upstream's test pick the same variables from the same seeded shuffle and differ only in how the shaders
spell the stage interface (taskNV blocks, gl_TaskCountNV, gl_PrimitiveCountNV and gl_PrimitiveIndicesNV instead of the EXT payload,
EmitMeshTasksEXT, SetMeshOutputsEXT and gl_PrimitiveTriangleIndicesEXT). So the permutations are not replayed a second time: the
committed EXT shaders under shaders/src/mesh_shader/in_out are rewritten into the NV spelling, each rewrite being one of the
differences read off the two initPrograms.

Usage: python3 hodow_cts/scripts/gen_mesh_shader_nv_in_out.py [--check]
"""

import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
EXT_DIR = CRATE_DIR / "shaders" / "src" / "mesh_shader" / "in_out"
NV_DIR = CRATE_DIR / "shaders" / "src" / "mesh_shader" / "nv_in_out"
EXT_MANIFEST = CRATE_DIR / "shaders" / "manifest" / "mesh_shader_in_out.toml"
MANIFEST = CRATE_DIR / "shaders" / "manifest" / "mesh_shader_nv_in_out.toml"

NUM_PRIMITIVES = 2
TASK_DATA = re.compile(r"struct TaskData \{\n(.*?)\};\n\ntaskPayloadSharedEXT TaskData td;\n", re.S)
TASK_DATA_MESH = TASK_DATA


def common(source):
    source = source.replace("GL_EXT_mesh_shader", "GL_NV_mesh_shader")
    for ext, nv in (("perprimitiveEXT", "perprimitiveNV"), ("gl_MeshPerVertexEXT", "gl_MeshPerVertexNV"),
                    ("gl_MeshVerticesEXT", "gl_MeshVerticesNV"), ("gl_MeshPerPrimitiveEXT", "gl_MeshPerPrimitiveNV"),
                    ("gl_MeshPrimitivesEXT", "gl_MeshPrimitivesNV")):
        source = source.replace(ext, nv)
    return source


def convert_frag(source):
    return common(source)


def convert_task(source):
    source = common(source)
    source, count = TASK_DATA.subn(lambda m: "out taskNV TaskData {\n" + m.group(1) + "} td;\n", source)
    assert count == 1
    source, count = re.subn(r"void main \(\)\n\{\n", "void main ()\n{\n    gl_TaskCountNV = 1;\n\n", source)
    assert count == 1
    source, count = re.subn(r"\n    EmitMeshTasksEXT\(1, 1, 1\);\n", "\n", source)
    assert count == 1
    return source


def convert_mesh(source):
    source = common(source)
    if "taskPayloadSharedEXT" in source:
        source, count = TASK_DATA_MESH.subn(lambda m: "in taskNV TaskData {\n" + m.group(1) + "} td;\n", source)
        assert count == 1
    source, count = re.subn(r"uvec3 indices\[2\] = uvec3\[\]\(\n    uvec3\(0, 1, 2\),\n    uvec3\(2, 3, 1\)\n\);\n",
                            "int indices[6] = int[](\n    0, 1, 2, 2, 3, 1\n);\n", source)
    assert count == 1
    source, count = re.subn(r"    SetMeshOutputsEXT\(4, 2\);\n", "    gl_PrimitiveCountNV = 2;\n", source)
    assert count == 1
    lines = "".join(f"    gl_PrimitiveIndicesNV[{k}] = indices[{k}];\n" for k in range(NUM_PRIMITIVES * 3))
    source, count = re.subn(r"(    gl_PrimitiveTriangleIndicesEXT\[\d+\] = indices\[\d+\];\n)+", lines, source)
    assert count == 1
    return source


CONVERTERS = {".frag": convert_frag, ".task": convert_task, ".mesh": convert_mesh}


def manifest_text():
    text = EXT_MANIFEST.read_text()
    body = text[text.index("[[case]]"):]
    body = body.replace("mesh_shader/in_out/", "mesh_shader/nv_in_out/").replace('rust_const = "IN_OUT_', 'rust_const = "NV_IN_OUT_')
    header = (
        "# Shader manifest for dEQP-VK.mesh_shader.nv.in_out.*\n#\n"
        "# @generated by hodow_cts/scripts/gen_mesh_shader_nv_in_out.py - do not hand-edit. `InterfaceVariablesCase::initPrograms`\n"
        "# of vktMeshShaderMiscTests.cpp: the same permutations as the EXT group, written in the NV spelling.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/mesh_shader/vktMeshShaderMiscTests.cpp"\n'
        'rust_module = "mesh_shader/in_out_nv_tests"\n\n'
    )
    return header + body


def main():
    check = "--check" in sys.argv
    outputs = {}
    for path in sorted(EXT_DIR.iterdir()):
        name = path.name
        if name.startswith("mesh_") and name.endswith("_task.mesh") or name.startswith(("frag_", "task_", "mesh_")):
            outputs[NV_DIR / name] = CONVERTERS[path.suffix](path.read_text())
    outputs[MANIFEST] = manifest_text()

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if check:
        if stale:
            print("stale:", *stale[:5], sep="\n  ")
            sys.exit(1)
        return
    NV_DIR.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(outputs[path])
    print(f"wrote {len(stale)} of {len(outputs)} files")


if __name__ == "__main__":
    main()
