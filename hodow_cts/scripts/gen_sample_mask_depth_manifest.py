#!/usr/bin/env python3
"""Writes shaders/manifest/pipeline_multisample_depth_mask.toml and its fragment shaders.

`SampleMaskWithDepthTestTest::initPrograms`: the fragment shader depends on whether post depth coverage is on and on samplesPerFragment,
which is the sample count, or for the fragment shading rate group four times that (minus half the sample count without post depth coverage).
The vertex shader is the multisample `color.vert`.
"""
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
SRC = CRATE / "shaders" / "src" / "pipeline" / "multisample_depth_mask"
MANIFEST = CRATE / "shaders" / "manifest" / "pipeline_multisample_depth_mask.toml"


def samples_per_fragment(samples: int, post_depth: bool, fsr: bool) -> int:
    count = samples
    if fsr:
        count *= 4
        if not post_depth:
            count -= samples // 2
    return count


def frag(post_depth: bool, spf: int) -> str:
    return (
        "#version 440\n"
        + ("#extension GL_ARB_post_depth_coverage : require\n" if post_depth else "")
        + "layout(early_fragment_tests) in;\n"
        + ("layout(post_depth_coverage) in;\n" if post_depth else "")
        + "layout(location = 0) in vec4 vtxColor;\n"
        "layout(location = 0) out vec4 fragColor;\n"
        "void main (void)\n"
        "{\n"
        "    const int coveredSamples = bitCount(gl_SampleMaskIn[0]);\n"
        f"    fragColor = vtxColor * (1.0 / {spf} * coveredSamples);\n"
        "}\n"
    )


def main() -> None:
    SRC.mkdir(parents=True, exist_ok=True)
    combos = sorted(
        {
            (post_depth, samples_per_fragment(samples, post_depth, fsr))
            for samples in (2, 4, 8, 16)
            for post_depth in (False, True)
            for fsr in (False, True)
        }
    )
    out = [
        "# Shader manifest for dEQP-VK.pipeline.*.multisample*.sample_mask_with_depth_test.*",
        "#",
        "# @generated by hodow_cts/scripts/gen_sample_mask_depth_manifest.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/pipeline/vktPipelineMultisampleTests.cpp"',
        'rust_module = "pipeline/multisample_tests"',
        "",
    ]
    for post_depth, spf in combos:
        key = f"pdc{int(post_depth)}_spf{spf}"
        (SRC / f"{key}.frag").write_text(frag(post_depth, spf))
        out += [
            "[[case]]",
            f'name = "{key}"',
            f'rust_const = "DEPTH_MASK_{key.upper()}"',
            'rust_type = "SharedProgram"',
            "programs = [",
            '    { name = "color_vert", template = "pipeline/multisample/color.vert", stage = "vert" },',
            f'    {{ name = "color_frag", template = "pipeline/multisample_depth_mask/{key}.frag", stage = "frag" }},',
            "]",
            "",
        ]
    MANIFEST.write_text("\n".join(out))


if __name__ == "__main__":
    main()
