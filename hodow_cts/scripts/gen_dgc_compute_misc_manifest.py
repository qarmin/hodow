#!/usr/bin/env python3
"""Writes the shader and the manifest of the dEQP-VK.dgc.ext.compute.misc cases that use `increaseValueByIndexPrograms`
(execute_many_*, many_sequences_*, two_cmd_buffers_*) and of max_pc_range_*. A pure text generator."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_compute_misc.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

COMP = """#version 460
layout (local_size_x=64, local_size_y=1, local_size_z=1) in;
layout (set=0, binding=0, std430) buffer OutputBlock { uint values[]; } outputBuffer;
layout (push_constant, std430) uniform PushConstantBlock { uint valueIndex; } pc;
void main (void) { atomicAdd(outputBuffer.values[pc.valueIndex], 1u); }
"""

PC_BYTES = [128, 256, 4096]

IUB_COUNT = 2
IUB_ITEM_COUNT = 128 // 16


def iub_comp(split_sets, i):
    if split_sets:
        iub_sets, iub_bindings = [0, 1], [0, 0]
    else:
        iub_sets, iub_bindings = [0, 0], [0, 2]  # Leave space for the output storage buffers.
    reverse = i > 0
    return (
        "#version 460\n"
        f"layout(local_size_x={IUB_ITEM_COUNT}) in;\n"
        f"layout(set={iub_sets[i]}, binding={iub_bindings[i]}) uniform IUBBlock{i} {{ uvec4 items[{IUB_ITEM_COUNT}]; }} iub{i};\n"
        f"layout(set={iub_sets[i]}, binding={iub_bindings[i] + 1}) buffer OutBlock{i} {{ uvec4 items[{IUB_ITEM_COUNT}]; }} ob{i};\n"
        "uint getWorkGroupSize (void) {\n"
        "    const uint workGroupSize = gl_WorkGroupSize.x * gl_WorkGroupSize.y * gl_WorkGroupSize.z;\n"
        "    return workGroupSize;\n"
        "}\n"
        "void main (void) {\n"
        + ("    const uint wgSize = getWorkGroupSize();\n" if reverse else "")
        + "    const uint srcIndex = "
        + ("(wgSize - gl_LocalInvocationIndex - 1u)" if reverse else "gl_LocalInvocationIndex")
        + ";\n"
        "    const uint dstIndex = gl_LocalInvocationIndex;\n"
        f"    ob{i}.items[dstIndex] = iub{i}.items[srcIndex];\n"
        "}\n"
    )


MULTIPLE_SETS_COMP = """#version 460
layout (local_size_x=32) in;
layout (set=0, binding=0, std430) readonly buffer Input {
   uint values[];
} ib;
layout (set=1, binding=0, std430) buffer Output {
   uint values[];
} ob;

uint getWorkGroupSize (void) {
    const uint workGroupSize = gl_WorkGroupSize.x * gl_WorkGroupSize.y * gl_WorkGroupSize.z;
    return workGroupSize;
}

uint getWorkGroupIndex (void) {
    const uint workGroupIndex = gl_NumWorkGroups.x * gl_NumWorkGroups.y * gl_WorkGroupID.z +
                                gl_NumWorkGroups.x * gl_WorkGroupID.y +
                                gl_WorkGroupID.x;
    return workGroupIndex;
}

uint getGlobalInvocationIndex (void) {
    const uint globalInvocationIndex = getWorkGroupIndex() * getWorkGroupSize() + gl_LocalInvocationIndex;
    return globalInvocationIndex;
}

void main (void)
{
    const uint globalInvocationIndex = getGlobalInvocationIndex();
    const uint value = ib.values[globalInvocationIndex];
    ob.values[globalInvocationIndex] = value;
}
"""


def max_pc_comp(pc_bytes):
    array_size = pc_bytes // 4
    return f"""#version 460
layout (local_size_x=1) in;
layout (push_constant, std430) uniform PCBlock {{
   uint values[{array_size}];
}} pc;
layout (set=0, binding=0, std430) buffer Output {{
   uint values[{array_size}];
}} ob;

uint getWorkGroupIndex (void) {{
    const uint workGroupIndex = gl_NumWorkGroups.x * gl_NumWorkGroups.y * gl_WorkGroupID.z +
                                gl_NumWorkGroups.x * gl_WorkGroupID.y +
                                gl_WorkGroupID.x;
    return workGroupIndex;
}}

void main (void)
{{
    const uint wgIndex = getWorkGroupIndex();
    const uint pcValue = pc.values[wgIndex];
    ob.values[wgIndex] = pcValue;
}}
"""


MANIFEST_TEXT = """# Shader manifest for dEQP-VK.dgc.ext.compute.misc
#
# @generated by hodow_cts/scripts/gen_dgc_compute_misc_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCComputeMiscTestsExt.cpp"
rust_module = "dgc/compute_misc_tests"

[[case]]
name = "misc_increase_value_by_index"
rust_const = "MISC_INCREASE_VALUE_BY_INDEX"
rust_type = "SharedProgram"
programs = [ { name = "comp", template = "dgc/misc_increase_value_by_index.comp", stage = "comp" } ]
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    (SRC_DIR / "misc_increase_value_by_index.comp").write_text(COMP)
    out = [MANIFEST_TEXT]
    for pc_bytes in PC_BYTES:
        key = f"misc_max_pc_{pc_bytes}"
        (SRC_DIR / f"{key}.comp").write_text(max_pc_comp(pc_bytes))
        out.append(
            f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [ {{ name = "comp", template = "dgc/{key}.comp", stage = "comp" }} ]
"""
        )
    (SRC_DIR / "misc_multiple_sets.comp").write_text(MULTIPLE_SETS_COMP)
    out.append(
        """
[[case]]
name = "misc_multiple_sets"
rust_const = "MISC_MULTIPLE_SETS"
rust_type = "SharedProgram"
programs = [ { name = "comp", template = "dgc/misc_multiple_sets.comp", stage = "comp" } ]
"""
    )
    for split_sets in (False, True):
        key = f"misc_iub_{'split' if split_sets else 'single'}"
        programs = []
        for i in range(IUB_COUNT):
            (SRC_DIR / f"{key}_{i}.comp").write_text(iub_comp(split_sets, i))
            programs.append(f'{{ name = "comp{i}", template = "dgc/{key}_{i}.comp", stage = "comp" }}')
        out.append(
            f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [ {", ".join(programs)} ]
"""
        )
    header = (
        "#version 460\n"
        "layout (local_size_x=64, local_size_y=1, local_size_z=1) in;\n"
        "layout (set=0, binding=0, std430) buffer OutputBlock { uint values[]; } outputBuffer;\n"
        "layout (set=0, binding=1, std430) readonly buffer InputBlock { uint values[]; } inputBuffer;\n"
        "layout (push_constant, std430) uniform PushConstantBlock { uint bufferOffset; } pc;\n"
    )
    (SRC_DIR / "misc_null_set_layouts_1.comp").write_text(
        header
        + "void main(void) {\n"
        "    const uint idx = gl_LocalInvocationIndex + pc.bufferOffset;\n"
        "    outputBuffer.values[idx] = inputBuffer.values[idx];\n"
        "}\n"
    )
    (SRC_DIR / "misc_null_set_layouts_2.comp").write_text(
        header
        + "void main(void) {\n"
        "    const uint srcIdx = gl_LocalInvocationIndex + pc.bufferOffset;\n"
        "    const uint dstIdx = (gl_WorkGroupSize.x - 1u - gl_LocalInvocationIndex) + pc.bufferOffset;\n"
        "    outputBuffer.values[dstIdx] = inputBuffer.values[srcIdx];\n"
        "}\n"
    )
    (SRC_DIR / "misc_dbpd.comp").write_text(
        "#version 460\n"
        "layout (local_size_x=64) in;\n"
        "layout (constant_id=0) const uint valueOffset = 0u;\n"
        "layout (set=0, binding=0) readonly buffer InBufferBlock { uint values[128]; } ib;\n"
        "layout (set=0, binding=1) buffer OutBufferBlock { uint values[128]; } ob;\n"
        "layout (push_constant, std430) uniform PCBlock { uint indexOffset; } pc;\n"
        "void main (void) {\n"
        "    const uint index = gl_LocalInvocationIndex + pc.indexOffset;\n"
        "    ob.values[index] = ib.values[index] + valueOffset;\n"
        "}\n"
    )
    out.append(
        """
[[case]]
name = "misc_dbpd"
rust_const = "MISC_DBPD"
rust_type = "SharedProgram"
programs = [ { name = "comp", template = "dgc/misc_dbpd.comp", stage = "comp" } ]
"""
    )
    out.append(
        """
[[case]]
name = "misc_null_set_layouts"
rust_const = "MISC_NULL_SET_LAYOUTS"
rust_type = "SharedProgram"
programs = [ { name = "comp1", template = "dgc/misc_null_set_layouts_1.comp", stage = "comp" }, { name = "comp2", template = "dgc/misc_null_set_layouts_2.comp", stage = "comp" } ]
"""
    )
    out.append(
        """
[[case]]
name = "misc_scratch_space"
rust_const = "MISC_SCRATCH_SPACE"
rust_type = "SharedProgram"
programs = [ { name = "comp", template = "dgc/scratch_space.asm", stage = "asm", spirv_version = "spirv1.0" } ]
"""
    )
    MANIFEST.write_text("".join(out))
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
