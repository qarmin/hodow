"""Emits the texture format table of the Khronos GL CTS texture-swizzle test as Rust consts.

Upstream (`external/openglcts/modules/gl/gl3cTextureSwizzleTests.cpp`) keeps it as a C++ initialiser list of 71 `_texture_format` entries that point at about 90 small `static const` source and expected-value arrays of different element types. This evaluates the arrays
to their native-endian bytes (the half floats, the 11/10-bit packed float and the `tcu::Float16(...).bits()` expressions included) and emits the table with the same field order. The types it is built from live in `src/khr_gl/texture_swizzle/mod.rs`.

Usage:
    python3 hodow_cts/scripts/gen_khr_texture_swizzle_tables.py [--cts-dir ../tmp/glcts-src] [--check]
"""

from __future__ import annotations

import argparse
import re
import struct
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
OUT_PATH = CRATE_DIR / "src" / "generated" / "khr_texture_swizzle_tables.rs"
SOURCE = "external/openglcts/modules/gl/gl3cTextureSwizzleTests.cpp"

STRUCT_FORMATS = {"GLhalf": "<H", "GLfloat": "<f", "GLbyte": "<b", "GLshort": "<h", "GLubyte": "<B", "GLushort": "<H", "GLint": "<i", "GLuint": "<I"}


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def float16_bits(value: float) -> int:
    return struct.unpack("<H", struct.pack("<e", value))[0]


def small_float_bits(value: float, mantissa_bits: int) -> int:
    """Bits of an unsigned 5-bit-exponent float with bias 15, for the exactly representable values the test uses."""
    import math

    exponent = math.floor(math.log2(value))
    mantissa = round((value / 2.0**exponent - 1.0) * (1 << mantissa_bits))
    return ((exponent + 15) << mantissa_bits) | mantissa


def evaluate_arrays(text: str) -> dict:
    """name -> (c type, bytes) of every `static const <type> <name>[] = {...};` before the texture table."""
    head = strip_comments(text[: text.index("static const _texture_format texture_formats")])
    variables = {"r11f": small_float_bits(0.5, 6), "g11f": small_float_bits(0.75, 6), "b10f": small_float_bits(0.25, 5)}
    arrays = {}
    for match in re.finditer(r"static const (glw::GL\w+)\s+(\w+)\[\]\s*=\s*\{(.*?)\};", head, re.S):
        c_type = match.group(1).replace("glw::", "")
        if c_type not in STRUCT_FORMATS:
            continue
        body = match.group(3)
        out = bytearray()
        # a top-level comma separates elements; the Float16 calls and the shifts have none outside parentheses
        depth = 0
        element = ""
        elements = []
        for c in body:
            depth += (c == "(") - (c == ")")
            if c == "," and depth == 0:
                elements.append(element)
                element = ""
            else:
                element += c
        if element.strip():
            elements.append(element)
        for element in elements:
            expr = element.strip()
            expr = re.sub(r"tcu::Float16\(([^)]*)\)\.bits\(\)", lambda m: str(float16_bits(float(m.group(1)))), expr)
            expr = re.sub(r"\b(r11f|g11f|b10f)\.bits\(\)", lambda m: str(variables[m.group(1)]), expr)
            expr = re.sub(r"(?<=\d)[uf]\b", "", expr)
            value = eval(expr, {"__builtins__": {}}, {})
            fmt = STRUCT_FORMATS[c_type]
            out += struct.pack(fmt, float(value) if fmt == "<f" else int(value))
        arrays[match.group(2)] = (c_type, bytes(out))
    return arrays


def parse_node(body: str, i: int):
    assert body[i] == "{"
    i += 1
    items = []
    token = ""
    while True:
        c = body[i]
        if c == "{":
            node, i = parse_node(body, i)
            items.append(node)
            continue
        if c in ",}":
            token = " ".join(token.split())
            if token:
                items.append(token)
            token = ""
            if c == "}":
                return items, i + 1
        else:
            token += c
        i += 1


def array_entries(text: str, name: str) -> list:
    start = text.index(name)
    start = text.index("= {", start) + 2
    node, _ = parse_node(text, start)
    return node


def rust_ident(name: str) -> str:
    """`name` or `name + k` (a pointer into the array, k elements in) as a const name."""
    match = re.fullmatch(r"(\w+) \+ (\d+)", name)
    if match:
        return f"{match.group(1).upper()}_PLUS_{match.group(2)}"
    return name.upper()


def render(text: str) -> str:
    arrays = evaluate_arrays(text)
    stripped = strip_comments(text)

    out = ["// @generated by hodow_cts/scripts/gen_khr_texture_swizzle_tables.py - do not edit.", "//", f"// The texture format table of {SOURCE}, with the arrays it points at as bytes.", "",
           "use crate::glw;", "use crate::khr_gl::texture_swizzle::{OutChDesc, SamplerDesc, TextureFormat};", ""]

    used = set()
    descs = {}
    for match in re.finditer(r"static const _out_ch_desc (\w+)\s*=\s*\{(\w+),\s*(\w+)\};", stripped):
        descs[match.group(1)] = (match.group(2), match.group(3))
        if match.group(3) != "0":
            used.add(match.group(3))

    table_text = stripped[stripped.index("static const _texture_format texture_formats") :]
    table_text = re.sub(r"glu::ApiType::core\((\d+),\s*(\d+)\)", r"core_\1_\2", table_text)
    entries = array_entries(table_text, "texture_formats")
    for entry in entries:
        for field in entry[6:10]:
            if isinstance(field, list) and field[1] != "nullptr":
                used.add(field[1])
        used.add(entry[10])

    for name in sorted(used):
        match = re.fullmatch(r"(\w+) \+ (\d+)", name)
        base, offset = (match.group(1), int(match.group(2))) if match else (name, 0)
        c_type, data = arrays[base]
        data = data[offset * struct.calcsize(STRUCT_FORMATS[c_type]) :]
        out.append(f"const {rust_ident(name)}: [u8; {len(data)}] = {list(data)};")
    out.append("")

    out.append("const ZERO_CH: OutChDesc = OutChDesc { internal_format: glw::GL_ZERO, expected_data: None };")
    out.append("const ONE_CH: OutChDesc = OutChDesc { internal_format: glw::GL_ONE, expected_data: None };")
    for name, (fmt, data) in descs.items():
        if name in ("zero_ch", "one_ch"):
            continue
        out.append(f"const {rust_ident(name)}: OutChDesc = OutChDesc {{ internal_format: glw::{fmt}, expected_data: Some(&{rust_ident(data)}) }};")
    out.append("")
    out += ["pub const SAMPLER: SamplerDesc = SamplerDesc { basic_type: \"float\", sampler_prefix: \"\" };",
            "pub const ISAMPLER: SamplerDesc = SamplerDesc { basic_type: \"int\", sampler_prefix: \"i\" };",
            "pub const USAMPLER: SamplerDesc = SamplerDesc { basic_type: \"uint\", sampler_prefix: \"u\" };", ""]

    def desc(field) -> str:
        if isinstance(field, str):
            return {"zero_ch": "ZERO_CH", "one_ch": "ONE_CH"}.get(field, rust_ident(field))
        fmt, data = field
        data_expr = "None" if data == "nullptr" else f"Some(&{rust_ident(data)})"
        return f"OutChDesc {{ internal_format: glw::{fmt}, expected_data: {data_expr} }}"

    out.append(f"pub static TEXTURE_FORMATS: [TextureFormat; {len(entries)}] = [")
    for entry in entries:
        api, internal, fmt, typ, ds_mode, sampler, red, green, blue, alpha, source, zero, one = entry
        major, minor = re.match(r"core_(\d+)_(\d+)", api).groups()
        out.append(
            f"    TextureFormat {{ minimum_gl_context: ({major}, {minor}), internal_format: glw::{internal}, format: glw::{fmt}, type_: glw::{typ}, ds_mode: glw::{ds_mode}, sampler: {sampler.upper()}, "
            f"red_ch: {desc(red)}, green_ch: {desc(green)}, blue_ch: {desc(blue)}, alpha_ch: {desc(alpha)}, source_data: &{rust_ident(source)}, zero_ch: {rust_ident(zero)}, one_ch: {rust_ident(one)} }},")
    out += ["];", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cts-dir", default=str(CRATE_DIR.parent / "tmp" / "glcts-src"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = (Path(args.cts_dir) / SOURCE).read_text()
    rendered = render(text)
    if args.check:
        if not OUT_PATH.exists() or OUT_PATH.read_text() != rendered:
            print(f"{OUT_PATH} is stale", file=sys.stderr)
            return 1
        return 0
    OUT_PATH.write_text(rendered)
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
