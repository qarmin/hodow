#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.image.mutable.* (`initPrograms` of vktImageMutableTests.cpp).

The shaders depend on the view format, the image type and which kind of upload (draw, store, any other) and download (copy, load, texture)
the case uses, so there is one entry per combination, found by `mutable_key` in mutable_tests.rs. A pure text generator: no glslang and no
cargo.
"""

import struct
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "image_mutable.toml"

HEADER = """# Shader manifest for dEQP-VK.image.mutable.*
#
# @generated by hodow_cts/scripts/gen_image_mutable_manifest.py - do not hand-edit.
#
# `initPrograms` of vktImageMutableTests.cpp, one entry per view format, image type and upload and download kind.

upstream_source = "external/vulkancts/modules/vulkan/image/vktImageMutableTests.cpp"
rust_module = "image/mutable_tests"
"""

# (view format, components, class, channel size in bytes, image qualifier) of the formats of s_formats
FORMATS = {
    "r32g32b32a32_sfloat": (4, "float", 4, "rgba32f"), "r16g16b16a16_sfloat": (4, "float", 2, "rgba16f"), "r32g32_sfloat": (2, "float", 4, "rg32f"),
    "r16g16_sfloat": (2, "float", 2, "rg16f"), "r32_sfloat": (1, "float", 4, "r32f"),
    "r32g32b32a32_uint": (4, "uint", 4, "rgba32ui"), "r16g16b16a16_uint": (4, "uint", 2, "rgba16ui"), "r8g8b8a8_uint": (4, "uint", 1, "rgba8ui"),
    "r32g32_uint": (2, "uint", 4, "rg32ui"), "r16g16_uint": (2, "uint", 2, "rg16ui"), "r32_uint": (1, "uint", 4, "r32ui"),
    "r32g32b32a32_sint": (4, "int", 4, "rgba32i"), "r16g16b16a16_sint": (4, "int", 2, "rgba16i"), "r8g8b8a8_sint": (4, "int", 1, "rgba8i"),
    "r32g32_sint": (2, "int", 4, "rg32i"), "r16g16_sint": (2, "int", 2, "rg16i"), "r32_sint": (1, "int", 4, "r32i"),
    "r8g8b8a8_unorm": (4, "float", 1, "rgba8"), "r8g8b8a8_snorm": (4, "float", 1, "rgba8_snorm"), "r8g8b8a8_srgb": (4, "float", 1, None),
    "b8g8r8a8_unorm": (4, "float", 1, None), "b8g8r8a8_snorm": (4, "float", 1, None), "b8g8r8a8_srgb": (4, "float", 1, None),
}

COLOR_TABLE_FLOAT = [(0.00, 0.40, 0.80, 0.10), (0.50, 0.10, 0.90, 0.20), (0.20, 0.60, 1.00, 0.30), (0.30, 0.70, 0.00, 0.40)]
COLOR_TABLE_INT = [
    (0x70707070, 0x3C3C3C3C, 0x65656565, 0x29292929),
    (0x3C3C3C3C, 0x65656565, 0x29292929, 0x70707070),
    (0x29292929, 0x70707070, 0x3C3C3C3C, 0x65656565),
    (0x65656565, 0x29292929, 0x70707070, 0x3C3C3C3C),
]
IMAGE_TYPES = ["2d", "2d_array"]


def f32(value):
    return struct.unpack("<f", struct.pack("<f", value))[0]


def number(value):
    return "%g" % f32(value)


def sampler_type(cls, image_type):
    prefix = {"uint": "u", "int": "i", "float": ""}[cls]
    return prefix + ("sampler2D" if image_type == "2d" else "sampler2DArray")


def image_type_str(cls, image_type):
    prefix = {"uint": "u", "int": "i", "float": ""}[cls]
    return prefix + ("image2D" if image_type == "2d" else "image2DArray")


def color_type(cls):
    return {"uint": "uvec4", "int": "ivec4", "float": "vec4"}[cls]


def color_format_str(components, cls):
    if components == 1:
        return {"uint": "uint", "int": "int", "float": "float"}[cls]
    return {"uint": "u", "int": "i", "float": ""}[cls] + f"vec{components}"


def pos_lines(image_type):
    if image_type == "2d":
        return "    ivec2 pos = ivec2(gl_GlobalInvocationID.xy);\n"
    return "    ivec3 pos = ivec3(gl_GlobalInvocationID.xyz);\n"


def draw_vert():
    return (
        "#version 450\n\nlayout(location = 0) in  vec4 in_position;\nlayout(location = 1) in  vec4 in_color;\nlayout(location = 0) out vec4 out_color;\n\n"
        "out gl_PerVertex {\n    vec4 gl_Position;\n};\n\nvoid main(void)\n{\n    gl_Position = in_position;\n    out_color = in_color;\n}\n"
    )


def draw_frag(components, cls):
    fmt = color_format_str(components, cls)
    expr = {1: "in_color.r", 2: "in_color.rg", 3: "in_color.rgb", 4: "in_color"}[components]
    return (
        f"#version 450\n\nlayout(location = 0) in  vec4 in_color;\nlayout(location = 0) out {fmt} out_color;\n\nvoid main(void)\n{{\n"
        f"    out_color = {fmt}({expr});\n}}\n"
    )


def store_comp(view, image_type):
    components, cls, size, qualifier = FORMATS[view]
    ctype = color_type(cls)
    out = f"#version 450\n\nlayout (local_size_x = 1) in;\n\nlayout(binding=0, {qualifier}) writeonly uniform {image_type_str(cls, image_type)} u_image;\n\n"
    out += f"const {ctype} colorTable[] = {ctype}[](\n"
    mask = {1: 0xFF, 2: 0xFFFF, 4: 0xFFFFFFFF}[size]
    for idx in range(4):
        if cls != "float":
            values = [v & mask for v in COLOR_TABLE_INT[idx]]
            values = [v - (1 << 32) if v >= (1 << 31) else v for v in values]
            out += f"     {ctype}({values[0]}, {values[1]}, {values[2]}, {values[3]})"
        else:
            v = COLOR_TABLE_FLOAT[idx]
            out += f"     {ctype}({number(v[0])}, {number(v[1])}, {number(v[2])}, {number(v[3])})"
        out += ",\n" if idx < 3 else "\n"
    out += ");\n\nvoid main(void)\n{\n" + pos_lines(image_type)
    out += f"    {ctype} color = colorTable[gl_GlobalInvocationID.z];\n    imageStore(u_image, pos, color);\n}}\n"
    return out


def load_comp(view, image_type):
    _, cls, _, qualifier = FORMATS[view]
    itype = image_type_str(cls, image_type)
    return (
        f"#version 450\n\nlayout (local_size_x = 1) in;\n\nlayout(binding=0, {qualifier}) readonly uniform {itype} in_image;\n"
        f"layout(binding=1, {qualifier}) writeonly uniform {itype} out_image;\n\nvoid main(void)\n{{\n" + pos_lines(image_type)
        + "    imageStore(out_image, pos, imageLoad(in_image, pos));\n}\n"
    )


def texture_comp(view, image_type):
    _, cls, _, qualifier = FORMATS[view]
    return (
        f"#version 450\n\nlayout (local_size_x = 1) in;\n\nlayout(binding=0) uniform {sampler_type(cls, image_type)} u_tex;\n"
        f"layout(binding=1, {qualifier}) writeonly uniform {image_type_str(cls, image_type)} out_image;\n\nvoid main(void)\n{{\n" + pos_lines(image_type)
        + "    imageStore(out_image, pos, texelFetch(u_tex, pos, 0));\n}\n"
    )


def toml_literal(text):
    return '"' + repr(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    out = [HEADER]
    count = 0
    for image_type in IMAGE_TYPES:
        for view, (components, cls, size, qualifier) in FORMATS.items():
            for upload in ("draw", "store", "other"):
                for download in ("copy", "load", "texture"):
                    capable = qualifier is not None
                    if upload == "store" and not capable:
                        continue
                    if download != "copy" and not capable:
                        continue
                    programs = []
                    derived = {}
                    if upload == "draw":
                        programs.append(("uploadDrawVert", "image/mutable_draw.vert", "vert"))
                        programs.append(("uploadDrawFrag", "image/mutable_draw.frag", "frag"))
                        derived["draw_frag_source"] = draw_frag(components, cls)
                    if upload == "store":
                        programs.append(("uploadStoreComp", "image/mutable_store.comp", "comp"))
                        derived["store_source"] = store_comp(view, image_type)
                    if download == "load":
                        programs.append(("downloadLoadComp", "image/mutable_load.comp", "comp"))
                        derived["load_source"] = load_comp(view, image_type)
                    if download == "texture":
                        programs.append(("downloadTextureComp", "image/mutable_texture.comp", "comp"))
                        derived["texture_source"] = texture_comp(view, image_type)
                    if not programs:
                        continue
                    key = f"mut_{image_type}_{view}_{upload}_{download}"
                    out.append("\n[[case]]\n")
                    out.append(f'name = "{key}"\nrust_const = "{key.upper()}"\nrust_type = "SharedProgram"\n')
                    out.append("programs = [\n")
                    for name, template, stage in programs:
                        out.append(f'    {{ name = "{name}", template = "{template}", stage = "{stage}" }},\n')
                    out.append("]\n")
                    if derived:
                        out.append("derived = { " + ", ".join(f"{k} = {toml_literal(v)}" for k, v in derived.items()) + " }\n")
                    count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} entries")


if __name__ == "__main__":
    main()
