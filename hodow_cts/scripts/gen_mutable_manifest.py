#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.binding_model.mutable_descriptor.*

`MutableTypesTest::initPrograms` builds its GLSL from the descriptor set of the case, so the sources are generated by mutable_cases.py
(a transliteration of that function) and carried in the manifest as derived values. Cases whose programs are identical share one entry, and
`src/vkt/tests/binding_model/mutable_programs.rs` maps the shader key of a case (`<set key>.<stage>.<pc|nopc>`) to the static compile_shaders.py
emits for it. Programs with ray queries or ray tracing stages need SPIR-V 1.4.

A pure text generator: no glslang and no cargo.
"""

import hashlib
import json
from pathlib import Path

import mutable_cases as mc

CRATE = Path(__file__).resolve().parent.parent
MANIFEST = CRATE / "shaders" / "manifest" / "binding_mutable.toml"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "binding_model" / "mutable"
PROGRAM_TABLE = CRATE / "src" / "vkt" / "tests" / "binding_model" / "mutable_programs.rs"
MAX_ITERATIONS = 8

HEADER = """# Shader manifest for dEQP-VK.binding_model.mutable_descriptor.*
#
# @generated by hodow_cts/scripts/gen_mutable_manifest.py - do not hand-edit.
#
# `MutableTypesTest::initPrograms`, one entry per distinct set of sources. The GLSL is a derived value because upstream builds it from the
# descriptor set in C++; src/vkt/tests/binding_model/mutable_programs.rs maps a case's shader key to its entry.

upstream_source = "external/vulkancts/modules/vulkan/binding_model/vktBindingMutableTests.cpp"
rust_module = "binding_model/mutable_tests"
"""


def py(value) -> str:
    return json.dumps(repr(value))


def template_name(program: str) -> str:
    if program.startswith("iteration-"):
        return "it" + program.removeprefix("iteration-")
    return "pass_" + program


def main() -> None:
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    names = [f"it{i}" for i in range(MAX_ITERATIONS)] + ["pass_vert", "pass_tese", "pass_tesc", "pass_rgen", "pass_miss"]
    for name in names:
        (TEMPLATE_DIR / f"{name}.glsl").write_text("${" + name + "}")

    key_to_sig: dict[str, tuple] = {}
    for key, ds, stage, pc in mc.shader_keys():
        programs = mc.init_programs(ds, stage, pc)
        assert ds.max_types() <= MAX_ITERATIONS
        key_to_sig[key] = tuple(sorted((n, st, src) for n, (st, src) in programs.items()))

    by_sig: dict[tuple, str] = {}
    entries = []
    table = []
    for key in sorted(key_to_sig):
        sig = key_to_sig[key]
        if sig not in by_sig:
            digest = hashlib.sha1(repr(sig).encode()).hexdigest()[:12]
            const = f"MT_{digest.upper()}"
            by_sig[sig] = const
            programs = []
            derived = []
            for name, stage, src in sig:
                tname = template_name(name)
                spirv = ', spirv_version = "spirv1.4"' if "GL_EXT_ray_query" in src or "GL_EXT_ray_tracing" in src else ""
                programs.append(f'{{ name = "{name}", template = "binding_model/mutable/{tname}.glsl", stage = "{stage}"{spirv} }}')
                derived.append(f"{tname} = {py(src)}")
            entries.append(
                f'\n[[case]]\nname = "mt_{digest}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\n'
                f"programs = [{', '.join(programs)}]\nderived = {{ {', '.join(derived)} }}\n"
            )
        table.append((key, by_sig[sig]))

    MANIFEST.write_text(HEADER + "".join(entries))

    lines = [
        "// @generated by hodow_cts/scripts/gen_mutable_manifest.py - do not hand-edit.",
        "//",
        "// The program set of every shader key `mutable_tests.rs::shader_key` can produce, sorted by key.",
        "",
        "use crate::generated::shaders::binding_mutable::*;",
        "use crate::vk::programs::SharedProgram;",
        "",
        "pub static PROGRAM_TABLE: &[(&str, &SharedProgram)] = &[",
    ]
    lines += [f'    ("{key}", &{const}),' for key, const in table]
    lines.append("];")
    PROGRAM_TABLE.write_text("\n".join(lines) + "\n")
    print(f"{len(key_to_sig)} shader keys, {len(entries)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
