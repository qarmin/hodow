#!/usr/bin/env python3
"""Writes shaders/manifest/texture_mipmap_fetch_lod.toml: the `*_FETCH_LOD` programs of Texture2DImageViewMinLodIntTexCoordTest::initPrograms and
Texture3DImageViewMinLodIntTexCoordTest::initPrograms (vktTextureMipmapTests.cpp), used by dEQP-VK.texture.mipmap.{2d,3d}.image_view_min_lod.*_integer_texel_coord*.

    python3 hodow_cts/scripts/gen_texture_mipmap_fetch_lod_manifest.py

A pure text generator: no glslang and no cargo.
"""

import json
import re
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "texture_mipmap_fetch_lod.toml"
SOURCE = "external/vulkancts/modules/vulkan/texture/vktTextureMipmapTests.cpp"


def cpp_string(text, var):
    start = text.index("static const char *" + var + " =")
    end = text.index(";\n", start)
    return "".join(json.loads('"' + piece + '"') for piece in re.findall(r'"((?:[^"\\]|\\.)*)"', text[start:end]))


def case(text, dim):
    begin = text.index(f"void Texture{dim}DImageViewMinLodIntTexCoordTest::initPrograms")
    end = text.index(f"void Texture{dim}DImageViewMinLodIntTexCoordTest::checkSupport", begin)
    body = text[begin:end]
    sources = {key: cpp_string(body, name) for key, name in (("vert", "vertShader"), ("frag", "fragShader"), ("comp", "compShader"))}
    program = f"{dim}D_FETCH_LOD"
    return (
        f'[[case]]\nname = "fetch_lod_{dim.lower()}d"\nrust_const = "FETCH_LOD_{dim}D"\nrust_type = "SharedProgram"\n'
        f'programs = [{{ name = "vertex_{program}", template = "texture_mipmap_fetch_lod/src_vert.glsl", stage = "vert" }}, '
        f'{{ name = "fragment_{program}", template = "texture_mipmap_fetch_lod/src_frag.glsl", stage = "frag" }}, '
        f'{{ name = "compute_{program}", template = "texture_mipmap_fetch_lod/src_comp.glsl", stage = "comp" }}]\n'
        f"derived = {{ src_vert = {json.dumps(repr(sources['vert']))}, src_frag = {json.dumps(repr(sources['frag']))}, src_comp = {json.dumps(repr(sources['comp']))} }}\n"
    )


def main():
    text = (CRATE / "upstream" / SOURCE).read_text(encoding="utf-8")
    out = (
        "# Shader manifest for dEQP-VK.texture.mipmap.{2d,3d}.image_view_min_lod integer texel coordinate cases\n#\n"
        "# @generated by hodow_cts/scripts/gen_texture_mipmap_fetch_lod_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "texture/mipmap_tests"\n\n'
        + case(text, "2")
        + "\n"
        + case(text, "3")
    )
    OUT.write_text(out, encoding="utf-8")
    print("wrote 2 cases")


if __name__ == "__main__":
    main()
