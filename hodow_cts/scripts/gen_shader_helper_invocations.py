#!/usr/bin/env python3
"""Writes the GLSL of dEQP-VK.glsl.helper_invocations (shaderexecutor/vktShaderHelperInvocationsTests.cpp) and its manifest.

One manifest case per test type, each with the shared vertex shader, `frag_write` and the type's `frag_read` (the C++ `initPrograms` replayed).
  * shaders/manifest/shader_helper_invocations.toml and shaders/src/shader_helper_invocations/

Run from hodow_cts/:  python3 scripts/gen_shader_helper_invocations.py   (then `just cts-shaders`)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "shaders" / "src" / "shader_helper_invocations"
MANIFEST = ROOT / "shaders" / "manifest" / "shader_helper_invocations.toml"

VERT = """#version 450
void main(void)
{
\tgl_Position = vec4(float(-0.6 + 0.6 * gl_VertexIndex),
\t                   float( 0.8 - 1.5 * (gl_VertexIndex % 2)), 0.0, 1.0);
}
"""

WRITE = """#version 450
layout(location = 0) out uint outColor;
void main (void)
{
\toutColor = 84;
%s}
"""

READ = {
    "load_from_ssbo": """#version 450
layout(location = 0) out uint outColor;
layout(std430, binding=0) readonly buffer Input { uint v[]; };
void main (void)
{
\tuint i = uint(gl_FragCoord.y)*32+uint(gl_FragCoord.x);
\toutColor = uint(fwidth(v[i]));
}
""",
    "load_from_address": """#version 450
#extension GL_EXT_buffer_reference : require
layout(location = 0) out uint outColor;
layout(std430, buffer_reference, buffer_reference_align = 4) readonly buffer Data
{ uint v[]; };
layout(std430, push_constant) uniform Input { Data data; };
void main (void)
{
\tuint i = uint(gl_FragCoord.y)*32+uint(gl_FragCoord.x);
\toutColor = uint(fwidth(data.v[i]));
}
""",
    "load_from_ubo": """#version 450
layout(location = 0) out uint outColor;
layout(binding=0) uniform Input { uvec4 v[32*8]; };
void main (void)
{
\tuint i = uint(gl_FragCoord.y)*8+uint(gl_FragCoord.x) / 4;
\tuvec4 color = v[i];
\toutColor = uint(fwidth(color[uint(gl_FragCoord.x) % 4]));
}
""",
    "load_from_image": """#version 450
layout(location = 0) out uint outColor;
layout(binding=0, r32ui) readonly uniform uimage2D image;
void main (void)
{
\tuint c = imageLoad(image, ivec2(uint(gl_FragCoord.x), uint(gl_FragCoord.y))).x;
\toutColor = uint(fwidth(c));
}
""",
    "load_from_texture": """#version 450
layout(location = 0) out uint outColor;
layout(binding=0) uniform usampler2D samp;
void main (void)
{
\tvec2 uv = vec2(gl_FragCoord.x, gl_FragCoord.y) / 32;
\tfloat c = texture(samp, uv).r;
\toutColor = uint(fwidth(c));
}
""",
    "output_variables": """#version 450
layout(location = 0) out uint outColor;
layout(input_attachment_index=0, binding=0) uniform usubpassInput image;
void main (void)
{
\tuint c = subpassLoad(image).x;
\toutColor = c + uint(gl_FragCoord.y) * uint(gl_FragCoord.x);
}
""",
}


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.glsl.helper_invocations.",
        "#",
        "# @generated by hodow_cts/scripts/gen_shader_helper_invocations.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/shaderexecutor/vktShaderHelperInvocationsTests.cpp"',
        'rust_module = "glsl/shader_helper_invocations_tests"',
        "",
    ]
    (SRC / "vert.vert").write_text(VERT)
    for name, read in READ.items():
        extra = "\toutColor = uint(gl_FragCoord.y)*32+uint(gl_FragCoord.x);\n" if name == "output_variables" else ""
        (SRC / f"{name}_frag_write.frag").write_text(WRITE % extra)
        (SRC / f"{name}_frag_read.frag").write_text(read)
        key = f"shi_{name}"
        out += [
            "[[case]]",
            f'name = "{key}"',
            f'rust_const = "{key.upper()}"',
            'rust_type = "SharedProgram"',
            "programs = [",
            '    { name = "vert", template = "shader_helper_invocations/vert.vert", stage = "vert" },',
            f'    {{ name = "frag_write", template = "shader_helper_invocations/{name}_frag_write.frag", stage = "frag" }},',
            f'    {{ name = "frag_read", template = "shader_helper_invocations/{name}_frag_read.frag", stage = "frag" }},',
            "]",
            "",
        ]
    MANIFEST.write_text("\n".join(out))
    print(len(READ), "cases")


if __name__ == "__main__":
    main()
