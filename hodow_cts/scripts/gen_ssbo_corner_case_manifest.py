#!/usr/bin/env python3
"""Writes shaders/manifest/ssbo_corner_case.toml: dEQP-VK.ssbo.corner_case.long_shader_bitwise_and (vktSSBOCornerCase.cpp).

`useCornerCaseShader(589)` draws four values per line from `de::Random(1)`; the shader is rebuilt here with the same draws.

    python3 hodow_cts/scripts/gen_ssbo_corner_case_manifest.py

A pure text generator: no glslang and no cargo.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from de_random import DeRandom  # noqa: E402

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "ssbo_corner_case.toml"
TEST_SIZE = 589


def corner_case_shader(loop_count):
    rnd = DeRandom(1)
    src = (
        "#version 310 es\n"
        "#extension GL_EXT_buffer_reference : enable\n"
        "layout(std430, buffer_reference) buffer BlockA\n"
        "{\n"
        " highp ivec4 a[];\n"
        "};\n"
        "layout(std140, binding = 0) buffer AcBlock { highp uint ac_numIrrelevant; };\n"
        "\n"
        "layout (push_constant, std430) uniform PC {\n"
        " BlockA blockA;\n"
        "};\n"
        "\n"
        "bool compare_ivec4(highp ivec4 a, highp ivec4 b) { return a == b; }\n"
        "\n"
        "void main (void)\n"
        "{\n"
        " int allOk = int(true);\n"
    )
    for i in range(loop_count):
        values = [rnd.get_int(-9, 9) for _ in range(4)]
        src += f" allOk = allOk & int(compare_ivec4((blockA.a[{i}]), ivec4({values[0]}, {values[1]}, {values[2]}, {values[3]})));\n"
    src += " if (allOk != int(false))\n {\n  ac_numIrrelevant++;\n }\n}\n"
    return src


def main():
    text = (
        "# Shader manifest for dEQP-VK.ssbo.corner_case\n#\n"
        "# @generated by hodow_cts/scripts/gen_ssbo_corner_case_manifest.py - do not hand-edit.\n#\n"
        "# `useCornerCaseShader(589)`: 589 comparisons through a buffer reference.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/ssbo/vktSSBOCornerCase.cpp"\n'
        'rust_module = "ssbo"\n\n'
        '[[case]]\nname = "long_shader_bitwise_and"\nrust_const = "LONG_SHADER_BITWISE_AND"\nrust_type = "SharedProgram"\n'
        'programs = [{ name = "compute", template = "ssbo/src_comp.glsl", stage = "comp" }]\n'
        f"derived = {{ src_comp = {json.dumps(repr(corner_case_shader(TEST_SIZE)))} }}\n"
    )
    OUT.write_text(text, encoding="utf-8")
    print("wrote 1 case")


if __name__ == "__main__":
    main()
