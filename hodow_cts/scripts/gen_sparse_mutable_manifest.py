#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.sparse_resources.image_sparse_residency.mutable.*.

`ImageMutableSparseTest::initPrograms`: a compute shader that stores one colour through each of two views of a sparse image, the
upper rows through the first and the lower through the second. It depends on the two view formats, the image type and the height of
the image only, so there is one entry per distinct (type, view 1, view 2) of the case tree, found by `mutable_key` in
image_sparse_residency_tests.rs. The case tree is `createImageSparseResidencyTestsCommon`'s "mutable" loop: the image types 2d, 2d_array
and 3d over `getTestFormatsForMutableSparse` (the 32 test formats less the two r64 ones), a case for every ordered triple of
three distinct formats of one texel size.

A pure text generator: no glslang and no cargo.
"""

import re
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "sparse_resources_image_mutable.toml"

HEADER = """# Shader manifest for dEQP-VK.sparse_resources.image_sparse_residency.mutable.*
#
# @generated by hodow_cts/scripts/gen_sparse_mutable_manifest.py - do not hand-edit.
#
# `ImageMutableSparseTest::initPrograms`, one entry per image type and pair of view formats.

upstream_source = "external/vulkancts/modules/vulkan/sparse_resources/vktSparseResourcesImageSparseResidency.cpp"
rust_module = "sparse_resources/image_sparse_residency_tests"
"""

BASE_FORMATS = [
    "R32_SINT", "R16_SINT", "R8_SINT", "R32_UINT", "R16_UINT", "R8_UINT", "R16_UNORM", "R8_UNORM", "R16_SNORM", "R8_SNORM",
    "R32G32_SINT", "R16G16_SINT", "R8G8_SINT", "R32G32_UINT", "R16G16_UINT", "R8G8_UINT", "R16G16_UNORM", "R8G8_UNORM",
    "R16G16_SNORM", "R8G8_SNORM", "R32G32B32A32_SINT", "R16G16B16A16_SINT", "R8G8B8A8_SINT", "R32G32B32A32_UINT",
    "R16G16B16A16_UINT", "R8G8B8A8_UINT", "R16G16B16A16_UNORM", "R8G8B8A8_UNORM", "R16G16B16A16_SNORM", "R8G8B8A8_SNORM",
]

COLOR_FLOAT = ["0", "0.4", "0.8", "0.1"]
COLOR_INT = [0x70707070, 0x3C3C3C3C, 0x65656565, 0x29292929]

IMAGE_TYPES = [
    ("2d", "2D", 2, 256),
    ("2d_array", "2DArray", 3, 512),
    ("3d", "3D", 3, 512),
]


def parse(name: str) -> dict:
    match = re.fullmatch(r"((?:[RGBA]\d+)+)_(SINT|UINT|UNORM|SNORM)", name)
    channels = re.findall(r"([RGBA])(\d+)", match.group(1))
    letters = "".join(c.lower() for c, _ in channels)
    bits = int(channels[0][1])
    kind = match.group(2)
    suffix = {"SINT": "i", "UINT": "ui", "UNORM": "", "SNORM": "_snorm"}[kind]
    return {
        "name": name.lower(),
        "kind": kind,
        "bits": bits,
        "texel": bits // 8 * len(channels),
        "qualifier": f"{letters}{bits}{suffix}",
        "prefix": {"SINT": "i", "UINT": "u"}.get(kind, ""),
        "integer": kind in ("SINT", "UINT"),
    }


def declaration(index: int, fmt: dict) -> str:
    prefix = fmt["prefix"]
    if fmt["integer"]:
        mask = (1 << fmt["bits"]) - 1
        values = ", ".join(str(value & mask) for value in COLOR_INT)
    else:
        values = ", ".join(COLOR_FLOAT)
    return f"{prefix}vec4 color{index} = {prefix}vec4({values});"


def case(type_name: str, glsl_type: str, dimension: int, height: int, fmt0: dict, fmt1: dict) -> str:
    key = f"mutable_{type_name}_{fmt0['name']}_{fmt1['name']}"
    position_type = {2: "ivec2", 3: "ivec3"}[dimension]
    position = {2: "ivec2(gl_GlobalInvocationID.xy)", 3: "ivec3(gl_GlobalInvocationID.xyz)"}[dimension]
    derived = {
        "qualifier0": fmt0["qualifier"],
        "qualifier1": fmt1["qualifier"],
        "image_type0": f"{fmt0['prefix']}image{glsl_type}",
        "image_type1": f"{fmt1['prefix']}image{glsl_type}",
        "color0_declaration": declaration(0, fmt0),
        "color1_declaration": declaration(1, fmt1),
        "position_type": position_type,
        "position": position,
        "portion1": str(height // 2),
    }
    derived_text = ", ".join(f"{k} = \"'{v}'\"" for k, v in derived.items())
    return f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "comp", template = "sparse_resources/residency/mutable.comp", stage = "comp" }}]
derived = {{ {derived_text} }}
"""


def main() -> None:
    formats = [parse(name) for name in BASE_FORMATS]
    out = [HEADER]
    seen = set()
    for type_name, glsl_type, dimension, height in IMAGE_TYPES:
        for image_format in formats:
            for fmt0 in formats:
                for fmt1 in formats:
                    names = {image_format["name"], fmt0["name"], fmt1["name"]}
                    if len(names) != 3 or not (image_format["texel"] == fmt0["texel"] == fmt1["texel"]):
                        continue
                    key = (type_name, fmt0["name"], fmt1["name"])
                    if key in seen:
                        continue
                    seen.add(key)
                    out.append(case(type_name, glsl_type, dimension, height, fmt0, fmt1))
    MANIFEST.write_text("".join(out))
    print(f"{len(seen)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
