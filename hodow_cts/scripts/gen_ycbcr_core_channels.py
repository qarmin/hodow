#!/usr/bin/env python3
"""Generate src/vkt/tests/ycbcr/format_channels_core.rs: the channel descriptions of `getCorePlanarFormatDescription` (vkImageUtil.cpp) for the plain colour
formats the ycbcr conversion tests sample (`noChromaSubsampledFormats` of vktYCbCrConversionTests.cpp).

`gen_ycbcr_channels.py` covers the YCbCr formats; the conversion tests also read the channels of ordinary packed formats such as R5G6B5 through the
same `getChannelAccess`.

Usage:
    python3 hodow_cts/scripts/gen_ycbcr_core_channels.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
OUT = CRATE_DIR / "src" / "vkt" / "tests" / "ycbcr" / "format_channels_core.rs"
SOURCE = CRATE_DIR / "upstream" / "external" / "vulkancts" / "framework" / "vulkan" / "vkImageUtil.cpp"

FORMATS = [
    "R4G4B4A4_UNORM_PACK16",
    "B4G4R4A4_UNORM_PACK16",
    "R5G6B5_UNORM_PACK16",
    "B5G6R5_UNORM_PACK16",
    "R5G5B5A1_UNORM_PACK16",
    "B5G5R5A1_UNORM_PACK16",
    "A1R5G5B5_UNORM_PACK16",
    "R8G8B8_UNORM",
    "B8G8R8_UNORM",
    "R8G8B8A8_UNORM",
    "B8G8R8A8_UNORM",
    "A8B8G8R8_UNORM_PACK32",
    "A2R10G10B10_UNORM_PACK32",
    "A2B10G10R10_UNORM_PACK32",
    "R16G16B16_UNORM",
    "R16G16B16A16_UNORM",
]

ROW = re.compile(r"\{\s*(\d+)\s*,\s*(unorm|snorm|uint|sint|sfloat|0)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}")


def main() -> int:
    text = SOURCE.read_text()
    start = text.index("PlanarFormatDescription getCorePlanarFormatDescription(VkFormat format)")
    end = text.index("\nPlanarFormatDescription getPlanarFormatDescription", start) if "\nPlanarFormatDescription getPlanarFormatDescription" in text[start:] else len(text)
    body = text[start:end]

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/vulkancts/framework/vulkan/vkImageUtil.cpp (`getCorePlanarFormatDescription`, the channel descriptions)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2025 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_ycbcr_core_channels.py; do not hand-edit.",
        "",
        "use vulkanalia::vk;",
        "",
        "use super::format_channels::ChannelDesc;",
        "",
        "/// The R, G, B and A channels of the plain colour formats the conversion tests sample.",
        "pub static CORE_CHANNELS: &[(vk::Format, [Option<ChannelDesc>; 4])] = &[",
    ]
    for name in FORMATS:
        marker = f"case VK_FORMAT_{name}:"
        pos = body.find(marker)
        if pos < 0:
            print(f"missing {name}", file=sys.stderr)
            return 1
        chunk = body[pos + len(marker) :]
        chunk = chunk[chunk.index("{") :]
        nxt = chunk.find("case VK_FORMAT_")
        chunk = chunk[: nxt if nxt >= 0 else len(chunk)]
        rows = ROW.findall(chunk)
        if len(rows) < 4:
            print(f"no channel rows for {name}", file=sys.stderr)
            return 1
        cells = []
        for plane, kind, offset, size, stride in rows[:4]:
            if kind == "0" and size == "0":
                cells.append("None")
            else:
                if kind != "unorm":
                    print(f"{name}: unexpected class {kind}", file=sys.stderr)
                    return 1
                cells.append(f"Some(ChannelDesc {{ plane: {plane}, offset_bits: {offset}, size_bits: {size}, stride_bytes: {stride} }})")
        lines.append(f"    (vk::Format::{name}, [{', '.join(cells)}]),")
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
