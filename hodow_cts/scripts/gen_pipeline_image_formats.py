#!/usr/bin/env python3
"""Writes src/vkt/tests/pipeline/image_format_lists.rs from upstream's vkFormatLists.inl (`pipelineImageFormats`).

A pure text generator: no cargo.
"""

import re
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
INL = CRATE_DIR / "upstream" / "external" / "vulkancts" / "framework" / "vulkan" / "generated" / "vulkan" / "vkFormatLists.inl"
IMAGE_VIEW_CPP = CRATE_DIR / "upstream" / "external" / "vulkancts" / "modules" / "vulkan" / "pipeline" / "vktPipelineImageViewTests.cpp"
OUT = CRATE_DIR / "src" / "vkt" / "tests" / "pipeline" / "image_format_lists.rs"


def main() -> None:
    text = INL.read_text()
    body = re.search(r"pipelineImageFormats\s*\{(.*?)\};", text, re.S).group(1)
    names = [name.removeprefix("VK_FORMAT_") for name in re.findall(r"VK_FORMAT_\w+", body)]
    lines = [
        "// @generated by hodow_cts/scripts/gen_pipeline_image_formats.py - do not hand-edit.",
        "//",
        "// `formats::pipelineImageFormats` of vkFormatLists.inl, the formats of dEQP-VK.pipeline.*.image.",
        "",
        "use vulkanalia::vk;",
        "",
        f"pub const PIPELINE_IMAGE_FORMATS: [vk::Format; {len(names)}] = [",
    ]
    lines += [f"    vk::Format::{name.upper()}," for name in names]
    lines.append("];")

    cpp = IMAGE_VIEW_CPP.read_text()
    view_body = re.search(r"const VkFormat formats\[\] = \{(.*?)\};", cpp, re.S).group(1)
    view_names = [name.removeprefix("VK_FORMAT_").removesuffix("_KHR").removesuffix("_EXT") for name in re.findall(r"VK_FORMAT_\w+", view_body)]
    lines += [
        "",
        "/// The `formats` of `createImageViewTests` (vktPipelineImageViewTests.cpp).",
        f"pub const IMAGE_VIEW_FORMATS: [vk::Format; {len(view_names)}] = [",
    ]
    lines += [f"    vk::Format::{name.upper()}," for name in view_names]
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(names)} formats -> {OUT}")


if __name__ == "__main__":
    main()
