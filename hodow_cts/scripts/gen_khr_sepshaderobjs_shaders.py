#!/usr/bin/env python3
"""Generates hodow_cts/src/khr_gl/sepshaderobjs/shaders.rs: the fragment shader templates of es31cSeparateShaderObjsTests.cpp.

The C++ keeps them as `static const char *name = "line\\n" "line\\n";` concatenations; this extracts them verbatim (the `${...}` placeholders stay, the Rust side substitutes them).

Usage:
    python3 hodow_cts/scripts/gen_khr_sepshaderobjs_shaders.py [--cpp PATH] [--out PATH] [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = CRATE_DIR.parent
DEFAULT_CPP = REPO_DIR / "tmp" / "glcts-src" / "external" / "openglcts" / "modules" / "gles31" / "es31cSeparateShaderObjsTests.cpp"
DEFAULT_OUT = CRATE_DIR / "src" / "khr_gl" / "sepshaderobjs" / "shaders.rs"

ESCAPES = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'"}

TEMPLATES = (
    ("s_unifFragShaderSrc", "UNIFORM_FRAG_SHADER_SRC"),
    ("s_unifFragSquareMatShaderSrc", "UNIFORM_FRAG_SQUARE_MAT_SHADER_SRC"),
    ("s_unifFragNonSquareMatShaderSrc", "UNIFORM_FRAG_NON_SQUARE_MAT_SHADER_SRC"),
)


def skip_space_and_comments(text: str, pos: int) -> int:
    while pos < len(text):
        if text[pos].isspace():
            pos += 1
        elif text.startswith("//", pos):
            pos = text.index("\n", pos)
        elif text.startswith("/*", pos):
            pos = text.index("*/", pos) + 2
        else:
            break
    return pos


def parse_literals(text: str, pos: int) -> tuple[str, int]:
    value = []
    while True:
        pos = skip_space_and_comments(text, pos)
        if pos >= len(text) or text[pos] != '"':
            return "".join(value), pos
        pos += 1
        while text[pos] != '"':
            if text[pos] == "\\":
                value.append(ESCAPES[text[pos + 1]])
                pos += 2
            else:
                value.append(text[pos])
                pos += 1
        pos += 1


def generate(src: str) -> str:
    out = [
        "// SPDX-License-Identifier: Apache-2.0\n//\n// GENERATED by hodow_cts/scripts/gen_khr_sepshaderobjs_shaders.py - do not edit by hand.\n//\n"
        "// Derived from VK-GL-CTS:\n//   external/openglcts/modules/gles31/es31cSeparateShaderObjsTests.cpp  (fragment shader templates)\n"
        "// Upstream revision: see hodow_cts/upstream/COMMIT\n//\n// Copyright (c) 2014-2016 The Khronos Group Inc.\n"
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).\n\n"
    ]
    for cpp_name, rust_name in TEMPLATES:
        match = re.search(r"\b" + re.escape(cpp_name) + r"\s*=\s*", src)
        if match is None:
            raise SystemExit(f"{cpp_name} not found")
        value, _ = parse_literals(src, match.end())
        out.append(f"pub(super) const {rust_name}: &str = {json.dumps(value)};\n\n")
    return "".join(out).rstrip("\n") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cpp", type=Path, default=DEFAULT_CPP)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="fail if the output file is stale instead of writing it")
    args = ap.parse_args()

    if not args.cpp.is_file():
        print(f"error: {args.cpp} not found; run `just glcts-build` first or pass --cpp", file=sys.stderr)
        return 2

    text = generate(args.cpp.read_text())
    if args.check:
        if not args.out.is_file() or args.out.read_text() != text:
            print(f"{args.out} is stale", file=sys.stderr)
            return 1
        return 0

    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
