#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.robustness.{robustness2,image_robustness,pipeline_robustness}.*

`RobustnessExtsTestCase::initPrograms` builds its GLSL from the case at run time, so the sources are generated here by robustness_exts_cases.py
(a transliteration of that function) and carried in the manifest as derived values. Cases whose programs are identical share one entry, and
`src/vkt/tests/robustness/exts_programs.rs` maps the shader key of a case (see `exts_tests.rs::shader_key`) to the static compile_shaders.py
emits for it.

A pure text generator: no glslang and no cargo.
"""

import hashlib
import json
from pathlib import Path

import robustness_exts_cases as rc

CRATE = Path(__file__).resolve().parent.parent
MANIFEST_DIR = CRATE / "shaders" / "manifest"
# GitHub warns on files over 50 MB, so the program sets are spread over manifests (robustness_exts.toml, robustness_exts_2.toml, ...)
# of about this many bytes each; every manifest becomes a generated module of the same name.
MANIFEST_SIZE_TARGET = 12_000_000
TEMPLATE_DIR = CRATE / "shaders" / "src" / "robustness" / "exts"
PROGRAM_TABLE = CRATE / "src" / "vkt" / "tests" / "robustness" / "exts_programs.rs"

HEADER = """# Shader manifest for dEQP-VK.robustness.{robustness2,image_robustness,pipeline_robustness}.*
#
# @generated by hodow_cts/scripts/gen_robustness_exts_manifest.py - do not hand-edit.
#
# `RobustnessExtsTestCase::initPrograms`, one entry per distinct set of sources. The GLSL is a derived value because upstream builds it from the
# case in C++; src/vkt/tests/robustness/exts_programs.rs maps a case's shader key to its entry.

upstream_source = "external/vulkancts/modules/vulkan/robustness/vktRobustnessExtsTests.cpp"
rust_module = "robustness/exts_tests"
"""

STAGE_OF_PROGRAM = {"test": None, "vert": "vert", "fillShader": "comp"}


def py(value) -> str:
    return json.dumps(repr(value))


def template_name(program: str) -> str:
    return {"test": "src_test", "vert": "src_vert", "fillShader": "src_fill"}[program]


def main() -> None:
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    for name in ("src_test", "src_vert", "src_fill"):
        (TEMPLATE_DIR / f"{name}.glsl").write_text("${" + name + "}")

    key_to_sets: dict[str, tuple] = {}
    for _, case in rc.all_cases():
        key = rc.shader_key(case)
        programs = rc.init_programs(case)
        signature = tuple(sorted((n, stage, src, spv) for n, (stage, src, spv, _scalar) in programs.items()))
        if key in key_to_sets:
            assert key_to_sets[key] == signature, f"shader key {key} is not a function of the sources"
            continue
        key_to_sets[key] = signature

    by_signature: dict[tuple, str] = {}
    entries = []
    table = []
    for key in sorted(key_to_sets):
        signature = key_to_sets[key]
        if signature not in by_signature:
            digest = hashlib.sha1(repr(signature).encode()).hexdigest()[:12]
            const = f"RX_{digest.upper()}"
            by_signature[signature] = const
            programs = []
            derived = []
            for name, stage, src, spv in signature:
                spv_text = f', spirv_version = "{spv}"' if spv else ""
                programs.append(f'{{ name = "{name}", template = "robustness/exts/{template_name(name)}.glsl", stage = "{stage}"{spv_text} }}')
                derived.append(f"{template_name(name)} = {py(src)}")
            entries.append(
                f'\n[[case]]\nname = "rx_{digest}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\n'
                f"programs = [{', '.join(programs)}]\nderived = {{ {', '.join(derived)} }}\n"
            )
        table.append((key, by_signature[signature]))

    chunks: list[list[str]] = [[]]
    chunk_size = 0
    for entry in entries:
        if chunk_size >= MANIFEST_SIZE_TARGET:
            chunks.append([])
            chunk_size = 0
        chunks[-1].append(entry)
        chunk_size += len(entry)
    modules = []
    for number, chunk in enumerate(chunks, start=1):
        module = "robustness_exts" if number == 1 else f"robustness_exts_{number}"
        modules.append(module)
        (MANIFEST_DIR / f"{module}.toml").write_text(HEADER + "".join(chunk))
    for stale in MANIFEST_DIR.glob("robustness_exts_[0-9]*.toml"):
        if stale.stem not in modules:
            stale.unlink()

    lines = [
        "// @generated by hodow_cts/scripts/gen_robustness_exts_manifest.py - do not hand-edit.",
        "//",
        "// The program set of every shader key `exts_tests.rs::shader_key` can produce, sorted by key.",
        "",
        *[f"use crate::generated::shaders::{module}::*;" for module in modules],
        "use crate::vk::programs::SharedProgram;",
        "",
        "pub static PROGRAM_TABLE: &[(&str, &SharedProgram)] = &[",
    ]
    lines += [f'    ("{key}", &{const}),' for key, const in table]
    lines.append("];")
    PROGRAM_TABLE.write_text("\n".join(lines) + "\n")
    print(f"{len(key_to_sets)} shader keys, {len(entries)} program sets -> {len(modules)} manifests {', '.join(modules)}")


if __name__ == "__main__":
    main()
