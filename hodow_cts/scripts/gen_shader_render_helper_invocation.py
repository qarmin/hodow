#!/usr/bin/env python3
"""Writes the GLSL of dEQP-VK.glsl.helper_invocation (shaderrender/vktShaderRenderHelperInvocationTests.cpp) and its manifest.

The five variants are the C++ `initPrograms` replayed: `genLoadedBlock`, `genVerificationTail` and the per-variant body, all
substituted into one fragment template. Shaders:
  * shaders/manifest/shader_render_helper_invocation.toml and shaders/src/shader_render_helper_invocation/

Run from hodow_cts/:  python3 scripts/gen_shader_render_helper_invocation.py   (then `just cts-shaders`)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "shaders" / "src" / "shader_render_helper_invocation"
MANIFEST = ROOT / "shaders" / "manifest" / "shader_render_helper_invocation.toml"

RENDER_SIZE = 16
ARRAY_SIZE = 32

VERT = """#version 450
void main (void)
{
    vec2 positions[3] = vec2[](vec2(-1.0, -1.0), vec2(1.0, -1.0), vec2(-1.0, 1.0));
    gl_Position = vec4(positions[gl_VertexIndex], 0.0, 1.0);
}
"""


def gen_loaded_block(target_var, sample_expr, array_size):
    return f"""    {{
        vec4 sampled = {sample_expr};
        vec4 scratch[{array_size}];
        for (int i = 0; i < {array_size}; ++i)
            scratch[i] = vec4(float(i) - 13.0);
        uint sx = uint(gl_FragCoord.x);
        uint sy = uint(gl_FragCoord.y);
        int storeIdx = int((sx * 7u + sy * 13u + 1u) % uint({array_size}));
        scratch[storeIdx] = sampled;
        int loadIdx = 0;
        for (int i = 0; i < {array_size}; ++i)
            if (i == storeIdx)
                loadIdx = i;
        {target_var} = scratch[loadIdx];
    }}
"""


def gen_verification_tail(render_size):
    lane_checks = ""
    for lane in range(4):
        lane_checks += f"""    {{
        vec4 laneLoaded = subgroupQuadBroadcast(loaded, {lane}u);
        vec4 laneCoord = subgroupQuadBroadcast(gl_FragCoord, {lane}u);
        helperBits |= subgroupQuadBroadcast(uint(gl_HelperInvocation), {lane}u);
        ivec2 lanePix = clamp(ivec2(laneCoord.xy), ivec2(0), ivec2({render_size - 1}, {render_size - 1}));
        vec4 expected = texelFetch(u_tex, lanePix, 0);
        if (any(greaterThan(abs(laneLoaded - expected), vec4(0.01))))
            ok = false;
    }}
"""
    return f"""    bool ok = true;
    uint helperBits = 0u;
{lane_checks}    uint px = uint(gl_FragCoord.x);
    uint py = uint(gl_FragCoord.y);
    uint idx = py * uint({render_size}) + px;
    if (idx < uint({render_size * render_size}))
        results[idx] = (ok ? 1u : 0u) | (helperBits != 0u ? 2u : 0u);
    o_color = ok ? vec4(0.0, 1.0, 0.0, 1.0) : vec4(1.0, 0.0, 0.0, 1.0);
"""


def fragment(variant):
    round_trip_fn = ""
    if variant == "function":
        round_trip_fn = (
            "vec4 roundTrip (vec2 uv)\n{\n    vec4 loaded;\n"
            + gen_loaded_block("loaded", "texture(u_tex, uv)", ARRAY_SIZE)
            + "    return loaded;\n}\n"
        )
    plain = gen_loaded_block("loaded", "texture(u_tex, uv)", ARRAY_SIZE)
    if variant == "base":
        body = "    vec4 loaded;\n" + plain
    elif variant == "derivative":
        body = "    vec4 loaded;\n" + gen_loaded_block("loaded", "textureGrad(u_tex, uv, dFdx(uv), dFdy(uv))", ARRAY_SIZE)
    elif variant == "divergent":
        body = (
            "    ivec2 quadId = ivec2(gl_FragCoord.xy) / ivec2(2);\n    vec4 loaded = vec4(0.0);\n    if (((quadId.x + quadId.y) & 1) == 0)\n"
            + plain
            + "    else\n"
            + plain
        )
    elif variant == "loop":
        body = (
            "    ivec2 quadId = ivec2(gl_FragCoord.xy) / ivec2(2);\n    int iters = 1 + (quadId.x & 3);\n    vec4 loaded = vec4(0.0);\n"
            "    for (int k = 0; k < iters; ++k)\n" + plain
        )
    else:
        body = "    vec4 loaded = roundTrip(uv);\n"
    return (
        "#version 450\n#extension GL_KHR_shader_subgroup_basic : require\n#extension GL_KHR_shader_subgroup_quad : require\n"
        "layout(location = 0) out vec4 o_color;\nlayout(set = 0, binding = 0) uniform sampler2D u_tex;\n"
        "layout(set = 0, binding = 1) buffer ResultBlock { uint results[]; };\n"
        + round_trip_fn
        + "void main (void)\n{\n"
        + f"    const vec2 fbSize = vec2({RENDER_SIZE}.0, {RENDER_SIZE}.0);\n"
        + "    vec2 uv = gl_FragCoord.xy / fbSize;\n"
        + body
        + gen_verification_tail(RENDER_SIZE)
        + "}\n"
    )


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.glsl.helper_invocation (load_after_store variants).",
        "#",
        "# @generated by hodow_cts/scripts/gen_shader_render_helper_invocation.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/shaderrender/vktShaderRenderHelperInvocationTests.cpp"',
        'rust_module = "glsl/shader_render_helper_invocation_tests"',
        "",
    ]
    (SRC / "vert.vert").write_text(VERT)
    for variant in ("base", "divergent", "loop", "derivative", "function"):
        key = f"sr_helper_invocation_{variant}"
        (SRC / f"{key}.frag").write_text(fragment(variant))
        out += [
            "[[case]]",
            f'name = "{key}"',
            f'rust_const = "{key.upper()}"',
            'rust_type = "SharedProgram"',
            "programs = [",
            '    { name = "vert", template = "shader_render_helper_invocation/vert.vert", stage = "vert" },',
            f'    {{ name = "frag", template = "shader_render_helper_invocation/{key}.frag", stage = "frag", spirv_version = "spirv1.3" }},',
            "]",
            "",
        ]
    MANIFEST.write_text("\n".join(out))
    print("5 cases")


if __name__ == "__main__":
    main()
