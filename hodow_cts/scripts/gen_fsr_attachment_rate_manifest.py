#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.fragment_shading_rate.*.attachment_rate.*.

`AttachmentRateTestCase::initPrograms`: which programs a case gets depends on its mode and on the rate it sets up, a number that is
(log2 width << 2) | log2 height. `atomics_<rate>` is the compute shader mode (comp, vert, frag), `setup_<rate>` the three modes that
render the rate (vert_setup, frag_setup, vert, frag), `plain` the modes that copy it or write it from the host (vert, frag) and
`two_subpass` the mode with two triangles (vert0, vert1, frag).

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "fragment_shading_rate_attachment_rate.toml"

HEADER = """# Shader manifest for dEQP-VK.fragment_shading_rate.*.attachment_rate.*
#
# @generated by hodow_cts/scripts/gen_fsr_attachment_rate_manifest.py - do not hand-edit.
#
# `AttachmentRateTestCase::initPrograms`, one entry per mode family and shading rate value.

upstream_source = "external/vulkancts/modules/vulkan/fragment_shading_rate/vktAttachmentRateTests.cpp"
rust_module = "fragment_shading_rate/attachment_rate_tests"
"""

T = "fragment_shading_rate/attachment_rate"
RATES = sorted({(w.bit_length() - 1) << 2 | (h.bit_length() - 1) for w in (1, 2, 4) for h in (1, 2, 4)})




def case(name: str, programs: list[str], derived: dict) -> str:
    derived_text = ", ".join(f"{k} = \"'{v}'\"" for k, v in derived.items())
    program_text = "\n".join(f"    {p}," for p in programs)
    return f"""
[[case]]
name = "{name}"
rust_const = "{name.upper()}"
rust_type = "SharedProgram"
programs = [
{program_text}
]
derived = {{ {derived_text} }}
"""


def main() -> None:
    out = [HEADER]
    program = lambda name, template, stage: f'{{ name = "{name}", template = "{T}/{template}", stage = "{stage}" }}'
    # The vertex shaders with another scale or translation are templates of their own (vert_setup, vert0, vert1), so a program set
    # holding two of them does not need two values of one placeholder.
    out.append(case("ar_plain", [program("vert", "vert.vert", "vert"), program("frag", "frag.frag", "frag")], {"scale": "0.8", "translate": "0.0"}))
    for rate in RATES:
        out.append(case(f"ar_atomics_{rate}", [program("comp", "comp.comp", "comp"), program("vert", "vert.vert", "vert"), program("frag", "frag.frag", "frag")], {"scale": "0.8", "translate": "0.0", "rate_value": str(rate)}))
        out.append(
            case(
                f"ar_setup_{rate}",
                [program("vert_setup", "vert_setup.vert", "vert"), program("frag_setup", "frag_setup.frag", "frag"), program("vert", "vert.vert", "vert"), program("frag", "frag.frag", "frag")],
                {"scale": "0.8", "translate": "0.0", "setup_scale": "9.0", "rate_value": str(rate)},
            )
        )
    out.append(case("ar_two_subpass", [program("vert0", "vert0.vert", "vert"), program("vert1", "vert1.vert", "vert"), program("frag", "frag.frag", "frag")], {"scale": "0.4", "translate_0": "-0.5", "translate_1": "0.5"}))
    MANIFEST.write_text("".join(out))
    print(f"{len(RATES) * 2 + 2} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
