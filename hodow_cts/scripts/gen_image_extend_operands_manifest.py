#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.image.extend_operands_spirv1p4 and dEQP-VK.image.nontemporal_operand.

`ImageExtendOperandTest::initPrograms`: one assembly compute shader reading a storage image and writing another with a SignExtend or
ZeroExtend (or Nontemporal) operand. It depends on the test type, the two formats, whether the sampled type is forced to the other
signedness and whether the source is RelaxedPrecision, so there is one entry per case of `createImageExtendOperandsTests` and
`createImageNontemporalOperandTests`, found by `extend_key` in extend_operands_tests.rs.

A pure text generator: no spirv-as and no cargo.
"""

import json
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "image_extend_operands.toml"

HEADER = """# Shader manifest for dEQP-VK.image.extend_operands_spirv1p4.* and dEQP-VK.image.nontemporal_operand.*
#
# @generated by hodow_cts/scripts/gen_image_extend_operands_manifest.py - do not hand-edit.
#
# `ImageExtendOperandTest::initPrograms`, one entry per case.

upstream_source = "external/vulkancts/modules/vulkan/image/vktImageLoadStoreTests.cpp"
rust_module = "image/extend_operands_tests"
"""

# (short name, SPIR-V format, signed, bits, bit depth) in the order of `s_formats` (the integral ones that have a SPIR-V format), then R64
FORMATS = [
    ("r32g32b32a32_uint", "Rgba32ui", False, 32, 32),
    ("r16g16b16a16_uint", "Rgba16ui", False, 32, 16),
    ("r8g8b8a8_uint", "Rgba8ui", False, 32, 8),
    ("r32_uint", "R32ui", False, 32, 32),
    ("r32g32b32a32_sint", "Rgba32i", True, 32, 32),
    ("r16g16b16a16_sint", "Rgba16i", True, 32, 16),
    ("r8g8b8a8_sint", "Rgba8i", True, 32, 8),
    ("r32_sint", "R32i", True, 32, 32),
    ("a2b10g10r10_uint_pack32", "Rgb10a2ui", False, 32, 10),
    ("r32g32_uint", "Rg32ui", False, 32, 32),
    ("r16g16_uint", "Rg16ui", False, 32, 16),
    ("r16_uint", "R16ui", False, 32, 16),
    ("r8g8_uint", "Rg8ui", False, 32, 8),
    ("r8_uint", "R8ui", False, 32, 8),
    ("r32g32_sint", "Rg32i", True, 32, 32),
    ("r16g16_sint", "Rg16i", True, 32, 16),
    ("r16_sint", "R16i", True, 32, 16),
    ("r8g8_sint", "Rg8i", True, 32, 8),
    ("r8_sint", "R8i", True, 32, 8),
    ("r64_sint", "R64i", True, 64, 64),
    ("r64_uint", "R64ui", False, 64, 64),
]
BY_NAME = {f[0]: f for f in FORMATS}

OTHER = {
    (False, False): "r32g32b32a32_uint",
    (True, False): "r32g32b32a32_sint",
    (False, True): "r64_uint",
    (True, True): "r64_sint",
}


def py(value) -> str:
    return json.dumps(repr(value))


def image_decl(type_id, ptr_type_id, var_id, image_id, sampled_type, image_format) -> tuple:
    return (
        f"{type_id}                     = OpTypeImage {sampled_type} 2D 0 0 0 2 {image_format}\n",
        f"{ptr_type_id}   = OpTypePointer UniformConstant {type_id}\n",
        f"{var_id}                      = OpVariable {ptr_type_id} UniformConstant\n",
        f"{image_id}                          = OpLoad {type_id} {var_id}\n",
    )


def case_entry(kind: str, read_name: str, write_name: str, forced: bool, relaxed: bool) -> tuple:
    read, write = BY_NAME[read_name], BY_NAME[write_name]
    is_write_test = kind in ("write", "nontemporal")
    tested = write if is_write_test else read
    is_signed = tested[2]
    using64 = read[3] == 64 or write[3] == 64

    capability = ""
    extension = ""
    extra_types = ""
    if using64:
        extension += 'OpExtension "SPV_EXT_shader_image_int64"\n'
        capability += "OpCapability Int64\nOpCapability Int64ImageEXT\n"
        extra_types += (
            "%type_i64                           = OpTypeInt 64 1\n%type_u64                           = OpTypeInt 64 0\n"
            "%type_vec3_i64                      = OpTypeVector %type_i64 3\n%type_vec3_u64                      = OpTypeVector %type_u64 3\n"
            "%type_vec4_i64                      = OpTypeVector %type_i64 4\n%type_vec4_u64                      = OpTypeVector %type_u64 4\n"
        )
    relaxed_text = "OpDecorate %src_image_ptr RelaxedPrecision\n" if relaxed else ""

    signed_sample_type = (is_signed and not forced) or (not is_signed and forced)
    sampled_postfix = ("i" if signed_sample_type else "u") + ("64" if using64 else "32")
    extend_operand = "SignExtend" if is_signed else "ZeroExtend"
    sampled_type = f"%type_{sampled_postfix}"
    write_operand = ("Nontemporal" if kind == "nontemporal" else (extend_operand if is_write_test else ""))
    read_operand = extend_operand if not is_write_test else ""

    if read_name == write_name:
        types, uniforms, variables, load = image_decl("%type_image", "%type_ptr_uniform_const_image", "%src_image_ptr", "%src_image", sampled_type, read[1])
        t2, u2, v2, l2 = image_decl("%type_image", "%type_ptr_uniform_const_image", "%dst_image_ptr", "%dst_image", sampled_type, read[1])
        image_types, image_uniforms, image_variables, image_load = types, uniforms, variables + v2, load + l2
    else:
        t1, u1, v1, l1 = image_decl("%type_src_image", "%type_ptr_uniform_const_src_image", "%src_image_ptr", "%src_image", sampled_type, read[1])
        t2, u2, v2, l2 = image_decl("%type_dst_image", "%type_ptr_uniform_const_dst_image", "%dst_image_ptr", "%dst_image", sampled_type, write[1])
        image_types, image_uniforms, image_variables, image_load = t1 + t2, u1 + u2, v1 + v2, l1 + l2

    derived = {
        "capability": capability,
        "extension": extension,
        "extra_types": extra_types,
        "relaxed_precision": relaxed_text,
        "image_types": image_types,
        "image_uniforms": image_uniforms,
        "image_variables": image_variables,
        "image_load": image_load,
        "sampled_type_vec4": f"%type_vec4_{sampled_postfix}",
        "read_extend_operand": read_operand,
        "write_extend_operand": write_operand,
    }
    return derived, "spirv1.6" if kind == "nontemporal" else "spirv1.4"


def emit(key: str, derived: dict, version: str) -> str:
    derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
    return f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "comp", template = "image/extend_operand.spvasm", stage = "asm", spirv_version = "{version}" }}]
derived = {{ {derived_text} }}
"""


def main() -> None:
    out = [HEADER]
    count = 0
    for fmt in FORMATS:
        name, _, is_signed, bits, _ = fmt
        for kind in ("read", "write"):
            for mismatched in (False, True):
                if mismatched and not is_signed:
                    continue
                for relaxed in (False, True):
                    signed_other = (is_signed and not mismatched) or (not is_signed and mismatched)
                    other = OTHER[(signed_other, bits == 64)]
                    read_name = name if kind == "read" else other
                    write_name = name if kind == "write" else other
                    if relaxed and BY_NAME[read_name][4] > 16:
                        continue
                    key = f"ext_{kind}_{read_name}_{write_name}_{int(mismatched)}_{int(relaxed)}"
                    derived, version = case_entry(kind, read_name, write_name, mismatched, relaxed)
                    out.append(emit(key, derived, version))
                    count += 1
        write_name = OTHER[(is_signed, bits == 64)]
        key = f"ext_nontemporal_{name}_{write_name}_0_0"
        derived, version = case_entry("nontemporal", name, write_name, False, False)
        out.append(emit(key, derived, version))
        count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
