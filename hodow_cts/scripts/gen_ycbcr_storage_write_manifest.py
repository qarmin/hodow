#!/usr/bin/env python3
"""Writes shaders/manifest/ycbcr_storage_image_write.toml, its GLSL sources and the program lookup of the Rust port.

`initPrograms` of vktYCbCrStorageImageWriteTests.cpp: one compute shader per plane of a format, its size and workgroup depend on the image size, so
there is one manifest case per (format, size) with the programs comp0..compN.
"""
import re
import sys
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_ycbcr_formats import read_planar_descriptions  # noqa: E402

UPSTREAM = CRATE / "upstream" / "external" / "vulkancts" / "framework" / "vulkan" / "vkImageUtil.cpp"
SRC = CRATE / "shaders" / "src" / "ycbcr" / "storage_write"
MANIFEST = CRATE / "shaders" / "manifest" / "ycbcr_storage_image_write.toml"
LOOKUP = CRATE / "src" / "vkt" / "tests" / "ycbcr" / "storage_write_programs.rs"
CASES = CRATE / "src" / "vkt" / "tests" / "ycbcr" / "not_ported_cases" / "storage_image_write.txt"

SIZES = [(512, 512), (1024, 128), (66, 32)]

WRITE_REDIRECT = {
    "VK_FORMAT_G8B8G8R8_422_UNORM": "VK_FORMAT_R8G8B8A8_UNORM",
    "VK_FORMAT_G10X6B10X6G10X6R10X6_422_UNORM_4PACK16": "VK_FORMAT_R16G16B16A16_UNORM",
    "VK_FORMAT_G12X4B12X4G12X4R12X4_422_UNORM_4PACK16": "VK_FORMAT_R16G16B16A16_UNORM",
    "VK_FORMAT_G16B16G16R16_422_UNORM": "VK_FORMAT_R16G16B16A16_UNORM",
    "VK_FORMAT_B8G8R8G8_422_UNORM": "VK_FORMAT_R8G8B8A8_UNORM",
    "VK_FORMAT_B10X6G10X6R10X6G10X6_422_UNORM_4PACK16": "VK_FORMAT_R16G16B16A16_UNORM",
    "VK_FORMAT_B12X4G12X4R12X4G12X4_422_UNORM_4PACK16": "VK_FORMAT_R16G16B16A16_UNORM",
    "VK_FORMAT_B16G16R16G16_422_UNORM": "VK_FORMAT_R16G16B16A16_UNORM",
}

QUALIFIER = {
    "R8_UNORM": "r8", "R16_UNORM": "r16", "R8G8_UNORM": "rg8", "R16G16_UNORM": "rg16",
    "R10X6_UNORM_PACK16": "r16", "R10X6G10X6_UNORM_2PACK16": "rg16", "R10X6G10X6B10X6A10X6_UNORM_4PACK16": "rgba16",
    "R12X4_UNORM_PACK16": "r16", "R12X4G12X4_UNORM_2PACK16": "rg16", "R12X4G12X4B12X4A12X4_UNORM_4PACK16": "rgba16",
    "R8G8B8A8_UNORM": "rgba8", "R16G16B16A16_UNORM": "rgba16",
}

VALUE_STRINGS = [
    "float(int(gl_GlobalInvocationID.x) % 127) / 127.0",
    "float(int(gl_GlobalInvocationID.y) % 127) / 127.0",
    "float(int(gl_GlobalInvocationID.z) % 127) / 127.0",
    "1.0",
]


def qualifier(vk_format: str) -> str:
    name = vk_format.removeprefix("VK_FORMAT_")
    if name in QUALIFIER:
        return QUALIFIER[name]
    return "rgba8" if not any(k in name for k in ("10X6", "12X4", "16")) else "rgba16"


def read_channels(text: str) -> dict:
    body = text[text.index("const PlanarFormatDescription &getYCbCrPlanarFormatDescription"):]
    end = body.find("\nbool isYCbCrExtensionFormat")
    body = body[: end if end >= 0 else len(body)]
    entries = {}
    chunks = re.split(r"\n\s*//\s*(VK_FORMAT_[A-Za-z0-9_]+)\s*\n", body)
    for i in range(1, len(chunks) - 1, 2):
        name, entry = chunks[i], chunks[i + 1]
        rows = re.findall(r"\{\s*(\d+)\s*,\s*(unorm|0)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", entry)
        if len(rows) < 4:
            continue
        channels = []
        for plane, kind, offset, size, stride in rows[:4]:
            channels.append(None if kind == "0" and size == "0" else (int(plane), int(offset)))
        entries.setdefault(name, channels)
    return entries


def work_group_size(w: int, h: int, d: int):
    max_inv = 128
    x = min(min(w, 128), max_inv)
    y = min(min(h, 128), max_inv // x)
    z = min(min(d, 64), max_inv // (x * y))
    return x, y, z


def shader(ext, local, qual, value):
    return (
        "#version 440\n"
        f"layout (local_size_x = {local[0]}, local_size_y = {local[1]}, local_size_z = {local[2]}) in; \n"
        f"layout (binding = 0, {qual}) writeonly uniform highp image2D u_image;\n"
        "void main (void)\n"
        "{\n"
        f"    if( gl_GlobalInvocationID.x < {ext[0]} ) \n"
        f"    if( gl_GlobalInvocationID.y < {ext[1]} ) \n"
        f"    if( gl_GlobalInvocationID.z < {ext[2]} ) \n"
        "    {\n"
        f"        imageStore(u_image, ivec2( gl_GlobalInvocationID.x, gl_GlobalInvocationID.y ) ,vec4{value});\n"
        "    }\n"
        "}\n"
    )


def main() -> None:
    text = UPSTREAM.read_text()
    planar = read_planar_descriptions(text)
    channels = read_channels(text)
    wanted = sorted({line.split(".")[0] for line in CASES.read_text().split()})
    by_lower = {name.removeprefix("VK_FORMAT_").removesuffix("_EXT").lower(): name for name in planar}

    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.ycbcr.storage_image_write.*",
        "#",
        "# @generated by hodow_cts/scripts/gen_ycbcr_storage_write_manifest.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/ycbcr/vktYCbCrStorageImageWriteTests.cpp"',
        'rust_module = "ycbcr/storage_write_tests"',
        "",
    ]
    table = []
    files = {}
    for lower in wanted:
        fmt = by_lower[lower]
        bw, bh, planes = planar[fmt]
        ch = channels[fmt]
        ax = max([bw] + [p[1] for p in planes])
        ay = max([bh] + [p[2] for p in planes])
        for (sx, sy) in SIZES:
            if sx % ax or sy % ay:
                continue
            grid = (sx // bw, sy // bh, 1)
            progs = []
            for plane_ndx, (esize, wdiv, hdiv, compat) in enumerate(planes):
                compat = compat.removesuffix("_EXT")
                write_compat = WRITE_REDIRECT.get(compat, compat)
                if write_compat != compat:
                    ext = (grid[0], grid[1], 1)
                else:
                    ext = (max(grid[0] // wdiv, 1), max(grid[1] // hdiv, 1), 1)
                on_plane = [(n, c[1]) for n, c in enumerate(ch) if c is not None and c[0] == plane_ndx]
                if len(planes) > 1:
                    on_plane.sort(key=lambda t: t[1])
                vals = [VALUE_STRINGS[n] for n, _ in on_plane]
                vals += ["0"] * (4 - len(vals))
                value = "( " + ", ".join(vals) + " )"
                src = shader(ext, work_group_size(*ext), qualifier(compat), value)
                if src not in files:
                    files[src] = f"s{len(files)}.comp"
                    (SRC / files[src]).write_text(src)
                progs.append(files[src])
            name = f"{lower}_{sx}_{sy}"
            const = "YCBCR_WRITE_" + name.upper()
            out += [
                "[[case]]",
                f'name = "{name}"',
                f'rust_const = "{const}"',
                'rust_type = "SharedProgram"',
                "programs = [",
            ]
            for i, f in enumerate(progs):
                out.append(f'    {{ name = "comp{i}", template = "ycbcr/storage_write/{f}", stage = "comp" }},')
            out += ["]", ""]
            table.append((name, const))
    MANIFEST.write_text("\n".join(out))

    lines = [
        "// @generated by hodow_cts/scripts/gen_ycbcr_storage_write_manifest.py - do not hand-edit.",
        "",
        "use crate::generated::shaders::ycbcr_storage_image_write::*;",
        "use crate::vk::programs::BinaryCollection;",
        "",
        "/// The programs of the manifest case `<format name lowercase>_<width>_<height>`",
        "pub fn programs_for(name: &str) -> Option<BinaryCollection> {",
        "    match name {",
    ]
    for name, const in table:
        lines.append(f'        "{name}" => Some({const}.programs),')
    lines += ["        _ => None,", "    }", "}", ""]
    LOOKUP.write_text("\n".join(lines))
    print(len(table), "cases,", len(files), "distinct shaders")


if __name__ == "__main__":
    main()
