#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.image.load_store_lod.*.

`LoadStoreTest::makePrograms` with `imageLoadStoreLodAMD`: a compute shader that, for each of the six mip levels of the texture, loads a texel
with imageLoadLodAMD and stores it mirrored horizontally with imageStoreLodAMD. It depends on the texture type, the format and the flags
that reach it (the format is declared on the reads, on the writes, one layer is bound at a time), so there is one entry per case of
`createImageLoadStoreLodAMDTests`, found by `lod_key` in load_store_lod_tests.rs. The format tables are those of gen_image_store_manifest.py.

A pure text generator: no glslang and no cargo.
"""

import json
from pathlib import Path

import gen_image_store_manifest as store

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "image_load_store_lod.toml"

HEADER = """# Shader manifest for dEQP-VK.image.load_store_lod.*
#
# @generated by hodow_cts/scripts/gen_image_load_store_lod_manifest.py - do not hand-edit.
#
# `LoadStoreTest::makePrograms` with imageLoadStoreLodAMD, one entry per texture type, format and flag combination.

upstream_source = "external/vulkancts/modules/vulkan/image/vktImageLoadStoreTests.cpp"
rust_module = "image/load_store_lod_tests"
"""

LEVELS = 6
TEXTURES = [t for t in store.TEXTURES if t[0] != "buffer"]


def py(value) -> str:
    return json.dumps(repr(value))


def body(dimension: int) -> str:
    lines = []
    if dimension == 1:
        lines.append("    int pos = int(gl_GlobalInvocationID.x);\n")
    elif dimension == 2:
        lines.append("    ivec2 pos = ivec2(gl_GlobalInvocationID.xy);\n")
    else:
        lines.append("    ivec3 pos = ivec3(gl_GlobalInvocationID);\n")
    for level in range(LEVELS):
        x_max = max((64 >> level) - 1, 1)
        if dimension == 1:
            load = f"imageLoadLodAMD(u_image0, {x_max}-pos, {level})"
            lines.append(f"    imageStoreLodAMD(u_image1, pos, {level}, {load});\n")
        elif dimension == 2:
            load = f"imageLoadLodAMD(u_image0, ivec2({x_max}-pos.x, pos.y), {level})"
            lines.append(f"    imageStoreLodAMD(u_image1, pos, {level}, {load});\n")
        else:
            load = f"imageLoadLodAMD(u_image0, ivec3({x_max}-pos.x, pos.y, pos.z), {level})"
            lines.append(f"    imageStoreLodAMD(u_image1, pos, {level}, {load});\n")
    return "".join(lines)


def main() -> None:
    out = [HEADER]
    count = 0
    for texture in TEXTURES:
        type_name, dimension, layer_dimension, _, _, layered, shader_type, single_type = texture
        for name in store.S_FORMATS:
            info = store.format_info(name)
            if not info["qualifier"]:
                continue
            image_prefix = {"uint": "u", "int": "i"}.get(info["cls"], "")
            combos = [(True, True, False), (False, True, False)]
            if layered:
                combos.append((True, True, True))
            for reads, writes, single_layer in combos:
                used_dimension = layer_dimension if single_layer else dimension
                image_type_name = single_type if single_layer else shader_type
                extensions = ""
                if not reads or not writes:
                    extensions += "#extension GL_EXT_shader_image_load_formatted : require\n"
                extensions += "#extension GL_AMD_shader_image_load_store_lod : require\n"
                derived = {
                    "extensions": extensions,
                    "read_qualifier": f", {info['qualifier']}" if reads else "",
                    "write_qualifier": f", {info['qualifier']}" if writes else "",
                    "image_type": f"{image_prefix}image{image_type_name}",
                    "body": body(used_dimension),
                }
                key = f"ld_{type_name}_{name.lower()}_{int(reads)}{int(writes)}{int(single_layer)}"
                derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
                out.append(
                    f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{{ name = "comp", template = "image/load_store_lod.comp", stage = "comp" }}]
derived = {{ {derived_text} }}
"""
                )
                count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
