#!/usr/bin/env python3
"""Generates khr_gl/geometry_shader/rendering_shaders.rs: the shader sources of GeometryShaderRendering{Points,Lines,Triangles}Case.

The text is taken verbatim from esextcGeometryShaderRendering.cpp of the pinned upstream checkout (--src, default tmp/glcts-src): every `static const char *NAME = "..." "...";` and `static std::string NAME = ...;` inside a `getFragmentShaderCode`, `getGeometryShaderCode` or `getVertexShaderCode` body becomes a constant `<CLASS>_<GETTER>_<NAME>`. `--check` fails when the committed file differs.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
UPSTREAM = "external/openglcts/modules/glesext/geometry_shader/esextcGeometryShaderRendering.cpp"
OUT = ROOT / "hodow_cts/src/khr_gl/geometry_shader/rendering_shaders.rs"

FUNC_RE = re.compile(r"^\S.*GeometryShaderRendering(Points|Lines|Triangles)Case::(get(?:Fragment|Geometry|Vertex)ShaderCode)\(")
DECL_RE = re.compile(r"^\s*static (?:const char \*|std::string )(\w+)\s*=(.*)$")
STR_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')
ESC = {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}


def unescape(raw):
    out = []
    i = 0
    while i < len(raw):
        if raw[i] == "\\":
            out.append(ESC[raw[i + 1]])
            i += 2
        else:
            out.append(raw[i])
            i += 1
    return "".join(out)


def rust_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def collect(lines):
    found = []
    cls = getter = None
    i = 0
    while i < len(lines):
        line = lines[i]
        m = FUNC_RE.match(line)
        if m:
            cls, getter = m.group(1), m.group(2)
        elif re.match(r"^\S.*::", line) and not line.startswith("//"):
            cls = getter = None
        m = DECL_RE.match(line)
        if m and cls:
            name = m.group(1)
            body = m.group(2)
            parts = []
            while True:
                stripped = re.sub(r"/\*.*?\*/", "", body)
                parts.extend(unescape(s) for s in STR_RE.findall(stripped))
                if ";" in re.sub(r'"(?:[^"\\]|\\.)*"', "", stripped):
                    break
                i += 1
                body = lines[i]
            found.append((f"{cls}_{getter}_{name}".upper().replace("GET", "", 1).replace("__", "_"), "".join(parts)))
        i += 1
    return found


def render(source):
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/openglcts/modules/glesext/geometry_shader/esextcGeometryShaderRendering.cpp  (shader sources)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2014-2016 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_khr_geometry_shader_rendering.py - do not edit.",
        "",
    ]
    for name, text in collect(source.splitlines()):
        out.append(f"pub(super) const {name}: &str = {rust_string(text)};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=pathlib.Path, default=ROOT / "tmp/glcts-src")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render((args.src / UPSTREAM).read_text())
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run {sys.argv[0]}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
