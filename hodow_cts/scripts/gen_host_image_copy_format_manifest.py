#!/usr/bin/env python3
"""Writes the shader manifest of the per-format groups of dEQP-VK.image.host_image_copy.*.

`HostImageCopyTestCase::initPrograms`: a full screen strip, the fragment shader that samples the copied image (the depth of a
depth format in the red channel) and the compute shader that does the same into a storage image (as unsigned integers when the
output format is R8G8B8A8_UINT). Four program sets, found by `HostImageCopyCase::programs`.

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "image_host_image_copy_format.toml"

HEADER = """# Shader manifest for the per-format groups of dEQP-VK.image.host_image_copy.*
#
# @generated by hodow_cts/scripts/gen_host_image_copy_format_manifest.py - do not hand-edit.
#
# `HostImageCopyTestCase::initPrograms`.

upstream_source = "external/vulkancts/modules/vulkan/image/vktImageHostImageCopyTests.cpp"
rust_module = "image/host_image_copy_format_tests"
"""


def py(value: str) -> str:
    return '"' + repr(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def case(key: str, programs: str, derived: str) -> str:
    return f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [{programs}]
derived = {{ {derived} }}
"""


def main() -> None:
    vert = '{ name = "vert", template = "image/host_image_copy_format/hic.vert", stage = "vert" }'
    frag = '{ name = "frag", template = "image/host_image_copy_format/hic.frag", stage = "frag" }'
    comp = '{ name = "comp", template = "image/host_image_copy_format/hic.comp", stage = "comp" }'
    out = [HEADER]
    out.append(case("hic_draw_color", f"{vert}, {frag}", f"output = {py('    out_color = texture(combinedSampler, texCoord);' + chr(10))}"))
    out.append(case("hic_draw_depth", f"{vert}, {frag}", f"output = {py('    out_color = vec4(texture(combinedSampler, texCoord).r, 0, 0, 0);' + chr(10))}"))
    float_output = "texture(combinedSampler, vec2(pixelCoord) / (textureSize(combinedSampler, 0) - vec2(0.001f)))"
    uint_output = "uvec4(texture(combinedSampler, vec2(pixelCoord) / (textureSize(combinedSampler, 0) - vec2(0.001f))) * 255)"
    out.append(case("hic_dispatch_float", comp, f"image = {py('image2D')}, output = {py(float_output)}"))
    out.append(case("hic_dispatch_uint", comp, f"image = {py('uimage2D')}, output = {py(uint_output)}"))
    MANIFEST.write_text("".join(out))
    print(f"4 program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
