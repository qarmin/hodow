#!/usr/bin/env python3
"""Generates khr_gl/transform_feedback_tests/geometry_shaders.rs: the raw-string shaders of gl3cts::TransformFeedback::Geometry.

The text is taken verbatim from gl3cTransformFeedbackTests.cpp of the pinned upstream checkout (--src, default tmp/glcts-src), so the Rust constants cannot drift from the C++ literals. `--check` fails when the committed file differs from what this script would write.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
UPSTREAM = "external/openglcts/modules/gl/gl3cTransformFeedbackTests.cpp"
OUT = ROOT / "hodow_cts/src/khr_gl/transform_feedback_tests/geometry_shaders.rs"
NAMES = [("s_vertex_shader", "VERTEX_SHADER"), ("s_geometry_shader", "GEOMETRY_SHADER"), ("s_fragment_shader", "FRAGMENT_SHADER")]


def rust_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def render(source):
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/openglcts/modules/gl/gl3cTransformFeedbackTests.cpp  (TransformFeedback::Geometry shaders)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2015-2016 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// GENERATED by scripts/gen_khr_transform_feedback_geometry_shaders.py - do not edit.",
        "",
    ]
    for cpp_name, rust_name in NAMES:
        match = re.search(r"Geometry::" + cpp_name + r'\s*=\s*R"\((.*?)\)";', source, re.S)
        if not match:
            sys.exit(f"{cpp_name} not found")
        out.append(f"pub(super) const {rust_name}: &str = {rust_string(match.group(1))};")
        out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", default=str(ROOT / "tmp/glcts-src"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    source = (pathlib.Path(args.src) / UPSTREAM).read_text()
    text = render(source)

    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is stale")
        return

    OUT.write_text(text)


if __name__ == "__main__":
    main()
