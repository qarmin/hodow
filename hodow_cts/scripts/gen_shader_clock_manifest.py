#!/usr/bin/env python3
"""Writes shaders/manifest/shader_clock.toml: the compute cases of dEQP-VK.glsl.shader_clock (4) of vktShaderClockTests.cpp.

Each reads a clock twice in every one of 32 invocations and writes uvec2(1, 0) where the second reading was lower than the first. The text is what
`ShaderClockCase::initShaderSpec` puts in the global declarations and the body of its ShaderSpec, wrapped the way the compute `ShaderExecutor` wraps it: the output
symbol `out0` is a uvec2 stored at the invocation's index of a storage buffer. The vertex and fragment cases need the executor's rendering pipelines and are not here.

    python3 hodow_cts/scripts/gen_shader_clock_manifest.py

A pure text generator: no glslang and no cargo.
"""

import json
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "shader_clock.toml"

# (clock name, 64 bit, device clock)
OPERATIONS = [("clockARB", True, False), ("clock2x32ARB", False, False), ("clockRealtimeEXT", True, True), ("clockRealtime2x32EXT", False, True)]


def shader(name, is_64bit, is_device):
    extensions = []
    if is_64bit:
        extensions.append("#extension GL_ARB_gpu_shader_int64 : require")
        body = [
            f"uint64_t time1 = {name}();",
            f"uint64_t time2 = {name}();",
            "out0  = uvec2(0, 0);",
            "if (time1 > time2) {",
            "    out0.x = 1;",
            "}",
        ]
    else:
        body = [
            f"uvec2 time1 = {name}();",
            f"uvec2 time2 = {name}();",
            "out0  = uvec2(0, 0);",
            "if (time1.y > time2.y || (time1.y == time2.y && time1.x > time2.x)){",
            "    out0.x = 1;",
            "}",
        ]
    extensions.append("#extension GL_EXT_shader_realtime_clock : require" if is_device else "#extension GL_ARB_shader_clock : enable")
    lines = ["#version 450", *extensions, "layout(local_size_x = 1, local_size_y = 1, local_size_z = 1) in;", "layout(set = 0, binding = 0, std430) buffer Output { uvec2 values[]; } outputBuffer;", "void main()", "{", "    uvec2 out0;"]
    lines += ["    " + line for line in body]
    lines += ["    outputBuffer.values[gl_GlobalInvocationID.x] = out0;", "}"]
    return "\n".join(lines) + "\n"


def main():
    out = [
        "# Shader manifest for dEQP-VK.glsl.shader_clock.compute.*\n#\n"
        "# @generated by hodow_cts/scripts/gen_shader_clock_manifest.py - do not hand-edit.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/shaderexecutor/vktShaderClockTests.cpp"\nrust_module = "glsl/shader_clock_tests"\n'
    ]
    for name, is_64bit, is_device in OPERATIONS:
        out.append(
            f'\n[[case]]\nname = "compute/{name}"\nrust_const = "SHADER_CLOCK_{name.upper()}"\nrust_type = "ShaderClockCase"\n'
            f'programs = [ {{ name = "compute", template = "glsl/source.comp", stage = "comp" }} ]\n'
            f'params = {{ bits64 = {{ type = "u32", value = {int(is_64bit)} }}, device = {{ type = "u32", value = {int(is_device)} }} }}\n'
            f"derived = {{ source_comp = {json.dumps(repr(shader(name, is_64bit, is_device)))} }}\n"
        )
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {len(OPERATIONS)} cases")


if __name__ == "__main__":
    main()
