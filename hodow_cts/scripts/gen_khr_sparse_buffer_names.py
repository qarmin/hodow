#!/usr/bin/env python3
"""Generates khr_gl/sparse_buffer_tests/names.rs: the BufferStorageTest case names of gl4cts::SparseBufferTests.

Upstream builds each name at run time from `testCase->getName()` plus loop indices (gl4cSparseBufferTests.cpp, `addBufferStorageTests`); the Khronos mustpass list is the record of what that code produces, so the names are read from it instead of being re-derived. `--check` fails when the committed file differs from what this script would write.
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DEFAULT_MUSTPASS = ROOT / "tmp/cts-openglcts/src/external/openglcts/data/gl_cts/data/mustpass/gl/khronos_mustpass/4.6.1.x/gl43-main.txt"
OUT = ROOT / "hodow_cts/src/khr_gl/sparse_buffer_tests/names.rs"
PREFIX = "KHR-GL43.sparse_buffer_tests."


def render(names):
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/openglcts/modules/gl/gl4cSparseBufferTests.cpp  (SparseBufferTests::addBufferStorageTests)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2016 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// GENERATED by scripts/gen_khr_sparse_buffer_names.py - do not edit.",
        "",
        f"pub(super) const BUFFER_STORAGE_TEST_NAMES: [&str; {len(names)}] = [",
    ]
    out += [f'    "{name}",' for name in names]
    out += ["];", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mustpass", default=str(DEFAULT_MUSTPASS))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    names = []
    for line in pathlib.Path(args.mustpass).read_text().splitlines():
        if line.startswith(PREFIX) and line[len(PREFIX):].startswith("BufferStorageTest_"):
            names.append(line[len(PREFIX):])

    if not names:
        sys.exit("no BufferStorageTest names found")

    text = render(names)

    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is stale")
        return

    OUT.write_text(text)


if __name__ == "__main__":
    main()
