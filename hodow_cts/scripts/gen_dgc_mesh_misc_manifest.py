#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.graphics.mesh.misc (`manySequencesInitPrograms` and `NoFragCase::initPrograms` of
vktDGCGraphicsMeshTestsExt.cpp). A pure text generator: no glslang, no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_mesh_misc.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

SEQ_WG = 64
SPV = ', spirv_version = "spirv1.4"'


def many_task():
    return (
        "#version 460\n"
        "#extension GL_EXT_mesh_shader : enable\n"
        f"layout (local_size_x={SEQ_WG}, local_size_y=1, local_size_z=1) in;\n"
        "layout (set=0, binding=0, std430) buffer OutputBlock { uint values[]; } outputBuffer;\n"
        "layout (push_constant, std430) uniform PushConstantBlock { uint valueIndex; } pc;\n"
        "void main (void) {\n"
        "    atomicAdd(outputBuffer.values[pc.valueIndex], 1u);\n"
        "    EmitMeshTasksEXT(0, 0, 0);\n"
        "}\n"
    )


def many_mesh():
    return (
        "#version 460\n"
        "#extension GL_EXT_mesh_shader : enable\n"
        f"layout (local_size_x={SEQ_WG}, local_size_y=1, local_size_z=1) in;\n"
        "layout (points) out;\n"
        "layout (max_vertices=1, max_primitives=1) out;\n"
        "layout (set=0, binding=0, std430) buffer OutputBlock { uint values[]; } outputBuffer;\n"
        "layout (push_constant, std430) uniform PushConstantBlock { uint valueIndex; } pc;\n"
        "void main (void) {\n"
        "    atomicAdd(outputBuffer.values[pc.valueIndex], 1u);\n"
        "    SetMeshOutputsEXT(0, 0);\n"
        "}\n"
    )


WG_SIZE = 64
OUT_SIZE = 1024
WG_FACTOR = 1000
TASK_DATA_DECL = "struct TaskData {\n    uint globalWorkGroupID;\n};\ntaskPayloadSharedEXT TaskData td;\n"


def nofrag_task(value):
    return (
        "#version 460\n"
        "#extension GL_EXT_mesh_shader : enable\n"
        f"layout (local_size_x={WG_SIZE}, local_size_y=1, local_size_z=1) in;\n"
        "layout (push_constant, std430) uniform PCBlock { uint prevWGCount; } pc;\n"
        f"layout (set=0, binding=0, std430) buffer OutputBlock {{ uint values[{OUT_SIZE}]; }} taskBuffer;\n"
        + TASK_DATA_DECL
        + "void main() {\n"
        "    const uint globalWorkGroupID = pc.prevWGCount + gl_WorkGroupID.x;\n"
        "    const uint slotIndex = globalWorkGroupID * gl_WorkGroupSize.x + gl_LocalInvocationIndex;\n"
        f"    const uint value = {value} + globalWorkGroupID * {WG_FACTOR} + gl_LocalInvocationIndex;\n"
        "    taskBuffer.values[slotIndex] = value;\n"
        "    if (gl_LocalInvocationIndex == 0u) {\n"
        "        td.globalWorkGroupID = globalWorkGroupID;\n"
        "    }\n"
        "    EmitMeshTasksEXT(1u, 1u, 1u);\n"
        "}\n"
    )


def nofrag_mesh(value, has_task):
    binding = 1 if has_task else 0
    decl = TASK_DATA_DECL if has_task else "layout (push_constant, std430) uniform PCBlock { uint prevWGCount; } pc;\n"
    wg_id = "td.globalWorkGroupID" if has_task else "pc.prevWGCount + gl_WorkGroupID.x"
    return (
        "#version 460\n"
        "#extension GL_EXT_mesh_shader : enable\n"
        f"layout (local_size_x={WG_SIZE}, local_size_y=1, local_size_z=1) in;\n"
        + decl
        + f"layout (set=0, binding={binding}, std430) buffer OutputBlock {{ uint values[{OUT_SIZE}]; }} meshBuffer;\n"
        "layout (points) out;\n"
        "layout (max_vertices=1, max_primitives=1) out;\n"
        "void main() {\n"
        f"    const uint globalWorkGroupID = {wg_id};\n"
        "    const uint slotIndex = globalWorkGroupID * gl_WorkGroupSize.x + gl_LocalInvocationIndex;\n"
        f"    const uint value = {value} + globalWorkGroupID * {WG_FACTOR} + gl_LocalInvocationIndex;\n"
        "    meshBuffer.values[slotIndex] = value;\n"
        "    SetMeshOutputsEXT(0u, 0u);\n"
        "}\n"
    )


def entry(name, file, stage):
    spv = SPV if stage in ("task", "mesh") else ""
    return f'{{ name = "{name}", template = "dgc/{file}", stage = "{stage}"{spv} }}'


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    manifest = (
        "# Shader manifest for dEQP-VK.dgc.ext.graphics.mesh.misc\n"
        "#\n"
        "# @generated by hodow_cts/scripts/gen_dgc_mesh_misc_manifest.py - do not hand-edit.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCGraphicsMeshTestsExt.cpp"\n'
        'rust_module = "dgc/graphics_mesh_misc_tests"\n'
    )

    def add_case(name, programs):
        nonlocal manifest
        manifest += (
            f'\n[[case]]\nname = "{name}"\nrust_const = "{name.upper()}"\nrust_type = "SharedProgram"\n'
            f"programs = [ {', '.join(programs)} ]\n"
        )

    (SRC_DIR / "mesh_many_mesh.mesh").write_text(many_mesh())
    (SRC_DIR / "mesh_many_task.task").write_text(many_task())
    add_case("mesh_many", [entry("mesh", "mesh_many_mesh.mesh", "mesh")])
    add_case("mesh_many_task", [entry("task", "mesh_many_task.task", "task"), entry("mesh", "mesh_many_mesh.mesh", "mesh")])

    for has_task in (False, True):
        for use_ies in (False, True):
            suffix = ("_task" if has_task else "") + ("_ies" if use_ies else "")
            programs = []
            if has_task:
                task_values = [1000000] + ([2000000] if use_ies else [])
                for i, value in enumerate(task_values):
                    file = f"mesh_nofrag{suffix}_task{i}.task"
                    (SRC_DIR / file).write_text(nofrag_task(value))
                    programs.append(entry(f"task{i}", file, "task"))
            mesh_values = [3000000 if has_task else 1000000] + ([4000000 if has_task else 2000000] if use_ies else [])
            for i, value in enumerate(mesh_values):
                file = f"mesh_nofrag{suffix}_mesh{i}.mesh"
                (SRC_DIR / file).write_text(nofrag_mesh(value, has_task))
                programs.append(entry(f"mesh{i}", file, "mesh"))
            add_case(f"mesh_nofrag{suffix}", programs)
    MANIFEST.write_text(manifest)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
