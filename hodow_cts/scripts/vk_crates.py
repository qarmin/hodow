#!/usr/bin/env python3
"""Writes the files that split the Vulkan half of hodow_cts over several crates, from hodow_cts/vk_crates.toml.

Usage (from the repository root):
    python3 hodow_cts/scripts/vk_crates.py           write them
    python3 hodow_cts/scripts/vk_crates.py --check   fail if they, or the groups on disk, disagree with vk_crates.toml

For each crate NAME it writes
    hodow_cts/src/vk_NAME.rs              the crate root: the framework re-exported from hodow_cts_base, `vkt::tests`, `generated`
    hodow_cts/src/vkt/tests_NAME.rs       its groups (found with #[path], nothing moved) and the `main` groups it uses
    hodow_cts/src/generated/vk_NAME/mod.rs  where compile_shaders.py puts the crate's shaders
    hodow_cts/crates/vk_NAME/Cargo.toml
and, for the crate that assembles them (hodow_cts itself), hodow_cts/src/vkt/tests_vulkan.rs.
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
CONFIG = CRATE_DIR / "vk_crates.toml"
TESTS_DIR = CRATE_DIR / "src" / "vkt" / "tests"
HEADER = "// @generated by hodow_cts/scripts/vk_crates.py from hodow_cts/vk_crates.toml - do not hand-edit.\n"

# The group that has a hand-written generated library (gen_vk_shader_library.py) its crate has to carry.
SHADER_LIBRARY_GROUP = "glsl"


def load() -> dict[str, list[str]]:
    return {name: list(c["groups"]) for name, c in tomllib.loads(CONFIG.read_text())["crates"].items()}


def crate_of_group(group: str) -> str:
    for name, groups in load().items():
        if group in groups:
            return name
    raise SystemExit(f"error: the test group `{group}` is in no crate of {CONFIG.name}")


def groups_on_disk() -> set[str]:
    return {p.stem if p.is_file() else p.name for p in TESTS_DIR.iterdir() if p.name != "mod.rs"}


def group_file(group: str) -> str:
    return f"tests/{group}/mod.rs" if (TESTS_DIR / group / "mod.rs").exists() else f"tests/{group}.rs"


def crate_name(name: str) -> str:
    return f"hodow_cts_vk_{name}"


def render(crates: dict[str, list[str]]) -> dict[Path, str]:
    files: dict[Path, str] = {}
    main_groups = sorted(crates["main"])
    for name, groups in crates.items():
        groups = sorted(groups)
        root = CRATE_DIR / "src" / f"vk_{name}.rs"
        files[root] = (
            HEADER
            + f"//\n//! Vulkan test groups: {', '.join(groups)}.\n//!\n"
            "//! The groups say `crate::tcu`, `crate::vk`, `crate::vkt::...` and `crate::generated::shaders::...`, as they did\n"
            "//! when the whole Vulkan half was one crate, so every crate of the half has those paths: the framework is\n"
            "//! re-exported from `hodow_cts_base`, and the groups of `main` appear under `vkt::tests`.\n\n"
            "pub use hodow_cts_base::{glu, rr, tcu, vk};\n"
            "pub use hodow_cts_base::{tcu_fail, tcu_not_ported, tcu_throw_not_supported};\n\n"
            f'#[path = "generated/vk_{name}/mod.rs"]\n'
            "pub mod generated;\n\n"
            "pub mod vkt {\n"
            "    pub use hodow_cts_base::vkt::*;\n\n"
            f'    #[path = "tests_{name}.rs"]\n'
            "    pub mod tests;\n"
            "}\n"
        )
        tests = [HEADER, f"// The groups compiled in `{crate_name(name)}`.\n\n"]
        for g in groups:
            tests.append(f'#[path = "{group_file(g)}"]\npub mod {g};\n\n')
        if name != "main":
            tests.append("// The groups of `main`, which these use.\n")
            tests.append(f"pub use hodow_cts_vk_main::vkt::tests::{{{', '.join(main_groups)}}};\n")
        files[CRATE_DIR / "src" / "vkt" / f"tests_{name}.rs"] = "".join(tests)

        shaders = HEADER + "\npub mod shaders;\n"
        if SHADER_LIBRARY_GROUP in groups:
            shaders += '\n#[path = "../vk_shader_library.rs"]\npub mod vk_shader_library;\n'
        files[CRATE_DIR / "src" / "generated" / f"vk_{name}" / "mod.rs"] = shaders

        dependencies = ['hodow_cts_base = { path = "../base", default-features = false, features = ["gles"] }']
        if name != "main":
            dependencies.append('hodow_cts_vk_main = { path = "../vk_main" }')
        files[CRATE_DIR / "crates" / f"vk_{name}" / "Cargo.toml"] = (
            "# @generated by hodow_cts/scripts/vk_crates.py from hodow_cts/vk_crates.toml - do not hand-edit.\n\n"
            "[package]\n"
            f'name = "{crate_name(name)}"\n'
            "version.workspace = true\nedition.workspace = true\nrust-version.workspace = true\nlicense.workspace = true\n"
            f'description = "Vulkan CTS test groups: {", ".join(groups)}"\n\n'
            "[lib]\n"
            f'name = "{crate_name(name)}"\n'
            f'path = "../../src/vk_{name}.rs"\n\n'
            "[dependencies]\n"
            + "\n".join(dependencies)
            + '\nvulkanalia = { version = "0.35", default-features = false, features = ["std", "libloading"] }\n'
            'libloading = "0.9"\nlog.workspace = true\nserde = { version = "1.0", features = ["derive"] }\nserde_json = "1.0"\n\n'
            "[lints]\nworkspace = true\n"
        )
    own = [HEADER, "// Every Vulkan group, from whichever crate has it: what `hodow_cts::vkt::tests` is.\n\n"]
    for name, groups in crates.items():
        own.append(f"pub use {crate_name(name)}::vkt::tests::{{{', '.join(sorted(groups))}}};\n")
    files[CRATE_DIR / "src" / "vkt" / "tests_vulkan.rs"] = "".join(own)
    return files


def problems(crates: dict[str, list[str]]) -> list[str]:
    found: list[str] = []
    seen: dict[str, str] = {}
    for name, groups in crates.items():
        for g in groups:
            if g in seen:
                found.append(f"group `{g}` is in both `{seen[g]}` and `{name}`")
            seen[g] = name
    on_disk = groups_on_disk()
    for g in sorted(on_disk - set(seen)):
        found.append(f"group `{g}` (src/vkt/tests) is in no crate of {CONFIG.name}")
    for g in sorted(set(seen) - on_disk):
        found.append(f"`{g}` is listed in {CONFIG.name} but there is no such group in src/vkt/tests")
    return found


def main() -> int:
    check = "--check" in sys.argv[1:]
    crates = load()
    bad = problems(crates)
    for message in bad:
        print(f"error: {message}", file=sys.stderr)
    if bad:
        return 1
    files = render(crates)
    if check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"error: {p.relative_to(CRATE_DIR)} is out of date; run hodow_cts/scripts/vk_crates.py", file=sys.stderr)
        if not stale:
            print(f"ok: {len(crates)} crates, {sum(len(g) for g in crates.values())} groups, {len(files)} files up to date")
        return 1 if stale else 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(files)} files for {len(crates)} crates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
