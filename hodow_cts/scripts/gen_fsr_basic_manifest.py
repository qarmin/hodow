#!/usr/bin/env python3
"""Writes the shader manifest of the fragment_shading_rate `basic` groups.

`FSRTestCase::initPrograms` builds a vertex (and geometry) or mesh shader, a fragment shader and a compute shader out of about twenty
flags of the case. The flags that reach each program are few, so the manifest holds one entry per distinct combination of them rather
than one per case: `vs_*` (vert, vert_1_2, geom), `ms_*` (mesh), `fs_*` (frag) and `cs_*` (comp), looked up by the key string
`basic_tests.rs` builds from the same flags. The combinations are collected by replaying `createBasicTests`' loops for the render pass
variant, whose cases are a superset of every other construction type and rendering mode.

A pure text generator: no glslang and no cargo.
"""

import json
from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "fragment_shading_rate_basic.toml"

HEADER = """# Shader manifest for dEQP-VK.fragment_shading_rate.*.basic.*
#
# @generated by hodow_cts/scripts/gen_fsr_basic_manifest.py - do not hand-edit.
#
# `FSRTestCase::initPrograms`, one entry per distinct combination of the flags each program depends on. The templates are under
# shaders/src/fragment_shading_rate/basic/ and read their flags from the `derived` table.

upstream_source = "external/vulkancts/modules/vulkan/fragment_shading_rate/vktFragmentShadingRateBasic.cpp"
rust_module = "fragment_shading_rate/basic_tests"
"""

GROUPS = [
    "basic", "apisamplemask", "samplemaskin", "conservativeunder", "conservativeover", "fragdepth", "fragstencil", "multiviewport",
    "colorlayered", "srlayered", "multiview", "multiviewsrlayered", "multiviewcorrelation", "interlock", "samplelocations",
    "sampleshadingenable", "sampleshadinginput", "fragdepth_early_late", "fragstencil_early_late", "fragdepth_clear",
    "fragstencil_clear", "fragdepth_baselevel", "fragstencil_baselevel", "multipass", "multipass_fragdepth", "multipass_fragstencil",
    "maintenance6", "samplemaskout", "ds_baselevel",
    "ds_baselayer", "ds_baselevel_baselayer",
]
ATTACHMENTS = ["noattachment", "attachment", "noattachmentptr"]
SHADER_RATES = [False, True]
COMBINERS = ["keep", "replace", "min", "max", "mul"]
EXTENTS = [(1, 1), (4, 4), (33, 35), (151, 431), (256, 256)]
SAMPLES = [1, 2, 4, 8, 16]
SHADERS = ["vs", "gs", "ms"]


def b(value) -> int:
    return 1 if value else 0


def py(value) -> str:
    """A TOML string holding the Python expression for `value`."""
    return json.dumps(repr(value))


def case_flags(group: str, shader: str, writes: bool) -> dict:
    ds_groups = ("ds_baselevel", "ds_baselayer", "ds_baselevel_baselayer")
    frag_depth = group in ("fragdepth", "fragdepth_early_late", "fragdepth_clear", "fragdepth_baselevel", "multipass_fragdepth")
    frag_stencil = group in ("fragstencil", "fragstencil_early_late", "fragstencil_clear", "fragstencil_baselevel", "multipass_fragstencil")
    return {
        "shader_writes_rate": writes,
        "geometry_shader": shader == "gs",
        "mesh_shader": shader == "ms",
        "sample_mask_in": group == "samplemaskin",
        "sample_mask_out": group == "samplemaskout",
        "frag_depth": frag_depth,
        "frag_stencil": frag_stencil,
        "multi_viewport": group == "multiviewport",
        "color_layered": group in ("colorlayered", "srlayered"),
        "interlock": group == "interlock",
        "sample_shading_enable": group == "sampleshadingenable",
        "sample_shading_input": group == "sampleshadinginput",
        "early_late": group in ("fragdepth_early_late", "fragstencil_early_late"),
        "helper_invocation": False,
        "use_depth_stencil": frag_depth or frag_stencil or group in ds_groups,
        "cons_rast": group in ("conservativeunder", "conservativeover"),
        "api_sample_mask": group == "apisamplemask",
        "maintenance6": group == "maintenance6",
    }


def keys(flags: dict, samples: int, extent: tuple) -> dict:
    vtx_depth = (not flags["frag_depth"]) and flags["use_depth_stencil"]
    return {
        "vs": f"vs_w{b(flags['shader_writes_rate'])}_g{b(flags['geometry_shader'])}_p{b(flags['multi_viewport'])}_l{b(flags['color_layered'])}_d{b(vtx_depth)}",
        "ms": f"ms_w{b(flags['shader_writes_rate'])}_p{b(flags['multi_viewport'])}_l{b(flags['color_layered'])}_d{b(vtx_depth)}",
        "fs": (
            f"fs_w{b(flags['shader_writes_rate'])}_e{b(flags['early_late'])}_fd{b(flags['frag_depth'])}_fs{b(flags['frag_stencil'])}"
            f"_il{b(flags['interlock'])}_hi{b(flags['helper_invocation'])}_si{b(flags['sample_shading_input'])}"
            f"_se{b(flags['sample_shading_enable'])}_so{b(flags['sample_mask_out'])}_sm{b(flags['sample_mask_in'])}"
        ),
        "cs": f"cs_s{samples}_w{extent[0]}_h{extent[1]}_d{b(flags['use_depth_stencil'])}",
        "simple": f"simple_fd{b(flags['frag_depth'])}_fs{b(flags['frag_stencil'])}_vd{b(vtx_depth)}",
    }, vtx_depth


def collect() -> dict:
    found: dict[str, dict] = {}
    for group in GROUPS:
        for dynamic in (True, False):
            for attachment in ATTACHMENTS:
                for writes in SHADER_RATES:
                    for cmb0 in COMBINERS:
                        for cmb1 in COMBINERS:
                            for extent in EXTENTS:
                                for samples in SAMPLES:
                                    for shader in SHADERS:
                                        flags = case_flags(group, shader, writes)
                                        use_gs = flags["geometry_shader"]
                                        if use_gs and not writes:
                                            continue
                                        if group != "basic" and (not dynamic or cmb0 not in ("keep", "replace") or cmb1 not in ("keep", "replace")):
                                            continue
                                        if use_gs and (flags["api_sample_mask"] or flags["sample_mask_in"] or flags["cons_rast"] or flags["use_depth_stencil"] or flags["maintenance6"] or flags["sample_mask_out"]):
                                            continue
                                        if use_gs and not dynamic:
                                            continue
                                        if group.startswith("multipass") and (attachment != "attachment" or samples != 1):
                                            continue
                                        if (flags["multi_viewport"] or flags["color_layered"]) and not writes:
                                            continue
                                        key_map, vtx_depth = keys(flags, samples, extent)
                                        found[key_map["fs"]] = {"kind": "fs", "flags": dict(flags)}
                                        if group.startswith("multipass"):
                                            found[key_map["simple"]] = {"kind": "simple", "flags": dict(flags), "vtx_depth": vtx_depth}
                                        found[key_map["cs"]] = {"kind": "cs", "flags": dict(flags), "samples": samples, "extent": extent}
                                        if flags["mesh_shader"]:
                                            found[key_map["ms"]] = {"kind": "ms", "flags": dict(flags), "vtx_depth": vtx_depth}
                                        else:
                                            found[key_map["vs"]] = {"kind": "vs", "flags": dict(flags), "vtx_depth": vtx_depth}
    # misc_tests.sample_mask_test and misc_tests.helper_invocation: 32x33, 4 samples, a vertex shader writing the rate
    for helper_invocation in (False, True):
        flags = case_flags("basic", "vs", True)
        flags["helper_invocation"] = helper_invocation
        flags["api_sample_mask"] = True
        key_map, vtx_depth = keys(flags, 4, (32, 33))
        found[key_map["fs"]] = {"kind": "fs", "flags": dict(flags)}
        found[key_map["cs"]] = {"kind": "cs", "flags": dict(flags), "samples": 4, "extent": (32, 33)}
        found[key_map["vs"]] = {"kind": "vs", "flags": dict(flags), "vtx_depth": vtx_depth}
    return found


def emit(name: str, programs: list[str], derived: dict) -> str:
    derived_text = ", ".join(f"{k} = {py(v)}" for k, v in derived.items())
    program_text = "\n".join(f"    {p}," for p in programs)
    return f"""
[[case]]
name = "{name}"
rust_const = "{name.upper()}"
rust_type = "SharedProgram"
programs = [
{program_text}
]
derived = {{ {derived_text} }}
"""


def main() -> None:
    found = collect()
    out = [HEADER]
    t = "fragment_shading_rate/basic"
    for name in sorted(found):
        entry = found[name]
        f = entry["flags"]
        if entry["kind"] == "vs":
            programs = [
                f'{{ name = "vert", template = "{t}/vert.vert", stage = "vert" }}',
                f'{{ name = "vert_1_2", template = "{t}/vert.vert", stage = "vert", spirv_version = "spirv1.5" }}',
            ]
            if f["geometry_shader"]:
                programs.append(f'{{ name = "geom", template = "{t}/geom.geom", stage = "geom" }}')
            writes = ""
            if f["shader_writes_rate"]:
                writes = "  gl_PrimitiveShadingRateEXT = pc.shadingRate;\n  if (gl_PrimitiveShadingRateEXT != pc.shadingRate) readbackok = 0;\n"
                if f["multi_viewport"]:
                    writes += "  gl_ViewportIndex = inInstanceIndex[0] & 1;\n"
                if f["color_layered"]:
                    writes += "  gl_Layer = (inInstanceIndex[0] & 2) >> 1;\n"
            derived = {
                "vtx_depth": bool(entry["vtx_depth"]),
                "shader_writes_rate": f["shader_writes_rate"],
                "geometry_shader": f["geometry_shader"],
                "multi_viewport": f["multi_viewport"],
                "color_layered": f["color_layered"],
                "shading_rate_writes": writes,
            }
            out.append(emit(name, programs, derived))
        elif entry["kind"] == "ms":
            programs = [f'{{ name = "mesh", template = "{t}/mesh.mesh", stage = "mesh", spirv_version = "spirv1.4" }}']
            derived = {
                "vtx_depth": bool(entry["vtx_depth"]),
                "shader_writes_rate": f["shader_writes_rate"],
                "multi_viewport": f["multi_viewport"],
                "color_layered": f["color_layered"],
            }
            out.append(emit(name, programs, derived))
        elif entry["kind"] == "simple":
            programs = [
                f'{{ name = "vert_simple", template = "{t}/vert_simple.vert", stage = "vert" }}',
                f'{{ name = "frag_simple", template = "{t}/frag_simple.frag", stage = "frag" }}',
            ]
            derived = {"vtx_depth": bool(entry["vtx_depth"]), "frag_depth": f["frag_depth"], "frag_stencil": f["frag_stencil"]}
            out.append(emit(name, programs, derived))
        elif entry["kind"] == "fs":
            programs = [f'{{ name = "frag", template = "{t}/frag.frag", stage = "frag" }}']
            derived = {
                "shader_writes_rate": f["shader_writes_rate"],
                "early_late": f["early_late"],
                "frag_depth": f["frag_depth"],
                "frag_stencil": f["frag_stencil"],
                "interlock": f["interlock"],
                "helper_invocation": f["helper_invocation"],
                "sample_shading_input": f["sample_shading_input"],
                "sample_shading_enable": f["sample_shading_enable"],
                "sample_mask_out": f["sample_mask_out"],
                "sample_mask_in": f["sample_mask_in"],
            }
            out.append(emit(name, programs, derived))
        else:
            programs = [f'{{ name = "comp", template = "{t}/comp.comp", stage = "comp" }}']
            derived = {
                "samples": entry["samples"],
                "width": entry["extent"][0],
                "height": entry["extent"][1],
                "use_depth_stencil": f["use_depth_stencil"],
            }
            out.append(emit(name, programs, derived))
    MANIFEST.write_text("".join(out))
    print(f"{len(found)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
