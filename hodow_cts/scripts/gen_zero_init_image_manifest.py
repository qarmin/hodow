#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.memory.zero_initialize_device_memory.image_transition.

`ImageTransitionCase::initPrograms` builds a compute or a fragment shader from the image's channel class, its storage format qualifier, whether it is a
storage image or a sampled one, and the mip extent. One manifest entry per (format, usage, stage, size) combination that the registration loops of
zero_initialize_image_tests.rs reach, keyed "<format>_<usage>_<stage>_<w>x<h>" there. The depth cases share the "depth" entry.

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

MANIFEST = Path(__file__).resolve().parent.parent / "shaders" / "manifest" / "memory_zero_initialize_image.toml"

HEADER = """# Shader manifest for dEQP-VK.memory.zero_initialize_device_memory.image_transition
#
# @generated by hodow_cts/scripts/gen_zero_init_image_manifest.py - do not hand-edit.
#
# One entry per (format, usage, stage, size) combination, plus "depth" for the depth/stencil cases; see the generator for the key scheme.

upstream_source = "external/vulkancts/modules/vulkan/memory/vktMemoryZeroInitializeDeviceMemoryTests.cpp"
rust_module = "memory/zero_initialize_image_tests"
"""

# (simple name, channel class, used channels, storage qualifier or None, compressed)
FORMATS = [
    ("r8_unorm", "float", 1, "r8", False),
    ("r8g8_unorm", "float", 2, "rg8", False),
    ("r16_unorm", "float", 1, "r16", False),
    ("r8g8b8_unorm", "float", 3, "rgb8", False),
    ("r8g8b8a8_unorm", "float", 4, "rgba8", False),
    ("r32_uint", "uint", 1, "r32ui", False),
    ("r32_sint", "int", 1, "r32i", False),
    ("r32_sfloat", "float", 1, "r32f", False),
    ("r32g32b32a32_sfloat", "float", 4, "rgba32f", False),
    ("bc1_rgba_unorm_block", "float", 4, "rgba8", True),
]
USAGES = ["transfer_src", "sampled", "storage"]
STAGES = ["xfer", "comp", "frag"]
SIZES = [(1, 1), (4, 4), (53, 92), (512, 512)]
DEPTH_FORMATS = ["d16_unorm", "x8_d24_unorm_pack32", "d32_sfloat", "s8_uint", "d16_unorm_s8_uint", "d24_unorm_s8_uint", "d32_sfloat_s8_uint"]


def shader_keys():
    """(key, format, usage, stage, w, h) for every case that has a shader."""
    out = []
    for fmt in FORMATS:
        for usage in USAGES:
            if not fmt[4] and fmt[2] == 3 and usage == "storage":
                continue
            for stage in STAGES:
                is_transfer = usage == "transfer_src"
                if is_transfer != (stage == "xfer"):
                    continue
                if is_transfer:
                    continue
                for w, h in SIZES:
                    out.append((f"{fmt[0]}_{usage}_{stage}_{w}x{h}", fmt, usage, stage, w, h))
    return out


def case_names():
    names = []
    for fmt in FORMATS:
        for usage in USAGES:
            if not fmt[4] and fmt[2] == 3 and usage == "storage":
                continue
            for stage in STAGES:
                is_transfer = usage == "transfer_src"
                if is_transfer != (stage == "xfer"):
                    continue
                if is_transfer and fmt[4]:
                    continue
                for w, h in SIZES:
                    for first in (True, False):
                        names.append(f"{fmt[0]}_{usage}_shader_{stage}_{w}x{h}_{'first_mip' if first else 'second_mip'}")
    for dfmt in DEPTH_FORMATS:
        for w, h in SIZES:
            for first in (True, False):
                names.append(f"{dfmt}_{w}x{h}_{'first_mip' if first else 'second_mip'}")
    return names


def toml_str(python_literal):
    escaped = python_literal.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def entry(key, fmt, usage, stage, w, h):
    _, klass, _, qualifier, _ = fmt
    is_storage = usage == "storage"
    prefix = {"int": "i", "uint": "u", "float": ""}[klass]
    pixel = {"int": "ivec4", "uint": "uvec4", "float": "vec4"}[klass]
    resource = "image2D" if is_storage else "sampler2D"
    suffix = f", {qualifier}" if is_storage else ""
    descriptors = (
        f"layout (set=0, binding=0{suffix}) uniform {prefix}{resource} res;\n"
        f"layout (set=0, binding=1) buffer OutBlock {{ {pixel} pixels[]; }} ssbo;\n"
    )
    derived = {
        "descriptors": descriptors,
        "width": str(w),
        "height": str(h),
        "pixel_type": pixel,
        "read_op": "imageLoad" if is_storage else "texelFetch",
        "lod_arg": "" if is_storage else ", 0",
    }
    programs = []
    if stage == "comp":
        programs.append(("comp", "memory/zero_initialize_image/comp.comp", "comp"))
    else:
        programs.append(("vert", "memory/zero_initialize_image/vert.vert", "vert"))
        programs.append(("frag", "memory/zero_initialize_image/frag.frag", "frag"))
    lines = ["", "[[case]]", f'name = "{key}"', f'rust_const = "ZII_{key.upper()}"', 'rust_type = "SharedProgram"', "programs = ["]
    for pname, template, pstage in programs:
        lines.append(f'    {{ name = "{pname}", template = "{template}", stage = "{pstage}" }},')
    lines.append("]")
    items = ", ".join(f"{k} = {toml_str(repr(v))}" for k, v in derived.items())
    lines.append(f"derived = {{ {items} }}")
    return "\n".join(lines)


def depth_entry():
    return "\n".join(
        [
            "",
            "[[case]]",
            'name = "depth"',
            'rust_const = "ZII_DEPTH"',
            'rust_type = "SharedProgram"',
            "programs = [",
            '    { name = "vert", template = "memory/zero_initialize_image/vert.vert", stage = "vert" },',
            '    { name = "frag", template = "memory/zero_initialize_image/depth_frag.frag", stage = "frag" },',
            "]",
            "derived = {}",
        ]
    )


def main():
    out = [HEADER]
    keys = shader_keys()
    for k in keys:
        out.append(entry(*k))
    out.append(depth_entry())
    MANIFEST.write_text("\n".join(out) + "\n")
    print(f"wrote {MANIFEST} with {len(keys) + 1} entries, {len(case_names())} cases")


if __name__ == "__main__":
    main()
