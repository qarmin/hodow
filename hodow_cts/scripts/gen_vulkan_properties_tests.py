#!/usr/bin/env python3
"""Generate src/vkt/tests/api/vulkan_properties_tests.rs, the `properties` case of dEQP-VK.api.info.vulkan1p{2,3,4}.

The member lists are read out of upstream's own `QueryMemberTableEntry` tables in vktApiFeatureInfo.cpp
(`devicePropertiesVulkan12/13/14`), and each C++ member name is matched to the field vulkanalia gives the same member, so the
Rust never states a field name this script has not found in the structure.

Usage:
    python3 hodow_cts/scripts/gen_vulkan_properties_tests.py
"""

from __future__ import annotations

import glob
import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
UPSTREAM = CRATE_DIR / "upstream/external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp"
OUT = CRATE_DIR / "src/vkt/tests/api/vulkan_properties_tests.rs"

TABLES = {
    "VkPhysicalDeviceVulkan11Properties": "properties11OffsetTable",
    "VkPhysicalDeviceVulkan12Properties": "properties12OffsetTable",
    "VkPhysicalDeviceVulkan13Properties": "properties13OffsetTable",
    "VkPhysicalDeviceVulkan14Properties": "properties14OffsetTable",
}


def vulkanalia_structs() -> str:
    paths = glob.glob(str(Path.home() / ".cargo/registry/src/*/vulkanalia-sys-0.35.0/src/structs.rs"))
    if not paths:
        sys.exit("vulkanalia-sys 0.35.0 is not in the cargo registry")
    return Path(paths[0]).read_text()


def rust_fields(structs: str, c_name: str) -> list[str]:
    rust_name = c_name.removeprefix("Vk")
    match = re.search(rf"pub struct {rust_name} \{{(.*?)\n\}}", structs, re.S)
    if not match:
        sys.exit(f"{rust_name} not found in vulkanalia-sys")
    return re.findall(r"pub (\w+):", match.group(1))


def normalise(name: str) -> str:
    return name.replace("_", "").lower()


def members(cpp: str, table: str, c_name: str) -> list[str]:
    start = cpp.index(f"const QueryMemberTableEntry {table}[]")
    end = cpp.index("{0, 0}};", start)
    return re.findall(rf"OFFSET_TABLE_ENTRY\(\s*{c_name},\s*(\w+)\)", cpp[start:end])


# Pointer members upstream sets to null before the query. Upstream then allocates the arrays the reported counts ask for and queries
# again; here the query stays a count-only one and the arrays are not compared.
NULL_POINTERS = {"Vulkan14": ["pCopySrcLayouts", "pCopyDstLayouts"]}


def main() -> int:
    cpp = UPSTREAM.read_text()
    structs = vulkanalia_structs()
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp (`devicePropertiesVulkan12`, `devicePropertiesVulkan13`,",
        "//   `devicePropertiesVulkan14`)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2015 The Khronos Group Inc.",
        "// Copyright (c) 2015 Intel Corporation",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_vulkan_properties_tests.py from upstream's member tables; do not hand-edit.",
        "//",
        "// The `properties` case of the `vulkan1p2`, `vulkan1p3` and `vulkan1p4` groups: each core properties structure is queried into",
        "// zeroed and into 0xFF-filled memory followed by a guard, and every member has to come back identical with the guard intact.",
        "",
        "use std::ffi::c_void;",
        "use std::mem::{offset_of, size_of};",
        "",
        "use vulkanalia::prelude::v1_0::*;",
        "use vulkanalia::vk::InstanceV1_1;",
        "",
        "use crate::tcu::{TestError, TestOutcome, TestStatus};",
        "use crate::vkt::Context;",
        "",
        "const GUARD_SIZE: usize = 0x20;",
        "const GUARD_VALUE: u8 = 0xcd;",
        "",
        "/// One `OFFSET_TABLE_ENTRY`: where a member lives in its structure and how large it is.",
        "type Member = (&'static str, usize, usize);",
        "",
        "macro_rules! member {",
        "    ($ty:ty, $field:ident) => {{",
        "        fn size_of_field<T, F>(_: fn(&T) -> &F) -> usize {",
        "            size_of::<F>()",
        "        }",
        "        (stringify!($field), offset_of!($ty, $field), size_of_field(|s: &$ty| &s.$field))",
        "    }};",
        "}",
        "",
    ]
    consts = []
    for c_name, table in TABLES.items():
        rust_name = c_name.removeprefix("Vk")
        by_norm = {normalise(f): f for f in rust_fields(structs, c_name)}
        entries = []
        for cpp_member in members(cpp, table, c_name):
            field = by_norm.get(normalise(cpp_member))
            if field is None:
                sys.exit(f"{c_name}.{cpp_member} has no counterpart in vulkanalia")
            entries.append(f"    member!(vk::{rust_name}, {field}),")
        const = f"{rust_name.upper()}_MEMBERS".replace("PHYSICALDEVICE", "PHYSICAL_DEVICE_")
        consts.append((rust_name, const))
        out += [f"fn {const.lower()}() -> Vec<Member> {{", "    vec![", *entries, "    ]", "}", ""]

    out += [
        "/// The members of `vk::PhysicalDeviceVulkan1xProperties` structures `structs` (sType, size, members) chained behind a",
        "/// `VkPhysicalDeviceProperties2`, each pre-filled with `fill` and followed by `GUARD_SIZE` bytes of `GUARD_VALUE`.",
        "fn query_chain(context: &Context<'_>, structs: &[(i32, usize, Vec<usize>)], fill: u8) -> Vec<Vec<u64>> {",
        "    let mut buffers: Vec<Vec<u64>> = structs.iter().map(|(_, size, _)| vec![0u64; (size + GUARD_SIZE).div_ceil(8)]).collect();",
        "    let base_pointers: Vec<*mut u8> = buffers.iter_mut().map(|b| b.as_mut_ptr().cast::<u8>()).collect();",
        "",
        "    for (ndx, (s_type, size, null_pointers)) in structs.iter().enumerate() {",
        "        let (s_type, size) = (*s_type, *size);",
        "        let pointer = base_pointers[ndx];",
        "        let next: *mut c_void = base_pointers.get(ndx + 1).map_or(std::ptr::null_mut(), |p| p.cast::<c_void>());",
        "        unsafe {",
        "            std::ptr::write_bytes(pointer.add(size), GUARD_VALUE, GUARD_SIZE);",
        "            std::ptr::write_bytes(pointer, fill, size);",
        "            pointer.cast::<i32>().write(s_type);",
        "            pointer.add(8).cast::<*mut c_void>().write(next);",
        "            for &offset in null_pointers {",
        "                pointer.add(offset).cast::<*mut c_void>().write(std::ptr::null_mut());",
        "            }",
        "        }",
        "    }",
        "",
        "    let mut properties2 = vk::PhysicalDeviceProperties2 { next: base_pointers[0].cast::<c_void>(), ..Default::default() };",
        "    unsafe { context.get_instance().get_physical_device_properties2(context.get_physical_device(), &mut properties2) };",
        "    buffers",
        "}",
        "",
        "/// `validateStructsWithGuard` for one structure queried twice.",
        "fn validate_struct(first: &[u64], second: &[u64], size: usize, members: &[Member]) -> bool {",
        "    let bytes = |buffer: &[u64]| unsafe { std::slice::from_raw_parts(buffer.as_ptr().cast::<u8>(), buffer.len() * 8) }.to_vec();",
        "    let (a, b) = (bytes(first), bytes(second));",
        "    for &(name, offset, member_size) in members {",
        "        if a[offset..offset + member_size] != b[offset..offset + member_size] {",
        "            log::info!(\"member {name} differs between the two queries\");",
        "            return false;",
        "        }",
        "    }",
        "    a[size..size + GUARD_SIZE].iter().chain(&b[size..size + GUARD_SIZE]).all(|&byte| byte == GUARD_VALUE)",
        "}",
        "",
        "type Described = (&'static str, i32, usize, Vec<Member>, Vec<usize>);",
        "",
        "fn device_properties_vulkan(context: &Context<'_>, version: (u32, u32), structs: &[Described]) -> TestOutcome {",
        "    let (major, minor, _) = context.api_version();",
        "    if (major, minor) < version {",
        "        return Err(TestError::NotSupported(format!(\"At least Vulkan {}.{} required to run test\", version.0, version.1)));",
        "    }",
        "",
        "    let layout: Vec<(i32, usize, Vec<usize>)> = structs.iter().map(|(_, s_type, size, _, nulls)| (*s_type, *size, nulls.clone())).collect();",
        "    let first = query_chain(context, &layout, 0x00);",
        "    let second = query_chain(context, &layout, 0xFF);",
        "",
        "    for (ndx, (name, _, size, members, _)) in structs.iter().enumerate() {",
        "        if !validate_struct(&first[ndx], &second[ndx], *size, members) {",
        "            log::info!(\"deviceProperties - {name} initialization failure\");",
        "            return Ok(TestStatus::fail(format!(\"{name} initialization failure\")));",
        "        }",
        "    }",
        "",
        "    Ok(TestStatus::pass(format!(\"Querying Vulkan {}.{} device properties succeeded\", version.0, version.1)))",
        "}",
        "",
    ]
    stypes = {"Vulkan11": 50, "Vulkan12": 52, "Vulkan13": 54, "Vulkan14": 56}
    funcs = {"12": ["Vulkan11", "Vulkan12"], "13": ["Vulkan13"], "14": ["Vulkan14"]}
    structs_src = structs
    const_by = {rust.removeprefix("PhysicalDevice").removesuffix("Properties"): const for rust, const in consts}
    for ver, names in funcs.items():
        entries = []
        for name in names:
            struct = f"vk::PhysicalDevice{name}Properties"
            const = const_by[name].lower()
            nulls = []
            for pointer in NULL_POINTERS.get(name, []):
                fields = {normalise(f): f for f in rust_fields(structs_src, f"VkPhysicalDevice{name}Properties")}
                field = fields.get(normalise(pointer)) or fields.get(normalise(pointer[1:]))
                if field is None:
                    sys.exit(f"{name}.{pointer} has no counterpart in vulkanalia")
                nulls.append(f"offset_of!({struct}, {field})")
            entries.append(f'            ("VkPhysicalDevice{name}Properties", {stypes[name]}, size_of::<{struct}>(), {const}(), vec![{", ".join(nulls)}]),')
        out += [
            f"pub fn device_properties_vulkan{ver}(context: &Context<'_>) -> TestOutcome {{",
            f"    device_properties_vulkan(context, (1, {ver[1]}), &[",
            *[e.removeprefix("    ") for e in entries],
            "    ])",
            "}",
            "",
        ]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(CRATE_DIR.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
