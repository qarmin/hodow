#!/usr/bin/env python3
"""Generate the shaders of dEQP-VK.glsl.limits.near_max.fragment_input.components_* and their manifest.

`FragmentInputComponentCase::initPrograms` writes one vertex and one fragment shader per component count, passing
`ceil((n - 4) / 4)` varyings whose value is their own location and checking each in the fragment shader.

Usage:
    python3 hodow_cts/scripts/gen_glsl_limits_shaders.py
"""

from __future__ import annotations

import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = CRATE_DIR.parent
SRC_REL = "glsl/limits"
SRC_DIR = CRATE_DIR / "shaders" / "src" / SRC_REL
MANIFEST = CRATE_DIR / "shaders" / "manifest" / "glsl_limits.toml"

FRAGMENT_COMPONENT_MAX_LIMITS = (64, 128, 256)
CASES_PER_LIMIT = 5


def component_counts() -> list[int]:
    return [limit - cases for limit in FRAGMENT_COMPONENT_MAX_LIMITS for cases in range(CASES_PER_LIMIT, 0, -1)]


def shaders(input_components: int) -> tuple[str, str]:
    max_locations = -(-(input_components - 4) // 4)
    varying_out = ""
    varying_decl = ""
    varying_in = ""
    verify = ""
    for loc in range(max_locations):
        if loc == max_locations - 1:
            varying_type = {1: "float", 2: "vec2", 3: "vec3"}.get(input_components - loc * 4, "vec4")
        else:
            varying_type = "vec4"
        varying_out += f"layout(location = {loc}) out highp {varying_type} o_color{loc};\n"
        varying_decl += f"    o_color{loc} = {varying_type}({loc}.0);\n"
        varying_in += f"layout(location = {loc}) in highp {varying_type} i_color{loc};\n"
        verify += f"    errorCount += (i_color{loc} == {varying_type}({loc}.0)) ? 0 : 1;\n"

    vertex = (
        "#version 450\n"
        "layout(location = 0) in highp vec4 a_position;\n"
        + varying_out
        + "void main (void)\n"
        "{\n"
        "    gl_Position = a_position;\n"
        + varying_decl
        + "}\n"
    )
    fragment = (
        "#version 450\n"
        "layout(location = 0) out highp vec4 o_color;\n"
        + varying_in
        + "void main (void)\n"
        "{\n"
        "    int errorCount = 0;\n"
        + verify
        + "\n"
        "    if (errorCount == 0)\n"
        "        o_color = vec4(0.0, 1.0, 0.0, 1.0);\n"
        "    else\n"
        "        o_color = vec4(1.0, 0.0, 0.0, 1.0);\n"
        "}\n"
    )
    return vertex, fragment


def main() -> int:
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    for stale in SRC_DIR.glob("*"):
        stale.unlink()

    programs = []
    for count in component_counts():
        vertex, fragment = shaders(count)
        for name, stage, source in ((f"vert_{count}", "vert", vertex), (f"frag_{count}", "frag", fragment)):
            (SRC_DIR / f"{name}.{stage}").write_text(source)
            programs.append((name, f"{SRC_REL}/{name}.{stage}", stage))

    lines = [
        "# Shader manifest for dEQP-VK.glsl.limits.*",
        "#",
        "# Generated by scripts/gen_glsl_limits_shaders.py together with the sources it names; do not hand-edit either.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/shaderrender/vktShaderRenderLimitTests.cpp"',
        'rust_module = "glsl/limit_tests"',
        "",
        "[[case]]",
        'name = "limits"',
        'rust_const = "GLSL_LIMITS"',
        'rust_type = "SharedProgram"',
        "programs = [",
    ]
    for name, template, stage in programs:
        lines.append(f'    {{ name = "{name}", template = "{template}", stage = "{stage}" }},')
    lines += ["]", ""]
    MANIFEST.write_text("\n".join(lines))
    print(f"wrote {MANIFEST.relative_to(REPO_DIR)} and {len(programs)} shaders in {SRC_DIR.relative_to(REPO_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
