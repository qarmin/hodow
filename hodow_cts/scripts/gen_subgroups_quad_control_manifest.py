#!/usr/bin/env python3
"""Writes shaders/manifest/subgroups_quad_control.toml: dEQP-VK.subgroups.shader_quad_control.* (vktSubgroupsQuadControlTests.cpp, `initPrograms`; the GLSL is in shaders/src/subgroups_quad_control).

    python3 hodow_cts/scripts/gen_subgroups_quad_control_manifest.py

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "subgroups_quad_control.toml"
SOURCE = "external/vulkancts/modules/vulkan/subgroups/vktSubgroupsQuadControlTests.cpp"
DIR = "subgroups_quad_control"

CASES = [
    ("quad_derivatives", [("frag", "quad_derivatives.frag")]),
    ("require_full_quads", [("frag", "require_full_quads.frag")]),
    ("divergent_condition", [("frag", "divergent_condition.frag")]),
    # `frag_ucf` is the variant with GL_EXT_subgroup_uniform_control_flow, `frag` the one with GL_EXT_maximal_reconvergence
    ("terminated_invocation", [("frag_ucf", "terminated_invocation_ucf.frag"), ("frag", "terminated_invocation.frag")]),
]


def main():
    out = [
        "# Shader manifest for dEQP-VK.subgroups.shader_quad_control.*\n#\n"
        "# @generated by hodow_cts/scripts/gen_subgroups_quad_control_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "subgroups/quad_control_tests"\n'
    ]
    for name, frags in CASES:
        programs = [f'    {{ name = "vert", template = "{DIR}/quad_control.vert", stage = "vert", spirv_version = "spirv1.3" }},\n']
        for program, template in frags:
            programs.append(f'    {{ name = "{program}", template = "{DIR}/{template}", stage = "frag", spirv_version = "spirv1.3" }},\n')
        out.append(
            f'\n[[case]]\nname = "{name}"\nrust_const = "QUAD_CONTROL_{name.upper()}"\nrust_type = "QuadControlCase"\n'
            "programs = [\n" + "".join(programs) + "]\n"
        )
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {len(CASES)} cases")


if __name__ == "__main__":
    main()
