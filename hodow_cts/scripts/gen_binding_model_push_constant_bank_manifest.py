#!/usr/bin/env python3
"""Writes shaders/manifest/binding_model_push_constant_bank.toml and its GLSL templates: dEQP-VK.binding_model.push_constant_bank.basic.* (vktBindingPushConstantBankTests.cpp, `initPrograms`).

    python3 hodow_cts/scripts/gen_binding_model_push_constant_bank_manifest.py

A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "binding_model_push_constant_bank.toml"
SRC_DIR = CRATE / "shaders" / "src" / "binding_model_push_constant_bank"
SOURCE = "external/vulkancts/modules/vulkan/binding_model/vktBindingPushConstantBankTests.cpp"
MAX_TEST_BANKS = 8

# (case name, stage, member_offset or None)
CASES = [
    ("compute", "comp", None),
    ("compute_offset_4", "comp", 4),
    ("compute_offset_16", "comp", 16),
    ("vertex", "vert", None),
    ("vertex_offset_4", "vert", 4),
    ("vertex_offset_16", "vert", 16),
]


def shader(stage, member_offset):
    src = "#version 460\n#extension GL_NV_push_constant_bank : require\n\n"
    if stage == "comp":
        src += "layout(local_size_x = 1) in;\n\n"
    src += f"layout(std430, binding = 0) writeonly buffer ResultData {{\n    uint bank[{MAX_TEST_BANKS}];\n}} resultData;\n\n"
    for bank in range(MAX_TEST_BANKS):
        offset = f", member_offset = {member_offset}" if member_offset is not None else ""
        src += f"layout(push_constant, bank = {bank}{offset}) uniform PushConstantBank{bank} {{\n    uint data;\n}} bank{bank};\n\n"
    src += "void main() {\n"
    for bank in range(MAX_TEST_BANKS):
        src += f"    resultData.bank[{bank}] = bank{bank}.data;\n"
    if stage == "vert":
        src += "    gl_Position = vec4(0, 0, 0, 1);\n"
    src += "}\n"
    return src


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.binding_model.push_constant_bank.basic.*\n#\n"
        "# @generated by hodow_cts/scripts/gen_binding_model_push_constant_bank_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "binding_model/push_constant_bank_tests"\n'
    ]
    for name, stage, member_offset in CASES:
        template = f"{name}.{stage}"
        (SRC_DIR / template).write_text(shader(stage, member_offset), encoding="utf-8")
        out.append(
            f'\n[[case]]\nname = "{name}"\nrust_const = "PUSH_CONSTANT_BANK_{name.upper()}"\nrust_type = "PushConstantBankShader"\n'
            f'programs = [\n    {{ name = "main", template = "binding_model_push_constant_bank/{template}", stage = "{stage}" }},\n]\n'
        )
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {len(CASES)} shaders")


if __name__ == "__main__":
    main()
