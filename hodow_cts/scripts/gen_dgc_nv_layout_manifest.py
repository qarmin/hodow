#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.nv.compute.layout (`LayoutTestCase::initPrograms` of vktDGCComputeLayoutTests.cpp): one
shared program per kind of constants (push constants only, with a complementary push constant, specialization constants only and the mixed
forms). A pure text generator: no glslang, no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_nv_layout.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

LOCAL_INVOCATIONS = 64


def shader(kind):
    complementary_push = kind == "complementary"
    complementary_push_with_pipeline = kind == "pipeline_complementary"
    if kind in ("push", "complementary"):
        constants = (
            "layout (push_constant, std430) uniform PushConstantBlock {\n"
            "    uint dispatchOffset;\n"
            "    uint skipIndex;\n"
            "    uint valueOffset;\n"
            + ("    uint valueOffset2;\n" if complementary_push else "")
            + "} pc;\n"
        )
        dispatch_offset_prefix = skip_index_prefix = value_offset_prefix = value_offset2_prefix = "pc."
    elif kind == "spec":
        constants = (
            "layout (constant_id=0) const uint pc_dispatchOffset = 0u;\n"
            "layout (constant_id=1) const uint pc_skipIndex = 0u;\n"
            "layout (constant_id=2) const uint pc_valueOffset = 0u;\n"
        )
        dispatch_offset_prefix = skip_index_prefix = value_offset_prefix = "pc_"
        value_offset2_prefix = ""
    else:
        constants = (
            "layout (push_constant, std430) uniform PushConstantBlock {\n"
            + ("    uint valueOffset2;\n" if complementary_push_with_pipeline else "")
            + "    uint dispatchOffset;\n"
            "    uint skipIndex;\n"
            "} pc;\n"
            "layout (constant_id=2) const uint pc_valueOffset = 0u;\n"
        )
        dispatch_offset_prefix = skip_index_prefix = value_offset2_prefix = "pc."
        value_offset_prefix = "pc_"

    comp = (
        "#version 460\n"
        f"layout (local_size_x={LOCAL_INVOCATIONS}, local_size_y=1, local_size_z=1) in;\n"
        "layout (set=0, binding=0, std430) buffer StorageBlock { uint values[]; } storageBuffer;\n"
        + constants
        + "void main (void) {\n"
        "    const uint workGroupIndex = gl_NumWorkGroups.x * gl_NumWorkGroups.y * gl_WorkGroupID.z + gl_NumWorkGroups.x * gl_WorkGroupID.y + gl_WorkGroupID.x;\n"
        f"    const uint valueIndex = {dispatch_offset_prefix}dispatchOffset + workGroupIndex * gl_WorkGroupSize.x + gl_LocalInvocationIndex;\n"
        f"    const uint storageValue = {value_offset_prefix}valueOffset + (workGroupIndex << 10) + gl_LocalInvocationIndex\n"
    )
    if complementary_push or complementary_push_with_pipeline:
        comp += f"        + {value_offset2_prefix}valueOffset2\n"
    comp += (
        "        ;\n"
        f"    if ({skip_index_prefix}skipIndex != gl_LocalInvocationIndex) {{\n"
        "        storageBuffer.values[valueIndex] = storageValue;\n"
        "    }\n"
        "}\n"
    )
    return comp


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    manifest = (
        "# Shader manifest for dEQP-VK.dgc.nv.compute.layout\n"
        "#\n"
        "# @generated by hodow_cts/scripts/gen_dgc_nv_layout_manifest.py - do not hand-edit.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCComputeLayoutTests.cpp"\n'
        'rust_module = "dgc/nv_compute_layout_tests"\n'
    )
    for kind in ("push", "complementary", "spec", "pipeline_push", "pipeline_complementary"):
        file = f"nv_layout_{kind}.comp"
        (SRC_DIR / file).write_text(shader(kind))
        name = f"nv_layout_{kind}"
        manifest += (
            f'\n[[case]]\nname = "{name}"\nrust_const = "{name.upper()}"\nrust_type = "SharedProgram"\n'
            f'programs = [ {{ name = "comp", template = "dgc/{file}", stage = "comp" }} ]\n'
        )
    MANIFEST.write_text(manifest)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
