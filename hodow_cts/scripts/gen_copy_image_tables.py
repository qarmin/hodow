#!/usr/bin/env python3
"""Generates hodow_cts/src/khr_gl/copy_image/tables.rs from gl4cCopyImageTests.cpp: the per-format switch statements of `CopyImage::Utils` and the target/format arrays.

Usage: python3 hodow_cts/scripts/gen_copy_image_tables.py <gl4cCopyImageTests.cpp> <out.rs>
"""
import re
import sys

src = open(sys.argv[1]).read()
out_path = sys.argv[2]


def rust_const(token):
    token = token.strip()
    if token.startswith("GL_"):
        return "glw::" + token
    return token


def function_body(signature_regex):
    m = re.search(signature_regex, src)
    if not m:
        raise SystemExit("function not found: " + signature_regex)
    start = src.index("{", m.end())
    depth = 0
    for i in range(start, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return src[start + 1 : i]
    raise SystemExit("unbalanced")


def switch_arms(body, variable):
    """Returns [(labels, value)] for `case A: case B: variable = V; break;` groups."""
    arms = []
    labels = []
    for line in body.splitlines():
        line = line.split("/*")[0].strip() if line.strip().startswith("/*") else re.sub(r"/\*.*?\*/", "", line).strip()
        m = re.match(r"case (\w+):", line)
        if m:
            labels.append(m.group(1))
            continue
        m = re.match(re.escape(variable) + r"\s*=\s*([^;]+);", line)
        if m and labels:
            arms.append((labels, m.group(1).strip()))
            labels = []
    return arms


def render_fn(name, arg, ret, body_regex, variable, value_kind):
    body = function_body(body_regex)
    arms = switch_arms(body, variable)
    lines = [f"pub(super) fn {name}({arg}: GLenum) -> {ret} {{", f"    match {arg} {{"]
    for labels, value in arms:
        pat = " | ".join(rust_const(l) for l in labels)
        lines.append(f"        {pat} => {rust_const(value)},")
    lines.append('        _ => panic!("Invalid enum"),')
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines)


def array(name):
    m = re.search(r"static const GLenum " + name + r"\[\] = \{(.*?)\};", src, re.S)
    items = [re.sub(r"/\*.*?\*/", "", x).strip() for x in m.group(1).split(",")]
    items = [x for x in items if x]
    return items


parts = ["// SPDX-License-Identifier: Apache-2.0", "//", "// Derived from VK-GL-CTS:", "//   external/openglcts/modules/gl/gl4cCopyImageTests.cpp", "// Upstream revision: see hodow_cts/upstream/COMMIT", "//", "// Copyright (c) 2014-2016 The Khronos Group Inc.", "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).", "//", "// Modifications: GENERATED by hodow_cts/scripts/gen_copy_image_tables.py from the upstream switch statements of `CopyImage::Utils`. Do not edit by hand.", "", "use crate::glw::{self, GLenum};", ""]

for name, items in (("INTERNAL_FORMATS", array("s_internal_formats")), ("INVALID_TARGETS", array("s_invalid_targets")), ("VALID_TARGETS", array("s_valid_targets"))):
    parts.append(f"pub(super) const {name}: [GLenum; {len(items)}] = [")
    for it in items:
        parts.append(f"    {rust_const(it)},")
    parts.append("];")
    parts.append("")

parts.append("/// `Utils::getEpsilon`")
parts.append(render_fn("get_epsilon", "internal_format", "f64", r"GLdouble Utils::getEpsilon\(GLenum internal_format\)", "epsilon", "f"))
parts.append("")
parts.append("/// `Utils::getFormat`")
parts.append(render_fn("get_format", "internal_format", "GLenum", r"GLenum Utils::getFormat\(GLenum internal_format\)", "format", "e"))
parts.append("")
parts.append("/// `Utils::getNumberOfChannels`")
parts.append(render_fn("get_number_of_channels", "internal_format", "u32", r"GLuint Utils::getNumberOfChannels\(GLenum internal_format\)", "result", "n"))
parts.append("")
parts.append("/// `Utils::getType`")
parts.append(render_fn("get_type", "internal_format", "GLenum", r"GLenum Utils::getType\(GLenum internal_format\)", "type", "e"))
parts.append("")
parts.append("/// `Utils::getPixelSizeForFormat`")
parts.append(render_fn("get_pixel_size_for_format", "internal_format", "u32", r"GLuint Utils::getPixelSizeForFormat\(GLenum internal_format\)", "size", "n"))
parts.append("")

body = function_body(r"bool filterFormats\(GLenum format\)")
arms = switch_arms(body, "result")
excluded = [l for labels, value in arms if value == "false" for l in labels]
parts.append("/// `filterFormats` (the `COPY_IMAGE_FUNCTIONAL_TEST_ENABLE_ALL_FORMATS == 0` variant)")
parts.append("pub(super) fn filter_formats(format: GLenum) -> bool {")
parts.append("    !matches!(")
parts.append("        format,")
parts.append("        " + " | ".join(rust_const(l) for l in excluded))
parts.append("    )")
parts.append("}")
parts.append("")

parts.append("/// `getTextureFormatString` for the formats `INTERNAL_FORMATS` lists")
parts.append("pub(super) fn texture_format_string(format: GLenum) -> &'static str {")
parts.append("    match format {")
for it in array("s_internal_formats"):
    parts.append(f'        {rust_const(it)} => "{it[3:].lower()}",')
parts.append('        _ => "null",')
parts.append("    }")
parts.append("}")
parts.append("")

open(out_path, "w").write("\n".join(parts))
