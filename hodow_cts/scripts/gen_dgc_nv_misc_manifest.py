#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.nv.compute.misc (`manyExecutesInitPrograms` and `fullReplayInitPrograms` of
vktDGCComputeMiscTests.cpp). A pure text generator: no glslang, no cargo."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_nv_misc.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"


def increase(local_size):
    return (
        "#version 460\n"
        f"layout (local_size_x={local_size}, local_size_y=1, local_size_z=1) in;\n"
        "layout (set=0, binding=0, std430) buffer OutputBlock { uint values[]; } outputBuffer;\n"
        "layout (push_constant, std430) uniform PushConstantBlock { uint valueIndex; } pc;\n"
        "void main (void) { atomicAdd(outputBuffer.values[pc.valueIndex], 1u); }\n"
    )


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    manifest = (
        "# Shader manifest for dEQP-VK.dgc.nv.compute.misc\n"
        "#\n"
        "# @generated by hodow_cts/scripts/gen_dgc_nv_misc_manifest.py - do not hand-edit.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCComputeMiscTests.cpp"\n'
        'rust_module = "dgc/nv_compute_misc_tests"\n'
    )
    for name, size in (("nv_misc_many", 64), ("nv_misc_replay", 1)):
        file = f"{name}.comp"
        (SRC_DIR / file).write_text(increase(size))
        manifest += (
            f'\n[[case]]\nname = "{name}"\nrust_const = "{name.upper()}"\nrust_type = "SharedProgram"\n'
            f'programs = [ {{ name = "comp", template = "dgc/{file}", stage = "comp" }} ]\n'
        )
    MANIFEST.write_text(manifest)
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
