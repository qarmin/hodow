#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.compute.pipeline.basic.{float16,float64}_isnan_isinf from the vendored Amber scripts.

Each script has one GLSL compute shader (`kShader`) that stores `isnan(x) + isinf(x)` of a float16_t or float64_t made from the first buffer into the second; the
Rust side runs it over a NaN, an infinity and a zero. Written: shaders/manifest/compute_isnan_isinf.toml and shaders/src/compute_isnan_isinf/.

Run from hodow_cts/:  python3 scripts/gen_compute_isnan_isinf_amber.py   (then `just cts-shaders`)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/compute"
SRC = ROOT / "shaders" / "src" / "compute_isnan_isinf"
MANIFEST = ROOT / "shaders" / "manifest" / "compute_isnan_isinf.toml"


def shader(text):
    lines = text.splitlines()
    for ndx, line in enumerate(lines):
        if line.startswith("SHADER compute kShader GLSL"):
            body = []
            for rest in lines[ndx + 1 :]:
                if rest.strip() == "END":
                    return "\n".join(body) + "\n"
                body.append(rest)
    raise RuntimeError("no shader")


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.compute.pipeline.basic.{float16,float64}_isnan_isinf.",
        "#",
        "# @generated by hodow_cts/scripts/gen_compute_isnan_isinf_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/compute/float16_isnan_isinf.amber"',
        'rust_module = "compute/isnan_isinf_tests"',
        "",
    ]
    for name in ("float16_isnan_isinf", "float64_isnan_isinf"):
        (SRC / f"{name}.comp").write_text(shader((AMBER / f"{name}.amber").read_text()))
        out += ["[[case]]", f'name = "{name}"', f'rust_const = "{name.upper()}"', 'rust_type = "SharedProgram"', "programs = [",
                f'    {{ name = "comp", template = "compute_isnan_isinf/{name}.comp", stage = "comp" }},', "]", ""]
    MANIFEST.write_text("\n".join(out))


if __name__ == "__main__":
    main()
