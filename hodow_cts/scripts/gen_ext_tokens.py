"""Generates `src/generated/ext_tokens.rs` from the Khronos GL CTS's `glcExtTokens.cpp`: `deqp::GLExtTokens`, the GL enums whose name differs between a context where a functionality is core and
one where an extension provides it (`GL_GEOMETRY_SHADER` against `GL_GEOMETRY_SHADER_EXT`).

Upstream picks one of two lists in `GLExtTokens::init`: ES 3.2 gets the core names, every other context - the desktop ones included - the extension names. The generated `init` does the same.

Usage:
    python3 hodow_cts/scripts/gen_ext_tokens.py [--cts-dir ../tmp/glcts-src] [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
OUT_PATH = CRATE_DIR / "src" / "generated" / "ext_tokens.rs"
SOURCE = "external/openglcts/modules/common/glcExtTokens.cpp"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cts-dir", default=str(CRATE_DIR.parent / "tmp" / "glcts-src"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    path = Path(args.cts_dir) / SOURCE
    if not path.is_file():
        print(f"error: {path} not found", file=sys.stderr)
        return 1
    text = path.read_text()
    start = text.index("void GLExtTokens::init")
    body = text[start:]
    split = re.search(r"\n    else\n", body)
    if not split:
        print("error: GLExtTokens::init has no else branch", file=sys.stderr)
        return 1
    branches = [body[: split.start()], body[split.end():]]
    assign = re.compile(r"^\s+(\w+)\s*=\s*(GL_\w+);", re.M)
    lists = [assign.findall(b) for b in branches]
    names = [n for n, _ in lists[0]]
    if names != [n for n, _ in lists[1]]:
        # Same members in both branches, but not necessarily in the same order.
        if sorted(names) != sorted(n for n, _ in lists[1]):
            print("error: the two branches assign different members", file=sys.stderr)
            return 1

    def field(name: str) -> str:
        return name.lower()

    out = [
        "// @generated by hodow_cts/scripts/gen_ext_tokens.py - do not hand-edit.",
        "//",
        f"// From VK-GL-CTS `{SOURCE}`.",
        "// Upstream revision: see hodow_cts/upstream/COMMIT.",
        "//",
        "// Copyright (c) 2016 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "",
        "use crate::glu::ContextType;",
        "use crate::glw::{self, GLenum};",
        "",
        "/// `deqp::GLExtTokens`",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct GlExtTokens {",
    ]
    out += [f"    pub {field(n)}: GLenum," for n in names]
    out += ["}", "", "impl GlExtTokens {", "    /// `GLExtTokens::init`: ES 3.2 has the functionality in core, anything else gets the extension's tokens.", "    pub fn init(context_type: ContextType) -> Self {"]
    for index, (condition, assignments) in enumerate([("if context_type.supports(3, 2)", lists[0]), ("", lists[1])]):
        values = dict(assignments)
        out.append(f"        {condition} {{" if condition else "        {")
        out.append("            Self {")
        out += [f"                {field(n)}: glw::{values[n]}," for n in names]
        out.append("            }")
        out.append("        }" + (" else" if index == 0 else ""))
    # Re-join `} else {` form.
    text_out = "\n".join(out)
    text_out = text_out.replace("        } else\n        {", "        } else {")
    text_out += "\n    }\n}\n"

    if args.check:
        if not OUT_PATH.exists() or OUT_PATH.read_text() != text_out:
            print("error: generated ext tokens are stale; re-run gen_ext_tokens.py", file=sys.stderr)
            return 1
        print("generated ext tokens are up to date")
        return 0
    OUT_PATH.write_text(text_out)
    print(f"wrote {OUT_PATH.relative_to(CRATE_DIR)} ({len(names)} tokens)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
