#!/usr/bin/env python3
"""Writes the shader manifest of dEQP-VK.image.texel_view_compatible.* (`TexelViewCompatibleCase::initPrograms` of
vktImageCompressionTranscodingSupport.cpp) and the static templates it uses.

Shader text depends on the uncompressed view format, the image type, the operation and (compute) whether the compressed reference is a 2D
array and whether the multi-layer view is used, so there is one entry per combination, found by `compute_key` / `fragment_key` in
texel_view_compatible_tests.rs. A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "image_texel_view_compatible.toml"
SRC = ROOT / "shaders" / "src" / "image"

HEADER = """# Shader manifest for dEQP-VK.image.texel_view_compatible.*
#
# @generated by hodow_cts/scripts/gen_texel_view_manifest.py - do not hand-edit.
#
# `initPrograms` of vktImageCompressionTranscodingSupport.cpp, one entry per uncompressed view format, image type and operation.

upstream_source = "external/vulkancts/modules/vulkan/image/vktImageCompressionTranscodingSupport.cpp"
rust_module = "image/texel_view_compatible_tests"
"""

# short name -> (class prefix of image/sampler types, image format qualifier, glsl colour type, subpassInput type)
UNCOMPRESSED = {
    "r16g16b16a16_unorm": ("", "rgba16", "vec4", "subpassInput"),
    "r16g16b16a16_snorm": ("", "rgba16_snorm", "vec4", "subpassInput"),
    "r16g16b16a16_uscaled": ("u", "rgba16ui", "vec4", "subpassInput"),
    "r16g16b16a16_sscaled": ("i", "rgba16i", "vec4", "subpassInput"),
    "r16g16b16a16_uint": ("u", "rgba16ui", "uvec4", "usubpassInput"),
    "r16g16b16a16_sint": ("i", "rgba16i", "ivec4", "isubpassInput"),
    "r32g32_uint": ("u", "rg32ui", "uvec2", "usubpassInput"),
    "r32g32_sint": ("i", "rg32i", "ivec2", "isubpassInput"),
    "r32g32b32a32_uint": ("u", "rgba32ui", "uvec4", "usubpassInput"),
    "r32g32b32a32_sint": ("i", "rgba32i", "ivec4", "isubpassInput"),
}
VERIFY = ("", "rgba8", "vec4", "subpassInput")
IMAGE_TYPES = ["1d", "2d", "3d"]
SUFFIX = {"1d": "1D", "2d": "2D", "3d": "3D"}
COMPUTE_OPS = ["image_load", "texel_fetch", "texture", "image_store"]
VERSION = "#version 450\n"
LOCAL = "layout (local_size_x = 1, local_size_y = 1, local_size_z = 1) in;\n\n"


def image_type(fmt, itype, array=False):
    return f"{fmt[0]}image{SUFFIX[itype]}" + ("Array" if array else "")


def sampler_type(fmt, itype, array=False):
    return f"{fmt[0]}sampler{SUFFIX[itype]}" + ("Array" if array else "")


def compute_source(op, fmt, itype, multi):
    idx = IMAGE_TYPES.index(itype)
    img = image_type(fmt, itype, multi)
    smp = sampler_type(fmt, itype, multi)
    qual = fmt[1]
    src = VERSION + "\n" + LOCAL
    if op == "image_load":
        pos = [
            "    highp int pos = int(gl_GlobalInvocationID.x);\n",
            "    ivec3 pos = ivec3(gl_GlobalInvocationID);\n" if multi else "    ivec2 pos = ivec2(gl_GlobalInvocationID.xy);\n",
            "    ivec3 pos = ivec3(gl_GlobalInvocationID);\n",
        ][idx]
        src += (
            f"layout (binding = 0, {qual}) readonly uniform {img} u_image0;\n"
            f"layout (binding = 1, {qual}) writeonly uniform {img} u_image1;\n\n"
            "void main (void)\n{\n" + pos + "    imageStore(u_image1, pos, imageLoad(u_image0, pos));\n}\n"
        )
    elif op == "texel_fetch":
        store = [
            "    imageStore(u_image1, pos.x, texelFetch(u_image0, pos.x, pos.z));\n",
            "    imageStore(u_image1, pos, texelFetch(u_image0, pos, 0));\n" if multi else "    imageStore(u_image1, pos.xy, texelFetch(u_image0, pos.xy, pos.z));\n",
            "    imageStore(u_image1, pos, texelFetch(u_image0, pos, pos.z));\n",
        ][idx]
        src += (
            f"layout (binding = 0) uniform {smp} u_image0;\n"
            f"layout (binding = 1, {qual}) writeonly uniform {img} u_image1;\n\n"
            "void main (void)\n{\n    ivec3 pos = ivec3(gl_GlobalInvocationID.xyz);\n" + store + "}\n"
        )
    elif op == "texture":
        coord = [
            "    const int     pos = int(gl_GlobalInvocationID.x);\n"
            "    const float coord = (float(gl_GlobalInvocationID.x) + 0.5) / pixels_resolution.x;\n",
            (
                "    const ivec3  pos = ivec3(gl_GlobalInvocationID.xyz);\n"
                "    const vec2    v2 = (vec2(gl_GlobalInvocationID.xy) + 0.5) / vec2(pixels_resolution);\n"
                "    const vec3 coord = vec3(v2, pos.z);\n"
                if multi
                else "    const ivec2  pos = ivec2(gl_GlobalInvocationID.xy);\n"
                "    const vec2 coord = (vec2(gl_GlobalInvocationID.xy) + 0.5) / vec2(pixels_resolution);\n"
            ),
            "    const ivec3  pos = ivec3(gl_GlobalInvocationID.xy, 0);\n"
            "    const vec2    v2 = (vec2(gl_GlobalInvocationID.xy) + 0.5) / vec2(pixels_resolution);\n"
            "    const vec3 coord = vec3(v2, 0.0);\n",
        ][idx]
        src += (
            f"layout (binding = 0) uniform {smp} u_image0;\n"
            f"layout (binding = 1, {qual}) writeonly uniform {img} u_image1;\n\n"
            "void main (void)\n{\n    const vec2 pixels_resolution = vec2(gl_NumWorkGroups.x, gl_NumWorkGroups.y);\n"
            + coord
            + "    imageStore(u_image1, pos, texture(u_image0, coord));\n}\n"
        )
    else:
        pos = [
            "    highp int pos = int(gl_GlobalInvocationID.x);\n",
            "    ivec3 pos = ivec3(gl_GlobalInvocationID);\n" if multi else "    ivec2 pos = ivec2(gl_GlobalInvocationID.xy);\n",
            "    ivec3 pos = ivec3(gl_GlobalInvocationID);\n",
        ][idx]
        src += (
            f"layout (binding = 0, {qual}) uniform {img}           u_image0;\n"
            f"layout (binding = 1, {qual}) readonly uniform {img}  u_image1;\n"
            f"layout (binding = 2, {qual}) writeonly uniform {img} u_image2;\n\n"
            "void main (void)\n{\n" + pos + "    imageStore(u_image0, pos, imageLoad(u_image1, pos));\n"
            "    imageStore(u_image2, pos, imageLoad(u_image0, pos));\n}\n"
        )
    return src


def decompress_source(itype, ref_array, multi):
    idx = IMAGE_TYPES.index(itype)
    res_smp = sampler_type(VERIFY, itype, multi)
    ref_smp = sampler_type(VERIFY, itype, ref_array)
    out_img = image_type(VERIFY, itype, multi)
    coord = [
        "    const highp float coord = float(gl_GlobalInvocationID.x) / pixels_resolution.x;\n"
        "    const highp int     pos = int(gl_GlobalInvocationID.x); \n",
        (
            "    const vec2    v2 = vec2(gl_GlobalInvocationID.xy) / vec2(pixels_resolution);\n"
            "    const vec3 coord = vec3(v2, gl_GlobalInvocationID.z);\n"
            "    const ivec3  pos = ivec3(gl_GlobalInvocationID); \n"
            if multi
            else "    const vec2 coord = vec2(gl_GlobalInvocationID.xy) / vec2(pixels_resolution);\n"
            "    const ivec2  pos = ivec2(gl_GlobalInvocationID.xy); \n"
        ),
        "    const vec2    v2 = vec2(gl_GlobalInvocationID.xy) / vec2(pixels_resolution);\n"
        "    const vec3 coord = vec3(v2, 0.0);\n"
        "    const ivec3  pos = ivec3(gl_GlobalInvocationID); \n",
    ][idx]
    qual = VERIFY[1]
    src = (
        VERSION + "\n" + LOCAL
        + f"layout (binding = 0) uniform {res_smp} compressed_result;\n"
        + f"layout (binding = 1) uniform {ref_smp} compressed_reference;\n"
        + f"layout (binding = 2, {qual}) writeonly uniform {out_img} decompressed_result;\n"
        + f"layout (binding = 3, {qual}) writeonly uniform {out_img} decompressed_reference;\n"
        + "layout (push_constant, std430) uniform PushConstants { uint layer; uint level; };\n\n"
        + "void main (void)\n{\n"
        + "    const vec2 pixels_resolution = vec2(gl_NumWorkGroups.xy);\n"
        + coord
        + "    imageStore(decompressed_result, pos, texture(compressed_result, coord));\n"
    )
    if ref_array and not multi:
        src += "    imageStore(decompressed_reference, pos, textureLod(compressed_reference, vec3(coord, layer), level));\n"
    else:
        src += "    imageStore(decompressed_reference, pos, texture(compressed_reference, coord));\n"
    return src + "}\n"


def attachment_frag(short):
    prefix, _, dst, inp = UNCOMPRESSED[short]
    return (
        VERSION + "\n"
        "precision highp int;\nprecision highp float;\n\n"
        f"layout (location = 0) out highp {dst} o_color;\n"
        f"layout (input_attachment_index = 0, set = 0, binding = 0) uniform highp {inp} inputImage1;\n\n"
        f"void main (void)\n{{\n    o_color = {dst}(subpassLoad(inputImage1));\n}}\n"
    )


def texture_frag(short, itype):
    fmt = UNCOMPRESSED[short]
    idx = IMAGE_TYPES.index(itype)
    inputs = [
        "    const highp int out_pos = int(gl_FragCoord.x);\n"
        "    const highp float pixels_resolution = textureSize(u_imageIn, 0);\n"
        "    const highp float in_pos = gl_FragCoord.x / pixels_resolution;\n",
        "    const ivec2 out_pos = ivec2(gl_FragCoord.xy);\n"
        "    const vec2 pixels_resolution = vec2(textureSize(u_imageIn, 0));\n"
        "    const vec2 in_pos = vec2(gl_FragCoord.xy) / vec2(pixels_resolution);\n",
        "    const ivec3 out_pos = ivec3(gl_FragCoord.xy, 0);\n"
        "    const vec3 pixels_resolution = vec3(textureSize(u_imageIn, 0));\n"
        "    const vec3 in_pos = vec3(gl_FragCoord.xy, 0) / vec3(pixels_resolution.xy, 1.0);\n",
    ][idx]
    return (
        VERSION + "\n"
        f"layout (binding = 0) uniform {sampler_type(fmt, itype)} u_imageIn;\n"
        f"layout (binding = 1, {fmt[1]}) writeonly uniform {image_type(fmt, itype)} u_imageOut;\n\n"
        "void main (void)\n{\n" + inputs + "    imageStore(u_imageOut, out_pos, texture(u_imageIn, in_pos));\n}\n"
    )


def verify_frag(itype):
    idx = IMAGE_TYPES.index(itype)
    pos0 = [
        "    const highp int out_pos = int(gl_FragCoord.x);\n"
        "    const highp float pixels_resolution0 = textureSize(u_imageIn0, 0);\n"
        "    const highp float in_pos0 = gl_FragCoord.x / pixels_resolution0;\n",
        "    const ivec2 out_pos = ivec2(gl_FragCoord.xy);\n"
        "    const vec2 pixels_resolution0 = vec2(textureSize(u_imageIn0, 0));\n"
        "    const vec2 in_pos0 = vec2(gl_FragCoord.xy) / vec2(pixels_resolution0);\n",
        "    const ivec3 out_pos = ivec3(ivec2(gl_FragCoord.xy), 0);\n"
        "    const vec3 pixels_resolution0 = vec3(textureSize(u_imageIn0, 0));\n"
        "    const vec3 in_pos0 = vec3(gl_FragCoord.xy, 0) / vec3(pixels_resolution0.xy, 1.0);\n",
    ][idx]
    pos1 = [
        "    const highp float pixels_resolution1 = textureSize(u_imageIn1, 0);\n"
        "    const highp float in_pos1 = gl_FragCoord.x / pixels_resolution1;\n",
        "    const vec2 pixels_resolution1 = vec2(textureSize(u_imageIn1, 0));\n"
        "    const vec2 in_pos1 = vec2(gl_FragCoord.xy) / vec2(pixels_resolution1);\n",
        "    const vec3 pixels_resolution1 = vec3(textureSize(u_imageIn1, 0));\n"
        "    const vec3 in_pos1 = vec3(gl_FragCoord.xy, 0) / vec3(pixels_resolution1.xy, 1.0);\n",
    ][idx]
    smp = sampler_type(VERIFY, itype)
    img = image_type(VERIFY, itype)
    q = VERIFY[1]
    return (
        VERSION + "\n"
        f"layout (binding = 0) uniform {smp} u_imageIn0;\n"
        f"layout (binding = 1) uniform {smp} u_imageIn1;\n"
        f"layout (binding = 2, {q}) writeonly uniform {img} u_imageOut0;\n"
        f"layout (binding = 3, {q}) writeonly uniform {img} u_imageOut1;\n\n"
        "void main (void)\n{\n" + pos0 + "    imageStore(u_imageOut0, out_pos, texture(u_imageIn0, in_pos0));\n\n" + pos1
        + "    imageStore(u_imageOut1, out_pos, texture(u_imageIn1, in_pos1));\n}\n"
    )


def toml_literal(text):
    return '"' + repr(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def entry(key, programs, derived):
    out = f'\n[[case]]\nname = "{key}"\nrust_const = "{key.upper()}"\nrust_type = "SharedProgram"\nprograms = [\n'
    for name, template, stage in programs:
        out += f'    {{ name = "{name}", template = "{template}", stage = "{stage}" }},\n'
    out += "]\n"
    out += "derived = { " + ", ".join(f"{k} = {toml_literal(v)}" for k, v in derived.items()) + " }\n"
    return out


def main():
    (SRC / "texel_view_comp.comp").write_text("${comp_source}")
    (SRC / "texel_view_decompress.comp").write_text("${decompress_source}")
    (SRC / "texel_view_frag.frag").write_text("${frag_source}")
    (SRC / "texel_view_frag_verify.frag").write_text("${verify_source}")
    (SRC / "texel_view.vert").write_text(
        "#version 450\n\nlayout(location = 0) in vec4 v_in_position;\n\nvoid main (void)\n{\n    gl_Position = v_in_position;\n}\n"
    )

    out = [HEADER]
    count = 0
    for op in COMPUTE_OPS:
        for short, fmt in UNCOMPRESSED.items():
            for itype in IMAGE_TYPES:
                for multi in (False, True):
                    if multi and itype != "2d":
                        continue
                    for ref_array in (False, True):
                        if ref_array and itype != "2d":
                            continue
                        if multi and not ref_array:
                            continue
                        key = f"c_{op}_{short}_{itype}_{int(ref_array)}_{int(multi)}"
                        programs = [
                            ("comp", "image/texel_view_comp.comp", "comp"),
                            ("decompress", "image/texel_view_decompress.comp", "comp"),
                        ]
                        derived = {
                            "comp_source": compute_source(op, fmt, itype, multi),
                            "decompress_source": decompress_source(itype, ref_array, multi),
                        }
                        out.append(entry(key, programs, derived))
                        count += 1
    for kind in ("att", "tex"):
        for short in UNCOMPRESSED:
            for itype in IMAGE_TYPES:
                if kind == "att" and itype == "3d":
                    continue
                key = f"g_{kind}_{short}_{itype}"
                programs = [
                    ("vert", "image/texel_view.vert", "vert"),
                    ("frag", "image/texel_view_frag.frag", "frag"),
                    ("frag_verify", "image/texel_view_frag_verify.frag", "frag"),
                ]
                frag = attachment_frag(short) if kind == "att" else texture_frag(short, itype)
                out.append(entry(key, programs, {"frag_source": frag, "verify_source": verify_frag(itype)}))
                count += 1
    MANIFEST.write_text("".join(out))
    print(f"{count} entries")


if __name__ == "__main__":
    main()
