#!/usr/bin/env python3
"""Writes the shaders and the manifest of dEQP-VK.dgc.ext.compute.smoke (`SmokeTestCase::initPrograms`).

The counting shader is the same for every case; the "gen" shader that copies the indirect commands only exists when the commands come from
a compute shader and depends on the sequence count. A pure text generator: no glslang and no cargo.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "shaders" / "manifest" / "dgc_compute_smoke.toml"
SRC_DIR = ROOT / "shaders" / "src" / "dgc"

LOCAL_INVOCATIONS = 64
MAX_WORK_GROUPS = 256
SEQUENCE_COUNTS = [4, 1024]

COMP = f"""#version 460
#extension GL_KHR_memory_scope_semantics : enable
layout (set=0, binding=0, std430) buffer AtomicCountersBlock {{
    uint value[{MAX_WORK_GROUPS}];
}} atomicCounters;
layout (local_size_x={LOCAL_INVOCATIONS}, local_size_y=1, local_size_z=1) in;
void main ()
{{
    const uint workGroupIndex = gl_NumWorkGroups.x * gl_NumWorkGroups.y * gl_WorkGroupID.z + gl_NumWorkGroups.x * gl_WorkGroupID.y + gl_WorkGroupID.x;
    atomicAdd(atomicCounters.value[workGroupIndex], 1u, gl_ScopeQueueFamily, gl_StorageSemanticsBuffer, (gl_SemanticsAcquireRelease | gl_SemanticsMakeAvailable | gl_SemanticsMakeVisible));
}}
"""


def gen(sequence_count):
    commands_per_inv = (sequence_count + (LOCAL_INVOCATIONS - 1)) // LOCAL_INVOCATIONS
    return f"""#version 460
layout (local_size_x={LOCAL_INVOCATIONS}, local_size_y=1, local_size_z=1) in;
struct VkDispatchIndirectCommand {{
    uint x;
    uint y;
    uint z;
}};
const uint sequenceCount = {sequence_count}u;
layout (set=0, binding=0, std430) readonly buffer HostBufferCommands {{
    VkDispatchIndirectCommand commands[sequenceCount];
}} hostBuffer;
layout (set=0, binding=1, std430) buffer IndirectCommandsBlock {{
    VkDispatchIndirectCommand commands[sequenceCount];
}} cmdBuffer;
void main (void) {{
    const uint commandsPerInv = {commands_per_inv};
    const uint firstCommand = gl_LocalInvocationIndex * commandsPerInv;
    for (uint i = 0u; i < commandsPerInv; ++i) {{
        const uint cmdIndex = firstCommand + i;
        if (cmdIndex < sequenceCount) {{
            cmdBuffer.commands[cmdIndex] = hostBuffer.commands[cmdIndex];
        }}
    }}
}}
"""


HEADER = """# Shader manifest for dEQP-VK.dgc.ext.compute.smoke
#
# @generated by hodow_cts/scripts/gen_dgc_compute_smoke_manifest.py - do not hand-edit.

upstream_source = "external/vulkancts/modules/vulkan/device_generated_commands/vktDGCComputeSmokeTestsExt.cpp"
rust_module = "dgc/compute_smoke_tests"
"""


def main():
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    (SRC_DIR / "smoke.comp").write_text(COMP)
    out = [HEADER]
    for count in SEQUENCE_COUNTS:
        (SRC_DIR / f"smoke_gen_{count}.comp").write_text(gen(count))
        for pre_compute in (False, True):
            key = f"smoke_s{count}_{'gen' if pre_compute else 'host'}"
            programs = ['{ name = "comp", template = "dgc/smoke.comp", stage = "comp", spirv_version = "spirv1.3" }']
            if pre_compute:
                programs.append(f'{{ name = "gen", template = "dgc/smoke_gen_{count}.comp", stage = "comp" }}')
            out.append(
                f"""
[[case]]
name = "{key}"
rust_const = "{key.upper()}"
rust_type = "SharedProgram"
programs = [ {", ".join(programs)} ]
"""
            )
    MANIFEST.write_text("".join(out))
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
