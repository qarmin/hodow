#!/usr/bin/env python3
"""Writes shaders/manifest/spirv_assembly_compare64_graphics.toml: the vertex and fragment cases of dEQP-VK.spirv_assembly.instruction.graphics.64bit_compare.*
(vktSpvAsm64bitCompareTests.cpp). The four SPIR-V templates (VertShaderSingle/Vector, FragShaderSingle/Vector) and the GLSL passthrough vertex shader the fragment
cases pair with are read out of the C++ into shaders/src/spirv_assembly/compare64_*; the substitutions are the ones `initPrograms` makes.

A pure text generator: no spirv-as and no cargo."""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CRATE = HERE.parent
CPP = CRATE / "upstream" / "external" / "vulkancts" / "modules" / "vulkan" / "spirv_assembly" / "vktSpvAsm64bitCompareTests.cpp"
SRC_DIR = CRATE / "shaders" / "src" / "spirv_assembly"
OUT = CRATE / "shaders" / "manifest" / "spirv_assembly_compare64_graphics.toml"
SOURCE = "external/vulkancts/modules/vulkan/spirv_assembly/vktSpvAsm64bitCompareTests.cpp"

OPERANDS = {"double": 20, "int64": 16, "uint64": 12}
FLOAT_COMPARES = ["Equal", "NotEqual", "LessThan", "LessThanEqual", "GreaterThan", "GreaterThanEqual"]
INT_COMPARES = ["IEqual", "INotEqual", "{S}LessThan", "{S}LessThanEqual", "{S}GreaterThan", "{S}GreaterThanEqual"]
TYPES = {
    "double": ("OpTypeFloat 64", "OpCapability Float64"),
    "int64": ("OpTypeInt 64 1", "OpCapability Int64"),
    "uint64": ("OpTypeInt 64 0", "OpCapability Int64"),
}


def write_templates():
    text = CPP.read_text(encoding="utf-8")
    for stage, kind, variable in (
        ("vert", "single", "VertShaderSingle"),
        ("vert", "vector", "VertShaderVector"),
        ("frag", "single", "FragShaderSingle"),
        ("frag", "vector", "FragShaderVector"),
    ):
        m = re.search(r'const tcu::StringTemplate ' + variable + r'\(R"\((.*?)\)"\);', text, re.S)
        (SRC_DIR / f"compare64_{stage}_{kind}.spvasm").write_text(m.group(1), encoding="utf-8")
    m = re.search(r'const std::string VertShaderPassThrough = R"\((.*?)\)";', text, re.S)
    (SRC_DIR / "compare64_frag_passthru.vert").write_text(m.group(1).lstrip("\n"), encoding="utf-8")


def main():
    write_templates()
    entries = []
    names = []
    for stage in ("vert", "frag"):
        for group, (optype, capability) in TYPES.items():
            if group == "double":
                op_names = [f"OpF{kind}{name}" for kind in ("Ord", "Unord") for name in FLOAT_COMPARES]
            else:
                sign = "S" if group == "int64" else "U"
                op_names = ["Op" + name.replace("{S}", sign) for name in INT_COMPARES]
            for data_type in ("single", "vector"):
                for nan_preserve in (False, True) if group == "double" else (False,):
                    for op_name in op_names:
                        nan_part = ("withnan_" if nan_preserve else "nonan_") if group == "double" else ""
                        path = f"64bit_compare/{group}/{stage}_{op_name.lower()}_{nan_part}{data_type}"
                        names.append(path)
                        operands = OPERANDS[group]
                        derived = {
                            "ITERS": str(operands if data_type == "single" else operands // 4),
                            "OPNAME": op_name,
                            "OPCAPABILITY": capability,
                            "OPTYPE": optype,
                            "NANCAP": "OpCapability SignedZeroInfNanPreserve" if nan_preserve else "",
                            "NANEXT": 'OpExtension "SPV_KHR_float_controls"' if nan_preserve else "",
                            "NANMODE": "OpExecutionMode %main SignedZeroInfNanPreserve 64" if nan_preserve else "",
                        }
                        programs = f'{{ name = "{stage}", template = "spirv_assembly/compare64_{stage}_{data_type}.spvasm", stage = "asm", spirv_version = "spirv1.0" }}'
                        if stage == "frag":
                            programs += ', { name = "vert", template = "spirv_assembly/compare64_frag_passthru.vert", stage = "vert" }'
                        derived_text = ", ".join(f"{key} = {json.dumps(repr(value))}" for key, value in derived.items())
                        entries.append(
                            f'\n[[case]]\nname = "{path}"\nrust_const = "C64_{re.sub("[^A-Za-z0-9]", "_", path).upper()}"\nrust_type = "Compare64GraphicsCase"\n'
                            f'programs = [ {programs} ]\nparams = {{ spec = {{ type = "str", value = "stage={stage}" }} }}\nderived = {{ {derived_text} }}\n'
                        )
    header = (
        "# Shader manifest for dEQP-VK.spirv_assembly.instruction.graphics.64bit_compare (vertex and fragment stages)\n#\n"
        "# @generated by hodow_cts/scripts/gen_spirv_assembly_compare64_graphics_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "spirv_assembly/compare64_graphics_tests"\n'
    )
    OUT.write_text(header + "".join(entries), encoding="utf-8")
    missing = (CRATE.parent / "tmp" / "missing" / "spirv_assembly.txt").read_text().splitlines()
    want = {line.split("instruction.graphics.", 1)[1].replace(".", "/") for line in missing if "instruction.graphics.64bit_compare." in line}
    print(f"{len(entries)} cases; mustpass {len(want)}, missing {len(want - set(names))}, extra {len(set(names) - want)}", file=sys.stderr)


if __name__ == "__main__":
    main()
