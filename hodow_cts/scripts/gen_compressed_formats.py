#!/usr/bin/env python3
"""Generate src/vk/compressed_formats.rs from upstream's vkImageUtil.cpp.

The block dimensions of 98 compressed formats. The copy tests need them because
`vkCmdCopyImage` between a compressed and an uncompressed image states its offsets and
extents in texels of the compressed side, so every one has to be scaled by the block
size - and a wrong block size there produces a copy that is off by a factor rather than
one that fails to build.

Nothing here decompresses anything: a copy moves blocks, so the host side views a
compressed image as an uncompressed one of the same block size (`getSizeCompatible-
TcuTextureFormat`).

Usage:
    python3 hodow_cts/scripts/gen_compressed_formats.py [--cts-dir tmp/VK-GL-CTS]
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = CRATE_DIR.parent
OUT = CRATE_DIR / "src" / "vk" / "compressed_formats.rs"

TABLES = [
    "compressedFormatParameters",
    "compressedAstcHdrFormatParameters",
    "compressed3DFormatParameters",
]

# vulkanalia drops a vendor suffix once the format is promoted to core and keeps it
# otherwise. The 3D ASTC formats - three block dimensions - never were.
ASTC_3D = re.compile(r"^VK_FORMAT_ASTC_\d+x\d+x\d+_")


def rust_name(enum_name: str) -> str:
    name = enum_name.removeprefix("VK_FORMAT_")
    if not ASTC_3D.match(enum_name):
        name = re.sub(r"_(KHR|EXT)$", "", name)
    name = re.sub(r"(?<=\d)x(?=\d)", "X", name)
    if name[0].isdigit():
        name = "_" + name
    return name


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cts-dir", type=Path, default=REPO_DIR / "tmp" / "VK-GL-CTS")
    args = ap.parse_args()

    src = args.cts_dir / "external/vulkancts/framework/vulkan/vkImageUtil.cpp"
    if not src.is_file():
        print(f"error: {src} not found; is --cts-dir right?", file=sys.stderr)
        return 2
    text = src.read_text()

    entries: list[tuple[str, int, int, int, int]] = []
    for table in TABLES:
        i = text.index(table + "[")
        j = text.index("};", i)
        found = re.findall(r"\{\s*(VK_FORMAT_\w+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", text[i:j])
        if not found:
            raise SystemExit(f"no entries found in {table}")
        print(f"{table}: {len(found)} formats")
        entries += [(f, int(b), int(w), int(h), int(d)) for f, b, w, h, d in found]

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/vulkancts/framework/vulkan/vkImageUtil.cpp",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2016 The Khronos Group Inc.",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_compressed_formats.py; do not hand-edit.",
        "",
        "use vulkanalia::vk;",
        "",
        "/// `vk::CompressedFormatParameters`",
        "pub struct CompressedFormatParameters {",
        "    pub format: vk::Format,",
        "    pub block_bytes: u32,",
        "    pub block_width: u32,",
        "    pub block_height: u32,",
        "    pub block_depth: u32,",
        "}",
        "",
        "/// Every compressed format upstream knows the block dimensions of.",
        "pub static COMPRESSED_FORMAT_PARAMETERS: &[CompressedFormatParameters] = &[",
    ]
    for f, b, w, h, d in entries:
        lines.append(
            f"    CompressedFormatParameters {{ format: vk::Format::{rust_name(f)}, "
            f"block_bytes: {b}, block_width: {w}, block_height: {h}, block_depth: {d} }},"
        )
    lines += [
        "];",
        "",
        "/// `vk::getCompressedFormats` - upstream indexes three contiguous ranges; a linear",
        "/// scan over 98 entries answers the same question without the range arithmetic.",
        "fn get_compressed_format(format: vk::Format) -> Option<&'static CompressedFormatParameters> {",
        "    COMPRESSED_FORMAT_PARAMETERS.iter().find(|p| p.format == format)",
        "}",
        "",
        "/// `vk::isCompressedFormat`",
        "pub fn is_compressed_format(format: vk::Format) -> bool {",
        "    get_compressed_format(format).is_some()",
        "}",
        "",
        "/// `vk::getBlockSizeInBytes`",
        "pub fn get_block_size_in_bytes(format: vk::Format) -> u32 {",
        "    get_compressed_format(format).map_or(0, |p| p.block_bytes)",
        "}",
        "",
        "/// `vk::getBlockWidth`",
        "pub fn get_block_width(format: vk::Format) -> u32 {",
        "    get_compressed_format(format).map_or(1, |p| p.block_width)",
        "}",
        "",
        "/// `vk::getBlockHeight`",
        "pub fn get_block_height(format: vk::Format) -> u32 {",
        "    get_compressed_format(format).map_or(1, |p| p.block_height)",
        "}",
        "",
        "/// `vk::getBlockDepth`",
        "pub fn get_block_depth(format: vk::Format) -> u32 {",
        "    get_compressed_format(format).map_or(1, |p| p.block_depth)",
        "}",
        "",
    ]

    header = (args.cts_dir / "external/vulkancts/framework/vulkan/generated/vulkan/vkFormatLists.inl").read_text()
    for list_name, fn_name, doc in [
        ("astcHDRFormats", "is_astc_hdr_format", "vk::isAstcHdrFormat"),
        ("astc3dFormats", "is_astc_3d_format", "vk::isAstc3DFormat"),
    ]:
        i = header.index("std::vector<VkFormat> " + list_name)
        j = header.index("};", i)
        fmts = re.findall(r"VK_FORMAT_\w+", header[i:j])
        print(f"{list_name}: {len(fmts)} formats")
        lines += [f"/// `{doc}`", f"pub fn {fn_name}(format: vk::Format) -> bool {{", "    matches!("]
        lines.append("        format,")
        lines.append("        " + "\n            | ".join(f"vk::Format::{rust_name(f)}" for f in fmts))
        lines += ["    )", "}", ""]
    OUT.write_text("\n".join(lines))
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], cwd=CRATE_DIR, check=False)
    print(f"wrote {OUT.relative_to(REPO_DIR)} ({len(entries)} formats)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
