#!/usr/bin/env python3
"""Writes shaders/manifest/spirv_assembly_multiple_shaders_extended.toml: the two cases of dEQP-VK.spirv_assembly.instruction.compute.multiple_shaders_extended
(`two_entry_points_execution_mode_id` and `two_entry_points_different_interfaces`) of vktSpvAsmMultipleShadersTests.cpp.

The assembly is read out of the C++ string literals of `Programs::init`, so it is exactly what the test assembles. The host side is
src/vkt/tests/spirv_assembly/multiple_shaders_extended_tests.rs.

    python3 hodow_cts/scripts/gen_spirv_assembly_multiple_shaders_extended_manifest.py [--cts-dir tmp/VK-GL-CTS]

A pure text generator: no spirv-as and no cargo.
"""

import argparse
import json
import re
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "spirv_assembly_multiple_shaders_extended.toml"
SOURCE = "external/vulkancts/modules/vulkan/spirv_assembly/vktSpvAsmMultipleShadersTests.cpp"
PREFIX = 'OpCapability Shader\n%1 = OpExtInstImport "GLSL.std.450"\nOpMemoryModel Logical GLSL450\n'


def literals(text):
    return "".join(bytes(literal, "utf-8").decode("unicode_escape") for literal in re.findall(r'"((?:[^"\\]|\\.)*)"', text))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cts-dir", default=str(CRATE.parent / "tmp" / "VK-GL-CTS"))
    source = (Path(parser.parse_args().cts_dir) / SOURCE).read_text()
    cases = []
    for marker, name, version in (("TWO_ENTRY_POINTS_EXECUTION_MODE_ID)\n", "two_entry_points_execution_mode_id", "spirv1.5"), ("TWO_ENTRY_POINTS_DIFFERENT_INTERFACES)\n", "two_entry_points_different_interfaces", None)):
        start = source.index("compSrc += ", source.index(marker, source.index("void init(")))
        end = source.index(";\n", start)
        cases.append((name, version, PREFIX + literals(source[start + len("compSrc += ") : end])))

    out = [
        "# Shader manifest for dEQP-VK.spirv_assembly.instruction.compute.multiple_shaders_extended.*\n#\n"
        "# @generated by hodow_cts/scripts/gen_spirv_assembly_multiple_shaders_extended_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "spirv_assembly/multiple_shaders_extended_tests"\n'
    ]
    for name, version, assembly in cases:
        extra = f', spirv_version = "{version}"' if version else ""
        out.append(
            f'\n[[case]]\nname = "{name}"\nrust_const = "MSE_{name.upper()}"\nrust_type = "SharedProgram"\n'
            f'programs = [ {{ name = "compute", template = "spirv_assembly/source.asm", stage = "asm"{extra} }} ]\n'
            f"derived = {{ source = {json.dumps(repr(assembly))} }}\n"
        )
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {len(cases)} cases")


if __name__ == "__main__":
    main()
