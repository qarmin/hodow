#!/usr/bin/env python3
"""Generate src/vkt/tests/api/vulkan_feature_consistency_tests.rs, `feature_extensions_consistency` of dEQP-VK.api.info.vulkan1p{2,3,4}.

Upstream's `deviceFeatureExtensionsConsistencyVulkan12/13/14` are one pattern repeated: query the core `VkPhysicalDeviceVulkan1xFeatures`
structures, query the feature structures of the extensions that were promoted into them, and fail on any member that differs. The
structure list, every compared member pair and the failure message are read out of the C++ here, and each structure and member name is
checked against vulkanalia, so the Rust never names something this script has not found.

Usage:
    python3 hodow_cts/scripts/gen_vulkan_feature_consistency_tests.py
"""

from __future__ import annotations

import glob
import re
import sys
from pathlib import Path

CRATE_DIR = Path(__file__).resolve().parent.parent
UPSTREAM = CRATE_DIR / "upstream/external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp"
OUT = CRATE_DIR / "src/vkt/tests/api/vulkan_feature_consistency_tests.rs"

FUNCTIONS = [("12", (1, 2)), ("13", (1, 3)), ("14", (1, 4))]


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def normalise(name: str) -> str:
    return name.replace("_", "").lower()


def vulkanalia_structs() -> str:
    paths = glob.glob(str(Path.home() / ".cargo/registry/src/*/vulkanalia-sys-0.35.0/src/structs.rs"))
    if not paths:
        sys.exit("vulkanalia-sys 0.35.0 is not in the cargo registry")
    return Path(paths[0]).read_text()


def rust_struct(structs: str, c_type: str) -> tuple[str, dict[str, str]]:
    base = c_type.removeprefix("Vk")
    candidates = [base] + [base[: -len(s)] for s in ("KHR", "EXT") if base.endswith(s)]
    for candidate in candidates:
        match = re.search(rf"pub struct {candidate} \{{(.*?)\n\}}", structs, re.S)
        if match:
            fields = re.findall(r"pub (\w+):", match.group(1))
            return candidate, {normalise(f): f for f in fields}
    sys.exit(f"{c_type} is not in vulkanalia-sys")


def function_text(cpp: str, name: str) -> str:
    start = cpp.index(f"tcu::TestStatus {name}(Context &context)")
    end = cpp.index("\ntcu::TestStatus ", start + 10)
    return cpp[start:end]


def balanced(text: str, open_at: int) -> tuple[str, int]:
    depth = 0
    for i in range(open_at, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return text[open_at + 1 : i], i
    sys.exit("unbalanced parentheses")


def literal(text: str) -> str:
    return "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', text))


def main() -> int:
    cpp = UPSTREAM.read_text()
    structs = vulkanalia_structs()
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Derived from VK-GL-CTS:",
        "//   external/vulkancts/modules/vulkan/api/vktApiFeatureInfo.cpp (`deviceFeatureExtensionsConsistencyVulkan12/13/14`)",
        "// Upstream revision: see hodow_cts/upstream/COMMIT",
        "//",
        "// Copyright (c) 2015 The Khronos Group Inc.",
        "// Copyright (c) 2015 Intel Corporation",
        "// Licensed under the Apache License, Version 2.0 (see LICENSE at the repo root).",
        "//",
        "// Generated by scripts/gen_vulkan_feature_consistency_tests.py from upstream's function bodies; do not hand-edit.",
        "//",
        "// `feature_extensions_consistency`: the feature structures of the extensions promoted into Vulkan 1.2, 1.3 and 1.4 report the same",
        "// members as the core `VkPhysicalDeviceVulkan1xFeatures` structures.",
        "",
        "use vulkanalia::prelude::v1_0::*;",
        "use vulkanalia::vk::InstanceV1_1;",
        "",
        "use crate::tcu::{TestError, TestOutcome, TestStatus};",
        "use crate::vkt::Context;",
        "",
        "fn require_api_version(context: &Context<'_>, version: (u32, u32)) -> Result<(), TestError> {",
        "    let (major, minor, _) = context.api_version();",
        "    if (major, minor) < version {",
        "        return Err(TestError::NotSupported(format!(\"At least Vulkan {}.{} required to run test\", version.0, version.1)));",
        "    }",
        "    Ok(())",
        "}",
        "",
    ]
    for suffix, version in FUNCTIONS:
        text = function_text(cpp, f"deviceFeatureExtensionsConsistencyVulkan{suffix}")
        decls = re.findall(r"(Vk\w+)\s+(\w+)\s*=\s*\n?\s*initVulkanStructure\(", text)
        variables: dict[str, tuple[str, dict[str, str]]] = {}
        order_core, order_ext = [], []
        for c_type, var in decls:
            if c_type == "VkPhysicalDeviceFeatures2":
                continue
            variables[var] = rust_struct(structs, c_type)
            (order_core if re.fullmatch(r"VkPhysicalDeviceVulkan1\dFeatures", c_type) else order_ext).append(var)

        out += [f"pub fn device_feature_extensions_consistency_vulkan{suffix}(context: &Context<'_>) -> TestOutcome {{", f"    require_api_version(context, {version})?;", ""]

        def query(vars_: list[str], what: str) -> list[str]:
            lines = []
            for var in vars_:
                lines.append(f"    let mut {snake(var)} = vk::{variables[var][0]}::default();")
            pushes = "".join(f".push_next(&mut {snake(v)})" for v in vars_)
            lines += [
                f"    {{",
                f"        let mut features2 = vk::PhysicalDeviceFeatures2::builder(){pushes};",
                "        unsafe { context.get_instance().get_physical_device_features2(context.get_physical_device(), &mut features2) };",
                "    }",
                "",
            ]
            return lines

        out += query(order_core, "core")

        validations = re.findall(r'\{\{"(VK_\w+)",\s*"\w+\.(\w+)"\},\s*(\w+)\.(\w+)\}', text)
        for ext, member_name, var, member in validations:
            field = variables[var][1].get(normalise(member))
            if field is None:
                sys.exit(f"{var}.{member} is not in vulkanalia")
            out += [
                f'    if context.is_device_functionality_supported("{ext}") && {snake(var)}.{field} == vk::FALSE {{',
                f'        return Ok(TestStatus::fail("Mismatch between extension {ext} and VkPhysicalDeviceVulkan{suffix[0]}{suffix[1]}Features.{member_name}".to_string()));',
                "    }",
            ]
        if validations:
            out.append("")

        out += query(order_ext, "ext")

        position = text.index("collect all extension features")
        body = text[position:]
        for match in re.finditer(r"\bif \(", body):
            condition, end = balanced(body, match.end() - 1)
            rest = body[end + 1 :].lstrip()
            if rest.startswith("{"):
                rest = rest[1:].lstrip()
            if not rest.startswith("TCU_FAIL("):
                continue
            message_args, _ = balanced(rest, len("TCU_FAIL"))
            message = literal(message_args)
            pairs = re.findall(r"(\w+)\.(\w+)\s*!=\s*(\w+)\.(\w+)", condition)
            if not pairs:
                sys.exit(f"no member pairs in: {condition}")
            leftover = re.sub(r"(\w+)\.(\w+)\s*!=\s*(\w+)\.(\w+)|\|\||[()\s]", "", condition)
            if leftover:
                sys.exit(f"unrecognised condition part {leftover!r} in: {condition}")
            terms = []
            for a_var, a_member, b_var, b_member in pairs:
                a_field = variables[a_var][1].get(normalise(a_member))
                b_field = variables[b_var][1].get(normalise(b_member))
                if a_field is None or b_field is None:
                    sys.exit(f"{a_var}.{a_member} or {b_var}.{b_member} is not in vulkanalia")
                terms.append(f"{snake(a_var)}.{a_field} != {snake(b_var)}.{b_field}")
            out += [f"    if {' || '.join(terms)} {{", f'        return Ok(TestStatus::fail("{message}".to_string()));', "    }"]

        out += [f'    Ok(TestStatus::pass("Vulkan {version[0]}.{version[1]} device features are consistent with extensions"))', "}", ""]

    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(CRATE_DIR.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
