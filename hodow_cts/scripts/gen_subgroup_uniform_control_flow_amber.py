#!/usr/bin/env python3
"""Writes the shaders, the manifest and the case table of dEQP-VK.subgroups.subgroup_uniform_control_flow from the vendored Amber scripts.

The compute scripts (`large_full`, `large_full_control`, `small_full`, `small_full_control`: the `fill` and `test` shaders over the buffers a, b, c, d and compare, two
dispatches, `EXPECT compare IDX 0 EQ ..` and `EXPECT b EQ_BUFFER compare`) are read completely. The `discard` script is a graphics one and is listed as a stub. Written:

  * shaders/manifest/subgroups_uniform_control_flow.toml and shaders/src/subgroups_uniform_control_flow/,
  * src/vkt/tests/subgroups/uniform_control_flow_cases.rs (the table of src/vkt/tests/subgroups/uniform_control_flow_tests.rs).

Run from hodow_cts/:  python3 scripts/gen_subgroup_uniform_control_flow_amber.py   (then `just cts-shaders`)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/subgroup_uniform_control_flow"
SRC = ROOT / "shaders" / "src" / "subgroups_uniform_control_flow"
MANIFEST = ROOT / "shaders" / "manifest" / "subgroups_uniform_control_flow.toml"
TABLE = ROOT / "src" / "vkt" / "tests" / "subgroups" / "uniform_control_flow_cases.rs"

GROUPS = [("large", "large_full"), ("large_control", "large_full_control"), ("small", "small_full"), ("small_control", "small_full_control")]


def shaders(text):
    """{name: (spirv version, source)} of the compute shaders."""
    found = {}
    lines = text.splitlines()
    for ndx, line in enumerate(lines):
        match = re.match(r"SHADER compute (\w+) GLSL TARGET_ENV spv(\d)\.(\d)", line)
        if match:
            body = []
            for rest in lines[ndx + 1 :]:
                if rest.strip() == "END":
                    break
                body.append(rest)
            found[match.group(1)] = (f"spirv{match.group(2)}.{match.group(3)}", "\n".join(body) + "\n")
    return found


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.subgroups.subgroup_uniform_control_flow.",
        "#",
        "# @generated by hodow_cts/scripts/gen_subgroup_uniform_control_flow_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/subgroup_uniform_control_flow/large/subgroup_reconverge00.amber"',
        'rust_module = "subgroups/uniform_control_flow_tests"',
        "",
    ]
    table = [
        "// @generated by hodow_cts/scripts/gen_subgroup_uniform_control_flow_amber.py - do not hand-edit.",
        "//",
        "// One row per Amber script of dEQP-VK.subgroups.subgroup_uniform_control_flow: the buffers, the two pipelines and the expectations.",
        "",
        "use super::uniform_control_flow_tests::{BufferSpec, PipelineSpec, UniformControlFlowCase};",
        "",
        "pub static UNIFORM_CONTROL_FLOW_CASES: &[UniformControlFlowCase] = &[",
    ]
    count = 0
    for directory, group in GROUPS:
        for path in sorted((AMBER / directory).glob("*reconverge[0-9][0-9].amber")):
            number = int(path.stem[-2:])
            if number > 20:
                continue
            name = path.stem
            text = path.read_text()
            key = f"subgroup_ucf_{group}_{name}"
            programs = shaders(text)
            buffers = []
            for m in re.finditer(r"BUFFER (\w+) DATA_TYPE uint32 SIZE (\d+) (?:FILL (\d+)|SERIES_FROM (\d+) INC_BY (\d+))", text):
                buffer_name, size, fill, series_from, series_inc = m.groups()
                if fill is not None:
                    buffers.append(f'BufferSpec {{ name: "{buffer_name}", count: {size}, from: {fill}, step: 0 }}')
                else:
                    buffers.append(f'BufferSpec {{ name: "{buffer_name}", count: {size}, from: {series_from}, step: {series_inc} }}')
            pipelines = []
            for block in re.finditer(r"PIPELINE compute (\w+)\n(.*?)\nEND\n", text, re.S):
                body = block.group(2)
                program = re.search(r"ATTACH (\w+)", body).group(1)
                bindings = sorted((int(b), n) for n, b in re.findall(r"BIND BUFFER (\w+) AS storage DESCRIPTOR_SET 0 BINDING (\d+)", body))
                assert [b for b, _ in bindings] == list(range(len(bindings)))
                names = ", ".join(f'"{n}"' for _, n in bindings)
                pipelines.append(f'PipelineSpec {{ program: "{program}", fully_populated: {str("FULLY_POPULATED on" in body).lower()}, bindings: &[{names}] }}')
            run_order = re.findall(r"RUN (\w+) 1 1 1", text)
            assert run_order == ["fill_pipe", "test_pipe"], run_order
            expect = re.search(r"EXPECT compare IDX 0 EQ (\d+) (\d+) (\d+) (\d+)", text).groups()
            size_control = "DEVICE_FEATURE SubgroupSizeControl.subgroupSizeControl" in text

            out += ["[[case]]", f'name = "{key}"', f'rust_const = "{key.upper()}"', 'rust_type = "SharedProgram"', "programs = ["]
            for program_name in ("fill", "test"):
                spirv, source = programs[program_name]
                (SRC / f"{key}_{program_name}.comp").write_text(source)
                out.append(f'    {{ name = "{program_name}", template = "subgroups_uniform_control_flow/{key}_{program_name}.comp", stage = "comp", spirv_version = "{spirv}" }},')
            out += ["]", ""]
            table.append(
                f'    UniformControlFlowCase {{ group: "{group}", name: "{name}", key: "{key}", size_control: {str(size_control).lower()}, buffers: &[{", ".join(buffers)}], '
                f'pipelines: &[{", ".join(pipelines)}], expected_compare: [{", ".join(expect)}] }},'
            )
            count += 1
    table.append("];")
    MANIFEST.write_text("\n".join(out))
    TABLE.write_text("\n".join(table) + "\n")
    print(count, "cases")


if __name__ == "__main__":
    main()
