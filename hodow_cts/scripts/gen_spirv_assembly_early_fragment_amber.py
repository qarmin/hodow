#!/usr/bin/env python3
"""Writes the shaders, the manifest and the case table of dEQP-VK.spirv_assembly.instruction.graphics.{early_fragment,early_and_late_fragment,execution_mode} from the vendored Amber scripts.

Each of the twenty-six scripts draws a rectangle with a SPIR-V assembly fragment shader that writes gl_FragDepth under a depth test (`COMPARE_OP`, `CLEAR_DEPTH`), then draws
a second rectangle that reads the depth buffer with texelFetch and paints green where it holds the expected value. Written: shaders/manifest/spirv_assembly_early_fragment.toml,
shaders/src/spirv_assembly_early_fragment/ and src/vkt/tests/spirv_assembly/early_fragment_cases.rs.

Run from hodow_cts/:  python3 scripts/gen_spirv_assembly_early_fragment_amber.py   (then `just cts-shaders`)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AMBER = ROOT / "upstream/external/vulkancts/data/vulkan/amber/spirv_assembly/instruction/graphics"
SRC = ROOT / "shaders" / "src" / "spirv_assembly_early_fragment"
MANIFEST = ROOT / "shaders" / "manifest" / "spirv_assembly_early_fragment.toml"
TABLE = ROOT / "src" / "vkt" / "tests" / "spirv_assembly" / "early_fragment_cases.rs"

PASSTHROUGH_VERTEX = "#version 430\nlayout(location = 0) in vec4 position;\nvoid main() {\n  gl_Position = position;\n}\n"
COMPARE_OPS = {"equal": "EQUAL", "greater": "GREATER", "greater_or_equal": "GREATER_OR_EQUAL", "less": "LESS", "less_or_equal": "LESS_OR_EQUAL", "not_equal": "NOT_EQUAL"}


def shader(text, kind, name):
    match = re.search(rf"SHADER {kind} {name} (GLSL|SPIRV-ASM)(?: TARGET_ENV spv(\d)\.(\d))?\n(.*?)\nEND\n", text, re.S)
    spirv = f"spirv{match.group(2)}.{match.group(3)}" if match.group(2) else None
    body = match.group(4)
    if match.group(1) == "GLSL" and not body.lstrip().startswith("#version"):
        body = "#version 430\n" + body
    return spirv, body + "\n"


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.spirv_assembly.instruction.graphics.{early_fragment,early_and_late_fragment,execution_mode}.",
        "#",
        "# @generated by hodow_cts/scripts/gen_spirv_assembly_early_fragment_amber.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/data/vulkan/amber/spirv_assembly/instruction/graphics/early_fragment/depth_equal.amber"',
        'rust_module = "spirv_assembly/early_fragment_tests"',
        "",
    ]
    table = [
        "// @generated by hodow_cts/scripts/gen_spirv_assembly_early_fragment_amber.py - do not hand-edit.",
        "//",
        "// One row per Amber script of the early_fragment and early_and_late_fragment groups.",
        "",
        "use super::early_fragment_tests::EarlyFragmentCase;",
        "use vulkanalia::prelude::v1_0::*;",
        "",
        "pub static EARLY_FRAGMENT_CASES: &[EarlyFragmentCase] = &[",
    ]
    count = 0
    for group in ("early_fragment", "early_and_late_fragment", "execution_mode"):
        for path in sorted((AMBER / group).glob("*.amber")):
            name = path.stem
            text = path.read_text()
            key = f"early_fragment_{group}_{name}"
            vertex_name = re.search(r"SHADER vertex (vert_shader|vtex_shader) GLSL", text).group(1)
            _, vertex = shader(text, "vertex", vertex_name)
            size = int(re.search(r"FRAMEBUFFER_SIZE (\d+) \d+", text).group(1))
            frag_version, fragment = shader(text, "fragment", "frag_shader")
            _, verify = shader(text, "fragment", "frag_shader_verify")
            compare = re.search(r"COMPARE_OP (\w+)", text).group(1)
            clear_depth = float(re.search(r"CLEAR_DEPTH my_pipeline ([\d.]+)", text).group(1))
            early_and_late = "VK_AMD_shader_early_and_late_fragment_tests" in text
            out += ["[[case]]", f'name = "{key}"', f'rust_const = "{key.upper()}"', 'rust_type = "SharedProgram"', "programs = ["]
            programs = [("vert", "vert", vertex, None), ("frag", "asm", fragment, frag_version), ("verify_vert", "vert", PASSTHROUGH_VERTEX, None), ("verify_frag", "frag", verify, None)]
            for program_name, stage, source, spirv in programs:
                file_name = f"{key}_{program_name}.{'asm' if stage == 'asm' else ('vert' if stage == 'vert' else 'frag')}"
                (SRC / file_name).write_text(source)
                spirv_field = f', spirv_version = "{spirv}"' if spirv else ""
                out.append(f'    {{ name = "{program_name}", template = "spirv_assembly_early_fragment/{file_name}", stage = "{stage}"{spirv_field} }},')
            out += ["]", ""]
            table.append(
                f'    EarlyFragmentCase {{ group: "{group}", name: "{name}", key: "{key}", compare_op: vk::CompareOp::{COMPARE_OPS[compare]}, clear_depth: {clear_depth!r}_f32, early_and_late: {str(early_and_late).lower()}, size: {size} }},'
            )
            count += 1
    table.append("];")
    MANIFEST.write_text("\n".join(out))
    TABLE.write_text("\n".join(table) + "\n")
    print(count, "cases")


if __name__ == "__main__":
    main()
