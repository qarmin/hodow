#!/usr/bin/env python3
"""Writes shaders/manifest/spirv_assembly_cpp_asm.toml: the compute cases of dEQP-VK.spirv_assembly.instruction.compute whose whole shader is one string literal in the C++ of
the test (`const string shaderSource = "..." "...";`) and whose expected output is a few lines of host code.

The assembly is read out of the vendored upstream source (`upstream/external/...`) by finding the named function and concatenating the string literals of its
`shaderSource` the way the compiler does; the expectation is written here next to the case, from the C++ loops it replaces. They run as `AmberCase`s on the compute case of the
assembly groups, like the Amber scripts and the convert groups do: the output buffer starts as 0xff bytes and `checks` holds what it must hold afterwards.

Groups: pointer_parameter (vktSpvAsmPointerParameterTests.cpp, the five compute cases).

    python3 hodow_cts/scripts/gen_spirv_assembly_cpp_asm_manifest.py

A pure text generator: no spirv-as and no cargo.
"""

import json
import re
import struct
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
UPSTREAM = CRATE / "upstream" / "external" / "vulkancts" / "modules" / "vulkan" / "spirv_assembly"
OUT = CRATE / "shaders" / "manifest" / "spirv_assembly_cpp_asm.toml"
TEMPLATE = "spirv_assembly/source.asm"
VP_SSBO = "VariablePointerFeatures.variablePointersStorageBuffer"
VP_FULL = "VariablePointerFeatures.variablePointers"

LITERAL_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')
ESCAPES = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'"}


def unescape(text):
    return re.sub(r"\\(.)", lambda m: ESCAPES[m.group(1)], text)


def shader_source(path, function, variable="shaderSource"):
    """The string literals assigned to `variable` inside `function`, joined."""
    source = (UPSTREAM / path).read_text(encoding="utf-8")
    start = source.index(function + "(")
    assign = source.index(f"const string {variable} =", start)
    end = source.index(";\n", assign)
    return "".join(unescape(m.group(1)) for m in LITERAL_RE.finditer(source[assign:end]))


def floats(values):
    return b"".join(struct.pack("<f", value) for value in values)


class Case:
    def __init__(self, name, source, expected, workgroups, features=(), spirv_version=None):
        self.name, self.source, self.expected, self.workgroups, self.features, self.spirv_version = name, source, expected, workgroups, list(features), spirv_version


def pointer_parameter_cases():
    path = "vktSpvAsmPointerParameterTests.cpp"
    float_count = 128
    workgroup_expected = []
    for vec in range(float_count // 8):
        workgroup_expected += [float((vec + 1) % 16 + 5)] * 4
    for vec in range(float_count // 8):
        workgroup_expected += [float((vec + 1) % 16)] * 4
    return [
        Case("pointer_parameter/param_to_param", shader_source(path, "addComputePointerParamToParamTest"), floats([7.0] * float_count), (float_count, 1, 1)),
        Case("pointer_parameter/param_to_global", shader_source(path, "addComputePointerParamToGlobalTest"), floats([7.0] * float_count), (float_count, 1, 1)),
        Case(
            "pointer_parameter/buffer_memory", shader_source(path, "addComputePointerBufferMemoryTest"), floats([5.0] * (float_count // 2) + [2.0] * (float_count // 2)), (16, 1, 1),
            [VP_SSBO, "VK_KHR_variable_pointers"],
        ),
        Case(
            "pointer_parameter/buffer_memory_variable_pointers", shader_source(path, "addComputePointerBufferMemoryVariablePointersTest"),
            floats([5.0] * (float_count // 2) + [2.0] * (float_count // 2)), (16, 1, 1), [VP_SSBO, "VK_KHR_variable_pointers"],
        ),
        Case(
            "pointer_parameter/workgroup_memory_variable_pointers", shader_source(path, "addComputePointerWorkgroupMemoryVariablePointersTest"), floats(workgroup_expected), (1, 1, 1),
            [VP_FULL, "VK_KHR_variable_pointers", "VK_KHR_workgroup_memory_explicit_layout", "VK_KHR_spirv_1_4"], "spirv1.4",
        ),
    ]


def main():
    out = [
        "# Shader manifest for compute cases of dEQP-VK.spirv_assembly.instruction.compute whose shader is a string literal of the C++\n#\n"
        "# @generated by hodow_cts/scripts/gen_spirv_assembly_cpp_asm_manifest.py - do not hand-edit; the assembly is read out of the vendored upstream source.\n\n"
        'upstream_source = "external/vulkancts/modules/vulkan/spirv_assembly/vktSpvAsmPointerParameterTests.cpp"\n'
        'rust_module = "spirv_assembly/amber_tests"\n'
    ]
    count = 0
    for case in pointer_parameter_cases():
        const = "CPPASM_" + "".join(c if c.isalnum() else "_" for c in case.name).upper()
        filler = (b"\xff" * len(case.expected)).hex()
        params = (
            f'dispatch_x = {{ type = "u32", value = {case.workgroups[0]} }}, dispatch_y = {{ type = "u32", value = {case.workgroups[1]} }}, dispatch_z = {{ type = "u32", value = {case.workgroups[2]} }}, '
            f'buffers = {{ type = "str", value = "0:{filler}" }}, checks = {{ type = "str", value = "0:{case.expected.hex()}:{filler}" }}, '
            'tolerance_width = { type = "u32", value = 0 }, push_constants = { type = "str", value = "" }, spec_constants = { type = "str", value = "" }, '
            f'features = {{ type = "str", value = {json.dumps(",".join(case.features))} }}'
        )
        version = f', spirv_version = "{case.spirv_version}"' if case.spirv_version else ""
        out.append(
            f'\n[[case]]\nname = "{case.name}"\nrust_const = "{const}"\nrust_type = "AmberCase"\n'
            f'programs = [ {{ name = "compute", template = "{TEMPLATE}", stage = "asm"{version} }} ]\n'
            f"params = {{ {params} }}\n"
            f"derived = {{ source = {json.dumps(repr(case.source), ensure_ascii=False)} }}\n"
        )
        count += 1
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {count} cases")


if __name__ == "__main__":
    main()
