#!/usr/bin/env python3
"""Writes shaders/manifest/texture_shadow_cube_array.toml: the PROGRAM_CUBE_ARRAY_SHADOW programs of vktTextureTestUtil.cpp's initializePrograms, used by dEQP-VK.texture.shadow.cube_array.

    python3 hodow_cts/scripts/gen_texture_shadow_cube_array_manifest.py

Reuses the three templates of gen_texture_swizzle_manifest.py. The compute lookup is `texture(u_sampler, texCoord, u_ref)` (upstream's `textureGrad` on samplerCubeArrayShadow has no GLSL overload; the shadow cases render with the graphics pipeline only).

A pure text generator: no glslang and no cargo.
"""

import json
import sys
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_texture_swizzle_manifest as swz  # noqa: E402

OUT = CRATE / "shaders" / "manifest" / "texture_shadow_cube_array.toml"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "texture_shadow_cube_array"
SOURCE = "external/vulkancts/modules/vulkan/texture/vktTextureTestUtil.cpp"
LOOKUP = "vec4(texture(u_sampler, texCoord, u_ref), 0.0, 0.0, 1.0)"
SAMPLER = "samplerCubeArrayShadow"


def main():
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    for name in ("vert", "frag", "comp"):
        (TEMPLATE_DIR / f"src_{name}.glsl").write_text("${src_" + name + "}")
    tc = "vec4"
    sources = {
        "src_vert": swz.VERT.replace("{tctype}", tc),
        "src_frag": swz.FRAG.replace("{fragprec}", "mediump").replace("{tctype}", tc).replace("{sampler}", SAMPLER).replace("{swz}", "").replace("{lookup}", LOOKUP),
        "src_comp": swz.COMP.replace("{imgfmt}", "rgba8").replace("{tctype}", tc).replace("{sampler}", SAMPLER).replace("{swz}", "").replace("{lookup}", LOOKUP),
    }
    program = "CUBE_ARRAY_SHADOW"
    programs = ", ".join(
        f'{{ name = "{stage}_{program}", template = "texture_shadow_cube_array/{key}.glsl", stage = "{short}" }}'
        for stage, key, short in (("vertex", "src_vert", "vert"), ("fragment", "src_frag", "frag"), ("compute", "src_comp", "comp"))
    )
    derived = ", ".join(f"{key} = {json.dumps(repr(src))}" for key, src in sources.items())
    OUT.write_text(
        "# Shader manifest for dEQP-VK.texture.shadow.cube_array\n#\n"
        "# @generated by hodow_cts/scripts/gen_texture_shadow_cube_array_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "texture/shadow_tests"\n\n'
        f'[[case]]\nname = "cube_array_shadow"\nrust_const = "CUBE_ARRAY_SHADOW"\nrust_type = "SharedProgram"\nprograms = [{programs}]\nderived = {{ {derived} }}\n',
        encoding="utf-8",
    )
    print("wrote 1 case")


if __name__ == "__main__":
    main()
