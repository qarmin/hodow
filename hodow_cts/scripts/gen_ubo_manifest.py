#!/usr/bin/env python3
"""Writes the shader manifest and the case table of dEQP-VK.ubo.*

ubo_cases.py reproduces what UniformBlockCase::delayedInit builds (the block layout and the shader sources) for every case upstream's createTests registers.
Cases whose programs are identical share one manifest entry; `src/vkt/tests/ubo/ubo_cases.rs` lists every case with its blocks and the program it uses, which is all
`ubo/mod.rs` needs to upload zeroed blocks and run the shaders.

A pure text generator: no glslang and no cargo.
"""

import hashlib
import json
from pathlib import Path

import ubo_cases as uc

CRATE = Path(__file__).resolve().parent.parent
MANIFEST = CRATE / "shaders" / "manifest" / "ubo.toml"
TEMPLATE_DIR = CRATE / "shaders" / "src" / "ubo"
CASE_TABLE = CRATE / "src" / "vkt" / "tests" / "ubo" / "ubo_cases.rs"

HEADER = """# Shader manifest for dEQP-VK.ubo.*
#
# @generated by hodow_cts/scripts/gen_ubo_manifest.py - do not hand-edit.
#
# `UniformBlockCase::delayedInit`, one entry per distinct set of sources.

upstream_source = "external/vulkancts/modules/vulkan/ubo/vktUniformBlockCase.cpp"
rust_module = "ubo"
"""

REQUIREMENTS = [(uc.LAYOUT_16BIT_STORAGE, "REQ_16BIT_STORAGE", 1 << 0), (uc.LAYOUT_8BIT_STORAGE, "REQ_8BIT_STORAGE", 1 << 1), (uc.LAYOUT_STD430, "REQ_STD430", 1 << 2),
                (uc.LAYOUT_SCALAR, "REQ_SCALAR", 1 << 3), (uc.LAYOUT_DESCRIPTOR_INDEXING, "REQ_DESCRIPTOR_INDEXING", 1 << 4)]


def py(value) -> str:
    return json.dumps(repr(value))


def main() -> None:
    TEMPLATE_DIR.mkdir(parents=True, exist_ok=True)
    templates = {"vert": ("src_vert", "vert"), "frag": ("src_frag", "frag"), "comp": ("src_comp", "comp")}
    for name, _ in templates.values():
        (TEMPLATE_DIR / f"{name}.glsl").write_text("${" + name + "}")

    cases = uc.all_cases()
    by_signature: dict[tuple, str] = {}
    entries = []
    rows = []
    for case in cases:
        signature = tuple(sorted((name, stage, src) for name, (stage, src) in case.programs.items()))
        if signature not in by_signature:
            digest = hashlib.sha1(repr(signature).encode()).hexdigest()[:12]
            const = f"UB_{digest.upper()}"
            by_signature[signature] = const
            programs = ", ".join(f'{{ name = "{name}", template = "ubo/{templates[name][0]}.glsl", stage = "{stage}" }}' for name, stage, _ in signature)
            derived = ", ".join(f"{templates[name][0]} = {py(src)}" for name, _, src in signature)
            entries.append(f'\n[[case]]\nname = "ub_{digest}"\nrust_const = "{const}"\nrust_type = "SharedProgram"\nprograms = [{programs}]\nderived = {{ {derived} }}\n')
        requirements = 0
        for flag, _, bit in REQUIREMENTS:
            if case.uses(flag):
                requirements |= bit
        blocks = ", ".join(f"BlockDef {{ binding: {b.binding_ndx}, instance: {b.instance_ndx}, size: {b.size} }}" for b in case.layout.blocks)
        rows.append(
            f'    UboCaseDef {{ name: "{".".join(case.path)}", per_block_buffer: {str(case.buffer_mode == uc.BUFFERMODE_PER_BLOCK).lower()}, compute: {str(case.is_compute).lower()}, '
            f'requirements: {requirements}, unsized_array: {str(case.unsized).lower()}, blocks: &[{blocks}], programs: &{by_signature[signature]} }},'
        )

    MANIFEST.write_text(HEADER + "".join(entries))

    lines = [
        "// @generated by hodow_cts/scripts/gen_ubo_manifest.py - do not hand-edit.",
        "//",
        "// Every case of dEQP-VK.ubo.* in upstream's order: its blocks as the reference layout computes them, and the programs of the manifest it uses.",
        "",
        "use crate::generated::shaders::ubo::*;",
        "use crate::vkt::tests::ubo::{BlockDef, UboCaseDef};",
        "",
    ]
    for _, name, bit in REQUIREMENTS:
        lines.append(f"pub const {name}: u32 = {bit};")
    lines += ["", "pub static UBO_CASES: &[UboCaseDef] = &["] + rows + ["];"]
    CASE_TABLE.parent.mkdir(parents=True, exist_ok=True)
    CASE_TABLE.write_text("\n".join(lines) + "\n")
    print(f"{len(cases)} cases, {len(entries)} program sets -> {MANIFEST}")


if __name__ == "__main__":
    main()
