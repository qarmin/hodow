#!/usr/bin/env python3
"""Writes shaders/manifest/texture_mipmap_misc.toml: dEQP-VK.texture.mipmap.cubemap.misc.projected_derivatives (MiscTestCase::initPrograms of vktTextureMipmapTests.cpp, graphics half).

    python3 hodow_cts/scripts/gen_texture_mipmap_misc_manifest.py

A pure text generator: no glslang and no cargo.
"""

import json
import re
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "shaders" / "manifest" / "texture_mipmap_misc.toml"
SOURCE = "external/vulkancts/modules/vulkan/texture/vktTextureMipmapTests.cpp"


def cpp_string(text, var):
    start = text.index("std::string " + var + " = ")
    end = text.index(";\n", start)
    return "".join(json.loads('"' + piece + '"') for piece in re.findall(r'"((?:[^"\\]|\\.)*)"', text[start:end]))


def main():
    text = (CRATE / "upstream" / SOURCE).read_text(encoding="utf-8")
    start = text.index("class MiscTestCase")
    body = text[start:]
    vert = cpp_string(body, "vert")
    frag = cpp_string(body, "frag")
    out = (
        "# Shader manifest for dEQP-VK.texture.mipmap.cubemap.misc\n#\n"
        "# @generated by hodow_cts/scripts/gen_texture_mipmap_misc_manifest.py - do not hand-edit.\n\n"
        f'upstream_source = "{SOURCE}"\nrust_module = "texture/mipmap_tests"\n\n'
        '[[case]]\nname = "projected_derivatives"\nrust_const = "PROJECTED_DERIVATIVES"\nrust_type = "SharedProgram"\n'
        'programs = [{ name = "vertex_CUBE_FLOAT", template = "texture_mipmap_misc/src_vert.glsl", stage = "vert" }, '
        '{ name = "fragment_CUBE_FLOAT", template = "texture_mipmap_misc/src_frag.glsl", stage = "frag" }]\n'
        f"derived = {{ src_vert = {json.dumps(repr(vert))}, src_frag = {json.dumps(repr(frag))} }}\n"
    )
    OUT.write_text(out, encoding="utf-8")
    print("wrote 1 case")


if __name__ == "__main__":
    main()
