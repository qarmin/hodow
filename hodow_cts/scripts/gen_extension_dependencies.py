#!/usr/bin/env python3
"""Writes src/vkt/tests/info/extension_dependencies.rs from the generated vkApiExtensionDependencyInfo.inl and vkEntryPointValidation.inl of the pinned upstream.

The C++ functions `check_<extension>(v, vIEP, vDEP)` are boolean expressions over `isSupported(<instance|device extensions>, "<name>")` and
`isCompatible(major, minor, v)`; they are translated one to one (`inst`/`dev` are the extension name lists, `is_compatible` is upstream's function).

Run from hodow_cts/:  python3 scripts/gen_extension_dependencies.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = ROOT / "upstream" / "external" / "vulkancts" / "framework" / "vulkan" / "generated" / "vulkan"
OUT = ROOT / "src" / "vkt" / "tests" / "info" / "extension_dependencies.rs"


def translate_expression(text):
    text = re.sub(r'isSupported\(vIEP, ("[^"]*")\)', r"is_supported(inst, \1)", text)
    text = re.sub(r'isSupported\(vDEP, ("[^"]*")\)', r"is_supported(dev, \1)", text)
    text = re.sub(r"isCompatible\((\d+), (\d+), v\)", r"is_compatible(\1, \2, v)", text)
    return text


def translate_function(body):
    lines = []
    pending_if = None
    for raw in body.splitlines():
        line = raw.strip()
        if not line or line.startswith("//") or line.startswith("DE_UNREF"):
            continue
        if line.startswith("if ("):
            pending_if = translate_expression(line[len("if (") : -1])
            continue
        match = re.fullmatch(r"return (.*);", line)
        assert match, line
        expression = match.group(1)
        if pending_if is not None:
            assert expression == "true", line
            lines.append(f"    if {pending_if} {{")
            lines.append("        return true;")
            lines.append("    }")
            pending_if = None
        else:
            lines.append(f"    {translate_expression(expression)}")
    assert pending_if is None
    return lines


def main():
    text = (GENERATED / "vkApiExtensionDependencyInfo.inl").read_text()
    functions = re.findall(r"bool (check_\w+)\(const tcu::UVec2& v, const ExtPropVect& vIEP, const ExtPropVect& vDEP\)\n\{\n(.*?)\n\}\n", text, re.S)
    tables = {}
    for kind in ("instanceExtensionDependencies", "deviceExtensionDependencies"):
        block = re.search(r"static const DependencyCheckVect " + kind + r"\s*\{(.*?)\n\};", text, re.S).group(1)
        tables[kind] = re.findall(r'std::make_pair\("(\w+)",\s*&(check_\w+)\)', block)

    versions = re.findall(r"std::make_tuple\(\d+, (\d+), (\d+), (\d+)\)", re.search(r"releasedApiVersions\[\]\s*=\s*\{(.*?)\};", text, re.S).group(1))

    entry_points = (GENERATED / "vkEntryPointValidation.inl").read_text()
    inst_ext_device_fun = []
    for name, body in re.findall(r'\{ "(\w+)",\s*\{(.*?)\}\s*\}', entry_points, re.S):
        inst_ext_device_fun.append((name, re.findall(r'"(\w+)"', body)))

    out = [
        "// @generated by hodow_cts/scripts/gen_extension_dependencies.py from the generated vkApiExtensionDependencyInfo.inl and vkEntryPointValidation.inl - do not hand-edit.",
        "",
        "#![allow(unused_parens)]",
        "",
        "pub type IsSupportedFun = fn((u32, u32), &[String], &[String]) -> bool;",
        "",
        "/// `isCompatible`: the tested API version is at least major.minor",
        "fn is_compatible(major: u32, minor: u32, tested: (u32, u32)) -> bool {",
        "    if major == tested.0 {",
        "        return minor <= tested.1;",
        "    }",
        "    major < tested.0",
        "}",
        "",
        "fn is_supported(extensions: &[String], name: &str) -> bool {",
        "    extensions.iter().any(|extension| extension == name)",
        "}",
        "",
        "/// `releasedApiVersions`, newest first",
        "pub const RELEASED_API_VERSIONS: [(u32, u32); %d] = [%s];" % (len(versions), ", ".join(f"({a}, {b})" for _, a, b in versions)),
        "",
        "/// `instExtDeviceFun`: the device level entry points an instance extension adds",
        "pub const INSTANCE_EXTENSION_DEVICE_FUNCTIONS: &[(&str, &[&str])] = &[",
    ]
    for name, functions_of in inst_ext_device_fun:
        out.append(f'    ("{name}", &[{", ".join(chr(34) + f + chr(34) for f in functions_of)}]),')
    out += ["];", ""]

    for name, body in functions:
        out.append("#[allow(unused_variables)]")
        out.append(f"fn {name.lower()}(v: (u32, u32), inst: &[String], dev: &[String]) -> bool {{")
        out += translate_function(body)
        out.append("}")
        out.append("")

    for kind, const in (("instanceExtensionDependencies", "INSTANCE_EXTENSION_DEPENDENCIES"), ("deviceExtensionDependencies", "DEVICE_EXTENSION_DEPENDENCIES")):
        out.append(f"/// `{kind}`")
        out.append(f"pub const {const}: &[(&str, IsSupportedFun)] = &[")
        for extension, function in tables[kind]:
            out.append(f'    ("{extension}", {function.lower()}),')
        out += ["];", ""]
    OUT.write_text("\n".join(out))
    print(len(functions), "functions,", len(tables["instanceExtensionDependencies"]), "instance and", len(tables["deviceExtensionDependencies"]), "device entries,", len(inst_ext_device_fun), "extensions with device entry points")


if __name__ == "__main__":
    main()
