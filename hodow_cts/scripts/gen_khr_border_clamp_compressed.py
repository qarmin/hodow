#!/usr/bin/env python3
"""Emit src/generated/khr_border_clamp_compressed.rs: the two ETC2 blobs of esextcTextureBorderClampCompressedResources.hpp."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
hpp = (root / "tmp/glcts-src/external/openglcts/modules/glesext/texture_border_clamp/esextcTextureBorderClampCompressedResources.hpp").read_text()

lines = ["// Generated by hodow_cts/scripts/gen_khr_border_clamp_compressed.py - do not edit.", ""]
for cname, name in (("COMPRESSED_IMAGE_DATA_2D", "compressed_image_data_2D"), ("COMPRESSED_IMAGE_DATA_2D_ARRAY", "compressed_image_data_2D_array")):
    m = re.search(r"unsigned char %s\[\] = \{(.*?)\};" % name, hpp, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    vals = [t.strip() for t in body.split(",") if t.strip()]
    assert all(re.fullmatch(r"0x[0-9a-f]{2}", v) for v in vals), name
    lines.append(f"pub static {cname}: [u8; {len(vals)}] = [")
    for i in range(0, len(vals), 16):
        lines.append("    " + ", ".join(vals[i:i + 16]) + ",")
    lines.append("];")
    lines.append("")
    print(name, len(vals), file=sys.stderr)
(root / "hodow_cts/src/generated/khr_border_clamp_compressed.rs").write_text("\n".join(lines))
