#!/usr/bin/env python3
"""Writes the shaders of dEQP-VK.glsl.bfloat16.constant.* (vktShaderBFloat16ConstantTests.cpp, the `initPrograms` of the compute, vertex and fragment cases) and their manifest.

A pure text generator: no glslang and no cargo.   Run from hodow_cts/:  python3 scripts/gen_bfloat16_constant_manifest.py   (then `just cts-shaders`)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "shaders" / "src" / "bfloat16_constant"
MANIFEST = ROOT / "shaders" / "manifest" / "shader_bfloat16_constant.toml"

TYPES = {
    "bf16": ("GL_EXT_bfloat16", "bfloat16_t", "bf16vec4"),
    "fe5m2": ("GL_EXT_float_e5m2", "floate5m2_t", "fe5m2vec4"),
    "fe4m3": ("GL_EXT_float_e4m3", "floate4m3_t", "fe4m3vec4"),
}

COMPUTE = """#version 450
#extension ${EXTENSION}: require
layout(binding=0) buffer InBufferX { ${VEC4} x[]; };
layout(binding=1) buffer InBufferY { ${VEC4} y[]; };
layout(binding=2) buffer OutBuffer { ${VEC4} z[]; };
layout(local_size_x_id = 0, local_size_y_id = 2, local_size_z_id = 4) in;
// local_size_x_id
layout(constant_id = 1)  const ${FLOAT_TYPE} c1 = ${FLOAT_TYPE}(0.0);
// local_size_y_id
layout(constant_id = 3)  const ${FLOAT_TYPE} c3 = ${FLOAT_TYPE}(0.0);
// local_size_z_id
layout(constant_id = 5)  const ${FLOAT_TYPE} c5 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 6)  const ${FLOAT_TYPE} c6 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 7)  const float c7 = 0.0;
layout(constant_id = 8)  const ${FLOAT_TYPE} c8 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 9)  const ${FLOAT_TYPE} c9 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 10) const ${FLOAT_TYPE} c10 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 11) const float c11 = 0.0;
const ${FLOAT_TYPE} c12 = ${FLOAT_TYPE}(c11);
const float c13 = float(c12);
void main() {
    z[0].x = ${FLOAT_TYPE}(float(gl_WorkGroupSize.x));
    z[0].y = ${FLOAT_TYPE}(c1);
    z[0].z = ${FLOAT_TYPE}(float(gl_WorkGroupSize.y));
    z[0].w = ${FLOAT_TYPE}(c3);
    z[1].x = ${FLOAT_TYPE}(float(gl_WorkGroupSize.z));
    z[1].y = ${FLOAT_TYPE}(c5);
    z[1].z = ${FLOAT_TYPE}(c6);
    z[1].w = ${FLOAT_TYPE}(c7);
    z[2].x = ${FLOAT_TYPE}(c8);
    z[2].y = ${FLOAT_TYPE}(c9);
    z[2].z = ${FLOAT_TYPE}(c10);
    z[2].w = ${FLOAT_TYPE}(c13);
}
"""

CONSTANTS = """layout(constant_id = 0)  const float c0 = 0.0;
layout(constant_id = 1)  const ${FLOAT_TYPE} c1 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 2)  const float c2 = 0.0;
layout(constant_id = 3)  const ${FLOAT_TYPE} c3 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 4)  const float c4 = 0.0;
layout(constant_id = 5)  const ${FLOAT_TYPE} c5 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 6)  const ${FLOAT_TYPE} c6 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 7)  const float c7 = 0.0;
layout(constant_id = 8)  const ${FLOAT_TYPE} c8 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 9)  const ${FLOAT_TYPE} c9 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 10) const ${FLOAT_TYPE} c10 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 11) const float c11 = 0.0;
layout(constant_id = 12) const ${FLOAT_TYPE} c12 = ${FLOAT_TYPE}(0.0);
layout(constant_id = 13) const ${FLOAT_TYPE} c13 = ${FLOAT_TYPE}(0.0);
"""

COPY = "".join(f"    z[{i}]{' ' if i < 10 else ''} = ${{VEC4}}(${{FLOAT_TYPE}}(c{i}));\n" for i in range(14))

HEADER = """#version 450
#extension ${EXTENSION}: require
layout(binding=0) buffer InBufferX { ${VEC4} x[]; };
layout(binding=1) buffer InBufferY { ${VEC4} y[]; };
layout(binding=2) buffer OutBuffer { ${VEC4} z[]; };
"""

VERT = (
    HEADER
    + CONSTANTS
    + "void main() {\n"
    + COPY
    + "\n    gl_Position = vec4(float(z[gl_VertexIndex * 2].x), float(z[gl_VertexIndex * 2 + 1].y), 0, 1);\n}\n"
)

FRAG_OF_VERT = "#version 450\nlayout(location = 0) out vec4 color;\nvoid main() {\n    color = vec4(1);\n}\n"

FRAG = (
    HEADER
    + "layout(location = 0) out vec4 color;\n"
    + CONSTANTS
    + "void copy() {\n"
    + COPY
    + "}\nvoid main() {\n    copy();\n    const float c = float(gl_PrimitiveID + 1);\n    color = vec4(c, c, c, 1.0);\n}\n"
)

VERT_OF_FRAG = "#version 450\nlayout(location = 0) in vec4 pos;\nvoid main() {\n    gl_Position = pos;\n}\n"


def specialize(text, type_key):
    ext, scalar, vec4 = TYPES[type_key]
    return text.replace("${EXTENSION}", ext).replace("${FLOAT_TYPE}", scalar).replace("${VEC4}", vec4)


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    out = [
        "# Shader manifest for dEQP-VK.glsl.bfloat16.constant.*",
        "#",
        "# @generated by hodow_cts/scripts/gen_bfloat16_constant_manifest.py - do not hand-edit.",
        "",
        'upstream_source = "external/vulkancts/modules/vulkan/shaderexecutor/vktShaderBFloat16ConstantTests.cpp"',
        'rust_module = "glsl/bfloat16_constant_tests"',
        "",
    ]
    for type_key in TYPES:
        for stage in ("compute", "vertex", "fragment"):
            name = f"{stage}{type_key}"
            if stage == "compute":
                files = [("compute", "comp", specialize(COMPUTE, type_key))]
            elif stage == "vertex":
                files = [("vert", "vert", specialize(VERT, type_key)), ("frag", "frag", FRAG_OF_VERT)]
            else:
                files = [("vert", "vert", VERT_OF_FRAG), ("frag", "frag", specialize(FRAG, type_key))]
            programs = []
            for program_name, ext, source in files:
                (SRC / f"{name}.{ext}").write_text(source)
                programs.append(f'{{ name = "{program_name}", template = "bfloat16_constant/{name}.{ext}", stage = "{ext}" }}')
            out += ["[[case]]", f'name = "{name}"', f'rust_const = "{name.upper()}"', 'rust_type = "SharedProgram"', f"programs = [{', '.join(programs)}]", ""]
    MANIFEST.write_text("\n".join(out))


main()
