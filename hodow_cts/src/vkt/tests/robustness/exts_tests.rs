#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Stage {
    Compute,
    Vertex,
    Fragment,
    Raygen,
}

impl Stage {
    fn key(self) -> &'static str {
        match self {
            Stage::Compute => "comp",
            Stage::Vertex => "vert",
            Stage::Fragment => "frag",
            Stage::Raygen => "rgen",
        }
    }
}

/// The descriptor types the cases bind, with upstream's phony `VERTEX_ATTRIBUTE_FETCH`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Desc {
    UniformBuffer,
    StorageBuffer,
    UniformBufferDynamic,
    StorageBufferDynamic,
    UniformTexelBuffer,
    StorageTexelBuffer,
    StorageImage,
    CombinedImageSampler,
    VertexAttributeFetch,
}

impl Desc {
    pub fn descriptor_type(self) -> Option<vk::DescriptorType> {
        match self {
            Desc::UniformBuffer => Some(vk::DescriptorType::UNIFORM_BUFFER),
            Desc::StorageBuffer => Some(vk::DescriptorType::STORAGE_BUFFER),
            Desc::UniformBufferDynamic => Some(vk::DescriptorType::UNIFORM_BUFFER_DYNAMIC),
            Desc::StorageBufferDynamic => Some(vk::DescriptorType::STORAGE_BUFFER_DYNAMIC),
            Desc::UniformTexelBuffer => Some(vk::DescriptorType::UNIFORM_TEXEL_BUFFER),
            Desc::StorageTexelBuffer => Some(vk::DescriptorType::STORAGE_TEXEL_BUFFER),
            Desc::StorageImage => Some(vk::DescriptorType::STORAGE_IMAGE),
            Desc::CombinedImageSampler => Some(vk::DescriptorType::COMBINED_IMAGE_SAMPLER),
            Desc::VertexAttributeFetch => None,
        }
    }

    pub fn is_ubo(self) -> bool {
        matches!(self, Desc::UniformBuffer | Desc::UniformBufferDynamic)
    }

    pub fn is_ssbo(self) -> bool {
        matches!(self, Desc::StorageBuffer | Desc::StorageBufferDynamic)
    }

    pub fn is_dynamic(self) -> bool {
        matches!(self, Desc::UniformBufferDynamic | Desc::StorageBufferDynamic)
    }

    pub fn is_image(self) -> bool {
        matches!(self, Desc::StorageImage | Desc::CombinedImageSampler)
    }

    /// `supportsStores`
    pub fn supports_stores(self) -> bool {
        matches!(
            self,
            Desc::StorageBufferDynamic | Desc::StorageBuffer | Desc::StorageTexelBuffer | Desc::StorageImage
        )
    }

    fn key(self) -> &'static str {
        match self {
            Desc::UniformBuffer => "ubo",
            Desc::StorageBuffer => "ssbo",
            Desc::UniformBufferDynamic => "ubod",
            Desc::StorageBufferDynamic => "ssbod",
            Desc::UniformTexelBuffer => "utb",
            Desc::StorageTexelBuffer => "stb",
            Desc::StorageImage => "simg",
            Desc::CombinedImageSampler => "cis",
            Desc::VertexAttributeFetch => "vaf",
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum PipelineRobustnessCase {
    Disabled,
    EnabledMonolithic,
    EnabledFastGpl,
    EnabledOptimizedGpl,
}

impl PipelineRobustnessCase {
    /// `getConstructionTypeFromRobustnessCase`
    pub fn construction_type(self) -> PipelineConstructionType {
        match self {
            PipelineRobustnessCase::EnabledFastGpl => PipelineConstructionType::FastLinkedLibrary,
            PipelineRobustnessCase::EnabledOptimizedGpl => PipelineConstructionType::LinkTimeOptimizedLibrary,
            _ => PipelineConstructionType::Monolithic,
        }
    }

    /// `getGPLSuffix`
    fn suffix(self) -> &'static str {
        match self {
            PipelineRobustnessCase::EnabledFastGpl => "_fast_gpl",
            PipelineRobustnessCase::EnabledOptimizedGpl => "_optimized_gpl",
            _ => "",
        }
    }
}

/// Scalar element type of the `GL_EXT_long_vector` cases.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum LongVectorScalar {
    F32,
    I32,
    U32,
    F16,
}

impl LongVectorScalar {
    pub fn size_bytes(self) -> u32 {
        match self {
            LongVectorScalar::F16 => 2,
            _ => 4,
        }
    }

    fn key(self) -> &'static str {
        match self {
            LongVectorScalar::F32 => "f32",
            LongVectorScalar::I32 => "i32",
            LongVectorScalar::U32 => "u32",
            LongVectorScalar::F16 => "f16",
        }
    }
}

/// `CaseDef`
#[derive(Clone, Copy, Debug)]
pub struct CaseDef {
    pub format: vk::Format,
    pub stage: Stage,
    pub desc: Desc,
    pub view_type: vk::ImageViewType,
    pub samples: vk::SampleCountFlags,
    /// `~0U` (as an int, -1) is the null descriptor
    pub buffer_len: i32,
    pub unroll: bool,
    pub vol: bool,
    pub null_descriptor: bool,
    pub use_template: bool,
    pub format_qualifier: bool,
    pub push_descriptor: bool,
    pub test_robustness2: bool,
    pub pipeline_robustness_case: PipelineRobustnessCase,
    pub image_dim: [u32; 3],
    pub read_only: bool,
    pub uses_64bit_indexing: bool,
    pub use_compute_queue: bool,
    /// 0 = legacy path
    pub long_vector_components: u32,
    pub long_vector_scalar: Option<LongVectorScalar>,
}

impl CaseDef {
    pub fn is_long_vector(&self) -> bool {
        self.long_vector_components != 0
    }

    /// `needsScalarBlockLayout`
    pub fn needs_scalar_block_layout(&self) -> bool {
        matches!(
            self.desc,
            Desc::UniformBufferDynamic | Desc::UniformBuffer | Desc::StorageBufferDynamic | Desc::StorageBuffer
        )
    }

    /// `needsPipelineRobustness`
    pub fn needs_pipeline_robustness(&self) -> bool {
        self.pipeline_robustness_case != PipelineRobustnessCase::Disabled
    }

    pub fn sample_count(&self) -> u32 {
        self.samples.bits()
    }
}

pub fn format_is_r64(format: vk::Format) -> bool {
    matches!(format, vk::Format::R64_SINT | vk::Format::R64_UINT)
}

pub fn format_is_float(format: vk::Format) -> bool {
    matches!(
        format,
        vk::Format::R32_SFLOAT | vk::Format::R32G32_SFLOAT | vk::Format::R32G32B32A32_SFLOAT
    )
}

pub fn format_is_signed_int(format: vk::Format) -> bool {
    matches!(
        format,
        vk::Format::R32_SINT | vk::Format::R64_SINT | vk::Format::R32G32_SINT | vk::Format::R32G32B32A32_SINT
    )
}

/// `tcu::getPixelSize` of the formats the cases use
pub fn format_pixel_size(format: vk::Format) -> u32 {
    match format {
        vk::Format::R32_SINT | vk::Format::R32_UINT | vk::Format::R32_SFLOAT => 4,
        vk::Format::R64_SINT
        | vk::Format::R64_UINT
        | vk::Format::R32G32_SINT
        | vk::Format::R32G32_UINT
        | vk::Format::R32G32_SFLOAT => 8,
        _ => 16,
    }
}

/// `tcu::getChannelSize` of the channel type
pub fn format_channel_size(format: vk::Format) -> u32 {
    if format_is_r64(format) { 8 } else { 4 }
}

fn format_key(format: vk::Format) -> &'static str {
    match format {
        vk::Format::R32_SINT => "r32i",
        vk::Format::R32_UINT => "r32ui",
        vk::Format::R32_SFLOAT => "r32f",
        vk::Format::R32G32_SINT => "rg32i",
        vk::Format::R32G32_UINT => "rg32ui",
        vk::Format::R32G32_SFLOAT => "rg32f",
        vk::Format::R32G32B32A32_SINT => "rgba32i",
        vk::Format::R32G32B32A32_UINT => "rgba32ui",
        vk::Format::R32G32B32A32_SFLOAT => "rgba32f",
        vk::Format::R64_SINT => "r64i",
        _ => "r64ui",
    }
}

fn view_key(view_type: vk::ImageViewType) -> &'static str {
    match view_type {
        vk::ImageViewType::_1D => "1d",
        vk::ImageViewType::_2D => "2d",
        vk::ImageViewType::_3D => "3d",
        vk::ImageViewType::CUBE => "cube",
        vk::ImageViewType::_1D_ARRAY => "1d_array",
        vk::ImageViewType::_2D_ARRAY => "2d_array",
        _ => "cube_array",
    }
}

/// The identity of the programs a case compiles, `shader_key` of scripts/robustness_exts_cases.py.
pub fn shader_key(c: &CaseDef) -> String {
    if let Some(scalar) = c.long_vector_scalar {
        return format!(
            "lv.{}.w{}.{}.l{}.u{}.o{}",
            scalar.key(),
            c.long_vector_components,
            c.desc.key(),
            c.buffer_len,
            u8::from(c.unroll),
            u8::from(c.read_only)
        );
    }
    let len = if c.null_descriptor {
        "null".to_string()
    } else {
        c.buffer_len.to_string()
    };
    format!(
        "{}.{}.{}.{}.s{}.l{}.u{}v{}f{}r{}o{}",
        format_key(c.format),
        c.stage.key(),
        c.desc.key(),
        view_key(c.view_type),
        c.sample_count(),
        len,
        u8::from(c.unroll),
        u8::from(c.vol),
        u8::from(c.format_qualifier),
        u8::from(c.test_robustness2),
        u8::from(c.read_only)
    )
}

fn programs_for(c: &CaseDef) -> BinaryCollection {
    let key = shader_key(c);
    match PROGRAM_TABLE.binary_search_by(|(k, _)| (*k).cmp(key.as_str())) {
        Ok(index) => PROGRAM_TABLE[index].1.programs,
        Err(_) => BinaryCollection::new(&[] as &'static [ProgramBinary]),
    }
}

/// `RobustnessExtsTestCase`
struct ExtsTestCase {
    name: String,
    data: CaseDef,
    programs: BinaryCollection,
}

impl TestCase for ExtsTestCase {
    fn name(&self) -> &str {
        &self.name
    }

    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        check_support(context, &self.data)
    }

    fn programs(&self) -> BinaryCollection {
        self.programs
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(ExtsInstance::new(context, self.data))
    }
}

fn not_supported(message: &str) -> Result<(), TestError> {
    Err(TestError::NotSupported(message.to_string()))
}

/// `FormatProperties3` with the fallback `Context::getFormatProperties` makes: the device features say whether the formats can be accessed without a qualifier.
fn format_properties3(context: &Context<'_>, format: vk::Format) -> vk::FormatProperties3 {
    let mut p = vk::FormatProperties3::default();
    let supported =
        context.api_version() >= (1, 3, 0) || context.is_device_functionality_supported("VK_KHR_format_feature_flags2");
    if supported {
        let mut properties = vk::FormatProperties2::builder().push_next(&mut p);
        unsafe {
            context.get_instance().get_physical_device_format_properties2(
                context.get_physical_device(),
                format,
                &mut properties,
            )
        };
        return p;
    }
    let properties = unsafe {
        context
            .get_instance()
            .get_physical_device_format_properties(context.get_physical_device(), format)
    };
    let features = context.get_device_features();
    let mut extra = vk::FormatFeatureFlags2::empty();
    if features.shader_storage_image_read_without_format != vk::FALSE {
        extra |= vk::FormatFeatureFlags2::STORAGE_READ_WITHOUT_FORMAT;
    }
    if features.shader_storage_image_write_without_format != vk::FALSE {
        extra |= vk::FormatFeatureFlags2::STORAGE_WRITE_WITHOUT_FORMAT;
    }
    p.optimal_tiling_features =
        vk::FormatFeatureFlags2::from_bits_truncate(u64::from(properties.optimal_tiling_features.bits())) | extra;
    p.buffer_features =
        vk::FormatFeatureFlags2::from_bits_truncate(u64::from(properties.buffer_features.bits())) | extra;
    p
}

/// `RobustnessExtsTestCase::checkSupport`
fn check_support(context: &Context<'_>, d: &CaseDef) -> Result<(), TestError> {
    let instance = context.get_instance();
    let physical_device = context.get_physical_device();

    check_pipeline_construction_requirements(context, d.pipeline_robustness_case.construction_type())?;

    // robustness2 and image robustness are always disabled in the default device but they may be available
    let mut robustness2_features = vk::PhysicalDeviceRobustness2FeaturesEXT::default();
    let mut image_robustness_features = vk::PhysicalDeviceImageRobustnessFeatures::default();
    let mut scalar_layout_features = vk::PhysicalDeviceScalarBlockLayoutFeatures::default();
    let mut pipeline_robustness_features = vk::PhysicalDevicePipelineRobustnessFeatures::default();
    let mut shader_64bit_indexing_features = vk::PhysicalDeviceShader64BitIndexingFeaturesEXT::default();
    let mut long_vector_features = vk::PhysicalDeviceShaderLongVectorFeaturesEXT::default();
    let mut float16_int8_features = vk::PhysicalDeviceShaderFloat16Int8Features::default();
    let mut storage16_features = vk::PhysicalDevice16BitStorageFeatures::default();
    let mut features2 = vk::PhysicalDeviceFeatures2::default();
    let mut chain: Vec<*mut std::ffi::c_void> = Vec::new();
    if context.is_device_functionality_supported("VK_EXT_scalar_block_layout") {
        chain.push((&raw mut scalar_layout_features).cast());
    }
    if context.is_device_functionality_supported("VK_EXT_image_robustness") {
        chain.push((&raw mut image_robustness_features).cast());
    }
    if context.is_device_functionality_supported("VK_KHR_robustness2")
        || context.is_device_functionality_supported("VK_EXT_robustness2")
    {
        chain.push((&raw mut robustness2_features).cast());
    }
    if context.is_device_functionality_supported("VK_EXT_pipeline_robustness") {
        chain.push((&raw mut pipeline_robustness_features).cast());
    }
    if context.is_device_functionality_supported("VK_EXT_shader_64bit_indexing") {
        chain.push((&raw mut shader_64bit_indexing_features).cast());
    }
    if context.is_device_functionality_supported("VK_EXT_shader_long_vector") {
        chain.push((&raw mut long_vector_features).cast());
    }
    if context.is_device_functionality_supported("VK_KHR_shader_float16_int8") {
        chain.push((&raw mut float16_int8_features).cast());
    }
    if context.is_device_functionality_supported("VK_KHR_16bit_storage") {
        chain.push((&raw mut storage16_features).cast());
    }
    // every struct starts with sType and pNext, so the chain is linked through the common header
    let mut next: *mut std::ffi::c_void = std::ptr::null_mut();
    for &ptr in chain.iter().rev() {
        unsafe { (*ptr.cast::<vk::BaseOutStructure>()).next = next.cast() };
        next = ptr;
    }
    features2.next = next;
    unsafe { instance.get_physical_device_features2(physical_device, &mut features2) };

    if format_is_r64(d.format) {
        context.require_device_functionality("VK_EXT_shader_image_atomic_int64")?;

        let format_properties = unsafe { instance.get_physical_device_format_properties(physical_device, d.format) };
        let format_properties3 = format_properties3(context, d.format);

        match d.desc {
            Desc::UniformTexelBuffer => {
                if !format_properties
                    .buffer_features
                    .contains(vk::FormatFeatureFlags::UNIFORM_TEXEL_BUFFER)
                {
                    return not_supported("VK_FORMAT_FEATURE_UNIFORM_TEXEL_BUFFER_BIT is not supported");
                }
            }
            Desc::StorageTexelBuffer => {
                if !format_properties
                    .buffer_features
                    .contains(vk::FormatFeatureFlags::STORAGE_TEXEL_BUFFER)
                {
                    return not_supported("VK_FORMAT_FEATURE_STORAGE_TEXEL_BUFFER_BIT is not supported");
                }
                if !d.format_qualifier
                    && !format_properties3
                        .buffer_features
                        .contains(vk::FormatFeatureFlags2::STORAGE_READ_WITHOUT_FORMAT)
                {
                    return not_supported("VK_FORMAT_FEATURE_2_STORAGE_READ_WITHOUT_FORMAT_BIT is not supported");
                }
            }
            Desc::StorageImage => {
                if !d.format_qualifier
                    && !format_properties3
                        .buffer_features
                        .contains(vk::FormatFeatureFlags2::STORAGE_READ_WITHOUT_FORMAT)
                {
                    return not_supported("VK_FORMAT_FEATURE_2_STORAGE_READ_WITHOUT_FORMAT_BIT is not supported");
                }
            }
            Desc::VertexAttributeFetch => {
                if !format_properties
                    .buffer_features
                    .contains(vk::FormatFeatureFlags::VERTEX_BUFFER)
                {
                    return not_supported("VK_FORMAT_FEATURE_VERTEX_BUFFER_BIT is not supported");
                }
            }
            Desc::CombinedImageSampler
                if !format_properties
                    .optimal_tiling_features
                    .contains(vk::FormatFeatureFlags::SAMPLED_IMAGE) =>
            {
                return not_supported("VK_FORMAT_FEATURE_VERTEX_BUFFER_BIT is not supported");
            }
            _ => {}
        }

        if d.samples != vk::SampleCountFlags::_1
            && !format_properties
                .optimal_tiling_features
                .contains(vk::FormatFeatureFlags::SAMPLED_IMAGE)
        {
            return not_supported("VK_FORMAT_FEATURE_SAMPLED_IMAGE_BIT is not supported");
        }
    }

    if d.needs_scalar_block_layout() && scalar_layout_features.scalar_block_layout == vk::FALSE {
        return not_supported("Scalar block layout not supported");
    }

    if d.stage == Stage::Vertex && features2.features.vertex_pipeline_stores_and_atomics == vk::FALSE {
        return not_supported("Vertex pipeline stores and atomics not supported");
    }

    if d.stage == Stage::Fragment && features2.features.fragment_stores_and_atomics == vk::FALSE {
        return not_supported("Fragment shader stores not supported");
    }

    if d.stage == Stage::Raygen {
        context.require_device_functionality("VK_KHR_ray_tracing_pipeline")?;
    }

    match d.desc {
        Desc::StorageImage | Desc::CombinedImageSampler => {
            if d.test_robustness2 && !d.null_descriptor {
                if robustness2_features.robust_image_access2 == vk::FALSE {
                    return not_supported("robustImageAccess2 not supported");
                }
            } else if !d.null_descriptor && image_robustness_features.robust_image_access == vk::FALSE {
                return not_supported("robustImageAccess not supported");
            }
        }
        _ => {
            if d.test_robustness2 && !d.null_descriptor && robustness2_features.robust_buffer_access2 == vk::FALSE {
                return not_supported("robustBufferAccess2 not supported");
            }
        }
    }

    if d.null_descriptor && robustness2_features.null_descriptor == vk::FALSE {
        return not_supported("nullDescriptor not supported");
    }

    // The fill shader for 64-bit multisample image tests uses a storage image.
    if d.samples != vk::SampleCountFlags::_1
        && format_is_r64(d.format)
        && features2.features.shader_storage_image_multisample == vk::FALSE
    {
        return not_supported("shaderStorageImageMultisample not supported");
    }

    if d.desc == Desc::StorageImage
        && d.samples != vk::SampleCountFlags::_1
        && features2.features.shader_storage_image_multisample == vk::FALSE
    {
        return not_supported("shaderStorageImageMultisample not supported");
    }

    if (d.use_template || format_is_r64(d.format)) && context.api_version() < (1, 1, 0) {
        return not_supported("Vulkan 1.1 not supported");
    }

    if d.desc == Desc::StorageImage && !d.format_qualifier {
        let properties = format_properties3(context, d.format);
        if !properties
            .optimal_tiling_features
            .contains(vk::FormatFeatureFlags2::STORAGE_READ_WITHOUT_FORMAT)
        {
            return not_supported("Format does not support reading without format");
        }
        if !properties
            .optimal_tiling_features
            .contains(vk::FormatFeatureFlags2::STORAGE_WRITE_WITHOUT_FORMAT)
        {
            return not_supported("Format does not support writing without format");
        }
    } else if d.desc == Desc::StorageTexelBuffer && !d.format_qualifier {
        let properties = format_properties3(context, d.format);
        if !properties
            .buffer_features
            .contains(vk::FormatFeatureFlags2::STORAGE_READ_WITHOUT_FORMAT)
        {
            return not_supported("Format does not support reading without format");
        }
        if !properties
            .buffer_features
            .contains(vk::FormatFeatureFlags2::STORAGE_WRITE_WITHOUT_FORMAT)
        {
            return not_supported("Format does not support writing without format");
        }
    }

    if d.push_descriptor {
        context.require_device_functionality("VK_KHR_push_descriptor")?;
    }

    if d.view_type == vk::ImageViewType::CUBE_ARRAY && features2.features.image_cube_array == vk::FALSE {
        return not_supported("Cube array image view type not supported");
    }

    if context.is_device_functionality_supported("VK_KHR_portability_subset")
        && context.get_device_features().robust_buffer_access == vk::FALSE
    {
        return not_supported("VK_KHR_portability_subset: robustBufferAccess not supported by this implementation");
    }

    if d.needs_pipeline_robustness() && pipeline_robustness_features.pipeline_robustness == vk::FALSE {
        return not_supported("pipelineRobustness not supported");
    }

    if d.uses_64bit_indexing && shader_64bit_indexing_features.shader_64bit_indexing == vk::FALSE {
        return not_supported("shader64BitIndexing not supported by this implementation");
    }

    if d.use_compute_queue && context.get_compute_queue().is_none() {
        return not_supported("Exclusive compute queue not supported.");
    }

    if d.is_long_vector() {
        context.require_device_functionality("VK_EXT_shader_long_vector")?;
        context.require_device_functionality("VK_EXT_scalar_block_layout")?;

        if long_vector_features.long_vector == vk::FALSE {
            return not_supported("longVector feature not supported");
        }

        let mut long_vector_properties = vk::PhysicalDeviceShaderLongVectorPropertiesEXT::default();
        {
            let mut properties2 = vk::PhysicalDeviceProperties2::builder().push_next(&mut long_vector_properties);
            unsafe { instance.get_physical_device_properties2(physical_device, &mut properties2) };
        }
        if d.long_vector_components > long_vector_properties.max_vector_components {
            return not_supported("longVectorComponents exceeds maxVectorComponents");
        }

        if d.long_vector_scalar == Some(LongVectorScalar::F16) {
            context.require_device_functionality("VK_KHR_shader_float16_int8")?;
            context.require_device_functionality("VK_KHR_16bit_storage")?;

            if float16_int8_features.shader_float16 == vk::FALSE {
                return not_supported("shaderFloat16 feature not supported");
            }

            if d.desc.is_ubo() && storage16_features.uniform_and_storage_buffer_16bit_access == vk::FALSE {
                return not_supported("uniformAndStorageBuffer16BitAccess feature not supported");
            }

            if !d.desc.is_ubo() && storage16_features.storage_buffer_16bit_access == vk::FALSE {
                return not_supported("storageBuffer16BitAccess feature not supported");
            }
        }
    }

    if d.desc.is_image() {
        let props = unsafe { instance.get_physical_device_format_properties(physical_device, d.format) };
        let features = props.optimal_tiling_features;

        if !features.intersects(vk::FormatFeatureFlags::TRANSFER_SRC | vk::FormatFeatureFlags::TRANSFER_DST) {
            return not_supported("Format not supported for transfer");
        }
    }

    Ok(())
}

