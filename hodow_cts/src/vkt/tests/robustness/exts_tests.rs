const STAGE_CASES: [(Stage, &str); 4] = [
    (Stage::Compute, "comp"),
    (Stage::Fragment, "frag"),
    (Stage::Vertex, "vert"),
    (Stage::Raygen, "rgen"),
];

/// `createTests`
fn add_tests(group: &mut TestCaseGroup, robustness2: bool, pipeline_robustness: bool, uses_64bit_indexing: bool) {
    let mut root = Node::new("root");

    for (push_descriptor, push_name) in [(false, "bind"), (true, "push")] {
        for (use_template, temp_name) in [(false, "notemplate"), (true, "template")] {
            for (format, fmt_name) in FORMATS {
                // Avoid too much duplication by excluding certain test cases
                if (pipeline_robustness || uses_64bit_indexing)
                    && !matches!(
                        format,
                        vk::Format::R32_UINT | vk::Format::R32G32B32A32_SFLOAT | vk::Format::R64_SINT
                    )
                {
                    continue;
                }

                let fmt_size = format_pixel_size(format) as i32;

                for (unroll, unroll_name) in [(false, "dontunroll"), (true, "unroll")] {
                    if unroll && (pipeline_robustness || uses_64bit_indexing) {
                        continue;
                    }

                    for (vol, vol_name) in [(false, "nonvolatile"), (true, "volatile")] {
                        let desc_cases: &[(Desc, &str)] = if robustness2 { &FULL_DESC_CASES } else { &IMG_DESC_CASES };

                        for &(desc, desc_name) in desc_cases {
                            if pipeline_robustness
                                && !matches!(
                                    desc,
                                    Desc::UniformBuffer
                                        | Desc::StorageBuffer
                                        | Desc::CombinedImageSampler
                                        | Desc::VertexAttributeFetch
                                )
                            {
                                continue;
                            }
                            if uses_64bit_indexing && desc != Desc::StorageBuffer {
                                continue;
                            }

                            // VUID-vkCmdDispatch-SampledType-04472
                            if format == vk::Format::R64_SINT && desc == Desc::UniformTexelBuffer {
                                continue;
                            }

                            for (read_only, ro_name) in [(false, "readwrite"), (true, "readonly")] {
                                // readonly cases are just for storage_buffer
                                if read_only && !desc.is_ssbo() {
                                    continue;
                                }

                                if (pipeline_robustness || uses_64bit_indexing) && read_only {
                                    continue;
                                }

                                for (format_qualifier, fmt_qual_name) in [(false, "no_fmt_qual"), (true, "fmt_qual")] {
                                    // format qualifier is only used for storage image and storage texel buffers
                                    if format_qualifier
                                        && !matches!(desc, Desc::StorageTexelBuffer | Desc::StorageImage)
                                    {
                                        continue;
                                    }

                                    if push_descriptor
                                        && matches!(
                                            desc,
                                            Desc::UniformBufferDynamic
                                                | Desc::StorageBufferDynamic
                                                | Desc::VertexAttributeFetch
                                        )
                                    {
                                        continue;
                                    }

                                    let is_r64 = format_is_r64(format);
                                    let len_cases: &[(i32, &str)] = if robustness2 {
                                        if is_r64 {
                                            &FULL_LEN_CASES_64BIT
                                        } else {
                                            &FULL_LEN_CASES_32BIT
                                        }
                                    } else {
                                        &IMG_LEN_CASES
                                    };

                                    for &(len, len_name) in len_cases {
                                        if len != NULL_LEN {
                                            let buffer_len = len != 0;
                                            let buffer_desc = !desc.is_image();
                                            if buffer_len != buffer_desc {
                                                continue;
                                            }

                                            // Add template tests cases only for null_descriptor cases
                                            if use_template {
                                                continue;
                                            }
                                        }

                                        if matches!(desc, Desc::StorageTexelBuffer | Desc::UniformTexelBuffer)
                                            && len != NULL_LEN
                                            && (len % fmt_size) != 0
                                        {
                                            continue;
                                        }

                                        // Avoid too much duplication by excluding certain test cases
                                        let len_bits = len as u32;
                                        if (pipeline_robustness || uses_64bit_indexing)
                                            && robustness2
                                            && (len_bits == 0 || (len_bits & len_bits.wrapping_sub(1)) != 0)
                                        {
                                            continue;
                                        }

                                        // "volatile" only applies to storage images/buffers
                                        if vol && !desc.supports_stores() {
                                            continue;
                                        }

                                        for (samples, samp_name) in SAMP_CASES {
                                            // Avoid too much duplication by excluding certain test cases
                                            if pipeline_robustness && samples != vk::SampleCountFlags::_1 {
                                                continue;
                                            }

                                            // Buffers don't support different sample counts at all
                                            if samples != vk::SampleCountFlags::_1 && !desc.is_image() {
                                                continue;
                                            }

                                            for (view_type, view_name) in VIEW_CASES {
                                                if view_type != vk::ImageViewType::_1D && !desc.is_image() {
                                                    // buffer descriptors don't have different dimensionalities. Only test "1D"
                                                    continue;
                                                }

                                                if view_type != vk::ImageViewType::_2D
                                                    && view_type != vk::ImageViewType::_2D_ARRAY
                                                    && samples != vk::SampleCountFlags::_1
                                                {
                                                    continue;
                                                }

                                                // Avoid too much duplication by excluding certain test cases
                                                if pipeline_robustness
                                                    && !matches!(
                                                        view_type,
                                                        vk::ImageViewType::_1D
                                                            | vk::ImageViewType::_2D
                                                            | vk::ImageViewType::_2D_ARRAY
                                                    )
                                                {
                                                    continue;
                                                }

                                                for (stage, stage_name) in STAGE_CASES {
                                                    if stage == Stage::Raygen && pipeline_robustness {
                                                        continue;
                                                    }
                                                    if len == NULL_LEN && pipeline_robustness {
                                                        continue;
                                                    }

                                                    if desc == Desc::VertexAttributeFetch && stage != Stage::Vertex {
                                                        continue;
                                                    }

                                                    let mut image_dim = [5u32, 11, 6];
                                                    if view_type == vk::ImageViewType::CUBE_ARRAY
                                                        || view_type == vk::ImageViewType::CUBE
                                                    {
                                                        image_dim[1] = image_dim[0];
                                                    }

                                                    let mut pipeline_robustness_cases = Vec::new();
                                                    if !pipeline_robustness {
                                                        pipeline_robustness_cases
                                                            .push(PipelineRobustnessCase::Disabled);
                                                    } else {
                                                        pipeline_robustness_cases
                                                            .push(PipelineRobustnessCase::EnabledMonolithic);
                                                        if stage != Stage::Raygen && stage != Stage::Compute {
                                                            pipeline_robustness_cases
                                                                .push(PipelineRobustnessCase::EnabledFastGpl);
                                                            pipeline_robustness_cases
                                                                .push(PipelineRobustnessCase::EnabledOptimizedGpl);
                                                        }
                                                    }

                                                    for pipeline_robustness_case in pipeline_robustness_cases {
                                                        for use_compute_queue in [false, true] {
                                                            if stage != Stage::Compute
                                                                && stage != Stage::Raygen
                                                                && use_compute_queue
                                                            {
                                                                continue;
                                                            }

                                                            let data = CaseDef {
                                                                format,
                                                                stage,
                                                                desc,
                                                                view_type,
                                                                samples,
                                                                buffer_len: len,
                                                                unroll,
                                                                vol,
                                                                null_descriptor: len == NULL_LEN,
                                                                use_template,
                                                                format_qualifier,
                                                                push_descriptor,
                                                                test_robustness2: robustness2,
                                                                pipeline_robustness_case,
                                                                image_dim,
                                                                read_only,
                                                                uses_64bit_indexing,
                                                                use_compute_queue,
                                                                long_vector_components: 0,
                                                                long_vector_scalar: None,
                                                            };

                                                            let name = format!(
                                                                "{stage_name}{}{}",
                                                                pipeline_robustness_case.suffix(),
                                                                if use_compute_queue { "_compute" } else { "" }
                                                            );

                                                            // Put storage_buffer tests in separate readonly vs readwrite groups. Other types go directly into the descriptor group
                                                            let mut path = vec![
                                                                push_name,
                                                                temp_name,
                                                                fmt_name,
                                                                unroll_name,
                                                                vol_name,
                                                                desc_name,
                                                            ];
                                                            if desc.is_ssbo() {
                                                                path.push(ro_name);
                                                            }
                                                            path.extend([
                                                                fmt_qual_name,
                                                                len_name,
                                                                samp_name,
                                                                view_name,
                                                            ]);

                                                            let programs = programs_for(&data);
                                                            root.insert(&path, ExtsTestCase { name, data, programs });
                                                        }
                                                    }
                                                }
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    for child in root.groups {
        group.add_child(child.into_group());
    }
}

/// `createLongVectorTests`
fn create_long_vector_tests(pipeline_robustness: bool) -> TestCaseGroup {
    let scalar_cases = [
        (LongVectorScalar::F32, "f32"),
        (LongVectorScalar::I32, "i32"),
        (LongVectorScalar::U32, "u32"),
        (LongVectorScalar::F16, "f16"),
    ];
    // Mix of power-of-two and prime widths above the legacy <=4 ceiling. Cases exceeding maxVectorComponents are skipped at runtime in checkSupport().
    let width_cases = [
        (5u32, "w5"),
        (7, "w7"),
        (8, "w8"),
        (11, "w11"),
        (13, "w13"),
        (16, "w16"),
    ];
    let desc_cases = [
        (Desc::StorageBuffer, "ssbo", false),
        (Desc::StorageBufferDynamic, "ssbo_dyn", false),
        (Desc::UniformBuffer, "ubo", true),
        (Desc::UniformBufferDynamic, "ubo_dyn", true),
    ];
    let len_cases = [(32i32, "len_32"), (256, "len_256"), (260, "len_260")];
    let ro_cases = [(false, "readwrite"), (true, "readonly")];
    let unroll_cases = [(true, "unroll"), (false, "dont_unroll")];

    let mut root = Node::new("long_vector");
    for (scalar, scalar_name) in scalar_cases {
        for (components, width_name) in width_cases {
            for (desc, desc_name, is_ubo) in desc_cases {
                for (len, len_name) in len_cases {
                    for (unroll, unroll_name) in unroll_cases {
                        for (read_only, ro_name) in ro_cases {
                            // UBOs are inherently read-only; emit a single variant.
                            if is_ubo && !read_only {
                                continue;
                            }

                            // Need room for at least one in-bounds element (else range == 0).
                            let element_bytes = components * scalar.size_bytes();
                            if element_bytes == 0 || (len as u32) < element_bytes {
                                continue;
                            }

                            let data = CaseDef {
                                format: vk::Format::R32_UINT,
                                stage: Stage::Compute,
                                desc,
                                view_type: vk::ImageViewType::_1D,
                                samples: vk::SampleCountFlags::_1,
                                buffer_len: len,
                                unroll,
                                vol: false,
                                null_descriptor: false,
                                use_template: false,
                                format_qualifier: false,
                                push_descriptor: false,
                                test_robustness2: true,
                                pipeline_robustness_case: if pipeline_robustness {
                                    PipelineRobustnessCase::EnabledMonolithic
                                } else {
                                    PipelineRobustnessCase::Disabled
                                },
                                image_dim: [1, 1, 1],
                                read_only,
                                uses_64bit_indexing: false,
                                use_compute_queue: false,
                                long_vector_components: components,
                                long_vector_scalar: Some(scalar),
                            };
                            let programs = programs_for(&data);
                            root.insert(
                                &[scalar_name, width_name, desc_name, len_name, "comp", unroll_name],
                                ExtsTestCase {
                                    name: ro_name.to_string(),
                                    data,
                                    programs,
                                },
                            );
                        }
                    }
                }
            }
        }
    }
    root.into_group()
}

/// `createRobustness2Tests`
pub fn create_robustness2_tests() -> TestCaseGroup {
    let mut group = TestCaseGroup::new("robustness2");
    add_tests(&mut group, true, false, false);

    let mut shader_64bit_indexing_group = TestCaseGroup::new("64b_indexing");
    add_tests(&mut shader_64bit_indexing_group, true, false, true);
    group.add_child(shader_64bit_indexing_group);

    group.add_child(create_long_vector_tests(false));
    group.add_child(crate::vkt::tests::robustness::exts_stride_tests::create_misc_tests(
        false,
    ));
    group
}

/// `createImageRobustnessTests`
pub fn create_image_robustness_tests() -> TestCaseGroup {
    let mut group = TestCaseGroup::new("image_robustness");
    add_tests(&mut group, false, false, false);
    group
}

/// `createPipelineRobustnessTests`
pub fn create_pipeline_robustness_tests() -> TestCaseGroup {
    let mut group = TestCaseGroup::new("pipeline_robustness");

    let mut robustness2_group = TestCaseGroup::new("robustness2");
    add_tests(&mut robustness2_group, true, true, false);
    robustness2_group.add_child(create_long_vector_tests(true));
    robustness2_group.add_child(crate::vkt::tests::robustness::exts_stride_tests::create_misc_tests(
        true,
    ));
    group.add_child(robustness2_group);

    let mut image_robustness_group = TestCaseGroup::new("image_robustness");
    add_tests(&mut image_robustness_group, false, true, false);
    group.add_child(image_robustness_group);

    group
}
