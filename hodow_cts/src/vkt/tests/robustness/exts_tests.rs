/// A group under construction; cases only ever sit in the innermost level, as upstream's view and `readonly` groups.
struct Node {
    name: String,
    groups: Vec<Node>,
    cases: Vec<ExtsTestCase>,
}

impl Node {
    fn new(name: &str) -> Self {
        Self {
            name: name.to_string(),
            groups: Vec::new(),
            cases: Vec::new(),
        }
    }

    /// Adds a case below `path`, reusing the last group when it has the name: the loops emit every group's cases back to back.
    fn insert(&mut self, path: &[&str], case: ExtsTestCase) {
        let Some((first, rest)) = path.split_first() else {
            self.cases.push(case);
            return;
        };
        if self.groups.last().is_none_or(|g| g.name != *first) {
            self.groups.push(Node::new(first));
        }
        self.groups.last_mut().expect("just pushed").insert(rest, case);
    }

    fn into_group(self) -> TestCaseGroup {
        let mut group = TestCaseGroup::new(self.name);
        for child in self.groups {
            group.add_child(child.into_group());
        }
        for case in self.cases {
            group.add_child(Box::new(case) as Box<dyn TestCase>);
        }
        group
    }
}

