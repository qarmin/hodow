/// `createCooperativeMatrixTestsInternal`
pub fn create_cooperative_matrix_tests_internal(use_type: UseType) -> TestCaseGroup {
    let mut group = TestCaseGroup::new(use_type.name());
    let tt_cases = tt_cases();
    let dt_cases = dt_cases();

    for (scope, scope_name) in SCOPE_CASES {
        let mut scope_group = TestCaseGroup::new(scope_name);
        if use_type == UseType::Nv && scope == vk::ScopeKHR::WORKGROUP {
            continue;
        }

        for &(test_type, tt_name, coopmat_feature) in &tt_cases {
            for (sgs, sgs_name) in SGS_CASES {
                if test_type != TestType::MatrixMulAdd && sgs != SubgroupSizeMode::None {
                    continue;
                }

                if test_type == TestType::MatrixMulAdd && sgs != SubgroupSizeMode::None && use_type == UseType::Nv {
                    continue;
                }

                let mut tt_group = TestCaseGroup::new(format!("{tt_name}{sgs_name}"));

                for &(input_type, output_type, dt_name) in &dt_cases {
                    let mut dt_group = TestCaseGroup::new(dt_name);
                    for (storage_class, sc_name) in SC_CASES {
                        if is_split_barrier_test(test_type)
                            && (storage_class != StorageClass::Workgroup || use_type != UseType::KhrResult)
                        {
                            continue;
                        }
                        let mut sc_group = TestCaseGroup::new(sc_name);
                        for (col_major, col_name) in COL_CASES {
                            let mut col_group = TestCaseGroup::new(col_name);
                            for (addr_method, addr_name) in ADDR_CASES {
                                let is_matrix_mul = is_matrix_mul_add_op(test_type);

                                if coopmat_feature == CoopMatFeature::Maint1
                                    && (is_reduce_op(test_type) || is_per_elem_op(test_type))
                                    && (scope != vk::ScopeKHR::SUBGROUP || addr_method != AddrMethod::Linear)
                                {
                                    continue;
                                }

                                if test_type == TestType::MatrixMulAddCross {
                                    if input_type.is_float()
                                        || output_type.is_float()
                                        || use_type == UseType::Nv
                                        || storage_class != StorageClass::Buffer
                                    {
                                        continue;
                                    }

                                    // handwritten spir-v would need to be ported
                                    if scope == vk::ScopeKHR::WORKGROUP {
                                        continue;
                                    }
                                } else {
                                    // Rest of tests do not run on matrix C
                                    if use_type == UseType::KhrC {
                                        continue;
                                    }

                                    // useType isn't used for matrixmul shaders. Don't generate 3 copies of those tests.
                                    if is_matrix_mul && (use_type == UseType::KhrA || use_type == UseType::KhrB) {
                                        continue;
                                    }

                                    // NV extension doesn't support mixing signedness
                                    if is_matrix_mul
                                        && use_type == UseType::Nv
                                        && input_type.is_sint() != output_type.is_sint()
                                    {
                                        continue;
                                    }

                                    if is_matrix_mul && input_type.bits() > output_type.bits() {
                                        continue;
                                    }

                                    if input_type.is_no_arithmetic() || output_type.is_no_arithmetic() {
                                        if use_type == UseType::Nv {
                                            continue;
                                        }

                                        if is_arithmetic_test(test_type) {
                                            continue;
                                        }
                                    }
                                }

                                if test_type == TestType::MatrixMulAddDequant {
                                    if input_type != Ct::F16 && !input_type.is_no_arithmetic() {
                                        continue;
                                    }
                                    if addr_method != AddrMethod::Decode {
                                        continue;
                                    }
                                    if col_major {
                                        // row major only, for now
                                        continue;
                                    }
                                }

                                if (addr_method == AddrMethod::BlockSize || addr_method == AddrMethod::Decode)
                                    && test_type != TestType::Negate
                                    && test_type != TestType::MatrixMulAddDequant
                                {
                                    // only certain tests ported to handle blocksize
                                    continue;
                                }

                                if (addr_method == AddrMethod::BlockSize || addr_method == AddrMethod::Decode)
                                    && (storage_class == StorageClass::Workgroup
                                        || storage_class == StorageClass::WorkgroupVariablePointers)
                                {
                                    // copying into shared memory not ported to handle block size
                                    continue;
                                }

                                if !is_matrix_mul && input_type != output_type {
                                    continue;
                                }

                                if test_type == TestType::Mul && use_type == UseType::Nv {
                                    continue;
                                }

                                if test_type == TestType::MatrixMulAddSaturated
                                    && (input_type.is_float() || use_type == UseType::Nv)
                                {
                                    continue;
                                }

                                if test_type == TestType::MatrixMulAddWrapping
                                    && (input_type.is_float() || use_type == UseType::Nv)
                                {
                                    continue;
                                }

                                if test_type == TestType::MatrixMulAddStride0 && use_type == UseType::Nv {
                                    continue;
                                }

                                if test_type == TestType::GetCoordinate && use_type == UseType::Nv {
                                    continue;
                                }

                                if test_type == TestType::Length
                                    && use_type != UseType::Nv
                                    && (output_type == Ct::S8 || output_type == Ct::U8)
                                {
                                    continue;
                                }

                                if test_type == TestType::MatrixMulAddPushConstants && addr_method != AddrMethod::Linear
                                {
                                    continue;
                                }

                                if use_type == UseType::Nv
                                    && (addr_method != AddrMethod::Linear
                                        || is_reduce_op(test_type)
                                        || is_per_elem_op(test_type))
                                {
                                    continue;
                                }

                                if is_reduce_op(test_type) && (use_type == UseType::KhrA || use_type == UseType::KhrB) {
                                    continue;
                                }

                                if is_reduce_op(test_type) && input_type != output_type {
                                    continue;
                                }

                                if is_tensor_layout_test(test_type)
                                    && (col_major
                                        || storage_class == StorageClass::Workgroup
                                        || storage_class == StorageClass::WorkgroupVariablePointers
                                        || storage_class == StorageClass::PhysicalStorageBuffer
                                        || addr_method == AddrMethod::Linear)
                                {
                                    continue;
                                }

                                if (storage_class == StorageClass::BufferVariablePointers
                                    || storage_class == StorageClass::WorkgroupVariablePointers)
                                    && (!(test_type == TestType::MatrixMulAdd || test_type == TestType::Mul)
                                        || sgs != SubgroupSizeMode::None)
                                {
                                    // trim test count
                                    continue;
                                }

                                if col_major && !(is_matrix_mul || test_type == TestType::Mul) {
                                    // trim test count
                                    continue;
                                }

                                if (storage_class == StorageClass::Workgroup
                                    || storage_class == StorageClass::WorkgroupVariablePointers
                                    || addr_method == AddrMethod::Linear)
                                    && is_clamp_test(test_type)
                                {
                                    continue;
                                }

                                let mut workgroups_x = 4u32;
                                let mut workgroups_y = 4u32;

                                let mut subgroups_per_workgroup_x = 2u32;
                                let mut subgroups_per_workgroup_y = 2u32;

                                // The program is meant to be run once
                                if is_tensor_layout_test(test_type) {
                                    subgroups_per_workgroup_x = 1;
                                    subgroups_per_workgroup_y = 1;
                                    workgroups_x = 1;
                                    workgroups_y = 1;
                                }

                                if is_split_barrier_test(test_type) {
                                    if addr_method != AddrMethod::Linear {
                                        continue;
                                    }
                                    subgroups_per_workgroup_x = 1;
                                    subgroups_per_workgroup_y = 2;
                                }

                                let c = CaseDef {
                                    test_type,
                                    scope,
                                    subgroups_per_workgroup_x,
                                    subgroups_per_workgroup_y,
                                    workgroups_x,
                                    workgroups_y,
                                    input_type,
                                    output_type,
                                    col_major,
                                    addr_method,
                                    storage_class,
                                    use_type,
                                    use_type2: use_type,
                                    coopmat_feature,
                                    subgroup_size_mode: sgs,
                                    input_component_count: 1,
                                    output_component_count: 1,
                                };
                                let key = format!(
                                    "{}.{}.{}{}.{}.{}.{}.{}",
                                    use_type.name(),
                                    scope_name,
                                    tt_name,
                                    sgs_name,
                                    dt_name,
                                    sc_name,
                                    col_name,
                                    addr_name
                                );
                                col_group
                                    .add_child(Box::new(CooperativeMatrixTestCase::new(addr_name, key, c))
                                        as Box<dyn TestCase>);
                            }
                            add_group(&mut sc_group, col_group);
                        }
                        add_group(&mut dt_group, sc_group);
                    }
                    add_group(&mut tt_group, dt_group);
                }
                add_group(&mut scope_group, tt_group);
            }
        }

        if use_type != UseType::KhrC {
            for use_type_dst in [UseType::Nv, UseType::KhrA, UseType::KhrB, UseType::KhrResult] {
                if (use_type == UseType::Nv) != (use_type_dst == UseType::Nv) {
                    continue;
                }
                if use_type != use_type_dst
                    && (use_type == UseType::KhrA || use_type == UseType::KhrB)
                    && (use_type_dst == UseType::KhrA || use_type_dst == UseType::KhrB)
                {
                    // not supported in coopmatmaint1/2
                    continue;
                }

                let mut conv_cases: Vec<ConvCase> = Vec::new();
                let mut push = |test_type, coopmat_feature, name| {
                    conv_cases.push(ConvCase {
                        test_type,
                        coopmat_feature,
                        name,
                    })
                };
                if use_type == use_type_dst {
                    // Same-use conversion works in the base cooperative matrix extension, and is also covered
                    // by the extension-specific conversion paths.
                    push(TestType::ConvertBase, CoopMatFeature::Base, "convert_base");
                    push(TestType::Convert, CoopMatFeature::Nv2, "convert_nv");
                    push(TestType::ConvertSat, CoopMatFeature::Nv2, "convert_sat_nv");
                    if use_type != UseType::Nv {
                        push(TestType::Convert, CoopMatFeature::Maint1, "convert_maint1");
                        push(TestType::ConvertSat, CoopMatFeature::Maint1, "convert_sat_maint1");
                    }
                } else if use_type == UseType::KhrResult {
                    // Result-to-A/B conversions can be expressed by either CM2 or CMM1.
                    push(TestType::Convert, CoopMatFeature::Nv2, "convert_nv");
                    push(TestType::Convert, CoopMatFeature::Maint1, "convert_maint1");
                    push(TestType::ConvertSat, CoopMatFeature::Nv2, "convert_sat_nv");
                    push(TestType::ConvertSat, CoopMatFeature::Maint1, "convert_sat_maint1");
                } else if use_type_dst == UseType::KhrResult {
                    // A/B-to-result conversions are tested through CMM1.
                    push(TestType::Convert, CoopMatFeature::Maint1, "convert_maint1");
                    push(TestType::ConvertSat, CoopMatFeature::Maint1, "convert_sat_maint1");
                }

                if use_type == UseType::KhrResult && use_type_dst == UseType::KhrB {
                    // Transpose conversion has separate CM2 and CMM1 entry points.
                    push(TestType::TransposeAccToB, CoopMatFeature::Nv2, "transpose");
                    push(TestType::TransposeAccToB, CoopMatFeature::Maint1, "transpose_maint1");
                }
                if use_type == UseType::KhrResult && use_type_dst == UseType::KhrA {
                    push(TestType::TransposeAccToA, CoopMatFeature::Maint1, "transpose_maint1");
                }

                for conv_case in &conv_cases {
                    let test_type = conv_case.test_type;
                    let name = format!("{}_dst_{}", conv_case.name, use_type_dst.name());

                    let mut tt_group = TestCaseGroup::new(name.clone());

                    for input_type in ALL_TYPES {
                        for output_type in ALL_TYPES {
                            if is_saturated_convert_op(test_type) {
                                if input_type == Ct::E5m2 || input_type == Ct::E4m3 {
                                    continue;
                                }
                                if output_type != Ct::E5m2 && output_type != Ct::E4m3 {
                                    continue;
                                }
                            }

                            let name2 = format!("input_{}_output_{}", input_type.type_name(), output_type.type_name());
                            let mut dt_group = TestCaseGroup::new(name2.clone());
                            for (storage_class, sc_name) in SC_CASES {
                                if storage_class != StorageClass::Buffer {
                                    // Conversion coverage comes from the type/use/scope/dialect combinations;
                                    // other storage classes duplicate load/store paths covered by the main tests.
                                    continue;
                                }

                                let mut sc_group = TestCaseGroup::new(sc_name);
                                for (col_major, col_name) in COL_CASES {
                                    if col_major {
                                        // trim test count
                                        continue;
                                    }

                                    let addr_method = if scope == vk::ScopeKHR::WORKGROUP {
                                        AddrMethod::TensorLayout
                                    } else {
                                        AddrMethod::Linear
                                    };

                                    let c = CaseDef {
                                        test_type,
                                        scope,
                                        subgroups_per_workgroup_x: 2,
                                        subgroups_per_workgroup_y: 2,
                                        workgroups_x: 4,
                                        workgroups_y: 4,
                                        input_type,
                                        output_type,
                                        col_major,
                                        addr_method,
                                        storage_class,
                                        use_type,
                                        use_type2: use_type_dst,
                                        coopmat_feature: conv_case.coopmat_feature,
                                        subgroup_size_mode: SubgroupSizeMode::None,
                                        input_component_count: 1,
                                        output_component_count: 1,
                                    };
                                    let key = format!(
                                        "{}.{}.{}.{}.{}.{}",
                                        use_type.name(),
                                        scope_name,
                                        name,
                                        name2,
                                        sc_name,
                                        col_name
                                    );
                                    sc_group
                                        .add_child(Box::new(CooperativeMatrixTestCase::new(col_name, key, c))
                                            as Box<dyn TestCase>);
                                }
                                add_group(&mut dt_group, sc_group);
                            }
                            add_group(&mut tt_group, dt_group);
                        }
                    }
                    add_group(&mut scope_group, tt_group);
                }
            }
        }

        if use_type != UseType::Nv && use_type != UseType::KhrC {
            let mut tt_group = TestCaseGroup::new("multicomponent");
            for (ct_name, component_count) in MULTICOMPONENT_TYPES {
                let mut ct_group = TestCaseGroup::new(ct_name);

                for (io_name, test_type) in IO_TYPES {
                    let mut io_group = TestCaseGroup::new(io_name);
                    let input_component_count = if test_type == TestType::MulticomponentLoad {
                        component_count
                    } else {
                        1
                    };
                    let output_component_count = if test_type == TestType::MulticomponentLoad {
                        1
                    } else {
                        component_count
                    };

                    for input_type in ALL_TYPES {
                        let mut dt_group = TestCaseGroup::new(input_type.type_name());
                        for (storage_class, sc_name) in SC_CASES {
                            let mut sc_group = TestCaseGroup::new(sc_name);
                            for (col_major, col_name) in COL_CASES {
                                let addr_method = if scope == vk::ScopeKHR::WORKGROUP {
                                    AddrMethod::TensorLayout
                                } else {
                                    AddrMethod::Linear
                                };

                                if col_major {
                                    // trim test count
                                    continue;
                                }

                                let c = CaseDef {
                                    test_type,
                                    scope,
                                    subgroups_per_workgroup_x: 2,
                                    subgroups_per_workgroup_y: 2,
                                    workgroups_x: 4,
                                    workgroups_y: 4,
                                    input_type,
                                    output_type: input_type,
                                    col_major,
                                    addr_method,
                                    storage_class,
                                    use_type,
                                    use_type2: use_type,
                                    coopmat_feature: CoopMatFeature::Base,
                                    subgroup_size_mode: SubgroupSizeMode::None,
                                    input_component_count,
                                    output_component_count,
                                };

                                let key = format!(
                                    "{}.{}.multicomponent.{}.{}.{}.{}.{}",
                                    use_type.name(),
                                    scope_name,
                                    ct_name,
                                    io_name,
                                    input_type.type_name(),
                                    sc_name,
                                    col_name
                                );
                                sc_group.add_child(
                                    Box::new(CooperativeMatrixTestCase::new(col_name, key, c)) as Box<dyn TestCase>
                                );
                            }
                            add_group(&mut dt_group, sc_group);
                        }
                        add_group(&mut io_group, dt_group);
                    }
                    add_group(&mut ct_group, io_group);
                }
                add_group(&mut tt_group, ct_group);
            }
            add_group(&mut scope_group, tt_group);
        }
        add_group(&mut group, scope_group);
    }

    group
}

