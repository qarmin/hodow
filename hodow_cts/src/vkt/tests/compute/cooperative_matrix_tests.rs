/// The component types the case tables use. The 64 bit ones appear only in `componentTypeInfo` upstream.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Ct {
    F16,
    F32,
    F64,
    S8,
    S16,
    S32,
    S64,
    U8,
    U16,
    U32,
    U64,
    Bf16,
    E5m2,
    E4m3,
}

impl Ct {
    pub fn vk(self) -> vk::ComponentTypeKHR {
        match self {
            Self::F16 => vk::ComponentTypeKHR::FLOAT16,
            Self::F32 => vk::ComponentTypeKHR::FLOAT32,
            Self::F64 => vk::ComponentTypeKHR::FLOAT64,
            Self::S8 => vk::ComponentTypeKHR::SINT8,
            Self::S16 => vk::ComponentTypeKHR::SINT16,
            Self::S32 => vk::ComponentTypeKHR::SINT32,
            Self::S64 => vk::ComponentTypeKHR::SINT64,
            Self::U8 => vk::ComponentTypeKHR::UINT8,
            Self::U16 => vk::ComponentTypeKHR::UINT16,
            Self::U32 => vk::ComponentTypeKHR::UINT32,
            Self::U64 => vk::ComponentTypeKHR::UINT64,
            Self::Bf16 => vk::ComponentTypeKHR::BFLOAT16,
            Self::E5m2 => vk::ComponentTypeKHR::FLOAT8_E5M2_EXT,
            Self::E4m3 => vk::ComponentTypeKHR::FLOAT8_E4M3_EXT,
        }
    }

    /// `componentTypeInfo.typeName`
    pub(super) fn type_name(self) -> &'static str {
        match self {
            Self::F16 => "float16_t",
            Self::F32 => "float32_t",
            Self::F64 => "float64_t",
            Self::S8 => "int8_t",
            Self::S16 => "int16_t",
            Self::S32 => "int32_t",
            Self::S64 => "int64_t",
            Self::U8 => "uint8_t",
            Self::U16 => "uint16_t",
            Self::U32 => "uint32_t",
            Self::U64 => "uint64_t",
            Self::Bf16 => "bfloat16_t",
            Self::E5m2 => "floate5m2_t",
            Self::E4m3 => "floate4m3_t",
        }
    }

    pub(super) fn bits(self) -> u32 {
        match self {
            Self::F16 | Self::S16 | Self::U16 | Self::Bf16 => 16,
            Self::F32 | Self::S32 | Self::U32 => 32,
            Self::F64 | Self::S64 | Self::U64 => 64,
            Self::S8 | Self::U8 | Self::E5m2 | Self::E4m3 => 8,
        }
    }

    pub(super) fn is_float(self) -> bool {
        matches!(
            self,
            Self::F16 | Self::F32 | Self::F64 | Self::Bf16 | Self::E5m2 | Self::E4m3
        )
    }

    pub(super) fn is_sint(self) -> bool {
        matches!(self, Self::S8 | Self::S16 | Self::S32 | Self::S64)
    }

    pub(super) fn is_no_arithmetic(self) -> bool {
        matches!(self, Self::Bf16 | Self::E5m2 | Self::E4m3)
    }
}

