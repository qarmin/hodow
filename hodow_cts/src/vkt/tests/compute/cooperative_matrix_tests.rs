/// `getCooperativeMatrixPropertiesConverted`
pub(super) fn cooperative_matrix_properties_converted(
    context: &Context<'_>,
    khr: bool,
) -> Result<Vec<MatrixProps>, TestError> {
    if khr {
        let properties = unsafe {
            context
                .get_instance()
                .get_physical_device_cooperative_matrix_properties_khr(context.get_physical_device())
        }
        .vk_check("vkGetPhysicalDeviceCooperativeMatrixPropertiesKHR")?;
        Ok(properties
            .iter()
            .map(|p| MatrixProps {
                m_size: p.m_size,
                n_size: p.n_size,
                k_size: p.k_size,
                a_type: p.a_type,
                b_type: p.b_type,
                c_type: p.c_type,
                result_type: p.result_type,
                saturating_accumulation: p.saturating_accumulation != vk::FALSE,
                scope: p.scope,
            })
            .collect())
    } else {
        let properties = unsafe {
            context
                .get_instance()
                .get_physical_device_cooperative_matrix_properties_nv(context.get_physical_device())
        }
        .vk_check("vkGetPhysicalDeviceCooperativeMatrixPropertiesNV")?;
        Ok(properties
            .iter()
            .map(|p| MatrixProps {
                m_size: p.m_size,
                n_size: p.n_size,
                k_size: p.k_size,
                a_type: p.a_type,
                b_type: p.b_type,
                c_type: p.c_type,
                result_type: p.d_type,
                saturating_accumulation: false,
                scope: p.scope,
            })
            .collect())
    }
}

/// The `supported[]` bookkeeping shared by the three property loops: `uses` selects which member of the properties a type is looked up in
fn mark_supported(
    supported: &mut [bool; 2],
    d: &CaseDef,
    a_type: vk::ComponentTypeKHR,
    b_type: vk::ComponentTypeKHR,
    c_type: vk::ComponentTypeKHR,
    result_type: vk::ComponentTypeKHR,
    nv_matches_any: bool,
) -> Result<(), TestError> {
    let types = [d.input_type.vk(), d.output_type.vk()];
    let uses = [d.use_type, d.use_type2];
    for j in 0..2 {
        match uses[j] {
            UseType::Nv => {
                if nv_matches_any
                    && (a_type == types[j] || b_type == types[j] || c_type == types[j] || result_type == types[j])
                {
                    supported[j] = true;
                }
            }
            UseType::KhrA => {
                if a_type == types[j] {
                    supported[j] = true;
                }
            }
            UseType::KhrB => {
                if b_type == types[j] {
                    supported[j] = true;
                }
            }
            UseType::KhrResult => {
                if result_type == types[j] {
                    supported[j] = true;
                }
            }
            UseType::KhrC => return Err(TestError::InternalError("Unsupported use type".to_string())),
        }
    }
    Ok(())
}

/// `CooperativeMatrixTestCase::checkSupport`
fn check_support(context: &Context<'_>, d: &CaseDef) -> Result<(), TestError> {
    if context.get_device_properties().api_version < vk::make_version(1, 1, 0) {
        return not_supported("Vulkan 1.1 not supported");
    }

    if d.use_type.is_khr() {
        let features = query_features!(
            context,
            "VK_KHR_cooperative_matrix",
            vk::PhysicalDeviceCooperativeMatrixFeaturesKHR
        );
        if features.cooperative_matrix == vk::FALSE {
            return not_supported("VkPhysicalDeviceCooperativeMatrixFeaturesKHR::cooperativeMatrix not supported");
        }
    } else {
        let features = query_features!(
            context,
            "VK_NV_cooperative_matrix",
            vk::PhysicalDeviceCooperativeMatrixFeaturesNV
        );
        if features.cooperative_matrix == vk::FALSE {
            return not_supported("VkPhysicalDeviceCooperativeMatrixFeaturesNV::cooperativeMatrix not supported");
        }
    }

    let memory_model = query_features!(
        context,
        "VK_KHR_vulkan_memory_model",
        vk::PhysicalDeviceVulkanMemoryModelFeatures
    );
    if memory_model.vulkan_memory_model == vk::FALSE {
        return not_supported("vulkanMemoryModel not supported");
    }

    if (d.storage_class == StorageClass::WorkgroupVariablePointers
        || d.storage_class == StorageClass::BufferVariablePointers)
        && {
            let variable_pointers = query_features!(
                context,
                "VK_KHR_variable_pointers",
                vk::PhysicalDeviceVariablePointersFeatures
            );
            variable_pointers.variable_pointers == vk::FALSE
        }
    {
        return not_supported("variable pointers not supported");
    }

    if is_split_barrier_test(d.test_type) && !raw_feature(context, "VK_EXT_shader_split_barrier", 1000305000, 24, 0) {
        return not_supported("shaderSplitBarrier not supported");
    }

    if d.storage_class == StorageClass::PhysicalStorageBuffer
        && !context.is_device_functionality_supported("VK_KHR_buffer_device_address")
    {
        return not_supported("buffer device address not supported");
    }

    let float16_int8 = query_features!(
        context,
        "VK_KHR_shader_float16_int8",
        vk::PhysicalDeviceShaderFloat16Int8Features
    );
    if float16_int8.shader_float16 == vk::FALSE && (d.input_type == Ct::F16 || d.output_type == Ct::F16) {
        return not_supported("shaderFloat16 not supported");
    }

    let require_maint1 = |feature: usize, name: &str| -> Result<(), TestError> {
        context.require_device_functionality("VK_EXT_cooperative_matrix_maintenance1")?;
        if !maintenance1_feature(context, feature) {
            return not_supported(&format!("{name} not supported"));
        }
        Ok(())
    };
    let require_cm2 = |select: fn(&vk::PhysicalDeviceCooperativeMatrix2FeaturesNV) -> vk::Bool32,
                       name: &str|
     -> Result<(), TestError> {
        context.require_device_functionality("VK_NV_cooperative_matrix2")?;
        if select(&cooperative_matrix2_features(context)) == vk::FALSE {
            return not_supported(&format!("{name} not supported"));
        }
        Ok(())
    };

    if d.scope == vk::ScopeKHR::WORKGROUP {
        require_cm2(
            |f| f.cooperative_matrix_workgroup_scope,
            "cooperativeMatrixWorkgroupScope",
        )?;
    } else {
        // When the dispatched subgroup size varies at runtime, size the workgroup for the worst case
        let effective_size = if has_varying_effective_subgroup_size(context, d.subgroup_size_mode, d.test_type) {
            subgroup_size_control_properties(context).max_subgroup_size
        } else {
            subgroup_size_from_mode(context, d.subgroup_size_mode)
        };
        let invocations = effective_size * d.subgroups_per_workgroup_x * d.subgroups_per_workgroup_y;
        if invocations
            > context
                .get_device_properties()
                .limits
                .max_compute_work_group_invocations
        {
            return not_supported("workgroup too large for this device");
        }
    }
    if is_reduce_op(d.test_type) {
        if d.coopmat_feature == CoopMatFeature::Maint1 {
            require_maint1(MAINT1_REDUCTIONS, "cooperativeMatrixReductions")?;
        }
        if d.coopmat_feature == CoopMatFeature::Nv2 {
            require_cm2(|f| f.cooperative_matrix_reductions, "cooperativeMatrixReductions")?;
        }
    }

    if is_transpose_test(d.test_type) && d.coopmat_feature == CoopMatFeature::Nv2 {
        require_cm2(|f| f.cooperative_matrix_conversions, "cooperativeMatrixConversions")?;
    }

    if is_transpose_test(d.test_type) && d.coopmat_feature == CoopMatFeature::Maint1 {
        require_maint1(MAINT1_CONVERSIONS, "cooperativeMatrixConversions")?;
    }

    if is_convert_op(d.test_type) {
        if d.coopmat_feature == CoopMatFeature::Nv2 {
            require_cm2(|f| f.cooperative_matrix_conversions, "cooperativeMatrixConversions")?;
        }
        if d.coopmat_feature == CoopMatFeature::Maint1 {
            require_maint1(MAINT1_CONVERSIONS, "cooperativeMatrixConversions")?;
        }
    }

    if is_per_elem_op(d.test_type) {
        if d.coopmat_feature == CoopMatFeature::Maint1 {
            require_maint1(MAINT1_PER_ELEMENT_OPERATIONS, "cooperativeMatrixPerElementOperations")?;
        }
        if d.coopmat_feature == CoopMatFeature::Nv2 {
            require_cm2(
                |f| f.cooperative_matrix_per_element_operations,
                "cooperativeMatrixPerElementOperations",
            )?;
        }
    }

    if d.test_type == TestType::GetCoordinate {
        require_maint1(MAINT1_GET_COORDINATE, "cooperativeMatrixGetCoordinate")?;
    }

    if d.addr_method != AddrMethod::Linear || is_tensor_layout_test(d.test_type) || is_clamp_test(d.test_type) {
        require_cm2(
            |f| f.cooperative_matrix_tensor_addressing,
            "cooperativeMatrixTensorAddressing",
        )?;
    }

    if is_tensor_layout_test(d.test_type) {
        require_cm2(
            |f| f.cooperative_matrix_flexible_dimensions,
            "cooperativeMatrixFlexibleDimensions",
        )?;
    }

    if d.addr_method == AddrMethod::BlockSize || d.addr_method == AddrMethod::Decode {
        require_cm2(|f| f.cooperative_matrix_block_loads, "cooperativeMatrixBlockLoads")?;
    }

    let properties = cooperative_matrix_properties_converted(context, d.use_type.is_khr())?;
    let mut supported = [false, false];
    let is_mma = is_matrix_mul_add_op(d.test_type);
    let is_mma_sat = d.test_type == TestType::MatrixMulAddSaturated;

    for p in &properties {
        if p.scope != d.scope {
            continue;
        }

        if is_mma && is_mma_sat != p.saturating_accumulation {
            continue;
        }

        if is_mma {
            if p.a_type == d.input_type.vk()
                && p.b_type == d.input_type.vk()
                && p.c_type == d.output_type.vk()
                && p.result_type == d.output_type.vk()
            {
                supported = [true, true];
            }
        } else {
            mark_supported(&mut supported, d, p.a_type, p.b_type, p.c_type, p.result_type, true)?;
        }
    }

    let use_flexible_properties = d.use_type.is_khr();
    let flexible_dimensions_supported =
        cooperative_matrix2_features(context).cooperative_matrix_flexible_dimensions != vk::FALSE;

    if use_flexible_properties && flexible_dimensions_supported {
        let flexible_properties = unsafe {
            context
                .get_instance()
                .get_physical_device_cooperative_matrix_flexible_dimensions_properties_nv(context.get_physical_device())
        }
        .vk_check("vkGetPhysicalDeviceCooperativeMatrixFlexibleDimensionsPropertiesNV")?;

        for p in &flexible_properties {
            if p.scope != d.scope {
                continue;
            }

            if is_mma && is_mma_sat != (p.saturating_accumulation != vk::FALSE) {
                continue;
            }

            if is_mma {
                if p.a_type == d.input_type.vk()
                    && p.b_type == d.input_type.vk()
                    && p.c_type == d.output_type.vk()
                    && p.result_type == d.output_type.vk()
                {
                    supported = [true, true];
                }
            } else {
                mark_supported(&mut supported, d, p.a_type, p.b_type, p.c_type, p.result_type, false)?;
            }
        }
    }

    let properties2_possible = d.use_type.is_khr() && maintenance1_feature(context, MAINT1_PROPERTIES2);

    if !supported[0] || !supported[1] {
        if properties2_possible {
            return Err(TestError::NotPorted(
                "vkGetPhysicalDeviceCooperativeMatrixProperties2EXT is not exposed by the bindings".to_string(),
            ));
        }
        return not_supported("cooperative matrix combination not supported");
    }

    check_shader_object_requirements(ComputePipelineConstructionType::Pipeline)?;

    let any_bfloat16 = d.input_type == Ct::Bf16 || d.output_type == Ct::Bf16;
    if any_bfloat16 {
        let bfloat16 = query_features!(
            context,
            "VK_KHR_shader_bfloat16",
            vk::PhysicalDeviceShaderBfloat16FeaturesKHR
        );
        if bfloat16.shader_b_float16_type == vk::FALSE {
            return not_supported("shaderBFloat16Type is not supported by device");
        }

        if bfloat16.shader_b_float16_cooperative_matrix == vk::FALSE {
            return not_supported("shaderBFloat16CooperativeMatrix is not supported by device");
        }
    }

    let any_float8 = matches!(d.input_type, Ct::E5m2 | Ct::E4m3) || matches!(d.output_type, Ct::E5m2 | Ct::E4m3);
    if any_float8 {
        let float8 = query_features!(
            context,
            "VK_EXT_shader_float8",
            vk::PhysicalDeviceShaderFloat8FeaturesEXT
        );
        if float8.shader_float8 == vk::FALSE {
            return not_supported("shaderFloat8 is not supported by device");
        }

        if float8.shader_float8_cooperative_matrix == vk::FALSE {
            return not_supported("shaderFloat8CooperativeMatrix is not supported by device");
        }
    }

    Ok(())
}
