/// The cases `cooperative_matrix_run` runs: the ones `scripts/gen_cooperative_matrix_manifest.py` writes a shader for
fn is_ported(d: &CaseDef) -> bool {
    let runs = |t: Ct| !matches!(t, Ct::F64 | Ct::S64 | Ct::U64);
    !(is_transpose_test(d.test_type) && d.coopmat_feature == CoopMatFeature::Base)
        && !(d.use_type == UseType::Nv && (d.input_type.is_no_arithmetic() || d.output_type.is_no_arithmetic()))
        && runs(d.input_type)
        && runs(d.output_type)
}

impl TestCase for CooperativeMatrixTestCase {
    fn name(&self) -> &str {
        &self.name
    }

    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        check_support(context, &self.data)?;
        if !is_ported(&self.data) {
            return Err(TestError::NotPorted(
                "the cooperative matrix shader generator and instance only cover the base feature set, subgroup scope and linear addressing"
                    .to_string(),
            ));
        }
        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        BinaryCollection::new(&[])
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        if is_ported(&self.data) {
            Box::new(super::cooperative_matrix_run::CooperativeMatrixInstance::new(
                context, self.data, &self.key,
            ))
        } else {
            Box::new(NotPortedInstance)
        }
    }

    fn is_stub(&self) -> bool {
        !is_ported(&self.data)
    }
}

