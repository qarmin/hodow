/// Empty groups are not registered: upstream's carry no cases either, and the tree has hundreds of thousands of them
fn add_group(parent: &mut TestCaseGroup, group: TestCaseGroup) {
    if !group.children().is_empty() {
        parent.add_child(group);
    }
}

