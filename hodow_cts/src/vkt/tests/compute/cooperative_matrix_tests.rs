/// `Context::get*Features*` for a struct vulkanalia has: all false when the extension is not enabled on the device
macro_rules! query_features {
    ($context:expr, $extension:expr, $ty:ty) => {{
        let mut features = <$ty>::default();
        if $context.is_device_functionality_supported($extension) {
            let mut features2 = vk::PhysicalDeviceFeatures2::builder().push_next(&mut features);
            unsafe {
                $context
                    .get_instance()
                    .get_physical_device_features2($context.get_physical_device(), &mut features2)
            };
        }
        features
    }};
}

/// One `VkBool32` member (index `field`) of a feature struct vulkanalia lacks, described by its `VkStructureType` and size
pub fn raw_feature(context: &Context<'_>, extension: &str, s_type: i32, size: usize, field: usize) -> bool {
    if !context.is_device_functionality_supported(extension) {
        return false;
    }
    let mut words = vec![0u64; size.div_ceil(8)];
    let base = words.as_mut_ptr();
    unsafe { base.cast::<i32>().write(s_type) };
    let mut features2 = vk::PhysicalDeviceFeatures2::default();
    features2.next = base.cast();
    unsafe {
        context
            .get_instance()
            .get_physical_device_features2(context.get_physical_device(), &mut features2)
    };
    unsafe { base.cast::<u32>().add(4 + field).read() != 0 }
}

/// `VkPhysicalDeviceCooperativeMatrixMaintenance1FeaturesEXT` member by index: properties2, reductions, conversions, perElementOperations, getCoordinate
pub fn maintenance1_feature(context: &Context<'_>, field: usize) -> bool {
    raw_feature(context, "VK_EXT_cooperative_matrix_maintenance1", 1000659000, 40, field)
}

