// Tests for VK_EXT_fragment_shader_interlock. These tests render a set of overlapping full-screen quads that use
// image or buffer reads and writes to accumulate values into a result image/buffer. They use fragment shader
// interlock to avoid race conditions on the read/write and validate that the final result includes all the writes.
// Each fragment shader invocation computes a coordinate, and does a read/modify/write into the image or buffer,
// inside the interlock. The value in memory accumulates a bitmask indicating which primitives or samples have
// already run through the interlock. e.g. for single sample, PIXEL_UNORDERED mode, there is one bit in the bitmask
// for each primitive and each primitive ORs in its own bit. For PIXEL_ORDERED mode, each invocation also tests that
// all the previous primitives (less significant bits) are also set, else it clobbers the value. Sample and
// shading_rate interlock are variants of this where there is one value per sample or per coarse fragment location,
// respectively. When there are multiple samples per fragment, we merge in the whole sample mask. But within a pixel,
// we don't try to distinguish primitive order between samples on the internal diagonal of the quad (triangle strip).
//
// Every fragment shader variant is generated by `scripts/gen_fsi_programs.py`; `program_name` is its naming scheme.

