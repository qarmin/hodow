#[derive(Clone, Copy, PartialEq, Eq)]
enum Resource {
    Ssbo,
    Image,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Interlock {
    PixelOrdered,
    PixelUnordered,
    SampleOrdered,
    SampleUnordered,
    ShadingRateOrdered,
    ShadingRateUnordered,
}

#[derive(Clone, Copy)]
struct CaseDef {
    dim: u32,
    res_type: Resource,
    interlock: Interlock,
    samples: u32,
    kill_odd: bool,
    sample_shading: bool,
}

impl CaseDef {
    fn is_sample_interlock(&self) -> bool {
        self.sample_shading
            || self.interlock == Interlock::SampleOrdered
            || self.interlock == Interlock::SampleUnordered
    }

    fn is_shading_rate(&self) -> bool {
        self.interlock == Interlock::ShadingRateOrdered || self.interlock == Interlock::ShadingRateUnordered
    }

    /// `bitsPerQuad`
    fn bits_per_quad(&self) -> u32 {
        let mut bpq = self.samples;

        if self.is_sample_interlock() {
            bpq = 1;
        } else if self.is_shading_rate() {
            bpq *= 4;
        }

        bpq
    }

    /// The name `scripts/gen_fsi_programs.py` gives this case's fragment shader.
    fn program_name(&self, resource_name: &str, interlock_name: &str) -> String {
        format!(
            "frag_{resource_name}_{interlock_name}_{}_{}_{}_{}",
            self.samples, self.sample_shading as u32, self.kill_odd as u32, self.dim
        )
    }
}

struct FsiTestCase {
    name: String,
    data: CaseDef,
    program: String,
}

impl TestCase for FsiTestCase {
    fn name(&self) -> &str {
        &self.name
    }

    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        context.require_device_functionality("VK_EXT_fragment_shader_interlock")?;

        let mut interlock_features = vk::PhysicalDeviceFragmentShaderInterlockFeaturesEXT::default();
        let mut shading_rate_features = vk::PhysicalDeviceFragmentShadingRateFeaturesKHR::default();
        let mut features2 = vk::PhysicalDeviceFeatures2::builder().push_next(&mut interlock_features);
        if context.is_device_functionality_supported("VK_KHR_fragment_shading_rate") {
            features2 = features2.push_next(&mut shading_rate_features);
        }
        unsafe {
            context
                .get_instance()
                .get_physical_device_features2(context.get_physical_device(), &mut features2)
        };

        let data = &self.data;

        if (data.interlock == Interlock::SampleOrdered || data.interlock == Interlock::SampleUnordered)
            && interlock_features.fragment_shader_sample_interlock == vk::FALSE
        {
            return Err(TestError::NotSupported(
                "Fragment shader sample interlock not supported".to_string(),
            ));
        }

        if (data.interlock == Interlock::PixelOrdered || data.interlock == Interlock::PixelUnordered)
            && interlock_features.fragment_shader_pixel_interlock == vk::FALSE
        {
            return Err(TestError::NotSupported(
                "Fragment shader pixel interlock not supported".to_string(),
            ));
        }

        if data.is_shading_rate() && interlock_features.fragment_shader_shading_rate_interlock == vk::FALSE {
            return Err(TestError::NotSupported(
                "Fragment shader shading rate interlock not supported".to_string(),
            ));
        }
        if data.is_shading_rate() {
            let mut shading_rate_properties = vk::PhysicalDeviceFragmentShadingRatePropertiesKHR::default();
            if context.is_device_functionality_supported("VK_KHR_fragment_shading_rate") {
                let mut properties2 = vk::PhysicalDeviceProperties2::builder().push_next(&mut shading_rate_properties);
                unsafe {
                    context
                        .get_instance()
                        .get_physical_device_properties2(context.get_physical_device(), &mut properties2)
                };
            }
            if shading_rate_features.pipeline_fragment_shading_rate == vk::FALSE
                || shading_rate_properties.fragment_shading_rate_with_fragment_shader_interlock == vk::FALSE
            {
                return Err(TestError::NotSupported(
                    "fragment shading rate not supported".to_string(),
                ));
            }
        }

        if data.is_sample_interlock() && context.get_device_features().sample_rate_shading == vk::FALSE {
            return Err(TestError::NotSupported(
                "Requested core feature is not supported: sampleRateShading".to_string(),
            ));
        }
        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        FSI_BASIC.programs
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(FsiTestInstance {
            context,
            data: self.data,
            program: &self.program,
        })
    }
}

struct FsiTestInstance<'a> {
    context: &'a Context<'a>,
    data: CaseDef,
    program: &'a str,
}

impl TestInstance for FsiTestInstance<'_> {
    fn iterate(&mut self) -> TestOutcome {
        let context = self.context;
        let data = self.data;
        let device = context.get_device();
        let allocator = context.get_default_allocator();
        let all_shader_stages = vk::ShaderStageFlags::VERTEX | vk::ShaderStageFlags::FRAGMENT;
        let all_pipeline_stages = vk::PipelineStageFlags::COLOR_ATTACHMENT_OUTPUT
            | vk::PipelineStageFlags::VERTEX_SHADER
            | vk::PipelineStageFlags::FRAGMENT_SHADER;
        let bind_point = vk::PipelineBindPoint::GRAPHICS;

        // Create a layout and allocate a descriptor set for it.
        let descriptor_set_layout = DescriptorSetLayoutBuilder::new()
            .add_single_binding(vk::DescriptorType::STORAGE_IMAGE, all_shader_stages)
            .add_single_binding(vk::DescriptorType::STORAGE_BUFFER, all_shader_stages)
            .build(device)?;
        let descriptor_pool = DescriptorPoolBuilder::new()
            .add_type(vk::DescriptorType::STORAGE_IMAGE, 1)
            .add_type(vk::DescriptorType::STORAGE_BUFFER, 1)
            .build(device, vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET, 1)?;
        let descriptor_set = make_descriptor_set(device, *descriptor_pool, *descriptor_set_layout)?;

        // one uint per sample (max of 4 samples)
        let buffer_size = (data.dim * data.dim) as vk::DeviceSize * std::mem::size_of::<u32>() as vk::DeviceSize * 4;

        let buffer = BufferWithMemory::new(
            device,
            allocator,
            make_buffer_create_info(
                buffer_size,
                vk::BufferUsageFlags::TRANSFER_SRC
                    | vk::BufferUsageFlags::TRANSFER_DST
                    | vk::BufferUsageFlags::STORAGE_BUFFER,
            ),
            MemoryRequirement::LOCAL,
        )?;

        let queue = context.get_universal_queue();
        let cmd_pool = make_command_pool(device, context.get_universal_queue_family_index())?;
        let cmd_buffer = allocate_command_buffer(device, *cmd_pool, vk::CommandBufferLevel::PRIMARY)?;

        begin_command_buffer(device, *cmd_buffer)?;

        let set_layouts = [*descriptor_set_layout];
        let pipeline_layout = make_pipeline_layout(device, &set_layouts)?;

        let copy_buffer = BufferWithMemory::new(
            device,
            allocator,
            make_buffer_create_info(buffer_size, vk::BufferUsageFlags::TRANSFER_DST),
            MemoryRequirement::HOST_VISIBLE | MemoryRequirement::CACHED,
        )?;

        let image_info = vk::ImageCreateInfo::builder()
            .image_type(vk::ImageType::_2D)
            .format(vk::Format::R32_UINT)
            .extent(vk::Extent3D {
                width: data.dim * data.samples,
                height: data.dim,
                depth: 1,
            })
            .mip_levels(1)
            .array_layers(1)
            .samples(vk::SampleCountFlags::_1)
            .tiling(vk::ImageTiling::OPTIMAL)
            .usage(vk::ImageUsageFlags::STORAGE | vk::ImageUsageFlags::TRANSFER_SRC | vk::ImageUsageFlags::TRANSFER_DST)
            .sharing_mode(vk::SharingMode::EXCLUSIVE)
            .initial_layout(vk::ImageLayout::UNDEFINED)
            .build();
        let range = make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, 1, 0, 1);
        let image = ImageWithMemory::new(device, allocator, image_info, MemoryRequirement::ANY)?;
        let image_view = make_image_view(device, image.get(), vk::ImageViewType::_2D, vk::Format::R32_UINT, range)?;

        let image_descriptor = [vk::DescriptorImageInfo {
            sampler: vk::Sampler::null(),
            image_view: *image_view,
            image_layout: vk::ImageLayout::GENERAL,
        }];
        let buffer_descriptor = [vk::DescriptorBufferInfo {
            buffer: buffer.get(),
            offset: 0,
            range: buffer_size,
        }];
        let writes = [
            vk::WriteDescriptorSet::builder()
                .dst_set(*descriptor_set)
                .dst_binding(0)
                .descriptor_type(vk::DescriptorType::STORAGE_IMAGE)
                .image_info(&image_descriptor)
                .build(),
            vk::WriteDescriptorSet::builder()
                .dst_set(*descriptor_set)
                .dst_binding(1)
                .descriptor_type(vk::DescriptorType::STORAGE_BUFFER)
                .buffer_info(&buffer_descriptor)
                .build(),
        ];
        unsafe { device.update_descriptor_sets(&writes, &[] as &[vk::CopyDescriptorSet]) };

        unsafe {
            device.cmd_bind_descriptor_sets(*cmd_buffer, bind_point, *pipeline_layout, 0, &[*descriptor_set], &[])
        };

        let shading_rate_enable = data.is_shading_rate();

        // A render pass and framebuffer with no attachments at all.
        let subpasses = [vk::SubpassDescription::builder()
            .pipeline_bind_point(vk::PipelineBindPoint::GRAPHICS)
            .build()];
        let render_pass_info = vk::RenderPassCreateInfo::builder().subpasses(&subpasses);
        let render_pass = Unique::new(
            device,
            unsafe { device.create_render_pass(&render_pass_info, None) }.vk_check("vkCreateRenderPass")?,
        );
        let framebuffer = make_framebuffer(device, *render_pass, &[], data.dim, data.dim, 1)?;

        let binaries = context.get_binary_collection();
        let fs = create_shader_module(device, binaries.get(self.program)?)?;
        let vs = create_shader_module(device, binaries.get("vert")?)?;

        let mut state =
            DrawPipelineState::new(vk::PrimitiveTopology::TRIANGLE_STRIP).with_full_viewport(data.dim, data.dim);
        state.rasterization.front_face = vk::FrontFace::CLOCKWISE;
        state.rasterization.depth_bias_enable = vk::FALSE;
        state.samples = vk::SampleCountFlags::from_bits_truncate(data.samples);
        state.sample_shading = data.sample_shading;
        state.color_attachment_count = 0;
        state.fragment_shading_rate = shading_rate_enable;
        let pipeline = create_draw_pipeline(
            device,
            *pipeline_layout,
            *render_pass,
            &[
                (vk::ShaderStageFlags::VERTEX, *vs),
                (vk::ShaderStageFlags::FRAGMENT, *fs),
            ],
            &state,
        )?;

        let image_barrier = make_image_memory_barrier(
            vk::AccessFlags::empty(),
            vk::AccessFlags::TRANSFER_WRITE,
            vk::ImageLayout::UNDEFINED,
            vk::ImageLayout::GENERAL,
            image.get(),
            range,
        );

        unsafe {
            device.cmd_pipeline_barrier(
                *cmd_buffer,
                vk::PipelineStageFlags::BOTTOM_OF_PIPE,
                vk::PipelineStageFlags::TRANSFER,
                vk::DependencyFlags::empty(),
                &[] as &[vk::MemoryBarrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[image_barrier],
            );

            device.cmd_bind_pipeline(*cmd_buffer, bind_point, *pipeline);

            let clear_color = vk::ClearColorValue { uint32: [0, 0, 0, 0] };
            device.cmd_clear_color_image(
                *cmd_buffer,
                image.get(),
                vk::ImageLayout::GENERAL,
                &clear_color,
                &[range],
            );

            device.cmd_fill_buffer(*cmd_buffer, buffer.get(), 0, buffer_size, 0);

            let mem_barrier = vk::MemoryBarrier::builder()
                .src_access_mask(vk::AccessFlags::TRANSFER_WRITE)
                .dst_access_mask(
                    vk::AccessFlags::COLOR_ATTACHMENT_READ
                        | vk::AccessFlags::SHADER_READ
                        | vk::AccessFlags::SHADER_WRITE,
                )
                .build();
            device.cmd_pipeline_barrier(
                *cmd_buffer,
                vk::PipelineStageFlags::TRANSFER,
                all_pipeline_stages,
                vk::DependencyFlags::empty(),
                &[mem_barrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[] as &[vk::ImageMemoryBarrier],
            );

            let begin_info = vk::RenderPassBeginInfo::builder()
                .render_pass(*render_pass)
                .framebuffer(*framebuffer)
                .render_area(rect_2d(data.dim, data.dim));
            device.cmd_begin_render_pass(*cmd_buffer, &begin_info, vk::SubpassContents::INLINE);

            // Draw N fullscreen "quads", one per instance.
            let n = 32 / data.bits_per_quad();
            device.cmd_draw(*cmd_buffer, 4, n, 0, 0);

            device.cmd_end_render_pass(*cmd_buffer);

            let mem_barrier = vk::MemoryBarrier::builder()
                .src_access_mask(vk::AccessFlags::SHADER_READ | vk::AccessFlags::SHADER_WRITE)
                .dst_access_mask(vk::AccessFlags::TRANSFER_READ | vk::AccessFlags::TRANSFER_WRITE)
                .build();
            device.cmd_pipeline_barrier(
                *cmd_buffer,
                all_pipeline_stages,
                vk::PipelineStageFlags::TRANSFER,
                vk::DependencyFlags::empty(),
                &[mem_barrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[] as &[vk::ImageMemoryBarrier],
            );

            let mut copy_dim_x = data.dim;
            let mut copy_dim_y = data.dim;

            if data.is_sample_interlock() {
                copy_dim_x *= data.samples;
            }

            if shading_rate_enable {
                copy_dim_x /= 2;
                copy_dim_y /= 2;
            }

            if data.res_type == Resource::Image {
                let copy_region = make_buffer_image_copy(
                    vk::Extent3D {
                        width: copy_dim_x,
                        height: copy_dim_y,
                        depth: 1,
                    },
                    make_image_subresource_layers(vk::ImageAspectFlags::COLOR, 0, 0, 1),
                );
                device.cmd_copy_image_to_buffer(
                    *cmd_buffer,
                    image.get(),
                    vk::ImageLayout::GENERAL,
                    copy_buffer.get(),
                    &[copy_region],
                );
            } else {
                let copy_region = vk::BufferCopy {
                    src_offset: 0,
                    dst_offset: 0,
                    size: (copy_dim_x * copy_dim_y) as vk::DeviceSize * std::mem::size_of::<u32>() as vk::DeviceSize,
                };
                device.cmd_copy_buffer(*cmd_buffer, buffer.get(), copy_buffer.get(), &[copy_region]);
            }

            let mem_barrier = vk::MemoryBarrier::builder()
                .src_access_mask(vk::AccessFlags::TRANSFER_WRITE)
                .dst_access_mask(vk::AccessFlags::HOST_READ)
                .build();
            device.cmd_pipeline_barrier(
                *cmd_buffer,
                vk::PipelineStageFlags::TRANSFER,
                vk::PipelineStageFlags::HOST,
                vk::DependencyFlags::empty(),
                &[mem_barrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[] as &[vk::ImageMemoryBarrier],
            );

            end_command_buffer(device, *cmd_buffer)?;
            submit_commands_and_wait(device, queue, *cmd_buffer)?;

            invalidate_alloc(device, copy_buffer.get_allocation())?;
            let count = (copy_dim_x * copy_dim_y) as usize;
            let values = std::slice::from_raw_parts(copy_buffer.get_allocation().get_host_ptr().cast::<u32>(), count);
            let expected_value = 0xFFFF_FFFFu32;

            let mut failed = false;
            for (i, &value) in values.iter().enumerate() {
                if data.kill_odd && (i & 1) != 0 {
                    if value != 0 {
                        failed = true;
                    }
                } else if value != expected_value {
                    failed = true;
                }
            }

            Ok(if failed {
                TestStatus::fail("Fail")
            } else {
                TestStatus::pass("Pass")
            })
        }
    }
}

/// `createBasicTests`
pub fn create_basic_tests() -> TestCaseGroup {
    let mut group = TestCaseGroup::new("basic");

    let dim_cases = [
        (8u32, "8x8"),
        (16, "16x16"),
        (32, "32x32"),
        (64, "64x64"),
        (128, "128x128"),
        (256, "256x256"),
        (512, "512x512"),
        (1024, "1024x1024"),
    ];
    let res_cases = [(Resource::Image, "image"), (Resource::Ssbo, "ssbo")];
    let kill_cases = [(false, "nodiscard"), (true, "discard")];
    let samp_cases = [(1u32, "1xaa"), (4, "4xaa")];
    let ss_cases = [(false, "no_sample_shading"), (true, "sample_shading")];
    let int_cases = [
        (Interlock::PixelOrdered, "pixel_ordered"),
        (Interlock::PixelUnordered, "pixel_unordered"),
        (Interlock::SampleOrdered, "sample_ordered"),
        (Interlock::SampleUnordered, "sample_unordered"),
        (Interlock::ShadingRateOrdered, "shading_rate_ordered"),
        (Interlock::ShadingRateUnordered, "shading_rate_unordered"),
    ];

    for (kill_odd, kill_name) in kill_cases {
        let mut kill_group = TestCaseGroup::new(kill_name);
        for (res_type, res_name) in res_cases {
            let mut res_group = TestCaseGroup::new(res_name);
            for (interlock, int_name) in int_cases {
                let mut int_group = TestCaseGroup::new(int_name);
                for (samples, samp_name) in samp_cases {
                    let mut samp_group = TestCaseGroup::new(samp_name);
                    for (sample_shading, ss_name) in ss_cases {
                        let mut ss_group = TestCaseGroup::new(ss_name);
                        for (dim, dim_name) in dim_cases {
                            let c = CaseDef {
                                dim,
                                res_type,
                                interlock,
                                samples,
                                kill_odd,
                                sample_shading,
                            };

                            if c.sample_shading && c.samples == 1 {
                                continue;
                            }

                            let program = c.program_name(res_name, int_name);
                            ss_group.add_child(Box::new(FsiTestCase {
                                name: dim_name.to_string(),
                                data: c,
                                program,
                            }) as Box<dyn TestCase>);
                        }
                        samp_group.add_child(ss_group);
                    }
                    int_group.add_child(samp_group);
                }
                res_group.add_child(int_group);
            }
            kill_group.add_child(res_group);
        }
        group.add_child(kill_group);
    }
    group
}
