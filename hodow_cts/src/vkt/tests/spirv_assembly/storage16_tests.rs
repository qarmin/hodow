fn field<'a>(spec: &'a str, key: &str) -> &'a str {
    spec.split(';')
        .find_map(|entry| entry.strip_prefix(key).and_then(|rest| rest.strip_prefix('=')))
        .unwrap_or_else(|| panic!("16 bit storage spec without {key}"))
}

fn flatten(elements: Vec<Vec<u8>>) -> Vec<u8> {
    elements.concat()
}

/// `compare32BitFloat`
fn compare_32bit_float(expected: f32, returned: f32) -> bool {
    let is_denorm = |value: f32| value.to_bits() & 0x7f80_0000 == 0 && value.to_bits() & 0x007f_ffff != 0;
    let is_zero = |value: f32| value.to_bits() & 0x7fff_ffff == 0;

    // Any denormalized value potentially generated by any instruction in a shader may be flushed to 0.
    if is_denorm(expected) && is_zero(returned) {
        return true;
    }

    // Any denormalized value input into a shader may be flushed to 0.
    let original = float32_to_float16(expected);
    if original & 0x7c00 == 0 && original & 0x3ff != 0 && is_zero(returned) {
        return true;
    }

    if expected.is_nan() {
        return returned.is_nan();
    }

    returned == expected
}

pub(super) fn verify_float32(_inputs: &[Vec<u8>], outputs: &[Vec<u8>], expected: &[Vec<u8>]) -> bool {
    outputs.iter().zip(expected).all(|(output, expected)| {
        expected
            .chunks_exact(4)
            .zip(output.chunks_exact(4))
            .all(|(expected, returned)| {
                compare_32bit_float(
                    f32::from_le_bytes(expected.try_into().expect("four bytes")),
                    f32::from_le_bytes(returned.try_into().expect("four bytes")),
                )
            })
    })
}

/// `addCompute16bitStorageUniform16To32ChainAccessGroup`'s spec of one case.
fn chain_access_spec(spec_text: &str) -> ComputeShaderSpec {
    let capability: usize = field(spec_text, "cap").parse().expect("a capability");
    let data_type: usize = field(spec_text, "type").parse().expect("a data type");
    let indices: Vec<usize> = field(spec_text, "idx")
        .split('.')
        .map(|index| index.parse().expect("an index"))
        .collect();
    let (x, y, z, w) = (indices[0], indices[1], indices[2], indices[3]);

    let mut rnd = Random::new(de_string_hash("uniform_16_to_32_chainaccess"));
    let input_data_float = flatten(get_float16s(&mut rnd, STRUCT_SIZE * 4));
    let input_data_int = flatten(get_int16s(&mut rnd, STRUCT_SIZE * 4));

    // Offsets are in multiples of 16 bits. Floats use a matrix as the second field, which has different layout rules than the 2D array of the integers.
    let field_offsets_float = [[0, 8, 0], [24, 24, 1], [120, 1, 0]];
    let field_offsets_int = [[0, 8, 0], [24, 24, 8], [120, 1, 0]];
    let offset_float =
        x * STRUCT_SIZE + field_offsets_float[y][0] + field_offsets_float[y][1] * z + field_offsets_float[y][2] * w;
    let offset_int =
        x * STRUCT_SIZE + field_offsets_int[y][0] + field_offsets_int[y][1] * z + field_offsets_int[y][2] * w;

    let read16 = |data: &[u8], offset: usize| u16::from_le_bytes([data[offset * 2], data[offset * 2 + 1]]);

    let mut spec = ComputeShaderSpec {
        num_work_groups: [1, 1, 1],
        extensions: vec!["VK_KHR_16bit_storage".to_string()],
        ..Default::default()
    };
    match data_type {
        0 => {
            spec.verify_io = Some(verify_float32);
            spec.inputs.push(input_data_float.clone());
            spec.outputs.push(
                float16_to_float32(read16(&input_data_float, offset_float))
                    .to_le_bytes()
                    .to_vec(),
            );
        }
        1 => {
            spec.inputs.push(input_data_int.clone());
            spec.outputs.push(
                i32::from(read16(&input_data_int, offset_int) as i16)
                    .to_le_bytes()
                    .to_vec(),
            );
        }
        _ => {
            spec.inputs.push(input_data_int.clone());
            spec.outputs
                .push(i32::from(read16(&input_data_int, offset_int)).to_le_bytes().to_vec());
        }
    }

    // `uniform_buffer_block` is a storage buffer declared as a BufferBlock, `uniform` a uniform buffer.
    if capability == 0 {
        spec.features.push(RequiredFeature::StorageBuffer16BitAccess);
    } else {
        spec.uniform_inputs = true;
        spec.features.push(RequiredFeature::UniformAndStorageBuffer16BitAccess);
    }
    spec
}

fn to_u16s(bytes: &[u8]) -> Vec<u16> {
    bytes
        .chunks_exact(2)
        .map(|pair| u16::from_le_bytes([pair[0], pair[1]]))
        .collect()
}

fn u16s_to_bytes(values: &[u16]) -> Vec<u8> {
    values.iter().flat_map(|value| value.to_le_bytes()).collect()
}

fn storage_features(capability: usize, spec: &mut ComputeShaderSpec) {
    spec.extensions.push("VK_KHR_16bit_storage".to_string());
    if capability == 0 {
        spec.features.push(RequiredFeature::StorageBuffer16BitAccess);
    } else {
        spec.uniform_inputs = true;
        spec.features.push(RequiredFeature::UniformAndStorageBuffer16BitAccess);
    }
}

/// `addCompute16bitStorageUniform16To32Group`'s spec of one case.
fn uniform_16_to_32_spec(spec_text: &str) -> ComputeShaderSpec {
    let number = |key: &str| -> i64 {
        field(spec_text, key)
            .parse()
            .unwrap_or_else(|_| panic!("16 bit storage spec with a bad {key}"))
    };
    const NUM_ELEMENTS: usize = 128;
    let (skip, capability, count, stride, constant) = (
        number("skip") as usize,
        number("cap") as usize,
        number("count") as usize,
        number("stride") as usize,
        number("const"),
    );
    let scalars_per_item = NUM_ELEMENTS / count;

    let mut rnd = Random::new(de_string_hash("uniform_16_to_32"));
    for _ in 0..skip {
        rnd.get_uint32();
    }

    let mut spec = ComputeShaderSpec {
        num_work_groups: [count as u32, 1, 1],
        ..Default::default()
    };
    storage_features(capability, &mut spec);

    if field(spec_text, "kind") == "float" {
        let float16_data = to_u16s(&flatten(get_float16s(&mut rnd, NUM_ELEMENTS * stride)));
        let float32_data: Vec<f32> = (0..count)
            .flat_map(|num_idx| (0..scalars_per_item).map(move |scalar_idx| (num_idx, scalar_idx)))
            .map(|(num_idx, scalar_idx)| float16_to_float32(float16_data[num_idx * stride + scalar_idx]))
            .collect();
        let output: Vec<f32> = if constant >= 0 {
            let num_floats = NUM_ELEMENTS / count;
            (0..NUM_ELEMENTS)
                .map(|num_idx| float32_data[constant as usize * num_floats + num_idx % num_floats])
                .collect()
        } else {
            float32_data
        };

        let input = if number("matrix") != 0 {
            // Matrices are treated as arrays of vectors: a vec4 is as large as eight f16, of which two are used and the other six are zero.
            let mut matrix_data = Vec::with_capacity(float16_data.len() * 4);
            for data_idx in 0..float16_data.len() / 2 {
                matrix_data.push(float16_data[data_idx * 2]);
                matrix_data.push(float16_data[data_idx * 2 + 1]);
                matrix_data.extend([0u16; 6]);
            }
            u16s_to_bytes(&matrix_data)
        } else {
            u16s_to_bytes(&float16_data)
        };
        spec.verify_io = Some(verify_float32);
        spec.inputs.push(input);
        spec.outputs
            .push(output.iter().flat_map(|value| value.to_le_bytes()).collect());
    } else {
        let inputs: Vec<i16> = to_u16s(&flatten(get_int16s(&mut rnd, NUM_ELEMENTS * stride)))
            .into_iter()
            .map(|value| value as i16)
            .collect();
        let mut signed_outputs = Vec::with_capacity(NUM_ELEMENTS);
        let mut unsigned_outputs = Vec::with_capacity(NUM_ELEMENTS);
        for num_ndx in 0..count {
            for scalar_idx in 0..scalars_per_item {
                let input = inputs[num_ndx * stride + scalar_idx];
                unsigned_outputs.push(i32::from(input as u16));
                signed_outputs.push(i32::from(input));
            }
        }
        let is_signed = number("signed") != 0;
        let output: Vec<i32> = if constant >= 0 {
            (0..NUM_ELEMENTS)
                .map(|num_idx| {
                    let idx = constant as usize * scalars_per_item + num_idx % scalars_per_item;
                    if is_signed {
                        signed_outputs[idx]
                    } else {
                        unsigned_outputs[idx]
                    }
                })
                .collect()
        } else if is_signed {
            signed_outputs
        } else {
            unsigned_outputs
        };
        spec.inputs
            .push(inputs.iter().flat_map(|value| value.to_le_bytes()).collect());
        spec.outputs
            .push(output.iter().flat_map(|value| value.to_le_bytes()).collect());
    }
    spec
}

/// `compare16BitFloat(float, uint16_t, RoundingModeFlags)`: `flags` has bit 0 for RTE and bit 1 for RTZ, any of them accepted.
pub(super) fn compare_16bit_float(original: f32, returned: u16, flags: u32) -> bool {
    let returned_is_zero = returned & 0x7fff == 0;
    let original_bits = original.to_bits();
    let original_is_zero = original_bits & 0x7fff_ffff == 0;
    let original_is_denorm = original_bits & 0x7f80_0000 == 0 && original_bits & 0x007f_ffff != 0;
    let original_is_inf = original_bits & 0x7fff_ffff == 0x7f80_0000;

    // Zero is turned into zero under both RTE and RTZ.
    if original_is_zero {
        return returned_is_zero;
    }

    // Any denormalized value input into a shader may be flushed to 0.
    if original_is_denorm && returned_is_zero {
        return true;
    }

    // Inf is always turned into Inf with the same sign.
    if original_is_inf {
        return returned & 0x7fff == 0x7c00 && (returned >> 15) == (original_bits >> 31) as u16;
    }

    // NaN is always turned into NaN.
    if original.is_nan() {
        return returned & 0x7c00 == 0x7c00 && returned & 0x3ff != 0;
    }

    for bit in 0..2 {
        if flags & (1 << bit) == 0 {
            continue;
        }
        let expected = float32_to_float16_round(original, bit == 1);

        // Any denormalized value potentially generated by any instruction in a shader may be flushed to 0.
        if expected & 0x7c00 == 0 && expected & 0x3ff != 0 && returned_is_zero {
            return true;
        }

        if expected == returned {
            return true;
        }
    }
    false
}

/// `computeCheck16BitFloats<RoundingMode>`: the input is the original floats and the output the 16 bit floats the shader made of them.
pub(super) fn verify_float16_results<const FLAGS: u32>(
    inputs: &[Vec<u8>],
    outputs: &[Vec<u8>],
    expected: &[Vec<u8>],
) -> bool {
    outputs
        .iter()
        .zip(inputs)
        .zip(expected)
        .all(|((output, input), expected)| {
            let count = expected.len() / 2;
            let input_stride = (input.len() / 4) / count;
            (0..count).all(|num_ndx| {
                let original = f32::from_le_bytes(
                    input[num_ndx * input_stride * 4..num_ndx * input_stride * 4 + 4]
                        .try_into()
                        .expect("four bytes"),
                );
                let returned = u16::from_le_bytes([output[num_ndx * 2], output[num_ndx * 2 + 1]]);
                compare_16bit_float(original, returned, FLAGS)
            })
        })
}

/// `addCompute16bitStorageUniform32To16Group`'s spec of one case.
fn uniform_32_to_16_spec(spec_text: &str) -> ComputeShaderSpec {
    let number = |key: &str| -> i64 {
        field(spec_text, key)
            .parse()
            .unwrap_or_else(|_| panic!("16 bit storage spec with a bad {key}"))
    };
    const NUM_ELEMENTS: usize = 128;
    let (skip, capability, count, stride) = (
        number("skip") as usize,
        number("cap") as usize,
        number("count") as usize,
        number("stride") as usize,
    );
    let scalars_per_item = NUM_ELEMENTS / count;

    let mut rnd = Random::new(de_string_hash("uniform_32_to_16"));
    for _ in 0..skip {
        rnd.get_uint32();
    }

    let mut spec = ComputeShaderSpec {
        num_work_groups: [count as u32, 1, 1],
        ..Default::default()
    };
    storage_features(capability, &mut spec);

    if field(spec_text, "kind") == "float" {
        spec.inputs.push(flatten(get_float32s(&mut rnd, NUM_ELEMENTS * stride)));
        // The check recalculates what it expects from the inputs; the expected output only has the size of the result.
        spec.outputs.push(vec![0u8; NUM_ELEMENTS * 2]);
        spec.verify_io = Some(match number("mode") {
            1 => verify_float16_results::<1>,
            2 => verify_float16_results::<2>,
            _ => verify_float16_results::<3>,
        });
    } else {
        let inputs = flatten(get_int32s(&mut rnd, NUM_ELEMENTS * stride));
        let values: Vec<i32> = inputs
            .chunks_exact(4)
            .map(|chunk| i32::from_le_bytes(chunk.try_into().expect("four bytes")))
            .collect();
        let mut outputs = Vec::with_capacity(NUM_ELEMENTS * 2);
        for num_ndx in 0..count {
            for scalar_idx in 0..scalars_per_item {
                outputs.extend((0xffff & values[num_ndx * stride + scalar_idx]).to_le_bytes()[..2].iter());
            }
        }
        spec.inputs.push(inputs);
        spec.outputs.push(outputs);
    }
    spec
}

/// `compare16BitFloat64`: the same rules as `compare_16bit_float` for a 64 bit original.
fn compare_16bit_float64(original: f64, returned: u16, flags: u32) -> bool {
    let returned_is_zero = returned & 0x7fff == 0;
    let original_bits = original.to_bits();
    let original_is_zero = original_bits & 0x7fff_ffff_ffff_ffff == 0;
    let original_is_denorm = original_bits & 0x7ff0_0000_0000_0000 == 0 && original_bits & 0x000f_ffff_ffff_ffff != 0;
    let original_is_inf = original_bits & 0x7fff_ffff_ffff_ffff == 0x7ff0_0000_0000_0000;

    if original_is_zero {
        return returned_is_zero;
    }
    if original_is_denorm && returned_is_zero {
        return true;
    }
    if original_is_inf {
        return returned & 0x7fff == 0x7c00 && (returned >> 15) as u64 == original_bits >> 63;
    }
    if original.is_nan() {
        return returned & 0x7c00 == 0x7c00 && returned & 0x3ff != 0;
    }

    for bit in 0..2 {
        if flags & (1 << bit) == 0 {
            continue;
        }
        let expected = float64_to_float16_round(original, bit == 1);
        if expected & 0x7c00 == 0 && expected & 0x3ff != 0 && returned_is_zero {
            return true;
        }
        if expected == returned {
            return true;
        }
    }
    false
}

/// `computeCheck16BitFloats64<RoundingMode>`: the packed originals are the inputs without the padding after each double.
pub(super) fn verify_float16_results64<const FLAGS: u32>(
    inputs: &[Vec<u8>],
    outputs: &[Vec<u8>],
    expected: &[Vec<u8>],
) -> bool {
    outputs
        .iter()
        .zip(inputs)
        .zip(expected)
        .all(|((output, input), expected)| {
            let count = expected.len() / 2;
            let input_stride = input.len() / count;
            (0..count).all(|num_ndx| {
                let original = f64::from_le_bytes(
                    input[num_ndx * input_stride..num_ndx * input_stride + 8]
                        .try_into()
                        .expect("eight bytes"),
                );
                let returned = u16::from_le_bytes([output[num_ndx * 2], output[num_ndx * 2 + 1]]);
                compare_16bit_float64(original, returned, FLAGS)
            })
        })
}

/// `addCompute16bitStorageUniform64To16Group`'s spec of one case.
fn uniform_64_to_16_spec(spec_text: &str) -> ComputeShaderSpec {
    let number = |key: &str| -> i64 {
        field(spec_text, key)
            .parse()
            .unwrap_or_else(|_| panic!("16 bit storage spec with a bad {key}"))
    };
    const NUM_ELEMENTS: usize = 128;
    let (capability, count, padding) = (
        number("cap") as usize,
        number("count") as u32,
        number("padding") as usize,
    );

    let mut rnd = Random::new(de_string_hash("uniform_64_to_16"));
    let data = get_float64s(&mut rnd, NUM_ELEMENTS);

    let mut spec = ComputeShaderSpec {
        num_work_groups: [count, 1, 1],
        ..Default::default()
    };
    // Float64Buffer pads every element with 0xff bytes.
    let mut bytes = Vec::with_capacity(NUM_ELEMENTS * (8 + padding));
    for element in &data {
        bytes.extend_from_slice(element);
        bytes.extend(std::iter::repeat_n(0xffu8, padding));
    }
    spec.inputs.push(bytes);
    spec.outputs.push(vec![0u8; NUM_ELEMENTS * 2]);
    spec.verify_io = Some(match number("mode") {
        1 => verify_float16_results64::<1>,
        2 => verify_float16_results64::<2>,
        _ => verify_float16_results64::<3>,
    });
    storage_features(capability, &mut spec);
    spec.features.push(RequiredFeature::ShaderFloat64);
    spec
}

/// `compare64BitFloat`
