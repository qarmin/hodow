struct BankInstance<'a> {
    context: &'a Context<'a>,
    test_type: TestType,
    num_banks: u32,
    member_offset: u32,
}

impl BankInstance<'_> {
    /// The constructor of `PushConstantBankTestInstance`: the queue family, extensions and the feature chain.
    fn create_device(&self) -> Result<(BankDevice, u32), TestError> {
        let vki = self.context.get_instance();
        let physical_device = self.context.get_physical_device();

        let required_flags = if self.test_type.is_compute() {
            vk::QueueFlags::COMPUTE
        } else {
            vk::QueueFlags::GRAPHICS
        };
        let families = unsafe { vki.get_physical_device_queue_family_properties(physical_device) };
        let queue_family_index = families
            .iter()
            .position(|family| family.queue_flags.contains(required_flags))
            .unwrap_or(0) as u32;

        let priorities = [1.0f32];
        let queue_infos = [vk::DeviceQueueCreateInfo::builder()
            .queue_family_index(queue_family_index)
            .queue_priorities(&priorities)
            .build()];

        let use_heap = self.test_type.uses_descriptor_heap();
        let mut extensions: Vec<&CStr> = vec![
            c"VK_NV_push_constant_bank",
            c"VK_KHR_maintenance5",
            c"VK_KHR_maintenance6",
        ];
        if use_heap {
            extensions.push(c"VK_EXT_descriptor_heap");
        }
        let extension_ptrs: Vec<*const c_char> = extensions.iter().map(|name| name.as_ptr()).collect();

        let mut bank_features = vk::PhysicalDevicePushConstantBankFeaturesNV {
            push_constant_bank: vk::TRUE,
            ..Default::default()
        };
        let mut maintenance5 = vk::PhysicalDeviceMaintenance5FeaturesKHR {
            maintenance5: vk::TRUE,
            ..Default::default()
        };
        let mut vulkan12 = vk::PhysicalDeviceVulkan12Features {
            buffer_device_address: if use_heap { vk::TRUE } else { vk::FALSE },
            ..Default::default()
        };
        let mut vulkan13 = vk::PhysicalDeviceVulkan13Features {
            dynamic_rendering: vk::TRUE,
            synchronization2: if use_heap { vk::TRUE } else { vk::FALSE },
            ..Default::default()
        };
        let mut heap_features = vk::PhysicalDeviceDescriptorHeapFeaturesEXT {
            descriptor_heap: vk::TRUE,
            ..Default::default()
        };
        let mut features2 = vk::PhysicalDeviceFeatures2::builder()
            .features(vk::PhysicalDeviceFeatures {
                vertex_pipeline_stores_and_atomics: vk::TRUE,
                ..Default::default()
            })
            .push_next(&mut vulkan12)
            .push_next(&mut vulkan13)
            .push_next(&mut maintenance5)
            .push_next(&mut bank_features);
        if use_heap {
            features2 = features2.push_next(&mut heap_features);
        }

        let device_info = vk::DeviceCreateInfo::builder()
            .queue_create_infos(&queue_infos)
            .enabled_extension_names(&extension_ptrs)
            .push_next(&mut features2);
        let device = unsafe { vki.create_device(physical_device, &device_info, None) }.vk_check("vkCreateDevice")?;
        Ok((BankDevice { device }, queue_family_index))
    }
}

/// `pushConstantsForBanks`
fn push_constants_for_banks(
    device: &Device,
    cmd: vk::CommandBuffer,
    layout: vk::PipelineLayout,
    stage_flags: vk::ShaderStageFlags,
    num_banks: u32,
    member_offset: u32,
) {
    let push_constant_size = member_offset + std::mem::size_of::<u32>() as u32;
    for bank in 0..num_banks {
        let mut push_data = vec![0u8; push_constant_size as usize];
        push_data[..4].copy_from_slice(&bank.to_ne_bytes());

        let bank_info = vk::PushConstantBankInfoNV {
            bank,
            ..Default::default()
        };
        let push_info = vk::PushConstantsInfo {
            s_type: vk::StructureType::PUSH_CONSTANTS_INFO,
            next: (&raw const bank_info).cast(),
            layout,
            stage_flags,
            offset: member_offset,
            size: push_constant_size,
            values: push_data.as_ptr().cast(),
        };
        unsafe { device.cmd_push_constants2_khr(cmd, &push_info) };
    }
}

/// `verifyResults`
fn verify_results(results: &[u32], num_banks: u32, member_offset: u32) -> TestOutcome {
    let mut pass = true;
    for bank in 0..num_banks {
        if results[bank as usize] != bank {
            let offset = if member_offset > 0 {
                format!(" with member_offset {member_offset}")
            } else {
                String::new()
            };
            log::error!("Bank {bank}{offset}: expected {bank}, got {}", results[bank as usize]);
            pass = false;
        }
    }
    Ok(if pass {
        TestStatus::pass("Pass")
    } else {
        TestStatus::fail("Result mismatch")
    })
}

impl TestInstance for BankInstance<'_> {
    /// `runComputeTest`, `runGraphicsTest`, `runComputeMemberOffsetTest` and `runGraphicsMemberOffsetTest`
    fn iterate(&mut self) -> TestOutcome {
        if self.test_type.uses_descriptor_heap() {
            return self.run_descriptor_heap_test();
        }
        let is_compute = self.test_type.is_compute();
        let member_offset = if matches!(
            self.test_type,
            TestType::ComputeMemberOffset | TestType::GraphicsMemberOffset
        ) {
            self.member_offset
        } else {
            0
        };

        let bank_properties = query_bank_properties(self.context);
        let max_banks = if is_compute {
            bank_properties.max_compute_push_constant_banks
        } else {
            bank_properties.max_graphics_push_constant_banks
        };
        let num_banks = self.num_banks.min(max_banks.min(MAX_TEST_BANKS));
        if num_banks < 1 {
            return Err(TestError::NotSupported(if is_compute {
                "No compute push constant banks available".to_string()
            } else {
                "No graphics push constant banks available".to_string()
            }));
        }

        let (bank_device, queue_family_index) = self.create_device()?;
        let vk = &bank_device.device;
        let queue = unsafe { vk.get_device_queue(queue_family_index, 0) };
        let allocator = SimpleAllocator::new(*self.context.get_default_allocator().memory_properties());
        let stage_flags = if is_compute {
            vk::ShaderStageFlags::COMPUTE
        } else {
            vk::ShaderStageFlags::VERTEX
        };

        // createResultBuffer
        let result_size = (std::mem::size_of::<u32>() as u32 * MAX_TEST_BANKS) as vk::DeviceSize;
        let result_buffer = BufferWithMemory::new(
            vk,
            &allocator,
            make_buffer_create_info(result_size, vk::BufferUsageFlags::STORAGE_BUFFER),
            MemoryRequirement::HOST_VISIBLE,
        )?;
        let result_ptr = result_buffer.get_allocation().get_host_ptr().cast::<u32>();
        for i in 0..MAX_TEST_BANKS as usize {
            unsafe { result_ptr.add(i).write(!0u32) };
        }
        flush_alloc(vk, result_buffer.get_allocation())?;

        // createDescriptorResources
        let descriptor_set_layout = DescriptorSetLayoutBuilder::new()
            .add_single_binding(vk::DescriptorType::STORAGE_BUFFER, stage_flags)
            .build(vk)?;
        let descriptor_pool = DescriptorPoolBuilder::new()
            .add_type(vk::DescriptorType::STORAGE_BUFFER, 1)
            .build(vk, vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET, 1)?;
        let descriptor_set = make_descriptor_set(vk, *descriptor_pool, *descriptor_set_layout)?;
        let result_info = make_descriptor_buffer_info(result_buffer.get(), 0, vk::WHOLE_SIZE);
        DescriptorSetUpdateBuilder::new()
            .write_single(
                descriptor_set.get(),
                Location::binding(0),
                vk::DescriptorType::STORAGE_BUFFER,
                &result_info,
            )
            .update(vk);

        // createPushConstantRanges: one range per bank
        let push_constant_size = member_offset + std::mem::size_of::<u32>() as u32;
        let ranges: Vec<vk::PushConstantRange> = (0..num_banks)
            .map(|_| vk::PushConstantRange {
                stage_flags,
                offset: 0,
                size: push_constant_size,
            })
            .collect();
        let set_layouts = [*descriptor_set_layout];
        let layout_info = vk::PipelineLayoutCreateInfo::builder()
            .set_layouts(&set_layouts)
            .push_constant_ranges(&ranges);
        let pipeline_layout = Unique::new(
            vk,
            unsafe { vk.create_pipeline_layout(&layout_info, None) }.vk_check("vkCreatePipelineLayout")?,
        );

        let shader_module = create_shader_module(vk, self.context.get_binary_collection().get("main")?)?;
        let pipeline_bind_point = if is_compute {
            vk::PipelineBindPoint::COMPUTE
        } else {
            vk::PipelineBindPoint::GRAPHICS
        };
        let pipeline = if is_compute {
            let stage = vk::PipelineShaderStageCreateInfo::builder()
                .stage(vk::ShaderStageFlags::COMPUTE)
                .module(*shader_module)
                .name(b"main\0")
                .build();
            let info = vk::ComputePipelineCreateInfo::builder()
                .stage(stage)
                .layout(*pipeline_layout)
                .base_pipeline_index(0)
                .build();
            unsafe { vk.create_compute_pipelines(vk::PipelineCache::null(), &[info], None) }
                .vk_check("vkCreateComputePipelines")?
                .0[0]
        } else {
            create_graphics_pipeline_with_discard(vk, *shader_module, *pipeline_layout)?
        };
        let pipeline = Unique::new(vk, pipeline);

        let cmd_pool = make_command_pool(vk, queue_family_index)?;
        let cmd_buffer = allocate_command_buffer(vk, *cmd_pool, vk::CommandBufferLevel::PRIMARY)?;
        let cmd = *cmd_buffer;

        begin_command_buffer(vk, cmd)?;
        if is_compute {
            unsafe {
                vk.cmd_bind_pipeline(cmd, pipeline_bind_point, *pipeline);
                vk.cmd_bind_descriptor_sets(
                    cmd,
                    pipeline_bind_point,
                    *pipeline_layout,
                    0,
                    &[descriptor_set.get()],
                    &[] as &[u32],
                );
            }
            push_constants_for_banks(vk, cmd, *pipeline_layout, stage_flags, num_banks, member_offset);
            unsafe { vk.cmd_dispatch(cmd, 1, 1, 1) };
        } else {
            let rendering_info = vk::RenderingInfo::builder()
                .render_area(vk::Rect2D {
                    offset: vk::Offset2D { x: 0, y: 0 },
                    extent: vk::Extent2D { width: 1, height: 1 },
                })
                .layer_count(1);
            unsafe {
                vk.cmd_begin_rendering(cmd, &rendering_info);
                vk.cmd_bind_pipeline(cmd, pipeline_bind_point, *pipeline);
                vk.cmd_bind_descriptor_sets(
                    cmd,
                    pipeline_bind_point,
                    *pipeline_layout,
                    0,
                    &[descriptor_set.get()],
                    &[] as &[u32],
                );
            }
            push_constants_for_banks(vk, cmd, *pipeline_layout, stage_flags, num_banks, member_offset);
            unsafe {
                vk.cmd_draw(cmd, 1, 1, 0, 0);
                vk.cmd_end_rendering(cmd);
            }
        }

        let memory_barrier = make_memory_barrier(vk::AccessFlags::SHADER_WRITE, vk::AccessFlags::HOST_READ);
        unsafe {
            vk.cmd_pipeline_barrier(
                cmd,
                if is_compute {
                    vk::PipelineStageFlags::COMPUTE_SHADER
                } else {
                    vk::PipelineStageFlags::VERTEX_SHADER
                },
                vk::PipelineStageFlags::HOST,
                vk::DependencyFlags::empty(),
                &[memory_barrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[] as &[vk::ImageMemoryBarrier],
            );
        }
        end_command_buffer(vk, cmd)?;
        submit_commands_and_wait(vk, queue, cmd)?;

        invalidate_alloc(vk, result_buffer.get_allocation())?;
        let results = unsafe { std::slice::from_raw_parts(result_ptr.cast_const(), MAX_TEST_BANKS as usize) };
        verify_results(results, num_banks, member_offset)
    }
}

/// `createGraphicsPipelineWithDiscard`: a point list, vertex stage only, rasterizer discard, dynamic rendering without attachments.
fn create_graphics_pipeline_with_discard(
    device: &Device,
    vertex_module: vk::ShaderModule,
    layout: vk::PipelineLayout,
) -> Result<vk::Pipeline, TestError> {
    let stages = [vk::PipelineShaderStageCreateInfo::builder()
        .stage(vk::ShaderStageFlags::VERTEX)
        .module(vertex_module)
        .name(b"main\0")
        .build()];
    let vertex_input = vk::PipelineVertexInputStateCreateInfo::builder();
    let input_assembly =
        vk::PipelineInputAssemblyStateCreateInfo::builder().topology(vk::PrimitiveTopology::POINT_LIST);
    let viewports = [vk::Viewport {
        x: 0.0,
        y: 0.0,
        width: 1.0,
        height: 1.0,
        min_depth: 0.0,
        max_depth: 1.0,
    }];
    let scissors = [vk::Rect2D {
        offset: vk::Offset2D { x: 0, y: 0 },
        extent: vk::Extent2D { width: 1, height: 1 },
    }];
    let viewport_state = vk::PipelineViewportStateCreateInfo::builder()
        .viewports(&viewports)
        .scissors(&scissors);
    let rasterization = vk::PipelineRasterizationStateCreateInfo::builder()
        .rasterizer_discard_enable(true)
        .polygon_mode(vk::PolygonMode::FILL)
        .line_width(1.0);
    let multisample = vk::PipelineMultisampleStateCreateInfo::builder().rasterization_samples(vk::SampleCountFlags::_1);
    let color_blend = vk::PipelineColorBlendStateCreateInfo::builder();
    let mut rendering = vk::PipelineRenderingCreateInfo::builder();

    let info = vk::GraphicsPipelineCreateInfo::builder()
        .stages(&stages)
        .vertex_input_state(&vertex_input)
        .input_assembly_state(&input_assembly)
        .viewport_state(&viewport_state)
        .rasterization_state(&rasterization)
        .multisample_state(&multisample)
        .color_blend_state(&color_blend)
        .layout(layout)
        .push_next(&mut rendering);
    let pipelines = unsafe { device.create_graphics_pipelines(vk::PipelineCache::null(), &[info], None) }
        .vk_check("vkCreateGraphicsPipelines")?
        .0;
    Ok(pipelines[0])
}

/// `pushDataForBanks`: `vkCmdPushDataEXT` once per bank, the bank number as the data
fn push_data_for_banks(device: &Device, cmd: vk::CommandBuffer, num_banks: u32) {
    for bank in 0..num_banks {
        let push_data = bank;
        let bank_info = vk::PushConstantBankInfoNV {
            bank,
            ..Default::default()
        };
        let push_info = vk::PushDataInfoEXT {
            s_type: vk::StructureType::PUSH_DATA_INFO_EXT,
            next: (&raw const bank_info).cast(),
            offset: 0,
            data: vk::HostAddressRangeConstEXT {
                address: (&raw const push_data).cast(),
                size: std::mem::size_of::<u32>(),
            },
        };
        unsafe { device.cmd_push_data_ext(cmd, &push_info) };
    }
}

fn align_up(value: vk::DeviceSize, alignment: vk::DeviceSize) -> vk::DeviceSize {
    value.div_ceil(alignment.max(1)) * alignment.max(1)
}

fn buffer_barrier2(
    buffer: vk::Buffer,
    dst_stage: vk::PipelineStageFlags2,
    dst_access: vk::AccessFlags2,
) -> vk::BufferMemoryBarrier2 {
    vk::BufferMemoryBarrier2 {
        src_stage_mask: vk::PipelineStageFlags2::HOST,
        src_access_mask: vk::AccessFlags2::HOST_WRITE,
        dst_stage_mask: dst_stage,
        dst_access_mask: dst_access,
        src_queue_family_index: vk::QUEUE_FAMILY_IGNORED,
        dst_queue_family_index: vk::QUEUE_FAMILY_IGNORED,
        buffer,
        offset: 0,
        size: vk::WHOLE_SIZE,
        ..Default::default()
    }
}

impl BankInstance<'_> {
    /// `runComputeDescriptorHeapTest` and `runGraphicsDescriptorHeapTest`: the result buffer is reached through a resource heap, the banks
    /// are written with `vkCmdPushDataEXT`.
    fn run_descriptor_heap_test(&self) -> TestOutcome {
        let is_compute = self.test_type.is_compute();
        let bank_properties = query_bank_properties(self.context);
        let max_banks = if is_compute {
            bank_properties.max_compute_push_data_banks
        } else {
            bank_properties.max_graphics_push_data_banks
        };
        let num_banks = self.num_banks.min(max_banks.min(MAX_TEST_BANKS));
        if num_banks < 1 {
            return Err(TestError::NotSupported(if is_compute {
                "No compute push data banks available".to_string()
            } else {
                "No graphics push data banks available".to_string()
            }));
        }

        let mut heap_properties = vk::PhysicalDeviceDescriptorHeapPropertiesEXT::default();
        let mut properties2 = vk::PhysicalDeviceProperties2::builder().push_next(&mut heap_properties);
        unsafe {
            self.context
                .get_instance()
                .get_physical_device_properties2(self.context.get_physical_device(), &mut properties2)
        };

        let (bank_device, queue_family_index) = self.create_device()?;
        let vk = &bank_device.device;
        let queue = unsafe { vk.get_device_queue(queue_family_index, 0) };
        let allocator = SimpleAllocator::new(*self.context.get_default_allocator().memory_properties());
        let stage_flags = if is_compute {
            vk::ShaderStageFlags::COMPUTE
        } else {
            vk::ShaderStageFlags::VERTEX
        };
        let shader_stage = if is_compute {
            vk::PipelineStageFlags2::COMPUTE_SHADER
        } else {
            vk::PipelineStageFlags2::VERTEX_SHADER
        };

        let buffer_descriptor_stride = align_up(
            heap_properties.buffer_descriptor_size,
            heap_properties.buffer_descriptor_alignment,
        );
        let resource_heap_reserved_offset = align_up(buffer_descriptor_stride, heap_properties.resource_heap_alignment);
        let resource_heap_size = resource_heap_reserved_offset + heap_properties.min_resource_heap_reserved_range;

        let heap_usage = vk::BufferUsageFlags::DESCRIPTOR_HEAP_EXT | vk::BufferUsageFlags::SHADER_DEVICE_ADDRESS;
        let resource_heap_buffer = BufferWithMemory::new(
            vk,
            &allocator,
            make_buffer_create_info(resource_heap_size, heap_usage),
            MemoryRequirement::HOST_VISIBLE | MemoryRequirement::DEVICE_ADDRESS,
        )?;
        let resource_heap_address = unsafe {
            vk.get_buffer_device_address(&vk::BufferDeviceAddressInfo::builder().buffer(resource_heap_buffer.get()))
        };

        let result_size = (std::mem::size_of::<u32>() as u32 * MAX_TEST_BANKS) as vk::DeviceSize;
        let result_buffer = BufferWithMemory::new(
            vk,
            &allocator,
            make_buffer_create_info(
                result_size,
                vk::BufferUsageFlags::STORAGE_BUFFER | vk::BufferUsageFlags::SHADER_DEVICE_ADDRESS,
            ),
            MemoryRequirement::HOST_VISIBLE | MemoryRequirement::DEVICE_ADDRESS,
        )?;
        let result_buffer_address = unsafe {
            vk.get_buffer_device_address(&vk::BufferDeviceAddressInfo::builder().buffer(result_buffer.get()))
        };
        let result_ptr = result_buffer.get_allocation().get_host_ptr().cast::<u32>();
        for i in 0..MAX_TEST_BANKS as usize {
            unsafe { result_ptr.add(i).write(!0u32) };
        }
        flush_alloc(vk, result_buffer.get_allocation())?;

        let result_address_range = vk::DeviceAddressRangeEXT {
            address: result_buffer_address,
            size: result_size,
        };
        let resource_info = vk::ResourceDescriptorInfoEXT {
            s_type: vk::StructureType::RESOURCE_DESCRIPTOR_INFO_EXT,
            next: std::ptr::null(),
            type_: vk::DescriptorType::STORAGE_BUFFER,
            data: vk::ResourceDescriptorDataEXT {
                address_range: &raw const result_address_range,
            },
        };
        let heap_host_range = vk::HostAddressRangeEXT {
            address: resource_heap_buffer.get_allocation().get_host_ptr().cast(),
            size: buffer_descriptor_stride as usize,
        };
        unsafe { vk.write_resource_descriptors_ext(&[resource_info], &[heap_host_range]) }
            .vk_check("vkWriteResourceDescriptorsEXT")?;
        flush_alloc(vk, resource_heap_buffer.get_allocation())?;

        let source_data = vk::DescriptorMappingSourceDataEXT {
            constant_offset: vk::DescriptorMappingSourceConstantOffsetEXT {
                heap_offset: 0,
                ..Default::default()
            },
        };
        let ssbo_mapping = vk::DescriptorSetAndBindingMappingEXT {
            s_type: vk::StructureType::DESCRIPTOR_SET_AND_BINDING_MAPPING_EXT,
            next: std::ptr::null(),
            descriptor_set: 0,
            first_binding: 0,
            binding_count: 1,
            resource_mask: vk::SpirvResourceTypeFlagsEXT::READ_WRITE_STORAGE_BUFFER,
            source: vk::DescriptorMappingSourceEXT::HEAP_WITH_CONSTANT_OFFSET,
            source_data,
        };
        let mapping_info = vk::ShaderDescriptorSetAndBindingMappingInfoEXT {
            s_type: vk::StructureType::SHADER_DESCRIPTOR_SET_AND_BINDING_MAPPING_INFO_EXT,
            next: std::ptr::null(),
            mapping_count: 1,
            mappings: &raw const ssbo_mapping,
        };
        let pipeline_flags2 = vk::PipelineCreateFlags2CreateInfo {
            s_type: vk::StructureType::PIPELINE_CREATE_FLAGS_2_CREATE_INFO,
            next: std::ptr::null(),
            flags: vk::PipelineCreateFlags2::DESCRIPTOR_HEAP_EXT,
        };

        let shader_module = create_shader_module(vk, self.context.get_binary_collection().get("main")?)?;
        let mut stage = vk::PipelineShaderStageCreateInfo::builder()
            .stage(stage_flags)
            .module(*shader_module)
            .name(b"main\0")
            .build();
        stage.next = (&raw const mapping_info).cast();

        // No layout for a descriptor heap pipeline
        let pipeline = if is_compute {
            let mut info = vk::ComputePipelineCreateInfo::builder()
                .stage(stage)
                .layout(vk::PipelineLayout::null())
                .base_pipeline_index(0)
                .build();
            info.next = (&raw const pipeline_flags2).cast();
            unsafe { vk.create_compute_pipelines(vk::PipelineCache::null(), &[info], None) }
                .vk_check("vkCreateComputePipelines")?
                .0[0]
        } else {
            create_heap_graphics_pipeline(vk, stage, &pipeline_flags2)?
        };
        let pipeline = Unique::new(vk, pipeline);

        let cmd_pool = make_command_pool(vk, queue_family_index)?;
        let cmd_buffer = allocate_command_buffer(vk, *cmd_pool, vk::CommandBufferLevel::PRIMARY)?;
        let cmd = *cmd_buffer;

        begin_command_buffer(vk, cmd)?;
        let barriers = [
            buffer_barrier2(
                resource_heap_buffer.get(),
                shader_stage,
                vk::AccessFlags2::RESOURCE_HEAP_READ_EXT,
            ),
            buffer_barrier2(result_buffer.get(), shader_stage, vk::AccessFlags2::SHADER_WRITE),
        ];
        let dependency_info = vk::DependencyInfo::builder().buffer_memory_barriers(&barriers);
        unsafe { vk.cmd_pipeline_barrier2(cmd, &dependency_info) };

        let bind_heap_info = vk::BindHeapInfoEXT {
            s_type: vk::StructureType::BIND_HEAP_INFO_EXT,
            next: std::ptr::null(),
            heap_range: vk::DeviceAddressRangeEXT {
                address: resource_heap_address,
                size: resource_heap_size,
            },
            reserved_range_offset: resource_heap_reserved_offset,
            reserved_range_size: heap_properties.min_resource_heap_reserved_range,
        };
        if is_compute {
            unsafe {
                vk.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::COMPUTE, *pipeline);
                vk.cmd_bind_resource_heap_ext(cmd, &bind_heap_info);
            }
            push_data_for_banks(vk, cmd, num_banks);
            unsafe { vk.cmd_dispatch(cmd, 1, 1, 1) };
        } else {
            let rendering_info = vk::RenderingInfo::builder()
                .render_area(vk::Rect2D {
                    offset: vk::Offset2D { x: 0, y: 0 },
                    extent: vk::Extent2D { width: 1, height: 1 },
                })
                .layer_count(1);
            unsafe {
                vk.cmd_begin_rendering(cmd, &rendering_info);
                vk.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::GRAPHICS, *pipeline);
                vk.cmd_bind_resource_heap_ext(cmd, &bind_heap_info);
            }
            push_data_for_banks(vk, cmd, num_banks);
            unsafe {
                vk.cmd_draw(cmd, 1, 1, 0, 0);
                vk.cmd_end_rendering(cmd);
            }
        }

        let memory_barrier = make_memory_barrier(vk::AccessFlags::SHADER_WRITE, vk::AccessFlags::HOST_READ);
        unsafe {
            vk.cmd_pipeline_barrier(
                cmd,
                if is_compute {
                    vk::PipelineStageFlags::COMPUTE_SHADER
                } else {
                    vk::PipelineStageFlags::VERTEX_SHADER
                },
                vk::PipelineStageFlags::HOST,
                vk::DependencyFlags::empty(),
                &[memory_barrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[] as &[vk::ImageMemoryBarrier],
            );
        }
        end_command_buffer(vk, cmd)?;
        submit_commands_and_wait(vk, queue, cmd)?;

        invalidate_alloc(vk, result_buffer.get_allocation())?;
        let results = unsafe { std::slice::from_raw_parts(result_ptr.cast_const(), MAX_TEST_BANKS as usize) };
        verify_results(results, num_banks, 0)
    }
}

/// The graphics pipeline of the heap test: `create_graphics_pipeline_with_discard` with the stage carrying the descriptor mapping, the heap
/// flag chained in front of the rendering info and no layout.
fn create_heap_graphics_pipeline(
    device: &Device,
    stage: vk::PipelineShaderStageCreateInfo,
    flags2: &vk::PipelineCreateFlags2CreateInfo,
) -> Result<vk::Pipeline, TestError> {
    let stages = [stage];
    let vertex_input = vk::PipelineVertexInputStateCreateInfo::builder();
    let input_assembly =
        vk::PipelineInputAssemblyStateCreateInfo::builder().topology(vk::PrimitiveTopology::POINT_LIST);
    let viewports = [vk::Viewport {
        x: 0.0,
        y: 0.0,
        width: 1.0,
        height: 1.0,
        min_depth: 0.0,
        max_depth: 1.0,
    }];
    let scissors = [vk::Rect2D {
        offset: vk::Offset2D { x: 0, y: 0 },
        extent: vk::Extent2D { width: 1, height: 1 },
    }];
    let viewport_state = vk::PipelineViewportStateCreateInfo::builder()
        .viewports(&viewports)
        .scissors(&scissors);
    let rasterization = vk::PipelineRasterizationStateCreateInfo::builder()
        .rasterizer_discard_enable(true)
        .polygon_mode(vk::PolygonMode::FILL)
        .line_width(1.0);
    let multisample = vk::PipelineMultisampleStateCreateInfo::builder().rasterization_samples(vk::SampleCountFlags::_1);
    let color_blend = vk::PipelineColorBlendStateCreateInfo::builder();
    let mut rendering = vk::PipelineRenderingCreateInfo::builder();

    let mut info = vk::GraphicsPipelineCreateInfo::builder()
        .stages(&stages)
        .vertex_input_state(&vertex_input)
        .input_assembly_state(&input_assembly)
        .viewport_state(&viewport_state)
        .rasterization_state(&rasterization)
        .multisample_state(&multisample)
        .color_blend_state(&color_blend)
        .layout(vk::PipelineLayout::null())
        .push_next(&mut rendering)
        .build();
    let mut flags2_copy = *flags2;
    flags2_copy.next = info.next;
    info.next = (&raw const flags2_copy).cast();
    let pipelines = unsafe { device.create_graphics_pipelines(vk::PipelineCache::null(), &[info], None) }
        .vk_check("vkCreateGraphicsPipelines")?
        .0;
    Ok(pipelines[0])
}

fn shader_named(name: &str) -> BinaryCollection {
    ALL_PUSH_CONSTANT_BANK_SHADER
        .iter()
        .find(|shader| shader.name == name)
        .map(|shader| shader.programs)
        .unwrap_or_else(|| panic!("no push_constant_bank shader {name}"))
}

/// `populateBasicTests` and the member offset cases: path (under `push_constant_bank.`) -> case
pub fn create_basic_cases() -> HashMap<String, Box<dyn TestCase>> {
    let mut cases: HashMap<String, Box<dyn TestCase>> = HashMap::new();
    let mut add = |name: String, test_type: TestType, num_banks: u32, member_offset: u32, shader: &str| {
        cases.insert(
            format!("push_constant_bank.basic.{name}"),
            Box::new(BankCase {
                name,
                test_type,
                num_banks,
                member_offset,
                programs: shader_named(shader),
            }),
        );
    };
    for banks in [1u32, 2, 4, 8] {
        add(
            format!("compute_{banks}_banks"),
            TestType::ComputeBasic,
            banks,
            0,
            "compute",
        );
        add(
            format!("graphics_{banks}_banks"),
            TestType::GraphicsBasic,
            banks,
            0,
            "vertex",
        );
    }
    for offset in [4u32, 16] {
        add(
            format!("compute_member_offset_{offset}"),
            TestType::ComputeMemberOffset,
            4,
            offset,
            &format!("compute_offset_{offset}"),
        );
        add(
            format!("graphics_member_offset_{offset}"),
            TestType::GraphicsMemberOffset,
            4,
            offset,
            &format!("vertex_offset_{offset}"),
        );
    }
    for banks in [1u32, 4, 8] {
        cases.insert(
            format!("push_constant_bank.descriptor_heap.compute_{banks}_banks"),
            Box::new(BankCase {
                name: format!("compute_{banks}_banks"),
                test_type: TestType::ComputeDescriptorHeap,
                num_banks: banks,
                member_offset: 0,
                programs: shader_named("compute"),
            }),
        );
        cases.insert(
            format!("push_constant_bank.descriptor_heap.graphics_{banks}_banks"),
            Box::new(BankCase {
                name: format!("graphics_{banks}_banks"),
                test_type: TestType::GraphicsDescriptorHeap,
                num_banks: banks,
                member_offset: 0,
                programs: shader_named("vertex"),
            }),
        );
    }
    cases
}
