#[derive(Clone, Copy, PartialEq, Eq)]
enum TestType {
    ComputeBasic,
    GraphicsBasic,
    ComputeMemberOffset,
    GraphicsMemberOffset,
    ComputeDescriptorHeap,
    GraphicsDescriptorHeap,
}

impl TestType {
    fn is_compute(self) -> bool {
        matches!(
            self,
            Self::ComputeBasic | Self::ComputeMemberOffset | Self::ComputeDescriptorHeap
        )
    }

    fn uses_descriptor_heap(self) -> bool {
        matches!(self, Self::ComputeDescriptorHeap | Self::GraphicsDescriptorHeap)
    }
}

struct BankCase {
    name: String,
    test_type: TestType,
    num_banks: u32,
    member_offset: u32,
    programs: BinaryCollection,
}

impl TestCase for BankCase {
    fn name(&self) -> &str {
        &self.name
    }

    /// `PushConstantBankTestCase::checkSupport`
    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        context.require_device_functionality("VK_KHR_maintenance5")?;
        context.require_device_functionality("VK_KHR_maintenance6")?;
        context.require_device_functionality("VK_NV_push_constant_bank")?;

        let vki = context.get_instance();
        let mut bank_features = vk::PhysicalDevicePushConstantBankFeaturesNV::default();
        let mut features2 = vk::PhysicalDeviceFeatures2::builder().push_next(&mut bank_features);
        unsafe { vki.get_physical_device_features2(context.get_physical_device(), &mut features2) };
        if bank_features.push_constant_bank == vk::FALSE {
            return Err(TestError::NotSupported(
                "pushConstantBank feature is not supported".to_string(),
            ));
        }

        if self.test_type.uses_descriptor_heap() {
            context.require_device_functionality("VK_EXT_descriptor_heap")?;
            let mut heap_features = vk::PhysicalDeviceDescriptorHeapFeaturesEXT::default();
            let mut features2 = vk::PhysicalDeviceFeatures2::builder().push_next(&mut heap_features);
            unsafe { vki.get_physical_device_features2(context.get_physical_device(), &mut features2) };
            if heap_features.descriptor_heap == vk::FALSE {
                return Err(TestError::NotSupported(
                    "descriptorHeap feature is not supported".to_string(),
                ));
            }
        }

        let bank_properties = query_bank_properties(context);
        let max_banks = match (self.test_type.is_compute(), self.test_type.uses_descriptor_heap()) {
            (true, false) => bank_properties.max_compute_push_constant_banks,
            (false, false) => bank_properties.max_graphics_push_constant_banks,
            (true, true) => bank_properties.max_compute_push_data_banks,
            (false, true) => bank_properties.max_graphics_push_data_banks,
        };
        if max_banks < 1 {
            return Err(TestError::NotSupported("No push constant banks available".to_string()));
        }

        if !self.test_type.is_compute() && context.get_device_features().vertex_pipeline_stores_and_atomics == vk::FALSE
        {
            return Err(TestError::NotSupported(
                "vertexPipelineStoresAndAtomics not supported".to_string(),
            ));
        }
        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        self.programs
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(BankInstance {
            context,
            test_type: self.test_type,
            num_banks: self.num_banks,
            member_offset: self.member_offset,
        })
    }
}

fn query_bank_properties(context: &Context<'_>) -> vk::PhysicalDevicePushConstantBankPropertiesNV {
    let mut bank_properties = vk::PhysicalDevicePushConstantBankPropertiesNV::default();
    let mut properties2 = vk::PhysicalDeviceProperties2::builder().push_next(&mut bank_properties);
    unsafe {
        context
            .get_instance()
            .get_physical_device_properties2(context.get_physical_device(), &mut properties2)
    };
    bank_properties
}

