#[derive(Clone, Copy, PartialEq, Eq)]
enum SpirVFunction {
    SparseFetch,
    SparseRead,
    SparseSampleExplicitLod,
    SparseSampleImplicitLod,
    SparseGather,
}

impl SpirVFunction {
    const ALL: [SpirVFunction; 5] = [
        Self::SparseFetch,
        Self::SparseRead,
        Self::SparseSampleExplicitLod,
        Self::SparseSampleImplicitLod,
        Self::SparseGather,
    ];

    /// The group name suffix of `functions[]`.
    fn group_suffix(self) -> &'static str {
        match self {
            Self::SparseFetch => "_sparse_fetch",
            Self::SparseRead => "_sparse_read",
            Self::SparseSampleExplicitLod => "_sparse_sample_explicit_lod",
            Self::SparseSampleImplicitLod => "_sparse_sample_implicit_lod",
            Self::SparseGather => "_sparse_gather",
        }
    }

    /// The part of a manifest key naming the function.
    fn key_name(self) -> &'static str {
        match self {
            Self::SparseFetch => "fetch",
            Self::SparseRead => "read",
            Self::SparseSampleExplicitLod => "explicit",
            Self::SparseSampleImplicitLod => "implicit",
            Self::SparseGather => "gather",
        }
    }

    /// Fetch and read are the compute shaders of `SparseShaderIntrinsicsCaseStorage`, the others the graphics ones of `...Sampled`.
    fn is_storage(self) -> bool {
        matches!(self, Self::SparseFetch | Self::SparseRead)
    }

    fn is_sampled_gather_or_sample(self) -> bool {
        !self.is_storage()
    }

    fn sparse_usage(self) -> vk::ImageUsageFlags {
        match self {
            Self::SparseFetch => vk::ImageUsageFlags::SAMPLED,
            Self::SparseRead => vk::ImageUsageFlags::STORAGE,
            _ => vk::ImageUsageFlags::SAMPLED,
        }
    }

    fn output_usage(self) -> vk::ImageUsageFlags {
        if self.is_storage() {
            vk::ImageUsageFlags::STORAGE
        } else {
            vk::ImageUsageFlags::COLOR_ATTACHMENT
        }
    }

    fn queue_flags(self) -> vk::QueueFlags {
        if self.is_storage() {
            vk::QueueFlags::COMPUTE
        } else {
            vk::QueueFlags::GRAPHICS
        }
    }
}

/// The key of a program of the manifest.
fn shader_key(function: SpirVFunction, image_type: ImageType, format: vk::Format, nontemporal: bool) -> String {
    format!(
        "si_{}_{}_{}_{}",
        function.key_name(),
        get_image_type_name(image_type),
        get_image_format_id(format),
        if nontemporal { "t" } else { "n" }
    )
}

fn find_program(key: &str) -> Result<&'static SharedProgram, TestError> {
    ALL_SHARED_PROGRAM
        .iter()
        .find(|program| program.name == key)
        .copied()
        .ok_or_else(|| TestError::InternalError(format!("no shader {key}")))
}

struct SparseShaderIntrinsicsCase {
    name: String,
    function: SpirVFunction,
    image_type: ImageType,
    image_size: [u32; 3],
    format: vk::Format,
    operand: &'static str,
}

impl TestCase for SparseShaderIntrinsicsCase {
    fn name(&self) -> &str {
        &self.name
    }

    /// `SparseShaderIntrinsicsCaseBase::checkSupport`
    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        let instance = context.get_instance();
        let physical_device = context.get_physical_device();

        if context.get_device_features().shader_resource_residency == vk::FALSE {
            return Err(TestError::NotSupported(
                "shaderResourceResidency not supported".to_string(),
            ));
        }

        // Check if image size does not exceed device limits
        if !is_image_size_supported(instance, physical_device, self.image_type, self.image_size) {
            return Err(TestError::NotSupported(
                "Image size not supported for device".to_string(),
            ));
        }

        // Check if device supports sparse operations for image type
        if !check_sparse_support_for_image_type(instance, physical_device, self.image_type) {
            return Err(TestError::NotSupported(
                "Sparse residency for image type is not supported".to_string(),
            ));
        }

        if self.operand.contains("Nontemporal") && context.api_version() < (1, 3, 0) {
            return Err(TestError::NotSupported(
                "Vulkan 1.3 or higher is required for this test to run".to_string(),
            ));
        }

        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        BinaryCollection::new(&[])
    }

    fn is_stub(&self) -> bool {
        is_ycbcr_format(self.format)
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(SparseShaderIntrinsicsInstance {
            context,
            function: self.function,
            image_type: self.image_type,
            image_size: self.image_size,
            format: self.format,
            nontemporal: self.operand.contains("Nontemporal"),
        })
    }
}

