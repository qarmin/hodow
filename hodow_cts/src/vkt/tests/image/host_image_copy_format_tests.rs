fn tcu_format_of(format: vk::Format) -> Option<TextureFormat> {
    if is_compressed_format(format) {
        get_uncompressed_format(format)
    } else {
        map_vk_format(format)
    }
}

fn is_ds_order(order: ChannelOrder) -> bool {
    matches!(order, ChannelOrder::D | ChannelOrder::S | ChannelOrder::DS)
}

/// `getAspectFlags`
fn get_aspect_flags(format: vk::Format) -> vk::ImageAspectFlags {
    if is_compressed_format(format) {
        return vk::ImageAspectFlags::COLOR;
    }
    match map_vk_format(format).map(|tcu_format| tcu_format.order) {
        Some(ChannelOrder::S) => vk::ImageAspectFlags::STENCIL,
        Some(ChannelOrder::D | ChannelOrder::DS) => vk::ImageAspectFlags::DEPTH,
        _ => vk::ImageAspectFlags::COLOR,
    }
}

/// `getChannelSize`
fn get_channel_size(format: vk::Format) -> u32 {
    let tcu_format = tcu_format_of(format);
    if let Some(tcu_format) = tcu_format
        && !is_ds_order(tcu_format.order)
    {
        return tcu_format.type_.channel_size().unwrap_or(0);
    }
    match format {
        vk::Format::D24_UNORM_S8_UINT | vk::Format::D32_SFLOAT => 4,
        vk::Format::D16_UNORM => 2,
        vk::Format::S8_UINT => 1,
        _ => 0,
    }
}

/// `getNumChannels`
fn get_num_channels(format: vk::Format) -> u32 {
    match tcu_format_of(format) {
        Some(tcu_format) if !is_ds_order(tcu_format.order) => tcu_format.order.num_used_channels(),
        _ => 1,
    }
}

fn is_depth_stencil(format: vk::Format) -> bool {
    !is_compressed_format(format) && map_vk_format(format).is_some_and(|tcu_format| is_ds_order(tcu_format.order))
}

/// `SparseImage` with its image, semaphore, optional fence and the memory bound to it.
struct SparseImage<'a> {
    image: Unique<'a, vk::Image>,
    semaphore: Unique<'a, vk::Semaphore>,
    fence: Option<Unique<'a, vk::Fence>>,
    #[allow(dead_code)]
    allocations: Vec<Allocation<'a>>,
}

impl<'a> SparseImage<'a> {
    fn new(context: &'a Context<'a>, create_info: &vk::ImageCreateInfo, with_fence: bool) -> Result<Self, TestError> {
        let device = context.get_device();
        let image = Unique::new(
            device,
            unsafe { device.create_image(create_info, None) }.vk_check("vkCreateImage")?,
        );
        let semaphore = Unique::new(
            device,
            unsafe { device.create_semaphore(&vk::SemaphoreCreateInfo::default(), None) }
                .vk_check("vkCreateSemaphore")?,
        );
        let fence = if with_fence {
            Some(Unique::new(
                device,
                unsafe { device.create_fence(&vk::FenceCreateInfo::default(), None) }.vk_check("vkCreateFence")?,
            ))
        } else {
            None
        };
        let mut allocations = Vec::new();
        let tcu_format = map_vk_format(create_info.format)
            .ok_or_else(|| TestError::NotPorted(format!("sparse image of {:?}", create_info.format)))?;
        allocate_and_bind_sparse_image(
            device,
            context.get_instance(),
            context.get_physical_device(),
            create_info,
            *semaphore,
            context.get_universal_queue(),
            context.get_default_allocator(),
            &mut allocations,
            tcu_format,
            *image,
            fence.as_ref().map_or(vk::Fence::null(), |fence| **fence),
        )?;
        Ok(Self {
            image,
            semaphore,
            fence,
            allocations,
        })
    }

    fn wait_for_fence(&self, device: &Device) -> Result<(), TestError> {
        if let Some(fence) = &self.fence {
            unsafe { device.wait_for_fences(&[**fence], true, u64::MAX) }.vk_check("vkWaitForFences")?;
        }
        Ok(())
    }
}

