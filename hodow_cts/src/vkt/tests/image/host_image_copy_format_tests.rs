impl TestCase for HostImageCopyCase {
    fn name(&self) -> &str {
        &self.name
    }

    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        let p = &self.params;
        let instance = context.get_instance();
        let physical_device = context.get_physical_device();

        context.require_device_functionality("VK_EXT_host_image_copy")?;
        if p.dynamic_rendering {
            context.require_device_functionality("VK_KHR_dynamic_rendering")?;
        }
        if p.sparse && context.get_device_features().sparse_binding == vk::FALSE {
            return Err(TestError::NotSupported(
                "sparseBinding feature is not supported".to_string(),
            ));
        }
        if p.sparse
            && !universal_queue_supports_sparse_binding(
                instance,
                physical_device,
                context.get_universal_queue_family_index(),
            )
        {
            return Err(TestError::NotSupported(
                "the universal queue does not support sparse binding".to_string(),
            ));
        }

        let host_image_copy_properties = get_host_image_copy_properties(context);
        let src_layout_supported = host_image_copy_properties.src_layouts.contains(&p.src_layout);
        let intermediate_layout_supported = host_image_copy_properties.src_layouts.contains(&p.intermediate_layout);
        if !src_layout_supported || !intermediate_layout_supported {
            return Err(TestError::NotSupported(
                "Layout not supported for src host copy".to_string(),
            ));
        }
        if !host_image_copy_properties.dst_layouts.contains(&p.dst_layout) {
            return Err(TestError::NotSupported(
                "Layout not supported for dst host copy".to_string(),
            ));
        }

        let mut usage = vk::ImageUsageFlags::SAMPLED | vk::ImageUsageFlags::TRANSFER_DST;
        if p.action == HostCopyAction::MemoryToImage || p.action == HostCopyAction::Memcpy {
            usage |= vk::ImageUsageFlags::HOST_TRANSFER;
        }
        if p.intermediate_layout == vk::ImageLayout::COLOR_ATTACHMENT_OPTIMAL {
            usage |= vk::ImageUsageFlags::COLOR_ATTACHMENT;
        } else if p.intermediate_layout == vk::ImageLayout::TRANSFER_SRC_OPTIMAL {
            usage |= vk::ImageUsageFlags::TRANSFER_SRC;
        } else if p.intermediate_layout == vk::ImageLayout::TRANSFER_DST_OPTIMAL {
            usage |= vk::ImageUsageFlags::TRANSFER_DST;
        } else if p.intermediate_layout == vk::ImageLayout::DEPTH_STENCIL_ATTACHMENT_OPTIMAL
            || p.intermediate_layout == vk::ImageLayout::DEPTH_STENCIL_READ_ONLY_OPTIMAL
        {
            usage |= vk::ImageUsageFlags::DEPTH_STENCIL_ATTACHMENT;
        }
        let flags = if p.sparse {
            vk::ImageCreateFlags::SPARSE_BINDING | vk::ImageCreateFlags::SPARSE_RESIDENCY
        } else {
            vk::ImageCreateFlags::empty()
        };

        let image_format_properties = unsafe {
            instance.get_physical_device_image_format_properties(
                physical_device,
                p.image_sampled_format,
                vk::ImageType::_2D,
                p.sampled_tiling,
                usage,
                flags,
            )
        };
        let image_format_properties = match image_format_properties {
            Ok(properties) => properties,
            Err(code) if code == vk::ErrorCode::FORMAT_NOT_SUPPORTED => {
                return Err(TestError::NotSupported("Image format not supported.".to_string()));
            }
            Err(code) => {
                return Err(TestError::Fail(format!(
                    "vkGetPhysicalDeviceImageFormatProperties returned {code:?}"
                )));
            }
        };

        let mut output_usage = vk::ImageUsageFlags::COLOR_ATTACHMENT | vk::ImageUsageFlags::TRANSFER_SRC;
        if p.action == HostCopyAction::ImageToMemory {
            output_usage |= vk::ImageUsageFlags::HOST_TRANSFER;
        }
        if p.command == Command::Dispatch {
            output_usage |= vk::ImageUsageFlags::STORAGE;
        }
        let output_properties = unsafe {
            instance.get_physical_device_image_format_properties(
                physical_device,
                p.image_output_format,
                vk::ImageType::_2D,
                vk::ImageTiling::OPTIMAL,
                output_usage,
                flags,
            )
        };
        if matches!(output_properties, Err(code) if code == vk::ErrorCode::FORMAT_NOT_SUPPORTED) {
            return Err(TestError::NotSupported("Image format not supported.".to_string()));
        }

        let mut format_properties3 = vk::FormatProperties3::default();
        let mut format_properties2 = vk::FormatProperties2::builder().push_next(&mut format_properties3);
        unsafe {
            instance.get_physical_device_format_properties2(
                physical_device,
                p.image_sampled_format,
                &mut format_properties2,
            )
        };
        if p.sampled_tiling == vk::ImageTiling::LINEAR
            && !format_properties3
                .linear_tiling_features
                .contains(vk::FormatFeatureFlags2::HOST_IMAGE_TRANSFER)
        {
            return Err(TestError::NotSupported(
                "Format feature host image transfer not supported for linear tiling.".to_string(),
            ));
        }
        if p.sampled_tiling == vk::ImageTiling::OPTIMAL
            && !format_properties3
                .optimal_tiling_features
                .contains(vk::FormatFeatureFlags2::HOST_IMAGE_TRANSFER)
        {
            return Err(TestError::NotSupported(
                "Format feature host image transfer not supported for optimal tiling.".to_string(),
            ));
        }

        require_host_image_copy_feature(context)?;

        if image_format_properties.max_mip_levels <= p.mip_level {
            return Err(TestError::NotSupported(
                "Required image mip levels not supported.".to_string(),
            ));
        }
        if p.command == Command::Dispatch
            && context.get_device_features().shader_storage_image_write_without_format == vk::FALSE
        {
            return Err(TestError::NotSupported(
                "shaderStorageImageWriteWithoutFormat feature is not supported".to_string(),
            ));
        }
        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        let p = &self.params;
        let key = match p.command {
            Command::Draw if is_depth_stencil(p.image_sampled_format) => "hic_draw_depth",
            Command::Draw => "hic_draw_color",
            Command::Dispatch if p.image_output_format == vk::Format::R8G8B8A8_UINT => "hic_dispatch_uint",
            Command::Dispatch => "hic_dispatch_float",
        };
        ALL_SHARED_PROGRAM
            .iter()
            .find(|program| program.name == key)
            .map_or(BinaryCollection::new(&[]), |program| program.programs)
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(HostImageCopyInstance {
            context,
            params: self.params,
        })
    }
}

/// `HostImageCopyTestInstance`
struct HostImageCopyInstance<'a> {
    context: &'a Context<'a>,
    params: TestParameters,
}

impl HostImageCopyInstance<'_> {
    /// `transitionImageLayout`
    fn transition_image_layout(
        &self,
        cmd: vk::CommandBuffer,
        image: vk::Image,
        usage: vk::ImageUsageFlags,
        old_layout: vk::ImageLayout,
        new_layout: vk::ImageLayout,
        range: vk::ImageSubresourceRange,
    ) -> Result<(), TestError> {
        let device = self.context.get_device();
        if self.params.host_transfer_layout && usage.contains(vk::ImageUsageFlags::HOST_TRANSFER) {
            let transition = host_layout_transition(image, old_layout, new_layout, range);
            unsafe { device.transition_image_layout_ext(&[transition]) }.vk_check("vkTransitionImageLayoutEXT")?;
        } else {
            begin_command_buffer(device, cmd)?;
            let barrier = make_image_memory_barrier(
                vk::AccessFlags::empty(),
                vk::AccessFlags::TRANSFER_WRITE,
                old_layout,
                new_layout,
                image,
                range,
            );
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::empty(),
                    vk::PipelineStageFlags::TRANSFER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[barrier],
                );
            }
            end_command_buffer(device, cmd)?;
            submit_commands_and_wait(device, self.context.get_universal_queue(), cmd)?;
        }
        Ok(())
    }

    /// `copyMemoryToImage`
    #[allow(clippy::too_many_arguments)]
    fn copy_memory_to_image(
        &self,
        test_data: &[u8],
        image: vk::Image,
        texel_size: u32,
        subresource_layers: vk::ImageSubresourceLayers,
        x_offset: i32,
        y_offset: i32,
        width: u32,
        height: u32,
    ) -> Result<(), TestError> {
        let device = self.context.get_device();
        let p = &self.params;
        let texel_size = texel_size as usize;
        let mut data = vec![0u8; texel_size * width as usize * height as usize];
        let image_width = p.image_size.width as usize;
        for i in 0..height as usize {
            let src = ((y_offset as usize + i) * image_width + x_offset as usize) * texel_size;
            let dst = i * width as usize * texel_size;
            let len = width as usize * texel_size;
            data[dst..dst + len].copy_from_slice(&test_data[src..src + len]);
        }

        let regions_count = if p.regions_count > height { p.regions_count } else { 1 };
        let mut regions = Vec::new();
        for i in 0..regions_count {
            let offset = vk::Offset3D {
                x: x_offset,
                y: (y_offset as u32 + height / regions_count * i) as i32,
                z: 0,
            };
            let mut extent = vk::Extent3D {
                width,
                height: height / regions_count,
                depth: 1,
            };
            if i == regions_count - 1 {
                extent.height = height - height / regions_count * i;
            }
            if extent.height == 0 {
                continue;
            }
            let data_offset = width as usize * (height / regions_count * i) as usize * texel_size;
            regions.push(memory_to_image_copy(
                data[data_offset..].as_ptr(),
                0,
                0,
                subresource_layers,
                offset,
                extent,
            ));
        }

        let info = vk::CopyMemoryToImageInfo {
            s_type: vk::StructureType::COPY_MEMORY_TO_IMAGE_INFO,
            next: std::ptr::null(),
            flags: vk::HostImageCopyFlags::empty(),
            dst_image: image,
            dst_image_layout: p.dst_layout,
            region_count: regions.len() as u32,
            regions: regions.as_ptr(),
        };
        unsafe { device.copy_memory_to_image_ext(&info) }.vk_check("vkCopyMemoryToImageEXT")?;
        Ok(())
    }
}

/// The samples of `vkQueueSubmit` with a wait semaphore, `submitCommandsAndWait` with its semaphore arguments.
fn submit_wait(
    device: &Device,
    queue: vk::Queue,
    cmd: vk::CommandBuffer,
    wait: Option<(vk::Semaphore, vk::PipelineStageFlags)>,
) -> Result<(), TestError> {
    let fence = Unique::new(
        device,
        unsafe { device.create_fence(&vk::FenceCreateInfo::default(), None) }.vk_check("vkCreateFence")?,
    );
    let cmd_buffers = [cmd];
    let wait_semaphores: Vec<vk::Semaphore> = wait.iter().map(|(semaphore, _)| *semaphore).collect();
    let wait_stages: Vec<vk::PipelineStageFlags> = wait.iter().map(|(_, stage)| *stage).collect();
    let submit_info = vk::SubmitInfo::builder()
        .command_buffers(&cmd_buffers)
        .wait_semaphores(&wait_semaphores)
        .wait_dst_stage_mask(&wait_stages);
    unsafe { device.queue_submit(queue, &[submit_info], *fence) }.vk_check("vkQueueSubmit")?;
    unsafe { device.wait_for_fences(&[*fence], true, u64::MAX) }.vk_check("vkWaitForFences")?;
    Ok(())
}

