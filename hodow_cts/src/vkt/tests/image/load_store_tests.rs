pub(super) const FLAG_SINGLE_LAYER_BIND: u32 = 1 << 0;
const FLAG_RESTRICT_IMAGES: u32 = 1 << 1;
pub(super) const FLAG_DECLARE_FORMAT_IN_SHADER_READS: u32 = 1 << 2;
pub(super) const FLAG_DECLARE_FORMAT_IN_SHADER_WRITES: u32 = 1 << 3;

/// The key of the manifest entry of a case.
fn load_store_key(image_type: ImageType, format: vk::Format, flags: u32) -> String {
    format!(
        "ls_{}_{}_{}{}{}{}",
        get_image_type_name(image_type),
        format_short_string(format),
        u32::from(flags & FLAG_DECLARE_FORMAT_IN_SHADER_READS != 0),
        u32::from(flags & FLAG_DECLARE_FORMAT_IN_SHADER_WRITES != 0),
        u32::from(flags & FLAG_SINGLE_LAYER_BIND != 0),
        if flags & FLAG_RESTRICT_IMAGES != 0 { "r" } else { "" }
    )
}

pub(super) struct LoadStoreCase {
    pub(super) name: String,
    pub(super) texture: Texture,
    pub(super) format: vk::Format,
    /// The storage format; the format of the shader's images is `format`
    pub(super) image_format: vk::Format,
    pub(super) tiling: vk::ImageTiling,
    pub(super) flags: u32,
}

impl TestCase for LoadStoreCase {
    fn name(&self) -> &str {
        &self.name
    }

    /// `LoadStoreTest::checkSupport`
    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        let instance = context.get_instance();
        let physical_device = context.get_physical_device();
        let declare_reads = self.flags & FLAG_DECLARE_FORMAT_IN_SHADER_READS != 0;
        let declare_writes = self.flags & FLAG_DECLARE_FORMAT_IN_SHADER_WRITES != 0;
        let image_type = self.texture.type_();

        for format in [self.format, self.image_format] {
            if format == vk::Format::A8_UNORM || format == vk::Format::A1B5G5R5_UNORM_PACK16 {
                context.require_device_functionality("VK_KHR_maintenance5")?;
            }
        }

        // VkFormatProperties3 when the device has it, the core properties and the without format features otherwise
        let mut properties3 = vk::FormatProperties3::default();
        let mut properties2 = vk::FormatProperties2::builder().push_next(&mut properties3);
        unsafe { instance.get_physical_device_format_properties2(physical_device, self.format, &mut properties2) };
        let core_properties = properties2.format_properties;
        let has_properties3 = context.api_version() >= (1, 3, 0)
            || context
                .get_device_extensions()
                .iter()
                .any(|extension| extension == "VK_KHR_format_feature_flags2");
        let features = context.get_device_features();
        let read_without_format_feature = features.shader_storage_image_read_without_format != vk::FALSE;
        let write_without_format_feature = features.shader_storage_image_write_without_format != vk::FALSE;

        let tiling_features = if self.tiling == vk::ImageTiling::OPTIMAL {
            core_properties.optimal_tiling_features
        } else {
            core_properties.linear_tiling_features
        };
        let (
            tiling_read_without_format,
            tiling_write_without_format,
            buffer_read_without_format,
            buffer_write_without_format,
        ) = if has_properties3 {
            let tiling3 = if self.tiling == vk::ImageTiling::OPTIMAL {
                properties3.optimal_tiling_features
            } else {
                properties3.linear_tiling_features
            };
            (
                tiling3.contains(vk::FormatFeatureFlags2::STORAGE_READ_WITHOUT_FORMAT),
                tiling3.contains(vk::FormatFeatureFlags2::STORAGE_WRITE_WITHOUT_FORMAT),
                properties3
                    .buffer_features
                    .contains(vk::FormatFeatureFlags2::STORAGE_READ_WITHOUT_FORMAT),
                properties3
                    .buffer_features
                    .contains(vk::FormatFeatureFlags2::STORAGE_WRITE_WITHOUT_FORMAT),
            )
        } else {
            (
                read_without_format_feature,
                write_without_format_feature,
                read_without_format_feature,
                write_without_format_feature,
            )
        };

        if !declare_reads && !tiling_read_without_format {
            return Err(TestError::NotSupported(
                "Format not supported for unformatted loads via storage images".to_string(),
            ));
        }

        if image_type == ImageType::Buffer && !declare_reads && !buffer_read_without_format {
            return Err(TestError::NotSupported(
                "Format not supported for unformatted loads via buffers".to_string(),
            ));
        }

        if !declare_writes && !tiling_write_without_format {
            return Err(TestError::NotSupported(
                "Format not supported for unformatted stores via storage images".to_string(),
            ));
        }

        if image_type == ImageType::Buffer && !declare_writes && !buffer_write_without_format {
            return Err(TestError::NotSupported(
                "Format not supported for unformatted stores via buffers".to_string(),
            ));
        }

        if image_type == ImageType::CubeArray && features.image_cube_array == vk::FALSE {
            return Err(TestError::NotSupported("imageCubeArray not supported".to_string()));
        }

        if image_type != ImageType::Buffer && !tiling_features.contains(vk::FormatFeatureFlags::STORAGE_IMAGE) {
            return Err(TestError::NotSupported(
                "Format not supported for storage images".to_string(),
            ));
        }

        let image_core_properties =
            unsafe { instance.get_physical_device_format_properties(physical_device, self.image_format) };
        let image_tiling_features = if self.tiling == vk::ImageTiling::OPTIMAL {
            image_core_properties.optimal_tiling_features
        } else {
            image_core_properties.linear_tiling_features
        };

        if image_type != ImageType::Buffer && !image_tiling_features.contains(vk::FormatFeatureFlags::STORAGE_IMAGE) {
            return Err(TestError::NotSupported(
                "Format not supported for storage images".to_string(),
            ));
        }

        if image_type != ImageType::Buffer && image_tiling_features.is_empty() {
            return Err(TestError::NotSupported(
                "Underlying format not supported at all for images".to_string(),
            ));
        }

        if image_type == ImageType::Buffer && image_core_properties.buffer_features.is_empty() {
            return Err(TestError::NotSupported(
                "Underlying format not supported at all for buffers".to_string(),
            ));
        }

        if image_type == ImageType::Buffer
            && !core_properties
                .buffer_features
                .contains(vk::FormatFeatureFlags::STORAGE_TEXEL_BUFFER)
        {
            return Err(TestError::NotSupported(
                "Format not supported for storage texel buffers".to_string(),
            ));
        }

        let result = unsafe {
            instance.get_physical_device_image_format_properties(
                physical_device,
                self.image_format,
                map_image_type(image_type),
                self.tiling,
                vk::ImageUsageFlags::STORAGE | vk::ImageUsageFlags::TRANSFER_SRC,
                vk::ImageCreateFlags::empty(),
            )
        };
        let image_format_properties = match result {
            Ok(properties) => properties,
            Err(error) if error == vk::ErrorCode::FORMAT_NOT_SUPPORTED => {
                return Err(TestError::NotSupported("Format unsupported for tiling".to_string()));
            }
            Err(_) => {
                return Err(TestError::Fail(
                    "vkGetPhysicalDeviceImageFormatProperties returned unexpected error".to_string(),
                ));
            }
        };

        if image_format_properties.max_array_layers < self.texture.num_layers() as u32 {
            return Err(TestError::NotSupported(
                "This format and tiling combination does not support this number of aray layers".to_string(),
            ));
        }

        if image_format_properties.max_mip_levels < self.texture.num_mipmap_levels() as u32 {
            return Err(TestError::NotSupported(
                "This format and tiling combination does not support this number of miplevels".to_string(),
            ));
        }

        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        BinaryCollection::new(&[])
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(LoadStoreInstance {
            context,
            texture: self.texture,
            format: self.format,
            image_format: self.image_format,
            tiling: self.tiling,
            flags: self.flags,
            key: load_store_key(self.texture.type_(), self.format, self.flags),
        })
    }
}

struct LoadStoreInstance<'a> {
    context: &'a Context<'a>,
    texture: Texture,
    format: vk::Format,
    image_format: vk::Format,
    tiling: vk::ImageTiling,
    flags: u32,
    key: String,
}

/// `flipHorizontally` on the raw pixels of a tightly packed image
pub(super) fn flip_horizontally(data: &mut [u8], size: [i32; 3], pixel_size: usize) {
    let (width, height, depth) = (size[0] as usize, size[1] as usize, size[2] as usize);
    for z in 0..depth {
        for y in 0..height {
            let row = (z * height + y) * width * pixel_size;
            for x in 0..width / 2 {
                let left = row + x * pixel_size;
                let right = row + (width - 1 - x) * pixel_size;
                for byte in 0..pixel_size {
                    data.swap(left + byte, right + byte);
                }
            }
        }
    }
}

impl TestInstance for LoadStoreInstance<'_> {
    /// `BaseTestInstance::queuePass` with `ImageLoadStoreTestInstance` or `BufferLoadStoreTestInstance`, on one queue
    fn iterate(&mut self) -> TestOutcome {
        let context = self.context;
        let device = context.get_device();
        let allocator = context.get_default_allocator();
        let single_layer_bind = self.flags & FLAG_SINGLE_LAYER_BIND != 0;
        let is_buffer = self.texture.type_() == ImageType::Buffer;
        let image_type = self.texture.type_();
        let size = self.texture.size(0);
        let num_layers = self.texture.num_layers();
        let tcu_format = map_vk_format(self.image_format)
            .ok_or_else(|| TestError::NotPorted(format!("texture format of {:?}", self.image_format)))?;
        let pixel_size = tcu_format
            .pixel_size()
            .ok_or_else(|| TestError::NotPorted("pixel size".to_string()))? as usize;

        let image_size_bytes = get_image_size_bytes(size, self.image_format)
            .ok_or_else(|| TestError::NotPorted(format!("size of {:?}", self.image_format)))?;
        let reference_image = generate_reference_image_for_read(size, self.image_format, self.format, false)?;
        let reference_data: Vec<u8> = reference_image.data().to_vec();

        // A helper buffer with enough space to hold the whole image: source data
        let image_buffer = BufferWithMemory::new(
            device,
            allocator,
            make_buffer_create_info(
                image_size_bytes,
                vk::BufferUsageFlags::STORAGE_TEXEL_BUFFER
                    | vk::BufferUsageFlags::TRANSFER_DST
                    | vk::BufferUsageFlags::TRANSFER_SRC,
            ),
            MemoryRequirement::HOST_VISIBLE,
        )?;
        unsafe {
            std::ptr::copy_nonoverlapping(
                reference_data.as_ptr(),
                image_buffer.get_allocation().get_host_ptr(),
                image_size_bytes as usize,
            )
        };
        flush_alloc(device, image_buffer.get_allocation())?;

        let program = ALL_SHARED_PROGRAM
            .iter()
            .find(|program| program.name == self.key)
            .ok_or_else(|| TestError::InternalError(format!("no shader {}", self.key)))?;
        let shader_module = create_shader_module(device, program.programs.get("comp")?)?;

        let image_src;
        let image_dst;
        let image_buffer_dst;
        let descriptor_set_layout;
        let descriptor_pool;
        let mut buffer_views = Vec::new();
        let mut descriptor_sets = Vec::new();
        let mut src_views = Vec::new();
        let mut dst_views = Vec::new();

        if is_buffer {
            image_src = None;
            image_dst = None;
            image_buffer_dst = Some(BufferWithMemory::new(
                device,
                allocator,
                make_buffer_create_info(image_size_bytes, vk::BufferUsageFlags::STORAGE_TEXEL_BUFFER),
                MemoryRequirement::HOST_VISIBLE,
            )?);
            descriptor_set_layout = DescriptorSetLayoutBuilder::new()
                .add_single_binding(vk::DescriptorType::STORAGE_TEXEL_BUFFER, vk::ShaderStageFlags::COMPUTE)
                .add_single_binding(vk::DescriptorType::STORAGE_TEXEL_BUFFER, vk::ShaderStageFlags::COMPUTE)
                .build(device)?;
            descriptor_pool = DescriptorPoolBuilder::new()
                .add_type(vk::DescriptorType::STORAGE_TEXEL_BUFFER, 1)
                .add_type(vk::DescriptorType::STORAGE_TEXEL_BUFFER, 1)
                .build(device, vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET, 1)?;
            descriptor_sets.push(make_descriptor_set(device, *descriptor_pool, *descriptor_set_layout)?);
            let dst_handle = image_buffer_dst.as_ref().map(|buffer| buffer.get()).unwrap_or_default();
            for buffer in [image_buffer.get(), dst_handle] {
                let view_info = vk::BufferViewCreateInfo::builder()
                    .buffer(buffer)
                    .format(self.format)
                    .offset(0)
                    .range(image_size_bytes);
                buffer_views.push(Unique::new(
                    device,
                    unsafe { device.create_buffer_view(&view_info, None) }.vk_check("vkCreateBufferView")?,
                ));
            }
        } else {
            image_buffer_dst = None;
            let layer_size = self.texture.layer_size(0);
            let mut flags = if self.format == self.image_format {
                vk::ImageCreateFlags::empty()
            } else {
                vk::ImageCreateFlags::MUTABLE_FORMAT
            };
            if self.texture.is_cube() {
                flags |= vk::ImageCreateFlags::CUBE_COMPATIBLE;
            }
            let info = vk::ImageCreateInfo::builder()
                .flags(flags)
                .image_type(map_image_type(image_type))
                .format(self.image_format)
                .extent(vk::Extent3D {
                    width: layer_size[0] as u32,
                    height: layer_size[1] as u32,
                    depth: layer_size[2] as u32,
                })
                .mip_levels(1)
                .array_layers(num_layers as u32)
                .samples(vk::SampleCountFlags::_1)
                .tiling(self.tiling)
                .usage(
                    vk::ImageUsageFlags::STORAGE
                        | vk::ImageUsageFlags::TRANSFER_SRC
                        | vk::ImageUsageFlags::TRANSFER_DST,
                )
                .sharing_mode(vk::SharingMode::EXCLUSIVE)
                .initial_layout(vk::ImageLayout::UNDEFINED)
                .build();
            image_src = Some(ImageWithMemory::new(device, allocator, info, MemoryRequirement::ANY)?);
            image_dst = Some(ImageWithMemory::new(device, allocator, info, MemoryRequirement::ANY)?);

            descriptor_set_layout = DescriptorSetLayoutBuilder::new()
                .add_single_binding(vk::DescriptorType::STORAGE_IMAGE, vk::ShaderStageFlags::COMPUTE)
                .add_single_binding(vk::DescriptorType::STORAGE_IMAGE, vk::ShaderStageFlags::COMPUTE)
                .build(device)?;
            descriptor_pool = DescriptorPoolBuilder::new()
                .add_type(vk::DescriptorType::STORAGE_IMAGE, num_layers as u32)
                .add_type(vk::DescriptorType::STORAGE_IMAGE, num_layers as u32)
                .build(
                    device,
                    vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET,
                    num_layers as u32,
                )?;

            let src_handle = image_src.as_ref().map(|image| image.get()).unwrap_or_default();
            let dst_handle = image_dst.as_ref().map(|image| image.get()).unwrap_or_default();
            if single_layer_bind {
                let single_layer_view_type = match image_type {
                    ImageType::OneD | ImageType::OneDArray => vk::ImageViewType::_1D,
                    ImageType::ThreeD => vk::ImageViewType::_3D,
                    _ => vk::ImageViewType::_2D,
                };
                for layer_ndx in 0..num_layers {
                    let range = make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, 1, layer_ndx as u32, 1);
                    descriptor_sets.push(make_descriptor_set(device, *descriptor_pool, *descriptor_set_layout)?);
                    src_views.push(make_image_view(
                        device,
                        src_handle,
                        single_layer_view_type,
                        self.format,
                        range,
                    )?);
                    dst_views.push(make_image_view(
                        device,
                        dst_handle,
                        single_layer_view_type,
                        self.format,
                        range,
                    )?);
                }
            } else {
                let view_type = map_image_view_type(image_type)
                    .ok_or_else(|| TestError::InternalError("no view type".to_string()))?;
                let range = make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, 1, 0, num_layers as u32);
                descriptor_sets.push(make_descriptor_set(device, *descriptor_pool, *descriptor_set_layout)?);
                src_views.push(make_image_view(device, src_handle, view_type, self.format, range)?);
                dst_views.push(make_image_view(device, dst_handle, view_type, self.format, range)?);
            }
        }

        // Pipeline
        let pipeline_layout = make_pipeline_layout(device, &[*descriptor_set_layout])?;
        let stage = vk::PipelineShaderStageCreateInfo::builder()
            .stage(vk::ShaderStageFlags::COMPUTE)
            .module(*shader_module)
            .name(b"main\0");
        let compute_info = vk::ComputePipelineCreateInfo::builder()
            .stage(*stage)
            .layout(*pipeline_layout)
            .base_pipeline_index(0);
        let pipelines = unsafe { device.create_compute_pipelines(vk::PipelineCache::null(), &[compute_info], None) }
            .vk_check("vkCreateComputePipelines")?;
        let pipeline = Unique::new(device, pipelines.0[0]);

        let command_pool = make_command_pool(device, context.get_universal_queue_family_index())?;
        let command_buffer = allocate_command_buffer(device, *command_pool, vk::CommandBufferLevel::PRIMARY)?;
        let cmd = *command_buffer;
        begin_command_buffer(device, cmd)?;
        unsafe { device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::COMPUTE, *pipeline) };

        let full_range = make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, 1, 0, num_layers as u32);
        let src_handle = image_src.as_ref().map(|image| image.get()).unwrap_or_default();
        let dst_handle = image_dst.as_ref().map(|image| image.get()).unwrap_or_default();
        let layer_size = self.texture.layer_size(0);
        let copy_region = vk::BufferImageCopy {
            buffer_offset: 0,
            buffer_row_length: 0,
            buffer_image_height: 0,
            image_subresource: make_image_subresource_layers(vk::ImageAspectFlags::COLOR, 0, 0, num_layers as u32),
            image_offset: vk::Offset3D { x: 0, y: 0, z: 0 },
            image_extent: vk::Extent3D {
                width: layer_size[0] as u32,
                height: layer_size[1] as u32,
                depth: layer_size[2] as u32,
            },
        };

        // commandBeforeCompute
        if !is_buffer {
            let pre_copy_image_barriers = [
                make_image_memory_barrier(
                    vk::AccessFlags::empty(),
                    vk::AccessFlags::TRANSFER_WRITE,
                    vk::ImageLayout::UNDEFINED,
                    vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                    src_handle,
                    full_range,
                ),
                make_image_memory_barrier(
                    vk::AccessFlags::empty(),
                    vk::AccessFlags::SHADER_WRITE,
                    vk::ImageLayout::UNDEFINED,
                    vk::ImageLayout::GENERAL,
                    dst_handle,
                    full_range,
                ),
            ];
            let barrier_flush_host_write_before_copy = make_buffer_memory_barrier(
                vk::AccessFlags::HOST_WRITE,
                vk::AccessFlags::TRANSFER_READ,
                image_buffer.get(),
                0,
                image_size_bytes,
            );
            let barrier_after_copy = make_image_memory_barrier(
                vk::AccessFlags::TRANSFER_WRITE,
                vk::AccessFlags::SHADER_READ,
                vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                vk::ImageLayout::GENERAL,
                src_handle,
                full_range,
            );
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::HOST,
                    vk::PipelineStageFlags::COMPUTE_SHADER | vk::PipelineStageFlags::TRANSFER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[barrier_flush_host_write_before_copy],
                    &pre_copy_image_barriers,
                );
                device.cmd_copy_buffer_to_image(
                    cmd,
                    image_buffer.get(),
                    src_handle,
                    vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                    &[copy_region],
                );
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::COMPUTE_SHADER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[barrier_after_copy],
                );
            }
        }

        let work_size = if single_layer_bind {
            self.texture.layer_size(0)
        } else {
            size
        };
        let loop_num_layers = if single_layer_bind { num_layers } else { 1 };
        for layer_ndx in 0..loop_num_layers as usize {
            let descriptor_set = descriptor_sets[layer_ndx].get();

            // commandBindDescriptorsForLayer
            if is_buffer {
                let src_view = [*buffer_views[0]];
                let dst_view = [*buffer_views[1]];
                let writes = [
                    vk::WriteDescriptorSet::builder()
                        .dst_set(descriptor_set)
                        .dst_binding(0)
                        .dst_array_element(0)
                        .descriptor_type(vk::DescriptorType::STORAGE_TEXEL_BUFFER)
                        .texel_buffer_view(&src_view)
                        .build(),
                    vk::WriteDescriptorSet::builder()
                        .dst_set(descriptor_set)
                        .dst_binding(1)
                        .dst_array_element(0)
                        .descriptor_type(vk::DescriptorType::STORAGE_TEXEL_BUFFER)
                        .texel_buffer_view(&dst_view)
                        .build(),
                ];
                unsafe { device.update_descriptor_sets(&writes, &[] as &[vk::CopyDescriptorSet]) };
            } else {
                let src_info = [vk::DescriptorImageInfo {
                    sampler: vk::Sampler::null(),
                    image_view: *src_views[layer_ndx],
                    image_layout: vk::ImageLayout::GENERAL,
                }];
                let dst_info = [vk::DescriptorImageInfo {
                    sampler: vk::Sampler::null(),
                    image_view: *dst_views[layer_ndx],
                    image_layout: vk::ImageLayout::GENERAL,
                }];
                let writes = [
                    vk::WriteDescriptorSet::builder()
                        .dst_set(descriptor_set)
                        .dst_binding(0)
                        .dst_array_element(0)
                        .descriptor_type(vk::DescriptorType::STORAGE_IMAGE)
                        .image_info(&src_info)
                        .build(),
                    vk::WriteDescriptorSet::builder()
                        .dst_set(descriptor_set)
                        .dst_binding(1)
                        .dst_array_element(0)
                        .descriptor_type(vk::DescriptorType::STORAGE_IMAGE)
                        .image_info(&dst_info)
                        .build(),
                ];
                unsafe { device.update_descriptor_sets(&writes, &[] as &[vk::CopyDescriptorSet]) };
            }
            unsafe {
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::COMPUTE,
                    *pipeline_layout,
                    0,
                    &[descriptor_set],
                    &[] as &[u32],
                )
            };

            if layer_ndx > 0 {
                // commandBetweenShaderInvocations
                let shader_write_barrier = make_image_memory_barrier(
                    vk::AccessFlags::SHADER_WRITE,
                    vk::AccessFlags::empty(),
                    vk::ImageLayout::GENERAL,
                    vk::ImageLayout::GENERAL,
                    dst_handle,
                    full_range,
                );
                unsafe {
                    device.cmd_pipeline_barrier(
                        cmd,
                        vk::PipelineStageFlags::COMPUTE_SHADER,
                        vk::PipelineStageFlags::COMPUTE_SHADER,
                        vk::DependencyFlags::empty(),
                        &[] as &[vk::MemoryBarrier],
                        &[] as &[vk::BufferMemoryBarrier],
                        &[shader_write_barrier],
                    );
                }
            }

            unsafe { device.cmd_dispatch(cmd, work_size[0] as u32, work_size[1] as u32, work_size[2] as u32) };
        }

        // commandAfterCompute
        let result_buffer = if is_buffer {
            image_buffer_dst
                .as_ref()
                .expect("the destination buffer of a buffer case")
        } else {
            &image_buffer
        };
        if is_buffer {
            let shader_write_barrier = make_buffer_memory_barrier(
                vk::AccessFlags::SHADER_WRITE,
                vk::AccessFlags::HOST_READ,
                result_buffer.get(),
                0,
                image_size_bytes,
            );
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::COMPUTE_SHADER,
                    vk::PipelineStageFlags::HOST,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[shader_write_barrier],
                    &[] as &[vk::ImageMemoryBarrier],
                );
            }
        } else {
            let prepare_for_transfer_barrier = make_image_memory_barrier(
                vk::AccessFlags::SHADER_WRITE,
                vk::AccessFlags::TRANSFER_READ,
                vk::ImageLayout::GENERAL,
                vk::ImageLayout::TRANSFER_SRC_OPTIMAL,
                dst_handle,
                full_range,
            );
            let copy_barrier = make_buffer_memory_barrier(
                vk::AccessFlags::TRANSFER_WRITE,
                vk::AccessFlags::HOST_READ,
                image_buffer.get(),
                0,
                image_size_bytes,
            );
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::COMPUTE_SHADER,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[prepare_for_transfer_barrier],
                );
                device.cmd_copy_image_to_buffer(
                    cmd,
                    dst_handle,
                    vk::ImageLayout::TRANSFER_SRC_OPTIMAL,
                    image_buffer.get(),
                    &[copy_region],
                );
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::HOST,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[copy_barrier],
                    &[] as &[vk::ImageMemoryBarrier],
                );
            }
        }

        end_command_buffer(device, cmd)?;
        submit_commands_and_wait(device, context.get_universal_queue(), cmd)?;

        // LoadStoreTestInstance::verifyResult - apply the same transformation as done in the shader
        let mut mirrored = reference_data;
        flip_horizontally(&mut mirrored, size, pixel_size);
        let reference =
            ConstPixelBufferAccess::new(tcu_format, [size[0] as u32, size[1] as u32, size[2] as u32], &mirrored);

        invalidate_alloc(device, result_buffer.get_allocation())?;
        let data = unsafe {
            std::slice::from_raw_parts(
                result_buffer.get_allocation().get_host_ptr().cast_const(),
                image_size_bytes as usize,
            )
        };
        let result = ConstPixelBufferAccess::new(tcu_format, [size[0] as u32, size[1] as u32, size[2] as u32], data);

        if compare_pixel_buffers(self.image_format, &reference, &result) {
            Ok(TestStatus::pass("Passed"))
        } else {
            Ok(TestStatus::fail("Image comparison failed"))
        }
    }
}

/// `createImageLoadStoreTests`
pub fn create_image_load_store_tests() -> TestCaseGroup {
    let textures = [
        Texture::simple(ImageType::OneD, [64, 1, 1], 1),
        Texture::simple(ImageType::OneDArray, [64, 1, 1], 8),
        Texture::simple(ImageType::TwoD, [64, 64, 1], 1),
        Texture::simple(ImageType::TwoDArray, [64, 64, 1], 8),
        Texture::simple(ImageType::ThreeD, [64, 64, 8], 1),
        Texture::simple(ImageType::Cube, [64, 64, 1], 6),
        Texture::simple(ImageType::CubeArray, [64, 64, 1], 2 * 6),
        Texture::simple(ImageType::Buffer, [64, 1, 1], 1),
    ];
    let tilings = [vk::ImageTiling::OPTIMAL, vk::ImageTiling::LINEAR];
    let both = FLAG_DECLARE_FORMAT_IN_SHADER_READS | FLAG_DECLARE_FORMAT_IN_SHADER_WRITES;

    let mut test_group = TestCaseGroup::new("load_store");
    let mut test_group_with_format = TestCaseGroup::new("with_format");
    let mut test_group_without_format = TestCaseGroup::new("without_format");
    let mut test_group_without_any_format = TestCaseGroup::new("without_any_format");

    for texture in textures {
        let image_type_name = get_image_type_name(texture.type_());
        let is_layered = texture.num_layers() > 1;
        let mut group_with_format_by_image_view_type = TestCaseGroup::new(image_type_name);
        let mut group_without_format_by_image_view_type = TestCaseGroup::new(image_type_name);
        let mut group_without_any_format_by_image_view_type = TestCaseGroup::new(image_type_name);

        for &(format, has_spv_format) in FORMATS {
            let short = format_short_string(format);

            for tiling in tilings {
                let suffix = tiling_suffix(tiling);
                let case = |name: String, flags: u32| {
                    Box::new(LoadStoreCase {
                        name,
                        texture,
                        format,
                        image_format: format,
                        tiling,
                        flags,
                    }) as Box<dyn TestCase>
                };

                if has_spv_format {
                    group_with_format_by_image_view_type.add_child(case(format!("{short}{suffix}"), both));
                    group_without_format_by_image_view_type
                        .add_child(case(format!("{short}{suffix}"), FLAG_DECLARE_FORMAT_IN_SHADER_WRITES));
                }

                group_without_any_format_by_image_view_type.add_child(case(format!("{short}{suffix}"), 0));

                if is_layered && has_spv_format {
                    group_with_format_by_image_view_type.add_child(case(
                        format!("{short}_single_layer{suffix}"),
                        FLAG_SINGLE_LAYER_BIND | both,
                    ));
                }
            }
        }

        test_group_with_format.add_child(group_with_format_by_image_view_type);
        test_group_without_format.add_child(group_without_format_by_image_view_type);
        test_group_without_any_format.add_child(group_without_any_format_by_image_view_type);
    }

    test_group.add_child(test_group_with_format);
    test_group.add_child(test_group_without_format);
    test_group.add_child(test_group_without_any_format);
    test_group
}

/// `formatsAreCompatible`
fn formats_are_compatible(format0: vk::Format, format1: vk::Format) -> bool {
    let is_alpha_only = format0 == vk::Format::A8_UNORM || format1 == vk::Format::A8_UNORM;
    let pixel_size = |format: vk::Format| map_vk_format(format).and_then(|f| f.pixel_size());
    format0 == format1 || (pixel_size(format0) == pixel_size(format1) && !is_alpha_only)
}

/// `createImageFormatReinterpretTests`
pub fn create_image_format_reinterpret_tests() -> TestCaseGroup {
    let textures = [
        Texture::simple(ImageType::OneD, [64, 1, 1], 1),
        Texture::simple(ImageType::OneDArray, [64, 1, 1], 8),
        Texture::simple(ImageType::TwoD, [64, 64, 1], 1),
        Texture::simple(ImageType::TwoDArray, [64, 64, 1], 8),
        Texture::simple(ImageType::ThreeD, [64, 64, 8], 1),
        Texture::simple(ImageType::Cube, [64, 64, 1], 6),
        Texture::simple(ImageType::CubeArray, [64, 64, 1], 2 * 6),
        Texture::simple(ImageType::Buffer, [64, 1, 1], 1),
    ];

    let mut test_group = TestCaseGroup::new("format_reinterpret");

    for texture in textures {
        let mut group_by_image_view_type = TestCaseGroup::new(get_image_type_name(texture.type_()));

        for (image_format_ndx, &(image_format, _)) in FORMATS.iter().enumerate() {
            for (format_ndx, &(format, has_spv_format)) in FORMATS.iter().enumerate() {
                if !has_spv_format {
                    continue;
                }

                if image_format_ndx != format_ndx && formats_are_compatible(image_format, format) {
                    group_by_image_view_type.add_child(Box::new(LoadStoreCase {
                        name: format!("{}_{}", format_short_string(image_format), format_short_string(format)),
                        texture,
                        format,
                        image_format,
                        tiling: vk::ImageTiling::OPTIMAL,
                        flags: FLAG_DECLARE_FORMAT_IN_SHADER_READS | FLAG_DECLARE_FORMAT_IN_SHADER_WRITES,
                    }) as Box<dyn TestCase>);
                }
            }
        }

        test_group.add_child(group_by_image_view_type);
    }

    test_group
}

