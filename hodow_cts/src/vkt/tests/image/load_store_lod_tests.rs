/// The key of the manifest entry of a case.
fn lod_key(image_type: ImageType, format: vk::Format, flags: u32) -> String {
    format!(
        "ld_{}_{}_{}{}{}",
        get_image_type_name(image_type),
        format_short_string(format),
        u32::from(flags & FLAG_DECLARE_FORMAT_IN_SHADER_READS != 0),
        u32::from(flags & FLAG_DECLARE_FORMAT_IN_SHADER_WRITES != 0),
        u32::from(flags & FLAG_SINGLE_LAYER_BIND != 0)
    )
}

struct LoadStoreLodCase {
    name: String,
    texture: Texture,
    format: vk::Format,
    flags: u32,
}

/// `getMipmapLevelImageSizeBytes`
fn level_size_bytes(texture: &Texture, pixel_size: usize, level: i32) -> usize {
    let size = texture.size(level);
    pixel_size * size[0] as usize * size[1] as usize * size[2] as usize
}

impl TestCase for LoadStoreLodCase {
    fn name(&self) -> &str {
        &self.name
    }

    /// `LoadStoreTest::checkSupport` with `imageLoadStoreLodAMD`
    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        context.require_device_functionality("VK_AMD_shader_image_load_store_lod")?;
        LoadStoreCase {
            name: self.name.clone(),
            texture: self.texture,
            format: self.format,
            image_format: self.format,
            tiling: vk::ImageTiling::OPTIMAL,
            flags: self.flags,
        }
        .check_support(context)
    }

    fn programs(&self) -> BinaryCollection {
        BinaryCollection::new(&[])
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(LoadStoreLodInstance {
            context,
            texture: self.texture,
            format: self.format,
            flags: self.flags,
        })
    }
}

struct LoadStoreLodInstance<'a> {
    context: &'a Context<'a>,
    texture: Texture,
    format: vk::Format,
    flags: u32,
}

impl TestInstance for LoadStoreLodInstance<'_> {
    /// `BaseTestInstance::queuePass` with `ImageLoadStoreLodAMDTestInstance`, on one queue
    fn iterate(&mut self) -> TestOutcome {
        let context = self.context;
        let device = context.get_device();
        let allocator = context.get_default_allocator();
        let single_layer_bind = self.flags & FLAG_SINGLE_LAYER_BIND != 0;
        let image_type = self.texture.type_();
        let num_layers = self.texture.num_layers();
        let num_levels = self.texture.num_mipmap_levels();
        let tcu_format = map_vk_format(self.format)
            .ok_or_else(|| TestError::NotPorted(format!("texture format of {:?}", self.format)))?;
        let pixel_size = tcu_format
            .pixel_size()
            .ok_or_else(|| TestError::NotPorted("pixel size".to_string()))? as usize;

        let image_size_bytes: usize = (0..num_levels)
            .map(|level| level_size_bytes(&self.texture, pixel_size, level))
            .sum();
        let mut reference_images = Vec::new();
        for level in 0..num_levels {
            reference_images.push(generate_reference_image(self.texture.size(level), self.format, false)?);
        }

        // A helper buffer with enough space to hold the whole image
        let image_buffer = BufferWithMemory::new(
            device,
            allocator,
            make_buffer_create_info(
                image_size_bytes as vk::DeviceSize,
                vk::BufferUsageFlags::STORAGE_TEXEL_BUFFER
                    | vk::BufferUsageFlags::TRANSFER_DST
                    | vk::BufferUsageFlags::TRANSFER_SRC,
            ),
            MemoryRequirement::HOST_VISIBLE,
        )?;
        // Copy reference data of every level to the buffer for the upload to the image
        let mut buffer_offset = 0usize;
        let mut buffer_offsets = Vec::new();
        for (level, reference) in reference_images.iter().enumerate() {
            let size = level_size_bytes(&self.texture, pixel_size, level as i32);
            unsafe {
                std::ptr::copy_nonoverlapping(
                    reference.data().as_ptr(),
                    image_buffer.get_allocation().get_host_ptr().add(buffer_offset),
                    size,
                )
            };
            buffer_offsets.push(buffer_offset);
            buffer_offset += size;
        }
        flush_alloc(device, image_buffer.get_allocation())?;

        let layer_size = self.texture.layer_size(0);
        let make_info = |usage: vk::ImageUsageFlags| {
            let mut flags = vk::ImageCreateFlags::empty();
            if self.texture.is_cube() {
                flags |= vk::ImageCreateFlags::CUBE_COMPATIBLE;
            }
            vk::ImageCreateInfo::builder()
                .flags(flags)
                .image_type(map_image_type(image_type))
                .format(self.format)
                .extent(vk::Extent3D {
                    width: layer_size[0] as u32,
                    height: layer_size[1] as u32,
                    depth: layer_size[2] as u32,
                })
                .mip_levels(num_levels as u32)
                .array_layers(num_layers as u32)
                .samples(vk::SampleCountFlags::_1)
                .tiling(vk::ImageTiling::OPTIMAL)
                .usage(usage)
                .sharing_mode(vk::SharingMode::EXCLUSIVE)
                .initial_layout(vk::ImageLayout::UNDEFINED)
                .build()
        };
        let image_src = ImageWithMemory::new(
            device,
            allocator,
            make_info(vk::ImageUsageFlags::STORAGE | vk::ImageUsageFlags::TRANSFER_DST),
            MemoryRequirement::ANY,
        )?;
        let image_dst = ImageWithMemory::new(
            device,
            allocator,
            make_info(vk::ImageUsageFlags::STORAGE | vk::ImageUsageFlags::TRANSFER_SRC),
            MemoryRequirement::ANY,
        )?;

        let descriptor_set_layout = DescriptorSetLayoutBuilder::new()
            .add_single_binding(vk::DescriptorType::STORAGE_IMAGE, vk::ShaderStageFlags::COMPUTE)
            .add_single_binding(vk::DescriptorType::STORAGE_IMAGE, vk::ShaderStageFlags::COMPUTE)
            .build(device)?;
        let descriptor_pool = DescriptorPoolBuilder::new()
            .add_type(vk::DescriptorType::STORAGE_IMAGE, num_layers as u32)
            .add_type(vk::DescriptorType::STORAGE_IMAGE, num_layers as u32)
            .build(
                device,
                vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET,
                num_layers as u32,
            )?;

        let mut descriptor_sets = Vec::new();
        let mut src_views = Vec::new();
        let mut dst_views = Vec::new();
        if single_layer_bind {
            let view_type = match image_type {
                ImageType::OneD | ImageType::OneDArray => vk::ImageViewType::_1D,
                ImageType::ThreeD => vk::ImageViewType::_3D,
                _ => vk::ImageViewType::_2D,
            };
            for layer_ndx in 0..num_layers {
                let range = make_image_subresource_range(
                    vk::ImageAspectFlags::COLOR,
                    0,
                    num_levels as u32,
                    layer_ndx as u32,
                    1,
                );
                descriptor_sets.push(make_descriptor_set(device, *descriptor_pool, *descriptor_set_layout)?);
                src_views.push(make_image_view(device, image_src.get(), view_type, self.format, range)?);
                dst_views.push(make_image_view(device, image_dst.get(), view_type, self.format, range)?);
            }
        } else {
            let view_type =
                map_image_view_type(image_type).ok_or_else(|| TestError::InternalError("no view type".to_string()))?;
            let range =
                make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, num_levels as u32, 0, num_layers as u32);
            descriptor_sets.push(make_descriptor_set(device, *descriptor_pool, *descriptor_set_layout)?);
            src_views.push(make_image_view(device, image_src.get(), view_type, self.format, range)?);
            dst_views.push(make_image_view(device, image_dst.get(), view_type, self.format, range)?);
        }

        let key = lod_key(image_type, self.format, self.flags);
        let program = ALL_SHARED_PROGRAM
            .iter()
            .find(|program| program.name == key)
            .ok_or_else(|| TestError::InternalError(format!("no shader {key}")))?;
        let shader_module = create_shader_module(device, program.programs.get("comp")?)?;
        let pipeline_layout = make_pipeline_layout(device, &[*descriptor_set_layout])?;
        let stage = vk::PipelineShaderStageCreateInfo::builder()
            .stage(vk::ShaderStageFlags::COMPUTE)
            .module(*shader_module)
            .name(b"main\0");
        let compute_info = vk::ComputePipelineCreateInfo::builder()
            .stage(*stage)
            .layout(*pipeline_layout)
            .base_pipeline_index(0);
        let pipelines = unsafe { device.create_compute_pipelines(vk::PipelineCache::null(), &[compute_info], None) }
            .vk_check("vkCreateComputePipelines")?;
        let pipeline = Unique::new(device, pipelines.0[0]);

        let command_pool = make_command_pool(device, context.get_universal_queue_family_index())?;
        let command_buffer = allocate_command_buffer(device, *command_pool, vk::CommandBufferLevel::PRIMARY)?;
        let cmd = *command_buffer;
        begin_command_buffer(device, cmd)?;
        unsafe { device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::COMPUTE, *pipeline) };

        let full_range =
            make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, num_levels as u32, 0, num_layers as u32);
        let copy_regions: Vec<vk::BufferImageCopy> = (0..num_levels)
            .map(|level| {
                let size = self.texture.layer_size(level);
                vk::BufferImageCopy {
                    buffer_offset: buffer_offsets[level as usize] as vk::DeviceSize,
                    buffer_row_length: 0,
                    buffer_image_height: 0,
                    image_subresource: make_image_subresource_layers(
                        vk::ImageAspectFlags::COLOR,
                        level as u32,
                        0,
                        num_layers as u32,
                    ),
                    image_offset: vk::Offset3D { x: 0, y: 0, z: 0 },
                    image_extent: vk::Extent3D {
                        width: size[0] as u32,
                        height: size[1] as u32,
                        depth: size[2] as u32,
                    },
                }
            })
            .collect();

        // commandBeforeCompute
        {
            let pre_copy_image_barriers = [
                make_image_memory_barrier(
                    vk::AccessFlags::empty(),
                    vk::AccessFlags::TRANSFER_WRITE,
                    vk::ImageLayout::UNDEFINED,
                    vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                    image_src.get(),
                    full_range,
                ),
                make_image_memory_barrier(
                    vk::AccessFlags::empty(),
                    vk::AccessFlags::SHADER_WRITE,
                    vk::ImageLayout::UNDEFINED,
                    vk::ImageLayout::GENERAL,
                    image_dst.get(),
                    full_range,
                ),
            ];
            let barrier_flush_host_write_before_copy = make_buffer_memory_barrier(
                vk::AccessFlags::HOST_WRITE,
                vk::AccessFlags::TRANSFER_READ,
                image_buffer.get(),
                0,
                image_size_bytes as vk::DeviceSize,
            );
            let barrier_after_copy = make_image_memory_barrier(
                vk::AccessFlags::TRANSFER_WRITE,
                vk::AccessFlags::SHADER_READ,
                vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                vk::ImageLayout::GENERAL,
                image_src.get(),
                full_range,
            );
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::HOST,
                    vk::PipelineStageFlags::COMPUTE_SHADER | vk::PipelineStageFlags::TRANSFER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[barrier_flush_host_write_before_copy],
                    &pre_copy_image_barriers,
                );
                device.cmd_copy_buffer_to_image(
                    cmd,
                    image_buffer.get(),
                    image_src.get(),
                    vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                    &copy_regions,
                );
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::COMPUTE_SHADER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[barrier_after_copy],
                );
            }
        }

        let work_size = if single_layer_bind {
            self.texture.layer_size(0)
        } else {
            self.texture.size(0)
        };
        let loop_num_layers = if single_layer_bind { num_layers } else { 1 };
        for layer_ndx in 0..loop_num_layers as usize {
            let descriptor_set = descriptor_sets[layer_ndx].get();
            let src_info = [vk::DescriptorImageInfo {
                sampler: vk::Sampler::null(),
                image_view: *src_views[layer_ndx],
                image_layout: vk::ImageLayout::GENERAL,
            }];
            let dst_info = [vk::DescriptorImageInfo {
                sampler: vk::Sampler::null(),
                image_view: *dst_views[layer_ndx],
                image_layout: vk::ImageLayout::GENERAL,
            }];
            let writes = [
                vk::WriteDescriptorSet::builder()
                    .dst_set(descriptor_set)
                    .dst_binding(0)
                    .dst_array_element(0)
                    .descriptor_type(vk::DescriptorType::STORAGE_IMAGE)
                    .image_info(&src_info)
                    .build(),
                vk::WriteDescriptorSet::builder()
                    .dst_set(descriptor_set)
                    .dst_binding(1)
                    .dst_array_element(0)
                    .descriptor_type(vk::DescriptorType::STORAGE_IMAGE)
                    .image_info(&dst_info)
                    .build(),
            ];
            unsafe {
                device.update_descriptor_sets(&writes, &[] as &[vk::CopyDescriptorSet]);
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::COMPUTE,
                    *pipeline_layout,
                    0,
                    &[descriptor_set],
                    &[] as &[u32],
                );
            }

            if layer_ndx > 0 {
                // commandBetweenShaderInvocations
                let shader_write_barrier = make_image_memory_barrier(
                    vk::AccessFlags::SHADER_WRITE,
                    vk::AccessFlags::empty(),
                    vk::ImageLayout::GENERAL,
                    vk::ImageLayout::GENERAL,
                    image_dst.get(),
                    full_range,
                );
                unsafe {
                    device.cmd_pipeline_barrier(
                        cmd,
                        vk::PipelineStageFlags::COMPUTE_SHADER,
                        vk::PipelineStageFlags::COMPUTE_SHADER,
                        vk::DependencyFlags::empty(),
                        &[] as &[vk::MemoryBarrier],
                        &[] as &[vk::BufferMemoryBarrier],
                        &[shader_write_barrier],
                    );
                }
            }

            unsafe { device.cmd_dispatch(cmd, work_size[0] as u32, work_size[1] as u32, work_size[2] as u32) };
        }

        // commandAfterCompute: commandCopyMipmapImageToBuffer
        {
            let prepare_for_transfer_barrier = make_image_memory_barrier(
                vk::AccessFlags::SHADER_WRITE,
                vk::AccessFlags::TRANSFER_READ,
                vk::ImageLayout::GENERAL,
                vk::ImageLayout::TRANSFER_SRC_OPTIMAL,
                image_dst.get(),
                full_range,
            );
            let copy_barrier = make_buffer_memory_barrier(
                vk::AccessFlags::TRANSFER_WRITE,
                vk::AccessFlags::HOST_READ,
                image_buffer.get(),
                0,
                image_size_bytes as vk::DeviceSize,
            );
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::COMPUTE_SHADER,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[prepare_for_transfer_barrier],
                );
                device.cmd_copy_image_to_buffer(
                    cmd,
                    image_dst.get(),
                    vk::ImageLayout::TRANSFER_SRC_OPTIMAL,
                    image_buffer.get(),
                    &copy_regions,
                );
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::HOST,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[copy_barrier],
                    &[] as &[vk::ImageMemoryBarrier],
                );
            }
        }

        end_command_buffer(device, cmd)?;
        submit_commands_and_wait(device, context.get_universal_queue(), cmd)?;

        // verifyResult
        invalidate_alloc(device, image_buffer.get_allocation())?;
        let data = unsafe {
            std::slice::from_raw_parts(
                image_buffer.get_allocation().get_host_ptr().cast_const(),
                image_size_bytes,
            )
        };
        for level in 0..num_levels {
            // Apply the same transformation as done in the shader.
            let size = self.texture.size(level);
            let mut mirrored = reference_images[level as usize].data().to_vec();
            flip_horizontally(&mut mirrored, size, pixel_size);
            let reference =
                ConstPixelBufferAccess::new(tcu_format, [size[0] as u32, size[1] as u32, size[2] as u32], &mirrored);
            let level_bytes = level_size_bytes(&self.texture, pixel_size, level);
            let offset = buffer_offsets[level as usize];
            let result = ConstPixelBufferAccess::new(
                tcu_format,
                [size[0] as u32, size[1] as u32, size[2] as u32],
                &data[offset..offset + level_bytes],
            );

            if !compare_pixel_buffers(self.format, &reference, &result) {
                return Ok(TestStatus::fail(format!("Image Level {level} comparison failed")));
            }
        }

        Ok(TestStatus::pass("Passed"))
    }
}

/// `createImageLoadStoreLodAMDTests`
pub fn create_image_load_store_lod_amd_tests() -> TestCaseGroup {
    let textures = [
        Texture::new(ImageType::OneDArray, [64, 1, 1], 8, 1, 6),
        Texture::new(ImageType::OneD, [64, 1, 1], 1, 1, 6),
        Texture::new(ImageType::TwoD, [64, 64, 1], 1, 1, 6),
        Texture::new(ImageType::TwoDArray, [64, 64, 1], 8, 1, 6),
        Texture::new(ImageType::ThreeD, [64, 64, 8], 1, 1, 6),
        Texture::new(ImageType::Cube, [64, 64, 1], 6, 1, 6),
        Texture::new(ImageType::CubeArray, [64, 64, 1], 2 * 6, 1, 6),
    ];

    let mut test_group = TestCaseGroup::new("load_store_lod");
    let mut test_group_with_format = TestCaseGroup::new("with_format");
    let mut test_group_without_format = TestCaseGroup::new("without_format");

    for texture in textures {
        let mut group_with_format_by_image_view_type = TestCaseGroup::new(get_image_type_name(texture.type_()));
        let mut group_without_format_by_image_view_type = TestCaseGroup::new(get_image_type_name(texture.type_()));
        let is_layered = texture.num_layers() > 1;
        let both = FLAG_DECLARE_FORMAT_IN_SHADER_READS | FLAG_DECLARE_FORMAT_IN_SHADER_WRITES;

        for &(format, has_spirv_format) in FORMATS {
            // These tests always require a SPIR-V format for the write image, even if the read image is being used without a format.
            if !has_spirv_format {
                continue;
            }
            let short = format_short_string(format);

            group_with_format_by_image_view_type.add_child(Box::new(LoadStoreLodCase {
                name: short.clone(),
                texture,
                format,
                flags: both,
            }) as Box<dyn TestCase>);
            group_without_format_by_image_view_type.add_child(Box::new(LoadStoreLodCase {
                name: short.clone(),
                texture,
                format,
                flags: FLAG_DECLARE_FORMAT_IN_SHADER_WRITES,
            }) as Box<dyn TestCase>);

            if is_layered {
                group_with_format_by_image_view_type.add_child(Box::new(LoadStoreLodCase {
                    name: format!("{short}_single_layer"),
                    texture,
                    format,
                    flags: FLAG_SINGLE_LAYER_BIND | both,
                }) as Box<dyn TestCase>);
            }
        }

        test_group_with_format.add_child(group_with_format_by_image_view_type);
        test_group_without_format.add_child(group_without_format_by_image_view_type);
    }

    test_group.add_child(test_group_with_format);
    test_group.add_child(test_group_without_format);
    test_group
}
