/// `LodBiasCase`
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum LodBiasCase {
    SamplerBias,
    SamplerMinLod,
    ShaderLod,
    ShaderBias,
    ViewMinLod,
}

impl LodBiasCase {
    const ALL: [LodBiasCase; 5] = [
        Self::SamplerBias,
        Self::SamplerMinLod,
        Self::ShaderLod,
        Self::ShaderBias,
        Self::ViewMinLod,
    ];

    /// `getLodBiasCaseName`
    fn name(self) -> &'static str {
        match self {
            Self::SamplerBias => "sampler_bias",
            Self::SamplerMinLod => "sampler_minlod",
            Self::ShaderLod => "shader_lod",
            Self::ShaderBias => "shader_bias",
            Self::ViewMinLod => "view_minlod",
        }
    }

    fn index(self) -> u32 {
        Self::ALL
            .iter()
            .position(|case| *case == self)
            .expect("every case is listed") as u32
    }
}

/// `MaxSamplerLodBiasParams`
#[derive(Clone, Copy)]
struct MaxSamplerLodBiasParams {
    lod_bias_case: LodBiasCase,
    use_compute: bool,
}

/// `MaxSamplerLodBiasCase`
struct MaxSamplerLodBiasCase {
    name: String,
    params: MaxSamplerLodBiasParams,
}

impl TestCase for MaxSamplerLodBiasCase {
    fn name(&self) -> &str {
        &self.name
    }

    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        if self.params.lod_bias_case == LodBiasCase::ViewMinLod {
            context.require_device_functionality("VK_EXT_image_view_min_lod")?;
        }
        if self.params.use_compute && context.get_compute_queue().is_none() {
            return Err(TestError::NotSupported(
                "Exclusive compute queue not supported.".to_string(),
            ));
        }
        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        let params = &self.params;
        let key = match (params.use_compute, params.lod_bias_case) {
            (false, LodBiasCase::ShaderLod) => "lodbias_gfx_lod",
            (false, LodBiasCase::ShaderBias) => "lodbias_gfx_bias",
            (false, _) => "lodbias_gfx_zero",
            // 'texture(sampler, uv, bias)' is not valid in compute, and with a base lod of 0 the bias is the explicit lod.
            (true, LodBiasCase::ShaderLod | LodBiasCase::ShaderBias) => "lodbias_cmp_lod",
            (true, _) => "lodbias_cmp_zero",
        };
        ALL_SHARED_PROGRAM
            .iter()
            .find(|program| program.name == key)
            .map_or(BinaryCollection::new(&[]), |program| program.programs)
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(MaxSamplerLodBiasInstance {
            context,
            params: self.params,
        })
    }
}

/// `MaxSamplerLodBiasInstance`
struct MaxSamplerLodBiasInstance<'a> {
    context: &'a Context<'a>,
    params: MaxSamplerLodBiasParams,
}

impl TestInstance for MaxSamplerLodBiasInstance<'_> {
    fn iterate(&mut self) -> TestOutcome {
        let context = self.context;
        let params = &self.params;
        let device = context.get_device();
        let allocator = context.get_default_allocator();
        let vk_format = vk::Format::R8G8B8A8_UNORM;
        let image_type = vk::ImageType::_2D;
        let tiling = vk::ImageTiling::OPTIMAL;
        let texture_usage = vk::ImageUsageFlags::TRANSFER_DST | vk::ImageUsageFlags::SAMPLED;
        let out_usage = vk::ImageUsageFlags::TRANSFER_SRC
            | if params.use_compute {
                vk::ImageUsageFlags::STORAGE
            } else {
                vk::ImageUsageFlags::COLOR_ATTACHMENT
            };
        let descriptor_type = vk::DescriptorType::COMBINED_IMAGE_SAMPLER;
        let max_lod_bias = context.get_device_properties().limits.max_sampler_lod_bias;
        let rounded_bias = (max_lod_bias + 0.5).floor();
        let texture_properties = unsafe {
            context.get_instance().get_physical_device_image_format_properties(
                context.get_physical_device(),
                vk_format,
                image_type,
                tiling,
                texture_usage,
                vk::ImageCreateFlags::empty(),
            )
        }
        .vk_check("vkGetPhysicalDeviceImageFormatProperties")?;
        let texture_extent = vk::Extent3D {
            width: texture_properties.max_extent.width,
            height: 1,
            depth: 1,
        };
        let (fb_width, fb_height) = (1u32, 1u32);
        let base_seed = 1_687_852_938u32;
        let (queue, queue_index) = queue_of(context, params.use_compute)?;

        let texture_info = vk::ImageCreateInfo::builder()
            .image_type(image_type)
            .format(vk_format)
            .extent(texture_extent)
            .mip_levels(texture_properties.max_mip_levels)
            .array_layers(1)
            .samples(vk::SampleCountFlags::_1)
            .tiling(tiling)
            .usage(texture_usage)
            .sharing_mode(vk::SharingMode::EXCLUSIVE)
            .initial_layout(vk::ImageLayout::UNDEFINED)
            .build();
        let texture = ImageWithMemory::new(device, allocator, texture_info, MemoryRequirement::ANY)?;
        let texture_color_srr =
            make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, texture_info.mip_levels, 0, 1);
        let accessed_level = rounded_bias.min((texture_info.mip_levels - 1) as f32);

        let mut view_min_lod = vk::ImageViewMinLodCreateInfoEXT::builder().min_lod(accessed_level);
        let mut view_info = vk::ImageViewCreateInfo::builder()
            .image(texture.get())
            .view_type(vk::ImageViewType::_2D)
            .format(vk_format)
            .components(vk::ComponentMapping {
                r: vk::ComponentSwizzle::R,
                g: vk::ComponentSwizzle::G,
                b: vk::ComponentSwizzle::B,
                a: vk::ComponentSwizzle::A,
            })
            .subresource_range(texture_color_srr);
        if params.lod_bias_case == LodBiasCase::ViewMinLod {
            view_info = view_info.push_next(&mut view_min_lod);
        }
        let texture_view = Unique::new(
            device,
            unsafe { device.create_image_view(&view_info, None) }.vk_check("vkCreateImageView")?,
        );

        // Output color buffer.
        let color_buffer = ImageWithBuffer::new(context, fb_width, fb_height, vk_format, out_usage, 4)?;

        // Texture sampler.
        let mut sampler_params =
            SamplerParams::default_params(vk::BorderColor::FLOAT_TRANSPARENT_BLACK, vk::LOD_CLAMP_NONE, false);
        sampler_params.address_mode_u = vk::SamplerAddressMode::REPEAT;
        sampler_params.address_mode_v = vk::SamplerAddressMode::REPEAT;
        sampler_params.address_mode_w = vk::SamplerAddressMode::REPEAT;
        sampler_params.mip_lod_bias = if params.lod_bias_case == LodBiasCase::SamplerBias {
            max_lod_bias
        } else {
            0.0
        };
        sampler_params.min_lod = if params.lod_bias_case == LodBiasCase::SamplerMinLod {
            max_lod_bias
        } else {
            0.0
        };
        sampler_params.max_anisotropy = 0.0;
        let sampler = sampler_params.create(device)?;

        // Push constants.
        let pc_values = [max_lod_bias, fb_width as f32, fb_height as f32];
        let pc_bytes: Vec<u8> = pc_values.iter().flat_map(|value| value.to_ne_bytes()).collect();
        let pc_stages = if params.use_compute {
            vk::ShaderStageFlags::COMPUTE
        } else {
            vk::ShaderStageFlags::FRAGMENT
        };
        let pc_range = [vk::PushConstantRange {
            stage_flags: pc_stages,
            offset: 0,
            size: pc_bytes.len() as u32,
        }];

        // Descriptor pool and set.
        let mut layout_builder = DescriptorSetLayoutBuilder::new();
        if params.use_compute {
            layout_builder = layout_builder
                .add_single_binding(descriptor_type, vk::ShaderStageFlags::COMPUTE)
                .add_single_binding(vk::DescriptorType::STORAGE_IMAGE, vk::ShaderStageFlags::COMPUTE);
        } else {
            layout_builder = layout_builder.add_single_binding(descriptor_type, vk::ShaderStageFlags::FRAGMENT);
        }
        let descriptor_set_layout = layout_builder.build(device)?;
        let set_layouts = [*descriptor_set_layout];
        let layout_info = vk::PipelineLayoutCreateInfo::builder()
            .set_layouts(&set_layouts)
            .push_constant_ranges(&pc_range);
        let pipeline_layout = Unique::new(
            device,
            unsafe { device.create_pipeline_layout(&layout_info, None) }.vk_check("vkCreatePipelineLayout")?,
        );

        let mut pool_builder = DescriptorPoolBuilder::new().add_type(descriptor_type, 1);
        if params.use_compute {
            pool_builder = pool_builder.add_type(vk::DescriptorType::STORAGE_IMAGE, 1);
        }
        let descriptor_pool = pool_builder.build(device, vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET, 1)?;
        let descriptor_set = make_descriptor_set(device, *descriptor_pool, *descriptor_set_layout)?;

        let sampler_descriptor_info = [vk::DescriptorImageInfo {
            sampler: *sampler,
            image_view: *texture_view,
            image_layout: vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL,
        }];
        let storage_info = [vk::DescriptorImageInfo {
            sampler: vk::Sampler::null(),
            image_view: *color_buffer.view,
            image_layout: vk::ImageLayout::GENERAL,
        }];
        let mut writes = vec![
            vk::WriteDescriptorSet::builder()
                .dst_set(descriptor_set.get())
                .dst_binding(0)
                .descriptor_type(descriptor_type)
                .image_info(&sampler_descriptor_info)
                .build(),
        ];
        if params.use_compute {
            writes.push(
                vk::WriteDescriptorSet::builder()
                    .dst_set(descriptor_set.get())
                    .dst_binding(1)
                    .descriptor_type(vk::DescriptorType::STORAGE_IMAGE)
                    .image_info(&storage_info)
                    .build(),
            );
        }
        unsafe { device.update_descriptor_sets(&writes, &[] as &[vk::CopyDescriptorSet]) };

        let cmd_pool = make_command_pool(device, queue_index)?;
        let cmd_buffer = allocate_command_buffer(device, *cmd_pool, vk::CommandBufferLevel::PRIMARY)?;
        let cmd = *cmd_buffer;
        begin_command_buffer(device, cmd)?;

        // Transition the texture to a layout suitable for filling.
        let pre_fill_barrier = make_image_memory_barrier(
            vk::AccessFlags::empty(),
            vk::AccessFlags::TRANSFER_WRITE,
            vk::ImageLayout::UNDEFINED,
            vk::ImageLayout::TRANSFER_DST_OPTIMAL,
            texture.get(),
            texture_color_srr,
        );
        unsafe {
            device.cmd_pipeline_barrier(
                cmd,
                vk::PipelineStageFlags::TOP_OF_PIPE,
                vk::PipelineStageFlags::TRANSFER,
                vk::DependencyFlags::empty(),
                &[] as &[vk::MemoryBarrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[pre_fill_barrier],
            );
        }

        // Fill every level with a different random color.
        let mut rnd = Random::new(base_seed + params.lod_bias_case.index());
        let mut level_colors = Vec::with_capacity(texture_info.mip_levels as usize);
        for level in 0..texture_info.mip_levels {
            let level_range = make_image_subresource_range(vk::ImageAspectFlags::COLOR, level, 1, 0, 1);
            // The colors are drawn one after the other, so the order does not depend on the compiler.
            let red = rnd.get_float_range(0.0, 1.0);
            let green = rnd.get_float_range(0.0, 1.0);
            let blue = rnd.get_float_range(0.0, 1.0);
            let clear_value = [red, green, blue, 1.0f32];
            level_colors.push(clear_value);
            let clear_color = vk::ClearColorValue { float32: clear_value };
            unsafe {
                device.cmd_clear_color_image(
                    cmd,
                    texture.get(),
                    vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                    &clear_color,
                    &[level_range],
                )
            };
        }

        // Transition the texture to a layout suitable for reading it in the shader.
        let pre_read_barrier = make_image_memory_barrier(
            vk::AccessFlags::TRANSFER_WRITE,
            vk::AccessFlags::SHADER_READ,
            vk::ImageLayout::TRANSFER_DST_OPTIMAL,
            vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL,
            texture.get(),
            texture_color_srr,
        );
        unsafe {
            device.cmd_pipeline_barrier(
                cmd,
                vk::PipelineStageFlags::TRANSFER,
                if params.use_compute {
                    vk::PipelineStageFlags::COMPUTE_SHADER
                } else {
                    vk::PipelineStageFlags::FRAGMENT_SHADER
                },
                vk::DependencyFlags::empty(),
                &[] as &[vk::MemoryBarrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[pre_read_barrier],
            );
        }

        let binaries = context.get_binary_collection();
        if params.use_compute {
            let compute_module = create_shader_module(device, binaries.get("comp")?)?;
            let stage = vk::PipelineShaderStageCreateInfo::builder()
                .stage(vk::ShaderStageFlags::COMPUTE)
                .module(*compute_module)
                .name(b"main\0")
                .build();
            let compute_info = vk::ComputePipelineCreateInfo::builder()
                .stage(stage)
                .layout(*pipeline_layout)
                .base_pipeline_index(0)
                .build();
            let pipeline = Unique::new(
                device,
                unsafe { device.create_compute_pipelines(vk::PipelineCache::null(), &[compute_info], None) }
                    .vk_check("vkCreateComputePipelines")?
                    .0[0],
            );

            let output_srr = make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, 1, 0, 1);
            let pre_write_barrier = make_image_memory_barrier(
                vk::AccessFlags::empty(),
                vk::AccessFlags::SHADER_WRITE,
                vk::ImageLayout::UNDEFINED,
                vk::ImageLayout::GENERAL,
                color_buffer.image.get(),
                output_srr,
            );
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TOP_OF_PIPE,
                    vk::PipelineStageFlags::COMPUTE_SHADER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[pre_write_barrier],
                );
                device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::COMPUTE, *pipeline);
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::COMPUTE,
                    *pipeline_layout,
                    0,
                    &[descriptor_set.get()],
                    &[] as &[u32],
                );
                device.cmd_push_constants(cmd, *pipeline_layout, vk::ShaderStageFlags::COMPUTE, 0, &pc_bytes);
                device.cmd_dispatch(cmd, 1, 1, 1);
            }

            // Copy the color buffer to the verification buffer.
            record_copy_image_to_buffer(
                device,
                cmd,
                color_buffer.image.get(),
                color_buffer.buffer.get(),
                [fb_width, fb_height],
                vk::AccessFlags::SHADER_WRITE,
                vk::ImageLayout::GENERAL,
                vk::PipelineStageFlags::COMPUTE_SHADER,
            );
            end_command_buffer(device, cmd)?;
            submit_commands_and_wait(device, queue, cmd)?;
        } else {
            // Vertex buffer.
            let vertices: [[f32; 4]; 4] = [
                [-1.0, -1.0, 0.0, 1.0],
                [-1.0, 1.0, 0.0, 1.0],
                [1.0, -1.0, 0.0, 1.0],
                [1.0, 1.0, 0.0, 1.0],
            ];
            let vertex_buffer_size = std::mem::size_of_val(&vertices) as vk::DeviceSize;
            let vertex_buffer = BufferWithMemory::new(
                device,
                allocator,
                make_buffer_create_info(vertex_buffer_size, vk::BufferUsageFlags::VERTEX_BUFFER),
                MemoryRequirement::HOST_VISIBLE,
            )?;
            unsafe {
                std::ptr::copy_nonoverlapping(
                    vertices.as_ptr().cast::<u8>(),
                    vertex_buffer.get_allocation().get_host_ptr(),
                    vertex_buffer_size as usize,
                )
            };
            flush_alloc(device, vertex_buffer.get_allocation())?;

            // Render pass and framebuffer.
            let render_pass = single_color_attachment_render_pass(device, vk_format)?;
            let framebuffer = make_framebuffer(device, *render_pass, &[*color_buffer.view], fb_width, fb_height, 1)?;

            // Pipeline.
            let vertex_module = create_shader_module(device, binaries.get("vert")?)?;
            let fragment_module = create_shader_module(device, binaries.get("frag")?)?;
            let mut state =
                DrawPipelineState::new(vk::PrimitiveTopology::TRIANGLE_STRIP).with_full_viewport(fb_width, fb_height);
            state.bindings = vec![vk::VertexInputBindingDescription {
                binding: 0,
                stride: 16,
                input_rate: vk::VertexInputRate::VERTEX,
            }];
            state.attributes = vec![vk::VertexInputAttributeDescription {
                location: 0,
                binding: 0,
                format: vk::Format::R32G32B32A32_SFLOAT,
                offset: 0,
            }];
            let pipeline = create_draw_pipeline(
                device,
                *pipeline_layout,
                *render_pass,
                &[
                    (vk::ShaderStageFlags::VERTEX, *vertex_module),
                    (vk::ShaderStageFlags::FRAGMENT, *fragment_module),
                ],
                &state,
            )?;

            let clear_values = [vk::ClearValue {
                color: vk::ClearColorValue { float32: [0.0; 4] },
            }];
            let begin_info = vk::RenderPassBeginInfo::builder()
                .render_pass(*render_pass)
                .framebuffer(*framebuffer)
                .render_area(make_rect_2d(0, 0, fb_width, fb_height))
                .clear_values(&clear_values);
            unsafe {
                device.cmd_begin_render_pass(cmd, &begin_info, vk::SubpassContents::INLINE);
                device.cmd_bind_vertex_buffers(cmd, 0, &[vertex_buffer.get()], &[0]);
                device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::GRAPHICS, *pipeline);
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::GRAPHICS,
                    *pipeline_layout,
                    0,
                    &[descriptor_set.get()],
                    &[] as &[u32],
                );
                device.cmd_push_constants(cmd, *pipeline_layout, pc_stages, 0, &pc_bytes);
                device.cmd_draw(cmd, 4, 1, 0, 0);
                device.cmd_end_render_pass(cmd);
            }

            // Copy the color buffer to the verification buffer.
            record_copy_image_to_buffer(
                device,
                cmd,
                color_buffer.image.get(),
                color_buffer.buffer.get(),
                [fb_width, fb_height],
                vk::AccessFlags::COLOR_ATTACHMENT_WRITE,
                vk::ImageLayout::COLOR_ATTACHMENT_OPTIMAL,
                vk::PipelineStageFlags::COLOR_ATTACHMENT_OUTPUT,
            );
            end_command_buffer(device, cmd)?;
            submit_commands_and_wait(device, queue, cmd)?;
        }

        // Verify that the color buffer has the color of the right mip level.
        let bytes = color_buffer.read_bytes(device)?;
        let result = ConstPixelBufferAccess::new(
            crate::tcu::texture::TextureFormat::new(
                crate::tcu::texture::ChannelOrder::RGBA,
                crate::tcu::texture::ChannelType::UNORM_INT8,
            ),
            [fb_width, fb_height, 1],
            bytes,
        );
        let expected = level_colors[accessed_level as usize];
        let actual = result.get_pixel(0, 0, 0);
        let channel_threshold = 0.005f32; // 1/255 < 0.005 < 2/255
        let threshold = [channel_threshold, channel_threshold, channel_threshold, 0.0];
        if (0..4).any(|c| (expected[c] - actual[c]).abs() > threshold[c]) {
            return Ok(TestStatus::fail(
                "Unexpected color found in color buffer -- check log for details",
            ));
        }

        Ok(TestStatus::pass("Pass"))
    }
}

/// `createMaxSamplerLodBiasTests`
pub fn create_max_sampler_lod_bias_tests(monolithic: bool) -> TestCaseGroup {
    let mut test_group = TestCaseGroup::new("max_sampler_lod_bias");

    for lod_bias_case in LodBiasCase::ALL {
        let name = lod_bias_case.name();
        test_group.add_child(Box::new(MaxSamplerLodBiasCase {
            name: name.to_string(),
            params: MaxSamplerLodBiasParams {
                lod_bias_case,
                use_compute: false,
            },
        }) as Box<dyn TestCase>);

        // Compute variant
        if monolithic {
            test_group.add_child(Box::new(MaxSamplerLodBiasCase {
                name: format!("{name}_compute"),
                params: MaxSamplerLodBiasParams {
                    lod_bias_case,
                    use_compute: true,
                },
            }) as Box<dyn TestCase>);
        }
    }

    test_group
}
