/// `ExactSamplingCase::Params`
#[derive(Clone, Copy)]
struct ExactSamplingParams {
    format: vk::Format,
    unnormalized_coordinates: bool,
    solid_color: bool,
    /// -1.0 or 1.0
    offset_sign: Option<f32>,
    use_compute: bool,
}

/// `ExactSamplingCase`
struct ExactSamplingCase {
    name: String,
    params: ExactSamplingParams,
}

/// `ExactSamplingCase::VertexData`
#[repr(C)]
#[derive(Clone, Copy)]
struct ExactVertexData {
    vtx_coords: [f32; 2],
    tex_coords: [f32; 2],
}

const EXACT_TEXTURE_SIZE: u32 = 256;

impl TestCase for ExactSamplingCase {
    fn name(&self) -> &str {
        &self.name
    }

    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        let params = &self.params;
        if params.format == vk::Format::A8_UNORM {
            context.require_device_functionality("VK_KHR_maintenance5")?;
        }

        let properties = unsafe {
            context
                .get_instance()
                .get_physical_device_format_properties(context.get_physical_device(), params.format)
        };
        let mut required_features = vk::FormatFeatureFlags::TRANSFER_DST
            | vk::FormatFeatureFlags::TRANSFER_SRC
            | vk::FormatFeatureFlags::SAMPLED_IMAGE
            | if params.use_compute {
                vk::FormatFeatureFlags::STORAGE_IMAGE
            } else {
                vk::FormatFeatureFlags::COLOR_ATTACHMENT
            };
        if params.solid_color {
            required_features |= vk::FormatFeatureFlags::SAMPLED_IMAGE_FILTER_LINEAR;
        }

        if !properties.optimal_tiling_features.contains(required_features) {
            return Err(TestError::NotSupported(
                "Selected format does not support the required features".to_string(),
            ));
        }
        if params.use_compute && context.get_compute_queue().is_none() {
            return Err(TestError::NotSupported(
                "Exclusive compute queue not supported.".to_string(),
            ));
        }
        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        let params = &self.params;
        let key = if params.use_compute {
            let qualifier = map_vk_format(params.format)
                .and_then(|format| get_shader_image_format_qualifier(format, params.format))
                .unwrap_or_default();
            format!("exact_cmp_{}_{}", qualifier, u32::from(params.unnormalized_coordinates))
        } else {
            format!(
                "exact_gfx_{}_{}",
                type_prefix(params.format),
                u32::from(params.unnormalized_coordinates)
            )
        };
        ALL_SHARED_PROGRAM
            .iter()
            .find(|program| program.name == key)
            .map_or(BinaryCollection::new(&[]), |program| program.programs)
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(ExactSamplingInstance {
            context,
            params: self.params,
        })
    }
}

/// `ExactSamplingInstance`
struct ExactSamplingInstance<'a> {
    context: &'a Context<'a>,
    params: ExactSamplingParams,
}

impl TestInstance for ExactSamplingInstance<'_> {
    fn iterate(&mut self) -> TestOutcome {
        let context = self.context;
        let params = &self.params;
        let device = context.get_device();
        let allocator = context.get_default_allocator();
        let (queue, queue_index) = queue_of(context, params.use_compute)?;
        let queue_family_indices = [queue_index];
        let tcu_format = map_vk_format(params.format)
            .ok_or_else(|| TestError::NotPorted(format!("no texture format for {:?}", params.format)))?;
        let format_info = get_texture_format_info(tcu_format);
        let tex_extent = vk::Extent3D {
            width: EXACT_TEXTURE_SIZE,
            height: EXACT_TEXTURE_SIZE,
            depth: 1,
        };
        let tex_usage = vk::ImageUsageFlags::TRANSFER_DST | vk::ImageUsageFlags::SAMPLED;
        let out_usage = vk::ImageUsageFlags::TRANSFER_SRC
            | if params.use_compute {
                vk::ImageUsageFlags::STORAGE
            } else {
                vk::ImageUsageFlags::COLOR_ATTACHMENT
            };
        let desc_type = vk::DescriptorType::COMBINED_IMAGE_SAMPLER;
        let tex_layout = vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL;
        let unnorm = params.unnormalized_coordinates;

        let image_info = |usage: vk::ImageUsageFlags| {
            vk::ImageCreateInfo::builder()
                .image_type(vk::ImageType::_2D)
                .format(params.format)
                .extent(tex_extent)
                .mip_levels(1)
                .array_layers(1)
                .samples(vk::SampleCountFlags::_1)
                .tiling(vk::ImageTiling::OPTIMAL)
                .usage(usage)
                .sharing_mode(vk::SharingMode::EXCLUSIVE)
                .queue_family_indices(&queue_family_indices)
                .initial_layout(vk::ImageLayout::UNDEFINED)
                .build()
        };

        // Create main and framebuffer images, with their views.
        let tex_image = ImageWithMemory::new(device, allocator, image_info(tex_usage), MemoryRequirement::ANY)?;
        let out_image = ImageWithMemory::new(device, allocator, image_info(out_usage), MemoryRequirement::ANY)?;
        let color_subresource_range = make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, 1, 0, 1);
        let tex_view = make_image_view(
            device,
            tex_image.get(),
            vk::ImageViewType::_2D,
            params.format,
            color_subresource_range,
        )?;
        let out_view = make_image_view(
            device,
            out_image.get(),
            vk::ImageViewType::_2D,
            params.format,
            color_subresource_range,
        )?;

        // Buffers to create the texture and verify results.
        let pixel_size = tcu_format
            .pixel_size()
            .ok_or_else(|| TestError::NotPorted(format!("pixel size of {:?}", params.format)))?;
        let tex_buffer_size =
            vk::DeviceSize::from(pixel_size * tex_extent.width * tex_extent.height * tex_extent.depth);
        let tex_buffer = BufferWithMemory::new(
            device,
            allocator,
            make_buffer_create_info(tex_buffer_size, vk::BufferUsageFlags::TRANSFER_SRC),
            MemoryRequirement::HOST_VISIBLE,
        )?;
        let results_buffer = BufferWithMemory::new(
            device,
            allocator,
            make_buffer_create_info(tex_buffer_size, vk::BufferUsageFlags::TRANSFER_DST),
            MemoryRequirement::HOST_VISIBLE,
        )?;

        // Create the texture.
        let (w, h) = (tex_extent.width, tex_extent.height);
        let tex_bytes = unsafe {
            std::slice::from_raw_parts_mut(tex_buffer.get_allocation().get_host_ptr(), tex_buffer_size as usize)
        };
        let mut tex_pixels = PixelBufferAccess::new(tcu_format, [w, h, 1], tex_bytes);
        let div_x = (w - 1) as f32;
        let div_y = (h - 1) as f32;
        for x in 0..w {
            for y in 0..h {
                let tex_color = if params.solid_color {
                    // Texture with solid color for filtered sampling.
                    [0.5f32, 0.25, 0.752_941_2, 1.0]
                } else {
                    // Use a color gradient otherwise.
                    let color_x = x as f32 / div_x;
                    let color_y = y as f32 / div_y;
                    [color_x, color_y, color_x.min(color_y), 1.0]
                };
                let final_color: [f32; 4] = std::array::from_fn(|c| {
                    (tex_color[c] - format_info.look_up_bias[c]) / format_info.look_up_scale[c]
                });
                tex_pixels.set_pixel(final_color, x, y, 0);
            }
        }
        flush_alloc(device, tex_buffer.get_allocation())?;

        let (mut min_u, mut max_u, mut min_v, mut max_v) = (0.0f32, 1.0f32, 0.0f32, 1.0f32);

        // When testing the edges, apply a texture offset of almost half a texel, so the sample location is very close to the texel border.
        if let Some(sign) = params.offset_sign {
            debug_assert!(sign == 1.0 || sign == -1.0);
            let offset_width = 0.498 / tex_extent.width as f32;
            let offset_height = 0.498 / tex_extent.height as f32;
            min_u += sign * offset_width;
            max_u += sign * offset_width;
            min_v += sign * offset_height;
            max_v += sign * offset_height;
        }

        // Descriptor set layout, pool and set.
        let mut layout_builder = DescriptorSetLayoutBuilder::new();
        if params.use_compute {
            layout_builder = layout_builder
                .add_single_binding(
                    vk::DescriptorType::COMBINED_IMAGE_SAMPLER,
                    vk::ShaderStageFlags::COMPUTE,
                )
                .add_single_binding(vk::DescriptorType::STORAGE_IMAGE, vk::ShaderStageFlags::COMPUTE);
        } else {
            layout_builder = layout_builder.add_single_binding(desc_type, vk::ShaderStageFlags::FRAGMENT);
        }
        let descriptor_set_layout = layout_builder.build(device)?;
        let mut pool_builder = DescriptorPoolBuilder::new().add_type(desc_type, 1);
        if params.use_compute {
            pool_builder = pool_builder.add_type(vk::DescriptorType::STORAGE_IMAGE, 1);
        }
        let descriptor_pool = pool_builder.build(device, vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET, 1)?;
        let descriptor_set = make_descriptor_set(device, *descriptor_pool, *descriptor_set_layout)?;

        // Texture sampler. When using a solid color, test linear filtering, which may lose a little precision, but should give the
        // same color when converting back to the original format.
        let min_mag_filter = if params.solid_color {
            vk::Filter::LINEAR
        } else {
            vk::Filter::NEAREST
        };
        let mut sampler_params = SamplerParams::default_params(vk::BorderColor::FLOAT_TRANSPARENT_BLACK, 0.0, unnorm);
        sampler_params.mag_filter = min_mag_filter;
        sampler_params.min_filter = min_mag_filter;
        let address_mode = if unnorm {
            vk::SamplerAddressMode::CLAMP_TO_EDGE
        } else {
            vk::SamplerAddressMode::REPEAT
        };
        sampler_params.address_mode_u = address_mode;
        sampler_params.address_mode_v = address_mode;
        sampler_params.address_mode_w = address_mode;
        let tex_sampler = sampler_params.create(device)?;

        // Update the descriptor set with the descriptors.
        let descriptor_image_info = [vk::DescriptorImageInfo {
            sampler: *tex_sampler,
            image_view: *tex_view,
            image_layout: tex_layout,
        }];
        let storage_image_info = [vk::DescriptorImageInfo {
            sampler: vk::Sampler::null(),
            image_view: *out_view,
            image_layout: vk::ImageLayout::GENERAL,
        }];
        let mut writes = vec![
            vk::WriteDescriptorSet::builder()
                .dst_set(descriptor_set.get())
                .dst_binding(0)
                .descriptor_type(desc_type)
                .image_info(&descriptor_image_info)
                .build(),
        ];
        if params.use_compute {
            writes.push(
                vk::WriteDescriptorSet::builder()
                    .dst_set(descriptor_set.get())
                    .dst_binding(1)
                    .descriptor_type(vk::DescriptorType::STORAGE_IMAGE)
                    .image_info(&storage_image_info)
                    .build(),
            );
        }
        unsafe { device.update_descriptor_sets(&writes, &[] as &[vk::CopyDescriptorSet]) };

        // Command pool and command buffer.
        let cmd_pool = make_command_pool(device, queue_index)?;
        let cmd_buffer = allocate_command_buffer(device, *cmd_pool, vk::CommandBufferLevel::PRIMARY)?;
        let cmd = *cmd_buffer;

        // Copy data to the texture
        let pre_buffer_copy_barrier = vk::BufferMemoryBarrier::builder()
            .src_access_mask(vk::AccessFlags::HOST_WRITE)
            .dst_access_mask(vk::AccessFlags::TRANSFER_READ)
            .src_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
            .dst_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
            .buffer(tex_buffer.get())
            .offset(0)
            .size(tex_buffer_size)
            .build();
        let pre_tex_copy_barrier = make_image_memory_barrier(
            vk::AccessFlags::empty(),
            vk::AccessFlags::TRANSFER_WRITE,
            vk::ImageLayout::UNDEFINED,
            vk::ImageLayout::TRANSFER_DST_OPTIMAL,
            tex_image.get(),
            color_subresource_range,
        );
        let post_tex_copy_barrier = make_image_memory_barrier(
            vk::AccessFlags::TRANSFER_WRITE,
            vk::AccessFlags::SHADER_READ,
            vk::ImageLayout::TRANSFER_DST_OPTIMAL,
            tex_layout,
            tex_image.get(),
            color_subresource_range,
        );
        let tex_image_copy = vk::BufferImageCopy {
            buffer_offset: 0,
            buffer_row_length: 0,
            buffer_image_height: 0,
            image_subresource: vk::ImageSubresourceLayers {
                aspect_mask: vk::ImageAspectFlags::COLOR,
                mip_level: 0,
                base_array_layer: 0,
                layer_count: 1,
            },
            image_offset: vk::Offset3D { x: 0, y: 0, z: 0 },
            image_extent: tex_extent,
        };

        begin_command_buffer(device, cmd)?;
        unsafe {
            device.cmd_pipeline_barrier(
                cmd,
                vk::PipelineStageFlags::HOST,
                vk::PipelineStageFlags::TRANSFER,
                vk::DependencyFlags::empty(),
                &[] as &[vk::MemoryBarrier],
                &[pre_buffer_copy_barrier],
                &[] as &[vk::ImageMemoryBarrier],
            );
            device.cmd_pipeline_barrier(
                cmd,
                vk::PipelineStageFlags::TOP_OF_PIPE,
                vk::PipelineStageFlags::TRANSFER,
                vk::DependencyFlags::empty(),
                &[] as &[vk::MemoryBarrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[pre_tex_copy_barrier],
            );
            device.cmd_copy_buffer_to_image(
                cmd,
                tex_buffer.get(),
                tex_image.get(),
                vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                &[tex_image_copy],
            );
        }

        let binaries = context.get_binary_collection();
        let set_layouts = [*descriptor_set_layout];

        if params.use_compute {
            // Pipeline layout for compute
            let pc_range = [vk::PushConstantRange {
                stage_flags: vk::ShaderStageFlags::COMPUTE,
                offset: 0,
                size: 24,
            }];
            let layout_info = vk::PipelineLayoutCreateInfo::builder()
                .set_layouts(&set_layouts)
                .push_constant_ranges(&pc_range);
            let pipeline_layout = Unique::new(
                device,
                unsafe { device.create_pipeline_layout(&layout_info, None) }.vk_check("vkCreatePipelineLayout")?,
            );

            let compute_module = create_shader_module(device, binaries.get("comp")?)?;
            let stage = vk::PipelineShaderStageCreateInfo::builder()
                .stage(vk::ShaderStageFlags::COMPUTE)
                .module(*compute_module)
                .name(b"main\0")
                .build();
            let compute_info = vk::ComputePipelineCreateInfo::builder()
                .stage(stage)
                .layout(*pipeline_layout)
                .base_pipeline_index(0)
                .build();
            let pipeline = Unique::new(
                device,
                unsafe { device.create_compute_pipelines(vk::PipelineCache::null(), &[compute_info], None) }
                    .vk_check("vkCreateComputePipelines")?
                    .0[0],
            );

            // Transition the output to general
            let storage_init_barrier = make_image_memory_barrier(
                vk::AccessFlags::empty(),
                vk::AccessFlags::SHADER_WRITE,
                vk::ImageLayout::UNDEFINED,
                vk::ImageLayout::GENERAL,
                out_image.get(),
                color_subresource_range,
            );
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::COMPUTE_SHADER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[post_tex_copy_barrier, storage_init_barrier],
                );
            }

            // Dispatch
            let push_constants = [
                tex_extent.width as f32,
                tex_extent.height as f32,
                min_u,
                min_v,
                max_u - min_u,
                max_v - min_v,
            ];
            let push_bytes: Vec<u8> = push_constants.iter().flat_map(|value| value.to_ne_bytes()).collect();
            unsafe {
                device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::COMPUTE, *pipeline);
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::COMPUTE,
                    *pipeline_layout,
                    0,
                    &[descriptor_set.get()],
                    &[] as &[u32],
                );
                device.cmd_push_constants(cmd, *pipeline_layout, vk::ShaderStageFlags::COMPUTE, 0, &push_bytes);
                device.cmd_dispatch(cmd, tex_extent.width.div_ceil(16), tex_extent.height.div_ceil(16), 1);
            }

            // Copy the result to the host buffer
            record_copy_image_to_buffer(
                device,
                cmd,
                out_image.get(),
                results_buffer.get(),
                [w, h],
                vk::AccessFlags::SHADER_WRITE,
                vk::ImageLayout::GENERAL,
                vk::PipelineStageFlags::COMPUTE_SHADER,
            );
            end_command_buffer(device, cmd)?;
            submit_commands_and_wait(device, queue, cmd)?;
        } else {
            let full_screen_quad = [
                ExactVertexData {
                    vtx_coords: [1.0, -1.0],
                    tex_coords: [max_u, min_v],
                },
                ExactVertexData {
                    vtx_coords: [-1.0, -1.0],
                    tex_coords: [min_u, min_v],
                },
                ExactVertexData {
                    vtx_coords: [-1.0, 1.0],
                    tex_coords: [min_u, max_v],
                },
                ExactVertexData {
                    vtx_coords: [-1.0, 1.0],
                    tex_coords: [min_u, max_v],
                },
                ExactVertexData {
                    vtx_coords: [1.0, -1.0],
                    tex_coords: [max_u, min_v],
                },
                ExactVertexData {
                    vtx_coords: [1.0, 1.0],
                    tex_coords: [max_u, max_v],
                },
            ];

            // Vertex buffer.
            let vertex_buffer_size = std::mem::size_of_val(&full_screen_quad) as vk::DeviceSize;
            let vertex_buffer = BufferWithMemory::new(
                device,
                allocator,
                make_buffer_create_info(vertex_buffer_size, vk::BufferUsageFlags::VERTEX_BUFFER),
                MemoryRequirement::HOST_VISIBLE,
            )?;
            unsafe {
                std::ptr::copy_nonoverlapping(
                    full_screen_quad.as_ptr().cast::<u8>(),
                    vertex_buffer.get_allocation().get_host_ptr(),
                    vertex_buffer_size as usize,
                )
            };
            flush_alloc(device, vertex_buffer.get_allocation())?;

            // Shader modules, render pass and framebuffer.
            let vertex_module = create_shader_module(device, binaries.get("vert")?)?;
            let fragment_module = create_shader_module(device, binaries.get("frag")?)?;
            let render_pass = single_color_attachment_render_pass(device, params.format)?;
            let framebuffer = make_framebuffer(
                device,
                *render_pass,
                &[*out_view],
                tex_extent.width,
                tex_extent.height,
                tex_extent.depth,
            )?;

            // Pipeline layout, with the push constants of the vertex shader.
            let pc_range = [vk::PushConstantRange {
                stage_flags: vk::ShaderStageFlags::VERTEX,
                offset: 0,
                size: 8,
            }];
            let layout_info = vk::PipelineLayoutCreateInfo::builder()
                .set_layouts(&set_layouts)
                .push_constant_ranges(&pc_range);
            let pipeline_layout = Unique::new(
                device,
                unsafe { device.create_pipeline_layout(&layout_info, None) }.vk_check("vkCreatePipelineLayout")?,
            );

            // Graphics pipeline.
            let mut state = DrawPipelineState::new(vk::PrimitiveTopology::TRIANGLE_LIST)
                .with_full_viewport(tex_extent.width, tex_extent.height);
            state.bindings = vec![vk::VertexInputBindingDescription {
                binding: 0,
                stride: std::mem::size_of::<ExactVertexData>() as u32,
                input_rate: vk::VertexInputRate::VERTEX,
            }];
            state.attributes = vec![
                vk::VertexInputAttributeDescription {
                    location: 0,
                    binding: 0,
                    format: vk::Format::R32G32_SFLOAT,
                    offset: std::mem::offset_of!(ExactVertexData, vtx_coords) as u32,
                },
                vk::VertexInputAttributeDescription {
                    location: 1,
                    binding: 0,
                    format: vk::Format::R32G32_SFLOAT,
                    offset: std::mem::offset_of!(ExactVertexData, tex_coords) as u32,
                },
            ];
            let pipeline = create_draw_pipeline(
                device,
                *pipeline_layout,
                *render_pass,
                &[
                    (vk::ShaderStageFlags::VERTEX, *vertex_module),
                    (vk::ShaderStageFlags::FRAGMENT, *fragment_module),
                ],
                &state,
            )?;

            // Draw the quad.
            let push_bytes: Vec<u8> = [tex_extent.width as f32, tex_extent.height as f32]
                .iter()
                .flat_map(|value| value.to_ne_bytes())
                .collect();
            let vertex_buffer_barrier = vk::BufferMemoryBarrier::builder()
                .src_access_mask(vk::AccessFlags::HOST_WRITE)
                .dst_access_mask(vk::AccessFlags::VERTEX_ATTRIBUTE_READ)
                .src_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
                .dst_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
                .buffer(vertex_buffer.get())
                .offset(0)
                .size(vertex_buffer_size)
                .build();
            let clear_values = [vk::ClearValue {
                color: vk::ClearColorValue {
                    float32: [0.0, 0.0, 0.0, 1.0],
                },
            }];
            let render_area = make_rect_2d(0, 0, tex_extent.width, tex_extent.height);
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::HOST,
                    vk::PipelineStageFlags::VERTEX_INPUT,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[vertex_buffer_barrier],
                    &[] as &[vk::ImageMemoryBarrier],
                );
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::FRAGMENT_SHADER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[post_tex_copy_barrier],
                );

                let begin_info = vk::RenderPassBeginInfo::builder()
                    .render_pass(*render_pass)
                    .framebuffer(*framebuffer)
                    .render_area(render_area)
                    .clear_values(&clear_values);
                device.cmd_begin_render_pass(cmd, &begin_info, vk::SubpassContents::INLINE);
                device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::GRAPHICS, *pipeline);
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::GRAPHICS,
                    *pipeline_layout,
                    0,
                    &[descriptor_set.get()],
                    &[] as &[u32],
                );
                device.cmd_bind_vertex_buffers(cmd, 0, &[vertex_buffer.get()], &[0]);
                device.cmd_push_constants(cmd, *pipeline_layout, vk::ShaderStageFlags::VERTEX, 0, &push_bytes);
                device.cmd_draw(cmd, full_screen_quad.len() as u32, 1, 0, 0);
                device.cmd_end_render_pass(cmd);
            }
            record_copy_image_to_buffer(
                device,
                cmd,
                out_image.get(),
                results_buffer.get(),
                [w, h],
                vk::AccessFlags::COLOR_ATTACHMENT_WRITE,
                vk::ImageLayout::COLOR_ATTACHMENT_OPTIMAL,
                vk::PipelineStageFlags::ALL_COMMANDS,
            );
            end_command_buffer(device, cmd)?;
            submit_commands_and_wait(device, queue, cmd)?;
        }

        // Check the results.
        invalidate_alloc(device, results_buffer.get_allocation())?;
        let result_bytes = unsafe {
            std::slice::from_raw_parts(results_buffer.get_allocation().get_host_ptr(), tex_buffer_size as usize)
        };
        let result_pixels = ConstPixelBufferAccess::new(tcu_format, [w, h, 1], result_bytes);
        let in_pixels = tex_pixels.as_const();

        let mut pass = true;
        for x in 0..w {
            for y in 0..h {
                if in_pixels.get_pixel(x, y, 0) != result_pixels.get_pixel(x, y, 0) {
                    pass = false;
                }
            }
        }

        if pass {
            Ok(TestStatus::pass("Pass"))
        } else {
            Ok(TestStatus::fail("Pixel mismatch; please check the rendered image"))
        }
    }
}

/// `isStorageCompatible`
fn is_storage_compatible(format: vk::Format) -> bool {
    map_vk_format(format).is_some_and(|tcu_format| tcu_format.order.num_used_channels() != 3)
}

/// `isFormatSwizzle` - swizzled formats are skipped in compute-only mode, as they cause undefined behavior.
fn is_format_swizzle(format: vk::Format) -> bool {
    use crate::tcu::texture::ChannelOrder::{A, BGR, BGRA};
    map_vk_format(format).is_some_and(|tcu_format| matches!(tcu_format.order, BGRA | BGR | A))
}

/// `createExactSamplingTests`
pub fn create_exact_sampling_tests(monolithic: bool) -> TestCaseGroup {
    use vk::Format as F;
    const FORMATS: [vk::Format; 35] = [
        F::R8_SRGB,
        F::R8G8B8_UINT,
        F::B8G8R8A8_SINT,
        F::R8G8_UNORM,
        F::B8G8R8_SNORM,
        F::R8G8B8A8_SNORM,
        F::R8G8_UINT,
        F::R8_SINT,
        F::R8G8B8A8_SRGB,
        F::R8G8B8A8_UNORM,
        F::B8G8R8A8_UNORM,
        F::B8G8R8_SRGB,
        F::R8G8_SRGB,
        F::R8_UINT,
        F::R8G8B8A8_UINT,
        F::R8G8_SINT,
        F::R8_SNORM,
        F::B8G8R8_SINT,
        F::R8G8_SNORM,
        F::B8G8R8_UNORM,
        F::R8_UNORM,
        F::A8_UNORM,
        F::R32G32_SFLOAT,
        F::R32G32B32_UINT,
        F::R16G16B16A16_SFLOAT,
        F::R16G16_UINT,
        F::R32G32B32A32_SINT,
        F::R16G16B16_SINT,
        F::R16_SFLOAT,
        F::R32_SINT,
        F::R32_UINT,
        F::R16G16B16_SFLOAT,
        F::R16G16_SINT,
        F::R16_SNORM,
        F::R32_SFLOAT,
    ];

    let mut exact_sampling_tests = TestCaseGroup::new("exact_sampling");

    for format in FORMATS {
        let mut format_group = TestCaseGroup::new(format_case_name(format));

        for (solid_color, solid_name) in [(false, "gradient"), (true, "solid_color")] {
            let mut solid_color_group = TestCaseGroup::new(solid_name);

            for (unnormalized, unnorm_name) in [(false, "normalized_coords"), (true, "unnormalized_coords")] {
                let mut coord_group = TestCaseGroup::new(unnorm_name);

                for (offset_sign, edge_name) in [
                    (None, "centered"),
                    (Some(-1.0f32), "edge_left"),
                    (Some(1.0f32), "edge_right"),
                ] {
                    let params = ExactSamplingParams {
                        format,
                        unnormalized_coordinates: unnormalized,
                        solid_color,
                        offset_sign,
                        use_compute: false,
                    };
                    coord_group.add_child(Box::new(ExactSamplingCase {
                        name: edge_name.to_string(),
                        params,
                    }) as Box<dyn TestCase>);

                    // Compute version if compatible
                    if is_storage_compatible(format) && !is_format_swizzle(format) && monolithic {
                        let params = ExactSamplingParams {
                            use_compute: true,
                            ..params
                        };
                        coord_group.add_child(Box::new(ExactSamplingCase {
                            name: format!("{edge_name}_compute"),
                            params,
                        }) as Box<dyn TestCase>);
                    }
                }

                solid_color_group.add_child(coord_group);
            }

            format_group.add_child(solid_color_group);
        }

        exact_sampling_tests.add_child(format_group);
    }

    exact_sampling_tests
}

