#[derive(Clone, Copy, PartialEq, Eq)]
enum FormatType {
    SignedInt,
    UnsignedInt,
    Float,
}

fn is_int_format(format: vk::Format) -> bool {
    map_vk_format(format).is_some_and(|tcu_format| tcu_format.channel_class() == TextureChannelClass::SignedInteger)
}

fn is_uint_format(format: vk::Format) -> bool {
    map_vk_format(format).is_some_and(|tcu_format| tcu_format.channel_class() == TextureChannelClass::UnsignedInteger)
}

fn is_depth_stencil_format(format: vk::Format) -> bool {
    map_vk_format(format)
        .is_some_and(|tcu_format| matches!(tcu_format.order, ChannelOrder::D | ChannelOrder::S | ChannelOrder::DS))
}

fn is_srgb_format(format: vk::Format) -> bool {
    map_vk_format(format).is_some_and(|tcu_format| tcu_format.order.is_srgb())
}

fn get_format_type(format: vk::Format, use_stencil: bool) -> FormatType {
    if is_int_format(format) {
        FormatType::SignedInt
    } else if is_uint_format(format) || use_stencil {
        FormatType::UnsignedInt
    } else {
        FormatType::Float
    }
}

/// Output color attachment format varies slightly with the chosen texture format to accommodate different clear colors.
fn get_color_attachment_format(texture_format: vk::Format, use_stencil: bool) -> vk::Format {
    match get_format_type(texture_format, use_stencil) {
        FormatType::SignedInt => vk::Format::R32G32B32A32_SINT,
        FormatType::UnsignedInt => vk::Format::R32G32B32A32_UINT,
        FormatType::Float => vk::Format::R32G32B32A32_SFLOAT,
    }
}

/// The key of the manifest entry of a case.
fn border_swizzle_key(params: &TestParams) -> String {
    let letter = match get_format_type(params.texture_format, params.use_stencil_aspect) {
        FormatType::SignedInt => "i",
        FormatType::UnsignedInt => "u",
        FormatType::Float => "f",
    };
    format!(
        "bs_{}_{}_{}",
        if params.use_compute { "comp" } else { "gfx" },
        letter,
        params.component_gather.unwrap_or(0)
    )
}

/// Apply swizzling to an array of 4 elements.
fn apply_swizzle<T: Copy>(orig: [T; 4], mapping: &Swizzles, zero: T, one: T) -> [T; 4] {
    let mut result = orig;
    for (i, &swizzle) in mapping.iter().enumerate() {
        result[i] = match swizzle {
            vk::ComponentSwizzle::IDENTITY => orig[i],
            vk::ComponentSwizzle::ZERO => zero,
            vk::ComponentSwizzle::ONE => one,
            other => orig[(other.as_raw() - vk::ComponentSwizzle::R.as_raw()) as usize],
        };
    }
    result
}

/// Apply gathering to an array of 4 elements.
fn apply_gather<T: Copy>(orig: [T; 4], component: u32) -> [T; 4] {
    [orig[component as usize]; 4]
}

/// Transforms an input border color, once expanded, to the expected output color.
fn get_expected_vec<T: Copy>(color: [T; 4], params: &TestParams, zero: T, one: T) -> [T; 4] {
    let mut result = apply_swizzle(color, &params.component_mapping, zero, one);
    if let Some(component) = params.component_gather {
        result = apply_gather(result, component);
    }
    result
}

/// Transforms an input border color to the expected output color, taking "Conversion to RGBA" from the spec into account.
fn get_expected_color(color: ColorBits, params: &TestParams) -> ColorBits {
    let tcu_format = map_vk_format(params.texture_format).expect("the format of a case has a texture format");
    let num_comp = tcu_format.order.num_used_channels() as usize;
    let format_type = get_format_type(params.texture_format, params.use_stencil_aspect);

    if has_depth_component(tcu_format.order) || has_stencil_component(tcu_format.order) {
        if params.use_stencil_aspect {
            let border = [color[0], 0u32, 0, 1];
            return get_expected_vec(border, params, 0u32, 1u32);
        }
        let border = [f32::from_bits(color[0]), 0.0, 0.0, 1.0];
        return get_expected_vec(border, params, 0.0f32, 1.0f32).map(f32::to_bits);
    }

    match format_type {
        FormatType::UnsignedInt => {
            let mut border = [0u32; 4];
            border[..num_comp].copy_from_slice(&color[..num_comp]);
            if num_comp < 4 {
                border[3] = 1;
            }
            get_expected_vec(border, params, 0u32, 1u32)
        }
        FormatType::SignedInt => {
            let mut border = [0i32; 4];
            for i in 0..num_comp {
                border[i] = color[i] as i32;
            }
            if num_comp < 4 {
                border[3] = 1;
            }
            get_expected_vec(border, params, 0i32, 1i32).map(|value| value as u32)
        }
        FormatType::Float => {
            let mut border = [0.0f32, 0.0, 0.0, 1.0];
            if params.texture_format == vk::Format::A8_UNORM {
                // Single component alpha format borders use [0,0,0,Ba] as the border texel components after replacing.
                border[3] = f32::from_bits(color[3]);
            } else {
                // Other formats use the first color components from the border, expanded to 4 components by filling missing components with
                // zero and the alpha component with 1.
                for i in 0..num_comp {
                    border[i] = f32::from_bits(color[i]);
                }
            }
            get_expected_vec(border, params, 0.0f32, 1.0f32).map(f32::to_bits)
        }
    }
}

/// `calcFloatDiff`: the exponent and mantissa of the difference reinterpreted as an integer.
fn calc_float_diff(a: f32, b: f32) -> u64 {
    let a_sign = a.to_bits() >> 31;
    // Upstream compares the sign of `a` with itself.
    let b_sign = a.to_bits() >> 31;
    let a_value = a.to_bits() & ((1u32 << 31) - 1);
    let b_value = b.to_bits() & ((1u32 << 31) - 1);

    if a_sign != b_sign {
        u64::from(a_value) + u64::from(b_value) + 1
    } else if a_value < b_value {
        u64::from(b_value - a_value)
    } else {
        u64::from(a_value - b_value)
    }
}

/// `comparePixelToColorClearValue`, over the raw RGBA32 pixels of the output image; the comparison covers all four channels.
fn compare_pixels_to_color(
    params: &TestParams,
    pixels: &[ColorBits],
    texture_format: TextureFormat,
    reference: ColorBits,
) -> Result<(), String> {
    let texture_format = if is_combined_depth_stencil_type(texture_format.type_) {
        // The verification loop does not support reading from combined depth stencil texture levels: get rid of the other aspect.
        if params.use_stencil_aspect {
            TextureFormat::new(ChannelOrder::S, ChannelType::UNSIGNED_INT8)
        } else {
            let channel_type = match texture_format.type_ {
                ChannelType::UNSIGNED_INT_16_8_8 => ChannelType::UNORM_INT16,
                ChannelType::UNSIGNED_INT_24_8 | ChannelType::UNSIGNED_INT_24_8_REV => ChannelType::UNORM_INT24,
                _ => ChannelType::FLOAT,
            };
            TextureFormat::new(ChannelOrder::D, channel_type)
        }
    } else {
        texture_format
    };

    let channel_class = texture_format.channel_class();
    // If the component mapping contains a SWIZZLE_ONE, overwrite it with a SWIZZLE_ZERO to ensure a strict tolerance when applying a
    // swizzle of SWIZZLE_ONE to the threshold.
    let threshold_mapping: Swizzles = params.component_mapping.map(|swizzle| {
        if swizzle == vk::ComponentSwizzle::ONE {
            vk::ComponentSwizzle::ZERO
        } else {
            swizzle
        }
    });
    let bit_depth = get_texture_format_bit_depth(texture_format);

    let finish = |threshold: [f64; 4], result: &dyn Fn(&ColorBits, usize) -> f64| -> Result<(), String> {
        for (index, pixel) in pixels.iter().enumerate() {
            for channel in 0..4 {
                if result(pixel, channel) > threshold[channel] {
                    return Err(format!(
                        "pixel {index}: reference {reference:#x?}, color {pixel:#x?}, thresholds {threshold:?}"
                    ));
                }
            }
        }
        Ok(())
    };

    let relax = |relaxed: [f64; 4]| -> [f64; 4] {
        let mut threshold = if params.is_custom() { relaxed } else { [0.0; 4] };
        threshold = apply_swizzle(threshold, &threshold_mapping, 0.0, 0.0);
        if let Some(component) = params.component_gather {
            threshold = apply_gather(threshold, component);
        }
        threshold
    };

    match channel_class {
        TextureChannelClass::UnsignedFixedPoint | TextureChannelClass::SignedFixedPoint => {
            let modifier = if channel_class == TextureChannelClass::UnsignedFixedPoint {
                0
            } else {
                1
            };
            let mut relaxed = [0.0f64; 4];
            for i in 0..4 {
                relaxed[i] = if bit_depth[i] > 0 {
                    f64::from(1.0f32 / (((1u32 << (bit_depth[i] - modifier)) as f32) - 1.0))
                } else {
                    0.0
                };
                if is_srgb_format(params.texture_format) {
                    // Widen thresholds a bit due to possible low-precision sRGB conversions.
                    relaxed[i] *= 2.0;
                }
            }
            let threshold = relax(relaxed);
            let reference_floats = reference.map(f32::from_bits);
            finish(threshold, &|pixel, channel| {
                f64::from((f32::from_bits(pixel[channel]) - reference_floats[channel]).abs())
            })
        }
        TextureChannelClass::UnsignedInteger => {
            let relaxed = bit_depth.map(|depth| if depth > 0 { 1.0 } else { 0.0 });
            let threshold = relax(relaxed);
            finish(threshold, &|pixel, channel| {
                f64::from(pixel[channel].abs_diff(reference[channel]))
            })
        }
        TextureChannelClass::SignedInteger => {
            let relaxed = bit_depth.map(|depth| if depth > 0 { 1.0 } else { 0.0 });
            let threshold = relax(relaxed);
            finish(threshold, &|pixel, channel| {
                f64::from((pixel[channel] as i32).abs_diff(reference[channel] as i32))
            })
        }
        TextureChannelClass::FloatingPoint => {
            let mantissa_bits = get_texture_format_mantissa_bit_depth(texture_format);
            let relaxed = mantissa_bits.map(|bits| {
                if bits > 0 {
                    (10u64 * (1u64 << (23 - bits as u64))) as f64
                } else {
                    0.0
                }
            });
            let threshold = relax(relaxed);
            let reference_floats = reference.map(f32::from_bits);
            finish(threshold, &|pixel, channel| {
                calc_float_diff(f32::from_bits(pixel[channel]), reference_floats[channel]) as f64
            })
        }
        _ => Err("invalid channel class".to_string()),
    }
}

/// `getBorderClearColorValue`: the clear color value of the border color, see "Texel Replacement" in the spec.
fn get_border_clear_color_value(params: &TestParams) -> ColorBits {
    let one_f = 1.0f32.to_bits();
    match params.border_color {
        vk::BorderColor::FLOAT_TRANSPARENT_BLACK | vk::BorderColor::INT_TRANSPARENT_BLACK => [0; 4],
        vk::BorderColor::FLOAT_OPAQUE_BLACK => [0, 0, 0, one_f],
        vk::BorderColor::INT_OPAQUE_BLACK => [0, 0, 0, 1],
        vk::BorderColor::FLOAT_OPAQUE_WHITE => [one_f; 4],
        vk::BorderColor::INT_OPAQUE_WHITE => [1; 4],
        _ => params
            .custom_border_color
            .expect("a custom border color case has a color"),
    }
}

struct BorderSwizzleCase {
    name: String,
    params: TestParams,
}

impl TestCase for BorderSwizzleCase {
    fn name(&self) -> &str {
        &self.name
    }

    /// `BorderSwizzleCase::checkSupport`
    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        let params = self.params;
        let instance = context.get_instance();
        let physical_device = context.get_physical_device();

        if matches!(
            params.texture_format,
            vk::Format::A8_UNORM | vk::Format::A1B5G5R5_UNORM_PACK16
        ) {
            context.require_device_functionality("VK_KHR_maintenance5")?;
        }

        let format_properties = unsafe {
            instance.get_physical_device_image_format_properties(
                physical_device,
                params.texture_format,
                vk::ImageType::_2D,
                vk::ImageTiling::OPTIMAL,
                vk::ImageUsageFlags::SAMPLED | vk::ImageUsageFlags::TRANSFER_DST,
                vk::ImageCreateFlags::empty(),
            )
        };
        match format_properties {
            Ok(_) => {}
            Err(error) if error == vk::ErrorCode::FORMAT_NOT_SUPPORTED => {
                return Err(TestError::NotSupported("Format not supported for sampling".to_string()));
            }
            Err(error) => {
                return Err(TestError::Fail(format!(
                    "vkGetPhysicalDeviceImageFormatProperties returned {error:?}"
                )));
            }
        }

        if params.use_compute {
            let storage_format = get_color_attachment_format(params.texture_format, params.use_stencil_aspect);
            let storage_format_props =
                unsafe { instance.get_physical_device_format_properties(physical_device, storage_format) };
            if !storage_format_props
                .optimal_tiling_features
                .contains(vk::FormatFeatureFlags::STORAGE_IMAGE)
            {
                return Err(TestError::NotSupported(
                    "Output format does not support storage image usage".to_string(),
                ));
            }
            if context.get_compute_queue().is_none() {
                return Err(TestError::NotSupported("No compute-only queue".to_string()));
            }
        }

        let mut border_color_features = vk::PhysicalDeviceCustomBorderColorFeaturesEXT::default();
        let mut border_swizzle_features = vk::PhysicalDeviceBorderColorSwizzleFeaturesEXT::default();
        {
            let mut features2 = vk::PhysicalDeviceFeatures2::builder()
                .push_next(&mut border_color_features)
                .push_next(&mut border_swizzle_features);
            unsafe { instance.get_physical_device_features2(physical_device, &mut features2) };
        }
        let identity = params.is_identity();

        if params.use_sampler_swizzle_hint {
            context.require_device_functionality("VK_EXT_border_color_swizzle")?;
        }

        // VK_COMPONENT_SWIZZLE_ONE is undefined with combined depth stencil formats, unless maintenance5's depthStencilSwizzleOneSupport is
        // supported. For depth/stencil formats, VK_COMPONENT_SWIZZLE_A is aliased to VK_COMPONENT_SWIZZLE_ONE within this test group.
        let tcu_format = map_vk_format(params.texture_format)
            .ok_or_else(|| TestError::NotPorted("texture format without a texture format".to_string()))?;
        if is_combined_depth_stencil_type(tcu_format.type_)
            && params
                .component_mapping
                .iter()
                .any(|&swizzle| swizzle == vk::ComponentSwizzle::ONE || swizzle == vk::ComponentSwizzle::A)
        {
            context.require_device_functionality("VK_KHR_maintenance5")?;
            let mut maintenance5_properties = vk::PhysicalDeviceMaintenance5Properties::default();
            {
                let mut properties2 = vk::PhysicalDeviceProperties2::builder().push_next(&mut maintenance5_properties);
                unsafe { instance.get_physical_device_properties2(physical_device, &mut properties2) };
            }
            if maintenance5_properties.depth_stencil_swizzle_one_support == vk::FALSE {
                return Err(TestError::NotSupported(
                    "Swizzle results are undefined without depthStencilSwizzleOneSupport".to_string(),
                ));
            }
        }

        if !params.use_compute {
            check_pipeline_construction_requirements(context, params.construction)?;
        }

        if params.is_custom() {
            if border_color_features.custom_border_colors == vk::FALSE {
                return Err(TestError::NotSupported(
                    "Custom border colors not supported".to_string(),
                ));
            }

            if matches!(
                params.texture_format,
                vk::Format::R4G4B4A4_UNORM_PACK16 | vk::Format::B4G4R4A4_UNORM_PACK16
            ) && border_color_features.custom_border_color_without_format == vk::FALSE
            {
                return Err(TestError::NotSupported(
                    "customBorderColorWithoutFormat feature is not supported".to_string(),
                ));
            }

            if !identity {
                if border_swizzle_features.border_color_swizzle == vk::FALSE {
                    return Err(TestError::NotSupported(
                        "Custom border color with non-identity swizzle not supported".to_string(),
                    ));
                }
                if !params.use_sampler_swizzle_hint
                    && border_swizzle_features.border_color_swizzle_from_image == vk::FALSE
                {
                    return Err(TestError::NotSupported("Custom border color with non-identity swizzle not supported without specifying sampler border mapping".to_string()));
                }
            }
        } else if params.is_opaque_black() {
            if matches!(
                params.texture_format,
                vk::Format::B4G4R4A4_UNORM_PACK16 | vk::Format::R4G4B4A4_UNORM_PACK16
            ) {
                let mut maintenance10_properties = vk::PhysicalDeviceMaintenance10PropertiesKHR::default();
                {
                    let mut properties2 =
                        vk::PhysicalDeviceProperties2::builder().push_next(&mut maintenance10_properties);
                    unsafe { instance.get_physical_device_properties2(physical_device, &mut properties2) };
                }
                if maintenance10_properties.rgba4_opaque_black_swizzled == vk::FALSE
                    && (params.disable_custom_border_color_features
                        || border_color_features.custom_border_colors == vk::FALSE)
                {
                    return Err(TestError::NotSupported(
                        "VK_FORMAT_B4G4R4A4_UNORM_PACK16 needs rgba4OpaqueBlackSwizzled set to false".to_string(),
                    ));
                }
            }

            if !identity {
                if border_swizzle_features.border_color_swizzle == vk::FALSE {
                    return Err(TestError::NotSupported(
                        "Opaque black with non-identity swizzle not supported".to_string(),
                    ));
                }
                if !params.use_sampler_swizzle_hint
                    && border_swizzle_features.border_color_swizzle_from_image == vk::FALSE
                {
                    return Err(TestError::NotSupported("Opaque black with non-identity swizzle not supported without specifying sampler border mapping".to_string()));
                }
            }
        }
        Ok(())
    }

    fn programs(&self) -> BinaryCollection {
        let key = border_swizzle_key(&self.params);
        ALL_SHARED_PROGRAM
            .iter()
            .find(|program| program.name == key)
            .map(|program| program.programs)
            .unwrap_or_else(|| BinaryCollection::new(&[]))
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(BorderSwizzleInstance {
            context,
            params: self.params,
        })
    }
}

