type Swizzles = [vk::ComponentSwizzle; 4];

const IMAGE_SIZE: u32 = 16;

/// Returns true if the mapping doesn't alter each component.
fn is_identity_swizzle(mapping: &Swizzles) -> bool {
    let identity = [
        vk::ComponentSwizzle::R,
        vk::ComponentSwizzle::G,
        vk::ComponentSwizzle::B,
        vk::ComponentSwizzle::A,
    ];
    mapping
        .iter()
        .zip(identity)
        .all(|(&swizzle, own)| swizzle == own || swizzle == vk::ComponentSwizzle::IDENTITY)
}

fn is_opaque_black_border(border_color: vk::BorderColor) -> bool {
    border_color == vk::BorderColor::INT_OPAQUE_BLACK || border_color == vk::BorderColor::FLOAT_OPAQUE_BLACK
}

fn is_custom_border(border_color: vk::BorderColor) -> bool {
    border_color == vk::BorderColor::INT_CUSTOM_EXT || border_color == vk::BorderColor::FLOAT_CUSTOM_EXT
}

