impl TestInstance for BorderSwizzleInstance<'_> {
    /// `BorderSwizzleInstance::iterate`
    fn iterate(&mut self) -> TestOutcome {
        let context = self.context;
        let device = context.get_device();
        let alloc = context.get_default_allocator();
        let params = self.params;
        let extent = vk::Extent3D {
            width: IMAGE_SIZE,
            height: IMAGE_SIZE,
            depth: 1,
        };
        let custom = params.is_custom();
        let is_ds_format = is_depth_stencil_format(params.texture_format);
        let has_stencil = params.use_stencil_aspect;
        let image_aspect = if is_ds_format {
            if has_stencil {
                vk::ImageAspectFlags::STENCIL
            } else {
                vk::ImageAspectFlags::DEPTH
            }
        } else {
            vk::ImageAspectFlags::COLOR
        };
        let image_subresource_range = make_image_subresource_range(image_aspect, 0, 1, 0, 1);
        let tcu_texture_format = map_vk_format(params.texture_format)
            .ok_or_else(|| TestError::NotPorted("texture format without a texture format".to_string()))?;
        let barrier_aspect = if tcu_texture_format.order == ChannelOrder::DS {
            vk::ImageAspectFlags::DEPTH | vk::ImageAspectFlags::STENCIL
        } else {
            image_aspect
        };
        let barrier_subresource_range = make_image_subresource_range(barrier_aspect, 0, 1, 0, 1);
        let color_attachment_format = get_color_attachment_format(params.texture_format, has_stencil);
        let color_subresource_range = make_image_subresource_range(vk::ImageAspectFlags::COLOR, 0, 1, 0, 1);

        let (queue, q_index) = if params.use_compute {
            context
                .get_compute_queue()
                .ok_or_else(|| TestError::NotSupported("No compute-only queue".to_string()))?
        } else {
            (
                context.get_universal_queue(),
                context.get_universal_queue_family_index(),
            )
        };

        // Texture.
        let texture_info = vk::ImageCreateInfo::builder()
            .image_type(vk::ImageType::_2D)
            .format(params.texture_format)
            .extent(extent)
            .mip_levels(1)
            .array_layers(1)
            .samples(vk::SampleCountFlags::_1)
            .tiling(vk::ImageTiling::OPTIMAL)
            .usage(vk::ImageUsageFlags::SAMPLED | vk::ImageUsageFlags::TRANSFER_DST)
            .sharing_mode(vk::SharingMode::EXCLUSIVE)
            .initial_layout(vk::ImageLayout::UNDEFINED)
            .build();
        let texture = ImageWithMemory::new(device, alloc, texture_info, MemoryRequirement::ANY)?;

        let texture_view_info = vk::ImageViewCreateInfo::builder()
            .image(texture.get())
            .view_type(vk::ImageViewType::_2D)
            .format(params.texture_format)
            .components(vk::ComponentMapping {
                r: params.component_mapping[0],
                g: params.component_mapping[1],
                b: params.component_mapping[2],
                a: params.component_mapping[3],
            })
            .subresource_range(image_subresource_range);
        let texture_view = Unique::new(
            device,
            unsafe { device.create_image_view(&texture_view_info, None) }.vk_check("vkCreateImageView")?,
        );

        // Output image
        let mut output_usage = vk::ImageUsageFlags::TRANSFER_SRC;
        output_usage |= if params.use_compute {
            vk::ImageUsageFlags::STORAGE
        } else {
            vk::ImageUsageFlags::COLOR_ATTACHMENT
        };
        let output_info = vk::ImageCreateInfo::builder()
            .image_type(vk::ImageType::_2D)
            .format(color_attachment_format)
            .extent(extent)
            .mip_levels(1)
            .array_layers(1)
            .samples(vk::SampleCountFlags::_1)
            .tiling(vk::ImageTiling::OPTIMAL)
            .usage(output_usage)
            .sharing_mode(vk::SharingMode::EXCLUSIVE)
            .initial_layout(vk::ImageLayout::UNDEFINED)
            .build();
        let color_attachment = ImageWithMemory::new(device, alloc, output_info, MemoryRequirement::ANY)?;
        let color_attachment_view = make_image_view(
            device,
            color_attachment.get(),
            vk::ImageViewType::_2D,
            color_attachment_format,
            color_subresource_range,
        )?;

        // Texture sampler.
        let border_color_mapping_info = vk::SamplerBorderColorComponentMappingCreateInfoEXT {
            s_type: vk::StructureType::SAMPLER_BORDER_COLOR_COMPONENT_MAPPING_CREATE_INFO_EXT,
            next: std::ptr::null(),
            components: vk::ComponentMapping {
                r: params.component_mapping[0],
                g: params.component_mapping[1],
                b: params.component_mapping[2],
                a: params.component_mapping[3],
            },
            srgb: u32::from(is_srgb_format(params.texture_format)),
        };
        let mapping_ptr = std::ptr::from_ref(&border_color_mapping_info).cast::<std::ffi::c_void>();
        let custom_border_color_info = vk::SamplerCustomBorderColorCreateInfoEXT {
            s_type: vk::StructureType::SAMPLER_CUSTOM_BORDER_COLOR_CREATE_INFO_EXT,
            next: if params.use_sampler_swizzle_hint {
                mapping_ptr
            } else {
                std::ptr::null()
            },
            custom_border_color: vk::ClearColorValue {
                uint32: params.custom_border_color.unwrap_or([0; 4]),
            },
            format: params.texture_format,
        };
        let next: *const std::ffi::c_void = if custom {
            std::ptr::from_ref(&custom_border_color_info).cast()
        } else if params.use_sampler_swizzle_hint {
            mapping_ptr
        } else {
            std::ptr::null()
        };
        let mut sampler_info = vk::SamplerCreateInfo::builder()
            .mag_filter(vk::Filter::NEAREST)
            .min_filter(vk::Filter::NEAREST)
            .mipmap_mode(vk::SamplerMipmapMode::NEAREST)
            .address_mode_u(vk::SamplerAddressMode::CLAMP_TO_BORDER)
            .address_mode_v(vk::SamplerAddressMode::CLAMP_TO_BORDER)
            .address_mode_w(vk::SamplerAddressMode::CLAMP_TO_BORDER)
            .mip_lod_bias(0.0)
            .anisotropy_enable(false)
            .max_anisotropy(0.0)
            .compare_enable(false)
            .compare_op(vk::CompareOp::NEVER)
            .min_lod(0.0)
            .max_lod(1.0)
            .border_color(params.border_color)
            .unnormalized_coordinates(false)
            .build();
        sampler_info.next = next;
        let sampler = Unique::new(
            device,
            unsafe { device.create_sampler(&sampler_info, None) }.vk_check("vkCreateSampler")?,
        );

        // Descriptor set layout, pipeline layout, pool and set.
        let sampled_stage = if params.use_compute {
            vk::ShaderStageFlags::COMPUTE
        } else {
            vk::ShaderStageFlags::FRAGMENT
        };
        let mut layout_builder = DescriptorSetLayoutBuilder::new()
            .add_single_binding(vk::DescriptorType::COMBINED_IMAGE_SAMPLER, sampled_stage);
        if params.use_compute {
            layout_builder =
                layout_builder.add_single_binding(vk::DescriptorType::STORAGE_IMAGE, vk::ShaderStageFlags::COMPUTE);
        }
        let ds_layout = layout_builder.build(device)?;
        let pipeline_layout = make_pipeline_layout(device, &[*ds_layout])?;

        let mut pool_builder = DescriptorPoolBuilder::new().add_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER, 1);
        if params.use_compute {
            pool_builder = pool_builder.add_type(vk::DescriptorType::STORAGE_IMAGE, 1);
        }
        let descriptor_pool = pool_builder.build(device, vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET, 1)?;
        let descriptor_set = make_descriptor_set(device, *descriptor_pool, *ds_layout)?;

        {
            let sampler_infos = [vk::DescriptorImageInfo {
                sampler: *sampler,
                image_view: *texture_view,
                image_layout: vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL,
            }];
            let storage_infos = [vk::DescriptorImageInfo {
                sampler: vk::Sampler::null(),
                image_view: *color_attachment_view,
                image_layout: vk::ImageLayout::GENERAL,
            }];
            let mut writes = vec![
                vk::WriteDescriptorSet::builder()
                    .dst_set(descriptor_set.get())
                    .dst_binding(0)
                    .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
                    .image_info(&sampler_infos)
                    .build(),
            ];
            if params.use_compute {
                writes.push(
                    vk::WriteDescriptorSet::builder()
                        .dst_set(descriptor_set.get())
                        .dst_binding(1)
                        .descriptor_type(vk::DescriptorType::STORAGE_IMAGE)
                        .image_info(&storage_infos)
                        .build(),
                );
            }
            unsafe { device.update_descriptor_sets(&writes, &[] as &[vk::CopyDescriptorSet]) };
        }

        // Spec constants
        let mut spec_data = Vec::new();
        spec_data.extend_from_slice(&params.texture_coordinates[0].to_ne_bytes());
        spec_data.extend_from_slice(&params.texture_coordinates[1].to_ne_bytes());
        spec_data.extend_from_slice(&i32::from(params.component_gather.is_some()).to_ne_bytes());
        let specialization_map = vec![
            vk::SpecializationMapEntry {
                constant_id: 0,
                offset: 0,
                size: 4,
            },
            vk::SpecializationMapEntry {
                constant_id: 1,
                offset: 4,
                size: 4,
            },
            vk::SpecializationMapEntry {
                constant_id: 2,
                offset: 8,
                size: 4,
            },
        ];

        // Pipelines
        let binaries = context.get_binary_collection();
        let render_pass = if params.use_compute {
            None
        } else {
            Some(make_color_render_pass(
                device,
                color_attachment_format,
                vk::AttachmentLoadOp::CLEAR,
                vk::AttachmentStoreOp::STORE,
                vk::ImageLayout::UNDEFINED,
                vk::ImageLayout::COLOR_ATTACHMENT_OPTIMAL,
                vk::ImageLayout::COLOR_ATTACHMENT_OPTIMAL,
            )?)
        };
        let framebuffer = match &render_pass {
            Some(render_pass) => Some(make_framebuffer(
                device,
                **render_pass,
                &[*color_attachment_view],
                IMAGE_SIZE,
                IMAGE_SIZE,
                1,
            )?),
            None => None,
        };
        let compute_module = if params.use_compute {
            Some(create_shader_module(device, binaries.get("comp")?)?)
        } else {
            None
        };
        let vert_module = if params.use_compute {
            None
        } else {
            Some(create_shader_module(device, binaries.get("vert")?)?)
        };
        let frag_module = if params.use_compute {
            None
        } else {
            Some(create_shader_module(device, binaries.get("frag")?)?)
        };

        let pipeline = if let Some(compute_module) = &compute_module {
            let specialization_info = vk::SpecializationInfo::builder()
                .map_entries(&specialization_map)
                .data(&spec_data);
            let stage = vk::PipelineShaderStageCreateInfo::builder()
                .stage(vk::ShaderStageFlags::COMPUTE)
                .module(**compute_module)
                .name(b"main\0")
                .specialization_info(&specialization_info);
            let info = vk::ComputePipelineCreateInfo::builder()
                .stage(stage)
                .layout(*pipeline_layout);
            let pipelines = unsafe { device.create_compute_pipelines(vk::PipelineCache::null(), &[info], None) }
                .vk_check("vkCreateComputePipelines")?;
            Unique::new(device, pipelines.0[0])
        } else {
            let mut state = DrawPipelineState::new(vk::PrimitiveTopology::TRIANGLE_STRIP)
                .with_full_viewport(IMAGE_SIZE, IMAGE_SIZE);
            state.specialization = Some((specialization_map.clone(), spec_data.clone()));
            state.construction = params.construction;
            let stages = [
                (
                    vk::ShaderStageFlags::VERTEX,
                    **vert_module.as_ref().expect("graphics case"),
                ),
                (
                    vk::ShaderStageFlags::FRAGMENT,
                    **frag_module.as_ref().expect("graphics case"),
                ),
            ];
            create_draw_pipeline(
                device,
                *pipeline_layout,
                **render_pass.as_ref().expect("graphics case"),
                &stages,
                &state,
            )?
        };

        // Output of the verification: the color attachment copied to a host buffer.
        let buffer_size = (IMAGE_SIZE * IMAGE_SIZE * 16) as vk::DeviceSize;
        let result_buffer = BufferWithMemory::new(
            device,
            alloc,
            make_buffer_create_info(buffer_size, vk::BufferUsageFlags::TRANSFER_DST),
            MemoryRequirement::HOST_VISIBLE,
        )?;

        // Command pool and buffer.
        let cmd_pool = make_command_pool(device, q_index)?;
        let cmd_buffer = allocate_command_buffer(device, *cmd_pool, vk::CommandBufferLevel::PRIMARY)?;
        let cmd = *cmd_buffer;

        // Texture barriers to fill it before using it.
        let pre_clear_barrier = make_image_memory_barrier(
            vk::AccessFlags::empty(),
            vk::AccessFlags::TRANSFER_WRITE,
            vk::ImageLayout::UNDEFINED,
            vk::ImageLayout::TRANSFER_DST_OPTIMAL,
            texture.get(),
            barrier_subresource_range,
        );
        let post_clear_barrier = make_image_memory_barrier(
            vk::AccessFlags::TRANSFER_WRITE,
            vk::AccessFlags::SHADER_READ,
            vk::ImageLayout::TRANSFER_DST_OPTIMAL,
            vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL,
            texture.get(),
            barrier_subresource_range,
        );

        begin_command_buffer(device, cmd)?;

        // Prepare texture.
        unsafe {
            device.cmd_pipeline_barrier(
                cmd,
                vk::PipelineStageFlags::TOP_OF_PIPE,
                vk::PipelineStageFlags::TRANSFER,
                vk::DependencyFlags::empty(),
                &[] as &[vk::MemoryBarrier],
                &[] as &[vk::BufferMemoryBarrier],
                &[pre_clear_barrier],
            );
            if is_ds_format {
                let clear_value = vk::ClearDepthStencilValue { depth: 0.0, stencil: 0 };
                device.cmd_clear_depth_stencil_image(
                    cmd,
                    texture.get(),
                    vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                    &clear_value,
                    &[image_subresource_range],
                );
            } else {
                let clear_value = vk::ClearColorValue {
                    uint32: params.texture_clear_color,
                };
                device.cmd_clear_color_image(
                    cmd,
                    texture.get(),
                    vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                    &clear_value,
                    &[image_subresource_range],
                );
            }
        }

        let attachment_layout = if params.use_compute {
            let barriers = [
                post_clear_barrier,
                make_image_memory_barrier(
                    vk::AccessFlags::empty(),
                    vk::AccessFlags::SHADER_WRITE,
                    vk::ImageLayout::UNDEFINED,
                    vk::ImageLayout::GENERAL,
                    color_attachment.get(),
                    color_subresource_range,
                ),
            ];
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::COMPUTE_SHADER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &barriers,
                );

                // Dispatch Compute. The workgroup size is 16x16x1 and the image 16x16, so one workgroup is enough.
                device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::COMPUTE, *pipeline);
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::COMPUTE,
                    *pipeline_layout,
                    0,
                    &[descriptor_set.get()],
                    &[] as &[u32],
                );
                device.cmd_dispatch(cmd, 1, 1, 1);
            }
            vk::ImageLayout::GENERAL
        } else {
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::FRAGMENT_SHADER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[post_clear_barrier],
                );

                // Read from the texture to render a full-screen quad to the color buffer.
                let clear_values = [clear_value_color([0.0; 4])];
                let begin_info = vk::RenderPassBeginInfo::builder()
                    .render_pass(**render_pass.as_ref().expect("graphics case"))
                    .framebuffer(**framebuffer.as_ref().expect("graphics case"))
                    .render_area(rect_2d(IMAGE_SIZE, IMAGE_SIZE))
                    .clear_values(&clear_values);
                device.cmd_begin_render_pass(cmd, &begin_info, vk::SubpassContents::INLINE);
                device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::GRAPHICS, pipeline.get());
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::GRAPHICS,
                    *pipeline_layout,
                    0,
                    &[descriptor_set.get()],
                    &[] as &[u32],
                );
                device.cmd_draw(cmd, 4, 1, 0, 0);
                device.cmd_end_render_pass(cmd);
            }
            vk::ImageLayout::COLOR_ATTACHMENT_OPTIMAL
        };

        // Copy the color attachment to the host buffer.
        {
            let attachment_access = if params.use_compute {
                vk::AccessFlags::SHADER_WRITE
            } else {
                vk::AccessFlags::COLOR_ATTACHMENT_WRITE
            };
            let src_stage = if params.use_compute {
                vk::PipelineStageFlags::COMPUTE_SHADER
            } else {
                vk::PipelineStageFlags::COLOR_ATTACHMENT_OUTPUT
            };
            let barrier = make_image_memory_barrier(
                attachment_access,
                vk::AccessFlags::TRANSFER_READ,
                attachment_layout,
                vk::ImageLayout::TRANSFER_SRC_OPTIMAL,
                color_attachment.get(),
                color_subresource_range,
            );
            let region = vk::BufferImageCopy {
                buffer_offset: 0,
                buffer_row_length: 0,
                buffer_image_height: 0,
                image_subresource: vk::ImageSubresourceLayers {
                    aspect_mask: vk::ImageAspectFlags::COLOR,
                    mip_level: 0,
                    base_array_layer: 0,
                    layer_count: 1,
                },
                image_offset: vk::Offset3D { x: 0, y: 0, z: 0 },
                image_extent: extent,
            };
            let buffer_barrier = vk::BufferMemoryBarrier::builder()
                .src_access_mask(vk::AccessFlags::TRANSFER_WRITE)
                .dst_access_mask(vk::AccessFlags::HOST_READ)
                .src_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
                .dst_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
                .buffer(result_buffer.get())
                .offset(0)
                .size(vk::WHOLE_SIZE)
                .build();
            unsafe {
                device.cmd_pipeline_barrier(
                    cmd,
                    src_stage,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[] as &[vk::BufferMemoryBarrier],
                    &[barrier],
                );
                device.cmd_copy_image_to_buffer(
                    cmd,
                    color_attachment.get(),
                    vk::ImageLayout::TRANSFER_SRC_OPTIMAL,
                    result_buffer.get(),
                    &[region],
                );
                device.cmd_pipeline_barrier(
                    cmd,
                    vk::PipelineStageFlags::TRANSFER,
                    vk::PipelineStageFlags::HOST,
                    vk::DependencyFlags::empty(),
                    &[] as &[vk::MemoryBarrier],
                    &[buffer_barrier],
                    &[] as &[vk::ImageMemoryBarrier],
                );
            }
        }
        end_command_buffer(device, cmd)?;
        submit_commands_and_wait(device, queue, cmd)?;

        // Verify the color buffer.
        invalidate_alloc(device, result_buffer.get_allocation())?;
        let raw =
            unsafe { std::slice::from_raw_parts(result_buffer.get_allocation().get_host_ptr(), buffer_size as usize) };
        let pixels: Vec<ColorBits> = raw
            .chunks_exact(16)
            .map(|pixel| {
                [0, 1, 2, 3].map(|channel| {
                    u32::from_ne_bytes([
                        pixel[channel * 4],
                        pixel[channel * 4 + 1],
                        pixel[channel * 4 + 2],
                        pixel[channel * 4 + 3],
                    ])
                })
            })
            .collect();
        let border_color = get_border_clear_color_value(&params);
        let expected_color = get_expected_color(border_color, &params);

        match compare_pixels_to_color(&params, &pixels, tcu_texture_format, expected_color) {
            Ok(()) => Ok(TestStatus::pass("Pass")),
            Err(message) => {
                // Per the Vulkan spec, implementations may return undefined values instead of the specified custom border color when it is
                // used on a compute-only queue, so a mismatch there is a quality issue rather than a failure.
                if params.is_custom() && params.use_compute {
                    return Ok(TestStatus::new(
                        TestResult::QualityWarning,
                        format!(
                            "Implementation returned an undefined value for the custom border color on a compute-only queue: {message}"
                        ),
                    ));
                }
                Ok(TestStatus::fail(message))
            }
        }
    }
}

fn swizzle_array_to_string(swizzles: &Swizzles) -> String {
    swizzles
        .iter()
        .map(|&swizzle| match swizzle {
            vk::ComponentSwizzle::IDENTITY => 'i',
            vk::ComponentSwizzle::ZERO => '0',
            vk::ComponentSwizzle::ONE => '1',
            vk::ComponentSwizzle::R => 'r',
            vk::ComponentSwizzle::G => 'g',
            vk::ComponentSwizzle::B => 'b',
            _ => 'a',
        })
        .collect()
}

/// `genMappingPermutations`: using every permutation of component swizzle values would be 7^4 = 2401 combinations, too many.
fn gen_mapping_permutations() -> Vec<Swizzles> {
    let standard: Swizzles = [
        vk::ComponentSwizzle::R,
        vk::ComponentSwizzle::G,
        vk::ComponentSwizzle::B,
        vk::ComponentSwizzle::A,
    ];
    let mut result = vec![standard];

    // A few combinations with rotated swizzles.
    for rotations in 1..standard.len() {
        let mut rotated = standard;
        rotated.rotate_left(rotations);
        result.push(rotated);
    }

    // Each special value in each of the positions.
    for special in [
        vk::ComponentSwizzle::IDENTITY,
        vk::ComponentSwizzle::ONE,
        vk::ComponentSwizzle::ZERO,
    ] {
        for pos in 0..standard.len() {
            let mut array = standard;
            array[pos] = special;
            result.push(array);
        }
    }
    result
}

