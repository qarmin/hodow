fn get_random_border_coordinates(rnd: &mut Random) -> [f32; 2] {
    let mut coords = [0.0f32; 2];

    // Two bits to decide which coordinates will be out of range (at least one).
    let out_of_range_mask = rnd.get_int(1, 3) as u32;

    for (i, coord) in coords.iter_mut().enumerate() {
        // Each coord will be in the [0.0, 0.9] range if in range, [1.1, 5.0] or [-5.0, -1.1] if out of range.
        let out_of_range = out_of_range_mask & (1 << i) != 0;
        let negative = out_of_range && rnd.get_bool();
        let min_coord = if out_of_range { 1.1f32 } else { 0.0 };
        let max_coord = if out_of_range { 5.0f32 } else { 0.9 };
        let value = (if negative { -1.0f32 } else { 1.0 }) * rnd.get_float_range(min_coord, max_coord);
        *coord = value;
    }
    coords
}

/// `getRandomClearColor`: a random clear color usable for the given format. All 4 components are generated, even when the format does not use
/// them, which provides a little more coverage (and is what gives A8_UNORM its border alpha).
fn get_random_clear_color(format: vk::Format, rnd: &mut Random, use_stencil: bool) -> ColorBits {
    let tcu_format = map_vk_format(format).expect("the format of a case has a texture format");
    let format_type = get_format_type(format, use_stencil);
    let mut color = [0u32; 4];

    for component in color.iter_mut() {
        if matches!(format_type, FormatType::SignedInt | FormatType::UnsignedInt) {
            let component_size = if use_stencil {
                1
            } else {
                u64::from(
                    tcu_format
                        .type_
                        .channel_size()
                        .expect("an integer format has a channel size"),
                )
            };
            let mask = if component_size >= 8 {
                u64::MAX
            } else {
                (1u64 << (component_size * 8)) - 1
            };
            let sign_bit = 1u64 << (component_size * 8 - 1);
            let sign_mask = !mask;
            let value = rnd.get_uint64();

            if format_type == FormatType::SignedInt {
                // Extend sign bit for negative values.
                let mut final_value = value & mask;
                if final_value & sign_bit != 0 {
                    final_value |= sign_mask;
                }
                *component = final_value as u32;
            } else {
                *component = (value & mask) as u32;
            }
        } else {
            *component = rnd.get_float().to_bits();
        }
    }
    color
}

