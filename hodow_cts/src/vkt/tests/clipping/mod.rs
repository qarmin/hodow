/// `ClipVolume::checkTopologySupport`
fn check_topology_support(context: &Context<'_>, topology: vk::PrimitiveTopology) -> Result<(), TestError> {
    if topology == vk::PrimitiveTopology::TRIANGLE_FAN
        && context.is_device_functionality_supported("VK_KHR_portability_subset")
    {
        let mut portability = vk::PhysicalDevicePortabilitySubsetFeaturesKHR::default();
        let mut features2 = vk::PhysicalDeviceFeatures2::builder().push_next(&mut portability);
        unsafe {
            context
                .get_instance()
                .get_physical_device_features2(context.get_physical_device(), &mut features2)
        };
        if portability.triangle_fans == vk::FALSE {
            return Err(TestError::NotSupported(
                "VK_KHR_portability_subset: Triangle fans are not supported by this implementation".to_string(),
            ));
        }
    }
    Ok(())
}

fn topology_of(param: Param) -> vk::PrimitiveTopology {
    match param {
        Param::Topology(topology) => topology,
        _ => unreachable!("the case was registered with a topology"),
    }
}

fn has_adjacency(topology: vk::PrimitiveTopology) -> bool {
    matches!(
        topology,
        vk::PrimitiveTopology::LINE_LIST_WITH_ADJACENCY
            | vk::PrimitiveTopology::LINE_STRIP_WITH_ADJACENCY
            | vk::PrimitiveTopology::TRIANGLE_LIST_WITH_ADJACENCY
            | vk::PrimitiveTopology::TRIANGLE_STRIP_WITH_ADJACENCY
    )
}

