/// `ClipDistance::testClipDistance`
fn test_clip_distance<'a>(context: &'a Context<'a>, param: Param) -> TestOutcome {
    let case_def = distance_case_of(param);

    // Check limits for supported features
    {
        let limits = context.get_device_properties().limits;

        if case_def.num_clip_distances > 0 && limits.max_clip_distances < MAX_CLIP_DISTANCES as u32 {
            return Ok(TestStatus::fail(
                "maxClipDistances smaller than the minimum required by the spec",
            ));
        }
        if case_def.num_cull_distances > 0 && limits.max_cull_distances < MAX_CULL_DISTANCES as u32 {
            return Ok(TestStatus::fail(
                "maxCullDistances smaller than the minimum required by the spec",
            ));
        }
        if case_def.num_cull_distances > 0
            && limits.max_combined_clip_and_cull_distances < MAX_COMBINED_CLIP_AND_CULL_DISTANCES as u32
        {
            return Ok(TestStatus::fail(
                "maxCombinedClipAndCullDistances smaller than the minimum required by the spec",
            ));
        }
    }

    let binaries = context.get_binary_collection();
    let mut shaders = get_shader_vector(&binaries)?;
    if case_def.enable_tessellation {
        shaders.push(VulkanShader {
            stage: vk::ShaderStageFlags::TESSELLATION_CONTROL,
            binary: binaries.get("tesc")?,
        });
        shaders.push(VulkanShader {
            stage: vk::ShaderStageFlags::TESSELLATION_EVALUATION,
            binary: binaries.get("tese")?,
        });
    }
    if case_def.enable_geometry {
        shaders.push(VulkanShader {
            stage: vk::ShaderStageFlags::GEOMETRY,
            binary: binaries.get("geom")?,
        });
    }

    let num_bars = MAX_COMBINED_CLIP_AND_CULL_DISTANCES;

    let mut vertices = Vec::new();
    {
        let dx = 2.0 / num_bars as f32;
        for i in 0..num_bars {
            let x = -1.0 + dx * i as f32;

            vertices.push(Vec4::new(x, -1.0, 0.0, 1.0));
            vertices.push(Vec4::new(x, 1.0, 0.0, 1.0));
            vertices.push(Vec4::new(x + dx, -1.0, 0.0, 1.0));

            vertices.push(Vec4::new(x, 1.0, 0.0, 1.0));
            vertices.push(Vec4::new(x + dx, 1.0, 0.0, 1.0));
            vertices.push(Vec4::new(x + dx, -1.0, 0.0, 1.0));
        }
    }

    // Drawing colored bars, clipping the first numClipDistances; expecting the upper half of the clipped bars to be black.
    let framebuffer_state = FrameBufferState::new(RENDER_SIZE as u32, RENDER_SIZE as u32);
    let mut pipeline_state = PipelineState::new(subpixel_bits(context));
    if case_def.enable_tessellation {
        pipeline_state.num_patch_control_points = NUM_PATCH_CONTROL_POINTS;
    }
    let pixels = draw_and_read(
        context,
        &framebuffer_state,
        &pipeline_state,
        &shaders,
        case_def.topology,
        &vertices,
    )?;

    // Count black pixels in the whole image.
    let num_black_pixels = count_pixels(&pixels, BLACK, Vec4::splat(0.0));
    let clip_region = (case_def.num_clip_distances * RENDER_SIZE / num_bars, RENDER_SIZE / 2);
    // Cull is set to > 0.75 in the shader if caseDef.readInFragmentShader is false
    let bars_culled = (0.25f32 / (1.0 / num_bars as f32)).floor() as i32;
    let cull_region = if case_def.read_in_fragment_shader || case_def.num_cull_distances == 0 {
        (0, 0)
    } else {
        (bars_culled, RENDER_SIZE)
    };
    let expected_clipped_pixels = clip_region.0 * clip_region.1 + cull_region.0 * cull_region.1;
    // Make sure the bottom half has no black pixels (possible if image became corrupted).
    let guard_pixels = count_pixels_in_region(&pixels, (0, RENDER_SIZE / 2), clip_region, BLACK, Vec4::splat(0.0));
    let frag_colors_ok = if case_def.read_in_fragment_shader {
        check_frag_colors(
            &pixels,
            clip_region,
            case_def.num_clip_distances / 2,
            case_def.num_cull_distances > 0,
        )
    } else {
        true
    };

    Ok(
        if num_black_pixels == expected_clipped_pixels && guard_pixels == 0 && frag_colors_ok {
            TestStatus::pass("OK")
        } else {
            TestStatus::fail("Rendered image(s) are incorrect")
        },
    )
}

