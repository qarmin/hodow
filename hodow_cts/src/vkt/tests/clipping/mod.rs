/// `ClipVolume::testPrimitivesInside`: primitives fully inside the clip volume.
fn test_primitives_inside<'a>(context: &'a Context<'a>, param: Param) -> TestOutcome {
    let topology = topology_of(param);
    let min_expected_black_pixels = match topology {
        // We draw only 5 points.
        vk::PrimitiveTopology::POINT_LIST => NUM_RENDER_PIXELS - 5,
        // Allow for some error.
        vk::PrimitiveTopology::LINE_LIST_WITH_ADJACENCY
        | vk::PrimitiveTopology::LINE_STRIP_WITH_ADJACENCY
        | vk::PrimitiveTopology::LINE_LIST
        | vk::PrimitiveTopology::LINE_STRIP => NUM_RENDER_PIXELS - 3 * RENDER_SIZE,
        // All render area should be covered.
        _ => 0,
    };

    let shaders = get_shader_vector(&context.get_binary_collection())?;
    let mut num_passed = 0;

    // Draw primitives at near clipping plane, z = 0.0; at z = 0.5; at far clipping plane, z = 1.0
    let z_positions = [0.0f32, 0.5, 1.0];
    for z_pos in z_positions {
        let vertices = gen_vertices(topology, Vec4::new(0.0, 0.0, z_pos, 0.0), 0.0);
        let framebuffer_state = FrameBufferState::new(RENDER_SIZE as u32, RENDER_SIZE as u32);
        let pipeline_state = PipelineState::new(subpixel_bits(context));

        let pixels = draw_and_read(
            context,
            &framebuffer_state,
            &pipeline_state,
            &shaders,
            topology,
            &vertices,
        )?;

        let num_black_pixels = count_pixels(&pixels, BLACK, Vec4::splat(0.0));
        if num_black_pixels >= min_expected_black_pixels {
            num_passed += 1;
        }
    }

    Ok(if num_passed == z_positions.len() {
        TestStatus::pass("OK")
    } else {
        TestStatus::fail("Rendered image(s) are incorrect")
    })
}

/// `ClipVolume::testPrimitivesOutside`: primitives fully outside the clip volume.
fn test_primitives_outside<'a>(context: &'a Context<'a>, param: Param) -> TestOutcome {
    let topology = topology_of(param);
    let shaders = get_shader_vector(&context.get_binary_collection())?;
    let mut num_passed = 0;

    // Drawing primitives outside the clip volume. Expecting an empty image: in front of the near clipping plane, z < 0.0,
    // and behind the far clipping plane, z > 1.0
    let z_positions = [-0.5f32, 1.5];
    for z_pos in z_positions {
        let vertices = gen_vertices(topology, Vec4::new(0.0, 0.0, z_pos, 0.0), 0.0);
        let framebuffer_state = FrameBufferState::new(RENDER_SIZE as u32, RENDER_SIZE as u32);
        let pipeline_state = PipelineState::new(subpixel_bits(context));

        let pixels = draw_and_read(
            context,
            &framebuffer_state,
            &pipeline_state,
            &shaders,
            topology,
            &vertices,
        )?;

        // All pixels must be black -- nothing is drawn.
        if count_pixels(&pixels, BLACK, Vec4::splat(0.0)) == NUM_RENDER_PIXELS {
            num_passed += 1;
        }
    }

    Ok(if num_passed == z_positions.len() {
        TestStatus::pass("OK")
    } else {
        TestStatus::fail("Rendered image(s) are incorrect")
    })
}

