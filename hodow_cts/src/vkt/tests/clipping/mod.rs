/// `ClipVolume::testWideLines`: wide line clipping.
fn test_wide_lines<'a>(context: &'a Context<'a>, param: Param) -> TestOutcome {
    let line_orientation = match param {
        Param::Orientation(orientation) => orientation,
        _ => unreachable!("the case was registered with an orientation"),
    };
    let shaders = get_shader_vector(&context.get_binary_collection())?;
    let delta = 0.1f32; // much smaller than the line width

    let vertices: Vec<Vec4> = if line_orientation == LineOrientation::AxisAligned {
        // Axis-aligned lines just outside the clip volume.
        let p = 1.0 + delta;
        let q = 0.9;

        vec![
            Vec4::new(-p, -q, 0.1, 1.0),
            Vec4::new(-p, q, 0.9, 1.0), // line 0
            Vec4::new(-q, p, 0.1, 1.0),
            Vec4::new(q, p, 0.9, 1.0), // line 1
            Vec4::new(p, q, 0.1, 1.0),
            Vec4::new(p, -q, 0.9, 1.0), // line 2
            Vec4::new(q, -p, 0.1, 1.0),
            Vec4::new(-q, -p, 0.9, 1.0), // line 3
        ]
    } else {
        // Diagonal lines just outside the clip volume.
        let p = 2.0 + delta;

        vec![
            Vec4::new(-p, 0.0, 0.1, 1.0),
            Vec4::new(0.0, -p, 0.9, 1.0), // line 0
            Vec4::new(0.0, -p, 0.1, 1.0),
            Vec4::new(p, 0.0, 0.9, 1.0), // line 1
            Vec4::new(p, 0.0, 0.1, 1.0),
            Vec4::new(0.0, p, 0.9, 1.0), // line 2
            Vec4::new(0.0, p, 0.1, 1.0),
            Vec4::new(-p, 0.0, 0.9, 1.0), // line 3
        ]
    };

    let limits = context.get_device_properties().limits;

    let line_width = (RENDER_SIZE as f32).min(limits.line_width_range[1]);
    let strict_lines = limits.strict_lines != vk::FALSE;

    let framebuffer_state = FrameBufferState::new(RENDER_SIZE as u32, RENDER_SIZE as u32);
    let pipeline_state = PipelineState::new(subpixel_bits(context));
    let pixels = draw_and_read(
        context,
        &framebuffer_state,
        &pipeline_state,
        &shaders,
        vk::PrimitiveTopology::LINE_LIST,
        &vertices,
    )?;

    // Popful case: All pixels must be black -- nothing is drawn.
    if count_pixels(&pixels, BLACK, Vec4::splat(0.0)) == NUM_RENDER_PIXELS {
        return Ok(TestStatus::pass("OK"));
    }

    // Pop-free case: All lines must be rendered.
    let half_width = line_width / RENDER_SIZE as f32;
    let mut ref_vertices: Vec<Vec4> = Vec::new();

    // Create reference primitives
    for line_ndx in 0..vertices.len() / 2 {
        let vertex_ndx0 = 2 * line_ndx;
        let vertex_ndx1 = 2 * line_ndx + 1;

        let delta_x = vertices[vertex_ndx1].x() - vertices[vertex_ndx0].x();
        let delta_y = vertices[vertex_ndx1].y() - vertices[vertex_ndx0].y();
        let x_major_axis = delta_x.abs() >= delta_y.abs();
        let length = Vec2::new(delta_x, delta_y);
        let magnitude = (length.x() * length.x() + length.y() * length.y()).sqrt();
        let line_dir = Vec2::new(delta_x / magnitude, delta_y / magnitude);
        let line_normal_dir = if strict_lines {
            // Line caps are perpendicular to the direction of the line segment.
            Vec4::new(line_dir.y(), -line_dir.x(), 0.0, 0.0)
        } else if x_major_axis {
            Vec4::new(0.0, 1.0, 0.0, 0.0)
        } else {
            // Line caps are aligned to the minor axis
            Vec4::new(1.0, 0.0, 0.0, 0.0)
        };

        let wide_line_vertices = [
            vertices[vertex_ndx0] + line_normal_dir * half_width,
            vertices[vertex_ndx0] - line_normal_dir * half_width,
            vertices[vertex_ndx1] - line_normal_dir * half_width,
            vertices[vertex_ndx1] + line_normal_dir * half_width,
        ];

        // 1st triangle
        ref_vertices.push(wide_line_vertices[0]);
        ref_vertices.push(wide_line_vertices[1]);
        ref_vertices.push(wide_line_vertices[2]);

        // 2nd triangle
        ref_vertices.push(wide_line_vertices[0]);
        ref_vertices.push(wide_line_vertices[2]);
        ref_vertices.push(wide_line_vertices[3]);
    }

    let vertex_shader = WideLineVertexShader::new();
    let fragment_shader = WideLineFragmentShader::new();

    // Draw wide line was two triangles
    let reference = reference_draw(
        &framebuffer_state,
        &[ReferenceDrawObject {
            pipeline_state: pipeline_state.clone(),
            vertex_shader: &vertex_shader,
            fragment_shader: &fragment_shader,
            draw_call_data: DrawCallData {
                topology: vk::PrimitiveTopology::TRIANGLE_LIST,
                vertices: &ref_vertices,
            },
        }],
    )?;

    if int_threshold_compare(
        &reference.get_const_access(),
        &pixels.get_const_access(),
        UVec4::new(1, 1, 1, 1),
    )
    .ok
    {
        return Ok(TestStatus::pass("OK"));
    }

    Ok(TestStatus::fail("Rendered image(s) are incorrect"))
}

