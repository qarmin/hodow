/// `ClipDistanceComplementarity::testComplementarity`
fn test_complementarity<'a>(context: &'a Context<'a>, param: Param) -> TestOutcome {
    let num_clip_distances = match param {
        Param::Count(count) => count,
        _ => unreachable!("the case was registered with a count"),
    };
    let shaders = get_shader_vector(&context.get_binary_collection())?;

    let mut vertices = Vec::new();
    {
        let mut rnd = Random::new(1234);
        let num_sections = 16;
        let num_vertices_per_section = 4; // logical verticies, due to triangle list topology we actually use 6 per section

        debug_assert!(RENDER_SIZE_LARGE % num_sections == 0);

        let clip_distances: Vec<f32> = (0..num_vertices_per_section * num_sections)
            .map(|_| rnd.get_float_range(-1.0, 1.0))
            .collect();

        // Two sets of identical primitives, but with a different ClipDistance sign.
        for set_ndx in 0..2 {
            let sign = if set_ndx == 0 { 1.0f32 } else { -1.0 };
            let dx = 2.0 / num_sections as f32;

            for i in 0..num_sections {
                let ndx_base = (num_vertices_per_section * i) as usize;
                let x = -1.0 + dx * i as f32;
                let p0 = Vec4::new(x, -1.0, 0.0, sign * clip_distances[ndx_base]);
                let p1 = Vec4::new(x, 1.0, 0.0, sign * clip_distances[ndx_base + 1]);
                let p2 = Vec4::new(x + dx, 1.0, 0.0, sign * clip_distances[ndx_base + 2]);
                let p3 = Vec4::new(x + dx, -1.0, 0.0, sign * clip_distances[ndx_base + 3]);

                vertices.push(p0);
                vertices.push(p1);
                vertices.push(p2);

                vertices.push(p2);
                vertices.push(p3);
                vertices.push(p0);
            }
        }
    }

    // Draw two sets of primitives with blending, differing only with ClipDistance sign. Expecting a uniform gray area, no
    // missing (black) nor overlapped (white) pixels.
    let _ = num_clip_distances;
    let framebuffer_state = FrameBufferState::new(RENDER_SIZE_LARGE as u32, RENDER_SIZE_LARGE as u32);
    let mut pipeline_state = PipelineState::new(subpixel_bits(context));
    pipeline_state.blend_enable = true;
    let pixels = draw_and_read(
        context,
        &framebuffer_state,
        &pipeline_state,
        &shaders,
        vk::PrimitiveTopology::TRIANGLE_LIST,
        &vertices,
    )?;

    let num_gray_pixels = count_pixels(&pixels, Vec4::new(0.5, 0.5, 0.5, 1.0), Vec4::new(0.02, 0.02, 0.02, 0.0));
    let num_expected_pixels = RENDER_SIZE_LARGE * RENDER_SIZE_LARGE;

    Ok(if num_gray_pixels == num_expected_pixels {
        TestStatus::pass("OK")
    } else {
        TestStatus::fail("Rendered image(s) are incorrect")
    })
}

fn cull_distance_check_support(context: &Context<'_>, _param: Param) -> Result<(), TestError> {
    require_features(context, FEATURE_SHADER_CULL_DISTANCE)
}

/// `CullDistance::testCullDistance`
fn test_cull_distance<'a>(context: &'a Context<'a>, _param: Param) -> TestOutcome {
    let shaders = get_shader_vector(&context.get_binary_collection())?;

    let vertices = vec![
        Vec4::new(-3.0, 0.0, 0.0, 1.0),
        Vec4::new(0.0, 3.0, 0.0, 1.0),
        Vec4::new(0.0, -3.0, 0.0, 1.0),
    ];

    let framebuffer_state = FrameBufferState::new(RENDER_SIZE as u32, RENDER_SIZE as u32);
    let pipeline_state = PipelineState::new(subpixel_bits(context));
    let pixels = draw_and_read(
        context,
        &framebuffer_state,
        &pipeline_state,
        &shaders,
        vk::PrimitiveTopology::TRIANGLE_STRIP,
        &vertices,
    )?;

    let num_drawn_pixels = count_pixels(&pixels, Vec4::new(1.0, 0.0, 0.0, 1.0), Vec4::new(0.02, 0.02, 0.02, 0.0));
    let num_expected_pixels = RENDER_SIZE * RENDER_SIZE / 2;

    // triangle should be drawn and half of framebuffer should be filled with red color
    Ok(if num_drawn_pixels == num_expected_pixels {
        TestStatus::pass("OK")
    } else {
        TestStatus::fail("Triangle was not drawn")
    })
}

fn primitive_support(context: &Context<'_>, param: Param) -> Result<(), TestError> {
    primitives_inside_outside_check_support(context, param)
}

/// `addFunctionCaseWithPrograms<Param>`
struct ClippingCase {
    name: String,
    programs: BinaryCollection,
    param: Param,
    support: fn(&Context<'_>, Param) -> Result<(), TestError>,
    run: for<'a> fn(&'a Context<'a>, Param) -> TestOutcome,
}

impl TestCase for ClippingCase {
    fn name(&self) -> &str {
        &self.name
    }

    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        (self.support)(context, self.param)
    }

    fn programs(&self) -> BinaryCollection {
        self.programs
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(ClippingInstance {
            context,
            param: self.param,
            run: self.run,
        })
    }
}

struct ClippingInstance<'a> {
    context: &'a Context<'a>,
    param: Param,
    run: for<'r> fn(&'r Context<'r>, Param) -> TestOutcome,
}

impl TestInstance for ClippingInstance<'_> {
    fn iterate(&mut self) -> TestOutcome {
        (self.run)(self.context, self.param)
    }
}

/// The programs of the generated case of the given name.
fn distance_programs(name: &str) -> BinaryCollection {
    ALL_SHARED_PROGRAM
        .iter()
        .find(|program| program.name == name)
        .unwrap_or_else(|| panic!("scripts/gen_clipping_programs.py generated no case named {name}"))
        .programs
}

/// `addClippingTests`
pub fn create_tests() -> TestCaseGroup {
    let mut clipping_tests_group = TestCaseGroup::new("clipping");

    // Clipping against the clip volume
    {
        let cases = [
            vk::PrimitiveTopology::POINT_LIST,
            vk::PrimitiveTopology::LINE_LIST,
            vk::PrimitiveTopology::LINE_LIST_WITH_ADJACENCY,
            vk::PrimitiveTopology::LINE_STRIP,
            vk::PrimitiveTopology::LINE_STRIP_WITH_ADJACENCY,
            vk::PrimitiveTopology::TRIANGLE_LIST,
            vk::PrimitiveTopology::TRIANGLE_LIST_WITH_ADJACENCY,
            vk::PrimitiveTopology::TRIANGLE_STRIP,
            vk::PrimitiveTopology::TRIANGLE_STRIP_WITH_ADJACENCY,
            vk::PrimitiveTopology::TRIANGLE_FAN,
        ];

        // `initPrograms(programCollection, topology)`: a point list gets a point size of one.
        let programs_of = |topology: vk::PrimitiveTopology| {
            if topology == vk::PrimitiveTopology::POINT_LIST {
                SIMPLE_POINT.programs
            } else {
                SIMPLE.programs
            }
        };
        let topology_group = |name: &str,
                              support: fn(&Context<'_>, Param) -> Result<(), TestError>,
                              run: for<'a> fn(&'a Context<'a>, Param) -> TestOutcome| {
            let mut group = TestCaseGroup::new(name);
            for topology in cases {
                group.add_child(Box::new(ClippingCase {
                    name: get_primitive_topology_short_name(topology).to_string(),
                    programs: programs_of(topology),
                    param: Param::Topology(topology),
                    support,
                    run,
                }) as Box<dyn TestCase>);
            }
            group
        };

        let mut clip_volume_group = TestCaseGroup::new("clip_volume");

        // Fully inside the clip volume
        clip_volume_group.add_child(topology_group("inside", primitive_support, test_primitives_inside));
        // Fully outside the clip volume
        clip_volume_group.add_child(topology_group("outside", primitive_support, test_primitives_outside));
        // Depth clamping
        clip_volume_group.add_child(topology_group(
            "depth_clamp",
            primitives_depth_clamp_check_support,
            test_primitives_depth_clamp,
        ));
        // Depth clipping
        clip_volume_group.add_child(topology_group(
            "depth_clip",
            primitives_depth_clip_check_support,
            test_primitives_depth_clip,
        ));

        // Large points and wide lines
        {
            // \note For both points and lines, if an unsupported size/width is selected, the nearest supported size will be chosen.
            //       We do have to check for feature support though.
            let mut group = TestCaseGroup::new("clipped");

            group.add_child(Box::new(ClippingCase {
                name: "large_points".to_string(),
                programs: POINT_SIZE_LARGE.programs,
                param: Param::None,
                support: large_points_check_support,
                run: test_large_points,
            }) as Box<dyn TestCase>);
            group.add_child(Box::new(ClippingCase {
                name: "wide_lines_axis_aligned".to_string(),
                programs: SIMPLE.programs,
                param: Param::Orientation(LineOrientation::AxisAligned),
                support: wide_lines_check_support,
                run: test_wide_lines,
            }) as Box<dyn TestCase>);
            group.add_child(Box::new(ClippingCase {
                name: "wide_lines_diagonal".to_string(),
                programs: SIMPLE.programs,
                param: Param::Orientation(LineOrientation::Diagonal),
                support: wide_lines_check_support,
                run: test_wide_lines,
            }) as Box<dyn TestCase>);

            clip_volume_group.add_child(group);
        }

        clipping_tests_group.add_child(clip_volume_group);
    }

    // User-defined clip planes
    {
        let mut clip_distance_group = TestCaseGroup::new("user_defined");

        // ClipDistance, CullDistance and maxCombinedClipAndCullDistances usage
        for (group_name, use_cull_distance) in [("clip_distance", false), ("clip_cull_distance", true)] {
            for dynamic_indexing in [false, true] {
                let main_group_name = format!("{group_name}{}", if dynamic_indexing { "_dynamic_index" } else { "" });
                let mut main_group = TestCaseGroup::new(&main_group_name);

                for shader_mask in 0u32..=3 {
                    let use_tessellation = shader_mask & 1 != 0;
                    let use_geometry = shader_mask & 2 != 0;
                    let shader_group_name = format!(
                        "vert{}{}",
                        if use_tessellation { "_tess" } else { "" },
                        if use_geometry { "_geom" } else { "" }
                    );

                    let mut shader_group = TestCaseGroup::new(&shader_group_name);

                    for num_clip_planes in 1..=MAX_CLIP_DISTANCES {
                        for (read_name, read_in_fragment_shader) in [("", false), ("_fragmentshader_read", true)] {
                            let num_cull_planes = if use_cull_distance {
                                MAX_CULL_DISTANCES.min(MAX_COMBINED_CLIP_AND_CULL_DISTANCES - num_clip_planes)
                            } else {
                                0
                            };
                            let case_name = format!(
                                "{num_clip_planes}{}{read_name}",
                                if num_cull_planes > 0 {
                                    format!("_{num_cull_planes}")
                                } else {
                                    String::new()
                                }
                            );
                            let topology = if use_tessellation {
                                vk::PrimitiveTopology::PATCH_LIST
                            } else {
                                vk::PrimitiveTopology::TRIANGLE_LIST
                            };

                            shader_group.add_child(Box::new(ClippingCase {
                                programs: distance_programs(&format!(
                                    "{main_group_name}__{shader_group_name}__{case_name}"
                                )),
                                name: case_name,
                                param: Param::Distance(CaseDefinition {
                                    topology,
                                    dynamic_indexing,
                                    enable_tessellation: use_tessellation,
                                    enable_geometry: use_geometry,
                                    num_clip_distances: num_clip_planes,
                                    num_cull_distances: num_cull_planes,
                                    read_in_fragment_shader,
                                }),
                                support: clip_distance_check_support,
                                run: test_clip_distance,
                            }) as Box<dyn TestCase>);
                        }
                    }
                    main_group.add_child(shader_group);
                }
                clip_distance_group.add_child(main_group);
            }
        }
        clipping_tests_group.add_child(clip_distance_group);

        // Complementarity criterion (i.e. clipped and not clipped areas must add up to a complete primitive with no holes nor overlap)
        {
            let mut group = TestCaseGroup::new("complementarity");

            for num_clip_distances in 1..=MAX_CLIP_DISTANCES {
                group.add_child(Box::new(ClippingCase {
                    name: num_clip_distances.to_string(),
                    programs: distance_programs(&format!("complementarity__{num_clip_distances}")),
                    param: Param::Count(num_clip_distances),
                    support: complementarity_check_support,
                    run: test_complementarity,
                }) as Box<dyn TestCase>);
            }

            clipping_tests_group.add_child(group);
        }

        {
            let mut group = TestCaseGroup::new("misc");

            group.add_child(Box::new(ClippingCase {
                name: "negative_and_non_negative_cull_distance".to_string(),
                programs: CULL_DISTANCE.programs,
                param: Param::None,
                support: cull_distance_check_support,
                run: test_cull_distance,
            }) as Box<dyn TestCase>);

            clipping_tests_group.add_child(group);
        }
    }

    clipping_tests_group
}
