/// `ClipVolume::getClippingBehavior`
fn get_clipping_behavior(context: &Context<'_>) -> vk::PointClippingBehavior {
    // The value `VK_POINT_CLIPPING_BEHAVIOR_LAST` stands for upstream: one no driver reports.
    let invalid_clipping_behavior = vk::PointClippingBehavior::from_raw(0x7fff_ffff);
    let mut behavior_properties = vk::PhysicalDevicePointClippingProperties {
        point_clipping_behavior: invalid_clipping_behavior,
        ..Default::default()
    };
    let mut properties2 = vk::PhysicalDeviceProperties2::builder().push_next(&mut behavior_properties);
    unsafe {
        context
            .get_instance()
            .get_physical_device_properties2(context.get_physical_device(), &mut properties2)
    };
    behavior_properties.point_clipping_behavior
}

/// `ClipVolume::testLargePoints`: large point clipping.
/// Spec: If the primitive under consideration is a point, then clipping passes it unchanged if it lies within the clip volume;
///       otherwise, it is discarded.
fn test_large_points<'a>(context: &'a Context<'a>, _param: Param) -> TestOutcome {
    let mut point_clipping_outside = true;

    if context.is_device_functionality_supported("VK_KHR_maintenance2") {
        let clipping_behavior = get_clipping_behavior(context);

        if clipping_behavior == vk::PointClippingBehavior::ALL_CLIP_PLANES {
            point_clipping_outside = true;
        } else if clipping_behavior == vk::PointClippingBehavior::USER_CLIP_PLANES_ONLY {
            point_clipping_outside = false;
        } else if clipping_behavior == vk::PointClippingBehavior::from_raw(0x7fff_ffff) {
            return Err(TestError::Fail("Clipping behavior read failure".to_string()));
        } else {
            return Err(TestError::Fail("Unexpected clipping behavior reported".to_string()));
        }
    }

    let shaders = get_shader_vector(&context.get_binary_collection())?;

    let delta = 0.1f32; // much smaller than the point size
    let p = 1.0 + delta;
    let vertices = vec![
        Vec4::new(-p, -p, 0.1, 1.0),
        Vec4::new(-p, p, 0.2, 1.0),
        Vec4::new(p, p, 0.4, 1.0),
        Vec4::new(p, -p, 0.6, 1.0),
        Vec4::new(0.0, -p, 0.8, 1.0),
        Vec4::new(p, 0.0, 0.7, 1.0),
        Vec4::new(0.0, p, 0.5, 1.0),
        Vec4::new(-p, 0.0, 0.3, 1.0),
    ];

    // Drawing several large points just outside the clip volume. Expecting an empty image or all points rendered.
    let framebuffer_state = FrameBufferState::new(RENDER_SIZE as u32, RENDER_SIZE as u32);
    let pipeline_state = PipelineState::new(subpixel_bits(context));
    let pixels = draw_and_read(
        context,
        &framebuffer_state,
        &pipeline_state,
        &shaders,
        vk::PrimitiveTopology::POINT_LIST,
        &vertices,
    )?;

    // Popful case: All pixels must be black -- nothing is drawn.
    let num_black_pixels = count_pixels(&pixels, BLACK, Vec4::splat(0.0));

    // Pop-free case: All points must be rendered.
    let all_points_rendered = vertices
        .iter()
        .all(|vertex| count_pixels(&pixels, Vec4::new(1.0, vertex.z(), 0.0, 1.0), Vec4::splat(0.01)) != 0);

    let result = if point_clipping_outside {
        num_black_pixels == NUM_RENDER_PIXELS || all_points_rendered
    } else {
        // Rendering pixels without clipping: all points should be drawn.
        all_points_rendered
    };

    Ok(if result {
        TestStatus::pass("OK")
    } else {
        TestStatus::fail("Rendered image(s) are incorrect")
    })
}

/// `WideLineVertexShader`
struct WideLineVertexShader {
    inputs: [VertexInputInfo; 1],
    outputs: [VertexOutputInfo; 1],
}

impl WideLineVertexShader {
    fn new() -> Self {
        Self {
            inputs: [VertexInputInfo {
                type_: Some(GenericVecType::Float),
            }],
            outputs: [VertexOutputInfo {
                type_: Some(GenericVecType::Float),
                flatshade: false,
            }],
        }
    }
}

impl VertexShader for WideLineVertexShader {
    fn inputs(&self) -> &[VertexInputInfo] {
        &self.inputs
    }

    fn outputs(&self) -> &[VertexOutputInfo] {
        &self.outputs
    }

    fn shade_vertices(&self, inputs: &[VertexAttrib], packets: &mut [VertexPacket]) {
        for packet in packets.iter_mut() {
            let mut position = Vec4::splat(0.0);
            // SAFETY: the attribute points at the vertices the test keeps alive across the draw.
            unsafe { read_vertex_attrib_float(&mut position, &inputs[0], packet.instance_ndx, packet.vertex_ndx, 0) };

            packet.position = position;
            packet.outputs[0] = GenericVec4::from_float(position);
        }
    }
}

/// `WideLineFragmentShader`
struct WideLineFragmentShader {
    inputs: [FragmentInputInfo; 1],
    outputs: [FragmentOutputInfo; 1],
}

impl WideLineFragmentShader {
    fn new() -> Self {
        Self {
            inputs: [FragmentInputInfo {
                type_: Some(GenericVecType::Float),
                flatshade: false,
            }],
            outputs: [FragmentOutputInfo {
                type_: Some(GenericVecType::Float),
            }],
        }
    }
}

impl FragmentShader for WideLineFragmentShader {
    fn inputs(&self) -> &[FragmentInputInfo] {
        &self.inputs
    }

    fn outputs(&self) -> &[FragmentOutputInfo] {
        &self.outputs
    }

    fn shade_fragments(&self, packets: &mut [FragmentPacket], context: &FragmentShadingContext) {
        for packet_ndx in 0..packets.len() {
            for frag_ndx in 0..4usize {
                // SAFETY: the context was set up by the renderer for exactly these packets.
                unsafe {
                    let depth = read_varying(&packets[packet_ndx], context, 0, frag_ndx).z();
                    write_fragment_output(
                        context,
                        packet_ndx as i32,
                        frag_ndx as i32,
                        0,
                        GenericVec4::from_float(Vec4::new(1.0, depth, 0.0, 1.0)),
                    );
                }
            }
        }
    }
}

