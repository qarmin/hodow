/// The per case minimum number of coloured pixels of the depth clamp and depth clip cases.
fn region_min_pixels(
    context: &Context<'_>,
    topology: vk::PrimitiveTopology,
    region_pixels: i32,
) -> Result<[i32; 4], TestError> {
    let mut case_min_pixels = [0i32; 4];

    match topology {
        vk::PrimitiveTopology::POINT_LIST => {
            case_min_pixels[0] = region_pixels - 1;
            case_min_pixels[2] = region_pixels - 1;
            case_min_pixels[1] = 2;
            case_min_pixels[3] = 2;
        }
        vk::PrimitiveTopology::LINE_LIST_WITH_ADJACENCY
        | vk::PrimitiveTopology::LINE_STRIP_WITH_ADJACENCY
        | vk::PrimitiveTopology::LINE_LIST
        | vk::PrimitiveTopology::LINE_STRIP => {
            if has_adjacency(topology) {
                require_features(context, FEATURE_GEOMETRY_SHADER)?;
            }
            case_min_pixels[0] = region_pixels;
            case_min_pixels[1] = RENDER_SIZE - 2;
            case_min_pixels[2] = region_pixels;
            case_min_pixels[3] = 2 * (RENDER_SIZE - 2);
        }
        _ => {
            if has_adjacency(topology) {
                require_features(context, FEATURE_GEOMETRY_SHADER)?;
            }
            case_min_pixels = [region_pixels; 4];
        }
    }
    Ok(case_min_pixels)
}

