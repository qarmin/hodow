/// `requireFeatures`
fn require_features(context: &Context<'_>, flags: u32) -> Result<(), TestError> {
    let features = context.get_device_features();
    let missing = |flag: u32, supported: vk::Bool32, message: &str| -> Result<(), TestError> {
        if flags & flag != 0 && supported == vk::FALSE {
            Err(TestError::NotSupported(message.to_string()))
        } else {
            Ok(())
        }
    };

    missing(
        FEATURE_TESSELLATION_SHADER,
        features.tessellation_shader,
        "Tessellation shader not supported",
    )?;
    missing(
        FEATURE_GEOMETRY_SHADER,
        features.geometry_shader,
        "Geometry shader not supported",
    )?;
    missing(FEATURE_DEPTH_CLAMP, features.depth_clamp, "Depth clamp not supported")?;
    missing(
        FEATURE_LARGE_POINTS,
        features.large_points,
        "Large points not supported",
    )?;
    missing(FEATURE_WIDE_LINES, features.wide_lines, "Wide lines not supported")?;
    missing(
        FEATURE_SHADER_CLIP_DISTANCE,
        features.shader_clip_distance,
        "Shader ClipDistance not supported",
    )?;
    missing(
        FEATURE_SHADER_CULL_DISTANCE,
        features.shader_cull_distance,
        "Shader CullDistance not supported",
    )?;
    Ok(())
}

/// `genVertices`
fn gen_vertices(topology: vk::PrimitiveTopology, offset: Vec4, slope: f32) -> Vec<Vec4> {
    let p = 1.0f32;
    let hp = 0.5f32;
    let z = 0.0f32;
    let w = 1.0f32;
    let zero = Vec4::splat(0.0);

    let mut vertices = Vec::new();

    // We're setting adjacent vertices to zero where needed, as we don't use them in meaningful way.
    match topology {
        vk::PrimitiveTopology::POINT_LIST => {
            vertices.push(offset + Vec4::new(0.0, 0.0, slope / 2.0 + z, w));
            vertices.push(offset + Vec4::new(-hp, -hp, z, w));
            vertices.push(offset + Vec4::new(hp, -hp, slope + z, w));
            vertices.push(offset + Vec4::new(-hp, hp, z, w));
            vertices.push(offset + Vec4::new(hp, hp, slope + z, w));
        }
        vk::PrimitiveTopology::LINE_LIST => {
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(offset + Vec4::new(p, p, slope + z, w)); // line 0
            vertices.push(offset + Vec4::new(p, p, slope + z, w));
            vertices.push(offset + Vec4::new(p, -p, slope + z, w)); // line 1
            vertices.push(offset + Vec4::new(p, -p, slope + z, w));
            vertices.push(offset + Vec4::new(-p, p, z, w)); // line 2
        }
        vk::PrimitiveTopology::LINE_LIST_WITH_ADJACENCY => {
            vertices.push(zero);
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(offset + Vec4::new(p, p, slope + z, w)); // line 0
            vertices.push(zero);
            vertices.push(zero);
            vertices.push(offset + Vec4::new(p, p, slope + z, w));
            vertices.push(offset + Vec4::new(p, -p, slope + z, w)); // line 1
            vertices.push(zero);
            vertices.push(zero);
            vertices.push(offset + Vec4::new(p, -p, slope + z, w));
            vertices.push(offset + Vec4::new(-p, p, z, w)); // line 2
            vertices.push(zero);
        }
        vk::PrimitiveTopology::LINE_STRIP => {
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(offset + Vec4::new(p, p, slope + z, w)); // line 0
            vertices.push(offset + Vec4::new(p, -p, slope + z, w)); // line 1
            vertices.push(offset + Vec4::new(-p, p, z, w)); // line 2
        }
        vk::PrimitiveTopology::LINE_STRIP_WITH_ADJACENCY => {
            vertices.push(zero);
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(offset + Vec4::new(p, p, slope + z, w)); // line 0
            vertices.push(offset + Vec4::new(p, -p, slope + z, w)); // line 1
            vertices.push(offset + Vec4::new(-p, p, z, w)); // line 2
            vertices.push(zero);
        }
        vk::PrimitiveTopology::TRIANGLE_LIST => {
            vertices.push(offset + Vec4::new(p, -p, slope + z, w));
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(offset + Vec4::new(-p, p, z, w)); // triangle 0
            vertices.push(offset + Vec4::new(-p, p, z, w));
            vertices.push(offset + Vec4::new(p, p, slope + z, w));
            vertices.push(offset + Vec4::new(p, -p, slope + z, w)); // triangle 1
        }
        vk::PrimitiveTopology::TRIANGLE_LIST_WITH_ADJACENCY => {
            vertices.push(offset + Vec4::new(p, -p, slope + z, w));
            vertices.push(zero);
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(zero);
            vertices.push(offset + Vec4::new(-p, p, z, w)); // triangle 0
            vertices.push(zero);
            vertices.push(offset + Vec4::new(-p, p, z, w));
            vertices.push(zero);
            vertices.push(offset + Vec4::new(p, p, slope + z, w));
            vertices.push(zero);
            vertices.push(offset + Vec4::new(p, -p, slope + z, w)); // triangle 1
            vertices.push(zero);
        }
        vk::PrimitiveTopology::TRIANGLE_STRIP => {
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(offset + Vec4::new(-p, p, z, w));
            vertices.push(offset + Vec4::new(p, -p, slope + z, w)); // triangle 0
            vertices.push(offset + Vec4::new(p, p, slope + z, w)); // triangle 1
        }
        vk::PrimitiveTopology::TRIANGLE_STRIP_WITH_ADJACENCY => {
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(zero);
            vertices.push(offset + Vec4::new(-p, p, z, w));
            vertices.push(zero);
            vertices.push(offset + Vec4::new(p, -p, slope + z, w)); // triangle 0
            vertices.push(zero);
            vertices.push(offset + Vec4::new(p, p, slope + z, w)); // triangle 1
            vertices.push(zero);
        }
        vk::PrimitiveTopology::TRIANGLE_FAN => {
            vertices.push(offset + Vec4::new(p, -p, slope + z, w));
            vertices.push(offset + Vec4::new(-p, -p, z, w));
            vertices.push(offset + Vec4::new(-p, p, z, w)); // triangle 0
            vertices.push(offset + Vec4::new(p, p, slope + z, w)); // triangle 1
        }
        _ => unreachable!("genVertices is not defined for this topology"),
    }
    vertices
}

/// `isColorInRange`
fn is_color_in_range(color: Vec4, min_color: Vec4, max_color: Vec4) -> bool {
    (0..4).all(|i| min_color[i] <= color[i] && color[i] <= max_color[i])
}

/// `countPixels`: pixels that match `color` within `color_threshold`, in the specified region.
fn count_pixels_in_region(
    pixels: &TextureLevel,
    region_offset: (i32, i32),
    region_size: (i32, i32),
    color: Vec4,
    color_threshold: Vec4,
) -> i32 {
    let min_color = color - color_threshold;
    let max_color = color + color_threshold;
    let x_end = region_offset.0 + region_size.0;
    let y_end = region_offset.1 + region_size.1;
    let access = pixels.get_const_access();
    let [width, height, _] = access.size();

    debug_assert!(x_end <= width as i32);
    debug_assert!(y_end <= height as i32);

    let mut num_pixels = 0;
    for y in region_offset.1..y_end {
        for x in region_offset.0..x_end {
            if is_color_in_range(
                Vec4::from_array(access.get_pixel(x as u32, y as u32, 0)),
                min_color,
                max_color,
            ) {
                num_pixels += 1;
            }
        }
    }
    num_pixels
}

/// `countPixels`, over the whole image.
fn count_pixels(pixels: &TextureLevel, color: Vec4, color_threshold: Vec4) -> i32 {
    let [width, height, _] = pixels.get_const_access().size();
    count_pixels_in_region(pixels, (0, 0), (width as i32, height as i32), color, color_threshold)
}

const BLACK: Vec4 = Vec4::new(0.0, 0.0, 0.0, 1.0);

/// `checkFragColors`: check for correct cull and clip distance values. Middle bar should contain clip distance with linear
/// values between 0 and 1. Cull distance is always 0.5 when enabled.
fn check_frag_colors(pixels: &TextureLevel, clip_region: (i32, i32), bar_idx: i32, has_cull_distance: bool) -> bool {
    let access = pixels.get_const_access();
    let [width, height, _] = access.size();
    let (width, height) = (width as i32, height as i32);

    for y in 0..height {
        for x in 0..width {
            if x < clip_region.0 && y < clip_region.1 {
                continue;
            }

            let color = access.get_pixel(x as u32, y as u32, 0);
            let bar_width = width / 8;
            let inside_bar = x >= bar_width * bar_idx && x < bar_width * (bar_idx + 1);
            let expected_clip_distance = if inside_bar {
                (((y as f32 + 0.5) / height as f32) - 0.5) * 2.0
            } else {
                0.0
            };
            let mut expected_cull_distance = 0.5f32;
            let clip_distance = color[1];
            let cull_distance = color[2];
            let height_f = height as f32;

            if has_cull_distance {
                // Linear interpolation of the cull distance.
                // Remember there are precision errors due to 8-bit UNORM, but they should fall inside 0.01f threshold.
                //
                // Notes about the results:
                // - linear interpolation of gl_CullDistance[i] = [0.0f, 0.5f]. Correct.
                // - Constant value:
                //   + 0.1f: value written by vertex shader when there are other geometry-related shaders. It means the value was not overriden. Failure.
                //   + 0.2f: value written by tessc shader when cull distance value from vertex is not 0.1f. Failure.
                //   + 0.3f: value written by tessc shader when cull distance value from vertex is 0.1f and there is geometry shader. Failure.
                //   + 0.4f: value written by geometry shader when cull distance is not either 0.1f (if no tess is present) or 0.3f (tess present). Failure.
                if y >= height / 2 {
                    expected_cull_distance = expected_cull_distance * (1.0 + (2.0 * y as f32) - height_f) / height_f;
                } else {
                    expected_cull_distance = 0.0;
                }
            }

            if (clip_distance - expected_clip_distance).abs() > 0.01 {
                return false;
            }
            if has_cull_distance && (cull_distance - expected_cull_distance).abs() > 0.01 {
                return false;
            }
        }
    }

    true
}

/// `getShaderVector`
fn get_shader_vector(binaries: &BinaryCollection) -> Result<Vec<VulkanShader>, TestError> {
    Ok(vec![
        VulkanShader {
            stage: vk::ShaderStageFlags::VERTEX,
            binary: binaries.get("vert")?,
        },
        VulkanShader {
            stage: vk::ShaderStageFlags::FRAGMENT,
            binary: binaries.get("frag")?,
        },
    ])
}

/// What the draws of one case need: the context, a framebuffer and a pipeline state, drawn and read back.
fn draw_and_read<'a>(
    context: &'a Context<'a>,
    framebuffer_state: &FrameBufferState,
    pipeline_state: &PipelineState,
    shaders: &[VulkanShader],
    topology: vk::PrimitiveTopology,
    vertices: &[Vec4],
) -> Result<TextureLevel, TestError> {
    let draw_call_data = DrawCallData { topology, vertices };
    let vulkan_program = VulkanProgram::new(shaders.to_vec());

    let mut draw_context = VulkanDrawContext::new(context, framebuffer_state)?;
    draw_context.register_draw_object(pipeline_state, &vulkan_program, &draw_call_data)?;
    draw_context.draw()?;
    draw_context.get_color_pixels()
}

