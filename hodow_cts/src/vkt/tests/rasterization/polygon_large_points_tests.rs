const NUM_TRIANGLES: u32 = 2;
const NUM_POINTS: u32 = NUM_TRIANGLES * 3;
const TARGET_SIZE: u32 = 4;
const CLEAR_COLOR: [u8; 4] = [0, 0, 0, 255];
const GEOMETRY_COLOR: [u8; 4] = [0, 0, 255, 255];

/// `PolygonModeLargePointsConfig`
#[derive(Clone, Copy)]
struct PolygonModeLargePointsConfig {
    point_size: f32,
    mesh_shader: bool,
    tessellation_shaders: bool,
    geometry_shader: bool,
    dynamic_polygon_mode: bool,
    default_size: bool,
}

struct PolygonModeLargePointsCase {
    name: String,
    config: PolygonModeLargePointsConfig,
}

fn maintenance5_polygon_mode_point_size(context: &Context<'_>) -> bool {
    let mut maintenance5 = vk::PhysicalDeviceMaintenance5Properties::default();
    let mut properties2 = vk::PhysicalDeviceProperties2::builder().push_next(&mut maintenance5);
    unsafe {
        context
            .get_instance()
            .get_physical_device_properties2(context.get_physical_device(), &mut properties2)
    };
    maintenance5.polygon_mode_point_size != vk::FALSE
}

impl TestCase for PolygonModeLargePointsCase {
    fn name(&self) -> &str {
        &self.name
    }

    /// `PolygonModeLargePointsCase::checkSupport`
    fn check_support(&self, context: &Context<'_>) -> Result<(), TestError> {
        let config = &self.config;
        let not_supported = |what: &str| Err(TestError::NotSupported(what.to_string()));

        context.require_device_functionality("VK_KHR_maintenance5")?;

        let features = context.get_device_features();
        if features.fill_mode_non_solid == vk::FALSE {
            return not_supported("Core feature fillModeNonSolid not supported");
        }

        if !maintenance5_polygon_mode_point_size(context) && !config.default_size {
            return not_supported(
                "VK_KHR_maintenance5: polygonModePointSize property is not supported by this implementation",
            );
        }

        let limits = &context.get_device_properties().limits;
        if limits.standard_sample_locations == vk::FALSE {
            return not_supported("standardSampleLocations not supported");
        }

        if config.mesh_shader {
            context.require_device_functionality("VK_EXT_mesh_shader")?;
        }

        if (config.tessellation_shaders || config.geometry_shader)
            && features.shader_tessellation_and_geometry_point_size == vk::FALSE
        {
            return not_supported("Core feature shaderTessellationAndGeometryPointSize not supported");
        }

        if config.tessellation_shaders && features.tessellation_shader == vk::FALSE {
            return not_supported("Core feature tessellationShader not supported");
        }

        if config.geometry_shader && features.geometry_shader == vk::FALSE {
            return not_supported("Core feature geometryShader not supported");
        }

        if config.point_size != 1.0 {
            if features.large_points == vk::FALSE {
                return not_supported("Core feature largePoints not supported");
            }

            let valid_range = limits.point_size_range;
            if valid_range[0] > config.point_size || valid_range[1] < config.point_size {
                return Err(TestError::NotSupported(format!(
                    "Required point size {} outside valid range [{}, {}]",
                    config.point_size, valid_range[0], valid_range[1]
                )));
            }
        }

        if config.dynamic_polygon_mode {
            context.require_device_functionality("VK_EXT_extended_dynamic_state3")?;

            let mut eds3_features = vk::PhysicalDeviceExtendedDynamicState3FeaturesEXT::default();
            let mut features2 = vk::PhysicalDeviceFeatures2::builder().push_next(&mut eds3_features);
            unsafe {
                context
                    .get_instance()
                    .get_physical_device_features2(context.get_physical_device(), &mut features2)
            };
            if eds3_features.extended_dynamic_state3_polygon_mode == vk::FALSE {
                return not_supported("extendedDynamicState3PolygonMode not supported");
            }
        }

        Ok(())
    }

    /// `PolygonModeLargePointsCase::initPrograms`, resolved ahead of time by the manifest.
    fn programs(&self) -> BinaryCollection {
        let config = &self.config;
        match (
            config.mesh_shader,
            config.tessellation_shaders,
            config.geometry_shader,
            config.default_size,
        ) {
            (true, _, _, true) => POLYGON_POINTS_MESH_DEFAULT.programs,
            (true, _, _, false) => POLYGON_POINTS_MESH_SIZED.programs,
            (false, false, false, true) => POLYGON_POINTS_VERT_DEFAULT.programs,
            (false, false, false, false) => POLYGON_POINTS_VERT_SIZED.programs,
            (false, true, false, true) => POLYGON_POINTS_VERT_TESS_DEFAULT.programs,
            (false, true, false, false) => POLYGON_POINTS_VERT_TESS_SIZED.programs,
            (false, false, true, true) => POLYGON_POINTS_VERT_GEOM_DEFAULT.programs,
            (false, false, true, false) => POLYGON_POINTS_VERT_GEOM_SIZED.programs,
            (false, true, true, true) => POLYGON_POINTS_VERT_TESS_GEOM_DEFAULT.programs,
            (false, true, true, false) => POLYGON_POINTS_VERT_TESS_GEOM_SIZED.programs,
        }
    }

    fn create_instance<'a>(&'a self, context: &'a Context<'a>) -> Box<dyn TestInstance + 'a> {
        Box::new(PolygonModeLargePointsInstance {
            context,
            config: self.config,
        })
    }
}

struct PolygonModeLargePointsInstance<'a> {
    context: &'a Context<'a>,
    config: PolygonModeLargePointsConfig,
}

/*
 * The test will create a 4x4 framebuffer and will draw a quad in the middle of it, roughly covering the 4 center pixels. Instead of
 * making the quad have the exact size to cover the whole center area, the quad will be slightly inside the 4 center pixels, with a
 * margin of 0.125 units (1/4 of a pixel in unnormalized coordinates). This means a point size of 1.0 will not reach the sampling
 * points at the pixel center of the edge pixels, but a point size of 2.0 will.
 */
impl TestInstance for PolygonModeLargePointsInstance<'_> {
    fn iterate(&mut self) -> TestOutcome {
        let context = self.context;
        let config = self.config;
        let device = context.get_device();
        let allocator = context.get_default_allocator();
        let queue = context.get_universal_queue();

        // Color buffer and verification buffer.
        let target = ColorTarget::new(context, TARGET_SIZE, TARGET_SIZE)?;

        // Vertex buffer.
        let inside_margin = 0.125f32;
        let top_left = Vec4::new(-0.5, -0.5, 0.0, 1.0);
        let top_right = Vec4::new(0.5, -0.5, 0.0, 1.0);
        let bottom_left = Vec4::new(-0.5, 0.5, 0.0, 1.0);
        let bottom_right = Vec4::new(0.5, 0.5, 0.0, 1.0);

        let actual_tl = Vec4::new(top_left.x() + inside_margin, top_left.y() + inside_margin, 0.0, 1.0);
        let actual_tr = Vec4::new(top_right.x() - inside_margin, top_right.y() + inside_margin, 0.0, 1.0);
        let actual_bl = Vec4::new(
            bottom_left.x() + inside_margin,
            bottom_left.y() - inside_margin,
            0.0,
            1.0,
        );
        let actual_br = Vec4::new(
            bottom_right.x() - inside_margin,
            bottom_right.y() - inside_margin,
            0.0,
            1.0,
        );

        let vertices: [[f32; 4]; NUM_POINTS as usize] =
            [actual_tl, actual_tr, actual_bl, actual_tr, actual_br, actual_bl]
                .map(|vertex| [vertex.x(), vertex.y(), vertex.z(), vertex.w()]);

        let vertex_buffer_size = std::mem::size_of_val(&vertices) as vk::DeviceSize;
        let vertex_buffer_usage = if config.mesh_shader {
            vk::BufferUsageFlags::STORAGE_BUFFER
        } else {
            vk::BufferUsageFlags::VERTEX_BUFFER
        };
        let vertex_buffer = BufferWithMemory::new(
            device,
            allocator,
            make_buffer_create_info(vertex_buffer_size, vertex_buffer_usage),
            MemoryRequirement::HOST_VISIBLE,
        )?;
        unsafe {
            std::ptr::copy_nonoverlapping(
                vertices.as_ptr() as *const u8,
                vertex_buffer.get_allocation().get_host_ptr(),
                vertex_buffer_size as usize,
            );
        }
        flush_alloc(device, vertex_buffer.get_allocation())?;

        // Pipeline layout.
        let mut set_layout_builder = DescriptorSetLayoutBuilder::new();
        if config.mesh_shader {
            set_layout_builder = set_layout_builder
                .add_single_binding(vk::DescriptorType::STORAGE_BUFFER, vk::ShaderStageFlags::MESH_EXT);
        }
        let set_layout = set_layout_builder.build(device)?;
        let pipeline_layout = make_pipeline_layout(device, &[*set_layout])?;

        // Descriptor pool and set if needed.
        let mut descriptor_pool = None;
        let mut descriptor_set = None;
        if config.mesh_shader {
            let pool = DescriptorPoolBuilder::new()
                .add_type(vk::DescriptorType::STORAGE_BUFFER, 1)
                .build(device, vk::DescriptorPoolCreateFlags::FREE_DESCRIPTOR_SET, 1)?;
            let set = make_descriptor_set(device, *pool, *set_layout)?;

            let vertex_buffer_desc_info = make_descriptor_buffer_info(vertex_buffer.get(), 0, vertex_buffer_size);
            DescriptorSetUpdateBuilder::new()
                .write_single(
                    *set,
                    Location::binding(0),
                    vk::DescriptorType::STORAGE_BUFFER,
                    &vertex_buffer_desc_info,
                )
                .update(device);

            descriptor_pool = Some(pool);
            descriptor_set = Some(set);
        }

        // Render pass and framebuffer.
        let render_pass = make_render_pass(device, COLOR_FORMAT)?;
        let framebuffer = make_framebuffer(device, *render_pass, &[*target.view], TARGET_SIZE, TARGET_SIZE, 1)?;

        // Shader modules.
        let binaries = context.get_binary_collection();
        let vert_module = if !config.mesh_shader {
            Some(create_shader_module(device, binaries.get("vert")?)?)
        } else {
            None
        };
        let mesh_module = if config.mesh_shader {
            Some(create_shader_module(device, binaries.get("mesh")?)?)
        } else {
            None
        };
        let frag_module = create_shader_module(device, binaries.get("frag")?)?;
        let tesc_module = if config.tessellation_shaders {
            Some(create_shader_module(device, binaries.get("tesc")?)?)
        } else {
            None
        };
        let tese_module = if config.tessellation_shaders {
            Some(create_shader_module(device, binaries.get("tese")?)?)
        } else {
            None
        };
        let geom_module = if config.geometry_shader {
            Some(create_shader_module(device, binaries.get("geom")?)?)
        } else {
            None
        };

        // Viewports and scissors.
        let viewports = [vk::Viewport {
            x: 0.0,
            y: 0.0,
            width: TARGET_SIZE as f32,
            height: TARGET_SIZE as f32,
            min_depth: 0.0,
            max_depth: 1.0,
        }];
        let scissors = [vk::Rect2D {
            offset: vk::Offset2D { x: 0, y: 0 },
            extent: vk::Extent2D {
                width: TARGET_SIZE,
                height: TARGET_SIZE,
            },
        }];
        let viewport_state = vk::PipelineViewportStateCreateInfo::builder()
            .viewports(&viewports)
            .scissors(&scissors);

        // Rasterization state: key for the test. Rendering triangles as points.
        let polygon_mode = if config.dynamic_polygon_mode {
            vk::PolygonMode::FILL
        } else {
            vk::PolygonMode::POINT
        };
        let rasterization_state = vk::PipelineRasterizationStateCreateInfo::builder()
            .depth_clamp_enable(false)
            .rasterizer_discard_enable(false)
            .polygon_mode(polygon_mode)
            .cull_mode(vk::CullModeFlags::NONE)
            .front_face(vk::FrontFace::CLOCKWISE)
            .depth_bias_enable(false)
            .line_width(1.0);

        let mut dynamic_states = Vec::new();
        if config.dynamic_polygon_mode {
            dynamic_states.push(vk::DynamicState::POLYGON_MODE_EXT);
        }
        let dynamic_state = vk::PipelineDynamicStateCreateInfo::builder().dynamic_states(&dynamic_states);

        let primitive_topology = if config.tessellation_shaders {
            vk::PrimitiveTopology::PATCH_LIST
        } else {
            vk::PrimitiveTopology::TRIANGLE_LIST
        };

        let vertex_bindings = [vk::VertexInputBindingDescription {
            binding: 0,
            stride: std::mem::size_of::<[f32; 4]>() as u32,
            input_rate: vk::VertexInputRate::VERTEX,
        }];
        let vertex_attributes = [vk::VertexInputAttributeDescription {
            location: 0,
            binding: 0,
            format: vk::Format::R32G32B32A32_SFLOAT,
            offset: 0,
        }];
        let vertex_input_state = vk::PipelineVertexInputStateCreateInfo::builder()
            .vertex_binding_descriptions(&vertex_bindings)
            .vertex_attribute_descriptions(&vertex_attributes);
        let input_assembly_state = vk::PipelineInputAssemblyStateCreateInfo::builder()
            .topology(primitive_topology)
            .primitive_restart_enable(false);
        let tessellation_state = vk::PipelineTessellationStateCreateInfo::builder().patch_control_points(3);
        let multisample_state =
            vk::PipelineMultisampleStateCreateInfo::builder().rasterization_samples(vk::SampleCountFlags::_1);
        let color_blend_attachments = [vk::PipelineColorBlendAttachmentState::builder()
            .blend_enable(false)
            .color_write_mask(vk::ColorComponentFlags::all())
            .build()];
        let color_blend_state = vk::PipelineColorBlendStateCreateInfo::builder().attachments(&color_blend_attachments);

        let stage = |stage: vk::ShaderStageFlags, module: vk::ShaderModule| {
            vk::PipelineShaderStageCreateInfo::builder()
                .stage(stage)
                .module(module)
                .name(b"main\0")
                .build()
        };
        let mut stages = Vec::new();
        if let Some(module) = &mesh_module {
            stages.push(stage(vk::ShaderStageFlags::MESH_EXT, **module));
        }
        if let Some(module) = &vert_module {
            stages.push(stage(vk::ShaderStageFlags::VERTEX, **module));
        }
        if let (Some(control), Some(evaluation)) = (&tesc_module, &tese_module) {
            stages.push(stage(vk::ShaderStageFlags::TESSELLATION_CONTROL, **control));
            stages.push(stage(vk::ShaderStageFlags::TESSELLATION_EVALUATION, **evaluation));
        }
        if let Some(module) = &geom_module {
            stages.push(stage(vk::ShaderStageFlags::GEOMETRY, **module));
        }
        stages.push(stage(vk::ShaderStageFlags::FRAGMENT, *frag_module));

        // A pipeline with a mesh shader has no vertex input and no input assembly state.
        let mut pipeline_info = vk::GraphicsPipelineCreateInfo::builder()
            .stages(&stages)
            .viewport_state(&viewport_state)
            .rasterization_state(&rasterization_state)
            .multisample_state(&multisample_state)
            .color_blend_state(&color_blend_state)
            .dynamic_state(&dynamic_state)
            .layout(*pipeline_layout)
            .render_pass(*render_pass)
            .subpass(0)
            .base_pipeline_index(0);
        if !config.mesh_shader {
            pipeline_info = pipeline_info
                .vertex_input_state(&vertex_input_state)
                .input_assembly_state(&input_assembly_state);
            if config.tessellation_shaders {
                pipeline_info = pipeline_info.tessellation_state(&tessellation_state);
            }
        }
        let pipelines = unsafe { device.create_graphics_pipelines(vk::PipelineCache::null(), &[pipeline_info], None) }
            .vk_check("vkCreateGraphicsPipelines")?;
        let pipeline = Unique::new(device, pipelines.0[0]);

        // Command pool and buffer, render and verify results.
        let cmd_pool = make_command_pool(device, context.get_universal_queue_family_index())?;
        let cmd_buffer = allocate_command_buffer(device, *cmd_pool, vk::CommandBufferLevel::PRIMARY)?;
        let cmd = *cmd_buffer;

        begin_command_buffer(device, cmd)?;
        begin_render_pass(
            device,
            cmd,
            *render_pass,
            *framebuffer,
            scissors[0],
            vk::ClearValue {
                color: vk::ClearColorValue {
                    float32: [0.0, 0.0, 0.0, 1.0],
                },
            },
        );
        unsafe {
            device.cmd_bind_pipeline(cmd, vk::PipelineBindPoint::GRAPHICS, *pipeline);

            if let Some(set) = &descriptor_set {
                device.cmd_bind_descriptor_sets(
                    cmd,
                    vk::PipelineBindPoint::GRAPHICS,
                    *pipeline_layout,
                    0,
                    &[**set],
                    &[],
                );
            } else {
                device.cmd_bind_vertex_buffers(cmd, 0, &[vertex_buffer.get()], &[0]);
            }

            if config.dynamic_polygon_mode {
                device.cmd_set_polygon_mode_ext(cmd, vk::PolygonMode::POINT);
            }

            if config.mesh_shader {
                device.cmd_draw_mesh_tasks_ext(cmd, 1, 1, 1);
            } else {
                device.cmd_draw(cmd, NUM_POINTS, 1, 0, 0);
            }
        }
        end_render_pass(device, cmd);

        // Copy image to verification buffer.
        copy_image_to_buffer(
            device,
            cmd,
            target.image.get(),
            target.buffer.get(),
            TARGET_SIZE,
            TARGET_SIZE,
        );
        end_command_buffer(device, cmd)?;
        submit_commands_and_wait(device, queue, cmd)?;

        // Check results.
        let pixels = target.read(context, (TARGET_SIZE * TARGET_SIZE) as usize)?;
        // If testing default size means we are not setting the point size in shaders, and therefore we don't care about polygonModePointSize.
        // Default size is 1.0f, so we should only take the border into account
        let point_size_used = if config.default_size {
            false
        } else {
            maintenance5_polygon_mode_point_size(context)
        };

        // Prepare reference color image, which depends on VkPhysicalDeviceMaintenance5PropertiesKHR::polygonModePointSize.
        for y in 0..TARGET_SIZE {
            for x in 0..TARGET_SIZE {
                let border = x == 0 || y == 0 || x == TARGET_SIZE - 1 || y == TARGET_SIZE - 1;
                let expected = if border && !point_size_used {
                    CLEAR_COLOR
                } else {
                    GEOMETRY_COLOR
                };
                let offset = ((y * TARGET_SIZE + x) * 4) as usize;
                if pixels[offset..offset + 4] != expected {
                    log::info!(
                        "Pixel ({x}, {y}) is {:?}, expected {expected:?}",
                        &pixels[offset..offset + 4]
                    );
                    return Ok(TestStatus::fail(
                        "Color buffer contents do not match expected result -- check log for details",
                    ));
                }
            }
        }

        drop(descriptor_pool);
        Ok(TestStatus::pass("Pass"))
    }
}

/// The two nested loops of `createRasterizationTests` that name the cases: mesh or vert, `_tess`, `_geom`, then the polygon mode.
fn add_cases(group: &mut TestCaseGroup, point_size: f32, default_size: bool) {
    for dynamic_polygon_mode in [false, true] {
        for tessellation in [false, true] {
            for geometry_shader in [false, true] {
                for mesh_shader in [false, true] {
                    if mesh_shader && (tessellation || geometry_shader) {
                        continue;
                    }

                    let mut name = String::from(if mesh_shader { "mesh" } else { "vert" });
                    if tessellation {
                        name.push_str("_tess");
                    }
                    if geometry_shader {
                        name.push_str("_geom");
                    }
                    name.push_str(if dynamic_polygon_mode {
                        "_dynamic_polygon_mode"
                    } else {
                        "_static_polygon_mode"
                    });

                    group.add_child(Box::new(PolygonModeLargePointsCase {
                        name,
                        config: PolygonModeLargePointsConfig {
                            point_size,
                            mesh_shader,
                            tessellation_shaders: tessellation,
                            geometry_shader,
                            dynamic_polygon_mode,
                            default_size,
                        },
                    }) as Box<dyn TestCase>);
                }
            }
        }
    }
}

/// `primitive_size.default_size.polygon_as_points`
pub fn create_polygon_as_points_tests() -> TestCaseGroup {
    let mut group = TestCaseGroup::new("polygon_as_points");
    add_cases(&mut group, 1.0, true);
    group
}

/// `polygon_as_large_points`
pub fn create_polygon_as_large_points_tests() -> TestCaseGroup {
    let mut group = TestCaseGroup::new("polygon_as_large_points");
    add_cases(&mut group, 2.0, false);
    group
}
