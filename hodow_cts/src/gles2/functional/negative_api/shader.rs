fn uniform_matrixfv_invalid_transpose(case: &mut ApiCase<'_>) {
    // A non-false `transpose` is an error only in ES 2.0 - ES 3.0 made it legal - and
    // upstream gates the whole case on the *version string* rather than on the context
    // type, because a 3.x driver handed an ES 2.0 context may still report the newer
    // behaviour. Kept exactly that way.
    let gl = case.gl();
    // SAFETY: glGetString returns a driver-owned null-terminated string.
    let version = unsafe { glw::string_from(gl.get_string(glw::GL_VERSION)) };
    if !version.starts_with("OpenGL ES 2.0 ") {
        log::debug!("// {version} is not an OpenGL ES 2.0 context, so transpose is not an error");
        return;
    }

    let program = uniform_program(case);
    let gl = case.gl();
    let data = [0.0f32; 16];

    case.section("GL_INVALID_VALUE is generated if transpose is not GL_FALSE.");
    // SAFETY: as above.
    unsafe { gl.use_program(program.program.program()) };
    unsafe { gl.uniform_matrix_2fv(0, 1, glw::TRUE, data.as_ptr()) };
    case.expect_error(glw::GL_INVALID_VALUE);
    unsafe { gl.uniform_matrix_3fv(0, 1, glw::TRUE, data.as_ptr()) };
    case.expect_error(glw::GL_INVALID_VALUE);
    unsafe { gl.uniform_matrix_4fv(0, 1, glw::TRUE, data.as_ptr()) };
    case.expect_error(glw::GL_INVALID_VALUE);

    unsafe { gl.use_program(0) };
}

