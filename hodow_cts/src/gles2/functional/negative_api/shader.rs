fn shader_binary(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    let binary_formats = case.get_supported_extensions(glw::GL_NUM_SHADER_BINARY_FORMATS, glw::GL_SHADER_BINARY_FORMATS);
    let shader_binary_supported = !binary_formats.is_empty();
    if shader_binary_supported {
        log::debug!("// Shader binaries supported");
    } else {
        log::debug!("// Shader binaries not supported.");
    }

    // SAFETY: every call passes a length of 0 or a negative one with a null binary, so
    // nothing is read through the pointer.
    let mut shaders = unsafe { [gl.create_shader(glw::GL_VERTEX_SHADER), gl.create_shader(glw::GL_VERTEX_SHADER)] };
    let program = unsafe { gl.create_program() };

    case.section("GL_INVALID_ENUM is generated if binaryformat is not a supported format returned in GL_SHADER_BINARY_FORMATS.");
    unsafe { gl.shader_binary(1, shaders.as_ptr(), BAD_ENUM, std::ptr::null(), 0) };
    case.expect_error(glw::GL_INVALID_ENUM);

    if shader_binary_supported {
        let format = binary_formats[0] as u32;

        case.section("GL_INVALID_VALUE is generated if any value in shaders is not a value generated by OpenGL.");
        shaders[0] = 137;
        unsafe { gl.shader_binary(1, shaders.as_ptr(), format, std::ptr::null(), 0) };
        case.expect_error(glw::GL_INVALID_VALUE);

        case.section("GL_INVALID_VALUE is generated if n or length is negative.");
        shaders[0] = unsafe { gl.create_shader(glw::GL_VERTEX_SHADER) };
        unsafe { gl.shader_binary(-1, shaders.as_ptr(), format, std::ptr::null(), 0) };
        case.expect_error2(glw::GL_INVALID_OPERATION, glw::GL_INVALID_VALUE);
        unsafe { gl.shader_binary(1, shaders.as_ptr(), format, std::ptr::null(), -1) };
        case.expect_error2(glw::GL_INVALID_OPERATION, glw::GL_INVALID_VALUE);

        case.section("GL_INVALID_OPERATION is generated if any value in shaders is not a shader object.");
        unsafe { gl.shader_binary(1, &program, format, std::ptr::null(), 0) };
        case.expect_error2(glw::GL_INVALID_OPERATION, glw::GL_INVALID_VALUE);

        case.section("GL_INVALID_OPERATION is generated if there is more than one vertex shader object handle or more than one fragment shader object handle in shaders.");
        shaders[0] = unsafe { gl.create_shader(glw::GL_VERTEX_SHADER) };
        shaders[1] = unsafe { gl.create_shader(glw::GL_VERTEX_SHADER) };
        unsafe { gl.shader_binary(2, shaders.as_ptr(), format, std::ptr::null(), 1) };
        case.expect_error2(glw::GL_INVALID_OPERATION, glw::GL_INVALID_VALUE);
    }

    unsafe {
        gl.delete_shader(shaders[0]);
        gl.delete_shader(shaders[1]);
        gl.delete_program(program);
    }
    // \note upstream: the format of the data pointed to by binary does not match
    // binaryformat - not checked, because there is no valid binary to malform.
}

fn attach_shader(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    // SAFETY: every handle is this case's own.
    let shader1 = unsafe { gl.create_shader(glw::GL_VERTEX_SHADER) };
    let shader2 = unsafe { gl.create_shader(glw::GL_VERTEX_SHADER) };
    let program = unsafe { gl.create_program() };

    case.section("GL_INVALID_OPERATION is generated if program is not a program object.");
    unsafe { gl.attach_shader(shader1, shader1) };
    case.expect_error(glw::GL_INVALID_OPERATION);

    case.section("GL_INVALID_OPERATION is generated if shader is not a shader object.");
    unsafe { gl.attach_shader(program, program) };
    case.expect_error(glw::GL_INVALID_OPERATION);
    unsafe { gl.attach_shader(shader1, program) };
    case.expect_error(glw::GL_INVALID_OPERATION);

    case.section("GL_INVALID_VALUE is generated if either program or shader is not a value generated by OpenGL.");
    unsafe { gl.attach_shader(program, BAD_NAME) };
    case.expect_error(glw::GL_INVALID_VALUE);
    unsafe { gl.attach_shader(BAD_NAME, shader1) };
    case.expect_error(glw::GL_INVALID_VALUE);
    unsafe { gl.attach_shader(BAD_NAME, BAD_NAME) };
    case.expect_error(glw::GL_INVALID_VALUE);

    case.section(
        "GL_INVALID_OPERATION is generated if shader is already attached to program, or if another shader object of the same type as shader is already attached to program.",
    );
    unsafe { gl.attach_shader(program, shader1) };
    case.expect_error(glw::GL_NO_ERROR);
    unsafe { gl.attach_shader(program, shader1) };
    case.expect_error(glw::GL_INVALID_OPERATION);
    unsafe { gl.attach_shader(program, shader2) };
    case.expect_error(glw::GL_INVALID_OPERATION);

    unsafe {
        gl.delete_program(program);
        gl.delete_shader(shader1);
        gl.delete_shader(shader2);
    }
}

