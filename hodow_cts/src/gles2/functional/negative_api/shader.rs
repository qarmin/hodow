const VERTEX_SHADER_SOURCE: &str = "void main (void) { gl_Position = vec4(0.0); }\n";
const FRAGMENT_SHADER_SOURCE: &str = "void main (void) { gl_FragColor = vec4(0.0); }\n";

const UNIFORM_TEST_VERT_SOURCE: &str = "uniform mediump vec4 vTest;\n\
                                        uniform mediump mat4 vMatrix;\n\
                                        void main (void)\n\
                                        {\n\
                                        \x20   gl_Position = vMatrix * vTest;\n\
                                        }\n";
const UNIFORM_TEST_FRAG_SOURCE: &str = "uniform mediump ivec4 fTest;\n\
                                        uniform sampler2D fSampler;\n\
                                        void main (void)\n\
                                        {\n\
                                        \x20   gl_FragColor.xy = vec4(fTest).xy;\n\
                                        \x20   gl_FragColor.zw = texture2D(fSampler, vec2(0.0, 0.0)).zw;\n\
                                        }\n";

/// The invalid object names upstream writes as `-1` and `-2`.
const BAD_NAME: GLuint = u32::MAX;
const BAD_NAME_2: GLuint = u32::MAX - 1;

fn uniform_location(case: &mut ApiCase<'_>, program: GLuint, name: &str) -> GLint {
    let gl = case.gl();
    let cname = std::ffi::CString::new(name).expect("no interior nul");
    // SAFETY: the name is a valid C string that outlives the call.
    let location = unsafe { gl.get_uniform_location(program, cname.as_ptr()) };
    if location == -1 {
        case.fail(format!("{name} has no location"), "Failed to retrieve uniform location");
    }
    location
}

fn shader_compiler_supported(case: &mut ApiCase<'_>) -> bool {
    let gl = case.gl();
    let mut supported = glw::FALSE;
    // SAFETY: GL_SHADER_COMPILER is a single boolean.
    unsafe { gl.get_booleanv(glw::GL_SHADER_COMPILER, &mut supported) };
    if supported != glw::FALSE {
        log::debug!("// Shader compiler supported");
    } else {
        log::debug!("// Shader compiler not supported, always expect GL_INVALID_OPERATION");
    }
    supported != glw::FALSE
}

/// The program the uniform cases share, plus the three locations they check against.
struct UniformProgram<'gl> {
    program: ShaderProgram<'gl>,
    v_unif: GLint,
    v_mat_unif: GLint,
    f_unif: GLint,
    f_sampler: GLint,
}

fn uniform_program<'gl>(case: &mut ApiCase<'gl>) -> UniformProgram<'gl> {
    let gl = case.gl();
    let program = ShaderProgram::new(gl, &ProgramSources::vtx_frag(UNIFORM_TEST_VERT_SOURCE, UNIFORM_TEST_FRAG_SOURCE));
    // SAFETY: the handle is this case's own.
    unsafe { gl.use_program(program.program()) };
    let handle = program.program();
    UniformProgram {
        v_unif: uniform_location(case, handle, "vTest"),
        v_mat_unif: uniform_location(case, handle, "vMatrix"),
        f_unif: uniform_location(case, handle, "fTest"),
        f_sampler: uniform_location(case, handle, "fSampler"),
        program,
    }
}

fn create_shader(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    case.section("GL_INVALID_ENUM is generated if shaderType is not an accepted value.");
    // SAFETY: a current context; the returned name is 0 on failure and is dropped.
    unsafe { gl.create_shader(BAD_ENUM) };
    case.expect_error(glw::GL_INVALID_ENUM);
}

fn shader_source(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    let supported = shader_compiler_supported(case);
    let expected = if supported { glw::GL_INVALID_VALUE } else { glw::GL_INVALID_OPERATION };

    case.section("GL_INVALID_VALUE is generated if shader is not a value generated by OpenGL.");
    // SAFETY: count is 0 or negative and both arrays are null, so nothing is read.
    unsafe { gl.shader_source(1, 0, std::ptr::null(), std::ptr::null()) };
    case.expect_error(expected);

    case.section("GL_INVALID_VALUE is generated if count is less than 0.");
    let shader = unsafe { gl.create_shader(glw::GL_VERTEX_SHADER) };
    unsafe { gl.shader_source(shader, -1, std::ptr::null(), std::ptr::null()) };
    case.expect_error(expected);

    case.section("GL_INVALID_OPERATION is generated if shader is not a shader object.");
    let program = unsafe { gl.create_program() };
    unsafe { gl.shader_source(program, 0, std::ptr::null(), std::ptr::null()) };
    case.expect_error(glw::GL_INVALID_OPERATION);

    unsafe {
        gl.delete_program(program);
        gl.delete_shader(shader);
    }
}

