fn get_shader_precision_format(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    let supported = shader_compiler_supported(gl);
    if supported {
        log::debug!("// Shader compiler supported");
    } else {
        log::debug!("// Shader compiler not supported, always expect GL_INVALID_OPERATION");
    }

    let mut range = [-1i32; 2];
    let mut precision = [-1i32; 1];

    case.section("GL_INVALID_ENUM is generated if shaderType or precisionType is not an accepted value.");
    let expected = if supported {
        glw::GL_INVALID_ENUM
    } else {
        glw::GL_INVALID_OPERATION
    };
    // SAFETY: the outputs are two integers and one integer, which is what the call
    // writes when it succeeds.
    for (shader_type, precision_type) in [
        (BAD_ENUM, glw::GL_MEDIUM_FLOAT),
        (glw::GL_VERTEX_SHADER, BAD_ENUM),
        (BAD_ENUM, BAD_ENUM),
    ] {
        unsafe {
            gl.get_shader_precision_format(shader_type, precision_type, range.as_mut_ptr(), precision.as_mut_ptr())
        };
        case.expect_error(expected);
    }

    case.section("GL_INVALID_OPERATION is generated if a shader compiler is not supported.");
    unsafe {
        gl.get_shader_precision_format(
            glw::GL_VERTEX_SHADER,
            glw::GL_MEDIUM_FLOAT,
            range.as_mut_ptr(),
            precision.as_mut_ptr(),
        )
    };
    case.expect_error(if supported {
        glw::GL_NO_ERROR
    } else {
        glw::GL_INVALID_OPERATION
    });
}

