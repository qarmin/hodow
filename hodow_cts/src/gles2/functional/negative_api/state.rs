/// The two uniform locations the `get_uniform*` cases need, and the failure upstream
/// reports if the driver will not give them.
fn uniform_locations(case: &mut ApiCase<'_>, program: &ShaderProgram<'_>) -> (GLint, GLint) {
    let gl = case.gl();
    let v_name = std::ffi::CString::new("vTest").expect("no interior nul");
    let f_name = std::ffi::CString::new("fTest").expect("no interior nul");
    // SAFETY: both names are valid C strings that outlive the calls.
    let (v_unif, f_unif) = unsafe {
        (
            gl.get_uniform_location(program.program(), v_name.as_ptr()),
            gl.get_uniform_location(program.program(), f_name.as_ptr()),
        )
    };
    if v_unif == -1 || f_unif == -1 {
        case.fail(
            format!("vTest={v_unif}, fTest={f_unif}"),
            "Failed to retrieve uniform location",
        );
    }
    (v_unif, f_unif)
}

fn get_uniformfv(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    let program = ShaderProgram::new(
        gl,
        &ProgramSources::vtx_frag(UNIFORM_TEST_VERT_SOURCE, UNIFORM_TEST_FRAG_SOURCE),
    );
    // SAFETY: the program handle is this case's own.
    unsafe { gl.use_program(program.program()) };

    let (v_unif, f_unif) = uniform_locations(case, &program);
    // SAFETY: the output is four floats, which is the width of `vTest`.
    let (shader, program_empty) = unsafe { (gl.create_shader(glw::GL_VERTEX_SHADER), gl.create_program()) };
    let mut params = [0.0f32; 4];
    let params_ptr = params.as_mut_ptr();

    case.section("GL_INVALID_VALUE is generated if program is not a value generated by OpenGL.");
    unsafe { gl.get_uniformfv(BAD_NAME, v_unif, params_ptr) };
    case.expect_error(glw::GL_INVALID_VALUE);

    case.section("GL_INVALID_OPERATION is generated if program is not a program object.");
    unsafe { gl.get_uniformfv(shader, v_unif, params_ptr) };
    case.expect_error(glw::GL_INVALID_OPERATION);

    case.section("GL_INVALID_OPERATION is generated if program has not been successfully linked.");
    unsafe { gl.get_uniformfv(program_empty, v_unif, params_ptr) };
    case.expect_error(glw::GL_INVALID_OPERATION);

    case.section("GL_INVALID_OPERATION is generated if location does not correspond to a valid uniform variable location for the specified program object.");
    unsafe { gl.get_uniformfv(program.program(), v_unif.max(f_unif) + 1, params_ptr) };
    case.expect_error(glw::GL_INVALID_OPERATION);

    unsafe {
        gl.delete_shader(shader);
        gl.delete_program(program_empty);
    }
}

