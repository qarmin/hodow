fn get_framebuffer_attachment_parameteriv(case: &mut ApiCase<'_>) {
    let gl = case.gl();

    // GL_MAJOR_VERSION does not exist in ES 2.0, so a query that succeeds is itself the
    // evidence that this is ES 3.0 or newer hardware - which changes what several of
    // the checks below are allowed to return. Upstream probes exactly this way.
    let mut major_version = 0;
    // SAFETY: the output is one integer; a context that rejects the name writes none.
    unsafe { gl.get_integerv(glw::GL_MAJOR_VERSION, &mut major_version) };
    let is_es3_compatible = unsafe { gl.get_error() } == glw::GL_NO_ERROR;

    let mut params = [-1i32; 1];
    let mut fbo = 0;
    unsafe {
        gl.gen_framebuffers(1, &mut fbo);
        gl.bind_framebuffer(glw::GL_FRAMEBUFFER, fbo);
    }

    case.section("GL_INVALID_ENUM is generated if target is not GL_FRAMEBUFFER.");
    unsafe {
        gl.get_framebuffer_attachment_parameteriv(
            BAD_ENUM,
            glw::GL_COLOR_ATTACHMENT0,
            glw::GL_FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE,
            params.as_mut_ptr(),
        )
    };
    case.expect_error(glw::GL_INVALID_ENUM);

    case.section("GL_INVALID_ENUM is generated if there is no attached object at the named attachment point and pname is not GL_FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE.");
    if is_es3_compatible {
        // The attachment's type is GL_NONE, which ES 3.0 answers for OBJECT_NAME.
        unsafe {
            gl.get_framebuffer_attachment_parameteriv(
                glw::GL_FRAMEBUFFER,
                glw::GL_COLOR_ATTACHMENT0,
                glw::GL_FRAMEBUFFER_ATTACHMENT_OBJECT_NAME,
                params.as_mut_ptr(),
            )
        };
        case.expect_error(glw::GL_NO_ERROR);
        unsafe {
            gl.get_framebuffer_attachment_parameteriv(
                glw::GL_FRAMEBUFFER,
                glw::GL_COLOR_ATTACHMENT0,
                glw::GL_FRAMEBUFFER_ATTACHMENT_COMPONENT_TYPE,
                params.as_mut_ptr(),
            )
        };
        case.expect_error(glw::GL_INVALID_OPERATION);
    } else {
        unsafe {
            gl.get_framebuffer_attachment_parameteriv(
                glw::GL_FRAMEBUFFER,
                glw::GL_COLOR_ATTACHMENT0,
                glw::GL_FRAMEBUFFER_ATTACHMENT_OBJECT_NAME,
                params.as_mut_ptr(),
            )
        };
        case.expect_error(glw::GL_INVALID_ENUM);
    }

    if !is_es3_compatible {
        case.section("GL_INVALID_ENUM is generated if the attached object at the named attachment point is incompatible with pname.");
        let mut attachment_object_type = -1;
        unsafe {
            gl.get_framebuffer_attachment_parameteriv(
                glw::GL_FRAMEBUFFER,
                glw::GL_COLOR_ATTACHMENT0,
                glw::GL_FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE,
                &mut attachment_object_type,
            )
        };
        case.expect_error(glw::GL_NO_ERROR);

        match attachment_object_type as u32 {
            glw::GL_RENDERBUFFER => unsafe {
                gl.get_framebuffer_attachment_parameteriv(
                    glw::GL_FRAMEBUFFER,
                    glw::GL_COLOR_ATTACHMENT0,
                    glw::GL_FRAMEBUFFER_ATTACHMENT_TEXTURE_LEVEL,
                    params.as_mut_ptr(),
                )
            },
            glw::GL_TEXTURE => unsafe {
                gl.get_framebuffer_attachment_parameteriv(
                    glw::GL_FRAMEBUFFER,
                    glw::GL_COLOR_ATTACHMENT0,
                    BAD_ENUM,
                    params.as_mut_ptr(),
                )
            },
            glw::GL_NONE => unsafe {
                gl.get_framebuffer_attachment_parameteriv(
                    glw::GL_FRAMEBUFFER,
                    glw::GL_COLOR_ATTACHMENT0,
                    glw::GL_FRAMEBUFFER_ATTACHMENT_OBJECT_NAME,
                    params.as_mut_ptr(),
                )
            },
            other => case.fail(
                format!("attachment object type {other:#x}"),
                "Invalid return value from glGetFramebufferAttachmentParameteriv()",
            ),
        }
        case.expect_error(glw::GL_INVALID_ENUM);
    }

    case.section("GL_INVALID_OPERATION is generated if the default framebuffer object name 0 is bound.");
    unsafe {
        gl.bind_framebuffer(glw::GL_FRAMEBUFFER, 0);
        gl.get_framebuffer_attachment_parameteriv(
            glw::GL_FRAMEBUFFER,
            glw::GL_COLOR_ATTACHMENT0,
            glw::GL_FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE,
            params.as_mut_ptr(),
        );
    }
    if is_es3_compatible {
        case.expect_error2(glw::GL_INVALID_OPERATION, glw::GL_INVALID_ENUM);
    } else {
        case.expect_error(glw::GL_INVALID_OPERATION);
    }

    unsafe { gl.delete_framebuffers(1, &fbo) };
}

fn get_renderbuffer_parameteriv(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    let mut params = [0i32; 1];
    let mut rbo = 0;
    // SAFETY: the output is one integer.
    unsafe {
        gl.gen_renderbuffers(1, &mut rbo);
        gl.bind_renderbuffer(glw::GL_RENDERBUFFER, rbo);
    }

    case.section("GL_INVALID_ENUM is generated if target is not GL_RENDERBUFFER.");
    unsafe { gl.get_renderbuffer_parameteriv(BAD_ENUM, glw::GL_RENDERBUFFER_WIDTH, params.as_mut_ptr()) };
    case.expect_error(glw::GL_INVALID_ENUM);

    case.section("GL_INVALID_ENUM is generated if pname is not one of the allowed values.");
    unsafe { gl.get_renderbuffer_parameteriv(glw::GL_RENDERBUFFER, BAD_ENUM, params.as_mut_ptr()) };
    case.expect_error(glw::GL_INVALID_ENUM);

    case.section("GL_INVALID_OPERATION is generated if the reserved renderbuffer object name 0 is bound.");
    unsafe {
        gl.bind_renderbuffer(glw::GL_RENDERBUFFER, 0);
        gl.get_renderbuffer_parameteriv(glw::GL_RENDERBUFFER, glw::GL_RENDERBUFFER_WIDTH, params.as_mut_ptr());
    }
    case.expect_error(glw::GL_INVALID_OPERATION);

    unsafe { gl.delete_renderbuffers(1, &rbo) };
}

fn get_is_enabled(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    case.section("GL_INVALID_ENUM is generated if cap is not an accepted value.");
    // SAFETY: a current context; the return value is ignored, as upstream ignores it.
    for cap in [BAD_ENUM, glw::GL_TRIANGLES] {
        unsafe { gl.is_enabled(cap) };
        case.expect_error(glw::GL_INVALID_ENUM);
    }
}

fn hint(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    case.section("GL_INVALID_ENUM is generated if either target or mode is not an accepted value.");
    // SAFETY: as above.
    for (target, mode) in [
        (glw::GL_GENERATE_MIPMAP_HINT, BAD_ENUM),
        (BAD_ENUM, glw::GL_FASTEST),
        (BAD_ENUM, BAD_ENUM),
    ] {
        unsafe { gl.hint(target, mode) };
        case.expect_error(glw::GL_INVALID_ENUM);
    }
}

fn is_buffer(case: &mut ApiCase<'_>) {
    let gl = case.gl();
    let mut buffer = 0;

    case.section("A name returned by glGenBuffers, but not yet associated with a buffer object by calling glBindBuffer, is not the name of a buffer object.");
    // SAFETY: every handle here is this case's own.
    let mut is_buffer = unsafe { gl.is_buffer(buffer) };
    case.check_booleans(i32::from(is_buffer), glw::FALSE);

    unsafe {
        gl.gen_buffers(1, &mut buffer);
        is_buffer = gl.is_buffer(buffer);
    }
    case.check_booleans(i32::from(is_buffer), glw::FALSE);

    unsafe {
        gl.bind_buffer(glw::GL_ARRAY_BUFFER, buffer);
        is_buffer = gl.is_buffer(buffer);
    }
    case.check_booleans(i32::from(is_buffer), glw::TRUE);

    unsafe {
        gl.bind_buffer(glw::GL_ARRAY_BUFFER, 0);
        gl.delete_buffers(1, &buffer);
        is_buffer = gl.is_buffer(buffer);
    }
    case.check_booleans(i32::from(is_buffer), glw::FALSE);

    case.expect_error(glw::GL_NO_ERROR);
}

