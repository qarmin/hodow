fn shader_binary(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    // \note upstream computes `shaderBinarySupported` from an empty vector before filling
    // it, so it is always false and only the first section ever runs. Kept as is.
    let mut num_formats: GLint = 0;
    let mut shaders = [0 as GLuint; 2];

    // SAFETY: as above; both shader names are this function's own.
    unsafe {
        ctx.gl()
            .get_integerv(glw::GL_NUM_SHADER_BINARY_FORMATS, &mut num_formats);
        if num_formats == 0 {
            log::debug!("// No supported extensions available.");
        }
        log::debug!("// Shader binaries not supported.");

        shaders[0] = ctx.gl().create_shader(glw::GL_VERTEX_SHADER);
        shaders[1] = ctx.gl().create_shader(glw::GL_VERTEX_SHADER);

        ctx.begin_section("GL_INVALID_ENUM is generated if binaryFormat is not an accepted value.");
        ctx.gl()
            .shader_binary(1, shaders.as_ptr(), BAD_ENUM, std::ptr::null(), 0);
        ctx.expect_error(glw::GL_INVALID_ENUM);
        ctx.end_section();

        ctx.gl().delete_shader(shaders[0]);
        ctx.gl().delete_shader(shaders[1]);
    }
    Ok(())
}

fn attach_shader(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    // SAFETY: as above.
    unsafe {
        let shader1 = ctx.gl().create_shader(glw::GL_VERTEX_SHADER);
        let shader2 = ctx.gl().create_shader(glw::GL_VERTEX_SHADER);
        let program = ctx.gl().create_program();

        // The sentinels come last: a name freed before these were created would be
        // handed straight back by them, and would no longer be an unknown name.
        let not_a_shader = deleted_shader(ctx);
        let not_a_program = deleted_program(ctx);

        ctx.begin_section("GL_INVALID_OPERATION is generated if program is not a program object.");
        ctx.gl().attach_shader(shader1, shader1);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();

        ctx.begin_section("GL_INVALID_OPERATION is generated if shader is not a shader object.");
        ctx.gl().attach_shader(program, program);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.gl().attach_shader(shader1, program);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();

        ctx.begin_section(
            "GL_INVALID_VALUE is generated if either program or shader is not a value generated by OpenGL.",
        );
        ctx.gl().attach_shader(program, not_a_shader);
        ctx.expect_error(glw::GL_INVALID_VALUE);
        ctx.gl().attach_shader(not_a_program, shader1);
        ctx.expect_error(glw::GL_INVALID_VALUE);
        ctx.gl().attach_shader(not_a_program, not_a_shader);
        ctx.expect_error(glw::GL_INVALID_VALUE);
        ctx.end_section();

        ctx.begin_section("GL_INVALID_OPERATION is generated if shader is already attached to program.");
        ctx.gl().attach_shader(program, shader1);
        ctx.expect_error(glw::GL_NO_ERROR);
        ctx.gl().attach_shader(program, shader1);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();

        ctx.begin_section(
            "GL_INVALID_OPERATION is generated if a shader of the same type as shader is already attached to program.",
        );
        ctx.gl().attach_shader(program, shader2);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();

        ctx.gl().delete_program(program);
        ctx.gl().delete_shader(shader1);
        ctx.gl().delete_shader(shader2);
    }
    Ok(())
}

