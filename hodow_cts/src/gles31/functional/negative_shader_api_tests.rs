fn bind_transform_feedback(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    let program = simple_program(ctx);
    let mut tf_id = [0 as GLuint; 2];
    let mut buf: GLuint = 0;

    // SAFETY: as above; both transform feedback objects are this function's own.
    unsafe {
        ctx.gl().gen_buffers(1, &mut buf);
        ctx.gl().gen_transform_feedbacks(2, tf_id.as_mut_ptr());

        ctx.begin_section("GL_INVALID_ENUM is generated if target is not GL_TRANSFORM_FEEDBACK.");
        ctx.gl().bind_transform_feedback(BAD_ENUM, tf_id[0]);
        ctx.expect_error(glw::GL_INVALID_ENUM);
        ctx.end_section();
    }

    ctx.begin_section("GL_INVALID_OPERATION is generated if the transform feedback operation is active on the currently bound transform feedback object, and is not paused.");
    begin_transform_feedback_on(ctx, &program, tf_id[0], buf, glw::GL_TRIANGLES);
    ctx.expect_error(glw::GL_NO_ERROR);

    // SAFETY: as above.
    unsafe {
        ctx.gl().bind_transform_feedback(glw::GL_TRANSFORM_FEEDBACK, tf_id[1]);
        ctx.expect_error(glw::GL_INVALID_OPERATION);

        ctx.gl().end_transform_feedback();
        ctx.expect_error(glw::GL_NO_ERROR);
        ctx.end_section();

        ctx.gl().use_program(0);
        ctx.gl().delete_buffers(1, &buf);
        ctx.gl().delete_transform_feedbacks(2, tf_id.as_ptr());
        ctx.expect_error(glw::GL_NO_ERROR);

        ctx.begin_section("GL_INVALID_OPERATION is generated if id has been deleted with glDeleteTransformFeedback().");
        ctx.gl().bind_transform_feedback(glw::GL_TRANSFORM_FEEDBACK, tf_id[0]);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();

        ctx.begin_section(
            "GL_INVALID_OPERATION is generated if id is not 0 or a value returned from glGenTransformFeedbacks().",
        );
        ctx.gl().bind_transform_feedback(glw::GL_TRANSFORM_FEEDBACK, BAD_ENUM);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();
    }
    Ok(())
}

