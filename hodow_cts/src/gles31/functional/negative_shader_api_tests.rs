const VERTEX_SHADER_SOURCE: &str = "#version 300 es\nvoid main (void)\n{\n    gl_Position = vec4(0.0);\n}\n";

const FRAGMENT_SHADER_SOURCE: &str = "#version 300 es\nlayout(location = 0) out mediump vec4 fragColor;void main (void)\n{\n    fragColor = vec4(0.0);\n}\n";

const UNIFORM_TEST_VERT_SOURCE: &str = "#version 300 es\nuniform mediump vec4 vec4_v;\nuniform mediump mat4 mat4_v;\nvoid main (void)\n{\n    gl_Position = mat4_v * vec4_v;\n}\n";

const UNIFORM_TEST_FRAG_SOURCE: &str = "#version 300 es\nuniform mediump ivec4 ivec4_f;\nuniform mediump uvec4 uvec4_f;\nuniform sampler2D sampler_f;\nlayout(location = 0) out mediump vec4 fragColor;void main (void)\n{\n    fragColor.xy = (vec4(uvec4_f) + vec4(ivec4_f)).xy;\n    fragColor.zw = texture(sampler_f, vec2(0.0, 0.0)).zw;\n}\n";

const UNIFORM_BLOCK_VERT_SOURCE: &str = "#version 300 es\nlayout(shared) uniform Block { lowp float var; };\nvoid main (void)\n{\n    gl_Position = vec4(var);\n}\n";

/// `supportsES32orGL45`
fn supports_es32(ctx: &NegativeTestContext<'_>, what: &str) -> Result<(), TestError> {
    if ctx.context_supports(3, 2) {
        Ok(())
    } else {
        Err(TestError::NotSupported(format!("{what} is not supported.")))
    }
}

fn simple_program<'gl>(ctx: &NegativeTestContext<'gl>) -> ShaderProgram<'gl> {
    ShaderProgram::new(
        ctx.gl(),
        &ProgramSources::vtx_frag(VERTEX_SHADER_SOURCE, FRAGMENT_SHADER_SOURCE),
    )
}

fn uniform_program<'gl>(ctx: &NegativeTestContext<'gl>) -> ShaderProgram<'gl> {
    ShaderProgram::new(
        ctx.gl(),
        &ProgramSources::vtx_frag(UNIFORM_TEST_VERT_SOURCE, UNIFORM_TEST_FRAG_SOURCE),
    )
}

/// A name `glCreateShader`/`glCreateProgram` returned and that was then deleted, so it is
/// no longer a value generated by OpenGL.
fn deleted_shader(ctx: &NegativeTestContext<'_>) -> GLuint {
    // SAFETY: the name is created and immediately deleted here.
    unsafe {
        let shader = ctx.gl().create_shader(glw::GL_VERTEX_SHADER);
        ctx.gl().delete_shader(shader);
        shader
    }
}

fn deleted_program(ctx: &NegativeTestContext<'_>) -> GLuint {
    // SAFETY: as above.
    unsafe {
        let program = ctx.gl().create_program();
        ctx.gl().delete_program(program);
        program
    }
}

/// The four uniform locations most `uniform*` cases look up, failing the case if any is
/// missing rather than silently testing against -1.
struct UniformLocations {
    vec4_v: GLint,
    ivec4_f: GLint,
    uvec4_f: GLint,
    sampler_f: GLint,
}

fn uniform_locations(ctx: &mut NegativeTestContext<'_>, program: &ShaderProgram<'_>) -> UniformLocations {
    // SAFETY: each name is a static NUL-terminated string.
    let locations = unsafe {
        ctx.gl().use_program(program.program());
        UniformLocations {
            vec4_v: ctx.gl().get_uniform_location(program.program(), c"vec4_v".as_ptr()),
            ivec4_f: ctx.gl().get_uniform_location(program.program(), c"ivec4_f".as_ptr()),
            uvec4_f: ctx.gl().get_uniform_location(program.program(), c"uvec4_f".as_ptr()),
            sampler_f: ctx.gl().get_uniform_location(program.program(), c"sampler_f".as_ptr()),
        }
    };
    ctx.expect_error(glw::GL_NO_ERROR);

    if locations.vec4_v == -1 || locations.ivec4_f == -1 || locations.uvec4_f == -1 || locations.sampler_f == -1 {
        log::debug!("// ERROR: Failed to retrieve uniform location");
        ctx.fail("Failed to retrieve uniform location");
    }

    locations
}

/// One uniform location looked up by name, with the same failure handling.
fn uniform_location(ctx: &mut NegativeTestContext<'_>, program: &ShaderProgram<'_>, name: &std::ffi::CStr) -> GLint {
    // SAFETY: as above.
    let location = unsafe {
        ctx.gl().use_program(program.program());
        ctx.gl().get_uniform_location(program.program(), name.as_ptr())
    };
    ctx.expect_error(glw::GL_NO_ERROR);

    if location == -1 {
        log::debug!("// ERROR: Failed to retrieve uniform location");
        ctx.fail("Failed to retrieve uniform location");
    }

    location
}

