/// The transform-feedback setup the `link_program` / `use_program` / `bind_transform_*`
/// cases share: capture `gl_Position` from `program`, relink it, and start feedback.
fn begin_transform_feedback_on(
    ctx: &mut NegativeTestContext<'_>,
    program: &ShaderProgram<'_>,
    tf_id: GLuint,
    buf: GLuint,
    mode: GLenum,
) {
    // SAFETY: the buffer gets 32 bytes with no initial data, and the varying name is a
    // static NUL-terminated string.
    unsafe {
        ctx.gl().use_program(program.program());
        let varying = c"gl_Position".as_ptr();
        ctx.gl()
            .transform_feedback_varyings(program.program(), 1, &varying, glw::GL_INTERLEAVED_ATTRIBS);
        ctx.gl().link_program(program.program());
        ctx.gl().bind_transform_feedback(glw::GL_TRANSFORM_FEEDBACK, tf_id);
        ctx.gl().bind_buffer(glw::GL_TRANSFORM_FEEDBACK_BUFFER, buf);
        ctx.gl().buffer_data(
            glw::GL_TRANSFORM_FEEDBACK_BUFFER,
            32,
            std::ptr::null(),
            glw::GL_DYNAMIC_DRAW,
        );
        ctx.gl().bind_buffer_base(glw::GL_TRANSFORM_FEEDBACK_BUFFER, 0, buf);
        ctx.gl().begin_transform_feedback(mode);
    }
}

fn link_program(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    // SAFETY: as above.
    unsafe {
        let shader = ctx.gl().create_shader(glw::GL_VERTEX_SHADER);
        let not_a_program = deleted_program(ctx);

        ctx.begin_section("GL_INVALID_VALUE is generated if program is not a value generated by OpenGL.");
        ctx.gl().link_program(not_a_program);
        ctx.expect_error(glw::GL_INVALID_VALUE);
        ctx.end_section();

        ctx.begin_section("GL_INVALID_OPERATION is generated if program is not a program object.");
        ctx.gl().link_program(shader);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();

        ctx.gl().delete_shader(shader);
    }

    ctx.begin_section("GL_INVALID_OPERATION is generated if program is the currently active program object and transform feedback mode is active.");
    let program = simple_program(ctx);
    let mut buf: GLuint = 0;
    let mut tf_id: GLuint = 0;

    // SAFETY: as above.
    unsafe {
        ctx.gl().gen_transform_feedbacks(1, &mut tf_id);
        ctx.gl().gen_buffers(1, &mut buf);
    }
    begin_transform_feedback_on(ctx, &program, tf_id, buf, glw::GL_TRIANGLES);
    ctx.expect_error(glw::GL_NO_ERROR);

    // SAFETY: as above.
    unsafe {
        ctx.gl().link_program(program.program());
        ctx.expect_error(glw::GL_INVALID_OPERATION);

        ctx.gl().end_transform_feedback();
        ctx.gl().delete_transform_feedbacks(1, &tf_id);
        ctx.gl().delete_buffers(1, &buf);
    }
    ctx.expect_error(glw::GL_NO_ERROR);
    ctx.end_section();
    Ok(())
}

fn use_program(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    // SAFETY: as above.
    unsafe {
        let shader = ctx.gl().create_shader(glw::GL_VERTEX_SHADER);
        let not_a_program = deleted_program(ctx);

        ctx.begin_section("GL_INVALID_VALUE is generated if program is neither 0 nor a value generated by OpenGL.");
        ctx.gl().use_program(not_a_program);
        ctx.expect_error(glw::GL_INVALID_VALUE);
        ctx.end_section();

        ctx.begin_section("GL_INVALID_OPERATION is generated if program is not a program object.");
        ctx.gl().use_program(shader);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();

        ctx.gl().delete_shader(shader);
    }

    ctx.begin_section("GL_INVALID_OPERATION is generated if transform feedback mode is active and not paused.");
    let program1 = simple_program(ctx);
    let program2 = simple_program(ctx);
    let mut buf: GLuint = 0;
    let mut tf_id: GLuint = 0;

    // SAFETY: as above.
    unsafe {
        ctx.gl().gen_transform_feedbacks(1, &mut tf_id);
        ctx.gl().gen_buffers(1, &mut buf);
    }
    begin_transform_feedback_on(ctx, &program1, tf_id, buf, glw::GL_TRIANGLES);
    ctx.expect_error(glw::GL_NO_ERROR);

    // SAFETY: as above.
    unsafe {
        ctx.gl().use_program(program2.program());
        ctx.expect_error(glw::GL_INVALID_OPERATION);

        ctx.gl().pause_transform_feedback();
        ctx.gl().use_program(program2.program());
        ctx.expect_error(glw::GL_NO_ERROR);

        ctx.gl().end_transform_feedback();
        ctx.gl().delete_transform_feedbacks(1, &tf_id);
        ctx.gl().delete_buffers(1, &buf);
        ctx.expect_error(glw::GL_NO_ERROR);
        ctx.end_section();

        ctx.gl().use_program(0);
    }
    Ok(())
}

