/// `glUseProgram(0)` then every width of one uniform setter at location -1, each of which
/// must fail for want of a current program.
const NO_CURRENT_PROGRAM: &str = "GL_INVALID_OPERATION is generated if there is no current program object.";

/// The section every `*_invalid_location` case runs: an invalid location (-2) is an error,
/// while -1 is the documented "ignore this call" and must not be.
const INVALID_LOCATION: &str = "GL_INVALID_OPERATION is generated if location is an invalid uniform location for the current program object and location is not equal to -1.";

/// The section every `*_invalid_count` case runs.
const INVALID_COUNT: &str = "GL_INVALID_OPERATION is generated if count is greater than 1 and the indicated uniform variable is not an array variable.";

/// The section shared by the size-mismatch checks.
const SIZE_MISMATCH: &str = "GL_INVALID_OPERATION is generated if the size of the uniform variable declared in the shader does not match the size indicated by the ctx.glUniform command.";

/// The section shared by the sampler checks.
const SAMPLER_MISUSE: &str = "GL_INVALID_OPERATION is generated if a sampler is loaded using a command other than ctx.glUniform1i and ctx.glUniform1iv.";

