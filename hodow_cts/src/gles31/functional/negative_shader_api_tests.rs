/// The setup the four active-feedback cases share, stopping short of
/// `glBeginTransformFeedback`.
fn prepare_transform_feedback(
    ctx: &mut NegativeTestContext<'_>,
    program: &ShaderProgram<'_>,
    tf_id: GLuint,
    buf: GLuint,
) {
    // SAFETY: as in `begin_transform_feedback_on`.
    unsafe {
        ctx.gl().use_program(program.program());
        let varying = c"gl_Position".as_ptr();
        ctx.gl()
            .transform_feedback_varyings(program.program(), 1, &varying, glw::GL_INTERLEAVED_ATTRIBS);
        ctx.gl().link_program(program.program());
        ctx.gl().bind_transform_feedback(glw::GL_TRANSFORM_FEEDBACK, tf_id);
        ctx.gl().bind_buffer(glw::GL_TRANSFORM_FEEDBACK_BUFFER, buf);
        ctx.gl().buffer_data(
            glw::GL_TRANSFORM_FEEDBACK_BUFFER,
            32,
            std::ptr::null(),
            glw::GL_DYNAMIC_DRAW,
        );
        ctx.gl().bind_buffer_base(glw::GL_TRANSFORM_FEEDBACK_BUFFER, 0, buf);
    }
    ctx.expect_error(glw::GL_NO_ERROR);
}

fn begin_transform_feedback(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    let program = simple_program(ctx);
    let mut tf_id = [0 as GLuint; 2];
    let mut buf: GLuint = 0;

    // SAFETY: as above.
    unsafe {
        ctx.gl().gen_buffers(1, &mut buf);
        ctx.gl().gen_transform_feedbacks(2, tf_id.as_mut_ptr());
    }
    prepare_transform_feedback(ctx, &program, tf_id[0], buf);

    // SAFETY: as above.
    unsafe {
        ctx.begin_section(
            "GL_INVALID_ENUM is generated if primitiveMode is not one of GL_POINTS, GL_LINES, or GL_TRIANGLES.",
        );
        ctx.gl().begin_transform_feedback(BAD_ENUM);
        ctx.expect_error(glw::GL_INVALID_ENUM);
        ctx.end_section();

        ctx.begin_section("GL_INVALID_OPERATION is generated if transform feedback is already active.");
        ctx.gl().begin_transform_feedback(glw::GL_TRIANGLES);
        ctx.expect_error(glw::GL_NO_ERROR);
        ctx.gl().begin_transform_feedback(glw::GL_POINTS);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.gl().end_transform_feedback();
        ctx.end_section();

        ctx.begin_section("GL_INVALID_OPERATION is generated if any binding point used in transform feedback mode does not have a buffer object bound.");
        ctx.gl().bind_buffer_base(glw::GL_TRANSFORM_FEEDBACK_BUFFER, 0, 0);
        ctx.gl().begin_transform_feedback(glw::GL_TRIANGLES);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.gl().bind_buffer_base(glw::GL_TRANSFORM_FEEDBACK_BUFFER, 0, buf);
        ctx.end_section();

        ctx.begin_section(
            "GL_INVALID_OPERATION is generated if no binding points would be used because no program object is active.",
        );
        ctx.gl().use_program(0);
        ctx.gl().begin_transform_feedback(glw::GL_TRIANGLES);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.gl().use_program(program.program());
        ctx.end_section();

        ctx.begin_section("GL_INVALID_OPERATION is generated if no binding points would be used because the active program object has specified no varying variables to record.");
        ctx.gl()
            .transform_feedback_varyings(program.program(), 0, std::ptr::null(), glw::GL_INTERLEAVED_ATTRIBS);
        ctx.gl().link_program(program.program());
        ctx.expect_error(glw::GL_NO_ERROR);
        ctx.gl().begin_transform_feedback(glw::GL_TRIANGLES);
        ctx.expect_error(glw::GL_INVALID_OPERATION);
        ctx.end_section();

        ctx.gl().delete_buffers(1, &buf);
        ctx.gl().delete_transform_feedbacks(2, tf_id.as_ptr());
        ctx.expect_error(glw::GL_NO_ERROR);
    }
    Ok(())
}

