/// Compile one shader of `shader_type` from `source` and answer its name; the caller
/// deletes it.
///
/// # Safety
/// The source must have no interior NUL.
unsafe fn make_shader(ctx: &NegativeTestContext<'_>, shader_type: GLenum, source: &std::ffi::CStr) -> GLuint {
    // SAFETY: one source string, NUL-terminated, so no length array is needed.
    unsafe {
        let shader = ctx.gl().create_shader(shader_type);
        let ptr = source.as_ptr();
        ctx.gl().shader_source(shader, 1, &ptr, std::ptr::null());
        ctx.gl().compile_shader(shader);
        shader
    }
}

fn link_compute_shader(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    const COMPUTE_SOURCE: &std::ffi::CStr = c"#version 320 es\nvoid main (void)\n{\n}\n";
    const GEOMETRY_SOURCE: &std::ffi::CStr = c"#version 320 es\nlayout(max_vertices = 3) out;\nvoid main(void){}\n";
    const COMPUTE_SOURCE_310: &std::ffi::CStr = c"#version 310 es\nvoid main (void)\n{\n}\n";

    let shader_types = [
        glw::GL_VERTEX_SHADER,
        glw::GL_FRAGMENT_SHADER,
        glw::GL_GEOMETRY_SHADER,
        glw::GL_TESS_CONTROL_SHADER,
        glw::GL_TESS_EVALUATION_SHADER,
    ];

    // SAFETY: as above; every object is created and deleted here.
    unsafe {
        ctx.begin_section("Compute Shader linked with shader of other kind.");
        for shader_type in shader_types {
            let mut link_status: GLint = -1;
            let program = ctx.gl().create_program();
            let compute_shader = make_shader(ctx, glw::GL_COMPUTE_SHADER, COMPUTE_SOURCE);
            let other_source = if shader_type == glw::GL_GEOMETRY_SHADER {
                GEOMETRY_SOURCE
            } else {
                COMPUTE_SOURCE
            };
            let other_shader = make_shader(ctx, shader_type, other_source);

            ctx.gl().attach_shader(program, compute_shader);
            ctx.gl().attach_shader(program, other_shader);
            ctx.gl().link_program(program);
            ctx.gl().get_programiv(program, glw::GL_LINK_STATUS, &mut link_status);
            ctx.gl().delete_shader(other_shader);
            ctx.gl().delete_shader(compute_shader);
            ctx.gl().delete_program(program);
            if link_status != glw::GL_FALSE as GLint {
                ctx.fail("Program should not have linked");
            }
        }
        ctx.end_section();

        ctx.begin_section("Compute Shader should not be linked with shaders of different version.");
        let mut link_status: GLint = -1;
        let program = ctx.gl().create_program();
        let compute_shader = make_shader(ctx, glw::GL_COMPUTE_SHADER, COMPUTE_SOURCE);
        // \note upstream names this `computeShader310` but creates a *fragment* shader.
        let other_shader = make_shader(ctx, glw::GL_FRAGMENT_SHADER, COMPUTE_SOURCE_310);

        ctx.gl().attach_shader(program, compute_shader);
        ctx.gl().attach_shader(program, other_shader);
        ctx.gl().link_program(program);
        ctx.gl().get_programiv(program, glw::GL_LINK_STATUS, &mut link_status);
        ctx.gl().delete_shader(other_shader);
        ctx.gl().delete_shader(compute_shader);
        ctx.gl().delete_program(program);
        if link_status != glw::GL_FALSE as GLint {
            ctx.fail("Program should not have linked");
        }
        ctx.end_section();
    }
    Ok(())
}

fn compile_compute_shader(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    /// Each deliberately-malformed compute shader and the reason it must not compile.
    const SOURCES: &[(&std::ffi::CStr, &str)] = &[
        (
            c"#version 300 es\nvoid main (void)\n{\n}\n",
            "Compute Shader should not have compiled with #version 300 es.",
        ),
        (
            c"#version 310 es\nbuffer SSBO { vec4 data }void main (void)\n{\n}\n",
            "Compute Shader should not have compiled: incorrect SSBO syntax.",
        ),
        (
            c"#version 310 es\nbuffer SSBO { vec4 data;};uniform mat4 data;void main (void)\n{\n}\n",
            "Compute Shader should not have compiled: buffer variable redefinition.",
        ),
        (
            c"#version 310 es\nbuffer SSBO { vec4 data[]; vec4 moreData;};void main (void)\n{\n}\n",
            "Compute Shader should not have compiled: unspecified length buffer member not at the end.",
        ),
        (
            c"#version 310 es\nin vec4 data;void main (void)\n{\n}\n",
            "Compute Shader should not have compiled: input qualifier used.",
        ),
        (
            c"#version 310 es\nshared uint data = 0;",
            "Compute Shader should not have compiled: shared-qualified variable initialized.",
        ),
        (
            c"#version 310 es\nbuffer SSBO { vec4 data; vec4 moreData[];} ssbo;void test (vec4 data[10]) {}void main (void)\n{\n    test(ssbo.moreData);}\n",
            "Compute Shader should not have compiled: unspecified length buffer member passed as argument to function.",
        ),
        (
            c"#version 310 es\nbuffer SSBO { vec4 data; vec4 moreData[];} ssbo;void main (void)\n{\n    vec4 var = ssbo.moreData[-1];}\n",
            "Compute Shader should not have compiled: unspecified length buffer member indexed with negative constant expression.",
        ),
        (
            c"#version 310 es\nlayout(binding=-1) buffer SSBO { vec4 data;};void main (void)\n{\n}\n",
            "Compute Shader should not have compiled: binding point less than zero.",
        ),
        (
            c"#version 310 es\nlayout(binding=1) buffer;layout(binding=2) buffer SSBO { vec4 data;};void main (void)\n{\n}\n",
            "Compute Shader should not have compiled: binding point specified for global scope.",
        ),
        (
            c"#version 310 es\nbuffer SSBO {    layout(binding=1) vec4 data;    layout(binding=2) vec4 moreData[];} ssbo;void main (void)\n{\n}\n",
            "Compute Shader should not have compiled: binding point specified for block member declarations.",
        ),
        (
            c"#version 310 es\nreadonly buffer SSBO {vec4 data;} ssbo;void main (void)\n{\nssbo.data = vec4(1, 1, 1, 1);}\n",
            "Compute Shader should not have compiled: writing to buffer block qualified with readonly.",
        ),
        (
            c"#version 310 es\nwriteonly buffer SSBO {vec4 data;} ssbo;void main (void)\n{\nvec4 var = ssbo.data;}\n",
            "Compute Shader should not have compiled: reading from buffer block qualified with writeonly.",
        ),
    ];

    ctx.begin_section("Compile Computer Shader");
    for (source, message) in SOURCES {
        // SAFETY: as above; the shader is created and deleted here.
        let compile_status = unsafe {
            let shader = make_shader(ctx, glw::GL_COMPUTE_SHADER, source);
            let mut status: GLint = -1;
            ctx.gl().get_shaderiv(shader, glw::GL_COMPILE_STATUS, &mut status);
            ctx.gl().delete_shader(shader);
            status
        };

        if compile_status != glw::GL_FALSE as GLint {
            ctx.fail(*message);
        }
    }
    ctx.end_section();
    Ok(())
}

/// The section every `srgb_decode_*` case runs.
const SRGB_DECODE_SECTION: &str = "GL_INVALID_ENUM is generated if pname is GL_TEXTURE_SRGB_DECODE_EXT and the value of param(s) is not a valid value (one of DECODE_EXT, or SKIP_DECODE_EXT).";

/// `GL_EXT_texture_sRGB_decode` is what every `srgb_decode_*` case needs.
fn check_srgb_decode(ctx: &NegativeTestContext<'_>) -> Result<(), TestError> {
    if ctx.is_extension_supported("GL_EXT_texture_sRGB_decode") {
        Ok(())
    } else {
        Err(TestError::NotSupported(
            "GL_EXT_texture_sRGB_decode is not supported.".to_string(),
        ))
    }
}

fn srgb_decode_samplerparameteri(ctx: &mut NegativeTestContext<'_>) -> Result<(), TestError> {
    check_srgb_decode(ctx)?;
    let mut sampler: GLuint = 0x1234;

    // SAFETY: as above.
    unsafe {
        ctx.gl().gen_samplers(1, &mut sampler);

        ctx.begin_section(SRGB_DECODE_SECTION);
        ctx.gl()
            .sampler_parameteri(sampler, glw::GL_TEXTURE_SRGB_DECODE_EXT, -1);
        ctx.expect_error(glw::GL_INVALID_ENUM);
        ctx.end_section();

        ctx.gl().delete_samplers(1, &sampler);
    }
    Ok(())
}

