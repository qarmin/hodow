/// `OpaqueTypeIndexingTests::init`
pub fn create_tests() -> TestCaseGroup {
    let mut group = TestCaseGroup::new("opaque_type_indexing");

    // .sampler
    {
        let mut sampler_group = TestCaseGroup::new("sampler");
        for &(index_expr_type, index_name) in &INDEXING_TYPES {
            let mut index_group = TestCaseGroup::new(index_name);
            for &(shader_type, shader_name) in &SHADER_TYPES {
                let mut shader_group = TestCaseGroup::new(shader_name);
                for &sampler_type in &SAMPLER_TYPES {
                    let case_name = sampler_type.name().to_lowercase();
                    shader_group.add_child(Box::new(SamplerIndexingCase {
                        case_name,
                        shader_type,
                        sampler_type,
                        index_expr_type,
                    }) as Box<dyn TestCase>);
                }
                index_group.add_child(shader_group);
            }
            sampler_group.add_child(index_group);
        }
        group.add_child(sampler_group);
    }

    // .ubo / .ssbo / .atomic_counter
    {
        let mut ubo_group = TestCaseGroup::new("ubo");
        let mut ssbo_group = TestCaseGroup::new("ssbo");
        let mut atomic_group = TestCaseGroup::new("atomic_counter");

        for &(index_expr_type, index_name) in &INDEXING_TYPES {
            for &(shader_type, shader_name) in &SHADER_TYPES {
                let name = format!("{index_name}_{shader_name}");

                ubo_group.add_child(Box::new(BlockArrayIndexingCase {
                    case_name: name.clone(),
                    block_type: BlockType::Uniform,
                    index_expr_type,
                    shader_type,
                }) as Box<dyn TestCase>);
                atomic_group.add_child(Box::new(AtomicCounterIndexingCase {
                    case_name: name.clone(),
                    index_expr_type,
                    shader_type,
                }) as Box<dyn TestCase>);

                if matches!(
                    index_expr_type,
                    IndexExprType::ConstLiteral | IndexExprType::ConstExpression
                ) {
                    ssbo_group.add_child(Box::new(BlockArrayIndexingCase {
                        case_name: name,
                        block_type: BlockType::Buffer,
                        index_expr_type,
                        shader_type,
                    }) as Box<dyn TestCase>);
                }
            }
        }

        group.add_child(ubo_group);
        group.add_child(ssbo_group);
        group.add_child(atomic_group);
    }

    group
}
