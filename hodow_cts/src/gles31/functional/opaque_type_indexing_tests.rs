/// A stable integer per `glu::ShaderType` value, for seeding this port's own PRNG -
/// it need not agree with upstream's own enum numbering (see the module header).
fn shader_type_seed(shader_type: ShaderType) -> i32 {
    match shader_type {
        ShaderType::Vertex => 0,
        ShaderType::Fragment => 1,
        ShaderType::Geometry => 2,
        ShaderType::TessControl => 3,
        ShaderType::TessEvaluation => 4,
        ShaderType::Compute => 5,
    }
}

/// `#extension GL_EXT_gpu_shader5 : require` - needed for `Uniform`/`DynamicUniform`
/// indexing on a context below ES 3.2.
fn dynamic_index_pragma(supports_es32: bool, index_expr_type: IndexExprType) -> &'static str {
    if !supports_es32 && matches!(index_expr_type, IndexExprType::Uniform | IndexExprType::DynamicUniform) {
        "#extension GL_EXT_gpu_shader5 : require\n"
    } else {
        ""
    }
}

fn check_ext(context: &Context, ext: &str) -> Result<(), TestError> {
    if context.context_info.is_extension_supported(ext) {
        Ok(())
    } else {
        Err(TestError::NotSupported(format!("{ext} extension is required")))
    }
}

fn get_integer(gl: &glw::Functions, pname: u32) -> Result<i32, TestError> {
    let mut value = 0;
    // SAFETY: every pname passed here is a single-integer query.
    unsafe { gl.get_integerv(pname, &mut value) };
    glu::expect_no_error(gl, "glGetIntegerv()")?;
    Ok(value)
}

/// The stage/index-expression support check shared by all three case shapes -
/// `SamplerIndexingCase::init`/`BlockArrayIndexingCase::init`/
/// `AtomicCounterIndexingCase::init`'s common prefix.
fn check_stage_and_index_support(
    context: &Context,
    shader_type: ShaderType,
    index_expr_type: IndexExprType,
) -> Result<(), TestError> {
    let supports_es32 = context.context_type().supports(3, 2);
    if !supports_es32 {
        match shader_type {
            ShaderType::Geometry => check_ext(context, "GL_EXT_geometry_shader")?,
            ShaderType::TessControl | ShaderType::TessEvaluation => check_ext(context, "GL_EXT_tessellation_shader")?,
            ShaderType::Vertex | ShaderType::Fragment | ShaderType::Compute => {}
        }
        if !matches!(
            index_expr_type,
            IndexExprType::ConstLiteral | IndexExprType::ConstExpression
        ) {
            check_ext(context, "GL_EXT_gpu_shader5")?;
        }
    }
    Ok(())
}

fn upload_uniform_indices(
    gl: &glw::Functions,
    program: GLuint,
    prefix: &str,
    indices: &[i32],
) -> Result<(), TestError> {
    for (ndx, &value) in indices.iter().enumerate() {
        let name = format!("{prefix}{ndx}");
        let c_name = CString::new(name.clone()).expect("uniform name has no interior NUL");
        // SAFETY: `program` is linked - checked by every caller before reaching this.
        let loc = unsafe { gl.get_uniform_location(program, c_name.as_ptr()) };
        if loc < 0 {
            return Err(TestError::Fail(format!("No location assigned for uniform '{name}'")));
        }
        // SAFETY: `loc` was just checked non-negative.
        unsafe { gl.uniform_1i(loc, value) };
    }
    Ok(())
}

/// Every executor readback comes back as native-endian `u32` words - one per output
/// scalar, in declaration order (see `FragmentOutExecutor`/`BufferIo`'s own readback
/// code in `gls::shader_exec_util`).
fn words_from_bytes(bytes: &[u8]) -> Vec<u32> {
    let (chunks, remainder) = bytes.as_chunks::<4>();
    debug_assert!(
        remainder.is_empty(),
        "executor readback is always a whole number of 4-byte words"
    );
    chunks.iter().map(|word| u32::from_ne_bytes(*word)).collect()
}

