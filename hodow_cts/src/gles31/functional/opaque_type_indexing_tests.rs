fn run_atomic_case(context: &Context, index_expr_type: IndexExprType, shader_type: ShaderType) -> TestOutcome {
    check_stage_and_index_support(context, shader_type, index_expr_type)?;
    let gl = context.gl();
    let num_counters = get_integer(gl, max_atomic_counters_pname(shader_type))?;
    if num_counters < 1 {
        return Err(TestError::NotSupported(format!(
            "Atomic counters not supported in {} shader",
            shader_type.as_str()
        )));
    }

    let num_invocations = 32i32;
    let num_ops = 4i32;

    let mut rnd = Random::new(de_int32_hash(shader_type_seed(shader_type)) ^ de_int32_hash(index_expr_type as i32));
    let op_indices: Vec<i32> = (0..num_ops).map(|_| rnd.get_int(0, num_ops - 1)).collect();

    let spec = build_atomic_shader_spec(context, index_expr_type, num_counters, num_ops, &op_indices);

    let mut out_values = vec![0u32; (num_invocations * num_ops) as usize];
    let mut counter_values = vec![0u32; num_counters as usize];

    {
        let counter_buffer = Buffer::new(gl);

        let executor = shader_exec_util::create_executor(&context.render_context, shader_type, &spec)?;
        if !executor.is_ok() {
            return Err(TestError::Fail(format!(
                "Compile failed: {}",
                executor.build_failure_summary().unwrap_or_default()
            )));
        }

        {
            let buf_size = get_program_resource_int(
                gl,
                executor.program(),
                glw::GL_ATOMIC_COUNTER_BUFFER,
                0,
                glw::GL_BUFFER_DATA_SIZE,
            )?;
            let max_ndx = *op_indices.iter().max().expect("num_ops > 0");
            if buf_size < (max_ndx + 1) * 4 {
                return Err(TestError::Fail(format!("GL reported invalid buffer size {buf_size}")));
            }
            let empty_data = vec![0u8; num_counters as usize * 4];
            // SAFETY: `counter_buffer` is a name this case owns, sized to exactly the
            // zeroed data supplied.
            unsafe {
                gl.bind_buffer(glw::GL_ATOMIC_COUNTER_BUFFER, counter_buffer.get());
                gl.buffer_data(
                    glw::GL_ATOMIC_COUNTER_BUFFER,
                    empty_data.len() as isize,
                    empty_data.as_ptr().cast(),
                    glw::GL_STATIC_DRAW,
                );
                gl.bind_buffer_base(glw::GL_ATOMIC_COUNTER_BUFFER, 0, counter_buffer.get());
            }
            glu::expect_no_error(gl, "Atomic counter buffer initialization failed")?;
        }

        executor.use_program(gl);

        let mut expanded_indices: Vec<i32> = Vec::new();
        let mut inputs: Vec<&[u8]> = Vec::new();
        if index_expr_type == IndexExprType::DynamicUniform {
            expanded_indices.resize((num_invocations * num_ops) as usize, 0);
            for (op_ndx, &op_index) in op_indices.iter().enumerate() {
                let start = op_ndx * num_invocations as usize;
                for v in &mut expanded_indices[start..start + num_invocations as usize] {
                    *v = op_index;
                }
            }
            for op_ndx in 0..num_ops as usize {
                let start = op_ndx * num_invocations as usize;
                // SAFETY: as in `run_block_case` above.
                let bytes = unsafe {
                    std::slice::from_raw_parts(
                        expanded_indices[start..].as_ptr().cast::<u8>(),
                        num_invocations as usize * 4,
                    )
                };
                inputs.push(bytes);
            }
        } else if index_expr_type == IndexExprType::Uniform {
            upload_uniform_indices(gl, executor.program(), "index", &op_indices)?;
        }

        glu::expect_no_error(gl, "Setup failed")?;

        let mut out_bytes = vec![0u8; out_values.len() * 4];
        {
            let mut output_slices: Vec<&mut [u8]> = out_bytes.chunks_exact_mut(num_invocations as usize * 4).collect();
            executor.execute(num_invocations, &inputs, &mut output_slices)?;
        }
        out_values = words_from_bytes(&out_bytes);

        // SAFETY: the buffer was just bound and sized above; the barrier the map
        // implies is what makes the shader's atomic increments visible to this read.
        unsafe { gl.bind_buffer(glw::GL_ATOMIC_COUNTER_BUFFER, counter_buffer.get()) };
        let map = BufferMemMap::new(
            gl,
            glw::GL_ATOMIC_COUNTER_BUFFER,
            0,
            (num_counters * 4) as isize,
            glw::GL_MAP_READ_BIT,
        )
        .ok_or_else(|| TestError::Fail("glMapBufferRange() returned null".to_string()))?;
        // SAFETY: the mapping covers exactly `num_counters` readable `u32`s, just
        // requested above.
        let src = unsafe { std::slice::from_raw_parts(map.get().cast::<u32>(), num_counters as usize) };
        counter_values.copy_from_slice(src);
    }

    let mut num_hits = vec![0i32; num_counters as usize];
    for &idx in &op_indices {
        num_hits[idx as usize] += 1;
    }

    for counter_ndx in 0..num_counters as usize {
        let ref_count = (num_hits[counter_ndx] * num_invocations) as u32;
        let res_count = counter_values[counter_ndx];
        if ref_count != res_count {
            return Ok(TestStatus::fail(format!(
                "ERROR: atomic counter {counter_ndx} has value {res_count}, expected {ref_count}"
            )));
        }
    }

    let mut counter_masks: Vec<Vec<bool>> = (0..num_counters as usize)
        .map(|c| vec![false; (num_hits[c] * num_invocations) as usize])
        .collect();
    for invocation_ndx in 0..num_invocations as usize {
        for op_ndx in 0..num_ops as usize {
            let counter_ndx = op_indices[op_ndx] as usize;
            let res_value = out_values[op_ndx * num_invocations as usize + invocation_ndx];
            let in_range = (res_value as usize) < counter_masks[counter_ndx].len();
            if !in_range || counter_masks[counter_ndx][res_value as usize] {
                return Ok(TestStatus::fail(format!(
                    "ERROR: at invocation {invocation_ndx}, op {op_ndx}: got invalid result value {res_value}"
                )));
            }
            counter_masks[counter_ndx][res_value as usize] = true;
        }
    }

    Ok(TestStatus::pass("Pass"))
}

