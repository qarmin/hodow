#[derive(Clone, Copy, PartialEq, Eq)]
enum BlockType {
    Uniform,
    Buffer,
}

fn max_shader_storage_blocks_pname(shader_type: ShaderType) -> u32 {
    match shader_type {
        ShaderType::Vertex => glw::GL_MAX_VERTEX_SHADER_STORAGE_BLOCKS,
        ShaderType::Fragment => glw::GL_MAX_FRAGMENT_SHADER_STORAGE_BLOCKS,
        ShaderType::Geometry => glw::GL_MAX_GEOMETRY_SHADER_STORAGE_BLOCKS,
        ShaderType::TessControl => glw::GL_MAX_TESS_CONTROL_SHADER_STORAGE_BLOCKS,
        ShaderType::TessEvaluation => glw::GL_MAX_TESS_EVALUATION_SHADER_STORAGE_BLOCKS,
        ShaderType::Compute => glw::GL_MAX_COMPUTE_SHADER_STORAGE_BLOCKS,
    }
}

fn build_block_shader_spec(
    context: &Context,
    block_type: BlockType,
    index_expr_type: IndexExprType,
    num_instances: i32,
    num_reads: i32,
    read_indices: &[i32],
) -> ShaderSpec {
    let supports_es32 = context.context_type().supports(3, 2);
    let mut spec = ShaderSpec::new(if supports_es32 {
        glu::GlslVersion::Es320
    } else {
        glu::GlslVersion::Es310
    });

    let mut global = String::new();
    global.push_str(dynamic_index_pragma(supports_es32, index_expr_type));
    if index_expr_type == IndexExprType::ConstExpression {
        global.push_str("const highp int indexBase = 1;\n");
    }
    let (interface_name, layout) = if block_type == BlockType::Uniform {
        ("uniform", "std140")
    } else {
        ("buffer", "std430")
    };
    let _ = writeln!(
        global,
        "layout({layout}, binding = 2) {interface_name} Block\n{{\n    highp uint value;\n}} block[{num_instances}];"
    );

    if index_expr_type == IndexExprType::DynamicUniform {
        for read_ndx in 0..num_reads {
            spec.inputs.push(Symbol::new(
                format!("index{read_ndx}"),
                VarType::basic(DataType::Int, Some(Precision::HighP)),
            ));
        }
    } else if index_expr_type == IndexExprType::Uniform {
        for read_ndx in 0..num_reads {
            let _ = writeln!(global, "uniform highp int index{read_ndx};");
        }
    }

    for read_ndx in 0..num_reads {
        spec.outputs.push(Symbol::new(
            format!("result{read_ndx}"),
            VarType::basic(DataType::Uint, Some(Precision::HighP)),
        ));
    }

    let mut code = String::new();
    for (read_ndx, &read_index) in read_indices.iter().enumerate() {
        let idx_expr = match index_expr_type {
            IndexExprType::ConstLiteral => read_index.to_string(),
            IndexExprType::ConstExpression => format!("indexBase + {}", read_index - 1),
            IndexExprType::Uniform | IndexExprType::DynamicUniform => format!("index{read_ndx}"),
        };
        let _ = writeln!(code, "result{read_ndx} = block[{idx_expr}].value;");
    }

    spec.global_declarations = global;
    spec.source = code;
    spec
}

fn run_block_case(
    context: &Context,
    block_type: BlockType,
    index_expr_type: IndexExprType,
    shader_type: ShaderType,
) -> TestOutcome {
    check_stage_and_index_support(context, shader_type, index_expr_type)?;
    if block_type == BlockType::Buffer {
        let max_blocks = get_integer(context.gl(), max_shader_storage_blocks_pname(shader_type))?;
        if max_blocks < 2 + 4 {
            return Err(TestError::NotSupported(
                "Not enough shader storage blocks supported for shader type".to_string(),
            ));
        }
    }

    let num_invocations = 32i32;
    let num_instances = 4i32;
    let num_reads = 4i32;

    let mut rnd = Random::new(
        de_int32_hash(shader_type_seed(shader_type))
            ^ de_int32_hash(block_type as i32)
            ^ de_int32_hash(index_expr_type as i32),
    );
    let read_indices: Vec<i32> = (0..num_reads).map(|_| rnd.get_int(0, num_instances - 1)).collect();
    let in_values: Vec<u32> = (0..num_instances).map(|_| rnd.get_uint32()).collect();

    let spec = build_block_shader_spec(
        context,
        block_type,
        index_expr_type,
        num_instances,
        num_reads,
        &read_indices,
    );

    let mut out_values = vec![0u32; (num_invocations * num_reads) as usize];

    {
        let gl = context.gl();
        let base_binding = 2u32;
        let buf_target = if block_type == BlockType::Buffer {
            glw::GL_SHADER_STORAGE_BUFFER
        } else {
            glw::GL_UNIFORM_BUFFER
        };
        let buffers: Vec<Buffer<'_>> = (0..num_instances).map(|_| Buffer::new(gl)).collect();

        let executor = shader_exec_util::create_executor(&context.render_context, shader_type, &spec)?;
        if !executor.is_ok() {
            return Err(TestError::Fail(format!(
                "Compile failed: {}",
                executor.build_failure_summary().unwrap_or_default()
            )));
        }
        executor.use_program(gl);

        for instance_ndx in 0..num_instances as usize {
            // SAFETY: each buffer is sized to hold exactly the one `u32` written into it.
            unsafe {
                gl.bind_buffer(buf_target, buffers[instance_ndx].get());
                gl.buffer_data(
                    buf_target,
                    4,
                    (&raw const in_values[instance_ndx]).cast(),
                    glw::GL_STATIC_DRAW,
                );
                gl.bind_buffer_base(
                    buf_target,
                    base_binding + instance_ndx as u32,
                    buffers[instance_ndx].get(),
                );
            }
        }

        let mut expanded_indices: Vec<i32> = Vec::new();
        let mut inputs: Vec<&[u8]> = Vec::new();
        if index_expr_type == IndexExprType::DynamicUniform {
            expanded_indices.resize((num_invocations * num_reads) as usize, 0);
            for (read_ndx, &read_index) in read_indices.iter().enumerate() {
                let start = read_ndx * num_invocations as usize;
                for v in &mut expanded_indices[start..start + num_invocations as usize] {
                    *v = read_index;
                }
            }
            for read_ndx in 0..num_reads as usize {
                let start = read_ndx * num_invocations as usize;
                // SAFETY: reinterpreting this `Vec<i32>`'s own storage as bytes, the
                // same convention every executor input uses.
                let bytes = unsafe {
                    std::slice::from_raw_parts(
                        expanded_indices[start..].as_ptr().cast::<u8>(),
                        num_invocations as usize * 4,
                    )
                };
                inputs.push(bytes);
            }
        } else if index_expr_type == IndexExprType::Uniform {
            upload_uniform_indices(gl, executor.program(), "index", &read_indices)?;
        }

        glu::expect_no_error(gl, "Setup failed")?;

        let mut out_bytes = vec![0u8; out_values.len() * 4];
        {
            let mut output_slices: Vec<&mut [u8]> = out_bytes.chunks_exact_mut(num_invocations as usize * 4).collect();
            executor.execute(num_invocations, &inputs, &mut output_slices)?;
        }
        out_values = words_from_bytes(&out_bytes);
    }

    for invocation_ndx in 0..num_invocations as usize {
        for read_ndx in 0..num_reads as usize {
            let reference = in_values[read_indices[read_ndx] as usize];
            let result = out_values[read_ndx * num_invocations as usize + invocation_ndx];
            if reference != result {
                return Ok(TestStatus::fail(format!(
                    "ERROR: at invocation {invocation_ndx}, read {read_ndx}: expected {reference:#x}, got {result:#x}"
                )));
            }
        }
    }

    Ok(TestStatus::pass("Pass"))
}

