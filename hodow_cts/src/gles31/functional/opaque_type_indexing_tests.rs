// Three case shapes, each registered once per shader stage
// `gls::shader_exec_util` can build a program for (all six, now that it has Geometry/
// TessControl/TessEvaluation executors too - see that module's header on why this group
// is what needed them, unlike `builtin_constants`): `SamplerIndexingCase` reads through a
// `uniform sampler[8]` array, `BlockArrayIndexingCase` through a UBO or SSBO instance
// array, `AtomicCounterIndexingCase` through an `atomic_uint counter[]` array. Every
// input value is generated by this port's own `tcu::random::Random`, not upstream's
// `de::Random` - `diff_vs_deqp.py` only ever compares a verdict category (Pass/Fail/
// NotSupported/...), never a logged value, so the two sides need not agree on which
// "random" bytes went into a texture or a buffer, only on what verdict the shader
// produces from whichever bytes each side chose.
//
// 1D-texture sampler types are excluded - upstream's own `samplerTypes` table comments
// them out ("1D images will be added by a later extension") and never instantiates a
// case for them, so `TextureType` here has no 1D variant either.
// `gather`/`scatter`-style bulk sampling and `SamplerBuffer`/multisample sampler types
// are equally out of scope: upstream's own indexing tests never touch them.

