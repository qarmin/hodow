/// `s_valueRange` - the range a non-normalizing loader's values are scaled into.
const VALUE_RANGE: i32 = 10;

/// `AttributeCase::RENDER_SIZE`
const RENDER_SIZE: i32 = 32;

/// Which module's shaders and loader set to use.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum EsVersion {
    Es2,
    Es3,
}

/// One of upstream's twelve `FloatLoader` classes.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Loader {
    /// `glVertexAttrib{1,2,3,4}f`
    FloatDirect(u32),
    /// `glVertexAttrib{1,2,3,4}fv`
    FloatIndirect(u32),
    /// `glVertexAttribI4i`
    IntDirect,
    /// `glVertexAttribI4iv`
    IntIndirect,
    /// `glVertexAttribI4ui`
    UintDirect,
    /// `glVertexAttribI4uiv`
    UintIndirect,
}

impl Loader {
    /// `LoaderType::COMPONENTS`
    fn components(self) -> u32 {
        match self {
            Self::FloatDirect(n) | Self::FloatIndirect(n) => n,
            _ => 4,
        }
    }

    /// `LoaderType::getCaseName`
    fn case_name(self) -> &'static str {
        match self {
            Self::FloatDirect(1) => "vertex_attrib_1f",
            Self::FloatDirect(2) => "vertex_attrib_2f",
            Self::FloatDirect(3) => "vertex_attrib_3f",
            Self::FloatDirect(_) => "vertex_attrib_4f",
            Self::FloatIndirect(1) => "vertex_attrib_1fv",
            Self::FloatIndirect(2) => "vertex_attrib_2fv",
            Self::FloatIndirect(3) => "vertex_attrib_3fv",
            Self::FloatIndirect(_) => "vertex_attrib_4fv",
            Self::IntDirect => "vertex_attribi_4i",
            Self::IntIndirect => "vertex_attribi_4iv",
            Self::UintDirect => "vertex_attribi_4ui",
            Self::UintIndirect => "vertex_attribi_4uiv",
        }
    }

    /// `std::numeric_limits<LoaderType::Type>::is_signed`, which is what upstream passes
    /// as `useNegative` - the unsigned loaders are the only ones tested with a
    /// non-negative range.
    fn use_negative(self) -> bool {
        !matches!(self, Self::UintDirect | Self::UintIndirect)
    }

    /// `FloatLoader::load` - sets the default attribute and returns the value the shader
    /// will see, which is the loader's own type after truncation and the `(0,0,0,1)`
    /// fill-in for the components it does not carry.
    fn load(self, gl: &glw::Functions, index: GLint, v: Vec4) -> Vec4 {
        let components = self.components() as usize;
        let src = [v.x(), v.y(), v.z(), v.w()];

        // `convertToTypeVec<Type, COMPONENTS>` then `convertToTypeVec<float, 4>`: the
        // second pass fills w with 1 before copying, so a loader narrower than 4 leaves
        // alpha at 1 and everything past its own width at 0.
        let mut loaded = [0.0f32, 0.0, 0.0, 1.0];

        // SAFETY: each entry point is given exactly the component count it names, and
        // the indirect ones a pointer to an array of that many elements.
        unsafe {
            match self {
                Self::FloatDirect(_) | Self::FloatIndirect(_) => {
                    let value: Vec<f32> = src[..components].to_vec();
                    for (dst, v) in loaded.iter_mut().zip(&value) {
                        *dst = *v;
                    }

                    match (self, components) {
                        (Self::FloatDirect(_), 1) => gl.vertex_attrib_1f(index as u32, value[0]),
                        (Self::FloatDirect(_), 2) => gl.vertex_attrib_2f(index as u32, value[0], value[1]),
                        (Self::FloatDirect(_), 3) => gl.vertex_attrib_3f(index as u32, value[0], value[1], value[2]),
                        (Self::FloatDirect(_), _) => {
                            gl.vertex_attrib_4f(index as u32, value[0], value[1], value[2], value[3])
                        }
                        (_, 1) => gl.vertex_attrib_1fv(index as u32, value.as_ptr()),
                        (_, 2) => gl.vertex_attrib_2fv(index as u32, value.as_ptr()),
                        (_, 3) => gl.vertex_attrib_3fv(index as u32, value.as_ptr()),
                        (_, _) => gl.vertex_attrib_4fv(index as u32, value.as_ptr()),
                    }
                }
                Self::IntDirect | Self::IntIndirect => {
                    let value: Vec<i32> = src.iter().map(|c| *c as i32).collect();
                    for (dst, v) in loaded.iter_mut().zip(&value) {
                        *dst = *v as f32;
                    }

                    if self == Self::IntDirect {
                        gl.vertex_attrib_i_4i(index as u32, value[0], value[1], value[2], value[3]);
                    } else {
                        gl.vertex_attrib_i_4iv(index as u32, value.as_ptr());
                    }
                }
                Self::UintDirect | Self::UintIndirect => {
                    let value: Vec<u32> = src.iter().map(|c| *c as u32).collect();
                    for (dst, v) in loaded.iter_mut().zip(&value) {
                        *dst = *v as f32;
                    }

                    if self == Self::UintDirect {
                        gl.vertex_attrib_i_4ui(index as u32, value[0], value[1], value[2], value[3]);
                    } else {
                        gl.vertex_attrib_i_4uiv(index as u32, value.as_ptr());
                    }
                }
            }
        }

        Vec4::new(loaded[0], loaded[1], loaded[2], loaded[3])
    }
}

/// `AttributeCase`
struct AttributeCase {
    name: String,
    es_version: EsVersion,
    loader: Loader,
    data_type: DataType,
}

/// `AttributeCase::iterate`'s `testValues`
const TEST_VALUES: [[f32; 4]; 7] = [
    [0.0, 0.5, 0.2, 1.0],
    [0.1, 0.7, 1.0, 0.6],
    [0.4, 0.2, 0.0, 0.5],
    [0.5, 0.0, 0.9, 0.1],
    [0.6, 0.2, 0.2, 0.9],
    [0.9, 1.0, 0.0, 0.0],
    [1.0, 0.5, 0.3, 0.8],
];

impl AttributeCase {
    /// `AttributeCase::genVertexSource`
    fn gen_vertex_source(&self) -> String {
        let is_matrix = self.data_type.is_matrix();
        let vector_size = if is_matrix {
            self.data_type.matrix_num_rows()
        } else if self.data_type.is_vector() {
            self.data_type.scalar_size()
        } else {
            -1
        };
        let vector_type = if is_matrix || self.data_type.is_vector() {
            glu::get_data_type_vector(DataType::Float, vector_size).name()
        } else {
            DataType::Float.name()
        };
        let components = if is_matrix {
            self.data_type.matrix_num_rows()
        } else {
            self.data_type.scalar_size()
        };

        let mut src = match self.es_version {
            EsVersion::Es2 => format!(
                "attribute highp vec4 a_position;\n\
                 attribute highp {} a_value;\n\
                 varying highp vec4 v_color;\n\
                 void main (void)\n\
                 {{\n    \
                 gl_Position = a_position;\n\
                 \n",
                self.data_type.name()
            ),
            EsVersion::Es3 => format!(
                "#version 300 es\n\
                 in highp vec4 a_position;\n\
                 in highp {} a_value;\n\
                 out highp vec4 v_color;\n\
                 void main (void)\n\
                 {{\n    \
                 gl_Position = a_position;\n\
                 \n",
                self.data_type.name()
            ),
        };

        // An integer attribute has to be cast before it can be divided; a float one is
        // left alone, which is what the empty prefix is.
        let cast = if self.data_type.scalar_type() == DataType::Float {
            ""
        } else {
            vector_type
        };
        let column = if is_matrix { "[1]" } else { "" };

        // No loader here normalizes, so the value is always scaled down by the range.
        src.push_str(&format!(
            "    highp {vector_type} normalizedValue = {cast}(a_value{column}) / float({VALUE_RANGE});\n"
        ));

        if self.loader.use_negative() {
            src.push_str(&format!(
                "    highp {vector_type} positiveNormalizedValue = (normalizedValue + {vector_type}(1.0)) / 2.0;\n"
            ));
        } else {
            src.push_str(&format!(
                "    highp {vector_type} positiveNormalizedValue = normalizedValue;\n"
            ));
        }

        src.push_str(match components {
            1 => "    v_color = vec4(positiveNormalizedValue, 0.0, 0.0, 1.0);\n",
            2 => "    v_color = vec4(positiveNormalizedValue.xy, 0.0, 1.0);\n",
            3 => "    v_color = vec4(positiveNormalizedValue.xyz, 1.0);\n",
            _ => "    v_color = vec4((positiveNormalizedValue.xy + positiveNormalizedValue.zz) / 2.0, positiveNormalizedValue.w, 1.0);\n",
        });

        src.push_str("}\n");
        src
    }

    /// `s_passThroughFragmentShaderSource`
    fn fragment_source(&self) -> &'static str {
        match self.es_version {
            EsVersion::Es2 => "varying mediump vec4 v_color;\nvoid main (void)\n{\n    gl_FragColor = v_color;\n}\n",
            EsVersion::Es3 => {
                "#version 300 es\n\
                 layout(location = 0) out mediump vec4 fragColor;\n\
                 in mediump vec4 v_color;\n\
                 void main (void)\n\
                 {\n    \
                 fragColor = v_color;\n\
                 }\n"
            }
        }
    }

    /// `AttributeCase::computeColor` - the same arithmetic the shader does, in host
    /// floats, which is what makes this case need no reference rasteriser.
    fn compute_color(&self, value: Vec4) -> Vec4 {
        let normalized = [value.x(), value.y(), value.z(), value.w()].map(|c| c / VALUE_RANGE as f32);
        let p = if self.loader.use_negative() {
            normalized.map(|c| (c + 1.0) / 2.0)
        } else {
            normalized
        };
        let components = if self.data_type.is_matrix() {
            self.data_type.matrix_num_rows()
        } else {
            self.data_type.scalar_size()
        };

        match components {
            1 => Vec4::new(p[0], 0.0, 0.0, 1.0),
            2 => Vec4::new(p[0], p[1], 0.0, 1.0),
            3 => Vec4::new(p[0], p[1], p[2], 1.0),
            _ => Vec4::new((p[0] + p[2]) / 2.0, (p[1] + p[2]) / 2.0, p[3], 1.0),
        }
    }

    /// `AttributeCase::verifyUnicoloredBuffer`. The error-mask image upstream builds is
    /// pure logging and is not produced here.
    fn verify_unicolored_buffer(&self, context: &Context, scene: &Surface, ref_value: Vec4) -> bool {
        const RESULT_THRESHOLD: i32 = 2;
        let ref_color = RGBA::from_vec(ref_value);
        let threshold = context.render_target().pixel_format().get_color_threshold();
        let threshold = RGBA::new(
            (threshold.get_red() * RESULT_THRESHOLD).min(255),
            (threshold.get_green() * RESULT_THRESHOLD).min(255),
            (threshold.get_blue() * RESULT_THRESHOLD).min(255),
            (threshold.get_alpha() * RESULT_THRESHOLD).min(255),
        );
        let mut error = None;

        for y in 0..RENDER_SIZE {
            for x in 0..RENDER_SIZE {
                let color = scene.get_pixel(x, y);

                if (color.get_red() - ref_color.get_red()).abs() > threshold.get_red()
                    || (color.get_green() - ref_color.get_green()).abs() > threshold.get_green()
                    || (color.get_blue() - ref_color.get_blue()).abs() > threshold.get_blue()
                {
                    error.get_or_insert((x, y, color));
                }
            }
        }

        match error {
            None => true,
            Some((x, y, color)) => {
                log::warn!("Found invalid pixel(s). Pixel at ({x}, {y}) color: {color:?}, expected {ref_color:?}");
                false
            }
        }
    }

    /// `AttributeCase::renderWithValue`
    fn render_with_value(
        &self,
        context: &Context,
        program: &ShaderProgram,
        buffer: &Buffer,
        v: Vec4,
    ) -> Result<bool, TestError> {
        let gl = context.gl();
        let mut dest = Surface::new(RENDER_SIZE, RENDER_SIZE);

        // SAFETY: the position attribute reads from the buffer filled below, and the
        // value attribute is a default one, which needs no storage at all.
        let loaded_value = unsafe {
            let position_index = gl.get_attrib_location(program.program(), c"a_position".as_ptr());
            let value_index = gl.get_attrib_location(program.program(), c"a_value".as_ptr());

            gl.clear_color(0.0, 0.0, 0.0, 0.0);
            gl.clear(glw::GL_COLOR_BUFFER_BIT);
            gl.viewport(0, 0, RENDER_SIZE, RENDER_SIZE);
            glu::expect_no_error(gl, "setup")?;

            gl.bind_buffer(glw::GL_ARRAY_BUFFER, buffer.get());
            gl.vertex_attrib_pointer(position_index as u32, 4, glw::GL_FLOAT, glw::FALSE, 0, std::ptr::null());
            gl.enable_vertex_attrib_array(position_index as u32);
            glu::expect_no_error(gl, "position va")?;

            // Transfer the test value; load it into the second column in the matrix case.
            let index = if self.data_type.is_matrix() {
                value_index + 1
            } else {
                value_index
            };
            let loaded_value = self.loader.load(gl, index, v);
            glu::expect_no_error(gl, "default va")?;

            gl.use_program(program.program());
            gl.draw_arrays(glw::GL_TRIANGLE_STRIP, 0, 4);
            gl.use_program(0);
            glu::expect_no_error(gl, "draw")?;

            loaded_value
        };

        glu::read_pixels(&context.render_context, 0, 0, &mut dest.get_access())?;

        Ok(self.verify_unicolored_buffer(context, &dest, self.compute_color(loaded_value)))
    }
}

impl TestCase for AttributeCase {
    fn name(&self) -> &str {
        &self.name
    }

    /// `AttributeCase::init` plus the seven `iterate` passes.
    fn iterate(&self, context: &Context) -> TestOutcome {
        let gl = context.gl();
        let render_target = context.render_target();

        if render_target.width < RENDER_SIZE || render_target.height < RENDER_SIZE {
            return Err(TestError::NotSupported(format!(
                "Render target must be at least {RENDER_SIZE}x{RENDER_SIZE}"
            )));
        }

        let program = ShaderProgram::new(
            gl,
            &ProgramSources::vtx_frag(self.gen_vertex_source(), self.fragment_source()),
        );
        if !program.is_ok() {
            return Err(TestError::Fail("could not build program".to_string()));
        }

        const FULLSCREEN_QUAD: [f32; 16] = [
            1.0, 1.0, 0.0, 1.0, //
            1.0, -1.0, 0.0, 1.0, //
            -1.0, 1.0, 0.0, 1.0, //
            -1.0, -1.0, 0.0, 1.0,
        ];

        let buffer = Buffer::new(gl);
        // SAFETY: the upload covers exactly the quad above.
        unsafe {
            gl.bind_buffer(glw::GL_ARRAY_BUFFER, buffer.get());
            gl.buffer_data(
                glw::GL_ARRAY_BUFFER,
                std::mem::size_of_val(&FULLSCREEN_QUAD) as isize,
                FULLSCREEN_QUAD.as_ptr().cast(),
                glw::GL_STATIC_DRAW,
            );
        }
        glu::expect_no_error(gl, "fill buffer")?;

        let mut all_iterations_passed = true;

        for value in TEST_VALUES {
            // Normalizing transfers would use the whole range; nothing here normalizes,
            // so the value is scaled up to `VALUE_RANGE` and, for a signed loader, first
            // moved into `[-1, 1]`.
            let test_value = if self.loader.use_negative() {
                Vec4::new(
                    value[0] * 2.0 - 1.0,
                    value[1] * 2.0 - 1.0,
                    value[2] * 2.0 - 1.0,
                    value[3] * 2.0 - 1.0,
                )
            } else {
                Vec4::new(value[0], value[1], value[2], value[3])
            };
            let test_value = Vec4::new(
                test_value.x() * VALUE_RANGE as f32,
                test_value.y() * VALUE_RANGE as f32,
                test_value.z() * VALUE_RANGE as f32,
                test_value.w() * VALUE_RANGE as f32,
            );

            if !self.render_with_value(context, &program, &buffer, test_value)? {
                all_iterations_passed = false;
            }
        }

        Ok(if all_iterations_passed {
            TestStatus::pass("Pass")
        } else {
            TestStatus::fail("Got unexpected values")
        })
    }
}

/// `AttributeCase::create`
pub fn case(es_version: EsVersion, loader: Loader, data_type: DataType) -> Box<dyn TestCase> {
    Box::new(AttributeCase {
        name: loader.case_name().to_string(),
        es_version,
        loader,
        data_type,
    })
}

/// One `Target` row: the attribute type under test and whether it gets the reduced set.
pub struct Target {
    pub name: &'static str,
    pub data_type: DataType,
    /// `reducedTestSets` - the two- and three-component loaders are skipped.
    pub reduced_test_sets: bool,
}

/// The eight float loaders each `floatTargets` row registers, four of them only when the
/// row asks for the full set.
pub fn add_float_target_group(root: &mut TestCaseGroup, es_version: EsVersion, target: &Target) {
    let mut group = TestCaseGroup::new(target.name);
    let full_set = !target.reduced_test_sets;

    for make in [Loader::FloatDirect, Loader::FloatIndirect] {
        for components in 1..=4 {
            if (components == 2 || components == 3) && !full_set {
                continue;
            }
            group.add_child(case(es_version, make(components), target.data_type));
        }
    }

    root.add_child(group);
}

/// The two integer loaders each `intTargets`/`uintTargets` row registers.
pub fn add_integer_target_group(root: &mut TestCaseGroup, target: &Target, loaders: [Loader; 2]) {
    let mut group = TestCaseGroup::new(target.name);
    for loader in loaders {
        group.add_child(case(EsVersion::Es3, loader, target.data_type));
    }
    root.add_child(group);
}
