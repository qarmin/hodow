/// `TCU_FAIL`
fn fail<T>(message: &str) -> Result<T, TestError> {
    Err(TestError::Fail(message.to_string()))
}

/// `glGetIntegerv(GL_SPARSE_BUFFER_PAGE_SIZE_ARB)` as every `initTestCaseGlobal` does it.
fn check_page_size(context: &Context) -> Result<GLint, TestError> {
    let gl = context.gl();
    let mut page_size: GLint = 0;

    gl_call!(
        gl,
        "glGetIntegerv() failed for GL_SPARSE_BUFFER_PAGE_SIZE_ARB pname",
        gl.get_integerv(glw::GL_SPARSE_BUFFER_PAGE_SIZE_ARB, &mut page_size)
    );
    Ok(page_size)
}

/// The `GL_ARB_sparse_buffer` check every `iterate` starts with.
fn check_sparse_buffer_support(context: &Context) -> Result<(), TestError> {
    if !context.context_info.is_extension_supported("GL_ARB_sparse_buffer") {
        return Err(TestError::NotSupported(
            "GL_ARB_sparse_buffer is not supported".to_string(),
        ));
    }
    Ok(())
}

/// `glGetError` compared with `expected`; the message is logged when it differs.
fn expect_error(gl: &glw::Functions, expected: glw::GLenum, message: &str) -> bool {
    // SAFETY: glGetError needs nothing but a current context.
    let error = unsafe { gl.get_error() };

    if error != expected {
        log::info!("{message}");
        return false;
    }

    true
}

fn verdict(result: bool) -> TestOutcome {
    if result {
        Ok(TestStatus::pass("Pass"))
    } else {
        Ok(TestStatus::fail("Fail"))
    }
}

/// The buffers of `NegativeTests`; its `deinit` is the `Drop`.
struct NegativeBuffers<'a> {
    context: &'a Context,
    helper_bo_id: GLuint,
    immutable_bo_id: GLuint,
    sparse_bo_id: GLuint,
}

impl Drop for NegativeBuffers<'_> {
    fn drop(&mut self) {
        let gl = self.context.gl();
        // SAFETY: every name below was generated by this value, is deleted once and zero names are skipped.
        unsafe {
            for bo_id in [self.helper_bo_id, self.immutable_bo_id, self.sparse_bo_id] {
                if bo_id != 0 {
                    gl.delete_buffers(1, &bo_id);
                }
            }
        }
    }
}

/// `NegativeTests`
struct NegativeTests;

impl TestCase for NegativeTests {
    fn name(&self) -> &str {
        "NegativeTests"
    }

    fn iterate(&self, context: &Context) -> TestOutcome {
        const IMMUTABLE_BO_SIZE: glw::GLsizeiptr = 1024768;

        let gl = context.gl();
        let mut result = true;

        check_sparse_buffer_support(context)?;

        let mut page_size: GLint = 0;
        gl_call!(
            gl,
            "glGetIntegerv() call failed.",
            gl.get_integerv(glw::GL_SPARSE_BUFFER_PAGE_SIZE_ARB, &mut page_size)
        );

        let mut buffers = NegativeBuffers {
            context,
            helper_bo_id: 0,
            immutable_bo_id: 0,
            sparse_bo_id: 0,
        };

        // SAFETY: plain object creation.
        unsafe {
            gl.gen_buffers(1, &mut buffers.helper_bo_id);
            gl.gen_buffers(1, &mut buffers.immutable_bo_id);
            gl.gen_buffers(1, &mut buffers.sparse_bo_id);
        }
        crate::glu::expect_no_error(gl, "glGenBuffers() call(s) failed.")?;

        // SAFETY: plain state calls.
        unsafe {
            gl.bind_buffer(glw::GL_ARRAY_BUFFER, buffers.sparse_bo_id);
            gl.bind_buffer(glw::GL_COPY_READ_BUFFER, buffers.immutable_bo_id);
            gl.bind_buffer(glw::GL_ELEMENT_ARRAY_BUFFER, buffers.helper_bo_id);
        }
        crate::glu::expect_no_error(gl, "glBindBuffer() call failed.")?;

        let page = page_size as glw::GLsizeiptr;

        // SAFETY: storage allocation with no initial data.
        unsafe {
            gl.buffer_storage(
                glw::GL_ARRAY_BUFFER,
                page * 3,
                std::ptr::null(),
                glw::GL_SPARSE_STORAGE_BIT_ARB,
            );
            gl.buffer_storage(glw::GL_COPY_READ_BUFFER, IMMUTABLE_BO_SIZE, std::ptr::null(), 0);
        }
        crate::glu::expect_no_error(gl, "glBufferStorage() call(s) failed.")?;

        let true_value = glw::GL_TRUE as glw::GLboolean;

        // SAFETY: the calls below only provoke the errors they check for.
        unsafe { gl.buffer_page_commitment_arb(glw::GL_INTERLEAVED_ATTRIBS, 0, page, true_value) };
        if !expect_error(
            gl,
            glw::GL_INVALID_ENUM,
            "Invalid <target> value passed to a glBufferPageCommitmentARB() call did not generate a GL_INVALID_ENUM error.",
        ) {
            result = false;
        }

        // SAFETY: as above.
        unsafe {
            gl.buffer_storage(
                glw::GL_ELEMENT_ARRAY_BUFFER,
                page * 3,
                std::ptr::null(),
                glw::GL_SPARSE_STORAGE_BIT_ARB | glw::GL_MAP_READ_BIT,
            )
        };
        if !expect_error(
            gl,
            glw::GL_INVALID_VALUE,
            "Invalid <flags> value set to GL_SPARSE_STORAGE_BIT_ARB | GL_MAP_READ_BIT did not generate a GL_INVALID_VALUE error.",
        ) {
            result = false;
        }

        // SAFETY: as above.
        unsafe {
            gl.buffer_storage(
                glw::GL_ELEMENT_ARRAY_BUFFER,
                page * 3,
                std::ptr::null(),
                glw::GL_SPARSE_STORAGE_BIT_ARB | glw::GL_MAP_WRITE_BIT,
            )
        };
        if !expect_error(
            gl,
            glw::GL_INVALID_VALUE,
            "Invalid <flags> value set to GL_SPARSE_STORAGE_BIT_ARB | GL_MAP_WRITE_BIT did not generate a GL_INVALID_VALUE error.",
        ) {
            result = false;
        }

        // SAFETY: as above.
        unsafe { gl.buffer_page_commitment_arb(glw::GL_COPY_READ_BUFFER, 0, page, true_value) };
        if !expect_error(
            gl,
            glw::GL_INVALID_OPERATION,
            "Invalid error code generated by glBufferPageCommitmentARB()  issued against an immutable, non-sparse buffer object.",
        ) {
            result = false;
        }

        if page_size != 1 {
            // SAFETY: as above.
            unsafe { gl.buffer_page_commitment_arb(glw::GL_ARRAY_BUFFER, page / 2, page, true_value) };
            if !expect_error(
                gl,
                glw::GL_INVALID_VALUE,
                "Invalid error code generated by glBufferPageCommitmentARB() whose <offset> value was set to (page size / 2).",
            ) {
                result = false;
            }
        }

        if page_size != 1 {
            // SAFETY: as above.
            unsafe { gl.buffer_page_commitment_arb(glw::GL_ARRAY_BUFFER, 0, page / 2, true_value) };
            if !expect_error(
                gl,
                glw::GL_INVALID_VALUE,
                "Invalid error code generated by glBufferPageCommitmentARB() whose <size> value was set to (page size / 2).",
            ) {
                result = false;
            }
        }

        // SAFETY: as above.
        unsafe { gl.buffer_page_commitment_arb(glw::GL_ARRAY_BUFFER, -1, page, true_value) };
        if !expect_error(
            gl,
            glw::GL_INVALID_VALUE,
            "Invalid error code generated by glBufferPageCommitmentARB() whose <offset> argument was set to -1.",
        ) {
            result = false;
        }

        // SAFETY: as above.
        unsafe { gl.buffer_page_commitment_arb(glw::GL_ARRAY_BUFFER, 0, -1, true_value) };
        if !expect_error(
            gl,
            glw::GL_INVALID_VALUE,
            "Invalid error code generated by glBufferPageCommitmentARB() whose <size> argument was set to -1.",
        ) {
            result = false;
        }

        // SAFETY: as above.
        unsafe { gl.buffer_page_commitment_arb(glw::GL_ARRAY_BUFFER, 0, page * 4, true_value) };
        if !expect_error(
            gl,
            glw::GL_INVALID_VALUE,
            "Invalid error code generated by glBufferPageCommitmentARB() whose <offset> was set to 0 and <size> was set to (page size * 4), when the buffer storage size had been configured to be (page size * 3).",
        ) {
            result = false;
        }

        // SAFETY: as above.
        unsafe { gl.buffer_page_commitment_arb(glw::GL_ARRAY_BUFFER, page, page * 3, true_value) };
        if !expect_error(
            gl,
            glw::GL_INVALID_VALUE,
            "Invalid error code generated by glBufferPageCommitmentARB() whose <offset> was set to (page size) and <size> was set to (page size * 3), when the buffer storage size had been configured to be (page size * 3).",
        ) {
            result = false;
        }

        // SAFETY: a mapping that must fail is requested; nothing is read from it.
        let data_ptr = unsafe { gl.map_buffer(glw::GL_ARRAY_BUFFER, glw::GL_READ_ONLY) };
        if !data_ptr.is_null() {
            log::info!(
                "Non-NULL pointer returned by an invalid glMapBuffer() call, issued against a sparse buffer object"
            );
            result = false;
        }
        if !expect_error(
            gl,
            glw::GL_INVALID_OPERATION,
            "Invalid error code generated by glMapBuffer() call, issued against a sparse buffer object",
        ) {
            result = false;
        }

        // SAFETY: as above.
        let data_ptr = unsafe { gl.map_buffer_range(glw::GL_ARRAY_BUFFER, 0, page, glw::GL_MAP_READ_BIT) };
        if !data_ptr.is_null() {
            log::info!(
                "Non-NULL pointer returned by an invalid glMapBufferRange() call, issued against a sparse buffer object"
            );
            result = false;
        }
        if !expect_error(
            gl,
            glw::GL_INVALID_OPERATION,
            "Invalid error code generated by glMapBufferRange() call, issued against a sparse buffer object",
        ) {
            result = false;
        }

        verdict(result)
    }
}

/// `PageSizeGetterTest`
struct PageSizeGetterTest;

impl TestCase for PageSizeGetterTest {
    fn name(&self) -> &str {
        "PageSizeGetterTest"
    }

    fn iterate(&self, context: &Context) -> TestOutcome {
        let gl = context.gl();
        let mut page_size_bool = glw::GL_FALSE as glw::GLboolean;
        let mut page_size_double: glw::GLdouble = 0.0;
        let mut page_size_float: glw::GLfloat = 0.0;
        let mut page_size_int: GLint = 0;
        let mut result = true;

        check_sparse_buffer_support(context)?;

        gl_call!(
            gl,
            "glGetIntegerv() call failed",
            gl.get_integerv(glw::GL_SPARSE_BUFFER_PAGE_SIZE_ARB, &mut page_size_int)
        );
        if !(1..=65536).contains(&page_size_int) {
            log::info!(
                "Page size reported by the implementation ({page_size_int}) by glGetIntegerv() is out of the allowed range."
            );
            result = false;
        }

        gl_call!(
            gl,
            "glGetBooleanv() call failed",
            gl.get_booleanv(glw::GL_SPARSE_BUFFER_PAGE_SIZE_ARB, &mut page_size_bool)
        );
        if page_size_bool == 0 {
            log::info!("Invalid page size reported by glGetBooleanv()");
            result = false;
        }

        gl_call!(
            gl,
            "glGetDoublev() call failed",
            gl.get_doublev(glw::GL_SPARSE_BUFFER_PAGE_SIZE_ARB, &mut page_size_double)
        );
        if (page_size_double - page_size_int as f64).abs() > 1e-5 {
            log::info!(
                "Invalid page size reported by glGetDoublev() (reported value: {page_size_double}, expected value: {page_size_int})"
            );
            result = false;
        }

        gl_call!(
            gl,
            "glGetFloatv() call failed",
            gl.get_floatv(glw::GL_SPARSE_BUFFER_PAGE_SIZE_ARB, &mut page_size_float)
        );
        if (page_size_float - page_size_int as f32).abs() > 1e-5 {
            log::info!(
                "Invalid page size reported by glGetFloatv() (reported value: {page_size_float}, expected value: {page_size_int})"
            );
            result = false;
        }

        let mut page_size_int64: glw::GLint64 = 0;
        gl_call!(
            gl,
            "glGetFloatv() call failed",
            gl.get_integer_64v(glw::GL_SPARSE_BUFFER_PAGE_SIZE_ARB, &mut page_size_int64)
        );
        if page_size_int64 != page_size_int as glw::GLint64 {
            log::info!(
                "Invalid page size reported by glGetInteger64v() (reported value: {page_size_int64}, expected value: {page_size_int})"
            );
            result = false;
        }

        verdict(result)
    }
}

/// The sparse buffer `BufferStorageTest` keeps in `m_sparse_bo`; its `deinit` is the `Drop`.
struct SparseBo<'a> {
    context: &'a Context,
    id: GLuint,
}

impl Drop for SparseBo<'_> {
    fn drop(&mut self) {
        if self.id != 0 {
            // SAFETY: the name was generated by this value and is deleted once.
            unsafe { self.context.gl().delete_buffers(1, &self.id) };
        }
    }
}

/// `BufferStorageTest`
struct BufferStorageTest {
    name: &'static str,
}

impl TestCase for BufferStorageTest {
    fn name(&self) -> &str {
        self.name
    }

    fn iterate(&self, context: &Context) -> TestOutcome {
        let gl = context.gl();
        let mut result = true;

        check_sparse_buffer_support(context)?;

        if !context.context_type().supports_core(4, 3) {
            return Err(TestError::NotSupported(
                "GL_ARB_sparse_buffer conformance tests require OpenGL 4.3 core feature-set".to_string(),
            ));
        }

        let Some(mut test_case) = storage_cases::create(context, self.name) else {
            crate::tcu_not_ported!(
                "the BufferStorageTestCase behind {} (gl4cSparseBufferTests.cpp)",
                self.name
            )
        };

        test_case.init_test_case_global()?;

        let mut sparse_bo = SparseBo { context, id: 0 };

        for n_flag_combination in 0..(1u32 << 4) {
            let flags = (if n_flag_combination & (1 << 0) != 0 {
                glw::GL_CLIENT_STORAGE_BIT
            } else {
                0
            }) | (if n_flag_combination & (1 << 1) != 0 {
                glw::GL_DYNAMIC_STORAGE_BIT
            } else {
                0
            }) | (if n_flag_combination & (1 << 2) != 0 {
                glw::GL_MAP_COHERENT_BIT
            } else {
                0
            }) | (if n_flag_combination & (1 << 3) != 0 {
                glw::GL_MAP_PERSISTENT_BIT
            } else {
                0
            }) | glw::GL_SPARSE_STORAGE_BIT_ARB;

            if flags & glw::GL_MAP_PERSISTENT_BIT != 0
                && flags & glw::GL_MAP_READ_BIT == 0
                && flags & glw::GL_MAP_WRITE_BIT == 0
            {
                continue;
            }

            if flags & glw::GL_MAP_COHERENT_BIT != 0 && flags & glw::GL_MAP_PERSISTENT_BIT == 0 {
                continue;
            }

            gl_call!(gl, "glGenBuffers() call failed.", gl.gen_buffers(1, &mut sparse_bo.id));
            gl_call!(
                gl,
                "glBindBuffer() call failed.",
                gl.bind_buffer(glw::GL_ARRAY_BUFFER, sparse_bo.id)
            );
            gl_call!(
                gl,
                "glBufferStorage() call failed.",
                gl.buffer_storage(glw::GL_ARRAY_BUFFER, 1024768 * 1024, std::ptr::null(), flags)
            );
            gl_call!(
                gl,
                "glBindBuffer() call failed.",
                gl.bind_buffer(glw::GL_ARRAY_BUFFER, sparse_bo.id)
            );

            if !test_case.init_test_case_iteration(sparse_bo.id)? {
                log::info!("Test case [{}] has failed to initialize.", self.name);
                result = false;
                break;
            }

            if !test_case.execute(flags)? {
                log::info!("Test case [{}] has failed to execute correctly.", self.name);
                result = false;
            }

            test_case.deinit_test_case_iteration()?;

            gl_call!(
                gl,
                "glDeleteBuffers() call failed.",
                gl.delete_buffers(1, &sparse_bo.id)
            );
            sparse_bo.id = 0;
        }

        verdict(result)
    }
}

/// `SparseBufferTests::init`
pub fn create_tests() -> TestCaseGroup {
    let mut group = TestCaseGroup::new("sparse_buffer_tests");
    group.add_child(Box::new(NegativeTests) as Box<dyn TestCase>);
    group.add_child(Box::new(PageSizeGetterTest) as Box<dyn TestCase>);

    for name in names::BUFFER_STORAGE_TEST_NAMES {
        group.add_child(Box::new(BufferStorageTest { name }) as Box<dyn TestCase>);
    }

    group
}
