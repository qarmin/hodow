/// `TessellationShadersIsolines`
pub(super) struct Isolines {
    pub ext_params: ExtParameters,
}

const SPACINGS: [VertexSpacing; 3] = [
    VertexSpacing::Equal,
    VertexSpacing::FractionalEven,
    VertexSpacing::FractionalOdd,
];

/// `_test_descriptor`
#[derive(Clone, Copy)]
struct TestDescriptor {
    inner_tess_levels: [f32; 2],
    irrelevant_tess_level: f32,
    outer_tess_levels: [f32; 4],
    vertex_spacing_mode: VertexSpacing,
}

/// `_test_result`
#[derive(Clone)]
struct TestResult {
    n_isolines: u32,
    n_vertices: u32,
    parent: TestDescriptor,
    rendered_data: Vec<f32>,
    irrelevant_tess_level: i32,
    outer1_tess_level: i32,
    outer2_tess_level: i32,
}

fn spacing_index(spacing: VertexSpacing) -> usize {
    SPACINGS
        .iter()
        .position(|candidate| *candidate == spacing)
        .expect("a spacing the test uses")
}

fn describe_levels(test: &TestDescriptor) -> String {
    format!(
        " ({}, {}) and the following outer tesellation level configuration: ({}, {}, {}, {})",
        test.inner_tess_levels[0],
        test.inner_tess_levels[1],
        test.outer_tess_levels[0],
        test.outer_tess_levels[1],
        test.outer_tess_levels[2],
        test.outer_tess_levels[3]
    )
}

#[derive(Default)]
struct Resources {
    vao_id: GLuint,
}

impl Isolines {
    /// `checkFirstOuterTessellationLevelEffect`
    fn check_first_outer_tessellation_level_effect(
        test_result: &TestResult,
        gl_max_tess_gen_level_value: GLint,
    ) -> Result<(), TestError> {
        if test_result.n_vertices != 0 {
            // The amount of isolines is always based on equal spacing, whatever the TE stage defines.
            let (_, outer_zero_tess_level_clamped_rounded) = get_tessellation_level_after_vertex_spacing(
                VertexSpacing::Equal,
                test_result.parent.outer_tess_levels[0],
                gl_max_tess_gen_level_value,
            );
            let n_isolines_expected = outer_zero_tess_level_clamped_rounded as u32;

            if test_result.n_isolines != n_isolines_expected {
                log::info!(
                    "Tessellator generated an invalid amount of isolines:{} instead of the expected amount:{n_isolines_expected} for the following inner tessellation level configuration:{}",
                    test_result.n_isolines,
                    describe_levels(&test_result.parent)
                );
                return Err(TestError::Fail(
                    "Invalid amount of isolines generated by tessellator".to_string(),
                ));
            }
        }
        Ok(())
    }

    /// `checkSecondOuterTessellationLevelEffect`
    fn check_second_outer_tessellation_level_effect(
        test_result: &TestResult,
        gl_max_tess_gen_level_value: GLint,
    ) -> Result<(), TestError> {
        let epsilon = 1e-5_f32;
        let mut found_line_segments: Vec<(f32, f32)> = Vec::new();

        if test_result.n_vertices != 0 {
            let (_, outer_tess_levels1_clamped_rounded) = get_tessellation_level_after_vertex_spacing(
                test_result.parent.vertex_spacing_mode,
                test_result.parent.outer_tess_levels[1],
                gl_max_tess_gen_level_value,
            );
            let n_line_segments_per_isoline_expected = outer_tess_levels1_clamped_rounded as u32;

            // Count the unique line segments among all the line segments of the result data set.
            for n_vertex in (0..test_result.n_vertices as usize).step_by(2) {
                let vertex1_x = test_result.rendered_data[n_vertex * 3];
                let vertex2_x = test_result.rendered_data[(n_vertex + 1) * 3];

                let was_line_segment_found = found_line_segments.iter().any(|(found_vertex1_x, found_vertex2_x)| {
                    (found_vertex1_x - vertex1_x).abs() < epsilon && (found_vertex2_x - vertex2_x).abs() < epsilon
                });
                if !was_line_segment_found {
                    found_line_segments.push((vertex1_x, vertex2_x));
                }
            }

            let n_unique_line_segments_found = found_line_segments.len() as u32;
            if n_unique_line_segments_found != n_line_segments_per_isoline_expected {
                log::info!(
                    "Tessellator generated an invalid amount of unique line segments:{n_unique_line_segments_found} instead of the expected amount:{n_line_segments_per_isoline_expected} for the following inner tessellation level configuration:{} and the following vertex spacing mode: {}",
                    describe_levels(&test_result.parent),
                    test_result.parent.vertex_spacing_mode as u32
                );
                return Err(TestError::Fail(
                    "Invalid amount of unique line segments generated by tessellator".to_string(),
                ));
            }
        }
        Ok(())
    }

    /// `checkNoLineSegmentIsDefinedAtHeightOne`
    fn check_no_line_segment_is_defined_at_height_one(test_result: &TestResult) -> Result<(), TestError> {
        let epsilon = 1e-5_f32;
        for n_vertex in 0..test_result.n_vertices as usize {
            let vertex = &test_result.rendered_data[n_vertex * 3..];
            if (vertex[1] - 1.0).abs() < epsilon {
                log::info!(
                    "Tessellator generated the following coordinate: ({}, {}, {}) for the following inner tessellation level configuration:{} which is invalid: Y must never be equal to 1.",
                    vertex[0],
                    vertex[1],
                    vertex[2],
                    describe_levels(&test_result.parent)
                );
                return Err(TestError::Fail(
                    "Invalid line segment generated by tessellator".to_string(),
                ));
            }
        }
        Ok(())
    }

    /// `findTestResult`
    fn find_test_result(
        test_results: &[Vec<TestResult>; 3],
        irrelevant_tess_level: i32,
        outer1_tess_level: i32,
        outer2_tess_level: i32,
        vertex_spacing_mode: VertexSpacing,
    ) -> Result<TestResult, TestError> {
        test_results[spacing_index(vertex_spacing_mode)]
            .iter()
            .find(|candidate| {
                candidate.irrelevant_tess_level == irrelevant_tess_level
                    && candidate.outer1_tess_level == outer1_tess_level
                    && candidate.outer2_tess_level == outer2_tess_level
            })
            .cloned()
            .ok_or_else(|| TestError::Fail("Requested test run was not found.".to_string()))
    }

    /// `checkIrrelevantTessellationLevelsHaveNoEffect`
    fn check_irrelevant_tessellation_levels_have_no_effect(
        test_results: &[Vec<TestResult>; 3],
        gl_max_tess_gen_level_value: GLint,
        irrelevant_tess_value_1: f32,
        irrelevant_tess_value_2: f32,
    ) -> Result<(), TestError> {
        let epsilon = 1e-5_f32;

        let (_, irrelevant_tess_level1_rounded_clamped) = get_tessellation_level_after_vertex_spacing(
            VertexSpacing::Equal,
            irrelevant_tess_value_1,
            gl_max_tess_gen_level_value,
        );
        let (_, irrelevant_tess_level2_rounded_clamped) = get_tessellation_level_after_vertex_spacing(
            VertexSpacing::Equal,
            irrelevant_tess_value_2,
            gl_max_tess_gen_level_value,
        );
        let irrelevant_tess_level1 = irrelevant_tess_level1_rounded_clamped as i32;
        let irrelevant_tess_level2 = irrelevant_tess_level2_rounded_clamped as i32;

        for test_result in &test_results[0] {
            if test_result.irrelevant_tess_level == irrelevant_tess_level1 {
                let test_result_reference = Self::find_test_result(
                    test_results,
                    irrelevant_tess_level2,
                    test_result.outer1_tess_level,
                    test_result.outer2_tess_level,
                    VertexSpacing::Equal,
                )?;

                for n_vertex in 0..test_result.n_vertices as usize {
                    let vertex_data_1 = &test_result.rendered_data[n_vertex * 3..];
                    let vertex_data_2 = &test_result_reference.rendered_data[n_vertex * 3..];

                    if (vertex_data_1[0] - vertex_data_2[0]).abs() > epsilon
                        || (vertex_data_1[1] - vertex_data_2[1]).abs() > epsilon
                        || (vertex_data_1[2] - vertex_data_2[2]).abs() > epsilon
                    {
                        log::info!(
                            "Tessellator generated non-matching data for different tessellation level configurations, where only irrelevant tessellation levels have been changed;  data generated for {{inner:{}}}: ({}, {}, {}), data generated for {{inner:{}}}: ({}, {}, {})",
                            describe_levels(&test_result.parent),
                            vertex_data_1[0],
                            vertex_data_1[1],
                            vertex_data_1[2],
                            describe_levels(&test_result_reference.parent),
                            vertex_data_2[0],
                            vertex_data_2[1],
                            vertex_data_2[2]
                        );
                        return Err(TestError::Fail(
                            "Invalid amount of unique line segments generated by tessellator".to_string(),
                        ));
                    }
                }
            }
        }
        Ok(())
    }

    /// `checkVertexSpacingDoesNotAffectAmountOfGeneratedIsolines`
    fn check_vertex_spacing_does_not_affect_amount_of_generated_isolines(
        test_results: &[Vec<TestResult>; 3],
    ) -> Result<(), TestError> {
        for test_result_equal in &test_results[0] {
            let test_result_fe = Self::find_test_result(
                test_results,
                test_result_equal.irrelevant_tess_level,
                test_result_equal.outer1_tess_level,
                test_result_equal.outer2_tess_level,
                VertexSpacing::FractionalEven,
            )?;
            let test_result_fo = Self::find_test_result(
                test_results,
                test_result_equal.irrelevant_tess_level,
                test_result_equal.outer1_tess_level,
                test_result_equal.outer2_tess_level,
                VertexSpacing::FractionalOdd,
            )?;

            if test_result_equal.n_isolines != test_result_fe.n_isolines
                || test_result_fe.n_isolines != test_result_fo.n_isolines
            {
                log::info!(
                    "Tessellator generated different amount of isolines for EQUAL/FRACTIONAL_EVEN/FRACTIONAL_ODD vertex spacing modes which is invalid."
                );
                return Err(TestError::Fail(
                    "Invalid amount of unique isolines generated by tessellator".to_string(),
                ));
            }
        }
        Ok(())
    }

    /// `countIsolines`
    fn count_isolines(test_result: &mut TestResult) {
        let epsilon = 1e-5_f32;
        let mut found_ys: Vec<f32> = Vec::new();

        for n_vertex in 0..test_result.n_vertices as usize {
            let vertex_y = test_result.rendered_data[n_vertex * 3 + 1];
            if !found_ys.iter().any(|found_y| (vertex_y - found_y).abs() < epsilon) {
                found_ys.push(vertex_y);
            }
        }
        test_result.n_isolines = found_ys.len() as u32;
    }

    fn run(&self, context: &Context, resources: &mut Resources) -> TestOutcome {
        let gl = context.gl();
        let base = TestCaseBase::init(context, self.ext_params);
        let tokens = base.gl_ext_tokens;

        if !base.is_tessellation_shader_supported {
            return Err(TestError::NotSupported(
                TESSELLATION_SHADER_EXTENSION_NOT_SUPPORTED.to_string(),
            ));
        }

        let utils = Utils::new(context, &base)?;

        gl!(gl.gen_vertex_arrays(1, &mut resources.vao_id));
        glu::expect_no_error(gl, "Could not generate vertex array object")?;
        gl!(gl.bind_vertex_array(resources.vao_id));
        glu::expect_no_error(gl, "Error binding vertex array object!")?;

        let mut gl_max_tess_gen_level_value: GLint = 0;
        gl!(gl.get_integerv(tokens.max_tess_gen_level, &mut gl_max_tess_gen_level_value));
        glu::expect_no_error(gl, "glGetIntegerv() failed for GL_MAX_TESS_GEN_LEVEL_EXT pname")?;

        // initTest: the reference tessellation values
        let tess_levels = [
            -1.0_f32,
            4.0,
            gl_max_tess_gen_level_value as f32 * 0.5,
            gl_max_tess_gen_level_value as f32,
        ];
        let irrelevant_tess_value_1 = tess_levels[0];
        let irrelevant_tess_value_2 = tess_levels[1];

        let mut tests: [Vec<TestDescriptor>; 3] = Default::default();
        for outer1_tess_level_index in 0..tess_levels.len() {
            for outer2_tess_level_index in 0..tess_levels.len() {
                // Just two different values for the other levels keep the execution time reasonable.
                for other_tess_level_index in 0..2 {
                    let inner_tess_levels = [tess_levels[other_tess_level_index], tess_levels[other_tess_level_index]];
                    let outer_tess_levels = [
                        tess_levels[outer1_tess_level_index],
                        tess_levels[outer2_tess_level_index],
                        tess_levels[other_tess_level_index],
                        tess_levels[other_tess_level_index],
                    ];

                    for vertex_spacing_mode in SPACINGS {
                        tests[spacing_index(vertex_spacing_mode)].push(TestDescriptor {
                            inner_tess_levels,
                            irrelevant_tess_level: tess_levels[other_tess_level_index],
                            outer_tess_levels,
                            vertex_spacing_mode,
                        });
                    }
                }
            }
        }

        // We only need to use one vertex per patch.
        gl!(gl.patch_parameteri(tokens.patch_vertices, 1));
        glu::expect_no_error(gl, "glPatchParameteriEXT() failed for GL_PATCH_VERTICES_EXT pname")?;

        gl!(gl.enable(glw::GL_RASTERIZER_DISCARD));
        glu::expect_no_error(gl, "glEnable(GL_RASTERIZER_DISCARD) failed")?;

        let mut max_tess_gen_level_again: GLint = 0;
        gl!(gl.get_integerv(tokens.max_tess_gen_level, &mut max_tess_gen_level_again));
        glu::expect_no_error(gl, "glGetIntegerv() failed for GL_MAX_TESS_GEN_LEVEL_EXT pname.")?;

        // Retrieve the tessellated coordinates for every configuration.
        let mut test_results: [Vec<TestResult>; 3] = Default::default();
        for tests_per_spacing in &tests {
            for test in tests_per_spacing {
                let n_rendered_vertices = utils.get_amount_of_vertices_generated_by_tessellator(
                    PrimitiveMode::Isolines,
                    &test.inner_tess_levels,
                    &test.outer_tess_levels,
                    test.vertex_spacing_mode,
                    false,
                )?;
                let rendered_data = utils.get_data_generated_by_tessellator(
                    &test.inner_tess_levels,
                    false,
                    PrimitiveMode::Isolines,
                    VertexOrdering::Ccw,
                    test.vertex_spacing_mode,
                    &test.outer_tess_levels,
                )?;

                let mut result = TestResult {
                    n_isolines: 0,
                    n_vertices: n_rendered_vertices,
                    parent: *test,
                    rendered_data: rendered_data
                        .chunks_exact(4)
                        .map(|bytes| f32::from_ne_bytes(bytes.try_into().expect("four bytes")))
                        .collect(),
                    irrelevant_tess_level: test.irrelevant_tess_level as i32,
                    outer1_tess_level: test.outer_tess_levels[0] as i32,
                    outer2_tess_level: test.outer_tess_levels[1] as i32,
                };
                if !result.rendered_data.is_empty() {
                    Self::count_isolines(&mut result);
                }
                test_results[spacing_index(test.vertex_spacing_mode)].push(result);
            }
        }

        // (test 1): the amount of isolines is determined by the first outer tessellation level.
        for test_result in test_results.iter().flatten() {
            Self::check_first_outer_tessellation_level_effect(test_result, max_tess_gen_level_again)?;
        }
        // (test 2): the amount of line segments per height is determined by the second outer tessellation level.
        for test_result in test_results.iter().flatten() {
            Self::check_second_outer_tessellation_level_effect(test_result, max_tess_gen_level_again)?;
        }
        // (test 3): the 3rd and 4th outer levels and both inner levels have no impact on the tessellated coordinates.
        Self::check_irrelevant_tessellation_levels_have_no_effect(
            &test_results,
            max_tess_gen_level_again,
            irrelevant_tess_value_1,
            irrelevant_tess_value_2,
        )?;
        // (test 4): whatever vertex spacing is requested in TC stage, equal_spacing is always applied.
        Self::check_vertex_spacing_does_not_affect_amount_of_generated_isolines(&test_results)?;
        // (test 5): no data set features a line segment at height of 1.
        for test_result in test_results.iter().flatten() {
            Self::check_no_line_segment_is_defined_at_height_one(test_result)?;
        }

        Ok(TestStatus::pass("Pass"))
    }
}

impl TestCase for Isolines {
    fn name(&self) -> &str {
        "isolines_tessellation"
    }

    fn iterate(&self, context: &Context) -> TestOutcome {
        let gl = context.gl();
        let mut resources = Resources::default();
        let outcome = self.run(context, &mut resources);

        let base = TestCaseBase::init(context, self.ext_params);
        if !base.is_tessellation_shader_supported {
            return outcome;
        }

        gl!(gl.patch_parameteri(base.gl_ext_tokens.patch_vertices, 3));
        gl!(gl.disable(glw::GL_RASTERIZER_DISCARD));
        gl!(gl.bind_vertex_array(0));
        if resources.vao_id != 0 {
            gl!(gl.delete_vertex_arrays(1, &resources.vao_id));
        }
        outcome
    }
}
