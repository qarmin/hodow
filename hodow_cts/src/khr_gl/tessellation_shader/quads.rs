#[derive(Default)]
struct Resources {
    vao_id: GLuint,
}

fn deinit(context: &Context, resources: &Resources) {
    let gl = context.gl();
    gl!(gl.bind_vertex_array(0));
    if resources.vao_id != 0 {
        gl!(gl.delete_vertex_arrays(1, &resources.vao_id));
    }
}

struct DegenerateRun {
    inner: [f32; 2],
    outer: [f32; 4],
    vertex_spacing: VertexSpacing,
    data: Vec<f32>,
    n_vertices: u32,
}

impl DegenerateCase {
    fn run(&self, context: &Context, resources: &mut Resources) -> TestOutcome {
        let gl = context.gl();
        let base = TestCaseBase::init(context, self.ext_params);

        if !base.is_tessellation_shader_supported {
            return Err(TestError::NotSupported(
                TESSELLATION_SHADER_EXTENSION_NOT_SUPPORTED.to_string(),
            ));
        }

        // initTest
        let utils = Utils::new(context, &base)?;

        gl!(gl.gen_vertex_arrays(1, &mut resources.vao_id));
        glu::expect_no_error(gl, "Could not generate vertex array object")?;
        gl!(gl.bind_vertex_array(resources.vao_id));
        glu::expect_no_error(gl, "Error binding vertex array object!")?;

        let mut gl_max_tess_gen_level_value: GLint = 0;
        gl!(gl.get_integerv(base.gl_ext_tokens.max_tess_gen_level, &mut gl_max_tess_gen_level_value));
        glu::expect_no_error(gl, "glGetIntegerv() call failed for GL_MAX_TESS_GEN_LEVEL_EXT pname")?;

        let tess_levels = [-gl_max_tess_gen_level_value / 2, -1, 1];
        // Fractional even spacing always clamps to 2, which is out of scope for this test.
        let vs_modes = [
            VertexSpacing::Default,
            VertexSpacing::Equal,
            VertexSpacing::FractionalOdd,
        ];

        let mut runs: Vec<DegenerateRun> = Vec::new();
        let mut has_failed = false;
        for vs_mode in vs_modes {
            for tess_level in tess_levels {
                // Outer levels are rounded to 1 if necessary, since otherwise no geometry is generated.
                let outer_level = (if tess_level < 0 { 1 } else { tess_level }) as f32;
                let mut run = DegenerateRun {
                    inner: [tess_level as f32; 2],
                    outer: [outer_level; 4],
                    vertex_spacing: vs_mode,
                    data: Vec::new(),
                    n_vertices: 0,
                };

                run.n_vertices = utils.get_amount_of_vertices_generated_by_tessellator(
                    PrimitiveMode::Quads,
                    &run.inner,
                    &run.outer,
                    run.vertex_spacing,
                    false,
                )?;
                if run.n_vertices == 0 {
                    log::info!(
                        "No vertices were generated by tessellator for: inner tess levels:[{}, {}], outer tess levels:[{}, {}, {}, {}], primitive mode: quads, vertex spacing: {}",
                        run.inner[0],
                        run.inner[1],
                        run.outer[0],
                        run.outer[1],
                        run.outer[2],
                        run.outer[3],
                        get_es_token_for_vertex_spacing_mode(vs_mode)
                    );
                    has_failed = true;
                } else {
                    run.data = bytes_to_floats(&utils.get_data_generated_by_tessellator(
                        &run.inner,
                        false,
                        PrimitiveMode::Quads,
                        VertexOrdering::Ccw,
                        run.vertex_spacing,
                        &run.outer,
                    )?);
                }
                runs.push(run);
            }
        }
        if has_failed {
            return Err(TestError::Fail(
                "Zero vertices were generated by tessellator for at least one run which is not a correct behavior"
                    .to_string(),
            ));
        }

        // The test fails if any of the runs did not generate exactly 6 coordinates.
        for run in &runs {
            if run.n_vertices != 2 * 3 {
                log::info!(
                    "Invalid number of coordinates ({}, instead of 6) was generated for the following tessellation configuration: primitive mode:quads, vertex spacing mode:{} inner tessellation levels:{}, {} outer tessellation levels:{}, {}, {}, {}",
                    run.n_vertices,
                    get_es_token_for_vertex_spacing_mode(run.vertex_spacing),
                    run.inner[0],
                    run.inner[1],
                    run.outer[0],
                    run.outer[1],
                    run.outer[2],
                    run.outer[3]
                );
                return Err(TestError::Fail(
                    "Invalid number of coordinates was generated for at least one run".to_string(),
                ));
            }
        }

        // All runs should generate exactly the same set of triangles, in whatever vertex order.
        let base_run = &runs[0];
        for n_triangle in 0..base_run.n_vertices as usize / 3 {
            let base_triangle_data = &base_run.data[3 * 3 * n_triangle..];

            for ref_run in &runs[1..] {
                let ref_triangle_data1 = &ref_run.data[..];
                let ref_triangle_data2 = &ref_run.data[3 * 3..];

                if !is_triangle_defined(base_triangle_data, ref_triangle_data1)
                    && !is_triangle_defined(base_triangle_data, ref_triangle_data2)
                {
                    log::info!(
                        "Reference run does not contain a triangle found in a base run generated for the following tessellation configuration: primitive mode:quads, base vertex spacing mode:{} base inner tessellation levels:{}, {} base outer tessellation levels:{}, {}, {}, {}reference vertex spacing mode:{} reference inner tessellation levels:{}, {} reference outer tessellation levels:{}, {}, {}, {}",
                        get_es_token_for_vertex_spacing_mode(base_run.vertex_spacing),
                        base_run.inner[0],
                        base_run.inner[1],
                        base_run.outer[0],
                        base_run.outer[1],
                        base_run.outer[2],
                        base_run.outer[3],
                        get_es_token_for_vertex_spacing_mode(ref_run.vertex_spacing),
                        ref_run.inner[0],
                        ref_run.inner[1],
                        ref_run.outer[0],
                        ref_run.outer[1],
                        ref_run.outer[2],
                        ref_run.outer[3]
                    );
                    return Err(TestError::Fail(
                        "Reference run does not contain a triangle found in a base run".to_string(),
                    ));
                }
            }
        }

        Ok(TestStatus::pass("Pass"))
    }
}

impl TestCase for DegenerateCase {
    fn name(&self) -> &str {
        "degenerate_case"
    }

    fn iterate(&self, context: &Context) -> TestOutcome {
        let mut resources = Resources::default();
        let outcome = self.run(context, &mut resources);
        deinit(context, &resources);
        outcome
    }
}

struct RoundingRun {
    set1_inner: [f32; 2],
    set1_outer: [f32; 4],
    set2_inner: [f32; 2],
    set2_outer: [f32; 4],
    vertex_spacing: VertexSpacing,
    set1_data: Vec<f32>,
    set2_data: Vec<f32>,
    n_vertices: u32,
}

impl InnerTessellationLevelRounding {
    /// `getUniqueTessCoordinatesFromVertexDataSet`; upstream steps over every second vertex.
    fn unique_tess_coordinates_from_vertex_data_set(raw_data: &[f32], n_raw_data_vertices: u32) -> Vec<[f32; 2]> {
        let mut result: Vec<[f32; 2]> = Vec::new();
        for n_vertex in (0..n_raw_data_vertices as usize).step_by(2) {
            let vertex = [raw_data[n_vertex * 3], raw_data[n_vertex * 3 + 1]];
            if !result.contains(&vertex) {
                result.push(vertex);
            }
        }
        result
    }

    /// `initTest`
    fn init_test(
        &self,
        context: &Context,
        base: &TestCaseBase,
        utils: &Utils<'_>,
        resources: &mut Resources,
    ) -> Result<Vec<RoundingRun>, TestError> {
        let gl = context.gl();

        gl!(gl.gen_vertex_arrays(1, &mut resources.vao_id));
        glu::expect_no_error(gl, "Could not generate vertex array object")?;
        gl!(gl.bind_vertex_array(resources.vao_id));
        glu::expect_no_error(gl, "Error binding vertex array object!")?;

        let mut gl_max_tess_gen_level_value: GLint = 0;
        gl!(gl.get_integerv(base.gl_ext_tokens.max_tess_gen_level, &mut gl_max_tess_gen_level_value));
        glu::expect_no_error(gl, "glGetIntegerv() call failed for GL_MAX_TESS_GEN_LEVEL_EXT pname")?;

        let tess_levels = [2, gl_max_tess_gen_level_value / 2, gl_max_tess_gen_level_value];
        let tess_levels_odd = [
            2 + 1,
            gl_max_tess_gen_level_value / 2 + 1,
            gl_max_tess_gen_level_value - 1,
        ];
        let vs_modes = [
            VertexSpacing::Equal,
            VertexSpacing::FractionalEven,
            VertexSpacing::FractionalOdd,
        ];

        let mut runs = Vec::new();
        for vs_mode in vs_modes {
            for n_tess_level in 0..tess_levels.len() {
                // Two cases: a) inner[0] is 1 in set A and the value it should round to in set B, inner[1] is irrelevant; b) the other way round.
                for n_inner_tess_level_combination in 0..2 {
                    let tess_level = if vs_mode == VertexSpacing::FractionalOdd {
                        tess_levels_odd[n_tess_level]
                    } else {
                        tess_levels[n_tess_level]
                    };

                    let mut run = RoundingRun {
                        set1_inner: [0.0; 2],
                        set1_outer: [tess_level as f32; 4],
                        set2_inner: [0.0; 2],
                        set2_outer: [tess_level as f32; 4],
                        vertex_spacing: vs_mode,
                        set1_data: Vec::new(),
                        set2_data: Vec::new(),
                        n_vertices: 0,
                    };

                    match n_inner_tess_level_combination {
                        0 => {
                            run.set1_inner[0] = 1.0;
                            run.set1_inner[1] = tess_level as f32;
                            run.set2_inner[1] = tess_level as f32;
                            run.set2_inner[0] = get_tessellation_level_after_vertex_spacing(
                                vs_mode,
                                run.set1_inner[0] + 1.0,
                                gl_max_tess_gen_level_value,
                            )
                            .1;
                        }
                        _ => {
                            run.set1_inner[0] = tess_level as f32;
                            run.set1_inner[1] = 1.0;
                            run.set2_inner[0] = tess_level as f32;
                            run.set2_inner[1] = get_tessellation_level_after_vertex_spacing(
                                vs_mode,
                                run.set1_inner[1] + 1.0,
                                gl_max_tess_gen_level_value,
                            )
                            .1;
                        }
                    }

                    let n_set1_vertices = utils.get_amount_of_vertices_generated_by_tessellator(
                        PrimitiveMode::Quads,
                        &run.set1_inner,
                        &run.set1_outer,
                        vs_mode,
                        false,
                    )?;
                    let n_set2_vertices = utils.get_amount_of_vertices_generated_by_tessellator(
                        PrimitiveMode::Quads,
                        &run.set2_inner,
                        &run.set2_outer,
                        vs_mode,
                        false,
                    )?;

                    if n_set1_vertices == 0 {
                        log::info!(
                            "No vertices were generated by tessellator for: inner tess levels:[{}, {}], outer tess levels:[{}, {}, {}, {}], primitive mode: quads, vertex spacing: {}",
                            run.set1_inner[0],
                            run.set1_inner[1],
                            run.set1_outer[0],
                            run.set1_outer[1],
                            run.set1_outer[2],
                            run.set1_outer[3],
                            get_es_token_for_vertex_spacing_mode(vs_mode)
                        );
                        return Err(TestError::Fail(
                            "Zero vertices were generated by tessellator for first test pass".to_string(),
                        ));
                    }
                    if n_set2_vertices == 0 {
                        log::info!(
                            "No vertices were generated by tessellator for: inner tess levels:[{}, {}], outer tess levels:[{}, {}, {}, {}], primitive mode: quads, vertex spacing: {}",
                            run.set2_inner[0],
                            run.set2_inner[1],
                            run.set2_outer[0],
                            run.set2_outer[1],
                            run.set2_outer[2],
                            run.set2_outer[3],
                            get_es_token_for_vertex_spacing_mode(vs_mode)
                        );
                        return Err(TestError::Fail(
                            "Zero vertices were generated by tessellator for second test pass".to_string(),
                        ));
                    }
                    if n_set1_vertices != n_set2_vertices {
                        log::info!(
                            "Amount of vertices generated by the tessellator differs for the following inner/outer configs: inner tess levels:[{}, {}], outer tess levels:[{}, {}, {}, {}] and inner tess levels:[{}, {}], outer tess levels:[{}, {}, {}, {}], primitive mode: quads, vertex spacing: {}",
                            run.set1_inner[0],
                            run.set1_inner[1],
                            run.set1_outer[0],
                            run.set1_outer[1],
                            run.set1_outer[2],
                            run.set1_outer[3],
                            run.set2_inner[0],
                            run.set2_inner[1],
                            run.set2_outer[0],
                            run.set2_outer[1],
                            run.set2_outer[2],
                            run.set2_outer[3],
                            get_es_token_for_vertex_spacing_mode(vs_mode)
                        );
                        return Err(TestError::Fail(
                            "Amount of vertices generated by tessellator differs between base and references passes"
                                .to_string(),
                        ));
                    }

                    run.n_vertices = n_set1_vertices;
                    run.set1_data = bytes_to_floats(&utils.get_data_generated_by_tessellator(
                        &run.set1_inner,
                        false,
                        PrimitiveMode::Quads,
                        VertexOrdering::Ccw,
                        vs_mode,
                        &run.set1_outer,
                    )?);
                    run.set2_data = bytes_to_floats(&utils.get_data_generated_by_tessellator(
                        &run.set2_inner,
                        false,
                        PrimitiveMode::Quads,
                        VertexOrdering::Ccw,
                        vs_mode,
                        &run.set2_outer,
                    )?);
                    runs.push(run);
                }
            }
        }
        Ok(runs)
    }

    fn describe(run: &RoundingRun) -> String {
        format!(
            "First pass' configuration: inner tess levels:[{}, {}], outer tess levels:[{}, {}, {}, {}]; second pass' configuration: inner tess levels:[{}, {}], outer tess levels:[{}, {}, {}, {}], primitive mode: quads, vertex spacing: {}",
            run.set1_inner[0],
            run.set1_inner[1],
            run.set1_outer[0],
            run.set1_outer[1],
            run.set1_outer[2],
            run.set1_outer[3],
            run.set2_inner[0],
            run.set2_inner[1],
            run.set2_outer[0],
            run.set2_outer[1],
            run.set2_outer[2],
            run.set2_outer[3],
            get_es_token_for_vertex_spacing_mode(run.vertex_spacing)
        )
    }

    /// Looks for a marker triangle: two vertices at `line` (in component `along`) that span the whole domain in the other component, and the third one at `edge`.
    fn has_marker_triangle(run: &RoundingRun, along: usize, line: f32, edge: f32) -> bool {
        let other = 1 - along;
        for n_triangle in 0..run.n_vertices as usize / 3 {
            let vertex1_data = &run.set1_data[3 * 3 * n_triangle..];
            let vertex2_data = &vertex1_data[3..];
            let vertex3_data = &vertex2_data[3..];

            let mut found: Option<(&[f32], &[f32], &[f32])> = None;
            if vertex1_data[along] == line {
                if vertex2_data[along] == line && vertex3_data[along] == edge {
                    found = Some((vertex1_data, vertex2_data, vertex3_data));
                } else if vertex2_data[along] == edge && vertex3_data[along] == line {
                    found = Some((vertex1_data, vertex3_data, vertex2_data));
                }
            } else if vertex2_data[along] == line && vertex3_data[along] == line && vertex1_data[along] == edge {
                found = Some((vertex2_data, vertex3_data, vertex1_data));
            }

            if let Some((vertex_1, vertex_2, _vertex_3)) = found {
                // Vertices 1 and 2 should span across the whole domain.
                if (vertex_1[other] == 0.0 && vertex_2[other] == 1.0)
                    || (vertex_1[other] == 1.0 && vertex_2[other] == 0.0)
                {
                    return true;
                }
            }
        }
        false
    }

    fn run(&self, context: &Context, resources: &mut Resources) -> TestOutcome {
        let base = TestCaseBase::init(context, self.ext_params);

        if !base.is_tessellation_shader_supported {
            return Err(TestError::NotSupported(
                TESSELLATION_SHADER_EXTENSION_NOT_SUPPORTED.to_string(),
            ));
        }

        let utils = Utils::new(context, &base)?;
        let runs = self.init_test(context, &base, &utils, resources)?;

        for run in &runs {
            if run.vertex_spacing != VertexSpacing::FractionalOdd {
                // The vertex data generated for the two passes must match.
                let n_triangles = run.n_vertices as usize / 3;
                let mut triangle_matched = vec![false; n_triangles];

                for n_triangle in 0..n_triangles {
                    let triangle_a = &run.set1_data[n_triangle * 3 * 3..];

                    let mut triangle_found = false;
                    for n_triangle_b in 0..n_triangles {
                        if !triangle_matched[n_triangle_b] {
                            let triangle_b = &run.set2_data[n_triangle_b * 3 * 3..];
                            if is_triangle_defined(triangle_a, triangle_b) {
                                triangle_matched[n_triangle_b] = true;
                                triangle_found = true;
                                break;
                            }
                        }
                    }

                    if !triangle_found {
                        log::info!(
                            "The following triangle, generated in the first pass, was not generated in the second one. {}",
                            Self::describe(run)
                        );
                        return Err(TestError::Fail(
                            "A triangle from first pass' data set was not found in second pass' data set.".to_string(),
                        ));
                    }
                }
            } else {
                // With fractional odd spacing two of the inner edges (the ones subdivided with level 1.0) are subdivided differently between the two runs, so the vertex positions shift and the
                // plain comparison above cannot work. The outermost spans of such a quad are degenerate (epsilon spacing), so the test looks for the two "marker triangles" capping both ends of the inner region.
                let set1_tess_coordinates =
                    Self::unique_tess_coordinates_from_vertex_data_set(&run.set1_data, run.n_vertices);

                let mut set1_tess_coordinates_x_sorted: Vec<f32> = Vec::new();
                let mut set1_tess_coordinates_y_sorted: Vec<f32> = Vec::new();
                for coordinate in &set1_tess_coordinates {
                    if !set1_tess_coordinates_x_sorted.contains(&coordinate[0]) {
                        set1_tess_coordinates_x_sorted.push(coordinate[0]);
                    }
                    if !set1_tess_coordinates_y_sorted.contains(&coordinate[1]) {
                        set1_tess_coordinates_y_sorted.push(coordinate[1]);
                    }
                }
                set1_tess_coordinates_x_sorted.sort_by(f32::total_cmp);
                set1_tess_coordinates_y_sorted.sort_by(f32::total_cmp);

                if set1_tess_coordinates_x_sorted.len() <= 2 || set1_tess_coordinates_y_sorted.len() <= 2 {
                    return Err(TestError::Fail("Too few distinct tessellation coordinates".to_string()));
                }

                if run.set1_inner[0] == 1.0 {
                    // The second horizontal line segment, from the top and from the bottom.
                    let second_y_from_top = set1_tess_coordinates_y_sorted[1];
                    let second_y_from_bottom = set1_tess_coordinates_y_sorted[set1_tess_coordinates_y_sorted.len() - 2];

                    for n in 0..2 {
                        let (y1_y2, y3) = if n == 0 {
                            (second_y_from_bottom, 1.0)
                        } else {
                            (second_y_from_top, 0.0)
                        };
                        if !Self::has_marker_triangle(run, 1, y1_y2, y3) {
                            return Err(TestError::Fail("Could not find a marker triangle".to_string()));
                        }
                    }
                } else {
                    // The second vertical line segment, from the left and from the right.
                    let second_x_from_left = set1_tess_coordinates_x_sorted[1];
                    let second_x_from_right = set1_tess_coordinates_x_sorted[set1_tess_coordinates_x_sorted.len() - 2];

                    for n in 0..2 {
                        let (x1_x2, x3) = if n == 0 {
                            (second_x_from_right, 1.0)
                        } else {
                            (second_x_from_left, 0.0)
                        };
                        if !Self::has_marker_triangle(run, 0, x1_x2, x3) {
                            return Err(TestError::Fail("Could not find a marker triangle (implies invalid quad tessellation for the case considered)".to_string()));
                        }
                    }
                }
            }
        }

        Ok(TestStatus::pass("Pass"))
    }
}

