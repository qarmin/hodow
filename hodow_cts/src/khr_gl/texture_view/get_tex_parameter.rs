use super::check_texture_view_support;
use super::utilities::init_texture_storage;
use crate::glu::{Context, TestCase};
use crate::glw::{self, GLenum, GLfloat, GLint, GLuint};
use crate::tcu::{TestError, TestOutcome, TestStatus};

#[derive(Clone, Copy, PartialEq, Eq)]
enum TestTextureType {
    NoStorageAllocated,
    ImmutableTextureObject,
    MutableTextureObject,
    TextureViewCreatedFromImmutableTextureObject,
    TextureViewCreatedFromTextureView,
}

/// `_test_run`
struct TestRun {
    expected_n_immutable_levels: GLint,
    expected_n_min_layer: GLint,
    expected_n_min_level: GLint,
    expected_n_num_layers: GLint,
    expected_n_num_levels: GLint,

    parent_texture_object_id: GLuint,
    texture_view_object_created_from_immutable_to_id: GLuint,
    texture_view_object_created_from_view_to_id: GLuint,

    texture_target: GLenum,
    texture_type: TestTextureType,
}

/// The test runs of one iteration; `TextureViewTestGetTexParameter::deinit` is the `Drop`.
struct State<'gl> {
    gl: &'gl glw::Functions,
    test_runs: Vec<TestRun>,
}

impl Drop for State<'_> {
    fn drop(&mut self) {
        let gl = self.gl;
        for test_run in &self.test_runs {
            for id in [
                test_run.parent_texture_object_id,
                test_run.texture_view_object_created_from_immutable_to_id,
                test_run.texture_view_object_created_from_view_to_id,
            ] {
                if id != 0 {
                    // SAFETY: the name was generated by init_test_runs and is deleted once.
                    unsafe { gl.delete_textures(1, &id) };
                }
            }
        }
    }
}

impl State<'_> {
    /// `initTestRuns`
    fn init_test_runs(&mut self) -> Result<(), TestError> {
        let gl = self.gl;
        let n_cubemaps_needed = 4;
        let texture_depth = 16;
        let texture_height = 32;
        let texture_width = 64;

        let texture_targets: [GLenum; 10] = [
            glw::GL_TEXTURE_1D,
            glw::GL_TEXTURE_1D_ARRAY,
            glw::GL_TEXTURE_2D,
            glw::GL_TEXTURE_2D_ARRAY,
            glw::GL_TEXTURE_2D_MULTISAMPLE,
            glw::GL_TEXTURE_2D_MULTISAMPLE_ARRAY,
            glw::GL_TEXTURE_3D,
            glw::GL_TEXTURE_CUBE_MAP,
            glw::GL_TEXTURE_CUBE_MAP_ARRAY,
            glw::GL_TEXTURE_RECTANGLE,
        ];
        let texture_types = [
            TestTextureType::NoStorageAllocated,
            TestTextureType::ImmutableTextureObject,
            TestTextureType::MutableTextureObject,
            TestTextureType::TextureViewCreatedFromImmutableTextureObject,
            TestTextureType::TextureViewCreatedFromTextureView,
        ];

        for texture_type in texture_types {
            for texture_target in texture_targets {
                let mut new_test_run = TestRun {
                    expected_n_immutable_levels: 0,
                    expected_n_min_layer: 0,
                    expected_n_min_level: 0,
                    expected_n_num_layers: 0,
                    expected_n_num_levels: 0,
                    parent_texture_object_id: 0,
                    texture_view_object_created_from_immutable_to_id: 0,
                    texture_view_object_created_from_view_to_id: 0,
                    texture_target,
                    texture_type,
                };

                if texture_target == glw::GL_TEXTURE_BUFFER && texture_type == TestTextureType::MutableTextureObject {
                    continue;
                }

                let n_levels_needed: u32 = 6;
                let mut n_min_layer: GLint = 1;
                let mut n_num_layers: GLint = 2;
                let mut n_min_level: GLint = 2;
                let n_num_levels: GLint = 3;
                let mut parent_texture_depth: GLint = texture_depth;
                let mut parent_texture_height: GLint = texture_height;
                let mut parent_texture_width: GLint = texture_width;

                if texture_target == glw::GL_TEXTURE_CUBE_MAP || texture_target == glw::GL_TEXTURE_CUBE_MAP_ARRAY {
                    n_num_layers = 6 * 2;
                    parent_texture_height = 64;
                    parent_texture_width = 64;
                    parent_texture_depth = 64;
                }

                if texture_target == glw::GL_TEXTURE_CUBE_MAP {
                    n_min_layer = 0;
                    n_num_layers = 6;
                }

                if texture_target == glw::GL_TEXTURE_CUBE_MAP_ARRAY {
                    n_min_layer = 0;
                }

                if texture_target == glw::GL_TEXTURE_1D
                    || texture_target == glw::GL_TEXTURE_2D
                    || texture_target == glw::GL_TEXTURE_2D_MULTISAMPLE
                    || texture_target == glw::GL_TEXTURE_3D
                    || texture_target == glw::GL_TEXTURE_RECTANGLE
                {
                    n_min_layer = 0;
                    n_num_layers = 1;
                }

                if texture_target == glw::GL_TEXTURE_2D_MULTISAMPLE
                    || texture_target == glw::GL_TEXTURE_2D_MULTISAMPLE_ARRAY
                    || texture_target == glw::GL_TEXTURE_RECTANGLE
                {
                    n_min_level = 0;
                }

                gl_call!(
                    gl,
                    "glGenTextures() call failed",
                    gl.gen_textures(1, &mut new_test_run.parent_texture_object_id)
                );
                // The state owns the name from here on, so it is deleted even if a later call fails.
                let parent_index = self.test_runs.len();
                self.test_runs.push(new_test_run);
                let new_test_run = &mut self.test_runs[parent_index];

                gl_call!(
                    gl,
                    "glBindTexture() call failed",
                    gl.bind_texture(texture_target, new_test_run.parent_texture_object_id)
                );

                if texture_type != TestTextureType::NoStorageAllocated {
                    init_texture_storage(
                        gl,
                        texture_type == TestTextureType::MutableTextureObject,
                        texture_target,
                        parent_texture_depth,
                        parent_texture_height,
                        parent_texture_width,
                        glw::GL_RGBA8,
                        glw::GL_RGBA,
                        glw::GL_UNSIGNED_BYTE,
                        n_levels_needed,
                        n_cubemaps_needed,
                        0,
                    )?;
                }

                if texture_type == TestTextureType::ImmutableTextureObject
                    || texture_type == TestTextureType::TextureViewCreatedFromImmutableTextureObject
                    || texture_type == TestTextureType::TextureViewCreatedFromTextureView
                {
                    new_test_run.expected_n_immutable_levels = n_levels_needed as GLint;
                    new_test_run.expected_n_num_layers = 1;
                    new_test_run.expected_n_num_levels = n_levels_needed as GLint;

                    match texture_target {
                        glw::GL_TEXTURE_1D_ARRAY => {
                            new_test_run.expected_n_num_layers = texture_height;
                        }
                        glw::GL_TEXTURE_CUBE_MAP => {
                            new_test_run.expected_n_num_layers = 6;
                        }
                        glw::GL_TEXTURE_RECTANGLE => {
                            new_test_run.expected_n_immutable_levels = 1;
                            new_test_run.expected_n_num_levels = 1;
                        }
                        glw::GL_TEXTURE_2D_ARRAY => {
                            new_test_run.expected_n_num_layers = texture_depth;
                        }
                        glw::GL_TEXTURE_2D_MULTISAMPLE => {
                            new_test_run.expected_n_immutable_levels = 1;
                            new_test_run.expected_n_num_levels = 1;
                        }
                        glw::GL_TEXTURE_2D_MULTISAMPLE_ARRAY => {
                            new_test_run.expected_n_immutable_levels = 1;
                            new_test_run.expected_n_num_levels = 1;
                            new_test_run.expected_n_num_layers = texture_depth;
                        }
                        glw::GL_TEXTURE_CUBE_MAP_ARRAY => {
                            let actual_texture_depth = 6 * n_cubemaps_needed as GLint;
                            new_test_run.expected_n_num_layers = actual_texture_depth;
                        }
                        _ => {}
                    }
                }

                if texture_type == TestTextureType::TextureViewCreatedFromImmutableTextureObject
                    || texture_type == TestTextureType::TextureViewCreatedFromTextureView
                {
                    let n_iterations = if texture_type == TestTextureType::TextureViewCreatedFromTextureView {
                        2
                    } else {
                        1
                    };

                    for n_iteration in 0..n_iterations {
                        let parent_id = if n_iteration == 0 {
                            new_test_run.parent_texture_object_id
                        } else {
                            new_test_run.texture_view_object_created_from_immutable_to_id
                        };

                        let view_id_ptr: &mut GLuint = if n_iteration == 0 {
                            &mut new_test_run.texture_view_object_created_from_immutable_to_id
                        } else {
                            &mut new_test_run.texture_view_object_created_from_view_to_id
                        };

                        gl_call!(gl, "glGenTextures() call failed", gl.gen_textures(1, view_id_ptr));
                        let view_id = *view_id_ptr;

                        gl_call!(
                            gl,
                            "glTextureView() call failed",
                            gl.texture_view(
                                view_id,
                                new_test_run.texture_target,
                                parent_id,
                                glw::GL_RGBA8,
                                n_min_level as u32,
                                n_num_levels as u32,
                                n_min_layer as u32,
                                n_num_layers as u32
                            )
                        );

                        let mut parent_min_level: GLint = -1;
                        let mut parent_min_layer: GLint = -1;
                        let mut parent_num_layers: GLint = -1;
                        let mut parent_num_levels: GLint = -1;
                        let mut parent_n_immutable_levels: GLint = -1;

                        gl_call!(
                            gl,
                            "glBindTexture() call failed",
                            gl.bind_texture(texture_target, parent_id)
                        );

                        gl_call!(
                            gl,
                            "glGetTexParameteriv() failed for GL_TEXTURE_IMMUTABLE_LEVELS pname queried for parent object",
                            gl.get_tex_parameteriv(
                                texture_target,
                                glw::GL_TEXTURE_IMMUTABLE_LEVELS,
                                &mut parent_n_immutable_levels
                            )
                        );
                        gl_call!(
                            gl,
                            "glGetTexParameteriv() failed for GL_TEXTURE_VIEW_MIN_LAYER pname queried for parent object",
                            gl.get_tex_parameteriv(
                                texture_target,
                                glw::GL_TEXTURE_VIEW_MIN_LAYER,
                                &mut parent_min_layer
                            )
                        );
                        gl_call!(
                            gl,
                            "glGetTexParameteriv() failed for GL_TEXTURE_VIEW_MIN_LEVEL pname queried for parent object",
                            gl.get_tex_parameteriv(
                                texture_target,
                                glw::GL_TEXTURE_VIEW_MIN_LEVEL,
                                &mut parent_min_level
                            )
                        );
                        gl_call!(
                            gl,
                            "glGetTexParameteriv() failed for GL_TEXTURE_VIEW_NUM_LAYERS pname queried for parent object",
                            gl.get_tex_parameteriv(
                                texture_target,
                                glw::GL_TEXTURE_VIEW_NUM_LAYERS,
                                &mut parent_num_layers
                            )
                        );
                        gl_call!(
                            gl,
                            "glGetTexParameteriv() failed for GL_TEXTURE_VIEW_NUM_LEVELS pname queried for parent object",
                            gl.get_tex_parameteriv(
                                texture_target,
                                glw::GL_TEXTURE_VIEW_NUM_LEVELS,
                                &mut parent_num_levels
                            )
                        );

                        new_test_run.expected_n_immutable_levels = parent_n_immutable_levels;
                        new_test_run.expected_n_min_level = n_min_level + parent_min_level;
                        new_test_run.expected_n_min_layer = n_min_layer + parent_min_layer;

                        if (parent_num_layers - n_min_layer) < n_num_layers {
                            new_test_run.expected_n_num_layers = parent_num_layers - n_min_layer;
                        } else {
                            new_test_run.expected_n_num_layers = n_num_layers;
                        }

                        if (parent_num_levels - n_min_level) < n_num_levels {
                            new_test_run.expected_n_num_levels = parent_num_levels - n_min_level;
                        } else {
                            new_test_run.expected_n_num_levels = n_num_levels;
                        }
                    }
                }
            }
        }

        Ok(())
    }
}

/// One `glGetTexParameterfv`/`glGetTexParameteriv` pair of the iterate loop, compared with the expected value.
fn verify_pname(
    gl: &glw::Functions,
    texture_target: GLenum,
    pname: GLenum,
    pname_name: &str,
    expected: GLint,
) -> Result<(), TestError> {
    let mut value_float: GLfloat = -1.0;
    let mut value_int: GLint = -1;

    gl_call!(
        gl,
        &format!("glGetTexParameterfv() failed for {pname_name} pname"),
        gl.get_tex_parameterfv(texture_target, pname, &mut value_float)
    );
    gl_call!(
        gl,
        &format!("glGetTexParameteriv() failed for {pname_name} pname"),
        gl.get_tex_parameteriv(texture_target, pname, &mut value_int)
    );

    let epsilon = 1e-5f32;

    if (value_float - expected as f32).abs() > epsilon {
        log::info!(
            "Invalid floating-point value reported for {pname_name} pname (expected: {expected} found: {value_float})."
        );

        return Err(TestError::Fail(format!(
            "Invalid FP value reported for {pname_name} pname"
        )));
    }

    if value_int != expected {
        log::info!("Invalid integer value reported for {pname_name} pname (expected: {expected} found: {value_int}).");

        return Err(TestError::Fail(format!(
            "Invalid FP value reported for {pname_name} pname"
        )));
    }

    Ok(())
}

/// `TextureViewTestGetTexParameter`
pub(super) struct GetTexParameter;

impl TestCase for GetTexParameter {
    fn name(&self) -> &str {
        "gettexparameter"
    }

    fn iterate(&self, context: &Context) -> TestOutcome {
        let gl = context.gl();

        check_texture_view_support(context)?;

        let mut state = State {
            gl,
            test_runs: Vec::new(),
        };
        state.init_test_runs()?;

        for test_run in &state.test_runs {
            let texture_object_id = match test_run.texture_type {
                TestTextureType::ImmutableTextureObject
                | TestTextureType::MutableTextureObject
                | TestTextureType::NoStorageAllocated => test_run.parent_texture_object_id,
                TestTextureType::TextureViewCreatedFromImmutableTextureObject => {
                    test_run.texture_view_object_created_from_immutable_to_id
                }
                TestTextureType::TextureViewCreatedFromTextureView => {
                    test_run.texture_view_object_created_from_view_to_id
                }
            };

            gl_call!(
                gl,
                "glBindTexture() call failed",
                gl.bind_texture(test_run.texture_target, texture_object_id)
            );

            verify_pname(
                gl,
                test_run.texture_target,
                glw::GL_TEXTURE_IMMUTABLE_LEVELS,
                "GL_TEXTURE_IMMUTABLE_LEVELS",
                test_run.expected_n_immutable_levels,
            )?;
            verify_pname(
                gl,
                test_run.texture_target,
                glw::GL_TEXTURE_VIEW_MIN_LAYER,
                "GL_TEXTURE_VIEW_MIN_LAYER",
                test_run.expected_n_min_layer,
            )?;
            verify_pname(
                gl,
                test_run.texture_target,
                glw::GL_TEXTURE_VIEW_MIN_LEVEL,
                "GL_TEXTURE_VIEW_MIN_LEVEL",
                test_run.expected_n_min_level,
            )?;
            verify_pname(
                gl,
                test_run.texture_target,
                glw::GL_TEXTURE_VIEW_NUM_LAYERS,
                "GL_TEXTURE_VIEW_NUM_LAYERS",
                test_run.expected_n_num_layers,
            )?;
            verify_pname(
                gl,
                test_run.texture_target,
                glw::GL_TEXTURE_VIEW_NUM_LEVELS,
                "GL_TEXTURE_VIEW_NUM_LEVELS",
                test_run.expected_n_num_levels,
            )?;
        }

        Ok(TestStatus::pass("Pass"))
    }
}
