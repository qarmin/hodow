/// The `GL_ARB_texture_view` check every case starts its `iterate` with.
fn check_texture_view_support(context: &Context) -> Result<(), TestError> {
    if !context.context_info.is_extension_supported("GL_ARB_texture_view") {
        return Err(TestError::NotSupported(
            "GL_ARB_texture_view is not supported".to_string(),
        ));
    }
    Ok(())
}

/// `glShaderSource` of a single string.
fn shader_source(gl: &glw::Functions, id: GLuint, body: &str, message: &str) -> Result<(), TestError> {
    let source = CString::new(body).map_err(|_| TestError::Fail("Shader source contains a NUL".to_string()))?;
    let source_ptr = source.as_ptr();
    gl_call!(gl, message, gl.shader_source(id, 1, &source_ptr, std::ptr::null()));
    Ok(())
}

/// `glCompileShader` followed by the compile status check that upstream only logs.
fn compile_shader(gl: &glw::Functions, id: GLuint) -> Result<(), TestError> {
    gl_call!(gl, "glCompileShader() call failed.", gl.compile_shader(id));

    let mut compile_status = glw::GL_FALSE as GLint;
    gl_call!(
        gl,
        "glGetShaderiv() call failed.",
        gl.get_shaderiv(id, glw::GL_COMPILE_STATUS, &mut compile_status)
    );

    if compile_status != glw::GL_TRUE as GLint {
        log::info!("Shader compilation failed");
    }
    Ok(())
}

/// `glLinkProgram` followed by the link status check that is a TCU_FAIL.
fn link_program(gl: &glw::Functions, id: GLuint, link_message: &str) -> Result<(), TestError> {
    gl_call!(gl, link_message, gl.link_program(id));

    let mut link_status = glw::GL_FALSE as GLint;
    gl_call!(
        gl,
        "glGetProgramiv() failed for GL_LINK_STATUS pname",
        gl.get_programiv(id, glw::GL_LINK_STATUS, &mut link_status)
    );

    if link_status != glw::GL_TRUE as GLint {
        return Err(TestError::Fail("Program linking failed".to_string()));
    }
    Ok(())
}

/// `glGetUniformLocation`
fn uniform_location(gl: &glw::Functions, id: GLuint, name: &str) -> GLint {
    let name = CString::new(name).expect("uniform names have no NUL");
    // SAFETY: the name is a live NUL-terminated string.
    unsafe { gl.get_uniform_location(id, name.as_ptr()) }
}

