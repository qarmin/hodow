/// `compareUintColors`
fn compare_uint_colors(color: u32, reference: u32, epsilon: i32) -> bool {
    (0..4).all(|channel| {
        let shift = channel * 8;
        let have = ((color >> shift) & 0xFF) as i32;
        let want = ((reference >> shift) & 0xFF) as i32;
        have >= want - epsilon && have <= want + epsilon
    })
}

