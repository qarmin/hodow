/// `PrepareProgram`; every failure is upstream's `throw 0` after the program is deleted.
fn prepare_program(
    gl: &glw::Functions,
    fragment_declaration: &str,
    fragment_tail: &str,
) -> Result<glw::GLuint, TestError> {
    // SAFETY: plain object creation with a current context.
    let po = unsafe { gl.create_program() };

    let linked = (|| -> Result<bool, TestError> {
        glu::expect_no_error(gl, "glCreateProgram call failed.")?;

        let vertex = Shader::new(gl, glw::GL_VERTEX_SHADER)?;
        let fragment = Shader::new(gl, glw::GL_FRAGMENT_SHADER)?;
        let vertex_parts = [VERTEX_SHADER];
        let fragment_parts = [FRAGMENT_SHADER_HEAD, fragment_declaration, fragment_tail];

        for (shader, parts) in [(&vertex, &vertex_parts[..]), (&fragment, &fragment_parts[..])] {
            // SAFETY: both objects are alive.
            unsafe { gl.attach_shader(po, shader.id) };
            glu::expect_no_error(gl, "glAttachShader call failed.")?;

            shader.source(parts)?;

            if !shader.compile()? {
                log::info!(
                    "Shader compilation has failed.\nShader source code:\n{}",
                    parts.concat()
                );
                return Ok(false);
            }
        }

        // SAFETY: the status is written to a live local.
        unsafe { gl.link_program(po) };
        glu::expect_no_error(gl, "glTransformFeedbackVaryings call failed.")?;

        let mut status = glw::GL_FALSE as glw::GLint;
        // SAFETY: as above.
        unsafe { gl.get_programiv(po, glw::GL_LINK_STATUS, &mut status) };
        if status != glw::GL_TRUE as glw::GLint {
            log::info!("Program linkage has failed.");
            return Ok(false);
        }

        for shader in [&vertex, &fragment] {
            // SAFETY: both objects are alive and attached.
            unsafe { gl.detach_shader(po, shader.id) };
            glu::expect_no_error(gl, "glDetachShader call failed.")?;
        }
        Ok(true)
    })();

    if matches!(linked, Ok(true)) {
        return Ok(po);
    }
    // SAFETY: deletes the program created above.
    unsafe { gl.delete_program(po) };
    Err(throw_zero())
}

