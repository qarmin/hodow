fn get_error(gl: &glw::Functions) -> glw::GLenum {
    gl!(gl.get_error())
}

/// 4.1.1 NegativeAPIBind
#[derive(Default)]
pub(super) struct NegativeApiBind;

impl Subcase for NegativeApiBind {
    fn run(&mut self, context: &Context) -> SubcaseResult {
        let gl = context.gl();
        let bindings = get_integer(gl, glw::GL_MAX_SHADER_STORAGE_BUFFER_BINDINGS);
        let alignment = get_integer(gl, glw::GL_SHADER_STORAGE_BUFFER_OFFSET_ALIGNMENT);

        gl!(gl.bind_buffer_base(glw::GL_SHADER_STORAGE_BUFFER, bindings as GLuint, 0));
        if get_error(gl) != glw::GL_INVALID_VALUE {
            log::info!(
                "INVALID_VALUE is generated by BindBufferBase if <target> is\nSHADER_STORAGE_BUFFER and <index> is greater than or equal to the value of\nMAX_SHADER_STORAGE_BUFFER_BINDINGS."
            );
            return Ok(ERROR);
        }

        gl!(gl.bind_buffer_range(glw::GL_SHADER_STORAGE_BUFFER, bindings as GLuint, 0, 0, 0));
        if get_error(gl) != glw::GL_INVALID_VALUE {
            log::info!(
                "INVALID_VALUE is generated by BindBufferRange if <target> is\nSHADER_STORAGE_BUFFER and <index> is greater than or equal to the value of\nMAX_SHADER_STORAGE_BUFFER_BINDINGS."
            );
            return Ok(ERROR);
        }

        gl!(gl.bind_buffer_range(glw::GL_SHADER_STORAGE_BUFFER, 0, 0, (alignment - 1) as isize, 0));
        if get_error(gl) != glw::GL_INVALID_VALUE {
            log::info!(
                "INVALID_VALUE is generated by BindBufferRange if <target> is\nSHADER_STORAGE_BUFFER and <offset> is not a multiple of the value of\nSHADER_STORAGE_BUFFER_OFFSET_ALIGNMENT."
            );
            return Ok(ERROR);
        }

        Ok(NO_ERROR)
    }
}

/// 4.1.2 NegativeAPIBlockBinding
#[derive(Default)]
pub(super) struct NegativeApiBlockBinding;

impl Subcase for NegativeApiBlockBinding {
    fn run(&mut self, context: &Context) -> SubcaseResult {
        let gl = context.gl();
        if !supported_in_vs(gl, 1) {
            return Ok(NOT_SUPPORTED);
        }
        let bindings = get_integer(gl, glw::GL_MAX_SHADER_STORAGE_BUFFER_BINDINGS);

        let glsl_vs = CString::new("#version 430 core\nbuffer Buffer {\n  int x;\n};\nvoid main() {\n  x = 0;\n}")
            .expect("no NUL");
        let source_pointer = glsl_vs.as_ptr();
        let sh = gl!(gl.create_shader(glw::GL_VERTEX_SHADER));
        gl!(gl.shader_source(sh, 1, &source_pointer, std::ptr::null()));
        gl!(gl.compile_shader(sh));

        let p = gl!(gl.create_program());
        gl!(gl.attach_shader(p, sh));
        gl!(gl.delete_shader(sh));
        gl!(gl.link_program(p));

        gl!(gl.shader_storage_block_binding(p, 0, bindings as GLuint));
        if get_error(gl) != glw::GL_INVALID_VALUE {
            log::info!(
                "An INVALID_VALUE error is generated if storageBlockBinding is\ngreater than or equal to the value of MAX_SHADER_STORAGE_BUFFER_BINDINGS."
            );
            gl!(gl.delete_program(p));
            return Ok(ERROR);
        }

        gl!(gl.shader_storage_block_binding(p, 1, 0));
        if get_error(gl) != glw::GL_INVALID_VALUE {
            log::info!(
                "An INVALID_VALUE error is generated if storageBlockIndex is not an\nactive shader storage block index in program."
            );
            gl!(gl.delete_program(p));
            return Ok(ERROR);
        }

        gl!(gl.shader_storage_block_binding(0, 0, 0));
        if get_error(gl) != glw::GL_INVALID_VALUE {
            log::info!(
                "An INVALID_VALUE error is generated if program is not the name of either a program or shader object."
            );
            gl!(gl.delete_program(p));
            return Ok(ERROR);
        }

        gl!(gl.shader_storage_block_binding(sh, 0, 0));
        if get_error(gl) != glw::GL_INVALID_OPERATION {
            log::info!("An INVALID_OPERATION error is generated if program is the name of a shader object.");
            gl!(gl.delete_program(p));
            return Ok(ERROR);
        }

        gl!(gl.delete_program(p));
        Ok(NO_ERROR)
    }
}

/// 4.2.1 NegativeGLSLCompileTime
#[derive(Default)]
pub(super) struct NegativeGlslCompileTime;

impl NegativeGlslCompileTime {
    fn shader1(binding: i32) -> String {
        format!("\nlayout(binding = {binding}) buffer Buffer {{\n  int x;\n}};\nvoid main() {{\n  x = 0;\n}}")
    }

    fn shader2(binding: i32) -> String {
        format!(
            "\nlayout(binding = {binding}) buffer Buffer {{\n  int x;\n}} g_array[4];\nvoid main() {{\n  g_array[0].x = 0;\n  g_array[1].x = 0;\n  g_array[2].x = 0;\n  g_array[3].x = 0;\n}}"
        )
    }

    fn compile(gl: &glw::Functions, source: &str) -> bool {
        let cs_ver = CString::new("#version 430 core").expect("no NUL");
        let source = CString::new(source).expect("no NUL");
        let src = [cs_ver.as_ptr(), source.as_ptr()];
        let sh = gl!(gl.create_shader(glw::GL_FRAGMENT_SHADER));
        gl!(gl.shader_source(sh, 2, src.as_ptr(), std::ptr::null()));
        gl!(gl.compile_shader(sh));

        let mut info_log = [0u8; 1024];
        gl!(gl.get_shader_info_log(
            sh,
            info_log.len() as i32,
            std::ptr::null_mut(),
            info_log.as_mut_ptr().cast()
        ));
        let end = info_log.iter().position(|&byte| byte == 0).unwrap_or(info_log.len());
        log::info!("Shader Info Log:\n{}", String::from_utf8_lossy(&info_log[..end]));

        let mut status: GLint = 0;
        gl!(gl.get_shaderiv(sh, glw::GL_COMPILE_STATUS, &mut status));
        gl!(gl.delete_shader(sh));

        if status == glw::GL_TRUE as GLint {
            log::info!("Compilation should fail.");
            return false;
        }

        true
    }
}

impl Subcase for NegativeGlslCompileTime {
    fn run(&mut self, context: &Context) -> SubcaseResult {
        let gl = context.gl();
        let bindings = get_integer(gl, glw::GL_MAX_SHADER_STORAGE_BUFFER_BINDINGS);

        let sources: [String; 17] = [
            // initialization of buffer block member 'x' not allowed
            "\nbuffer Buffer { int x = 10; };\nvoid main() {\n  x = 0;\n}".to_string(),
            // syntax error, unexpected '-', expecting integer constant or unsigned integer constant at token "-"
            Self::shader1(-1),
            // invalid value 96 for layout specifier 'binding'
            Self::shader1(bindings),
            // invalid value 98 for layout specifier 'binding'
            Self::shader2(bindings - 2),
            // OpenGL does not allow declaring buffer variable 'x' in the global scope. Use buffer blocks instead
            "\nbuffer int x;\nvoid main() {\n  x = 0;\n}".to_string(),
            // OpenGL requires buffer variables to be declared in a shader storage block in the global scope
            "\nbuffer Buffer { int y; };\nvoid main() {\n  y = 0;\n  buffer int x = 0;\n}".to_string(),
            // OpenGL does not allow a parameter to be a buffer
            "\nbuffer Buffer { int y; };\nvoid Modify(buffer int a) {\n  atomicAdd(a, 1);\n}\nvoid main() {\n  Modify(y);\n}".to_string(),
            // layout specifier 'std430', incompatible with 'uniform blocks'
            "\nlayout(std430) uniform UBO { int x; };\nbuffer SSBO { int y; };\nvoid main() {\n  y = x;\n}".to_string(),
            // unknown layout specifier 'std430'
            "\nbuffer SSBO {\n  layout(std430) int x;\n};\nvoid main() {\n  x = 0;\n}".to_string(),
            // unknown layout specifier 'binding = 1'
            "\nbuffer SSBO {\n  layout(binding = 1) int x;\n};\nvoid main() {\n  x = 0;\n}".to_string(),
            // OpenGL does not allow writing to readonly variable 'x'
            "\nreadonly buffer SSBO {\n  int x;\n};\nvoid main() {\n  x = 0;\n}".to_string(),
            // OpenGL does not allow reading writeonly variable 'y'
            "\nbuffer SSBO {\n  int x;\n};\nwriteonly buffer SSBO2 {\n  int y;\n};\nvoid main() {\n  x = y;\n}".to_string(),
            // OpenGL does not allow writing to readonly variable 'z'
            "\nbuffer SSBO {\n  int x;\n};\nbuffer SSBO2 {\n  writeonly int y;\n  readonly int z;\n};\nvoid main() {\n  x = y;\n  z = 0;\n}".to_string(),
            // OpenGL does not allow having both readonly and writeonly qualifiers on a variable
            "\nbuffer SSBO {\n  int x;\n};\nreadonly buffer SSBO2 {\n  writeonly int y;\n};\nvoid main() {\n  x = y;\n}".to_string(),
            // "layout(binding = 1) buffer;" should cause compile-time error
            "\nlayout(binding = 1) buffer;\nbuffer SSBO {\n  int x;\n};\nvoid main() {\n  x = 0;\n}".to_string(),
            // "  atomicAdd(y, 2);"  should cause compile-time error
            "\nbuffer Buffer { int x; };\nint y;\nvoid main() {\n  atomicAdd(x, 1);\n  atomicAdd(y, 2);\n}".to_string(),
            // can't construct vector from an array
            "\nbuffer b {\n  vec4 x[10];\n};\nvoid main() {\n  vec4 y = vec4(x);\n}".to_string(),
        ];

        for source in sources.iter() {
            if !Self::compile(gl, source) {
                return Ok(ERROR);
            }
        }

        Ok(NO_ERROR)
    }
}

/// 4.2.2 NegativeGLSLLinkTime
#[derive(Default)]
pub(super) struct NegativeGlslLinkTime;

impl NegativeGlslLinkTime {
    fn attach_fragment(gl: &glw::Functions, program: GLuint, source: &str, which: &str) -> bool {
        let sh = gl!(gl.create_shader(glw::GL_FRAGMENT_SHADER));
        gl!(gl.attach_shader(program, sh));
        gl!(gl.delete_shader(sh));
        let source = CString::new(source).expect("no NUL");
        let source_pointer = source.as_ptr();
        gl!(gl.shader_source(sh, 1, &source_pointer, std::ptr::null()));
        gl!(gl.compile_shader(sh));

        let mut status: GLint = 0;
        gl!(gl.get_shaderiv(sh, glw::GL_COMPILE_STATUS, &mut status));
        if status == glw::GL_FALSE as GLint {
            gl!(gl.delete_program(program));
            log::info!("{which} compilation should be ok.");
            return false;
        }
        true
    }

    fn link(gl: &glw::Functions, cs0: &str, cs1: &str) -> bool {
        let p = gl!(gl.create_program());

        if !Self::attach_fragment(gl, p, cs0, "VS0") {
            return false;
        }
        if !Self::attach_fragment(gl, p, cs1, "VS1") {
            return false;
        }

        gl!(gl.link_program(p));

        let mut info_log = [0u8; 1024];
        gl!(gl.get_program_info_log(
            p,
            info_log.len() as i32,
            std::ptr::null_mut(),
            info_log.as_mut_ptr().cast()
        ));
        let end = info_log.iter().position(|&byte| byte == 0).unwrap_or(info_log.len());
        log::info!("Program Info Log:\n{}", String::from_utf8_lossy(&info_log[..end]));

        let mut status: GLint = 0;
        gl!(gl.get_programiv(p, glw::GL_LINK_STATUS, &mut status));
        gl!(gl.delete_program(p));

        if status == glw::GL_TRUE as GLint {
            log::info!("Link operation should fail.");
            return false;
        }

        true
    }
}

impl Subcase for NegativeGlslLinkTime {
    fn run(&mut self, context: &Context) -> SubcaseResult {
        let gl = context.gl();

        let pairs: [(&str, &str); 4] = [
            // declaration of "x" conflicts with previous declaration at 0(4)
            (
                "#version 430 core\nbuffer Buffer { int x; };\nvoid Run();\nvoid main() {\n  Run();\n  x += 2;\n}",
                "#version 430 core\nbuffer Buffer { uint x; };\nvoid Run() {\n  x += 3;\n}",
            ),
            // declaration of "Buffer" conflicts with previous declaration at 0(4)
            (
                "#version 430 core\nbuffer Buffer { int x; int y; };\nvoid Run();\nvoid main() {\n  Run();\n  x += 2;\n}",
                "#version 430 core\nbuffer Buffer { int x; };\nvoid Run() {\n  x += 3;\n}",
            ),
            // declaration of "Buffer" conflicts with previous declaration at 0(4)
            (
                "#version 430 core\nbuffer Buffer { int y; };\nvoid Run();\nvoid main() {\n  Run();\n  y += 2;\n}",
                "#version 430 core\nbuffer Buffer { int x; };\nvoid Run() {\n  x += 3;\n}",
            ),
            // declaration of "g_buffer" conflicts with previous declaration at 0(4)
            (
                "#version 430 core\nbuffer Buffer { int x; } g_buffer[2];\nvoid Run();\nvoid main() {\n  Run();\n  g_buffer[0].x += 2;\n}",
                "#version 430 core\nbuffer Buffer { int x; } g_buffer[3];\nvoid Run() {\n  g_buffer[1].x += 3;\n}",
            ),
        ];

        for (cs0, cs1) in pairs {
            if !Self::link(gl, cs0, cs1) {
                return Ok(ERROR);
            }
        }

        Ok(NO_ERROR)
    }
}
