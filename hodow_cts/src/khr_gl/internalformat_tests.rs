/// `RenderbufferCase::prepareColoringProgramSources`, the core-profile branch.
fn prepare_coloring_program_sources(
    context: &Context,
    format: GLenum,
    type_: GLenum,
) -> Result<ProgramSources, TestError> {
    let version_declaration = format!("{}\n", context.context_type().glsl_version().declaration());

    let vs = format!(
        "{version_declaration}in highp vec3 position;\nin highp vec4 color;\nout highp vec4 fColor;\nuniform mat4 mvpMatrix;\nvoid main()\n{{\n  fColor = color;\n  gl_Position = mvpMatrix * vec4(position, 1.0);\n}}\n"
    );
    let fs = format!(
        "{version_declaration}in highp vec4 fColor;\nout ${{COLOR_DATA}} color;\nvoid main()\n{{\n  color = ${{COMPUTE_COLOR}};\n}}\n"
    );

    let mut params: Vec<(&str, String)> = Vec::new();
    if format == glw::GL_RGBA_INTEGER {
        const COMPUTE_COLOR: &str = "${COLOR_DATA}(${MAX_RED} * fColor.r, ${MAX_GREEN} * fColor.g, ${MAX_BLUE} * fColor.b, ${MAX_ALPHA} * fColor.a)";

        let (max_color, max_alpha) = if type_ == glw::GL_UNSIGNED_INT_2_10_10_10_REV {
            ("1023", "3")
        } else {
            ("255", "255")
        };
        params.push(("MAX_RED", max_color.to_string()));
        params.push(("MAX_GREEN", max_color.to_string()));
        params.push(("MAX_BLUE", max_color.to_string()));
        params.push(("MAX_ALPHA", max_alpha.to_string()));
        params.push(("COLOR_DATA", "uvec4".to_string()));
        let compute_color = specialize(COMPUTE_COLOR, &params)?;
        params.push(("COMPUTE_COLOR", compute_color));
    } else {
        params.push(("COLOR_DATA", "highp vec4".to_string()));
        params.push(("COMPUTE_COLOR", "fColor".to_string()));
    }

    Ok(ProgramSources::vtx_frag(
        specialize(&vs, &params)?,
        specialize(&fs, &params)?,
    ))
}

/// `RenderbufferCase::convertUInt` and `convertUInt_2_10_10_10_rev`: the integer read-back scaled into a normalized surface.
fn convert_uint_pixels(pixels: &[u8], dst: &mut Surface, width: i32, height: i32, scale: [f32; 4]) {
    let mut access = dst.get_access();
    for y in 0..height {
        for x in 0..width {
            let offset = (y as usize * width as usize + x as usize) * 16;
            let mut dst_pixel = [0.0f32; 4];
            for (k, value) in dst_pixel.iter_mut().enumerate() {
                let bytes: [u8; 4] = pixels[offset + k * 4..offset + k * 4 + 4]
                    .try_into()
                    .expect("four bytes");
                *value = u32::from_ne_bytes(bytes) as f32 / scale[k];
            }
            access.set_pixel(dst_pixel, x as u32, y as u32, 0);
        }
    }
}

