/// The `m_fbo`, `m_rbColor`, `m_rbDepth` and `m_rbStencil` members of `RenderbufferCase`; `delete` is `deleteFramebuffer`.
struct RenderbufferFbo<'gl> {
    gl: &'gl glw::Functions,
    fbo: GLuint,
    rb_color: GLuint,
    rb_depth: GLuint,
    rb_stencil: GLuint,
}

impl<'gl> RenderbufferFbo<'gl> {
    fn new(gl: &'gl glw::Functions) -> Self {
        Self {
            gl,
            fbo: 0,
            rb_color: 0,
            rb_depth: 0,
            rb_stencil: 0,
        }
    }

    /// `createAndAttachRenderBuffer`
    fn create_and_attach_render_buffer(
        &self,
        rb_format: GLenum,
        fb_attachment: GLenum,
        width: i32,
        height: i32,
    ) -> Result<GLuint, TestError> {
        let mut rb_name: GLuint = 0;
        // SAFETY: a current context and a live local.
        unsafe {
            self.gl.gen_renderbuffers(1, &mut rb_name);
            self.gl.bind_renderbuffer(glw::GL_RENDERBUFFER, rb_name);
            self.gl
                .renderbuffer_storage(glw::GL_RENDERBUFFER, rb_format, width, height);
        }
        glu::expect_no_error(self.gl, "glRenderbufferStorage")?;
        // SAFETY: the renderbuffer was just created.
        unsafe {
            self.gl
                .framebuffer_renderbuffer(glw::GL_FRAMEBUFFER, fb_attachment, glw::GL_RENDERBUFFER, rb_name)
        };
        glu::expect_no_error(self.gl, "glFramebufferRenderbuffer")?;
        Ok(rb_name)
    }

    /// `createFramebuffer`; an unsupported or incomplete framebuffer is a not-supported result.
    fn create(&mut self, test_format: &RenderbufferFormat, width: i32, height: i32) -> Result<(), TestError> {
        // SAFETY: a current context and a live field.
        unsafe {
            self.gl.gen_framebuffers(1, &mut self.fbo);
            self.gl.bind_framebuffer(glw::GL_FRAMEBUFFER, self.fbo);
        }

        if test_format.type_ == RenderbufferType::Color {
            self.rb_color =
                self.create_and_attach_render_buffer(test_format.format, glw::GL_COLOR_ATTACHMENT0, width, height)?;
            self.rb_depth = self.create_and_attach_render_buffer(
                glw::GL_DEPTH_COMPONENT16,
                glw::GL_DEPTH_ATTACHMENT,
                width,
                height,
            )?;
        } else {
            self.rb_color =
                self.create_and_attach_render_buffer(glw::GL_RGBA8, glw::GL_COLOR_ATTACHMENT0, width, height)?;
            match test_format.type_ {
                RenderbufferType::Depth => {
                    self.rb_depth = self.create_and_attach_render_buffer(
                        test_format.format,
                        glw::GL_DEPTH_ATTACHMENT,
                        width,
                        height,
                    )?
                }
                RenderbufferType::Stencil => {
                    self.rb_stencil = self.create_and_attach_render_buffer(
                        test_format.format,
                        glw::GL_STENCIL_ATTACHMENT,
                        width,
                        height,
                    )?
                }
                RenderbufferType::DepthStencil => {
                    self.rb_depth = self.create_and_attach_render_buffer(
                        test_format.format,
                        glw::GL_DEPTH_STENCIL_ATTACHMENT,
                        width,
                        height,
                    )?
                }
                RenderbufferType::Color => {}
            }
        }

        // SAFETY: a current context.
        let buffer_status = unsafe { self.gl.check_framebuffer_status(glw::GL_FRAMEBUFFER) };
        if buffer_status == glw::GL_FRAMEBUFFER_UNSUPPORTED {
            Err(TestError::NotSupported("Unsuported framebuffer".to_string()))
        } else if buffer_status != glw::GL_FRAMEBUFFER_COMPLETE {
            Err(TestError::NotSupported("Framebuffer not complete".to_string()))
        } else {
            Ok(())
        }
    }

    fn delete(&mut self) {
        // SAFETY: a current context; zero names are skipped.
        unsafe {
            self.gl.bind_framebuffer(glw::GL_FRAMEBUFFER, 0);
            if self.fbo != 0 {
                self.gl.delete_framebuffers(1, &self.fbo);
            }
            if self.rb_color != 0 {
                self.gl.delete_renderbuffers(1, &self.rb_color);
            }
            if self.rb_depth != 0 {
                self.gl.delete_renderbuffers(1, &self.rb_depth);
            }
            if self.rb_stencil != 0 {
                self.gl.delete_renderbuffers(1, &self.rb_stencil);
            }
        }
        self.fbo = 0;
        self.rb_color = 0;
        self.rb_depth = 0;
        self.rb_stencil = 0;
    }
}

impl Drop for RenderbufferFbo<'_> {
    fn drop(&mut self) {
        self.delete();
    }
}

/// `RenderbufferCase::constructOrthoProjMatrix`
fn construct_ortho_proj_matrix(l: f32, r: f32, b: f32, t: f32, n: f32, f: f32) -> [f32; 16] {
    let inv_width = 1.0 / (r - l);
    let inv_height = 1.0 / (t - b);
    let inv_depth = 1.0 / (f - n);

    let mut mat4 = [0.0f32; 16];
    mat4[0] = 2.0 * inv_width;
    mat4[5] = 2.0 * inv_height;
    mat4[10] = 2.0 * inv_depth;

    mat4[12] = -(r + l) * inv_width;
    mat4[13] = -(t + b) * inv_height;
    mat4[14] = -(f + n) * inv_depth;
    mat4[15] = 1.0;
    mat4
}

