/// The `GL_MAX_*_ATOMIC_COUNTERS` and `GL_MAX_*_SHADER_STORAGE_BLOCKS` values (`m_max_*`); zero until queried, as upstream's constructor leaves them.
#[derive(Default)]
struct Limits {
    gs_acs: glw::GLint,
    tc_acs: glw::GLint,
    te_acs: glw::GLint,
    vs_acs: glw::GLint,
    fs_ssbos: glw::GLint,
    gs_ssbos: glw::GLint,
    tc_ssbos: glw::GLint,
    te_ssbos: glw::GLint,
    vs_ssbos: glw::GLint,
}

/// `getReservedNames`: the keywords of the running version followed by its reserved names.
fn get_reserved_names(context_type: glu::ContextType) -> Result<Vec<&'static str>, TestError> {
    let (keywords, reserved) = match (context_type.api.major, context_type.api.minor) {
        (3, 1) => (KEYWORDS_GL31, RESERVED_GL31),
        (3, 2) => (KEYWORDS_GL32, RESERVED_GL32),
        (3, 3) => (KEYWORDS_GL33, RESERVED_GL33),
        (4, 0) => (KEYWORDS_GL40, RESERVED_GL40),
        (4, 1) => (KEYWORDS_GL41, RESERVED_GL41),
        (4, 2) => (KEYWORDS_GL42, RESERVED_GL42),
        (4, 3) => (KEYWORDS_GL43, RESERVED_GL43),
        (4, 4) => (KEYWORDS_GL44, RESERVED_GL44),
        (4, 5) => (KEYWORDS_GL45, RESERVED_GL45),
        (4, 6) => (KEYWORDS_GL46, RESERVED_GL46),
        _ => {
            return Err(TestError::Fail(
                "Unsupported GL context version - please implement.".to_string(),
            ));
        }
    };
    Ok(keywords.iter().chain(reserved.iter()).copied().collect())
}

/// `getShaderBody`
fn get_shader_body(
    context_type: glu::ContextType,
    shader_type: ShaderType,
    language_feature: LanguageFeature,
    invalid_name: &str,
) -> Result<String, TestError> {
    use LanguageFeature as F;

    let version = match (context_type.api.major, context_type.api.minor) {
        (3, 1) => "140",
        (3, 2) => "150",
        (3, 3) => "330",
        (4, 0) => "400",
        (4, 1) => "410",
        (4, 2) => "420",
        (4, 3) => "430",
        (4, 4) => "440",
        (4, 5) => "450",
        (4, 6) => "460",
        _ => {
            return Err(TestError::Fail(
                "Unsupported GL context version - please implement".to_string(),
            ));
        }
    };
    let mut body = format!("#version {version}\n\n");

    match shader_type {
        ShaderType::Compute => body.push_str("layout(local_size_x = 1, local_size_y = 1, local_size_z = 1) in;\n"),
        ShaderType::TessControl => body.push_str("layout(vertices = 3) out;\n"),
        ShaderType::TessEvaluation => body.push_str("layout(triangles) in;\n"),
        _ => {}
    }
    body.push_str("\n\n");

    let input_array = matches!(
        shader_type,
        ShaderType::Geometry | ShaderType::TessControl | ShaderType::TessEvaluation
    );
    let input_suffix = if input_array { "[]" } else { "" };
    let output_suffix = if shader_type == ShaderType::TessControl {
        "[]"
    } else {
        ""
    };

    match language_feature {
        F::AtomicCounter => body.push_str(&format!("layout(binding = 0, offset = 0) uniform atomic_uint {invalid_name};\n")),
        F::Attribute => body.push_str(&format!("attribute vec4 {invalid_name};\n")),
        F::Constant => body.push_str(&format!("const vec4 {invalid_name} = vec4(2.0, 3.0, 4.0, 5.0);\n")),
        F::FunctionArgumentName => body.push_str(&format!("void test(in vec4 {invalid_name})\n{{\n}}\n")),
        F::FunctionName => body.push_str(&format!("void {invalid_name}(in vec4 test)\n{{\n}}\n")),
        F::Input => body.push_str(&format!("in vec4 {invalid_name}{input_suffix};\n")),
        F::InputBlockInstanceName => body.push_str(&format!("in testBlock\n{{\n    vec4 test;\n}} {invalid_name}{input_suffix};\n")),
        F::InputBlockMemberName => body.push_str(&format!("in testBlock\n{{\n    vec4 {invalid_name};\n}} testBlockInstance{input_suffix};\n")),
        F::InputBlockName => body.push_str(&format!("in {invalid_name}\n{{\n    vec4 test;\n}} testBlockInstance{input_suffix};\n")),
        F::Output => body.push_str(&format!("out vec4 {invalid_name}{output_suffix};\n")),
        F::OutputBlockInstanceName => body.push_str(&format!("out testBlock\n{{\n    vec4 test;\n}} {invalid_name}{output_suffix};\n")),
        F::OutputBlockMemberName => body.push_str(&format!("out testBlock\n{{\n    vec4 {invalid_name};\n}} testBlockInstance{output_suffix};\n")),
        F::OutputBlockName => body.push_str(&format!("out {invalid_name}\n{{\n    vec4 test;\n}} testBlockInstance{output_suffix};\n")),
        F::ShaderStorageBlockInstanceName => body.push_str(&format!("buffer testBlock\n{{\n    vec4 test;\n}} {invalid_name};\n")),
        F::ShaderStorageBlockMemberName => body.push_str(&format!("buffer testBlock\n{{\n    vec4 {invalid_name};\n}};\n")),
        F::ShaderStorageBlockName => body.push_str(&format!("buffer {invalid_name}\n{{\n    vec4 test;\n}};\n")),
        F::SubroutineFunctionName => body.push_str(&format!(
            "subroutine void exampleSubroutine(inout vec4 {invalid_name});\n\nsubroutine (exampleSubroutine) void invert(inout vec4 {invalid_name})\n{{\n    {invalid_name} += vec4(0.0, 1.0, 2.0, 3.0);\n}}\n\nsubroutine uniform exampleSubroutine testSubroutine;\n"
        )),
        F::SubroutineType => body.push_str(&format!(
            "subroutine void {invalid_name}(inout vec4 arg);\n\nsubroutine ({invalid_name}) void invert(inout vec4 arg)\n{{\n    arg += vec4(0.0, 1.0, 2.0, 3.0);\n}}\n\nsubroutine uniform {invalid_name} testSubroutine;\n"
        )),
        F::SubroutineUniform => body.push_str(&format!(
            "subroutine void exampleSubroutine(inout vec4 arg);\n\nsubroutine (exampleSubroutine) void invert(inout vec4 arg)\n{{\n    arg += vec4(0.0, 1.0, 2.0, 3.0);\n}}\n\nsubroutine uniform exampleSubroutine {invalid_name};\n"
        )),
        F::Uniform => body.push_str(&format!("uniform sampler2D {invalid_name};\n")),
        F::UniformBlockInstanceName => body.push_str(&format!("uniform testBlock\n{{\n    vec4 test;\n}} {invalid_name};\n")),
        F::UniformBlockMemberName => body.push_str(&format!("uniform testBlock\n{{\n    vec4 {invalid_name};\n}};\n")),
        F::UniformBlockName => body.push_str(&format!("uniform {invalid_name}\n{{\n    vec4 test;\n}};\n")),
        F::Varying => body.push_str(&format!("varying vec4 {invalid_name};\n")),
        F::SharedVariable | F::StructureInstanceName | F::StructureMember | F::StructureName | F::Variable => {}
    }

    body.push_str("void main()\n{\n");

    match language_feature {
        F::SharedVariable => body.push_str(&format!("shared vec4 {invalid_name};\n")),
        F::StructureInstanceName => body.push_str(&format!("struct\n{{\n    vec4 test;\n}} {invalid_name};\n")),
        F::StructureMember => body.push_str(&format!("struct\n{{\n    vec4 {invalid_name};\n}} testInstance;\n")),
        F::StructureName => body.push_str(&format!("struct {invalid_name}{{\n    vec4 test;\n}};\n")),
        F::Variable => body.push_str(&format!("vec4 {invalid_name};\n")),
        _ => {}
    }

    body.push_str("}\n");
    Ok(body)
}

/// `getSupportedLanguageFeatures`
fn get_supported_language_features(
    context_type: glu::ContextType,
    limits: &Limits,
    shader_type: ShaderType,
) -> Vec<LanguageFeature> {
    use LanguageFeature as F;
    use ShaderType as S;

    let mut result = Vec::new();

    if context_type.supports_core(4, 2)
        && (shader_type == S::Compute
            || shader_type == S::Fragment
            || (shader_type == S::Geometry && limits.gs_acs > 0)
            || (shader_type == S::TessControl && limits.tc_acs > 0)
            || (shader_type == S::TessEvaluation && limits.te_acs > 0)
            || (shader_type == S::Vertex && limits.vs_acs != 0))
    {
        result.push(F::AtomicCounter);
    }

    if shader_type == S::Vertex && !context_type.supports_core(4, 2) {
        result.push(F::Attribute);
    }

    result.push(F::Constant);
    result.push(F::FunctionArgumentName);
    result.push(F::FunctionName);

    if shader_type != S::Compute {
        result.push(F::Input);
    }

    if shader_type != S::Compute && context_type.supports_core(3, 2) {
        result.extend([F::InputBlockInstanceName, F::InputBlockMemberName, F::InputBlockName]);
    }

    if shader_type != S::Compute {
        result.push(F::Output);
    }

    if matches!(
        shader_type,
        S::Geometry | S::TessControl | S::TessEvaluation | S::Vertex
    ) && context_type.supports_core(3, 2)
    {
        result.extend([F::OutputBlockInstanceName, F::OutputBlockMemberName, F::OutputBlockName]);
    }

    if context_type.supports_core(4, 3)
        && (shader_type == S::Compute
            || (shader_type == S::Fragment && limits.fs_ssbos > 0)
            || (shader_type == S::Geometry && limits.gs_ssbos > 0)
            || (shader_type == S::TessControl && limits.tc_ssbos > 0)
            || (shader_type == S::TessEvaluation && limits.te_ssbos > 0)
            || (shader_type == S::Vertex && limits.vs_ssbos != 0))
    {
        result.extend([
            F::ShaderStorageBlockInstanceName,
            F::ShaderStorageBlockMemberName,
            F::ShaderStorageBlockName,
        ]);
    }

    if shader_type == S::Compute {
        result.push(F::SharedVariable);
    }

    result.extend([F::StructureInstanceName, F::StructureMember, F::StructureName]);

    if context_type.supports_core(4, 0) && shader_type != S::Compute {
        result.extend([F::SubroutineFunctionName, F::SubroutineType, F::SubroutineUniform]);
    }

    if shader_type != S::Compute {
        result.extend([
            F::UniformBlockInstanceName,
            F::UniformBlockMemberName,
            F::UniformBlockName,
            F::Uniform,
        ]);
    }

    result.push(F::Variable);

    if matches!(shader_type, S::Fragment | S::Vertex) && !context_type.supports_core(4, 3) {
        result.push(F::Varying);
    }

    result
}

/// `getSupportedShaderTypes`
fn get_supported_shader_types(context_type: glu::ContextType) -> Vec<ShaderType> {
    let mut result = Vec::new();

    if context_type.supports_core(4, 3) {
        result.push(ShaderType::Compute);
    }
    result.push(ShaderType::Fragment);
    if context_type.supports_core(3, 2) {
        result.push(ShaderType::Geometry);
    }
    if context_type.supports_core(4, 0) {
        result.push(ShaderType::TessControl);
        result.push(ShaderType::TessEvaluation);
    }
    result.push(ShaderType::Vertex);
    result
}

/// `isStructAllowed`
fn is_struct_allowed(shader_type: ShaderType, language_feature: LanguageFeature) -> bool {
    use LanguageFeature as F;

    if language_feature == F::Uniform || language_feature == F::UniformBlockName {
        return true;
    }

    match shader_type {
        ShaderType::Fragment => language_feature == F::InputBlockName,
        ShaderType::Geometry | ShaderType::TessControl | ShaderType::TessEvaluation => {
            matches!(language_feature, F::OutputBlockName | F::InputBlockName)
        }
        ShaderType::Vertex => language_feature == F::OutputBlockName,
        ShaderType::Compute => false,
    }
}

/// `ReservedNamesTest`
struct ReservedNamesTest;

impl TestCase for ReservedNamesTest {
    fn name(&self) -> &str {
        "CommonBug_ReservedNames"
    }

    fn iterate(&self, context: &Context) -> TestOutcome {
        let gl = context.gl();
        let context_type = context.context_type();
        let mut result = true;
        let mut limits = Limits::default();

        if context_type.supports_core(4, 2) {
            // SAFETY: each value is written to a live field.
            unsafe {
                gl.get_integerv(glw::GL_MAX_GEOMETRY_ATOMIC_COUNTERS, &mut limits.gs_acs);
                gl.get_integerv(glw::GL_MAX_TESS_CONTROL_ATOMIC_COUNTERS, &mut limits.tc_acs);
                gl.get_integerv(glw::GL_MAX_TESS_EVALUATION_ATOMIC_COUNTERS, &mut limits.te_acs);
                gl.get_integerv(glw::GL_MAX_VERTEX_ATOMIC_COUNTERS, &mut limits.vs_acs);
            }
        }
        if context_type.supports_core(4, 3) {
            // SAFETY: each value is written to a live field.
            unsafe {
                gl.get_integerv(glw::GL_MAX_FRAGMENT_SHADER_STORAGE_BLOCKS, &mut limits.fs_ssbos);
                gl.get_integerv(glw::GL_MAX_GEOMETRY_SHADER_STORAGE_BLOCKS, &mut limits.gs_ssbos);
                gl.get_integerv(glw::GL_MAX_TESS_CONTROL_SHADER_STORAGE_BLOCKS, &mut limits.tc_ssbos);
                gl.get_integerv(glw::GL_MAX_TESS_EVALUATION_SHADER_STORAGE_BLOCKS, &mut limits.te_ssbos);
                gl.get_integerv(glw::GL_MAX_VERTEX_SHADER_STORAGE_BLOCKS, &mut limits.vs_ssbos);
            }
            glu::expect_no_error(gl, "glGetIntegerv() call(s) failed.")?;
        }

        let reserved_names = get_reserved_names(context_type)?;
        let shader_types = get_supported_shader_types(context_type);

        for shader_type in shader_types {
            let shader = Shader::new(gl, shader_type.gl_type())?;

            for language_feature in get_supported_language_features(context_type, &limits, shader_type) {
                let struct_allowed = is_struct_allowed(shader_type, language_feature);

                for invalid_name in &reserved_names {
                    if struct_allowed && *invalid_name == "struct" {
                        continue;
                    }

                    let so_body = get_shader_body(context_type, shader_type, language_feature, invalid_name)?;
                    shader.source(&[so_body.as_str()])?;

                    if shader.compile()? {
                        log::info!(
                            "A {} named [{invalid_name}], defined in {}, was accepted by the compiler, which is prohibited by the spec. Offending source code:\n>>\n{so_body}\n<<\n\n",
                            language_feature.name(),
                            shader_type.name()
                        );
                        result = false;
                    }
                }
            }
        }
        verdict(result)
    }
}

/// `ReservedNamesTest`, as a node of `CommonBugs`.
pub fn create_test() -> Box<dyn TestCase> {
    Box::new(ReservedNamesTest)
}
