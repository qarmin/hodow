fn fail<T>(message: &str) -> Result<T, TestError> {
    Err(TestError::Fail(message.to_string()))
}

/// `generateBasicVertexSrc`
fn generate_basic_vertex_src(glsl_version: GlslVersion) -> String {
    let mut source = format!("{}\n", glsl_version.declaration());
    source.push_str("in highp vec4 a_position;\n");

    if glsl_version >= GlslVersion::Glsl410 {
        source.push_str("out gl_PerVertex {\n  vec4 gl_Position;\n};\n");
    }

    source.push_str("void main (void)\n{\n   gl_Position = a_position;\n}\n");
    source
}

/// `generateBasicFragmentSrc`
fn generate_basic_fragment_src(glsl_version: GlslVersion) -> String {
    let mut source = format!("{}\n", glsl_version.declaration());
    source.push_str("uniform highp vec4 u_color;\nlayout(location = 0) out mediump vec4 o_color;\nvoid main (void)\n{\n   o_color = u_color;\n}\n");
    source
}

/// `glCreateShaderProgramv` over `strings`, `count` strings long (callers pass -1 for the negative case); 0 is the failure name.
fn create_shader_programv(
    gl: &glw::Functions,
    shader_type: GLenum,
    count: GLsizei,
    strings: &[impl AsRef<str>],
) -> GLuint {
    let c_strings: Vec<CString> = strings
        .iter()
        .map(|string| CString::new(string.as_ref()).expect("shader strings have no NUL"))
        .collect();
    let pointers: Vec<_> = c_strings.iter().map(|string| string.as_ptr()).collect();

    // SAFETY: the pointers are live NUL-terminated strings; a count that is not the length is what the negative case asks for and is rejected by the driver before any read.
    unsafe { gl.create_shader_programv(shader_type, count, pointers.as_ptr()) }
}

/// `glGetError`
fn get_error(gl: &glw::Functions) -> GLenum {
    // SAFETY: glGetError needs nothing but a current context.
    unsafe { gl.get_error() }
}

/// `glGetProgramPipelineiv` of one pname.
fn get_program_pipeline(gl: &glw::Functions, pipeline: GLuint, pname: GLenum) -> GLuint {
    let mut value: GLint = 0;
    // SAFETY: one integer of output is given.
    unsafe { gl.get_program_pipelineiv(pipeline, pname, &mut value) };
    value as GLuint
}

/// `glGetProgramiv` of one pname.
fn get_program(gl: &glw::Functions, program: GLuint, pname: GLenum) -> GLint {
    let mut value: GLint = 0;
    // SAFETY: one integer of output is given.
    unsafe { gl.get_programiv(program, pname, &mut value) };
    value
}

/// `SeparateShaderObjsTests::init`
pub fn create_tests(glsl_version: GlslVersion) -> TestCaseGroup {
    let mut group = TestCaseGroup::new("sepshaderobjs");
    group.add_child(Box::new(create_shader_program::CreateShadProgCase { glsl_version }) as Box<dyn TestCase>);
    group.add_child(Box::new(use_program_stages::UseProgStagesCase { glsl_version }) as Box<dyn TestCase>);
    group.add_child(Box::new(pipeline_api::PipelineApiCase { glsl_version }) as Box<dyn TestCase>);
    group.add_child(Box::new(prog_uniform::ProgramUniformCase { glsl_version }) as Box<dyn TestCase>);
    group.add_child(Box::new(state_interaction::StateInteractionCase { glsl_version }) as Box<dyn TestCase>);
    for flavour in [
        interface_matching::Flavour::Float,
        interface_matching::Flavour::Int,
        interface_matching::Flavour::UInt,
    ] {
        group.add_child(
            Box::new(interface_matching::InterfaceMatchingCase { glsl_version, flavour }) as Box<dyn TestCase>,
        );
    }
    group
}
