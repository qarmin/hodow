/// `tcu::deFloatFrac` - the positive fractional part, so `frac(-1.25) == 0.75`.
fn float_frac(f: f32) -> f32 {
    f - f.floor()
}

/// `tcu::convertSatRte<T>` - round to nearest, ties to even, then saturate.
///
/// Not `f.round()`: that rounds ties away from zero, which would put half the
/// exactly-representable midpoints one step off from what upstream stores.
fn convert_sat_rte(f: f32, min_val: i64, max_val: i64) -> i64 {
    if f.is_nan() {
        return 0;
    }
    let q = float_frac(f);
    let mut int_val = (f - q) as i64;

    if q == 0.5 {
        if int_val % 2 != 0 {
            int_val += 1;
        }
    } else if q > 0.5 {
        int_val += 1;
    }

    int_val.clamp(min_val, max_val)
}

/// `tcu::unormFloatToChannel`
fn unorm_float_to_channel(src: f32, bits: i32) -> u32 {
    let max_val = (1u32 << bits) - 1;
    let int_val = convert_sat_rte(src * max_val as f32, 0, u32::MAX as i64) as u32;
    int_val.min(max_val)
}

/// `tcu::snormFloatToChannel`
fn snorm_float_to_channel(src: f32, bits: i32) -> u32 {
    let range = ((1u32 << (bits - 1)) - 1) as i32;
    let mask = (1u64 << bits) - 1;
    let int_val = convert_sat_rte(src * range as f32, i32::MIN as i64, i32::MAX as i64) as i32;
    (int_val.clamp(-range, range) as u32) & mask as u32
}

/// `tcu::uintToChannel`
fn uint_to_channel(src: u32, bits: i32) -> u32 {
    src.min((1u32 << bits) - 1)
}

/// `tcu::intToChannel`
fn int_to_channel(src: i32, bits: i32) -> u32 {
    let min_val = -((1i32) << (bits - 1));
    let max_val = (1i32 << (bits - 1)) - 1;
    let mask = (1u32 << bits) - 1;
    (src.clamp(min_val, max_val) as u32) & mask
}

/// `tcu::Float<uint32_t, ExponentBits, MantissaBits, Bias>` built from an f32, for the
/// unsigned small floats packed into 11F_11F_10F. Round to nearest, ties to even, with
/// denormals - matching the read path's `float_bits_to_f32`, which is its inverse.
pub fn f32_to_small_float_bits(value: f32, exp_bits: i32, mantissa_bits: i32, bias: i32) -> u32 {
    // Negative and NaN both clamp to zero: these formats carry no sign bit.
    if value.is_nan() || value <= 0.0 {
        return 0;
    }

    let bits = value.to_bits();
    let exp = ((bits >> 23) & 0xFF) as i32;
    let mantissa = bits & 0x007F_FFFF;
    let max_exp = (1 << exp_bits) - 1;

    if exp == 0xFF {
        // Infinity, since NaN was handled above.
        return (max_exp as u32) << mantissa_bits;
    }

    let unbiased = exp - 127 + bias;
    if unbiased >= max_exp {
        return (max_exp as u32) << mantissa_bits;
    }

    let drop = 23 - mantissa_bits;
    let (mut out, rem, halfway) = if unbiased <= 0 {
        // Denormal: the implicit leading one comes back and the whole thing shifts down.
        let shift = (drop + 1 - unbiased) as u32;
        if shift >= 32 {
            return 0;
        }
        let m = mantissa | 0x0080_0000;
        (m >> shift, m & ((1u32 << shift) - 1), 1u32 << (shift - 1))
    } else {
        (
            ((unbiased as u32) << mantissa_bits) | (mantissa >> drop),
            mantissa & ((1u32 << drop) - 1),
            1u32 << (drop - 1),
        )
    };
    if rem > halfway || (rem == halfway && (out & 1) != 0) {
        out += 1;
    }
    out
}

/// `tcu::packRGB999E5` - the shared-exponent encoder, the inverse of `unpack_rgb999e5`.
fn pack_rgb999e5(color: [f32; 4]) -> u32 {
    const M_BITS: i32 = 9;
    const E_BITS: i32 = 5;
    const E_BIAS: i32 = 15;
    const E_MAX: i32 = (1 << E_BITS) - 1;
    let max_val = (((1 << M_BITS) - 1) * (1i64 << (E_MAX - E_BIAS))) as f32 / (1 << M_BITS) as f32;

    let rc = color[0].clamp(0.0, max_val);
    let gc = color[1].clamp(0.0, max_val);
    let bc = color[2].clamp(0.0, max_val);
    let maxc = rc.max(gc).max(bc);

    let log2c = maxc.log2();
    let floorc = if log2c.is_infinite() { i32::MIN } else { log2c.floor() as i32 };
    let mut exps = floorc.max(-E_BIAS - 1) + 1 + E_BIAS;
    let mut e = 2f32.powi(exps - E_BIAS - M_BITS);
    let maxs = (maxc / e + 0.5).floor() as i32;

    if maxs == (1 << M_BITS) {
        exps += 1;
        e *= 2.0;
    }

    let rs = (rc / e + 0.5).floor() as u32;
    let gs = (gc / e + 0.5).floor() as u32;
    let bs = (bc / e + 0.5).floor() as u32;

    rs | (gs << 9) | (bs << 18) | ((exps as u32) << 27)
}

/// The packed half of `PixelBufferAccess::setPixel`.
///
fn set_packed_pixel(dst: &mut [u8], color: [f32; 4], format: TextureFormat) {
    use ChannelType::*;
    // The write swizzle runs RGBA -> order, the opposite direction from the read path's
    // order -> RGBA.
    let sw = swizzle_ge(color, ChannelOrder::RGBA, format.order);
    // The three-channel packings swizzle from RGB, not RGBA - with a BGR order the two
    // disagree, and the write would land R and B in each other's bits.
    let sw3 = swizzle_ge(color, ChannelOrder::RGB, format.order);
    let pn = |v: f32, offs: u32, bits: i32| unorm_float_to_channel(v, bits) << offs;
    let ps = |v: f32, offs: u32, bits: i32| snorm_float_to_channel(v, bits) << offs;
    let pu = |v: f32, offs: u32, bits: i32| uint_to_channel(v as u32, bits) << offs;
    let pi = |v: f32, offs: u32, bits: i32| int_to_channel(v as i32, bits) << offs;

    let write16 = |dst: &mut [u8], v: u32| dst[..2].copy_from_slice(&(v as u16).to_le_bytes());
    let write32 = |dst: &mut [u8], v: u32| dst[..4].copy_from_slice(&v.to_le_bytes());

    match format.type_ {
        UNORM_BYTE_44 => dst[0] = (pn(color[0], 4, 4) | pn(color[1], 0, 4)) as u8,
        UNSIGNED_BYTE_44 => dst[0] = (pu(color[0], 4, 4) | pu(color[1], 0, 4)) as u8,
        UNORM_INT_101010 => write32(dst, pn(color[0], 22, 10) | pn(color[1], 12, 10) | pn(color[2], 2, 10)),
        UNORM_SHORT_565 => write16(dst, pn(sw3[0], 11, 5) | pn(sw3[1], 5, 6) | pn(sw3[2], 0, 5)),
        UNSIGNED_SHORT_565 => write16(dst, pu(sw3[0], 11, 5) | pu(sw3[1], 5, 6) | pu(sw3[2], 0, 5)),
        UNORM_SHORT_555 => write16(dst, pn(sw3[0], 10, 5) | pn(sw3[1], 5, 5) | pn(sw3[2], 0, 5)),
        UNORM_SHORT_4444 => write16(dst, pn(sw[0], 12, 4) | pn(sw[1], 8, 4) | pn(sw[2], 4, 4) | pn(sw[3], 0, 4)),
        UNSIGNED_SHORT_4444 => write16(dst, pu(sw[0], 12, 4) | pu(sw[1], 8, 4) | pu(sw[2], 4, 4) | pu(sw[3], 0, 4)),
        UNORM_SHORT_5551 => write16(dst, pn(sw[0], 11, 5) | pn(sw[1], 6, 5) | pn(sw[2], 1, 5) | pn(sw[3], 0, 1)),
        UNORM_SHORT_1555 => write16(dst, pn(sw[0], 15, 1) | pn(sw[1], 10, 5) | pn(sw[2], 5, 5) | pn(sw[3], 0, 5)),
        UNSIGNED_SHORT_5551 => write16(dst, pu(sw[0], 11, 5) | pu(sw[1], 6, 5) | pu(sw[2], 1, 5) | pu(sw[3], 0, 1)),
        UNORM_INT_1010102_REV => write32(dst, pn(sw[0], 0, 10) | pn(sw[1], 10, 10) | pn(sw[2], 20, 10) | pn(sw[3], 30, 2)),
        SNORM_INT_1010102_REV => write32(dst, ps(sw[0], 0, 10) | ps(sw[1], 10, 10) | ps(sw[2], 20, 10) | ps(sw[3], 30, 2)),
        UNSIGNED_INT_1010102_REV | USCALED_INT_1010102_REV => {
            write32(dst, pu(sw[0], 0, 10) | pu(sw[1], 10, 10) | pu(sw[2], 20, 10) | pu(sw[3], 30, 2));
        }
        SIGNED_INT_1010102_REV | SSCALED_INT_1010102_REV => {
            write32(dst, pi(sw[0], 0, 10) | pi(sw[1], 10, 10) | pi(sw[2], 20, 10) | pi(sw[3], 30, 2));
        }
        // These two take the unswizzled colour: upstream packs the channels in the
        // order the format name reverses, so the bit positions already carry it.
        UNSIGNED_INT_11F_11F_10F_REV => {
            let v = f32_to_small_float_bits(color[0], 5, 6, 15) | (f32_to_small_float_bits(color[1], 5, 6, 15) << 11) | (f32_to_small_float_bits(color[2], 5, 5, 15) << 22);
            write32(dst, v);
        }
        UNSIGNED_INT_999_E5_REV => write32(dst, pack_rgb999e5(color)),
        other => unreachable!("set_packed_pixel reached {other:?}; TextureLevel::new should have refused it"),
    }
}

/// The packed types `set_packed_pixel` can store.
fn is_packed_writable(type_: ChannelType) -> bool {
    use ChannelType::*;
    matches!(
        type_,
        UNORM_BYTE_44
            | UNSIGNED_BYTE_44
            | UNORM_INT_101010
            | UNORM_SHORT_565
            | UNSIGNED_SHORT_565
            | UNORM_SHORT_555
            | UNORM_SHORT_4444
            | UNSIGNED_SHORT_4444
            | UNORM_SHORT_5551
            | UNORM_SHORT_1555
            | UNSIGNED_SHORT_5551
            | UNORM_INT_1010102_REV
            | SNORM_INT_1010102_REV
            | UNSIGNED_INT_1010102_REV
            | USCALED_INT_1010102_REV
            | SIGNED_INT_1010102_REV
            | SSCALED_INT_1010102_REV
            | UNSIGNED_INT_11F_11F_10F_REV
            | UNSIGNED_INT_999_E5_REV
    )
}

/// `tcu::floatToChannel`, restricted to the non-packed channel types.
///
/// The packed types are written through a separate switch in upstream's `setPixel`;
/// no ported test writes one yet, and `TextureLevel::new` refuses such a format up
/// front rather than letting a silent approximation reach a comparison.
///
/// The packed half of `PixelBufferAccess::setPixel(const IVec4&)`.
fn set_packed_pixel_int(dst: &mut [u8], color: [i32; 4], format: TextureFormat) {
    use ChannelType::*;
    let sw = swizzle_ge(color, ChannelOrder::RGBA, format.order);
    let sw3 = swizzle_ge(color, ChannelOrder::RGB, format.order);
    let pu = |v: i32, offs: u32, bits: i32| uint_to_channel(v as u32, bits) << offs;
    let pi = |v: i32, offs: u32, bits: i32| int_to_channel(v, bits) << offs;

    let write16 = |dst: &mut [u8], v: u32| dst[..2].copy_from_slice(&(v as u16).to_le_bytes());
    let write32 = |dst: &mut [u8], v: u32| dst[..4].copy_from_slice(&v.to_le_bytes());

    // Every case here uses PU/PI - the integer setter stores the raw channel value, so
    // a UNORM packed type is written with the same unsigned packing as its UNSIGNED
    // sibling, unlike the float setter which normalises.
    match format.type_ {
        UNORM_BYTE_44 | UNSIGNED_BYTE_44 => dst[0] = (pu(color[0], 4, 4) | pu(color[1], 0, 4)) as u8,
        UNORM_INT_101010 => write32(dst, pu(color[0], 22, 10) | pu(color[1], 12, 10) | pu(color[2], 2, 10)),
        UNORM_SHORT_565 | UNSIGNED_SHORT_565 => write16(dst, pu(sw3[0], 11, 5) | pu(sw3[1], 5, 6) | pu(sw3[2], 0, 5)),
        UNORM_SHORT_555 => write16(dst, pu(sw3[0], 10, 5) | pu(sw3[1], 5, 5) | pu(sw3[2], 0, 5)),
        UNORM_SHORT_4444 | UNSIGNED_SHORT_4444 => write16(dst, pu(sw[0], 12, 4) | pu(sw[1], 8, 4) | pu(sw[2], 4, 4) | pu(sw[3], 0, 4)),
        UNORM_SHORT_5551 | UNSIGNED_SHORT_5551 => write16(dst, pu(sw[0], 11, 5) | pu(sw[1], 6, 5) | pu(sw[2], 1, 5) | pu(sw[3], 0, 1)),
        UNORM_SHORT_1555 => write16(dst, pu(sw[0], 15, 1) | pu(sw[1], 10, 5) | pu(sw[2], 5, 5) | pu(sw[3], 0, 5)),
        UNORM_INT_1010102_REV | UNSIGNED_INT_1010102_REV | USCALED_INT_1010102_REV => {
            write32(dst, pu(sw[0], 0, 10) | pu(sw[1], 10, 10) | pu(sw[2], 20, 10) | pu(sw[3], 30, 2));
        }
        SNORM_INT_1010102_REV | SIGNED_INT_1010102_REV | SSCALED_INT_1010102_REV => {
            write32(dst, pi(sw[0], 0, 10) | pi(sw[1], 10, 10) | pi(sw[2], 20, 10) | pi(sw[3], 30, 2));
        }
        other => unreachable!("set_packed_pixel_int reached {other:?}; is_packed_int_writable should have refused it"),
    }
}

/// The packed types `set_packed_pixel_int` can store. Upstream's integer setter has no
/// case for the two float-packed types, so they fall to its generic path and assert
/// there; refusing them here keeps that loud rather than writing nonsense.
fn is_packed_int_writable(type_: ChannelType) -> bool {
    use ChannelType::*;
    is_packed_writable(type_) && !matches!(type_, UNSIGNED_INT_11F_11F_10F_REV | UNSIGNED_INT_999_E5_REV)
}

/// `tcu::intToChannel`, the byte-writing overload.
///
/// Saturating, not wrapping: an out-of-range value clamps to the destination's limits,
/// which is what makes `intNearestBlitCompare`'s format conversion well defined.
fn int_to_channel_bytes(dst: &mut [u8], src: i32, type_: ChannelType) -> bool {
    use ChannelType::*;
    let s = src as i64;
    let sat_i = |lo: i64, hi: i64| s.clamp(lo, hi);
    // The unsigned conversions read the value as uint32_t first, so a negative source
    // becomes a very large unsigned one and saturates to the maximum, not to zero.
    let u = src as u32 as u64;
    let sat_u = |hi: u64| u.min(hi);

    match type_ {
        SNORM_INT8 | SIGNED_INT8 | SSCALED_INT8 => dst[..1].copy_from_slice(&(sat_i(-128, 127) as i8).to_le_bytes()),
        SNORM_INT16 | SIGNED_INT16 | SSCALED_INT16 => dst[..2].copy_from_slice(&(sat_i(-32768, 32767) as i16).to_le_bytes()),
        SIGNED_INT32 => dst[..4].copy_from_slice(&src.to_le_bytes()),
        SIGNED_INT64 => dst[..8].copy_from_slice(&s.to_le_bytes()),
        UNORM_INT8 | UNSIGNED_INT8 | USCALED_INT8 => dst[..1].copy_from_slice(&(sat_u(255) as u8).to_le_bytes()),
        UNORM_INT16 | UNSIGNED_INT16 | USCALED_INT16 => dst[..2].copy_from_slice(&(sat_u(65535) as u16).to_le_bytes()),
        UNORM_INT24 | UNSIGNED_INT24 => {
            let v = sat_u(0x00FF_FFFF) as u32;
            dst[..3].copy_from_slice(&v.to_le_bytes()[..3]);
        }
        UNSIGNED_INT32 => dst[..4].copy_from_slice(&(src as u32).to_le_bytes()),
        UNSIGNED_INT64 => dst[..8].copy_from_slice(&u.to_le_bytes()),
        HALF_FLOAT => dst[..2].copy_from_slice(&f32_to_f16_bits(src as f32).to_le_bytes()),
        FLOAT => dst[..4].copy_from_slice(&(src as f32).to_le_bytes()),
        FLOAT64 => dst[..8].copy_from_slice(&(src as f64).to_le_bytes()),
        UNORM_SHORT_10 => dst[..2].copy_from_slice(&((sat_u(1023) as u16) << 6).to_le_bytes()),
        UNORM_SHORT_12 => dst[..2].copy_from_slice(&((sat_u(4095) as u16) << 4).to_le_bytes()),
        // SNORM_INT32 and UNORM_INT32 have no case upstream - the switch asserts.
        _ => return false,
    }
    true
}

fn float_to_channel(dst: &mut [u8], src: f32, type_: ChannelType) {
    use ChannelType::*;
    let sat = |scale: f32, lo: i64, hi: i64| convert_sat_rte(src * scale, lo, hi);
    match type_ {
        SNORM_INT8 => dst[..1].copy_from_slice(&(sat(127.0, -128, 127) as i8).to_le_bytes()),
        SNORM_INT16 => dst[..2].copy_from_slice(&(sat(32767.0, -32768, 32767) as i16).to_le_bytes()),
        SNORM_INT32 => dst[..4].copy_from_slice(&(sat(2_147_483_647.0, i32::MIN as i64, i32::MAX as i64) as i32).to_le_bytes()),
        UNORM_INT8 => dst[..1].copy_from_slice(&(sat(255.0, 0, 255) as u8).to_le_bytes()),
        UNORM_INT16 => dst[..2].copy_from_slice(&(sat(65535.0, 0, 65535) as u16).to_le_bytes()),
        UNORM_INT24 => {
            let v = sat(16_777_215.0, 0, u32::MAX as i64) as u32;
            dst[..3].copy_from_slice(&v.to_le_bytes()[..3]);
        }
        UNORM_INT32 => dst[..4].copy_from_slice(&(sat(4_294_967_295.0, 0, u32::MAX as i64) as u32).to_le_bytes()),
        SIGNED_INT8 | SSCALED_INT8 => dst[..1].copy_from_slice(&(sat(1.0, -128, 127) as i8).to_le_bytes()),
        SIGNED_INT16 | SSCALED_INT16 => dst[..2].copy_from_slice(&(sat(1.0, -32768, 32767) as i16).to_le_bytes()),
        SIGNED_INT32 => dst[..4].copy_from_slice(&(sat(1.0, i32::MIN as i64, i32::MAX as i64) as i32).to_le_bytes()),
        // Upstream converts as 32 bits and stores as 64; keeping that means a value
        // outside the 32-bit range saturates the same way it does there.
        SIGNED_INT64 => dst[..8].copy_from_slice(&i64::from(sat(1.0, i32::MIN as i64, i32::MAX as i64) as i32).to_le_bytes()),
        UNSIGNED_INT8 | USCALED_INT8 => dst[..1].copy_from_slice(&(sat(1.0, 0, 255) as u8).to_le_bytes()),
        UNSIGNED_INT16 | USCALED_INT16 => dst[..2].copy_from_slice(&(sat(1.0, 0, 65535) as u16).to_le_bytes()),
        UNSIGNED_INT24 => {
            let v = sat(1.0, 0, u32::MAX as i64) as u32;
            dst[..3].copy_from_slice(&v.to_le_bytes()[..3]);
        }
        UNSIGNED_INT32 => dst[..4].copy_from_slice(&(sat(1.0, 0, u32::MAX as i64) as u32).to_le_bytes()),
        UNSIGNED_INT64 => dst[..8].copy_from_slice(&u64::from(sat(1.0, 0, u32::MAX as i64) as u32).to_le_bytes()),
        HALF_FLOAT => dst[..2].copy_from_slice(&f32_to_f16_bits(src).to_le_bytes()),
        FLOAT => dst[..4].copy_from_slice(&src.to_le_bytes()),
        FLOAT64 => dst[..8].copy_from_slice(&f64::from(src).to_le_bytes()),
        // The value lives in the high bits; the low ones stay zero.
        UNORM_SHORT_10 => dst[..2].copy_from_slice(&((sat(1023.0, 0, 1023) as u16) << 6).to_le_bytes()),
        UNORM_SHORT_12 => dst[..2].copy_from_slice(&((sat(4095.0, 0, 4095) as u16) << 4).to_le_bytes()),
        other => unreachable!("float_to_channel reached the packed type {other:?}; TextureLevel::new should have refused it"),
    }
}

/// Whether `float_to_channel` can store this type at all.
fn is_writable_channel_type(type_: ChannelType) -> bool {
    use ChannelType::*;
    if is_packed_writable(type_) {
        return true;
    }
    // A combined depth/stencil type has no `set_pixel` path - upstream asserts there
    // too - but `set_pix_depth`/`set_pix_stencil` can write it, which is all its
    // callers use.
    if is_combined_depth_stencil_type(type_) {
        return true;
    }
    matches!(
        type_,
        SNORM_INT8
            | SNORM_INT16
            | SNORM_INT32
            | UNORM_INT8
            | UNORM_INT16
            | UNORM_INT24
            | UNORM_INT32
            | SIGNED_INT8
            | SIGNED_INT16
            | SIGNED_INT32
            | SIGNED_INT64
            | UNSIGNED_INT8
            | UNSIGNED_INT16
            | UNSIGNED_INT24
            | UNSIGNED_INT32
            | UNSIGNED_INT64
            | HALF_FLOAT
            | FLOAT
            | FLOAT64
            | UNORM_SHORT_10
            | UNORM_SHORT_12
            | USCALED_INT8
            | USCALED_INT16
            | SSCALED_INT8
            | SSCALED_INT16
    )
}

/// `deFloat32To16` - round-to-nearest-even, matching the read path's `rd_f16`.
pub fn f32_to_f16_bits(value: f32) -> u16 {
    let bits = value.to_bits();
    let sign = ((bits >> 16) & 0x8000) as u16;
    let exp = ((bits >> 23) & 0xFF) as i32;
    let mantissa = bits & 0x007F_FFFF;

    if exp == 0xFF {
        // Inf or NaN. A NaN must stay a NaN, so force a non-zero mantissa.
        let m = if mantissa != 0 { 0x200 } else { 0 };
        return sign | 0x7C00 | m;
    }

    let unbiased = exp - 127 + 15;
    if unbiased >= 0x1F {
        return sign | 0x7C00;
    }
    if unbiased <= 0 {
        if unbiased < -10 {
            return sign;
        }
        let m = mantissa | 0x0080_0000;
        let shift = (14 - unbiased) as u32;
        let mut half = m >> shift;
        // Round to nearest even on the bits shifted out.
        let rem = m & ((1 << shift) - 1);
        let halfway = 1 << (shift - 1);
        if rem > halfway || (rem == halfway && (half & 1) != 0) {
            half += 1;
        }
        return sign | half as u16;
    }

    let mut half = ((unbiased as u32) << 10) | (mantissa >> 13);
    let rem = mantissa & 0x1FFF;
    if rem > 0x1000 || (rem == 0x1000 && (half & 1) != 0) {
        half += 1;
    }
    sign | half as u16
}

/// `tcu::getEffectiveDepthStencilTextureFormat`
pub fn get_effective_depth_stencil_texture_format(base: TextureFormat, mode: DepthStencilMode) -> TextureFormat {
    effective_depth_stencil_view(base, mode).map_or(base, |(format, _)| format)
}

/// `toSamplerAccess` reduced to what it decides: the single-aspect format, and how far
/// into the combined texel that aspect starts.
///
/// `None` for a format that is not combined - there the access is returned unchanged.
/// Little-endian only, which is what the byte offsets below assume.
fn effective_depth_stencil_view(base: TextureFormat, mode: DepthStencilMode) -> Option<(TextureFormat, usize)> {
    use ChannelType::*;
    use DepthStencilMode::*;
    if !is_combined_depth_stencil_type(base.type_) {
        return None;
    }
    let stencil = (TextureFormat::new(ChannelOrder::S, UNSIGNED_INT8), 0);
    Some(match (base.type_, mode) {
        (FLOAT_UNSIGNED_INT_24_8_REV, Depth) => (TextureFormat::new(ChannelOrder::D, FLOAT), 0),
        // The stencil byte of a d32_sfloat_s8 texel lives in the second word.
        (FLOAT_UNSIGNED_INT_24_8_REV, Stencil) => (stencil.0, 4),
        (UNSIGNED_INT_16_8_8, Depth) => (TextureFormat::new(ChannelOrder::D, UNORM_INT16), 2),
        (UNSIGNED_INT_16_8_8, Stencil) => stencil,
        (UNSIGNED_INT_24_8, Depth) => (TextureFormat::new(ChannelOrder::D, UNORM_INT24), 1),
        (UNSIGNED_INT_24_8, Stencil) => stencil,
        (UNSIGNED_INT_24_8_REV, Depth) => (TextureFormat::new(ChannelOrder::D, UNORM_INT24), 0),
        (UNSIGNED_INT_24_8_REV, Stencil) => (stencil.0, 3),
        (other, _) => unreachable!("unknown combined format {other:?}"),
    })
}

/// `tcu::getEffectiveDepthStencilAccess` on a writable level.
pub fn get_effective_depth_stencil_access_mut<'a>(base: &'a mut PixelBufferAccess<'a>, mode: DepthStencilMode) -> PixelBufferAccess<'a> {
    let (format, offset) = effective_depth_stencil_view(base.format(), mode).unwrap_or((base.format(), 0));
    PixelBufferAccess {
        format,
        size: base.size(),
        pitch: base.pitch,
        data: &mut base.data[offset..],
    }
}

/// `tcu::getEffectiveDepthStencilAccess`
///
/// A view of one aspect of a combined depth/stencil level. It keeps the combined
/// format's pitch and only narrows the format and offsets the base, which is what lets
/// the single-aspect texel reads work over interleaved storage.
pub fn get_effective_depth_stencil_access<'a>(base: &'a ConstPixelBufferAccess<'a>, mode: DepthStencilMode) -> ConstPixelBufferAccess<'a> {
    match effective_depth_stencil_view(base.format(), mode) {
        None => ConstPixelBufferAccess::new_with_pitch(base.format(), base.size(), base.pitch(), base.raw()),
        Some((format, offset)) => ConstPixelBufferAccess::new_with_pitch(format, base.size(), base.pitch(), &base.raw()[offset..]),
    }
}

/// `tcu::Sampler::WrapMode`, narrowed to the mode the blit reference samples with.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum WrapMode {
    ClampToEdge,
    /// `CLAMP_TO_BORDER` - reached only through `remap_cube_edge_coords`, which uses
    /// the out-of-range values -1 and `size` it produces as its "left the face" signal.
    ClampToBorder,
    Repeat,
}

/// `tcu::Sampler::FilterMode`, minus the mipmapping modes no ported test reaches.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum FilterMode {
    Nearest,
    Linear,
    Cubic,
}

/// The Catmull-Rom weights `sampleCubic*` computes as `alpha * crBasis`.
///
/// Upstream builds the row-major basis matrix and multiplies; written out, the four
/// weights are the standard Catmull-Rom polynomials in the fractional coordinate.
fn cubic_weights(a: f32) -> [f32; 4] {
    let (a2, a3) = (a * a, a * a * a);
    [-0.5 * a + a2 - 0.5 * a3, 1.0 - 2.5 * a2 + 1.5 * a3, 0.5 * a + 2.0 * a2 - 1.5 * a3, -0.5 * a2 + 0.5 * a3]
}

/// `tcu::Sampler`, narrowed to what `tcu::scale` constructs: clamp-to-edge on every
/// axis, one filter, non-normalized coordinates.
#[derive(Clone, Copy)]
pub struct Sampler {
    pub wrap_s: WrapMode,
    pub wrap_t: WrapMode,
    pub wrap_r: WrapMode,
    pub filter: FilterMode,
    pub normalized_coords: bool,
}

impl Sampler {
    pub fn clamp_to_edge(filter: FilterMode) -> Self {
        Self {
            wrap_s: WrapMode::ClampToEdge,
            wrap_t: WrapMode::ClampToEdge,
            wrap_r: WrapMode::ClampToEdge,
            filter,
            normalized_coords: false,
        }
    }
}

/// `tcu::wrap`
pub fn wrap(mode: WrapMode, c: i32, size: i32) -> i32 {
    match mode {
        WrapMode::ClampToEdge => c.clamp(0, size - 1),
        WrapMode::ClampToBorder => c.clamp(-1, size),
        WrapMode::Repeat => c.rem_euclid(size),
    }
}

/// `tcu::unnormalize` - the ordinary case; the CL wrap modes that fold the coordinate
/// here instead of in `wrap` are not ported.
pub fn unnormalize(_mode: WrapMode, c: f32, size: u32) -> f32 {
    size as f32 * c
}

/// `tcu::sRGBChannelToLinear`
pub fn srgb_channel_to_linear(cs: f32) -> f32 {
    if cs <= 0.04045 { cs / 12.92 } else { ((cs + 0.055) / 1.055).powf(2.4) }
}

/// `tcu::sRGBToLinear`
pub fn srgb_to_linear(cs: [f32; 4]) -> [f32; 4] {
    [srgb_channel_to_linear(cs[0]), srgb_channel_to_linear(cs[1]), srgb_channel_to_linear(cs[2]), cs[3]]
}

/// `tcu::linearToSRGBIfNeeded`
pub fn linear_to_srgb_if_needed(format: TextureFormat, color: [f32; 4]) -> [f32; 4] {
    if format.order.is_srgb() { linear_to_srgb(color) } else { color }
}

/// `tcu::lookup` - the float specialisation, which converts an sRGB source to linear.
///
/// Upstream reads an 8-bit sRGB channel out of a 256-entry table; computing it instead
/// differs by at most 1.8e-7, checked against the table, which is orders of magnitude
/// below any threshold these comparisons use.
pub fn lookup(access: &ConstPixelBufferAccess<'_>, i: i32, j: i32, k: i32) -> [f32; 4] {
    let c = access.get_pixel(i as u32, j as u32, k as u32);
    if access.format().order.is_srgb() { srgb_to_linear(c) } else { c }
}

impl ConstPixelBufferAccess<'_> {
    /// `sampleNearest2D` / `sampleLinear2D`, reached through `sample2DOffset`.
    ///
    /// Only CLAMP_TO_EDGE is ported, so the CLAMP_TO_BORDER branches upstream carries
    /// through both functions are absent rather than dead.
    pub fn sample_2d(&self, sampler: &Sampler, s: f32, t: f32, layer: i32) -> [f32; 4] {
        let [w, h, _] = self.size();
        let (u, v) = if sampler.normalized_coords {
            (unnormalize(sampler.wrap_s, s, w), unnormalize(sampler.wrap_t, t, h))
        } else {
            (s, t)
        };

        match sampler.filter {
            FilterMode::Nearest => {
                let i = wrap(sampler.wrap_s, u.floor() as i32, w as i32);
                let j = wrap(sampler.wrap_t, v.floor() as i32, h as i32);
                lookup(self, i, j, layer)
            }
            FilterMode::Linear => {
                let x0 = (u - 0.5).floor() as i32;
                let y0 = (v - 0.5).floor() as i32;
                let i0 = wrap(sampler.wrap_s, x0, w as i32);
                let i1 = wrap(sampler.wrap_s, x0 + 1, w as i32);
                let j0 = wrap(sampler.wrap_t, y0, h as i32);
                let j1 = wrap(sampler.wrap_t, y0 + 1, h as i32);

                let a = frac(u - 0.5);
                let b = frac(v - 0.5);

                let p00 = lookup(self, i0, j0, layer);
                let p10 = lookup(self, i1, j0, layer);
                let p01 = lookup(self, i0, j1, layer);
                let p11 = lookup(self, i1, j1, layer);

                std::array::from_fn(|c| p00[c] * (1.0 - a) * (1.0 - b) + p10[c] * a * (1.0 - b) + p01[c] * (1.0 - a) * b + p11[c] * a * b)
            }
            // `sampleCubic2D` - a 4x4 tap centred one texel earlier than the linear
            // pair, weighted by the Catmull-Rom basis.
            FilterMode::Cubic => {
                let x0 = (u - 1.5).floor() as i32;
                let y0 = (v - 1.5).floor() as i32;
                let i: [i32; 4] = std::array::from_fn(|m| wrap(sampler.wrap_s, x0 + m as i32, w as i32));
                let j: [i32; 4] = std::array::from_fn(|n| wrap(sampler.wrap_t, y0 + n as i32, h as i32));

                let wi = cubic_weights(frac(u - 0.5));
                let wj = cubic_weights(frac(v - 0.5));

                let mut result = [0.0f32; 4];
                for n in 0..4 {
                    for m in 0..4 {
                        let p = lookup(self, i[m], j[n], layer);
                        for (c, r) in result.iter_mut().enumerate() {
                            *r += wi[m] * wj[n] * p[c];
                        }
                    }
                }
                result
            }
        }
    }

    /// `sampleNearest3D` / `sampleLinear3D`, reached through `sample3DOffset`.
    pub fn sample_3d(&self, sampler: &Sampler, s: f32, t: f32, r: f32) -> [f32; 4] {
        let [w, h, d] = self.size();
        let (u, v, ww) = if sampler.normalized_coords {
            (unnormalize(sampler.wrap_s, s, w), unnormalize(sampler.wrap_t, t, h), unnormalize(sampler.wrap_r, r, d))
        } else {
            (s, t, r)
        };

        match sampler.filter {
            FilterMode::Nearest => {
                let i = wrap(sampler.wrap_s, u.floor() as i32, w as i32);
                let j = wrap(sampler.wrap_t, v.floor() as i32, h as i32);
                let k = wrap(sampler.wrap_r, ww.floor() as i32, d as i32);
                lookup(self, i, j, k)
            }
            FilterMode::Linear => {
                let x0 = (u - 0.5).floor() as i32;
                let y0 = (v - 0.5).floor() as i32;
                let z0 = (ww - 0.5).floor() as i32;
                let i0 = wrap(sampler.wrap_s, x0, w as i32);
                let i1 = wrap(sampler.wrap_s, x0 + 1, w as i32);
                let j0 = wrap(sampler.wrap_t, y0, h as i32);
                let j1 = wrap(sampler.wrap_t, y0 + 1, h as i32);
                let k0 = wrap(sampler.wrap_r, z0, d as i32);
                let k1 = wrap(sampler.wrap_r, z0 + 1, d as i32);

                let a = frac(u - 0.5);
                let b = frac(v - 0.5);
                let c = frac(ww - 0.5);

                let p000 = lookup(self, i0, j0, k0);
                let p100 = lookup(self, i1, j0, k0);
                let p010 = lookup(self, i0, j1, k0);
                let p110 = lookup(self, i1, j1, k0);
                let p001 = lookup(self, i0, j0, k1);
                let p101 = lookup(self, i1, j0, k1);
                let p011 = lookup(self, i0, j1, k1);
                let p111 = lookup(self, i1, j1, k1);

                std::array::from_fn(|n| {
                    p000[n] * (1.0 - a) * (1.0 - b) * (1.0 - c)
                        + p100[n] * a * (1.0 - b) * (1.0 - c)
                        + p010[n] * (1.0 - a) * b * (1.0 - c)
                        + p110[n] * a * b * (1.0 - c)
                        + p001[n] * (1.0 - a) * (1.0 - b) * c
                        + p101[n] * a * (1.0 - b) * c
                        + p011[n] * (1.0 - a) * b * c
                        + p111[n] * a * b * c
                })
            }
            // `sampleCubic3D` - the same basis on all three axes, 64 taps.
            FilterMode::Cubic => {
                let x0 = (u - 1.5).floor() as i32;
                let y0 = (v - 1.5).floor() as i32;
                let z0 = (ww - 1.5).floor() as i32;
                let i: [i32; 4] = std::array::from_fn(|m| wrap(sampler.wrap_s, x0 + m as i32, w as i32));
                let j: [i32; 4] = std::array::from_fn(|n| wrap(sampler.wrap_t, y0 + n as i32, h as i32));
                let k: [i32; 4] = std::array::from_fn(|o| wrap(sampler.wrap_r, z0 + o as i32, d as i32));

                let wi = cubic_weights(frac(u - 0.5));
                let wj = cubic_weights(frac(v - 0.5));
                let wk = cubic_weights(frac(ww - 0.5));

                let mut result = [0.0f32; 4];
                for o in 0..4 {
                    for n in 0..4 {
                        for m in 0..4 {
                            let p = lookup(self, i[m], j[n], k[o]);
                            for (c, r) in result.iter_mut().enumerate() {
                                *r += wi[m] * wj[n] * wk[o] * p[c];
                            }
                        }
                    }
                }
                result
            }
        }
    }

    /// `tcu::getSubregion` - a view of a box inside this level, sharing its pitch.
    pub fn get_subregion(&self, x: u32, y: u32, z: u32, width: u32, height: u32, depth: u32) -> ConstPixelBufferAccess<'_> {
        let [pixel_pitch, row_pitch, slice_pitch] = self.pitch();
        let offset = x as usize * pixel_pitch + y as usize * row_pitch + z as usize * slice_pitch;
        ConstPixelBufferAccess::new_with_pitch(self.format(), [width, height, depth], self.pitch(), &self.raw()[offset..])
    }
}

impl<'a> PixelBufferAccess<'a> {
    /// `tcu::getSubregion` on a writable level.
    pub fn get_subregion(&mut self, x: u32, y: u32, z: u32, width: u32, height: u32, depth: u32) -> PixelBufferAccess<'_> {
        let [pixel_pitch, row_pitch, slice_pitch] = self.pitch;
        let offset = x as usize * pixel_pitch + y as usize * row_pitch + z as usize * slice_pitch;
        PixelBufferAccess {
            format: self.format,
            size: [width, height, depth],
            pitch: self.pitch,
            data: &mut self.data[offset..],
        }
    }

    /// The read view of the same region, for the passes that sample what they wrote.
    pub fn as_const(&self) -> ConstPixelBufferAccess<'_> {
        ConstPixelBufferAccess::new_with_pitch(self.format, self.size, self.pitch, self.data)
    }
}

/// `tcu::scale` - resample `src` to fill `dst`, at `dst`'s resolution.
///
/// The coordinate is the destination texel centre scaled by the size ratio, so the
/// edges are sampled at half a destination texel in, not at 0 and 1.
pub fn scale(dst: &mut PixelBufferAccess<'_>, src: &ConstPixelBufferAccess<'_>, filter: FilterMode) {
    let sampler = Sampler::clamp_to_edge(filter);
    let [sw, sh, sd] = src.size();
    let [dw, dh, dd] = dst.size();

    let s_x = sw as f32 / dw as f32;
    let s_y = sh as f32 / dh as f32;
    let s_z = sd as f32 / dd as f32;
    let dst_format = dst.format();

    if dd == 1 && sd == 1 {
        for y in 0..dh {
            for x in 0..dw {
                let c = src.sample_2d(&sampler, (x as f32 + 0.5) * s_x, (y as f32 + 0.5) * s_y, 0);
                dst.set_pixel(linear_to_srgb_if_needed(dst_format, c), x, y, 0);
            }
        }
    } else {
        for z in 0..dd {
            for y in 0..dh {
                for x in 0..dw {
                    let c = src.sample_3d(&sampler, (x as f32 + 0.5) * s_x, (y as f32 + 0.5) * s_y, (z as f32 + 0.5) * s_z);
                    dst.set_pixel(linear_to_srgb_if_needed(dst_format, c), x, y, z);
                }
            }
        }
    }
}

/// `deFloatFrac`
fn frac(v: f32) -> f32 {
    v - v.floor()
}

/// `tcu::TextureLevel` - owns tightly-packed storage for one mip level.
pub struct TextureLevel {
    format: TextureFormat,
    size: [u32; 3],
    data: Vec<u8>,
}

impl TextureLevel {
    pub fn new(format: TextureFormat, width: u32, height: u32, depth: u32) -> Result<Self, TestError> {
        if !is_writable_channel_type(format.type_) {
            return Err(TestError::NotPorted(format!("writing texels of channel type {:?}", format.type_)));
        }
        let pixel_size = format
            .pixel_size()
            .ok_or_else(|| TestError::NotPorted(format!("pixel size of channel type {:?}", format.type_)))?;
        let len = (width as usize) * (height as usize) * (depth as usize) * (pixel_size as usize);
        Ok(Self {
            format,
            size: [width, height, depth],
            data: vec![0u8; len],
        })
    }

    /// `TextureLevel::getAccess`
    pub fn get_access(&mut self) -> PixelBufferAccess<'_> {
        PixelBufferAccess {
            format: self.format,
            size: self.size,
            pitch: tight_pitch(self.format, self.size),
            data: &mut self.data,
        }
    }

    /// `TextureLevel::getAccess` on a const level.
    pub fn get_const_access(&self) -> ConstPixelBufferAccess<'_> {
        ConstPixelBufferAccess::new(self.format, self.size, &self.data)
    }

    pub fn format(&self) -> TextureFormat {
        self.format
    }

    pub fn size(&self) -> [u32; 3] {
        self.size
    }

    pub fn data(&self) -> &[u8] {
        &self.data
    }

    pub fn data_mut(&mut self) -> &mut [u8] {
        &mut self.data
    }
}

/// `tcu::PixelBufferAccess` - the writable twin of `ConstPixelBufferAccess`.
pub struct PixelBufferAccess<'a> {
    format: TextureFormat,
    size: [u32; 3],
    /// `m_pitch` - see `ConstPixelBufferAccess`.
    pitch: [usize; 3],
    data: &'a mut [u8],
}

impl PixelBufferAccess<'_> {
    pub fn format(&self) -> TextureFormat {
        self.format
    }

    pub fn size(&self) -> [u32; 3] {
        self.size
    }

    /// `getPitch`
    pub fn pitch(&self) -> [usize; 3] {
        self.pitch
    }

    fn pixel_size(&self) -> usize {
        self.format.pixel_size().expect("checked in TextureLevel::new") as usize
    }

    fn pixel_offset(&self, x: u32, y: u32, z: u32) -> usize {
        let [pixel_pitch, row_pitch, slice_pitch] = self.pitch;
        x as usize * pixel_pitch + y as usize * row_pitch + z as usize * slice_pitch
    }

    /// `tcu::PixelBufferAccess::setPixel(const IVec4&)`
    ///
    /// Returns false for a channel type upstream's switch asserts on, rather than
    /// writing an approximation a comparison could not tell from a driver bug.
    #[must_use]
    pub fn set_pixel_int(&mut self, color: [i32; 4], x: u32, y: u32, z: u32) -> bool {
        // `writeRGBA8888Int` / `writeRGB888Int`. Not just an optimisation: these clamp
        // the *signed* value, so a negative channel becomes 0 here, where the generic
        // path below reads it as uint32_t first and saturates it to the maximum. Both
        // R8G8B8A8_UNORM and B8G8R8A8_UNORM are blit formats, so the two behaviours
        // are reachable side by side and cannot be unified.
        if self.format.type_ == ChannelType::UNORM_INT8 {
            let n = match self.format.order {
                ChannelOrder::RGBA | ChannelOrder::sRGBA => 4,
                ChannelOrder::RGB | ChannelOrder::sRGB => 3,
                _ => 0,
            };
            if n > 0 {
                let base = self.pixel_offset(x, y, z);
                for (dst, &c) in self.data[base..base + n].iter_mut().zip(color.iter()) {
                    *dst = c.clamp(0, 255) as u8;
                }
                return true;
            }
        }

        if is_packed_int_writable(self.format.type_) {
            let base = self.pixel_offset(x, y, z);
            let size = self.pixel_size();
            let format = self.format;
            set_packed_pixel_int(&mut self.data[base..base + size], color, format);
            return true;
        }
        if is_packed_writable(self.format.type_) {
            return false;
        }

        let num_channels = self.format.order.num_used_channels() as usize;
        let map = get_channel_write_swizzle(self.format.order);
        let Some(channel_size) = self.format.type_.channel_size().map(|s| s as usize) else {
            return false;
        };
        let base = self.pixel_offset(x, y, z);
        let type_ = self.format.type_;

        for (c, swz) in map.iter().take(num_channels).enumerate() {
            let src = swz.index().expect("write swizzle names a real component below num_used_channels");
            let off = base + channel_size * c;
            if !int_to_channel_bytes(&mut self.data[off..off + channel_size], color[src], type_) {
                return false;
            }
        }
        true
    }

    /// `tcu::PixelBufferAccess::setPixel`, generic path only.
    pub fn set_pixel(&mut self, color: [f32; 4], x: u32, y: u32, z: u32) {
        if is_packed_writable(self.format.type_) {
            let base = self.pixel_offset(x, y, z);
            let size = self.pixel_size();
            let format = self.format;
            set_packed_pixel(&mut self.data[base..base + size], color, format);
            return;
        }

        let num_channels = self.format.order.num_used_channels() as usize;
        let map = get_channel_write_swizzle(self.format.order);
        let channel_size = self.format.type_.channel_size().expect("non-packed, checked in TextureLevel::new") as usize;
        let base = self.pixel_offset(x, y, z);
        let type_ = self.format.type_;

        for (c, swz) in map.iter().take(num_channels).enumerate() {
            let src = swz.index().expect("write swizzle names a real component below num_used_channels");
            let off = base + channel_size * c;
            float_to_channel(&mut self.data[off..off + channel_size], color[src], type_);
        }
    }

    /// The mirror of `copy_texels_from`: a run taken from an (x, y, z) position in a
    /// multi-dimensional source into a flat index here. `tcu::getSubregion` on the
    /// source side rather than the destination side, which is the only difference
    /// between upstream's two copyRegionToTextureLevel directions.
    pub fn copy_texels_from_position(&mut self, src: &ConstPixelBufferAccess<'_>, src_pos: (u32, u32, u32), dst_texel: usize, count: usize) {
        let pixel_size = self.pixel_size();
        let [sw, sh, _] = src.size();
        let src_index = ((src_pos.2 as usize * sh as usize) + src_pos.1 as usize) * sw as usize + src_pos.0 as usize;
        let src_off = src_index * pixel_size;
        let dst_off = dst_texel * pixel_size;
        let bytes = count * pixel_size;
        self.data[dst_off..dst_off + bytes].copy_from_slice(&src.raw()[src_off..src_off + bytes]);
    }

    /// `PixelBufferAccess::setPixDepth`
    ///
    /// Only the combined types need a case of their own; a depth-only format falls
    /// through to the ordinary channel encoder.
    pub fn set_pix_depth(&mut self, depth: f32, x: u32, y: u32, z: u32) {
        use ChannelType::*;
        let base = self.pixel_offset(x, y, z);
        let type_ = self.format.type_;
        let dst = &mut self.data[base..];
        match type_ {
            UNSIGNED_INT_16_8_8 => {
                let v = convert_sat_rte(depth * 65535.0, 0, 65535) as u16;
                dst[2..4].copy_from_slice(&v.to_le_bytes());
            }
            UNSIGNED_INT_24_8 => {
                let v = convert_sat_rte(depth * 16_777_215.0, 0, u32::MAX as i64) as u32;
                dst[1..4].copy_from_slice(&v.to_le_bytes()[..3]);
            }
            UNSIGNED_INT_24_8_REV => {
                let v = convert_sat_rte(depth * 16_777_215.0, 0, u32::MAX as i64) as u32;
                dst[0..3].copy_from_slice(&v.to_le_bytes()[..3]);
            }
            FLOAT_UNSIGNED_INT_24_8_REV => dst[..4].copy_from_slice(&depth.to_le_bytes()),
            other => {
                let size = other.channel_size().expect("a depth-only format has a channel size") as usize;
                float_to_channel(&mut dst[..size], depth, other);
            }
        }
    }

    /// `PixelBufferAccess::setPixStencil`
    pub fn set_pix_stencil(&mut self, stencil: u32, x: u32, y: u32, z: u32) {
        use ChannelType::*;
        let base = self.pixel_offset(x, y, z);
        let type_ = self.format.type_;
        let value = stencil.min(255) as u8;
        let dst = &mut self.data[base..];
        match type_ {
            UNSIGNED_INT_16_8_8 | UNSIGNED_INT_24_8 => dst[0] = value,
            UNSIGNED_INT_24_8_REV => dst[3] = value,
            FLOAT_UNSIGNED_INT_24_8_REV => dst[4] = value,
            other => {
                let size = other.channel_size().expect("a stencil-only format has a channel size") as usize;
                float_to_channel(&mut dst[..size], f32::from(value), other);
            }
        }
    }

    /// Fills a texel with a repeated byte, the last one replaced. `FILL_MODE_RANDOM_GRAY`
    /// writes the raw bytes rather than a colour for the float formats, so this bypasses
    /// the channel encoders entirely.
    pub fn fill_pixel_bytes(&mut self, x: u32, y: u32, z: u32, value: u8, last: u8, pixel_size: usize) {
        let base = self.pixel_offset(x, y, z);
        self.data[base..base + pixel_size - 1].fill(value);
        self.data[base + pixel_size - 1] = last;
    }

    /// A 3D region copied verbatim, byte for byte.
    ///
    /// `vkCmdCopyImage` acts like a memcpy even between different formats, as long as
    /// they are size-compatible, so upstream imposes the source format on the
    /// destination access and copies. That is only sound when the two texel sizes
    /// match, which size-compatibility guarantees - asserted here rather than assumed.
    pub fn copy_region_from(&mut self, src: &ConstPixelBufferAccess<'_>, src_pos: (u32, u32, u32), dst_pos: (u32, u32, u32), extent: (u32, u32, u32)) {
        let pixel_size = self.pixel_size();
        assert_eq!(
            pixel_size,
            src.format().pixel_size().expect("source format has a pixel size") as usize,
            "copy_region_from needs size-compatible formats"
        );
        let [sw, sh, _] = src.size();
        let [dw, dh, _] = self.size();

        for z in 0..extent.2 {
            for y in 0..extent.1 {
                let s = (((src_pos.2 + z) as usize * sh as usize) + (src_pos.1 + y) as usize) * sw as usize + src_pos.0 as usize;
                let d = (((dst_pos.2 + z) as usize * dh as usize) + (dst_pos.1 + y) as usize) * dw as usize + dst_pos.0 as usize;
                let bytes = extent.0 as usize * pixel_size;
                self.data[d * pixel_size..d * pixel_size + bytes].copy_from_slice(&src.raw()[s * pixel_size..s * pixel_size + bytes]);
            }
        }
    }

    /// Raw texel-run copy. Both sides are tightly packed and share a format, which is
    /// all `tcu::copy` amounts to for the buffer/image copy tests.
    pub fn copy_texels_from(&mut self, src: &ConstPixelBufferAccess<'_>, src_texel: usize, dst: (u32, u32, u32), count: usize) {
        let pixel_size = self.pixel_size();
        let src_off = src_texel * pixel_size;
        let dst_off = self.pixel_offset(dst.0, dst.1, dst.2);
        let bytes = count * pixel_size;
        self.data[dst_off..dst_off + bytes].copy_from_slice(&src.raw()[src_off..src_off + bytes]);
    }
}

/// `tcu::linearInterpolate`
fn linear_interpolate(t: f32, min_val: f32, max_val: f32) -> f32 {
    min_val + (max_val - min_val) * t
}

/// The four per-channel interpolation coefficients at one texel, factored out of the
/// fill loops so the combined depth/stencil branch can read the same ones.
fn gradient_coefficients(x: u32, y: u32, z: u32, width: u32, height: u32, depth: u32, style: GradientStyle) -> [f32; 4] {
    let s = (x as f32 + 0.5) / width as f32;

    if height == 1 && depth == 1 {
        return [s; 4];
    }

    let t = (y as f32 + 0.5) / height as f32;

    if depth == 1 {
        if style == GradientStyle::Pyramid {
            let xedge = (width as f32 * 0.6).floor() as u32;
            let yedge = (height as f32 * 0.6).floor() as u32;
            let (mut cr, mut cg, mut cb, mut ca) = if x < xedge {
                (s * 0.4, s * 0.4, (1.0 - s) * 0.4, (1.0 - s) * 0.4)
            } else {
                ((1.0 - s) * 0.6, (1.0 - s) * 0.6, s * 0.6 - 0.2, s * 0.6 - 0.2)
            };
            if y < yedge {
                cr += t * 0.4;
                cg += (1.0 - t) * 0.4;
                cb += t * 0.4;
                ca += (1.0 - t) * 0.4;
            } else {
                cr += (1.0 - t) * 0.6;
                cg += t * 0.6 - 0.2;
                cb += (1.0 - t) * 0.6;
                ca += t * 0.6 - 0.2;
            }
            return [cr, cg, cb, ca];
        }
        return [(s + t) * 0.5, (s + (1.0 - t)) * 0.5, ((1.0 - s) + t) * 0.5, ((1.0 - s) + (1.0 - t)) * 0.5];
    }

    let p = (z as f32 + 0.5) / depth as f32;
    if style == GradientStyle::New {
        [
            (s + t + p) / 3.0,
            (s + (1.0 - (t + p) * 0.5) * 2.0) / 3.0,
            ((1.0 - (s + t) * 0.5) * 2.0 + p) / 3.0,
            1.0 - (s + t + p) / 3.0,
        ]
    } else {
        [s, t, p, 1.0 - (s + t + p) / 3.0]
    }
}

/// `tcu::GradientStyle`
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum GradientStyle {
    New,
    Pyramid,
}

/// `tcu::fillWithComponentGradients2`
pub fn fill_with_component_gradients2(access: &mut PixelBufferAccess<'_>, min_val: [f32; 4], max_val: [f32; 4]) {
    fill_with_component_gradients_styled(access, min_val, max_val, GradientStyle::New);
}

/// `tcu::fillWithComponentGradients3`
pub fn fill_with_component_gradients3(access: &mut PixelBufferAccess<'_>, min_val: [f32; 4], max_val: [f32; 4]) {
    fill_with_component_gradients_styled(access, min_val, max_val, GradientStyle::Pyramid);
}

/// `tcu::fillWithComponentGradientsStyled`, dispatched on dimensionality exactly as
/// upstream does. Only the 2D fill actually reads the style: the 1D one ignores it, and
/// the 3D one treats anything that is not `New` as the old per-axis ramp.
pub fn fill_with_component_gradients_styled(access: &mut PixelBufferAccess<'_>, min_val: [f32; 4], max_val: [f32; 4], style: GradientStyle) {
    let [width, height, depth] = access.size();

    // Upstream recurses into the effective depth and stencil accesses, the stencil one
    // with the bounds swizzled so that channel 0 carries what was the alpha bound. Both
    // fills share the geometry, so both read the channel-0 coefficient - which is what
    // this writes directly rather than building a strided sub-access to recurse into.
    if is_combined_depth_stencil_type(access.format().type_) {
        for z in 0..depth {
            for y in 0..height {
                for x in 0..width {
                    let coef = gradient_coefficients(x, y, z, width, height, depth, style)[0];
                    access.set_pix_depth(linear_interpolate(coef, min_val[0], max_val[0]), x, y, z);
                    access.set_pix_stencil(linear_interpolate(coef, min_val[3], max_val[3]) as u32, x, y, z);
                }
            }
        }
        return;
    }

    for z in 0..depth {
        for y in 0..height {
            for x in 0..width {
                let c = gradient_coefficients(x, y, z, width, height, depth, style);
                let color = std::array::from_fn(|i| linear_interpolate(c[i], min_val[i], max_val[i]));
                access.set_pixel(color, x, y, z);
            }
        }
    }
}


// ---------------------------------------------------------------------------------
// Texture views
//
// `Texture1DArrayView` and friends: a sampler's-eye view of a mip pyramid, where the
// caller has already cut the levels it wants. Only lod 0 with a non-mipmapping filter
// is ported, which is what every case reaching this today asks for; upstream's
// `sampleLevelArray*` chooses between min and mag filter on `lod <= lodThreshold` and
// then indexes a level, and with one filter and lod 0 that reduces to level 0.
// ---------------------------------------------------------------------------------

impl ConstPixelBufferAccess<'_> {
    /// `sampleNearest1D` / `sampleLinear1D`, reached through `sample1D`. `layer` is
    /// the offset.y() upstream threads through for a 1D array.
    pub fn sample_1d(&self, sampler: &Sampler, s: f32, layer: i32) -> [f32; 4] {
        let w = self.size()[0];
        let u = if sampler.normalized_coords { unnormalize(sampler.wrap_s, s, w) } else { s };

        match sampler.filter {
            FilterMode::Nearest => lookup(self, wrap(sampler.wrap_s, u.floor() as i32, w as i32), layer, 0),
            FilterMode::Linear => {
                let x0 = (u - 0.5).floor() as i32;
                let i0 = wrap(sampler.wrap_s, x0, w as i32);
                let i1 = wrap(sampler.wrap_s, x0 + 1, w as i32);
                let a = frac(u - 0.5);

                let p0 = lookup(self, i0, layer, 0);
                let p1 = lookup(self, i1, layer, 0);
                std::array::from_fn(|c| p0[c] * (1.0 - a) + p1[c] * a)
            }
            FilterMode::Cubic => unimplemented!("cubic 1D sampling"),
        }
    }
}

/// `tcu::CubeFace`
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum CubeFace {
    NegativeX,
    PositiveX,
    NegativeY,
    PositiveY,
    NegativeZ,
    PositiveZ,
}

/// `tcu::getCubeArrayFaceIndex` - where a face sits among the six layers Vulkan
/// stores a cube in, which is a different order from `CubeFace` itself.
pub fn get_cube_array_face_index(face: CubeFace) -> u32 {
    match face {
        CubeFace::PositiveX => 0,
        CubeFace::NegativeX => 1,
        CubeFace::PositiveY => 2,
        CubeFace::NegativeY => 3,
        CubeFace::PositiveZ => 4,
        CubeFace::NegativeZ => 5,
    }
}

/// `tcu::selectCubeFace` - the major axis wins; when two are equal the tie-break
/// rules below decide, which is what keeps the choice deterministic on an edge.
pub fn select_cube_face(coords: [f32; 3]) -> CubeFace {
    let [x, y, z] = coords;
    let (ax, ay, az) = (x.abs(), y.abs(), z.abs());

    let px = if x >= 0.0 { CubeFace::PositiveX } else { CubeFace::NegativeX };
    let py = if y >= 0.0 { CubeFace::PositiveY } else { CubeFace::NegativeY };
    let pz = if z >= 0.0 { CubeFace::PositiveZ } else { CubeFace::NegativeZ };

    if ay < ax && az < ax {
        px
    } else if ax < ay && az < ay {
        py
    } else if ax < az && ay < az {
        pz
    } else if ax == ay {
        if ax < az { pz } else { px }
    } else if ax == az {
        if az < ay { py } else { pz }
    } else if ay == az {
        if ay < ax { px } else { py }
    } else {
        px
    }
}

/// `tcu::projectToFace`
pub fn project_to_face(face: CubeFace, coord: [f32; 3]) -> [f32; 2] {
    let [rx, ry, rz] = coord;
    let (sc, tc, ma) = match face {
        CubeFace::NegativeX => (rz, -ry, -rx),
        CubeFace::PositiveX => (-rz, -ry, rx),
        CubeFace::NegativeY => (rx, -rz, -ry),
        CubeFace::PositiveY => (rx, rz, ry),
        CubeFace::NegativeZ => (-rx, -ry, -rz),
        CubeFace::PositiveZ => (rx, -ry, rz),
    };

    if ma.abs() < f32::EPSILON {
        return [0.0, 0.0];
    }

    [((sc / ma) + 1.0) / 2.0, ((tc / ma) + 1.0) / 2.0]
}

/// `tcu::getCubeFaceCoords`
pub fn get_cube_face_coords(coords: [f32; 3]) -> (CubeFace, [f32; 2]) {
    let face = select_cube_face(coords);
    (face, project_to_face(face, coords))
}

/// `tcu::remapCubeEdgeCoords` - a texel that fell off one face lands on a neighbour.
/// `None` means it fell off in both axes at once, i.e. it is a corner and no single
/// neighbour owns it.
pub fn remap_cube_edge_coords(face: CubeFace, s: i32, t: i32, size: i32) -> Option<(CubeFace, i32, i32)> {
    let u_in_bounds = (0..size).contains(&s);
    let v_in_bounds = (0..size).contains(&t);

    if u_in_bounds && v_in_bounds {
        return Some((face, s, t));
    }
    if !u_in_bounds && !v_in_bounds {
        return None;
    }

    let x = wrap(WrapMode::ClampToBorder, s, size);
    let y = wrap(WrapMode::ClampToBorder, t, size);

    // Map the uv coordinates onto the cube's own axes, where "off the face" becomes a
    // coordinate of -1 or size and so names the neighbour directly.
    let c = match face {
        CubeFace::NegativeX => [0, size - 1 - y, x],
        CubeFace::PositiveX => [size - 1, size - 1 - y, size - 1 - x],
        CubeFace::NegativeY => [x, 0, size - 1 - y],
        CubeFace::PositiveY => [x, size - 1, y],
        CubeFace::NegativeZ => [size - 1 - x, size - 1 - y, 0],
        CubeFace::PositiveZ => [x, size - 1 - y, size - 1],
    };

    if c[0] == -1 {
        return Some((CubeFace::NegativeX, c[2], size - 1 - c[1]));
    }
    if c[0] == size {
        return Some((CubeFace::PositiveX, size - 1 - c[2], size - 1 - c[1]));
    }
    if c[1] == -1 {
        return Some((CubeFace::NegativeY, c[0], size - 1 - c[2]));
    }
    if c[1] == size {
        return Some((CubeFace::PositiveY, c[0], c[2]));
    }
    if c[2] == -1 {
        return Some((CubeFace::NegativeZ, size - 1 - c[0], size - 1 - c[1]));
    }
    if c[2] == size {
        return Some((CubeFace::PositiveZ, c[0], size - 1 - c[1]));
    }
    unreachable!("a coordinate out of bounds in exactly one axis always names a neighbour")
}

/// `sampleCubeSeamlessNearest` - a nearest tap never crosses an edge, so the only
/// thing seamlessness changes is that the wrap mode is forced to clamp.
fn sample_cube_seamless_nearest(face_access: &ConstPixelBufferAccess<'_>, sampler: &Sampler, s: f32, t: f32, depth: i32) -> [f32; 4] {
    let mut clamping = *sampler;
    clamping.wrap_s = WrapMode::ClampToEdge;
    clamping.wrap_t = WrapMode::ClampToEdge;
    clamping.filter = FilterMode::Nearest;
    face_access.sample_2d(&clamping, s, t, depth)
}

/// `getCubeLinearSamples` - the four taps of a bilinear filter, each followed onto
/// whichever face it actually landed on. A corner tap belongs to no face, so upstream
/// gives it the average of the other three.
fn get_cube_linear_samples(face_accesses: &[ConstPixelBufferAccess<'_>; 6], base_face: CubeFace, u: f32, v: f32, depth: i32) -> [[f32; 4]; 4] {
    let size = face_accesses[0].size()[0] as i32;
    let x0 = (u - 0.5).floor() as i32;
    let y0 = (v - 0.5).floor() as i32;
    let base = [(x0, y0), (x0 + 1, y0), (x0, y0 + 1), (x0 + 1, y0 + 1)];

    let mut colors = [[0.0f32; 4]; 4];
    let mut corner = None;
    for (i, (x, y)) in base.into_iter().enumerate() {
        match remap_cube_edge_coords(base_face, x, y, size) {
            Some((face, s, t)) => colors[i] = lookup(&face_accesses[get_cube_face_slot(face)], s, t, depth),
            None => corner = Some(i),
        }
    }

    if let Some(i) = corner {
        let mut sum = [0.0f32; 4];
        for (j, color) in colors.iter().enumerate() {
            if j != i {
                for (c, s) in sum.iter_mut().zip(color) {
                    *c += s;
                }
            }
        }
        colors[i] = sum.map(|c| c / 3.0);
    }

    colors
}

/// Where a face sits in a `[ConstPixelBufferAccess; 6]` indexed by `CubeFace` itself,
/// which is the enum's own order rather than the Vulkan layer order.
fn get_cube_face_slot(face: CubeFace) -> usize {
    match face {
        CubeFace::NegativeX => 0,
        CubeFace::PositiveX => 1,
        CubeFace::NegativeY => 2,
        CubeFace::PositiveY => 3,
        CubeFace::NegativeZ => 4,
        CubeFace::PositiveZ => 5,
    }
}

/// `sampleCubeSeamlessLinear`
fn sample_cube_seamless_linear(face_accesses: &[ConstPixelBufferAccess<'_>; 6], base_face: CubeFace, sampler: &Sampler, s: f32, t: f32, depth: i32) -> [f32; 4] {
    let size = face_accesses[0].size()[0];
    let (u, v) = if sampler.normalized_coords {
        (unnormalize(sampler.wrap_s, s, size), unnormalize(sampler.wrap_t, t, size))
    } else {
        (s, t)
    };

    let colors = get_cube_linear_samples(face_accesses, base_face, u, v, depth);
    let a = frac(u - 0.5);
    let b = frac(v - 0.5);

    std::array::from_fn(|c| colors[0][c] * (1.0 - a) * (1.0 - b) + colors[1][c] * a * (1.0 - b) + colors[2][c] * (1.0 - a) * b + colors[3][c] * a * b)
}

/// `tcu::Texture1DArrayView`, at lod 0.
pub struct Texture1DArrayView<'a> {
    pub level0: ConstPixelBufferAccess<'a>,
}

impl Texture1DArrayView<'_> {
    /// `selectLayer` - the array index is a coordinate, rounded rather than filtered.
    fn select_layer(&self, t: f32) -> i32 {
        ((t + 0.5).floor() as i32).clamp(0, self.level0.size()[1] as i32 - 1)
    }

    pub fn sample(&self, sampler: &Sampler, s: f32, t: f32) -> [f32; 4] {
        self.level0.sample_1d(sampler, s, self.select_layer(t))
    }
}

