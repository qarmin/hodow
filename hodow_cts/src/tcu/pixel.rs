/// `sample_2d_mipmap`'s `textureOffset`/`textureProjOffset`/... counterpart.
pub fn sample_2d_mipmap_offset(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    s: f32,
    t: f32,
    lod: f32,
    offset: [i32; 2],
) -> [f32; 4] {
    levels[mipmap_level(levels.len(), lod)].sample_2d_offset(sampler, s, t, 0, offset)
}

/// `sample_2d_mipmap_compare`'s `textureOffset`/`textureProjOffset`/... counterpart -
/// the shadow-sampler analogue of `sample_2d_mipmap_offset`, same single-level-pick mip
/// dispatch (no `_filtered`/trilinear variant exists for this pairing any more than for
/// `sample_2d_mipmap_offset` itself - nothing this port builds samples a shadow texture
/// with both `textureOffset` and `*_MIPMAP_LINEAR` at once).
pub fn sample_2d_mipmap_compare_offset(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    ref_: f32,
    s: f32,
    t: f32,
    lod: f32,
    offset: [i32; 2],
) -> f32 {
    levels[mipmap_level(levels.len(), lod)].sample_2d_compare_offset(sampler, ref_, s, t, 0, offset)
}

/// `evalTexelFetch2D` - `texelFetch` reads one texel of one explicit level directly, with
/// no filtering and no wrapping at all (an out-of-range coordinate is undefined behaviour
/// in GLSL, not a wrapped one), so this bypasses `Sampler` entirely rather than routing
/// through `sample_2d`/`sample_2d_offset`.
pub fn texel_fetch_2d(levels: &[ConstPixelBufferAccess<'_>], lod: i32, x: i32, y: i32) -> [f32; 4] {
    lookup(&levels[lod as usize], x, y, 0)
}

/// `Texture2DArrayView::selectLayer` - the array-layer coordinate is rounded to the
/// nearest integer layer (never filtered/interpolated across layers), then clamped to the
/// texture's own layer count.
fn select_layer(r: f32, num_layers: u32) -> i32 {
    ((r + 0.5).floor() as i32).clamp(0, num_layers as i32 - 1)
}

/// `Texture2DArrayView::sample` through `sampleLevelArray2D` - the array counterpart of
/// `sample_2d_mipmap`. Every level's `ConstPixelBufferAccess` already holds all of its
/// layers as depth slices (see `build_texture_levels`'s `Array2D` branch), so this reuses
/// `sample_2d`'s own `layer` parameter rather than needing a new per-layer sampler.
pub fn sample_2d_array_mipmap(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    s: f32,
    t: f32,
    r: f32,
    lod: f32,
) -> [f32; 4] {
    let layer = select_layer(r, levels[0].size()[2]);
    levels[mipmap_level(levels.len(), lod)].sample_2d(sampler, s, t, layer)
}

/// `sample_2d_array_mipmap`, generalized with the `MipmapFilterMode` axis
/// `sample_2d_mipmap_filtered` introduced - same additive shape, same magnified-always-
/// level-0 narrowing, same trilinear blend formula. The layer is resolved once (array
/// layer selection is nearest-only, never blended across levels or layers, matching
/// `select_layer`'s own doc comment) and reused for both candidate levels.
pub fn sample_2d_array_mipmap_filtered(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    s: f32,
    t: f32,
    r: f32,
    lod: f32,
    mip_filter: MipmapFilterMode,
) -> [f32; 4] {
    let layer = select_layer(r, levels[0].size()[2]);

    if lod <= 0.0 {
        return levels[0].sample_2d(sampler, s, t, layer);
    }

    match mip_filter {
        MipmapFilterMode::Nearest => levels[mipmap_level(levels.len(), lod)].sample_2d(sampler, s, t, layer),
        MipmapFilterMode::Linear => {
            let max_level = levels.len() as i32 - 1;
            let level0 = (lod.floor() as i32).clamp(0, max_level);
            let level1 = (level0 + 1).min(max_level);
            let f = lod.fract();
            let t0 = levels[level0 as usize].sample_2d(sampler, s, t, layer);
            let t1 = levels[level1 as usize].sample_2d(sampler, s, t, layer);
            std::array::from_fn(|c| t0[c] * (1.0 - f) + t1[c] * f)
        }
    }
}

/// `sample_2d_array_mipmap`'s `textureOffset`/... counterpart - the offset only ever
/// covers the `s`/`t` axes, never the layer (`Texture2DArrayView::sampleOffset` folds the
/// selected layer into its `IVec3`'s `z` untouched by `offset`).
pub fn sample_2d_array_mipmap_offset(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    s: f32,
    t: f32,
    r: f32,
    lod: f32,
    offset: [i32; 2],
) -> [f32; 4] {
    let layer = select_layer(r, levels[0].size()[2]);
    levels[mipmap_level(levels.len(), lod)].sample_2d_offset(sampler, s, t, layer, offset)
}

/// `sample_2d_array_mipmap_offset`'s shadow-sampler counterpart - the array analogue of
/// `sample_2d_mipmap_compare_offset`, reusing `sample_2d_compare_offset`'s own `layer`
/// parameter exactly the way `sample_2d_array_mipmap_offset` reuses `sample_2d_offset`'s.
