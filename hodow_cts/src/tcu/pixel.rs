#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum Swz {
    C0,
    C1,
    C2,
    C3,
    ZERO,
    ONE,
    /// `TextureSwizzle::CHANNEL_LAST` - upstream's "slot unused" marker. Only the first
    /// `num_used_channels` entries of a write swizzle are meaningful; the rest are this.
    LAST,
}

impl Swz {
    fn index(self) -> Option<usize> {
        match self {
            Self::C0 => Some(0),
            Self::C1 => Some(1),
            Self::C2 => Some(2),
            Self::C3 => Some(3),
            Self::ZERO | Self::ONE | Self::LAST => None,
        }
    }
}

