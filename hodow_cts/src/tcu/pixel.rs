    const GRID_COLOR_A: [f32; 4] = [1.0, 0.0, 0.0, 1.0];
    const GRID_COLOR_B: [f32; 4] = [0.0, 1.0, 0.0, 1.0];

    /// A height-1/depth-1 access is upstream's `fillWithGrid1D` case: only `x` ever
    /// varies, so the pattern alternates every `cell_size` pixels along that one axis.
    #[test]
    fn fill_with_grid_1d_alternates_by_cell() {
        let format = TextureFormat::new(ChannelOrder::RGBA, ChannelType::FLOAT);
        let mut level = TextureLevel::new(format, 6, 1, 1).unwrap();
        super::fill_with_grid(&mut level.get_access(), 2, GRID_COLOR_A, GRID_COLOR_B);

        let access = level.get_const_access();
        // mx = (x / 2) % 2: x in {0,1} -> 0 -> A, {2,3} -> 1 -> B, {4,5} -> 0 -> A.
        let expect = [
            GRID_COLOR_A,
            GRID_COLOR_A,
            GRID_COLOR_B,
            GRID_COLOR_B,
            GRID_COLOR_A,
            GRID_COLOR_A,
        ];
        for (x, want) in expect.into_iter().enumerate() {
            assert_eq!(access.get_pixel(x as u32, 0, 0), want, "x={x}");
        }
    }

    /// A depth-1, height>1 access is `fillWithGrid2D`: both `x` and `y` are xored
    /// together, so a cell flips colour when crossing either axis but not when moving
    /// diagonally across a shared corner.
    #[test]
    fn fill_with_grid_2d_xors_both_axes() {
        let format = TextureFormat::new(ChannelOrder::RGBA, ChannelType::FLOAT);
        let mut level = TextureLevel::new(format, 4, 4, 1).unwrap();
        super::fill_with_grid(&mut level.get_access(), 1, GRID_COLOR_A, GRID_COLOR_B);

        let access = level.get_const_access();
        assert_eq!(access.get_pixel(0, 0, 0), GRID_COLOR_A, "(0,0): 0^0=0");
        assert_eq!(access.get_pixel(1, 0, 0), GRID_COLOR_B, "(1,0): 1^0=1");
        assert_eq!(access.get_pixel(0, 1, 0), GRID_COLOR_B, "(0,1): 0^1=1");
        assert_eq!(access.get_pixel(1, 1, 0), GRID_COLOR_A, "(1,1): 1^1=0");
        assert_eq!(access.get_pixel(2, 1, 0), GRID_COLOR_B, "(2,1): 0^1=1");
    }

    /// A genuinely 3D access (`height > 1 && depth > 1`) is `fillWithGrid3D`: all three
    /// axes are xored together, which the 2D test above cannot distinguish from a
    /// per-slice-identical 2D fill.
    #[test]
    fn fill_with_grid_3d_xors_all_three_axes() {
        let format = TextureFormat::new(ChannelOrder::RGBA, ChannelType::FLOAT);
        let mut level = TextureLevel::new(format, 2, 2, 2).unwrap();
        super::fill_with_grid(&mut level.get_access(), 1, GRID_COLOR_A, GRID_COLOR_B);

        let access = level.get_const_access();
        assert_eq!(access.get_pixel(1, 1, 0), GRID_COLOR_A, "(1,1,0): 1^1^0=0");
        assert_eq!(access.get_pixel(1, 1, 1), GRID_COLOR_B, "(1,1,1): 1^1^1=1");
        assert_eq!(access.get_pixel(0, 0, 1), GRID_COLOR_B, "(0,0,1): 0^0^1=1");
    }

    /// The combined depth-stencil branch: depth comes from each colour's component 0,
    /// stencil from component 3 - the same split
    /// `effective_depth_stencil_view_matches_in_place_reads` above already exercises
    /// for `get_pix_depth`/`get_pix_stencil` themselves, now driven by the grid's own
    /// per-cell parity rather than a hand-written per-pixel loop.
    #[test]
    fn fill_with_grid_combined_depth_stencil_writes_both_channels_by_parity() {
        let format = TextureFormat::new(ChannelOrder::DS, ChannelType::UNSIGNED_INT_24_8_REV);
        let mut level = TextureLevel::new(format, 4, 1, 1).unwrap();
        let color_a = [0.25, 0.0, 0.0, 10.0];
        let color_b = [0.75, 0.0, 0.0, 20.0];
        super::fill_with_grid(&mut level.get_access(), 1, color_a, color_b);

        let access = level.get_const_access();
        let expect = [(0.25, 10u32), (0.75, 20), (0.25, 10), (0.75, 20)];
        for (x, (want_depth, want_stencil)) in expect.into_iter().enumerate() {
            let got_depth = access.get_pix_depth(x as u32, 0, 0);
            assert!(
                (got_depth - want_depth).abs() < 1e-6,
                "x={x} depth: got {got_depth} want {want_depth}"
            );
            assert_eq!(access.get_pix_stencil(x as u32, 0, 0), want_stencil, "x={x} stencil");
        }
    }
