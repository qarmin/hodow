/// The single-level body `sample_cube_mipmap` used to be - pulled out so
/// `sample_cube_mipmap_filtered`'s trilinear path can sample two different levels
/// through the exact same seamless logic rather than duplicating it.
pub(crate) fn sample_cube_level(
    access: &ConstPixelBufferAccess<'_>,
    sampler: &Sampler,
    s: f32,
    t: f32,
    r: f32,
) -> [f32; 4] {
    let [w, h, _] = access.size();
    let (face, coords) = get_cube_face_coords([s, t, r]);

    match sampler.filter {
        FilterMode::Nearest => {
            let depth = get_cube_array_face_index(face) as i32;
            sample_cube_seamless_nearest(access, sampler, coords[0], coords[1], depth)
        }
        _ => {
            let faces: [ConstPixelBufferAccess<'_>; 6] = std::array::from_fn(|slot| {
                let f = [
                    CubeFace::NegativeX,
                    CubeFace::PositiveX,
                    CubeFace::NegativeY,
                    CubeFace::PositiveY,
                    CubeFace::NegativeZ,
                    CubeFace::PositiveZ,
                ][slot];
                let depth = get_cube_array_face_index(f);
                access.get_subregion(0, 0, depth, w, h, 1)
            });
            sample_cube_seamless_linear(&faces, face, sampler, coords[0], coords[1], 0)
        }
    }
}

