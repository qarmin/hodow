/// `sampleCubeSeamlessLinearCompare`'s own tap-gathering half - the shadow-sampler
/// counterpart of `get_cube_linear_samples`: each of the four taps is compared against
/// `ref_` individually (through `exec_compare`, exactly as `sample_2d_compare`'s own
/// `FilterMode::Linear` arm does) *before* the bilinear blend below, never by averaging
/// the four depths and comparing once. The doubly-out-of-bounds corner tap (one that
/// `remap_cube_edge_coords` cannot resolve to any face) still gets the average of the
/// other three *compare results*, matching upstream's own comment that this averaging
/// is a convention, not a spec requirement.
fn get_cube_linear_compares(
    face_accesses: &[ConstPixelBufferAccess<'_>; 6],
    base_face: CubeFace,
    sampler: &Sampler,
    ref_: f32,
    u: f32,
    v: f32,
    depth: i32,
) -> [f32; 4] {
    let size = face_accesses[0].size()[0] as i32;
    let x0 = (u - 0.5).floor() as i32;
    let y0 = (v - 0.5).floor() as i32;
    let base = [
        (x0, y0),
        (x0.wrapping_add(1), y0),
        (x0, y0.wrapping_add(1)),
        (x0.wrapping_add(1), y0.wrapping_add(1)),
    ];

    let mut results = [0.0f32; 4];
    let mut corner = None;
    for (i, (x, y)) in base.into_iter().enumerate() {
        match remap_cube_edge_coords(base_face, x, y, size) {
            Some((face, s, t)) => {
                let access = &face_accesses[get_cube_face_slot(face)];
                let is_fixed_point = is_fixed_point_depth_texture_format(access.format());
                results[i] = exec_compare(
                    lookup(access, s, t, depth),
                    sampler.compare,
                    sampler.compare_channel as usize,
                    ref_,
                    is_fixed_point,
                );
            }
            None => corner = Some(i),
        }
    }

    if let Some(i) = corner {
        let sum: f32 = results
            .iter()
            .enumerate()
            .filter(|&(j, _)| j != i)
            .map(|(_, r)| r)
            .sum();
        results[i] = sum / 3.0;
    }

    results
}

/// `sampleCubeSeamlessLinearCompare`
fn sample_cube_seamless_linear_compare(
    face_accesses: &[ConstPixelBufferAccess<'_>; 6],
    base_face: CubeFace,
    sampler: &Sampler,
    ref_: f32,
    s: f32,
    t: f32,
    depth: i32,
) -> f32 {
    let size = face_accesses[0].size()[0];
    let (u, v) = if sampler.normalized_coords {
        (
            unnormalize(sampler.wrap_s, s, size),
            unnormalize(sampler.wrap_t, t, size),
        )
    } else {
        (s, t)
    };

    let results = get_cube_linear_compares(face_accesses, base_face, sampler, ref_, u, v, depth);
    let a = frac(u - 0.5);
    let b = frac(v - 0.5);

    results[0] * (1.0 - a) * (1.0 - b) + results[1] * a * (1.0 - b) + results[2] * (1.0 - a) * b + results[3] * a * b
}

