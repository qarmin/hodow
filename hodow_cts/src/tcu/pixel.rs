/// `sample_2d_array_mipmap_compare`, generalized with the `mip_filter` axis the same
/// way `sample_2d_mipmap_compare_filtered` generalizes its own non-array sibling -
/// `layer` is resolved once (array layer selection is never itself blended, matching
/// `sample_2d_array_mipmap`'s own convention) and reused for both candidate levels.
#[allow(clippy::too_many_arguments)]
pub fn sample_2d_array_mipmap_compare_filtered(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    ref_: f32,
    s: f32,
    t: f32,
    r: f32,
    lod: f32,
    mip_filter: MipmapFilterMode,
) -> f32 {
    let layer = select_layer(r, levels[0].size()[2]);
    if lod <= 0.0 {
        return levels[0].sample_2d_compare(sampler, ref_, s, t, layer);
    }

    match mip_filter {
        MipmapFilterMode::Nearest => sample_2d_array_mipmap_compare(levels, sampler, ref_, s, t, r, lod),
        MipmapFilterMode::Linear => {
            let max_level = levels.len() as i32 - 1;
            let level0 = (lod.floor() as i32).clamp(0, max_level);
            let level1 = (level0 + 1).min(max_level);
            let f = lod.fract();
            let c0 = levels[level0 as usize].sample_2d_compare(sampler, ref_, s, t, layer);
            let c1 = levels[level1 as usize].sample_2d_compare(sampler, ref_, s, t, layer);
            c0 * (1.0 - f) + c1 * f
        }
    }
}

