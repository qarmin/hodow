#[cfg(test)]
mod shadow_sampling_tests {
    use super::*;
    use crate::tcu::texture::{ChannelOrder, ChannelType};

    fn nearest_compare_sampler(compare: CompareMode) -> Sampler {
        Sampler {
            compare,
            normalized_coords: true,
            ..Sampler::clamp_to_edge(FilterMode::Nearest)
        }
    }

    /// Every `exec_compare` branch against hand-picked `(ref, stored)` pairs, mirroring
    /// upstream's own switch 1:1 - `Less`/`LessOrEqual` etc. read as `ref <op> stored`,
    /// not the other way around (a common mix-up porting a GLSL `textureProj` depth
    /// compare, where the *shader's* `ref` coordinate is the left-hand side).
    #[test]
    fn exec_compare_matches_every_mode_by_hand() {
        let color = [0.5, 0.0, 0.0, 1.0];
        assert_eq!(exec_compare(color, CompareMode::Less, 0, 0.25, true), 1.0); // 0.25 < 0.5
        assert_eq!(exec_compare(color, CompareMode::Less, 0, 0.75, true), 0.0); // 0.75 < 0.5 is false
        assert_eq!(exec_compare(color, CompareMode::LessOrEqual, 0, 0.5, true), 1.0);
        assert_eq!(exec_compare(color, CompareMode::Greater, 0, 0.75, true), 1.0);
        assert_eq!(exec_compare(color, CompareMode::GreaterOrEqual, 0, 0.5, true), 1.0);
        assert_eq!(exec_compare(color, CompareMode::Equal, 0, 0.5, true), 1.0);
        assert_eq!(exec_compare(color, CompareMode::Equal, 0, 0.6, true), 0.0);
        assert_eq!(exec_compare(color, CompareMode::NotEqual, 0, 0.6, true), 1.0);
        assert_eq!(exec_compare(color, CompareMode::Always, 0, 999.0, true), 1.0);
        assert_eq!(exec_compare(color, CompareMode::Never, 0, -999.0, true), 0.0);
        assert_eq!(exec_compare(color, CompareMode::None, 0, 0.0, true), 0.0);
    }

    /// A fixed-point depth format clamps an out-of-`[0,1]` `ref` before comparing (the
    /// GLES spec's own rule for `GL_DEPTH_COMPONENT16`/`24` textures) - `ref = 2.0`
    /// clamps to `1.0`, which is not less than the stored `0.5`. A floating-point depth
    /// format (`is_fixed_point = false`) compares the raw, unclamped value instead.
    #[test]
    fn exec_compare_clamps_ref_only_for_fixed_point_depth_formats() {
        let color = [0.5, 0.0, 0.0, 1.0];
        assert_eq!(exec_compare(color, CompareMode::Less, 0, 2.0, true), 0.0);
        assert_eq!(exec_compare(color, CompareMode::Greater, 0, 2.0, false), 1.0);
    }

    #[test]
    fn is_fixed_point_depth_texture_format_matches_upstream_classes() {
        assert!(is_fixed_point_depth_texture_format(TextureFormat::new(
            ChannelOrder::D,
            ChannelType::UNORM_INT16
        )));
        assert!(!is_fixed_point_depth_texture_format(TextureFormat::new(
            ChannelOrder::D,
            ChannelType::FLOAT
        )));
    }

    fn depth_level() -> TextureLevel {
        // A 2x2 UNORM_INT16 depth texture: shallow-to-deep left-to-right,
        // bottom-to-top, exactly the same per-texel layout convention
        // `glu::texture_test_util`'s own `checkerboard_level` test helper uses.
        let mut level =
            TextureLevel::new(TextureFormat::new(ChannelOrder::D, ChannelType::UNORM_INT16), 2, 2, 1).unwrap();
        let mut access = level.get_access();
        access.set_pixel([0.25, 0.0, 0.0, 1.0], 0, 0, 0);
        access.set_pixel([0.75, 0.0, 0.0, 1.0], 1, 0, 0);
        access.set_pixel([0.1, 0.0, 0.0, 1.0], 0, 1, 0);
        access.set_pixel([0.9, 0.0, 0.0, 1.0], 1, 1, 0);
        level
    }

    /// `NEAREST` shadow sampling at an exact texel centre must reproduce `exec_compare`
    /// applied to that one stored depth value, with no blending at all.
    #[test]
    fn sample_2d_compare_nearest_reads_one_texel_unblended() {
        let level = depth_level();
        let access = level.get_const_access();
        let sampler = nearest_compare_sampler(CompareMode::Less);

        // Texel (0,0) stores depth 0.25: ref=0.0 < 0.25 is true.
        assert_eq!(access.sample_2d_compare(&sampler, 0.0, 0.25, 0.25, 0), 1.0);
        // Texel (1,1) stores depth 0.9: ref=0.95 < 0.9 is false.
        assert_eq!(access.sample_2d_compare(&sampler, 0.95, 0.75, 0.75, 0), 0.0);
    }

    /// `LINEAR` ("PCF") shadow sampling averages four *comparison results*, not four
    /// depth values - with `ref` chosen to sit strictly between two of the four
    /// texels' depths and above/below the other two, each of the four quadrants
    /// contributes a different 0/1 term, and the equal bilinear weights at the shared
    /// corner make the result the plain average of however many of the four taps
    /// passed.
    #[test]
    fn sample_2d_compare_linear_averages_individual_compare_results_not_depths() {
        let level = depth_level();
        let access = level.get_const_access();
        // Pixel-space coordinates here (not normalized) - `normalized_coords: false`
        // is `Sampler::clamp_to_edge`'s own default, unlike `nearest_compare_sampler`'s
        // override above.
        let sampler = Sampler {
            filter: FilterMode::Linear,
            compare: CompareMode::LessOrEqual,
            ..Sampler::clamp_to_edge(FilterMode::Linear)
        };

        // Sampling at the exact shared corner of all four texels (u=1.0, v=1.0 in
        // unnormalized pixel-centre-at-0.5 coordinates) weights all four taps equally
        // at 0.25 each. Depths are 0.25, 0.75, 0.1, 0.9 (texels (0,0),(1,0),(0,1),(1,1));
        // ref=0.5 is <= to 0.75 and 0.9 only, so 2 of 4 pass -> average 0.5.
        let got = access.sample_2d_compare(&sampler, 0.5, 1.0, 1.0, 0);
        assert!((got - 0.5).abs() < 1e-6, "got {got}");
    }

    /// `sample_2d_array_mipmap_compare` selects a layer the same way
    /// `sample_2d_array_mipmap` does (rounded `r`, clamped to the layer count), then
    /// compares within that layer exactly like `sample_2d_compare` - a 1x1-per-layer,
    /// 2-layer depth array with a distinct depth per layer isolates layer selection
    /// from within-layer addressing.
    #[test]
    fn sample_2d_array_mipmap_compare_selects_the_right_layer() {
        let mut level =
            TextureLevel::new(TextureFormat::new(ChannelOrder::D, ChannelType::UNORM_INT16), 1, 1, 2).unwrap();
        {
            let mut access = level.get_access();
            access.set_pixel([0.2, 0.0, 0.0, 1.0], 0, 0, 0); // layer 0
            access.set_pixel([0.8, 0.0, 0.0, 1.0], 0, 0, 1); // layer 1
        }
        let levels = [level.get_const_access()];
        let sampler = nearest_compare_sampler(CompareMode::Less);

        // Layer 0 stores 0.2: ref=0.0 < 0.2 is true.
        assert_eq!(
            sample_2d_array_mipmap_compare(&levels, &sampler, 0.0, 0.5, 0.5, 0.0, 0.0),
            1.0
        );
        // Layer 1 stores 0.8: ref=0.9 < 0.8 is false.
        assert_eq!(
            sample_2d_array_mipmap_compare(&levels, &sampler, 0.9, 0.5, 0.5, 1.0, 0.0),
            0.0
        );
    }
}

