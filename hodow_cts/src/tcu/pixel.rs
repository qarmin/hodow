    /// `UNSIGNED_INT_24_8` (non-REV) packs stencil in byte 0 and depth in the high 3
    /// bytes - the opposite of `_24_8_REV` above. `get_pix_depth`/`get_pix_stencil` had
    /// no arm at all for this plain variant and silently fell through to
    /// `channel_to_float`/`channel_to_int64`'s own catch-all `_ => 0`, so every read
    /// came back 0.0/0 regardless of what `set_pix_depth`/`set_pix_stencil` (which did
    /// have a correct arm each) had just written - a write/read asymmetry found while
    /// porting `rr::multisample_pixel_buffer_access`'s depth/stencil resolve. This pins both directions: a value that is not 0 and
    /// not the all-ones saturation value, so a regression back to "always reads 0" or
    /// "always reads the saturated max" both fail it.
    #[test]
    fn combined_depth_stencil_non_rev_roundtrips_per_aspect() {
        let f = TextureFormat::new(ChannelOrder::DS, ChannelType::UNSIGNED_INT_24_8);
        let mut level = TextureLevel::new(f, 1, 1, 1).expect("writable through the aspect setters");
        level.get_access().set_pix_depth(0.5, 0, 0, 0);
        level.get_access().set_pix_stencil(0x42, 0, 0, 0);
        let acc = level.get_const_access();
        assert!(
            (acc.get_pix_depth(0, 0, 0) - 0.5).abs() < 1e-6,
            "{}",
            acc.get_pix_depth(0, 0, 0)
        );
        assert_eq!(acc.get_pix_stencil(0, 0, 0), 0x42);

        // Byte layout check, not just the round trip: stencil at offset 0, depth's
        // 24-bit value starting at offset 1, matching `set_pix_depth`'s own
        // `dst[1..4]` write exactly.
        let bytes = level.data();
        assert_eq!(bytes[0], 0x42);
        let depth_bits = read_uint24(&bytes[1..4]);
        // `convert_sat_rte(0.5 * 16_777_215.0, ...)` is `0.5 * 16777215 = 8388607.5`,
        // an exact tie - round-half-to-even takes it to the nearest *even* integer,
        // which is 8388608 (0x800000), not 8388607.
        assert_eq!(depth_bits, 8_388_608);
    }

