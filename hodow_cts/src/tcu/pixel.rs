    /// `MirroredRepeat` on an 8-wide axis: the first half-period `[0,7]` maps straight
    /// through (a texel mirrors onto itself at the symmetry boundary, `c=7`), the
    /// second half `[8,15]` mirrors back `7..0`, and the whole 16-wide period repeats
    /// from there - hand-derived from upstream's own `(size-1) - mirror(imod(c, 2*size)
