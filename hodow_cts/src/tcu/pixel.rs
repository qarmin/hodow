/// `tcu::TextureCubeArrayView`, at lod 0 and always seamless - the only sampler these
/// tests build sets `seamlessCubeMap`.
pub struct TextureCubeArrayView<'a> {
    pub level0: ConstPixelBufferAccess<'a>,
}

impl TextureCubeArrayView<'_> {
    fn select_layer(&self, q: f32) -> i32 {
        ((q + 0.5).floor() as i32).clamp(0, (self.level0.size()[2] / 6) as i32 - 1)
    }

    /// `TextureCubeArrayView::sample` -> `sampleCubeArraySeamless`
    pub fn sample(&self, sampler: &Sampler, s: f32, t: f32, r: f32, q: f32) -> [f32; 4] {
        let (face, coords) = get_cube_face_coords([s, t, r]);
        let layer = self.select_layer(q);
        let [w, h, _] = self.level0.size();

        match sampler.filter {
            FilterMode::Nearest => {
                let face_depth = layer * 6 + get_cube_array_face_index(face) as i32;
                sample_cube_seamless_nearest(&self.level0, sampler, coords[0], coords[1], face_depth)
            }
            _ => {
                // Each face becomes its own one-slice access, so a tap that walks off
                // an edge can be looked up in the neighbour directly.
                let faces: [ConstPixelBufferAccess<'_>; 6] = std::array::from_fn(|slot| {
                    let face = [
                        CubeFace::NegativeX,
                        CubeFace::PositiveX,
                        CubeFace::NegativeY,
                        CubeFace::PositiveY,
                        CubeFace::NegativeZ,
                        CubeFace::PositiveZ,
                    ][slot];
                    let depth = layer as u32 * 6 + get_cube_array_face_index(face);
                    self.level0.get_subregion(0, 0, depth, w, h, 1)
                });
                sample_cube_seamless_linear(&faces, face, sampler, coords[0], coords[1], 0)
            }
        }
    }
}

/// `sampleLevelArray2DOffset`'s level-selection math, restricted to what
/// `shaders.texture_functions` needs: every sampler it builds has `lodThreshold ==
/// 0.0` (upstream's own default, never overridden here) and no
/// `VK_EXT_image_view_min_lod` state, which collapses upstream's `minLodRelative`-carrying
/// branches to a plain `lod` comparison. Both of this test's two sampler shapes reach the
/// same formula: a single-level (`LINEAR`, no mipmap) sampler falls into upstream's
/// `NEAREST/LINEAR/CUBIC` branch, whose `level0` is `clamp(ceil(0.5) - 1, 0, maxLevel)` =
/// `0` regardless of `lod` (`maxLevel` is `0`); a `LINEAR_MIPMAP_NEAREST` sampler is
/// magnified (`lod <= 0.0`, using level `0`) or minified (`clamp(ceil(lod + 0.5) - 1, 0,
/// maxLevel)`) - and clamping the first sampler's always-`0` pre-clamp value to `maxLevel
/// == 0` gives the same `0` either formula would, so one function covers both shapes.
fn mipmap_level(num_levels: usize, lod: f32) -> usize {
    if lod <= 0.0 {
        0
    } else {
        let max_level = num_levels as i32 - 1;
        ((lod + 0.5).ceil() as i32 - 1).clamp(0, max_level) as usize
    }
}

/// `Texture2DView::sample` through `sampleLevelArray2D`, restricted as `mipmap_level`
/// documents - the per-level tap is always `LINEAR` (upstream's `levelFilter`, forced
/// regardless of the sampler's own `NEAREST_MIPMAP_NEAREST`/`LINEAR_MIPMAP_NEAREST` split,
/// since every sampler this test builds uses the `LINEAR` half).
pub fn sample_2d_mipmap(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    s: f32,
    t: f32,
    lod: f32,
) -> [f32; 4] {
    levels[mipmap_level(levels.len(), lod)].sample_2d(sampler, s, t, 0)
}

/// `sample_2d_mipmap`'s shadow-sampler counterpart (the `Texture2DView::sampleCompare`
/// path a `sampler2DShadow` lookup takes) - see `sample_2d_compare`'s own doc comment
/// for what distinguishes this from filtering `sample_2d_mipmap` then comparing once.
pub fn sample_2d_mipmap_compare(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    ref_: f32,
    s: f32,
    t: f32,
    lod: f32,
) -> f32 {
    levels[mipmap_level(levels.len(), lod)].sample_2d_compare(sampler, ref_, s, t, 0)
}

/// `sample_2d_mipmap_compare`, generalized with the `mip_filter` axis
/// `sample_2d_mipmap_filtered` introduced - same additive shape (this crate's only
/// existing caller, `sample_2d_mipmap_compare` itself, is untouched), same
/// magnified-always-level-0 narrowing, same two-level blend, just blending the two
/// levels' own *compare results* (each already a per-tap-compared, PCF-averaged
/// scalar - see `sample_2d_compare`'s own doc comment for why that one float, not the
/// raw depth, is what gets interpolated) instead of a `[f32; 4]` colour.
pub fn sample_2d_mipmap_compare_filtered(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    ref_: f32,
    s: f32,
    t: f32,
    lod: f32,
    mip_filter: MipmapFilterMode,
) -> f32 {
    if lod <= 0.0 {
        return levels[0].sample_2d_compare(sampler, ref_, s, t, 0);
    }

    match mip_filter {
        MipmapFilterMode::Nearest => sample_2d_mipmap_compare(levels, sampler, ref_, s, t, lod),
        MipmapFilterMode::Linear => {
            let max_level = levels.len() as i32 - 1;
            let level0 = (lod.floor() as i32).clamp(0, max_level);
            let level1 = (level0 + 1).min(max_level);
            let f = lod.fract();
            let c0 = levels[level0 as usize].sample_2d_compare(sampler, ref_, s, t, 0);
            let c1 = levels[level1 as usize].sample_2d_compare(sampler, ref_, s, t, 0);
            c0 * (1.0 - f) + c1 * f
        }
    }
}

/// The mipmap-interpolation axis of `Sampler::FilterMode`, isolated from the
/// per-level tap: `Nearest` is upstream's `*_MIPMAP_NEAREST` (pick exactly one level,
/// `mipmap_level`'s existing formula - what `sample_2d_mipmap` above already does for
/// every caller it has today), `Linear` is `*_MIPMAP_LINEAR` (true trilinear - blend
/// the two adjacent levels `floor(lod)`/`floor(lod)+1` by `frac(lod)`).
///
/// Still passed as its own argument to every `sample_*_mipmap_filtered` function below
/// rather than read off `sampler.mip_filter` internally - those functions are the
/// mechanism `glu::texture_test_util::exec_sample_2d`/`_cube`/`_3d`/`_2d_array` already
/// dispatch on `sampler.mip_filter` to choose between (see `Sampler`'s own doc comment
/// for why the field now exists), so threading it through a second time here would
/// just move the `match` rather than remove it.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum MipmapFilterMode {
    Nearest,
    Linear,
}

/// `sampleLevelArray2DOffset`, generalized with the `mip_filter` axis above -
/// `sample_2d_mipmap` is this with `MipmapFilterMode::Nearest`, unchanged in behaviour
/// and left as its own function so no existing caller needs to change. `texture.mipmap`
/// is the group this unlocks (confirmed by grepping `es3fTextureMipmapTests.cpp`
/// directly: every one of its cases constructs a real `GL_*_MIPMAP_LINEAR` minFilter and
/// checks `isTrilinear` to loosen its own comparison threshold, so a case built against
/// this crate needs a reference image that actually blends, not the single-level
/// approximation `sample_2d_mipmap` makes do with for `shaders.texture_functions`'s own,
/// never-`*_MIPMAP_LINEAR` sampler shapes).
///
/// The magnified case (`lod <= 0.0`, upstream's `lodThreshold` default) always samples
/// level 0 alone, regardless of `mip_filter` - a narrowing of upstream's own ES2-specific
/// `isLinearMipmapMode` branch (magnified-but-still-blending-with-level-1 under a
/// `GL_LINEAR` magFilter plus a `*_MIPMAP_LINEAR` minFilter, an ES2 quirk
/// `isSamplerMipmapModeLinear` exists only to express), not needed by anything this port
/// builds yet and left `unimplemented!`-free only because it is genuinely unreachable
/// for a magnified lookup against the samplers this crate constructs (every one of them
/// uses `lodThreshold == 0.0` with a plain `LINEAR`/`NEAREST` magFilter, never queried in
/// the magnified branch beyond level 0 itself).
pub fn sample_2d_mipmap_filtered(
    levels: &[ConstPixelBufferAccess<'_>],
    sampler: &Sampler,
    s: f32,
    t: f32,
    lod: f32,
    mip_filter: MipmapFilterMode,
) -> [f32; 4] {
    if lod <= 0.0 {
        return levels[0].sample_2d(sampler, s, t, 0);
    }

    match mip_filter {
        MipmapFilterMode::Nearest => levels[mipmap_level(levels.len(), lod)].sample_2d(sampler, s, t, 0),
        MipmapFilterMode::Linear => {
            let max_level = levels.len() as i32 - 1;
            let level0 = (lod.floor() as i32).clamp(0, max_level);
            let level1 = (level0 + 1).min(max_level);
            let f = lod.fract();
            let t0 = levels[level0 as usize].sample_2d(sampler, s, t, 0);
            let t1 = levels[level1 as usize].sample_2d(sampler, s, t, 0);
            std::array::from_fn(|c| t0[c] * (1.0 - f) + t1[c] * f)
        }
    }
}

