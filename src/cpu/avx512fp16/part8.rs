use std::arch::x86_64::*;

use log::info;

use crate::cpu::common::{check_float_array_equality, get_random_float32_array};
use crate::cpu::get_iterations;
use crate::get_fuzzing;

pub(super) fn test_mm_mask_fmul_sch() -> Result<(), String> {
    unsafe {
        let a = _mm_set_ps(1.0, 2.0, 3.0, 4.0);
        let b = _mm_set_ps(2.0, 2.0, 2.0, 2.0);
        let r = _mm_fmul_sch(a, b);
        let out: [f32; 4] = std::mem::transmute::<__m128, [f32; 4]>(r);
        check_float_array_equality(&out, &[2.0, 4.0, 6.0, 8.0])?;
    }
    if get_fuzzing() {
        info!("Starting fuzzing");
        for _ in 0..get_iterations() {
            unsafe {
                let _ = _mm_fmul_sch(_mm_set1_ps(get_random_float32_array::<1>()[0]), _mm_set1_ps(2.0));
            }
        }
    }
    Ok(())
}

pub(super) fn test_mm_maskz_fmul_sch() -> Result<(), String> {
    test_mm_mask_fmul_sch()
}

